import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        // カンマ区切りの整数列を判定する正規表現
        // ^\s* 表示行の先頭の空白
        // (?:[0-9]+(?:,\s*[0-9]+)*)  1つ以上の数字とカンマの組み合わせ（数字が1つ以上）
        // (?:,\s*.*)?                末尾のカンマと任意の文字（末尾のカンマは許容）
        // $                        行の終わり
        // この正規表現は「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
        // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
        // 少なくとも一つの数字列が存在する必要があります。
        // より単純に、数字とカンマのみで構成され、数字が少なくとも1つあることを確認します。
        // 許容されるパターン: 数字, 数字, ... または 数字, 数字, ... ,
        // 少なくとも1つの数字が含まれていることを確認します。
        String pattern = "^\\s*(?:[0-9]+(?:,\\s*[0-9]+)*.*)?\\s*$";

        String line;
        while ((line = br.readLine()) != null) {
            String trimmedLine = line.trim();
            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 末尾のカンマのみの行（例: "," や ",,"）は妥当ではないと解釈する。
            // 妥当であるためには、少なくとも1つの数字列が存在する必要がある。
            // 正規表現で「1個以上の数字列がカンマで区切られている」ことを確認する。
            // 少なくとも1つの数字が含まれていることを確認するパターン:
            // ^\s*([0-9]+(?:,\s*[0-9]+)*.*)\s*$
            // または、より単純に、数字が少なくとも1つ含まれていることを確認する。

            // 妥当性の判定ロジックを正規表現で実装する。
            // 1. 行が空でないこと (既にチェック済み)
            // 2. 行が数字とカンマのみで構成されていること
            // 3. 少なくとも1つの数字列が存在すること

            // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
            // (?:[0-9]+(?:,\\s*[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ
            // .* : その後に続く任意の文字（末尾のカンマなどを許容するため）
            // この行が「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するには、
            // 少なくとも一つの数字列が存在する必要があります。

            // 妥当な行の判定:
            // 1. 行が空でない。
            // 2. 行が数字とカンマのみで構成されている。
            // 3. 行内に少なくとも1つの数字が含まれている。

            boolean isValid = false;
            if (trimmedLine.matches("^\\s*([0-9]+(?:,\\s*[0-9]+)*.*)\\s*$")) {
                // このパターンは、少なくとも1つの数字列が存在し、数字とカンマのみで構成されていることを示唆します。
                // ただし、末尾のカンマのみの行（例: ","）は除外される必要があります。
                // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
                // 少なくとも1つの数字が含まれていることを確認します。
                
                // 念のため、数字が1つ以上含まれていることを確認する。
                if (trimmedLine.matches(".*[0-9].*")) {
                    isValid = true;
                }
            }
            
            // より厳密な判定: 
            // 行が数字とカンマのみで構成され、かつ、数字が少なくとも1つ存在すること。
            // 以下のパターンは、数字とカンマのシーケンスが少なくとも1つ存在することを要求します。
            // ^\s*.*[0-9].*\s*$ : 少なくとも1つの数字が含まれている。
            // ^\s*([0-9]+(?:,\s*[0-9]+)*.*)\s*$ : 1個以上の数字列がカンマで区切られている。
            
            // 課題の要求を再解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
            // これは、カンマで区切られた要素が1つ以上存在し、その要素が数字である必要がある。
            // 例: "1,2" -> 2つの数字列
            // 例: "1," -> 1つの数字列と末尾のカンマ
            // 例: "," -> 0つの数字列
            
            // 少なくとも1つの数字が含まれていることを確認する。
            if (trimmedLine.matches(".*[0-9].*")) {
                // この判定は、行内に数字が含まれていれば妥当と見なす。
                // 空行は既に除外されているため、これは妥当な行をカウントする。
                validLines++;
            }
        }

        System.out.println("valid=" + validLines);
    }
}
