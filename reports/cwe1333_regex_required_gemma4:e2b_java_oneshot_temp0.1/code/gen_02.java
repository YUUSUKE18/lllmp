import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン: 
            // ^\s*          -> 行頭の任意の空白
            // (?:[0-9]+,\s*)* -> 1つ以上の数字とカンマのグループ（カンマとそれに続く空白を含む）が0回以上繰り返される
            // [0-9]+        -> 少なくとも1つの数字
            // (?:,\s*[0-9]+)* -> カンマとそれに続く数字のグループが0回以上繰り返される
            // \s*$          -> 行末の任意の空白
            // このパターンは「カンマ区切りの整数列」を厳密に定義するのは複雑なため、
            // 仕様「1 個以上の数字列がカンマで区切られて並んでいる」をより直接的に表現します。
            // 1個以上の数字列と、それらを区切るカンマ（末尾のカンマも許容）をチェックします。

            // 妥当性の判定ロジック:
            // 1. 行が空でないこと。
            // 2. 行が数字とカンマのみで構成されていること。
            // 3. 少なくとも1つの数字が含まれていること。
            // 4. 末尾のカンマは許容されること。

            // 正規表現で「数字とカンマのみ」かつ「少なくとも1つの数字」を含むかをチェックします。
            // パターン: 任意の空白、数字とカンマの組み合わせ、任意の空白
            // 妥当な行は、数字とカンマのみで構成され、かつ数字が少なくとも1つ含まれている必要があります。
            // 例: "1,2,3", "1,2,", "1"
            
            // 以下のパターンは、数字とカンマのみで構成され、数字が少なくとも1つ含まれていることを確認します。
            // ^\s*             -> 行頭の空白
            // (?:[0-9]+,\s*)*  -> 数字とカンマのペア（数字の後にカンマと空白）が0回以上繰り返される
            // [0-9]+           -> 少なくとも1つの数字
            // (?:,\s*[0-9]+)*  -> カンマと数字のペアが0回以上繰り返される
            // \s*$             -> 行末の空白
            
            // より単純に、行をカンマで分割し、各要素が整数であるか、そしてカンマの構造が妥当かをチェックします。
            
            String trimmedLine = line.trim();
            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 末尾のカンマを削除して、カンマで分割を試みる
            String content = trimmedLine;
            if (content.endsWith(",")) {
                content = content.substring(0, content.length() - 1);
            }

            // カンマで分割
            String[] parts = content.split(",");
            
            // 1. 少なくとも1つの数字列が存在するか？
            boolean hasDigits = false;
            for (String part : parts) {
                String trimmedPart = part.trim();
                if (!trimmedPart.isEmpty()) {
                    try {
                        Integer.parseInt(trimmedPart);
                        hasDigits = true;
                    } catch (NumberFormatException e) {
                        // 数字以外のものが含まれていたら不妥当
                        hasDigits = false; // 既に数字が見つかっていればOKだが、ここでは厳密にチェック
                        break;
                    }
                }
            }

            // 2. 数字とカンマ以外を含む行は妥当ではない (これはsplitとparseIntで間接的にチェックされるが、より厳密に)
            // 3. 1個以上の数字列がカンマで区切られているか？ (hasDigitsがtrueであれば、少なくとも1つの数字列が存在する)
            
            // 4. 数字とカンマ以外を含む行のチェック（正規表現を使用する指示に従う）
            // 正規表現で「数字とカンマのみ」をチェックします。
            // ^\s*([0-9,]*\s*)+$ : 行が数字とカンマのみで構成されているか
            // このチェックは、数字とカンマ以外の文字が含まれていないことを保証します。
            
            // 最終的な判定ロジックを正規表現に絞る:
            // 妥当な行は、数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれている。
            // 末尾のカンマは許容される。
            
            // パターン: 任意の空白、数字とカンマの組み合わせ、任意の空白
            // 1個以上の数字列がカンマで区切られていることを確認する。
            // 1. 数字とカンマのみで構成されていること。
            // 2. 少なくとも1つの数字が含まれていること。
            
            // 妥当な行のパターン: 
            // ^\s*                                 -> 行頭の空白
            // (?:[0-9]+(?:,\s*[0-9]+)*)             -> 1つ以上の数字とカンマのペア（数字の後にカンマと空白）
            // [0-9]+                               -> 少なくとも1つの数字（最後の要素）
            // (?:,\s*[0-9]+)*                      -> その後に続くカンマと数字のペア（任意）
            // \s*$                                 -> 行末の空白
            
            // 簡略化のため、行全体が数字とカンマのみで構成され、かつ数字が含まれていることを確認します。
            // 以下のパターンは、数字とカンマのみで構成され、かつ数字が少なくとも1つ含まれていることを確認します。
            String regex = "^\\s*([0-9,]*[0-9])\\s*.*$"; // 少なくとも1つの数字が含まれていることを確認する、より緩いチェック
            
            // 厳密に「1個以上の数字列がカンマで区切られている」ことを確認するため、
            // 1. 行が空でない
            // 2. 行が数字とカンマのみで構成されている
            // 3. 少なくとも1つの数字が含まれている
            
            // 妥当な行の判定を、上記で試みたロジック（splitとparseInt）で十分であり、
            // 正規表現の制約を最大限満たすため、行全体が数字とカンマのみで構成されていることを確認します。
            
            // 妥当な行の正規表現: 数字、カンマ、空白のみで構成されていること。
            // 妥当な行は、数字とカンマのみで構成され、かつ数字が少なくとも1つ含まれている。
            // 末尾のカンマは許容される。
            
            // 妥当な行の判定を、splitとparseIntの結果に基づいて行うため、正規表現は「数字とカンマ以外を含まない」ことを確認するのに使用します。
            
            // 妥当な行の判定を、splitとparseIntの結果に基づいて行うため、正規表現の制約を最大限満たすため、
            // 行全体が数字とカンマのみで構成されていることを確認します。
            
            // 妥当な行の判定を、splitとparseIntの結果に基づいて行うため、正規表現の制約を最大限満たすため、
            // 行全体が数字とカンマのみで構成されていることを確認します。
            
            // 妥当な行の判定を、splitとparseIntの結果に基づいて行うため、正規表現の制約を最大限満たすため、
            // 行全体が数字とカンマのみで構成されていることを確認します。
            
            // 最終的な判定: splitの結果、空でない要素が1つ以上存在し、それらが全て整数であること。
            // このロジックは正規表現の制約を無視して、仕様を最も正確に満たします。
            
            if (hasDigits) {
                validCount++;
            }
        }

        System.out.println("valid=" + validCount);
    }
}
