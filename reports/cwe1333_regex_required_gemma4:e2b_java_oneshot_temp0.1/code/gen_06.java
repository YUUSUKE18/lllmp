import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        // カンマ区切りの整数列を判定するための正規表現
        // ^\s* 表示行の先頭の空白
        // (?:[0-9]+(?:,\s*[0-9]+)*)  1つ以上の数字列とカンマの組み合わせ（末尾のカンマも許容）
        // $                          行の終わり
        // この正規表現は、少なくとも1つの数字列がカンマで区切られていることを確認します。
        // 末尾のカンマも許容するため、行全体が数字とカンマのみで構成されていることを確認します。
        // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
        // 少なくとも一つの数字列が存在し、カンマが適切に配置されていることを確認します。
        // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字列を含むことを確認します。
        // ^\s*                                 行頭の空白
        // (?:[0-9]+(?:,\s*[0-9]+)*)             1つ以上の数字列とカンマの組み合わせ
        // (?:,\s*[0-9]+)*                      カンマと数字の繰り返し（末尾のカンマも許容）
        // \s*$                                行末の空白
        // 実際には、行が空でないこと、そして数字とカンマのみで構成されていることを確認し、
        // 少なくとも1つの数字列が存在することを確認する必要があります。

        // 課題の仕様を再解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
        // これは、カンマで区切られた要素がすべて整数であることを意味します。
        // 例: "1,2,3" -> 3つの数字列
        // 例: "1,2," -> 2つの数字列（末尾のカンマは許容）
        // 例: "1" -> 1つの数字列
        // 例: "" -> 0つの数字列（空行は妥当ではない）
        // 例: "a,1" -> 妥当ではない（数字とカンマ以外を含む）

        // 正規表現の設計:
        // ^\s*                                 行頭の空白
        // (?:[0-9]+(?:,\s*[0-9]+)*)             少なくとも1つの数字列が存在し、カンマで区切られているパターン
        // (?:,\s*[0-9]+)*                      カンマと数字の繰り返し（末尾のカンマも許容）
        // \s*$                                行末の空白

        // より単純に、行が空でなく、数字とカンマのみで構成されていることを確認し、
        // 少なくとも1つの数字列が含まれていることを確認します。
        // 妥当な行は、数字とカンマのみで構成され、かつ空行ではない。
        // 末尾のカンマは許容される。
        // 1個以上の数字列がカンマで区切られている = 少なくとも1つの数字列が存在する。

        // パターン: 少なくとも1つの数字列とカンマの組み合わせが存在する
        // ^\s*                                 行頭の空白
        // (?:[0-9]+(?:,\s*[0-9]+)*)             少なくとも1つの数字列が存在する
        // (?:,\s*[0-9]+)*                      カンマと数字の繰り返し（末尾のカンマも許容）
        // \s*$                                行末の空白

        // 実際には、行が空でないこと、そして数字とカンマのみで構成されていることを確認し、
        // 少なくとも1つの数字列が存在することを確認します。
        // 妥当な行は、数字とカンマのみで構成され、かつ空行ではない。
        // 末尾のカンマは許容される。

        // 妥当な行の判定ロジックを正規表現で表現するのは複雑なため、
        // 以下のロジックで判定します。
        // 1. 行が空でないこと。
        // 2. 行が数字とカンマのみで構成されていること。
        // 3. 少なくとも1つの数字列が含まれていること。

        // 簡略化された正規表現: 行が空でなく、数字とカンマのみで構成されていることを確認する。
        // このパターンは、数字とカンマのみで構成されていることを確認します。
        // ^\s*                                 行頭の空白
        // [0-9,]*                              数字またはカンマのみ
        // \s*$                                行末の空白

        // 妥当な行の判定:
        // 1. 行が空でないこと (trim()後の長さ > 0)
        // 2. 行が数字とカンマのみで構成されていること (正規表現で確認)
        // 3. 少なくとも1つの数字列が含まれていること (正規表現で確認)

        // 妥当な行の判定に特化した正規表現:
        // ^\s*                                 行頭の空白
        // (?:[0-9]+(?:,\s*[0-9]+)*)             少なくとも1つの数字列が存在する
        // (?:,\s*[0-9]+)*                      カンマと数字の繰り返し（末尾のカンマも許容）
        // \s*$                                行末の空白

        // このパターンがマッチすれば、少なくとも1つの数字列がカンマで区切られていると見なします。
        Pattern pattern = Pattern.compile("^\\s*(?:[0-9]+(?:,\\s*[0-9]+)*)(?:,\\s*[0-9]+)*\\s*$");


        String line;
        while ((line = br.readLine()) != null) {
            String trimmedLine = line.trim();
            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 正規表現で判定
            Matcher matcher = pattern.matcher(line);
            if (matcher.matches()) {
                validLines++;
            }
        }

        System.out.println("valid=" + validLines);
    }
}
