import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        // カンマ区切りの整数列を判定するための正規表現
        // ^\s* 表示行の先頭の空白
        // (?:[0-9]+(?:,\s*[0-9]+)*)  1つ以上の数字列とカンマの組み合わせ
        // (?:,\s*[0-9]+)*            カンマと数字の組み合わせが0回以上繰り返される
        // $                        行の終わり
        // この正規表現は「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
        // 末尾のカンマも許容するため、行末にカンマが続くパターンも考慮する必要があります。
        // よりシンプルに、「カンマで区切られた数字の並び」をチェックします。
        // 1個以上の数字とカンマの組み合わせが存在することを確認します。
        // 例: 1,2,3 または 1,2,3,
        String pattern = "^\\s*(?:[0-9]+(?:,\\s*[0-9]+)*)(?:,\\s*[0-9]+)*\\s*$";

        String line;
        while ((line = br.readLine()) != null) {
            String trimmedLine = line.trim();
            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 正規表現で判定
            // 1個以上の数字とカンマの組み合わせが存在することを確認する。
            // 厳密には「1個以上の数字列がカンマで区切られて並んでいる」ことを意味します。
            // 例: "1,2,3" -> 妥当
            // 例: "1," -> 妥当 (末尾のカンマは許容)
            // 例: "," -> 不妥当 (数字がない)
            // 例: "abc" -> 不妥当 (数字ではない)
            
            // 1. 数字とカンマのみで構成されているかを確認する
            // 2. 少なくとも1つの数字が含まれていることを確認する
            
            // 妥当性の定義を再解釈: 1個以上の数字列がカンマで区切られている。
            // これは、カンマで区切られた要素が少なくとも1つ存在し、それらが数字である必要がある。
            
            // 正規表現の調整: 少なくとも1つの数字が含まれていることを確認する。
            // (?:[0-9]+(?:,\\s*[0-9]+)*) は、1つ以上の数字列がカンマで区切られているパターン。
            // 末尾のカンマを許容するため、行全体が数字とカンマのみで構成されていることを確認します。
            
            // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
            // ^\s*                  行頭の空白
            // (?:[0-9]+(?:,\s*[0-9]+)*)  少なくとも1つの数字列（カンマ区切り）
            // (?:,\s*[0-9]+)*         それに続くカンマ区切り（0回以上）
            // \s*$                  行末の空白
            
            // 簡略化のため、行を分割してチェックする方が意図に合致しやすいが、正規表現での一括判定を試みる。
            
            // 妥当な行の判定ロジックを正規表現で表現する。
            // 1. 行が空でないこと (既にチェック済み)
            // 2. 行が数字とカンマのみで構成されていること。
            // 3. 行内に少なくとも1つの数字が含まれていること。
            
            // 1. 数字とカンマのみで構成されているか (数字とカンマ以外の文字がない)
            // 2. 少なくとも1つの数字が含まれているか
            
            // 妥当な行のパターン: 
            // 少なくとも1つの数字が含まれ、それらがカンマで区切られている。
            // 例: "1,2,3" または "1," または ",1" (これは不妥当)
            
            // 少なくとも1つの数字が含まれていることを確認するパターン:
            Pattern validPattern = Pattern.compile("^\\s*([0-9]+(?:,\\s*[0-9]+)*)(?:,\\s*[0-9]+)*\\s*$");
            Matcher matcher = validPattern.matcher(line);
            
            // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を判定する。
            // これは、カンマで区切られた要素が少なくとも1つ存在し、それらが数字である必要がある。
            // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
            // (?:[0-9]+(?:,\\s*[0-9]+)*) は、1つ以上の数字列がカンマで区切られていることを意味する。
            // 末尾のカンマを許容するため、行全体がこの構造に従うことを確認する。
            
            // 最終的な判定ロジックとして、行をカンマで分割し、すべてが数字であることを確認する方が、
            // 「数字列がカンマで区切られている」という構造をより正確に捉える。
            
            String[] parts = line.split(",");
            boolean isValid = false;
            
            if (parts.length > 0) {
                // 少なくとも1つの要素が存在し、その要素が数字であるかチェック
                for (String part : parts) {
                    String trimmedPart = part.trim();
                    if (!trimmedPart.isEmpty()) {
                        try {
                            Integer.parseInt(trimmedPart);
                            // 数字としてパースできた
                        } catch (NumberFormatException e) {
                            // 数字以外が含まれていた場合、この行は不妥当
                            isValid = false;
                            break;
                        }
                    }
                }
                
                if (isValid) {
                    // 1個以上の数字列がカンマで区切られていることを確認。
                    // 空の要素が連続して存在しないか、少なくとも1つの数字が存在するか。
                    // 妥当なのは、数字が1つ以上存在し、それらがカンマで区切られている場合。
                    
                    // 例: "1,2" -> parts=["1", "2"] -> 2要素。OK
                    // 例: "1," -> parts=["1", ""] -> 2要素。OK (末尾のカンマは許容)
                    // 例: "," -> parts=["", ""] -> 2要素。数字がないためNG。
                    
                    // 少なくとも1つの数字が含まれていることを確認する。
                    boolean containsDigit = false;
                    for (String part : parts) {
                        if (!part.trim().isEmpty()) {
                            try {
                                Integer.parseInt(part.trim());
                                containsDigit = true;
                            } catch (NumberFormatException e) {
                                // これは上記ループで既にチェックされているはずだが、念のため
                            }
                        }
                    }
                    
                    if (containsDigit) {
                        validLines++;
                    }
                }
            }
        }

        System.out.println("valid=" + validLines);
    }
}
