package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 末尾のカンマを考慮して、カンマで分割を試みる
		// 妥当な行は「1 個以上の数字列がカンマで区切られて並んでいること」
		// これは、少なくともカンマが1つ以上含まれており、かつその間に数字があることを意味する。
		// または、カンマで分割した結果、空でないトークンが1つ以上存在すること。

		// 行全体をカンマで分割してみる
		parts := strings.Split(trimmedLine, ",")

		// 末尾のカンマが許容されるため、末尾の要素が空であっても良いが、
		// 仕様では「1 個以上の数字列がカンマで区切られて並んでいること」が重要。
		// 空行以外で、少なくとも1つ以上の数字列が含まれていれば妥当とする。

		hasNumbers := false
		for _, part := range parts {
			// トリムしてから数字であるかチェック
			trimmedPart := strings.TrimSpace(part)
			if trimmedPart != "" {
				// その部分がすべて数字であるかチェックする必要があるが、
				// 仕様は「カンマ区切りの整数列」なので、各要素が整数である必要はなく、
				// カンマで区切られた「列」が存在すれば良い、と解釈する。
				// ただし、「数字列」という表現があるため、各要素が数値であることを確認するのが自然。
				// 仕様: 妥当とは、1 個以上の数字列がカンマで区切られて並んでいることです。

				// 各部分が数字のみで構成されているか（および空でないか）をチェック
				if _, err := fmt.Sscan(trimmedPart); err == nil {
					// 成功した場合、それは整数列として扱える
					hasNumbers = true
				} else {
					// 数字列ではないもの（例: "a,b"）が含まれていれば妥当ではない。
					// 仕様の「数字列」が整数を指すため、数字以外が含まれていたら不適。
					// ただし、仕様は「数字列がカンマで区切られていること」であり、他の文字が含まれることを直接禁止していない。
					// 「数字とカンマ以外を含む行は妥当ではありません」という制約を考慮する。

					// 全体として、トリム後の行がカンマと数字のみで構成されているか確認する。
					// 全体をチェックする方が安全。
					goto checkOverall
				}
			}
		}

	checkOverall:
		// 空行以外で、カンマと数字のみで構成されているか、かつ少なくとも1つの数字列が存在するかを確認する。
		if trimmedLine != "" {
			// カンマで分割した後の非空要素が1つ以上存在するか確認する
			// また、"数字とカンマ以外を含む行は妥当ではありません"のチェックも行う。
			isValidFormat := true
			for _, char := range trimmedLine {
				if char != ',' && char != ' ' {
					// 空白は無視されるが、数字とカンマ以外が含まれていたらNG
					// 行の前後の空白は無視される、とあるので、文字列操作で検証する。
					// ここでは、行が「数字とカンマのみ」で構成されているかを確認する。
				}
			}

			// より厳密に、「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
			// これは、カンマが存在し、その間に少なくとも1つの数字が意味的に来ることを意味する。
			// または、カンマで分割して、非空の要素が1つ以上あること。

			// 末尾のカンマが許容されるため、カンマで分割して、空でない要素が1つ以上あればOKとする。
			// 例: "1,2" -> ["1", "2"] (2要素) -> OK
			// 例: "1," -> ["1", ""] (2要素) -> OK (末尾のカンマ許容のため)
			// 例: "," -> ["", ""] (2要素) -> NG (数字列ではない)
			// 例: "" -> NG (空行は既にスキップ済み)

			if len(parts) > 0 {
				// 妥当な条件：少なくとも1つの部分が存在し、その中に数字が含まれているか。
				foundDigit := false
				for _, part := range parts {
					trimmedPart := strings.TrimSpace(part)
					if trimmedPart != "" {
						// その部分が整数として解釈可能かチェック
						_, err := fmt.Sscan(trimmedPart)
						if err == nil {
							foundDigit = true
						} else {
							// 数字とカンマ以外を含む行のチェック：
							// "1,a,2" のように数字以外が含まれている場合、Sscanは失敗する。
							// Sscanが失敗した場合、その行は「数字とカンマ以外を含む」と見なす。
							isValidFormat = false
							break
						}
					}
				}

				if foundDigit {
					validCount++
				}
			}
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理はここでは省略（標準的な競技プログラミングでは必須ではないが）
	}

	fmt.Printf("valid=%d\n", validCount)
}
