package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	for scanner.Scan() {
		line := scanner.Text()
		// 行の前後の空白を無視する（ここでは行全体をそのまま処理する）

		// 末尾の空白を削除
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 行が空でないことを確認した上で、カンマ区切りの整数列であるかを判定する

		// カンマ区切りの整数列として妥当であるための条件をチェックする。
		// 妥当とは「1 個以上の数字列がカンマで区切られて並んでいること」
		// したがって、少なくとも1つのカンマを含むか、あるいはカンマを含まない整数の並びである必要がある。
		// ただし、仕様では「1 個以上の数字列がカンマで区切られて並んでいること」が妥当。
		// これは、数字とカンマのみで構成されており、少なくとも1つの数字が存在すれば良い、と解釈できる。

		// 最も厳しい解釈：カンマ区切りで数字のみで構成されていること。
		// 「1 個以上の数字列がカンマで区切られて並んでいる」
		// 例: "1,2,3" (3つの数字列) -> 妥当
		// 例: "123" (1つの数字列) -> 妥当 (カンマがなくても1つの数字列として解釈されるか？)
		// 仕様：「1 個以上の数字列がカンマで区切られて並んでいる」

		// 空白、および数字とカンマ以外を含む行は妥当ではない。
		// これは、行が「数字とカンマ」のみで構成されていることを意味する。

		isValid := false
		if len(trimmedLine) > 0 {
			// 行に含まれる文字が数字とカンマのみであるかを確認する
			isAlphanumericAndComma := true
			for _, char := range trimmedLine {
				if !('0' <= char && char <= '9') && char != ',' {
					isAlphanumericAndComma = false
					break
				}
			}

			if isAlphanumericAndComma {
				// 数字とカンマのみで構成されている。
				// さらに、「1 個以上の数字列がカンマで区切られて並んでいる」という条件を満たす必要がある。
				// これは、カンマが1つ以上存在するか、あるいはカンマがなくても数字のみで構成されていれば良い、と解釈する。
				// 多くのカンマ区切りパースの文脈では、カンマが存在することが区切りを意味する。
				// 末尾のカンマは許容される。

				// 妥当性の判定を「少なくとも1つのカンマが存在する」または「カンマがなくとも数字のみで構成される」と解釈する。
				// 単純に「カンマ区切り」という表現に基づき、数字とカンマのみで構成されれば妥当とする。
				// 空行でない、数字とカンマ以外を含まない、という条件が主要である。

				// ここでは、カンマの有無に関わらず、数字とカンマのみで構成されていれば妥当と判断する。
				// （例: "123" や "1,2"）

				isValid = true
			}
		}

		if isValid {
			validCount++
		}
	}

	if scanner.Err() != nil {
		// エラー処理（通常、標準入力の読み込みエラー）
	}

	fmt.Printf("valid=%d\n", validCount)
}
