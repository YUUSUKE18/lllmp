package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	for scanner.Scan() {
		line := scanner.Text()
		// 行の前後の空白を無視する
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 妥当性の判定
		// 1. 数字とカンマ以外を含まないこと
		// 2. 1個以上の数字列がカンマで区切られていること（末尾のカンマは許容）

		// 妥当な行であるためには、少なくとも1つのカンマが存在するか、あるいは数字のみの列が続く必要がある。
		// 仕様：「1 個以上の数字列がカンマで区切られて並んでいることです。末尾のカンマは許容します。」
		// これは、カンマで区切られた数字のシーケンスが少なくとも1つ存在することを意味する。

		// 数字とカンマ以外を含む行は妥当ではない。
		isValidContent := true
		for _, r := range trimmedLine {
			if !('0' <= r && r <= '9' || r == ',') {
				isValidContent = false
				break
			}
		}

		if !isValidContent {
			continue
		}

		// 妥当な行の判定: 1個以上の数字列がカンマで区切られているか、または数字のみの行も許容されるか？
		// 仕様：「1 個以上の数字列がカンマで区切られて並んでいることです。」
		// 1. "1,2,3" -> 妥当
		// 2. "123" -> 区切られていないが、1つの数字列であり、カンマがない。これは「1個以上の数字列がカンマで区切られて並んでいる」の解釈で曖昧。
		//    通常、区切り文字がある場合に「区切られた列」を数える。
		//    しかし、行全体が「カンマで区切られて並んでいる」かどうかに焦点を当てる。
		//    もし "123" が妥当でないなら、最低1つのカンマが必要。
		//    「妥当とは、1 個以上の数字列がカンマで区切られて並んでいることです。」
		//    これは、行内にカンマが存在し、それが数字列を区切っていることを意味する。

		// 行内にカンマが存在するかどうかをチェックする。
		if strings.Contains(trimmedLine, ",") {
			// カンマが存在する場合、数字列が存在することを前提とする。
			validCount++
		} else {
			// カンマがない場合。これは「1 個以上の数字列がカンマで区切られて並んでいる」の定義に厳密には当てはまらないが、
			// 厳密な解釈に基づき、カンマがない行は不適当とする。
			// ただし、もし "123" が許容されるなら、このelseブロックの処理を変更する必要がある。
			// 仕様を「カンマが含まれていれば、それが1個以上の数字列の区切りである」と解釈し、
			// カンマの存在を必須条件とするのが最も安全。
			// 念のため、ここではカンマの存在を妥当性の主要因とする。
			// 「妥当とは、1 個以上の数字列がカンマで区切られて並んでいることです。」
			// カンマがない行は「区切られていない」ため、妥当ではないと判断する。
		}
	}

	if scanner.Err() != nil {
		// エラー処理（今回は不要だが慣習として）
	}

	fmt.Printf("valid=%d\n", validCount)
}
