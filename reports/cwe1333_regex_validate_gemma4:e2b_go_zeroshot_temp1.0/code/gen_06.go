package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	for scanner.Scan() {
		line := scanner.Text()
		// 行の前後の空白を無視する（TrimSpaceはここでは不要かもしれないが、念のため）
		trimmedLine := strings.TrimSpace(line)

		// 妥当性の判定ロジック
		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 末尾のカンマは許容する。
		// 1個以上の数字列がカンマで区切られている必要がある。
		// つまり、カンマで区切られた結果が少なくとも1つ以上存在する必要がある。

		// 1. 行全体をカンマで分割する
		parts := strings.Split(trimmedLine, ",")

		// 2. 数字列が1つ以上存在するか、または数字列が空でないかを確認する
		// 妥当な行とは、「1個以上の数字列がカンマで区切られて並んでいること」
		// 例: "1,2,3" -> ["1", "2", "3"] (長さ3) -> 妥当
		// 例: "1," -> ["1", ""] (長さ2) -> 妥当 (末尾のカンマが空文字列を生成する)
		// 例: "," -> ["", ""] (長さ2) -> 妥当? (仕様：「1 個以上の数字列がカンマで区切られて並んでいる」)

		// ここでの「数字列」とは、カンマで区切られた要素のうち、実際に数字（または空文字列だがカンマ区切り構造の一部）を指す。
		// 仕様の解釈：「1 個以上の数字列がカンマで区切られて並んでいる」
		// これは、カンマで区切られた要素の総数が、少なくとも1以上であることを意味する。
		// ただし、「空行、および数字とカンマ以外を含む行は妥当ではない」という制約があるため、
		// 全ての要素が数字列であるか、少なくともカンマ区切りとして意味のあるパターンを許容する。

		// 最も厳密な解釈: カンマで分割した結果の要素の数が1以上であること。
		// ただし、これは「1個以上の数字列」が保証されるわけではないため、
		// 実際に数字列として意味を持つ要素が存在するか確認が必要。

		// 仕様の再確認: 「1 個以上の数字列がカンマで区切られて並んでいることです。」
		// これは、分割された要素の中に、数字として解釈できるものが少なくとも1つあることを意味する。

		hasNumber := false
		for _, part := range parts {
			// 各パートが空文字列でなく、かつ数字のみで構成されているかチェックする
			if part != "" {
				// 空文字列でない場合、そのパートが数字列であるか確認
				if _, err := fmt.Sscanf(part, "%d", new(int)); err == nil {
					hasNumber = true
				}
			}
		}

		// もしカンマで区切られた結果が空文字列のみ（例: ",," や ""）の場合、それは妥当ではない。
		// ただし、"1," は ["1", ""] であり、"1" は妥当。
		// 空行はスキップ済み。
		// 数字とカンマ以外を含む行（例: "a,b"）は、Sscanfが失敗するため hasNumber=false になる。

		// 妥当な行の判定：
		// 1. 空行でない (既に確認済み)
		// 2. 少なくとも1つの数字列が含まれている (hasNumber == true)
		// 3. カンマ区切りとして意味を持つ (これは Split の結果が空でないことを意味するが、Sscanfで数字が含まれていれば十分と判断する)

		if hasNumber {
			validCount++
		}
	}

	fmt.Println("valid=", validCount)
}
