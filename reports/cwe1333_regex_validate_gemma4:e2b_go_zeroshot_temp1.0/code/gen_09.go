package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 末尾のカンマは許容されるため、カンマで分割して要素が存在するか確認する
		// ただし、行全体がカンマで区切られた整数列である必要がある。
		// 「1 個以上の数字列がカンマで区切られて並んでいること」を検証する。

		// 行をカンマで分割する
		parts := strings.Split(trimmedLine, ",")

		// 妥当である条件は「1 個以上の数字列がカンマで区切られて並んでいること」
		// これは、分割後の要素の数が 1 以上であれば満たされる、と解釈する。
		// ただし、空の要素（例: "1,,2" のようにカンマが連続する場合）が許容されるか、
		// または「数字列のみ」が許容されるかを明確にする必要がある。

		// 仕様の再解釈: 「カンマ区切りの整数列」が妥当。
		// 「1 個以上の数字列がカンマで区切られて並んでいる」
		// 例: "1,2,3" -> 3つの数字列
		// 例: "1," -> 2つの要素 ["1", ""]
		// 例: "," -> 2つの要素 ["", ""]

		// 空行、および数字とカンマ以外を含む行は妥当ではない。
		// 数字とカンマ以外を含む行も不適。

		// 妥当性の判定ロジック:
		// 1. 行が空でないこと (既にチェック済み)
		// 2. 行が数字とカンマのみで構成されていること。
		// 3. 少なくとも1つの非空の数字列が存在すること。

		isTolerable := true
		
		// 各部分が数字列であることを確認し、少なくとも1つは非空であることを確認する
		hasNumber := false
		for _, part := range parts {
			if part != "" {
				// 数字列であることを確認 (すべて数字のみ)
				if _, err := fmt.Sscan(part); err != nil {
					isTolerable = false
					break
				}
				hasNumber = true
			} else if part == "" {
				// 空の要素はカンマの連続や末尾のカンマによって生じる可能性がある。
				// 末尾のカンマは許容される。
				// "1," の場合、parts=["1", ""]。これは1個以上の数字列が区切られていると見なせる。
			}
		}

		if !isTolerable {
			continue
		}

		// 少なくとも1つの数字列が存在すれば妥当
		if hasNumber {
			validCount++
		} else {
			// 例: "," の場合、parts=["", ""]。hasNumberはfalse。不適。
			// 例: "," の行は、空行でないが、数字列を含まないため不適。
			// ただし、行が空でなければ、カンマのみの行は「数字列列」ではないため不適。
			// 「数字とカンマ以外を含む行」に該当しないか確認。カンマのみは含まれる。
			// 「1 個以上の数字列がカンマで区切られて並んでいる」を満たさない。
		}
	}

	fmt.Println("valid=", validCount)
}
