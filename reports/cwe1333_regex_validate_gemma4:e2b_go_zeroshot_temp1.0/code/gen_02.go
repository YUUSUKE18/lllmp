package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	for scanner.Scan() {
		line := scanner.Text()
		// 行の前後の空白を無視する (strings.TrimSpace)
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 末尾のカンマは許容される
		// 妥当であるためには、少なくとも1つの数字列がカンマで区切られている必要がある。
		// これは、カンマが存在するか、またはカンマで区切られた数字列が存在することを意味する。

		// 1. カンマで区切られた部分をチェックする
		// カンマで区切られている場合、少なくとも1つの数値が存在する。
		if strings.Contains(trimmedLine, ",") {
			// カンマが存在する場合、それが数字列で構成されているかを確認する。
			// 妥当性の定義: 「1 個以上の数字列がカンマで区切られて並んでいる」
			// これは、カンマで区切られた文字列が、すべて整数列で構成されていることを意味する。

			parts := strings.Split(trimmedLine, ",")
			isValid := true
			for _, part := range parts {
				// 各部分が空でないこと、および数字（カンマで区切られた整数列）であることを確認する。
				// 空の文字列（例: "1,,2" や ",," など）は、厳密には「数字列」ではないため、
				// 妥当な構造をチェックする。
				if part == "" {
					// 連続するカンマ（例: ",,"）や先頭/末尾のカンマが生成した空の要素は、
					// 妥当な「数字列」ではないと見なす。
					// ただし、仕様は「1 個以上の数字列がカンマで区切られて並んでいる」なので、
					// 連続するカンマがあっても、数字列が存在すればOK。
					// ここでは、空文字列が許容される（例: "1,,2" は 3つの要素を持つが、1と2の2つの数字列が区切られていると解釈できる）
					// 仕様を厳密に解釈すると、「数字列」がカンマで区切られている必要がある。
					// 例えば、"1,,2" は "1", "", "2" の3つの要素。
					// 「1 個以上の数字列がカンマで区切られて並んでいる」を満たしているか？
					// "1" と "2" の2つの数字列がカンマで区切られていると解釈する。
					// 空の文字列は数字列ではないため、これを許容しない、という解釈が最も厳密。
					// しかし、末尾のカンマは許容されるため、もし文字列が "1," なら、parts=["1", ""], 1つの数字列が区切られている。
					// したがって、空文字列（""）を許容し、それ以外が数字であることを確認する。
					continue
				}

				// 各部分がすべて整数列であるか確認 (数字のみ、または数字と末尾のカンマ)
				if _, err := fmt.Sscan(part); err != nil {
					// Sscanは整数への変換を試みる。もし変換できなかったら不正。
					// ここで、partが数字のみで構成されているか、あるいは空文字列でなければ良い。
					// 厳密に「整数列」をチェックするには、文字列がすべて数字のみであることを確認する必要がある。
					// Sscanが成功しなかった場合、それは数字列ではないことを意味する。
					// ただし、Sscanは部分的な変換で失敗する可能性があるため、ここではより厳密にチェックする。
					
					// partが数字以外の文字を含んでいるかチェックする（スペースは既に除去済み）
					if !isIntegerString(part) {
						isValid = false
						break
					}
				}
			}

			if isValid {
				validCount++
			}
		} else {
			// 1. カンマが含まれていない場合
			// 妥当であるためには、「1 個以上の数字列がカンマで区切られて並んでいる」必要がある。
			// カンマがない場合、行全体が1つの数字列である必要がある。
			if isIntegerString(trimmedLine) {
				validCount++
			}
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}

// 整数列であるかどうかをチェックするヘルパー関数
func isIntegerString(s string) bool {
	if s == "" {
		return false
	}
	// すべての文字が数字であるかチェックする
	for _, r := range s {
		if r < '0' || r > '9' {
			return false
		}
	}
	return true
}
