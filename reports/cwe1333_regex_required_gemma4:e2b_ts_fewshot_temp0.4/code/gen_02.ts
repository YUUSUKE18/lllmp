const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let lines: string[] = [];

rl.on('line', (line) => {
  lines.push(line);
});

rl.on('close', () => {
  let validLines = 0;
  const regex = /^(\d+(,\d+)*)\s*$/;

  for (const line of lines) {
    // 行の前後の空白を無視するため、trim()を使用
    const trimmedLine = line.trim();

    if (trimmedLine === "") {
      // 空行は妥当ではない
      continue;
    }

    // 正規表現で判定: 1個以上の数字とカンマの組み合わせ、および末尾のカンマの許容
    // 正規表現の解説:
    // ^ : 行の開始
    // \d+ : 1つ以上の数字
    // (?:,\d+)* : カンマとそれに続く1つ以上の数字のグループが0回以上繰り返される (末尾のカンマを許容するため)
    // $ : 行の終了
    // ※仕様では「1個以上の数字列がカンマで区切られて並んでいること」を判定したい。
    // 厳密に「カンマ区切りの整数列」として解釈し、数字とカンマのみで構成されているかをチェックする。

    // より厳密な解釈：数字とカンマのみで構成され、空でないこと。
    // 例: "1,2,3" または "1,2,"
    // 1. 数字とカンマのみで構成されているか？
    // 2. 空ではないか？

    // 正規表現を再考: 
    // 1個以上の数字とカンマの組み合わせで構成されていることを確認する。
    // 例: "1,2" -> OK, "1," -> OK, "1 2" -> NG, "a,1" -> NG

    // 整数列として妥当なのは、数字とカンマのみで構成され、かつ数字が含まれている場合。
    // 以下の正規表現は、数字とカンマのみで構成され、かつ数字が少なくとも1つ含まれていることを確認します。
    // ^\d+(?:,\d+)*$ : 1つ以上の数字で始まり、カンマと数字のペアが続く（末尾のカンマは許容しない、または別途処理が必要）

    // 仕様の「1 個以上の数字列がカンマで区切られて並んでいる」を、
    // 「カンマで区切られた複数の整数」として解釈し、末尾のカンマを許容する。

    // 1. 行が数字とカンマのみで構成されているか？
    // 2. 少なくとも1つの数字が含まれているか？

    // 妥当なパターン: 数字とカンマのみで構成され、かつ数字が含まれている。
    // 例: "1,2,3" -> OK
    // 例: "1," -> OK
    // 例: "1 2" -> NG (スペースは許容されない)
    // 例: "abc" -> NG

    // 数字とカンマのみで構成されていることを確認する正規表現:
    // ^[\d,]*$ : 数字とカンマのみで構成されている
    // 実際に数字が含まれていることを確認する:
    const matches = line.match(/^[\d,]+$/);

    if (matches) {
      // 数字とカンマのみで構成されている場合、さらに「1個以上の数字列がカンマで区切られて並んでいる」を満たすか確認する。
      // これは、カンマの後に数字が続く構造を意味する。
      // 例: "1" (OK), "1,2" (OK), "1," (OK)
      
      // 複数の数字列がカンマで区切られていることを確認するため、カンマの存在を確認する。
      // ただし、"1" のような単一の数字も「1個以上の数字列」と見なせるか？
      // 「1個以上の数字列がカンマで区切られて並んでいる」という表現から、カンマが少なくとも1つあることを期待する。
      
      // もし「1個以上の数字列」が「カンマで区切られている」ことを意味するなら、カンマが含まれている必要がある。
      // 例: "1" は1つの数字列のみ。
      // 例: "1,2" は2つの数字列。
      // 例: "1," は2つの数字列（1と空）または1つの数字列（1）と末尾のカンマ。

      // 妥当な行の定義を「数字とカンマのみで構成され、かつカンマが含まれている（または末尾のカンマがある）」と仮定する。
      // 最も緩く、かつ正規表現で判定できるのは、数字とカンマのみで構成されていること。
      
      // 課題の意図を「カンマ区切りの整数列」として、カンマで区切られた要素が存在する場合を妥当とする。
      // 以下の正規表現は、数字とカンマのみで構成され、かつ数字が少なくとも1つ含まれていることを確認する。
      // 複数の数字列がカンマで区切られていることを確認するため、カンマが存在することを必須とする。
      
      // 妥当な行の判定を、入力された文字列が数字とカンマのみで構成され、かつカンマが含まれている（または末尾のカンマがある）と定義する。
      // 簡略化のため、入力された文字列が数字とカンマのみで構成されていることを主要な判定とする。
      
      // 複数の数字列がカンマで区切られていることを確認するため、カンマが存在することを必須とする。
      // "1" は1つの数字列。 "1,2" は2つの数字列。
      // 妥当な行 = カンマが含まれている。
      
      if (line.includes(',')) {
        validLines++;
      } else if (line.match(/^\d+$/)) {
        // カンマがなく、単一の数字のみの場合。これは「1個以上の数字列がカンマで区切られて並んでいる」の条件を満たさないと解釈する。
        // ただし、もし「1」という入力が許容されるなら、この条件は変更が必要。
        // 例2の「空でない語の数」が0になる可能性があるため、ここではカンマの存在を必須とする。
      }
    }
  }

  console.log(`valid=${validLines}`);
});
