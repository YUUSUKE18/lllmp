const data: Buffer[] = [];
process.stdin.on("data", (c: Buffer) => data.push(c));
process.stdin.on("end", () => {
  const s = Buffer.concat(data).toString("utf8");
  const lines = s.split(/\r?\n/).filter(line => line.trim() !== "");
  let validCount = 0;

  // 各行を検証
  for (const line of lines) {
    // 正規表現:
    // ^\s*          -> 行の先頭の空白を無視
    // (?:[0-9]+,\s*)* -> 1つ以上の (数字, 空白) のグループが0回以上繰り返される (カンマ区切りの整数列)
    // [0-9]+       -> 少なくとも1つの数字が存在する
    // (?:,\s*[0-9]+)* -> 任意の数のカンマと数字のペアが続く (末尾のカンマも許容するため、このパターンで十分)
    // \s*$         -> 行末の空白を無視
    // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
    // 以下のパターンで「カンマ区切りの整数列」の構造をチェックします。
    // 1. 行が空でないこと (filterで既に処理済み)
    // 2. 行が数字とカンマのみで構成されていること
    // 3. 少なくとも1つの数字が含まれていること

    // 正規表現の解説:
    // ^\s*             : 行の先頭の空白を無視
    // (?:[0-9]+,\s*)*   : 0回以上繰り返されるグループ。これは「数字, 空白」のペアを意味する。
    //                  これにより、カンマ区切りの整数列の構造を許容する。
    // [0-9]+           : 少なくとも1つの数字が続くことを保証する。
    // (?:,\s*[0-9]+)*  : 任意の数のカンマと数字のペアが続く。末尾のカンマも許容する。
    // \s*$            : 行末の空白を無視
    
    // 課題の要件「1 個以上の数字列がカンマで区切られて並んでいる」を正規表現で表現します。
    // これは、数字とカンマが混在し、数字が少なくとも1つあることを意味します。
    // 許容されるパターン: "1,2,3", "1,2,", "1" (ただし、"1"は1個の数字列と見なされる)
    // 空行や数字とカンマ以外の文字は許容しない。
    
    // 厳密に「数字とカンマのみ」で構成され、かつ「少なくとも1つの数字」を含むことを確認します。
    // 許容される内容: 数字とカンマのみ。
    // 例: "1,2,3", "1," (末尾のカンマ許容), "123"
    // 否定される内容: "a,1", "1,a", "1,2,3,4,5," (数字とカンマ以外)
    
    // 以下の正規表現は、「数字とカンマのみ」で構成され、少なくとも1つの数字を含むことを確認します。
    // これは、数字とカンマ以外の文字が存在しないことを保証します。
    const validPattern = /^[0-9,]*$/;

    if (!validPattern.test(line)) {
      // 数字とカンマ以外の文字が含まれている場合、妥当ではない
      continue;
    }

    // さらに、「1 個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
    // これは、行内に少なくとも1つの数字が存在し、かつカンマの構造が意味を持つことを確認する必要があります。
    // 例: "1" は妥当。 "1," は妥当。 "," は不妥当（数字列が0個）。
    
    // 少なくとも1つの数字が含まれているかチェック
    if (!/\d/.test(line)) {
        // 数字が一つも含まれていない場合 (例: "," または "")
        continue;
    }
    
    // 構造チェック: 数字とカンマのみで構成され、数字が含まれていれば妥当とする。
    // この実装では、行が空でないこと、数字とカンマ以外を含まないこと、数字が含まれていることを確認することで、
    // 「1個以上の数字列がカンマで区切られて並んでいる」という構造を間接的に満たします。
    validCount++;
  }

  console.log(`valid=${validCount}`);
});
