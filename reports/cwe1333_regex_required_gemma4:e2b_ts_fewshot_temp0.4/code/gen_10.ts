const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let lines = 0;
let validLines = 0;

rl.on('line', (line) => {
  lines++;
  // 正規表現: 
  // ^\s*       - 行頭の空白を無視
  // (?:[0-9]+,\s*)* - 1つ以上の (数字 + カンマ + 空白) のパターンが0回以上繰り返される
  // [0-9]+     - 最後の数字列
  // (?:,\s*|$)  - カンマと空白、または行末
  // $          - 行末
  // この正規表現は、数字とカンマのみで構成され、空行やその他の文字を含まないことを確認するのに役立ちます。
  // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するために、
  // 以下のロジックで検証します。
  
  // 1. 空行のチェック
  if (line.trim() === "") {
    // 空行は妥当ではない
    return;
  }

  // 2. 正規表現による検証
  // 1個以上の数字列がカンマで区切られていることを確認する。
  // 許容されるパターン: 数字, 数字, ..., 数字, (カンマ)
  // 例: "1,2,3" または "1,2,"
  // 数字とカンマ以外の文字を含まないことを確認するため、
  // 1. 数字とカンマのみで構成されているかを確認する。
  // 2. カンマで区切られているかを確認する。
  
  // 正規表現の解説:
  // ^\s*             : 行頭の空白を無視
  // (?:[0-9]+,\s*)*  : 1つ以上の (数字 + カンマ + 空白) のグループが0回以上繰り返される
  // [0-9]+           : 最後の数字列
  // (?:,\s*|$)       : 最後のカンマと空白、または行末
  // \s*$            : 行末の空白
  
  // 簡略化のため、ここでは「数字とカンマのみで構成され、空でない」ことを確認し、
  // 実際に分割して数字のみが残るかを確認するアプローチを取ります。
  
  // 厳密な仕様に基づき、数字とカンマ以外の文字が含まれていないかを確認し、
  // カンマで区切られた数字列が存在するかを確認します。
  
  // 数字とカンマのみで構成されているかチェック
  const validCharsRegex = /^[0-9,]*$/;
  if (!validCharsRegex.test(line)) {
    return; // 数字とカンマ以外が含まれていたら不妥当
  }
  
  // カンマで区切られた数字列が存在するかチェック
  // 1. カンマで分割し、空でない要素があるか確認する。
  const parts = line.split(',');
  let hasNumbers = false;
  for (const part of parts) {
    if (part.trim() !== "") {
      // その部分が整数であるか確認 (数字のみ)
      if (/^[0-9]+$/.test(part.trim())) {
        hasNumbers = true;
      } else {
        // 数字とカンマ以外が含まれていた場合、これは上記のvalidCharsRegexで既に除外されるはずだが、念のため
        // (例: "1,a,2" は validCharsRegex で弾かれる)
        // このチェックは、数字列がカンマで区切られていることを保証する。
      }
    }
  }

  if (hasNumbers) {
    validLines++;
  }
});

rl.on('close', () => {
  console.log(`valid=${validLines}`);
});
