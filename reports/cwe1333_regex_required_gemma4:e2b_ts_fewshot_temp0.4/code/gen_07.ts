const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  terminal: false
});

let lines: string[] = [];

rl.on('line', (line) => {
  lines.push(line);
});

rl.on('close', () => {
  let validLines = 0;
  const validRegex = /^[\d,]+(?:,[\d,]+)*$|^,[\d,]+(?:,[\d,]+)*$|^,$/;

  for (const line of lines) {
    const trimmedLine = line.trim();
    if (trimmedLine === "") {
      continue; // 空行は妥当ではない
    }

    // 末尾のカンマを許容しつつ、数字とカンマのみで構成されているかを確認する
    // 正規表現の調整: 
    // 1. 1個以上の数字とカンマの組み合わせ (例: 1,2,3, または 1,2,3,)
    // 2. 末尾のカンマのみ (例: ,)
    // 3. カンマのみ (例: ,) - これは「1個以上の数字列がカンマで区切られて並んでいる」という要件を満たさないため、厳密に数字列が伴うことを確認する。

    // 要件の再解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
    // これは、カンマで区切られた要素がすべて整数（または整数列）である必要がある。
    // 例: "1,2,3" -> 3つの数字列
    // 例: "1,2," -> 2つの数字列
    // 例: "," -> 0個の数字列（または不正）

    // 妥当なパターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれていること。
    // 許容されるパターン: 1,2,3, または 1,2, または 1,2,
    const isValid = /^[0-9,]+(?:,[0-9,]+)*$|^,?[0-9,]+(?:,[0-9,]+)*$|^,?$/.test(line);

    // より厳密に「1個以上の数字列」をチェックするため、カンマで区切られた要素がすべて数字列であるかを確認する。
    // 以下の正規表現は、カンマ区切りの数字列が連続していることを確認する。
    // 1. 1つ以上の数字列がカンマで区切られている (例: 1,2,3)
    // 2. 末尾にカンマがあっても良い (例: 1,2,)
    // 3. カンマのみ (例: ,) は除外したい。

    // 妥当なパターンを再定義: 
    // 1. 少なくとも1つの数字が含まれている。
    // 2. 数字とカンマ以外の文字が含まれていない。
    // 3. カンマで区切られている。

    // 以下の正規表現は、数字とカンマのみで構成され、少なくとも1つの数字が含まれることを確認する。
    // (数字とカンマの組み合わせが連続していることを許容)
    const strictRegex = /^[\d,]+(?:,[\d,]+)*$|^,[\d,]+(?:,[\d,]+)*$|^,?$|^,$/;
    
    // 最終的な判定ロジック（正規表現の適用）
    // 行が空でないことを確認し、数字とカンマのみで構成されていることを確認する。
    // 末尾のカンマは許容される。
    // 1個以上の数字列がカンマで区切られていること。
    
    // 妥当な行の判定:
    // 1. 行が空でない。
    // 2. 行に含まれる文字が数字('0'-'9')とカンマ(',')のみである。
    // 3. 少なくとも1つの数字が含まれている（カンマのみの行は除外）。
    // 4. カンマで区切られている（カンマが0個または1個以上存在する）。
    
    // 簡略化のため、入力された行が「カンマ区切りの整数列」の形式を満たしているかをチェックする。
    // 許容される形式: 1,2,3, または 1,2, または 1,2,
    // 許容される形式: ,1,2, または ,
    
    // 1. 数字とカンマのみで構成されているか
    const containsOnlyDigitsAndCommas = /^[0-9,]*$/.test(line);
    
    if (!containsOnlyDigitsAndCommas) {
      continue; // 数字とカンマ以外を含む行は妥当ではない
    }
    
    // 2. 少なくとも1つの数字が含まれているか (カンマのみの行を除外)
    const containsDigit = /\d/.test(line);
    
    if (!containsDigit) {
      // カンマのみの行 (例: "," または ",,") は妥当ではない
      continue;
    }

    // 3. カンマ区切りであること (これは上記2で暗黙的に満たされるが、念のため)
    // 1個以上の数字列がカンマで区切られていることを確認。
    // 実際には、数字とカンマのみで構成され、数字が含まれていれば、それは「カンマ区切りの整数列」として扱う。
    validLines++;
  }

  console.log(`valid=${validLines}`);
});
