const data: Buffer[] = [];
process.stdin.on("data", (c: Buffer) => data.push(c));
process.stdin.on("end", () => {
  const s = Buffer.concat(data).toString("utf8");
  const lines = s.split(/\r?\n/).filter(line => line.trim() !== "");

  let validLines = 0;
  const regex = /^[\d,]+,?$|^[\d,]+$|^[\d,]+,[\d,]+.*$/;

  for (const line of lines) {
    const trimmedLine = line.trim();

    // 1. 空行は除外済み (filterで処理済み)

    // 2. 数字とカンマのみ、または数字とカンマの組み合わせであるかを確認
    // 末尾のカンマは許容する。
    // 正規表現の解説:
    // ^[\d,]+,?$ : 数字とカンマのみで構成され、末尾にカンマがあっても良い (例: "1,2" または "1,2,")
    // |         : または
    // [\d,]+$    : 数字とカンマのみで構成される (例: "123" または "1,2,3")
    // |         : または
    // [\d,]+,[\d,]+.* : 数字とカンマが混在し、中身がある (例: "1,2,3,4")
    //
    // よりシンプルに「数字とカンマのみ」で構成され、かつ「1個以上の数字列」がカンマで区切られているか、または単なる数字列であるかを判定する。
    // 仕様：「1 個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容する。」
    // これは、カンマで区切られた要素がすべて数字（カンマを含む）で構成されていることを意味する。

    // 許容されるパターン:
    // 1. 数字とカンマのみで構成されている (例: "1,2", "123", "1,2,")
    // 2. 数字とカンマが混在している (例: "1,2,3")

    // 空白や数字・カンマ以外の文字が含まれていないことを確認する。
    // 厳密に「数字とカンマのみ」で構成されている行を対象とする。
    const matches = line.match(/^[\d,]+(?:,[\d,]+)*$/);

    if (matches) {
      validLines++;
    }
  }

  console.log(`valid=${validLines}`);
});
