const data: Buffer[] = [];
process.stdin.on("data", (c: Buffer) => data.push(c));
process.stdin.on("end", () => {
  const input = Buffer.concat(data).toString("utf8");
  const lines = input.split('\n').length;
  let validLines = 0;

  // 各行をチェック
  for (const line of input.split('\n')) {
    const trimmedLine = line.trim();

    // 空行は妥当ではない（仕様：空行は妥当ではない）
    if (trimmedLine === "") {
      continue;
    }

    // 正規表現による判定: 
    // ^[0-9,]*$ : 行が数字とカンマのみで構成されていることを確認
    // (?:[0-9,]+) : 少なくとも1つの数字が含まれていることを確認（カンマ区切りの整数列）
    // .*$ : 行の残りの部分（ここでは行全体がこのパターンにマッチするかどうかを厳密にチェックする）
    
    // 仕様の解釈: 1個以上の数字列がカンマで区切られて並んでいること。
    // これは、行がカンマで区切られた数字の集合で構成されていることを意味します。
    // 末尾のカンマは許容されます。
    // 空行、および数字とカンマ以外を含む行は妥当ではない。

    // 妥当な行の条件を再定義:
    // 1. 行が空でないこと (trimmedLine !== "")
    // 2. 行が数字とカンマのみで構成されていること (正規表現でチェック)
    // 3. 少なくとも1つの数字が含まれていること (カンマ区切りの整数列)

    // 正規表現の設計: 
    // ^[0-9,]* : 任意の数の数字またはカンマ
    // (?:[0-9]+) : 少なくとも1つの数字が存在すること (グループ化は必須ではないが、存在確認のため)
    // [0-9,]*$ : 行の終わりまで数字またはカンマのみ
    
    // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックするには、
    // カンマで区切られた要素がすべて整数である、という前提が必要です。
    // ここでは、行が数字とカンマのみで構成され、かつ数字が少なくとも1つ含まれているかをチェックします。
    
    // 1. 数字とカンマのみで構成されているか (数字とカンマ以外の文字がないか)
    const regexCheck = /^[0-9,]*$/;
    if (!regexCheck.test(line)) {
      continue; // 数字とカンマ以外を含む行は不妥当
    }

    // 2. 少なくとも1つの数字が含まれているか (カンマ区切りの整数列)
    // 数字が含まれているかを確認するために、数字のみを含む部分があるかチェックする。
    const containsDigit = /[0-9]/.test(line);
    
    if (containsDigit) {
      validLines++;
    }
  }

  console.log(`valid=${validLines}`);
});
