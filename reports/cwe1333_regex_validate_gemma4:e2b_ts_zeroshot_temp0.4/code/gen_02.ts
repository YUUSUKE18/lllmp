import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    if (!input) {
        console.log('valid=0');
        return;
    }

    const lines = input.split('\n');
    let validCount = 0;

    for (const line of lines) {
        // 行の前後の空白を無視
        const trimmedLine = line.trim();

        if (trimmedLine === '') {
            // 空行は妥当ではない
            continue;
        }

        // 末尾のカンマは許容されるため、行全体をチェックする
        // 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」こと。
        // これは、少なくとも1つのカンマが存在するか、または数字のみで構成されている場合に適用される。
        // 仕様の解釈：「1 個以上の数字列がカンマで区切られて並んでいる」
        // 例: "1,2,3" -> 3つの数字列
        // 例: "123" -> 1つの数字列（カンマがない場合も許容されるか？「カンマで区切られて並んでいる」が必須なら、カンマが必要）
        // 仕様：「1 個以上の数字列がカンマで区切られて並んでいることです。」
        // 「末尾のカンマは許容します。」

        // 妥当性の判定ロジックを再検討します。
        // 1. 空行は不適。
        // 2. 数字とカンマ以外を含む行は不適。
        // 3. 妥当な行は「1 個以上の数字列がカンマで区切られて並んでいる」こと。

        // 1. 数字とカンマ以外を含む行のチェック
        let isValidCharacters = true;
        for (const char of trimmedLine) {
            if (!/^[0-9,]*$/.test(char)) {
                isValidCharacters = false;
                break;
            }
        }
        if (!isValidCharacters) {
            continue;
        }

        // 2. カンマ区切りのチェック
        // 末尾のカンマは許容される。
        // 妥当なのは「1個以上の数字列がカンマで区切られている」場合。
        // これは、カンマが存在する場合、または数字のみの場合を考慮する必要があります。

        // 最も緩い解釈（数字とカンマのみで構成されていること、かつ空行でないこと）
        // もし「カンマで区切られている」ことが必須なら、少なくとも1つのカンマが必要、または数字のみでOK。
        // 「1 個以上の数字列がカンマで区切られて並んでいる」
        // これは、カンマが1つ以上あるか、または数字のみで構成されている場合に満たされると解釈します。
        // ただし、末尾のカンマは許容される。

        // 妥当な行の判定：
        // 1. 行が空でない。
        // 2. 行に含まれる文字は数字とカンマのみ。
        // 3. 少なくとも1つの数字列が存在する。

        // 数字列が存在するかどうかをチェック
        const parts = trimmedLine.split(',');
        let hasDigits = false;
        for (const part of parts) {
            if (part.trim() !== '') {
                // 数字列が存在する
                hasDigits = true;
            }
        }

        // 末尾のカンマの処理：split(',')は末尾のカンマを考慮して要素を生成する。
        // 例: "1,2," -> ["1", "2", ""]
        // "123" -> ["123"]

        // 妥当な条件：数字列が1つ以上存在すること。
        if (hasDigits) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
