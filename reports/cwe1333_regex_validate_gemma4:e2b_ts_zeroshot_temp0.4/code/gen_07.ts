import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    if (!input) {
        console.log('valid=0');
        return;
    }

    const lines = input.split('\n');
    let validCount = 0;

    for (const line of lines) {
        // 行の前後の空白を無視
        const trimmedLine = line.trim();

        if (trimmedLine === "") {
            // 空行は妥当ではない
            continue;
        }

        // 末尾のカンマは許容する
        // 正規表現で、数字とカンマのみで構成されているか、かつ少なくとも1つの数字が含まれているかをチェックする
        // ^\s* : 行の先頭の空白
        // (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ (例: 1,2,3 または 1,2,3,)
        // \s*$ : 行の末尾の空白
        // この正規表現は、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを保証する。
        // 末尾のカンマも許容するため、行全体をチェックする。
        
        // 妥当性の判定ロジックを再考：
        // 妥当とは「1 個以上の数字列がカンマで区切られて並んでいること」
        // これは、カンマで区切られた要素がすべて整数である必要があることを意味する。
        
        // 1. 行をカンマで分割する
        const parts = trimmedLine.split(',');

        if (parts.length === 0) {
            // これは空行で既に除外されているはずだが念のため
            continue;
        }

        let isValid = false;
        
        // 各部分が空でないか、かつ整数であるかを確認する
        // 妥当な形式: 1個以上の数字列がカンマで区切られている。
        // 例: "1,2,3" -> ["1", "2", "3"] (長さ3)
        // 例: "1,2," -> ["1", "2", ""] (長さ3)
        // 例: "1,," -> ["1", "", ""] (長さ3)
        
        // 妥当な行は、少なくとも1つの要素が数字（カンマで区切られた整数）である必要がある。
        // 空行は除外済み。
        // 数字とカンマ以外を含む行は除外。
        
        // 妥当な行の定義を厳密に解釈する:
        // 「1 個以上の数字列がカンマで区切られて並んでいること」
        // これは、カンマで区切られた要素がすべて整数である、ということを意味する。
        // ただし、仕様には「数字とカンマ以外を含む行は妥当ではない」とあるため、
        // 各要素が数字のみで構成されている必要がある。
        
        // 1. 全ての要素が空文字列でないこと (カンマが連続していない、または空要素がない)
        // 2. 全ての要素が整数であること
        
        // 厳密に「カンマ区切りの整数列」を評価する。
        // 末尾のカンマは許容。
        
        // 例: "1,2,3" -> OK
        // 例: "1,2," -> OK (末尾のカンマは許容)
        // 例: "1,a,3" -> NG (aは整数ではない)
        // 例: ",," -> NG (数字列が0個)
        // 例: "" -> NG (空行)
        // 例: "abc" -> NG (数字とカンマ以外を含む)
        
        const allPartsAreValid = parts.every(part => {
            if (part === "") {
                // 末尾のカンマによる空要素は許容されるが、
                // 連続するカンマや、数字とカンマ以外の文字が含まれる場合はNG。
                // ここでは、空要素は「区切り」として許容されるが、
                // 「数字列が並んでいる」という条件を満たす必要がある。
                // 空要素が許容される場合、"1,,2" は "1", "", "2" と解釈される。
                // この解釈では、"1,2" は OK だが、"1,,2" は OK になる。
                // 仕様：「1 個以上の数字列がカンマで区切られて並んでいる」
                // 空要素は「数字列」ではないため、ここでは空要素はNGとするのが妥当。
                return false; // 空要素はNGとする
            }
            // 数字のみで構成されているかチェック
            return /^\d+$/.test(part);
        });

        if (allPartsAreValid) {
            // 少なくとも1つの要素が存在すれば妥当
            isValid = parts.some(part => part.length > 0);
        }
        
        // 末尾のカンマの許容を考慮した最終チェック
        // "1,2,3" -> ["1", "2", "3"] -> allPartsAreValid=true, isValid=true
        // "1,2," -> ["1", "2", ""] -> allPartsAreValid=false (空要素のため)
        // この解釈だと、末尾のカンマが許容されるという条件と矛盾する可能性がある。
        
        // 仕様を再解釈: 
        // 「カンマで区切られたもの」が「整数列」であること。末尾のカンマは区切り記号として許容される。
        
        // 最終的な判定ロジック：
        // 1. 行が空でないこと。
        // 2. 行全体を、数字とカンマのみで構成されていること。
        // 3. 区切られた要素がすべて整数であること（空要素は許容しない）。
        
        let finalIsValid = false;
        if (trimmedLine.length > 0) {
            // 末尾のカンマを削除してチェックする（末尾のカンマは許容されるため、その後の文字列が数字のみで構成されているか確認する）
            const content = trimmedLine.endsWith(',') ? trimmedLine.slice(0, -1) : trimmedLine;
            
            if (content.length > 0) {
                const actualParts = content.split(',');
                
                // すべての要素が数字のみで構成されているか、かつ空要素がないか
                const allAreDigits = actualParts.every(p => /^\d+$/.test(p));
                
                if (allAreDigits) {
                    // 少なくとも1つの要素があること
                    if (actualParts.length >= 1) {
                        finalIsValid = true;
                    }
                }
            }
        }


        if (finalIsValid) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
