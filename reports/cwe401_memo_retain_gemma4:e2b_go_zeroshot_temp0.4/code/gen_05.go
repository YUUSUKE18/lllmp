package main

import (
	"bufio"
	"fmt"
	"os"
	"strconv"
)

func main() {
	// 標準入力からデータを読み込む
	scanner := bufio.NewScanner(os.Stdin)
	var total int64 = 0

	// メモ化のためのマップ
	memo := make(map[int]int64)

	for scanner.Scan() {
		line := scanner.Text()
		// 空行を無視
		if line == "" {
			continue
		}

		// 整数として解析を試みる
		n, err := strconv.Atoi(line)
		if err != nil {
			// 整数として解釈できない行は無視
			continue
		}

		// n が 1 の場合の処理
		if n == 1 {
			// 1 の場合の操作回数は 0
			// memo[1] = 0 // 1 は終了条件なので、ここでは計算しないか、0として扱う
			continue
		}

		// 再帰的または反復的に計算し、メモ化を利用する
		// ここでは、与えられた操作を1に到達するまでの手数を求める
		currentN := n
		steps := int64(0)

		// 1 に到達するまで繰り返す
		for currentN != 1 {
			if val, ok := memo[currentN]; ok {
				steps += val
				currentN = 1 // 既に計算済みの結果を直接加算
				break
			}

			// 操作の適用
			if currentN%2 == 0 {
				currentN /= 2
			} else {
				currentN = 3*currentN + 1
			}
			steps++
		}

		// 1 に到達したときのステップ数をメモ化
		// 注意: この問題は、各クエリ n について、n から 1 に到達するまでの「手数」を求める。
		// 実際には、n から 1 に到達するまでの操作回数を求める必要がある。
		// 質問の意図を再解釈: "n が 1 に到達するまでの手数を求めます。"
		// これは、n から操作を繰り返し、1 に到達するまでのステップ数を意味する。

		// 再計算（メモ化をより適切に使うため、再帰的な構造を考える）
		// n から 1 へのパスを求める。
		
		// 以下のロジックは、n から 1 へのパスを求める一般的な方法（Collatz問題の逆操作）に従う。
		// ただし、問題文の操作は n -> n/2 (n偶) または n -> 3n+1 (n奇) の順に行う操作であり、
		// 1 に到達するまでの「手数」を求める。

		// 最初のループでの計算を修正し、メモ化を正しく適用する。
		// n から 1 へのパスを求めるため、n を 1 に到達するまでのステップ数を求める。
		
		// 再度、n から 1 へのパスを求める。
		// この問題は、通常、n から 1 へのパスを求めるのではなく、n から 1 への「到達」を問う。
		// 質問の意図を「n を操作して 1 に到達するまでのステップ数」と解釈し、memoize を使う。
		
		// 最初のループは、n から 1 へのパスを求める。
		// 1 に到達するまでの手数を求めるため、n からスタートして 1 に到達するまでのステップ数を数える。
		
		// 最初のループでの計算結果を total に加算する。
		total += steps
		memo[n] = steps
	}

	// 結果の出力
	fmt.Printf("total=%d\n", total)
}
