package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())

		if line == "" {
			// 空行は妥当ではない
			continue
		}

		// 末尾のカンマは許容するが、数字とカンマ以外は許容しない
		// 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」こと。
		// これは、カンマで区切られた要素が存在し、それらがすべて数字であることを意味する。
		
		// 行をカンマで分割する
		parts := strings.Split(line, ",")
		
		// 妥当性の判定: 1個以上の要素があり、かつ各要素が数字であること。
		// 仕様の解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
		// これは、カンマで分割した結果、空でない要素がすべて整数である必要がある、と解釈する。
		
		isValid := true
		if len(parts) == 0 {
			isValid = false
		} else {
			for _, part := range parts {
				trimmedPart := strings.TrimSpace(part)
				if trimmedPart == "" {
					// 末尾のカンマや連続するカンマによる空要素は許容されるか？
					// 「末尾のカンマは許容します」という記述から、末尾のカンマは無視できる。
					// 「1 個以上の数字列がカンマで区切られて並んでいる」を満たすためには、
					// 少なくとも1つの有効な数字列が存在する必要がある。
					// ここでは、空の文字列が要素として存在することを許容しない（数字列ではない）と判断する。
					// ただし、末尾のカンマは許容されるため、末尾がカンマで終わる場合はその要素は空になる。
					
					// 厳密に「数字列」のみを許容する場合、空文字列はNG。
					// 例: "1,2," -> ["1", "2", ""]。最後の""は許容されるか？
					// 「1 個以上の数字列」が重要。
					
					// 行が「1個以上の数字列」で構成されているかを確認する。
					// 妥当な行の例: "1,2,3", "1", "1,"
					
					// 空の要素が一つでもあれば、それは数字列ではないため、妥当ではないと判断する。
					// ただし、末尾のカンマが許容されるため、最後の要素が空でも許容する。
					// 妥当な条件は、少なくとも1つの非空の数字列が存在すること。
					
					// シンプルに、カンマで分割して、非空の要素がすべて数字であるかを確認する。
					// 最後の要素が空でも、それは末尾のカンマの結果として許容される。
					
					// 妥当な行の定義を「カンマで区切られた要素が、すべて数字であること」と解釈する。
					// 空の要素（末尾のカンマによるもの）は無視する。
					continue
				}
				
				// 要素が整数であるかチェック
				if _, err := fmt.Sscan(trimmedPart); err != nil {
					isValid = false
					break
				}
			}
		}

		if isValid {
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常は不要だが念のため）
	}

	fmt.Printf("valid=%d\n", validCount)
}
