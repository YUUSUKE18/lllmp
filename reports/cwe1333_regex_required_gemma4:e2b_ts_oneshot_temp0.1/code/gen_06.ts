const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
  // 正規表現: 
  // ^\s*          -> 行頭の空白を無視
  // (?:          -> 非キャプチャグループ開始
  //   \d+,\s*    -> 1つ以上の数字とカンマ、それに続く空白（1個以上の要素）
  //   |          -> または
  //   \d+       -> 単独の数字（末尾のカンマを除く、またはカンマなしのケースを考慮するため）
  // )+           -> 上記のパターンが1回以上繰り返される
  // (?:,\s*|\s*$) -> 末尾がカンマと空白、または行末
  // $            -> 行末
  // 
  // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」を判定するために、
  // カンマで区切られた数字の並びをチェックします。
  // 許容されるパターン: 数字, 数字, ... (末尾のカンマは許容)
  // 
  // 判定ロジック:
  // 1. 行が空でないこと。
  // 2. 行が数字とカンマのみで構成されていること。
  // 3. 少なくとも1つの数字が含まれていること。
  
  // 正規表現の解説:
  // ^\s*             : 行頭の空白を無視
  // (?:              : 非キャプチャグループ開始
  //   \d+            : 1つ以上の数字
  //   (?:,\s*)?      : カンマと空白が0回または1回続く（最後の要素の後のカンマを許容するため）
  // )+               : 上記のパターンが1回以上繰り返される（複数の要素があることを保証）
  // (?:,\s*|\s*$)    : 末尾がカンマと空白、または行末
  // \s*$            : 行末の空白を無視
  
  // 簡略化して、カンマ区切りの整数列が1つ以上存在するかどうかをチェックします。
  // 許容されるのは「数字とカンマのみ」で構成され、かつ「数字」が少なくとも1つ含まれている場合です。
  
  // 1. 数字とカンマのみで構成されているか、および数字が含まれているかをチェック
  const regex = /^\s*[\d,]*\s*$/;
  if (!regex.test(line)) {
    // 数字とカンマ以外の文字が含まれている場合は妥当ではない
    // ただし、仕様では「空行、および数字とカンマ以外を含む行は妥当ではない」とあるため、
    // この行が数字とカンマのみで構成されているかを確認する必要があります。
    // 厳密に「カンマ区切りの整数列」を判定するため、数字とカンマ以外の文字がないことを確認します。
    
    // 念のため、数字とカンマ以外の文字が含まれていたら不適とします。
    // ただし、行が完全に空（空白のみ）の場合は、後続のチェックで不適とします。
    
    // ここでは、行が数字とカンマのみで構成されているか、かつ数字が含まれているかをチェックします。
    // 以下の正規表現は、数字とカンマのみで構成されていることを確認します。
    const content = line.trim();
    if (content === "") {
        // 空行は妥当ではない
        // continue; // 空行は妥当ではないので、validLinesは増えない
    } else if (!/^[0-9,]*$/.test(content)) {
        // 数字とカンマ以外の文字が含まれている場合は妥当ではない
        // continue;
    } else {
        // 数字とカンマのみで構成されている場合、少なくとも1つの数字が含まれているかチェック
        if (/[0-9]/.test(content)) {
            validLines++;
        }
    }
  } else {
    // 数字とカンマのみで構成されている場合、少なくとも1つの数字が含まれているかチェック
    if (/[0-9]/.test(line.trim())) {
        validLines++;
    }
  }
});

rl.on('end', () => {
  console.log(`valid=${validLines}`);
});
