const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
  // 正規表現: 
  // ^\s*          -> 行頭の任意の空白
  // (?:          -> 非キャプチャグループの開始
  //   \d+,\s*    -> 1つ以上の数字、カンマ、任意の空白
  // )+           -> 上記パターンが1回以上繰り返される
  // \d+          -> 最後の数字列
  // (?:,\s*)*     -> 末尾のカンマと空白が0回以上繰り返される
  // \s*$         -> 行末の任意の空白
  // この正規表現は「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
  // ただし、行全体が数字とカンマのみで構成されていることを確認するため、
  // より厳密に「数字とカンマのみ」で構成されていることを確認するパターンを組み合わせます。

  // 妥当性の判定ロジック
  // 1. 行が空でないこと
  // 2. 行が数字とカンマのみで構成されていること
  // 3. 少なくとも1つの数字列が含まれていること (カンマのみや空行は除く)

  // 判定のための正規表現:
  // ^\s*             -> 行頭の空白
  // (?:              -> 非キャプチャグループ
  //   \d+(?:,\s*\d+)* -> 1つ以上の数字、それに続くカンマと数字の繰り返し (例: 1,2,3 または 1,2,3,4)
  // )               -> グループの終わり
  // (?:,\s*)?       -> 末尾のカンマと空白が0回または1回 (末尾のカンマは許容)
  // \s*$            -> 行末の空白
  
  // よりシンプルに、数字とカンマのみで構成され、かつ数字が含まれているかをチェックします。
  // 妥当な行は、数字とカンマのみで構成され、かつ数字が少なくとも1つ含まれている必要があります。
  
  const trimmedLine = line.trim();
  
  if (trimmedLine.length === 0) {
    // 空行は妥当ではない
    return;
  }

  // 数字とカンマのみで構成されているかチェック
  // この行が「カンマ区切りの整数列」であるためには、数字とカンマ以外の文字が含まれていてはならない。
  const isNumericAndCommaOnly = /^[0-9,]*$/.test(trimmedLine);

  if (!isNumericAndCommaOnly) {
    // 数字とカンマ以外を含む行は妥当ではない
    return;
  }

  // 少なくとも1つの数字が含まれているかチェック
  // 数字が含まれていない場合（例: "," や ",," など）、妥当ではない
  const containsDigit = /\d/.test(trimmedLine);

  if (containsDigit) {
    // 1個以上の数字列がカンマで区切られているか、または単一の数字列であるか
    // 妥当な形式: 数字とカンマのみで構成され、かつ数字が含まれている。
    validLines++;
  }
});

rl.on('end', () => {
  console.log(`valid=${validLines}`);
});
