const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
  // 正規表現: 
  // ^\s*       - 行の先頭の空白を無視
  // (?:      - 非キャプチャグループの開始
  //   \d+    - 1桁以上の数字
  //   ,?     - カンマ（0個または1個）
  // )+       - 上記グループが1回以上繰り返される
  // \s*$      - 行末の空白を無視
  // この正規表現は、数字とカンマのみで構成され、1つ以上の数字列がカンマで区切られていることを確認します。
  // 末尾のカンマも許容するため、行全体が数字とカンマのみで構成されていることを確認します。
  // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するには、
  // 少なくとも1つの数字列が存在し、その間にカンマが適切に配置されている必要があります。

  // 妥当性の判定ロジックを正規表現で表現します。
  // 1. 行が空でないこと。
  // 2. 行が数字とカンマのみで構成されていること。
  // 3. 少なくとも1つの数字列が存在すること。

  // 妥当なパターン: 
  // 1つ以上の数字列と、それらを区切るカンマ（末尾のカンマも許容）
  // 例: "1,2,3", "1,2,"
  // 数字とカンマのみで構成され、数字が少なくとも1つ含まれていることを確認します。
  const regex = /^\s*(\d+(?:,\d+)*)(?:,*\d+)*\s*$/;
  
  // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する正規表現を試みます。
  // 数字とカンマのみで構成され、数字が少なくとも1つ含まれていることを確認します。
  // 許容される形式: 数字,数字,... または 数字,
  // 少なくとも1つの数字列が存在し、カンマが適切に配置されている必要があります。
  // 例: "1,2,3" -> OK
  // 例: "1" -> OK (カンマなしも許容されるか？仕様では「カンマで区切られて並んでいる」)
  // 「1個以上の数字列がカンマで区切られて並んでいる」
  // これは、数字の並びがカンマで区切られていることを意味します。
  // 最小のパターン: 数字が1つ以上存在し、カンマが0個以上存在する。
  
  // 以下の正規表現は、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
  // (?:[\d,]+) は、数字とカンマの連続を意味します。
  // ^\s*[\d,]+.*$ は、数字とカンマが少なくとも1つ含まれていることを確認します。
  // 末尾のカンマも許容するため、行全体が数字とカンマのみで構成されていることを確認します。
  
  // 妥当な行の定義: 
  // 1. 行が空でない。
  // 2. 行に含まれる文字が数字('0'-'9')とカンマ(',')のみである。
  // 3. 行に少なくとも1つの数字が含まれている。
  // 4. 末尾のカンマは許容される。

  // 簡略化のため、行をトリムし、数字とカンマのみで構成されているかを確認し、数字が含まれているかを確認します。
  const trimmedLine = line.trim();
  
  if (trimmedLine.length === 0) {
    // 空行は妥当ではない
    return;
  }

  // 数字とカンマのみで構成されているかチェック
  const onlyDigitsAndCommas = /^[0-9,]*$/.test(trimmedLine);

  if (!onlyDigitsAndCommas) {
    // 数字とカンマ以外を含む行は妥当ではない
    return;
  }

  // 少なくとも1つの数字が含まれているかチェック
  const containsDigit = /\d/.test(trimmedLine);

  if (containsDigit) {
    // 1個以上の数字列がカンマで区切られているか、または単一の数字列である場合
    // この条件は、数字とカンマのみで構成され、数字が含まれていれば、
    // 「1個以上の数字列がカンマで区切られて並んでいる」という条件を満たすと解釈します。
    validLines++;
  }
});

rl.on('end', () => {
  console.log(`valid=${validLines}`);
});
