const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
  // 正規表現: 
  // ^\s*          -> 行頭の任意の空白
  // (?:          -> 非キャプチャグループ開始
  //   \d+,\s*    -> 1つ以上の数字、カンマ、任意の空白
  // )+           -> 上記パターンが1回以上繰り返される
  // \d+          -> 最後の数字列
  // (?:,\s*)*     -> 末尾のカンマと空白が0回以上繰り返される
  // \s*$         -> 行末の任意の空白
  // この正規表現は「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
  // ただし、仕様では「1個以上の数字列がカンマで区切られて並んでいる」ことを確認し、
  // 空行や数字とカンマ以外の文字を含まないことを確認する必要があります。

  // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認し、
  // 空行や不正な文字を含まないことを確認します。
  // 1. 行が空でないこと
  // 2. 行が数字とカンマのみで構成されていること
  // 3. 少なくとも1つの数字列が存在すること
  
  // 正規表現の設計:
  // ^\s*             -> 行頭の空白
  // (?:              -> 非キャプチャグループ開始
  //   \d+,\s*        -> 1つ以上の数字、カンマ、空白
  // )+               -> 上記が1回以上繰り返される (少なくとも1つの数字列があることを保証)
  // \d+              -> 最後の数字列
  // (?:,\s*)*         -> 末尾のカンマと空白が0回以上繰り返される
  // \s*$             -> 行末の空白
  
  // 実際には、行全体が「数字とカンマ」で構成され、かつ「カンマで区切られた数字列」が存在する必要があります。
  // 以下の正規表現は、行が数字とカンマのみで構成され、少なくとも1つの数字列を含むことを確認します。
  const regex = /^\s*(?:\d+(?:,\s*\d+)*)\s*$/;
  
  // 仕様の解釈に基づき、より単純に「カンマ区切りの整数列」の構造をチェックします。
  // 1. 行が空でないこと
  // 2. 行が数字とカンマのみで構成されていること
  // 3. 少なくとも1つの数字列が存在すること
  
  // 試行錯誤の結果、最もシンプルで意図に近い判定は、行が数字とカンマのみで構成され、
  // 少なくとも1つの数字が含まれているかを確認することです。
  
  // 以下の正規表現は、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
  // (?:[0-9]+(?:,\s*[0-9]+)*) は、数字とカンマのペアが繰り返されるパターンを意味します。
  const strictRegex = /^\s*(?:[0-9]+(?:,\s*[0-9]+)*)\s*$/;

  if (strictRegex.test(line)) {
    validLines++;
  }
});

rl.on('end', () => {
  console.log(`valid=${validLines}`);
});
