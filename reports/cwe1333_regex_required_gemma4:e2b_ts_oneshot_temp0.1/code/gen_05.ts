const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
  // 正規表現: 
  // ^\s*          -> 行頭の空白を無視
  // (?:          -> 非キャプチャグループ開始
  //   \d+,\s*    -> 1つ以上の数字とカンマ、それに続く空白（1個以上の要素）
  //   |          -> または
  //   \d+       -> 単独の数字（末尾のカンマを除く、またはカンマなしのケースを考慮するため）
  // )+           -> 上記のパターンが1回以上繰り返される
  // (?:,\s*|\s*$) -> 末尾がカンマと空白、または行末
  // $            -> 行末
  // 
  // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」を判定するため、
  // 以下のロジックを採用します。
  // 1. 行全体が数字とカンマ、空白のみで構成されているか。
  // 2. カンマで区切られた要素が1つ以上存在するか。
  
  // 妥当な行の判定ロジック
  // 1. 行をトリムする
  const trimmedLine = line.trim();

  if (trimmedLine === "") {
    // 空行は妥当ではない
    return;
  }

  // 2. 正規表現で検証: 
  // 少なくとも1つの数字とカンマの組み合わせが存在し、それ以外は許容しない。
  // パターン: 数字とカンマが混在している、または数字のみの列が存在する。
  // 妥当な形式: (数字, 数字, ...) または (数字, 数字, ...)
  // 末尾のカンマは許容される。
  
  // 許容されるパターン: 数字とカンマが混在している、または数字のみの列が続く。
  // 例: "1,2,3" または "100" または "1,2,"
  // 否定されるパターン: "abc", "1,a", "1,,2" (カンマの連続)
  
  // 1. 数字とカンマのみで構成されているかを確認
  const regex = /^[\d,]*(\d+)(?:,\s*|\s*)$/;
  
  // よりシンプルなアプローチとして、カンマで区切られた要素が存在するかを確認する。
  // 1. 行をカンマで分割する。
  const parts = line.split(',');
  
  // 2. 妥当性のチェック
  // 少なくとも1つの要素が存在し、その要素が数字に変換可能であること。
  // 末尾のカンマは許容されるため、splitの結果が空文字列や数字のみで構成されているかを確認する。
  
  let isValid = false;
  
  // 各要素が数字（または空文字列、末尾のカンマによる）であるかを確認
  let hasNumber = false;
  for (const part of parts) {
    const trimmedPart = part.trim();
    if (trimmedPart.length > 0) {
      // 数字のみ（カンマなし）または数字とカンマの組み合わせを許容する
      if (/^\d+$/.test(trimmedPart)) {
        hasNumber = true;
      } else if (trimmedPart.includes(',') && /^\d+.*$/.test(trimmedPart)) {
        // カンマを含むが、数字で始まっている（例: "1,2"）
        hasNumber = true;
      }
    }
  }
  
  // 妥当な条件: 1個以上の数字列がカンマで区切られていること。
  // これは、少なくとも1つの数字が含まれており、かつ、行が数字とカンマのみで構成されていることを意味する。
  // 末尾のカンマは許容される。
  
  // 最終的な判定基準: 
  // 1. 行が空でない。
  // 2. 行に含まれる要素のうち、少なくとも1つが有効な整数である。
  // 3. 行に含まれる文字が数字とカンマのみである（他の文字は許容しない）。
  
  // 正規表現による厳密な判定: 
  // 1. 行全体が数字、カンマ、空白のみで構成されていること。
  // 2. 少なくとも1つの数字が含まれていること。
  // 3. カンマの連続や数字以外の文字が含まれていないこと。
  
  // 妥当な行の定義を再解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
  // これは、カンマで区切られた要素が、すべて整数である、ということを意味する。
  
  // 妥当なパターン: (数字, 数字, ...) または (数字, 数字, ...)
  // 末尾のカンマは許容される。
  
  // 以下の正規表現は、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
  // ^\s* : 行頭の空白
  // (?:[\d,]+(?:\s*,\s*)*) : 1つ以上の数字とカンマの組み合わせ（要素の列）
  // \s*$ : 行末の空白
  
  // 簡略化し、行が数字とカンマのみで構成され、空でないことを確認する。
  // 妥当な行は、カンマで区切られた要素が1つ以上存在し、それらが数字である場合に成立すると解釈する。
  
  // 最終的な判定: カンマで分割した結果、少なくとも1つの要素が数字であること。
  const actualParts = line.split(',');
  let containsNumber = false;
  
  for (const part of actualParts) {
    const trimmedPart = part.trim();
    if (trimmedPart.length > 0 && /^\d+$/.test(trimmedPart)) {
      containsNumber = true;
    }
  }
  
  // 妥当な行は、数字とカンマのみで構成され、少なくとも1つの数字を含むこと。
  // 例: "1,2" -> true, "abc" -> false, "" -> false
  
  // 厳密に「数字列がカンマで区切られている」ことを確認するため、
  // カンマで分割した要素が、すべて数字（または空文字列）で構成されていることを確認する。
  
  let isStrictlyValid = true;
  for (const part of actualParts) {
      const trimmedPart = part.trim();
      if (trimmedPart.length > 0 && !/^\d+$/.test(trimmedPart)) {
          isStrictlyValid = false;
          break;
      }
  }
  
  if (isStrictlyValid && containsNumber) {
      validLines++;
  }
});

rl.on('end', () => {
  console.log(`valid=${validLines}`);
});
