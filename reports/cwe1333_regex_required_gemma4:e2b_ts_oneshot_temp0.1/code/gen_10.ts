const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
  // 正規表現: 
  // ^\s*          -> 行頭の空白を無視
  // (?:          -> 非キャプチャグループ開始
  //   \d+,\s*    -> 1つ以上の数字とカンマ、それに続く空白（1個以上の要素）
  //   |          -> または
  //   \d+       -> 単独の数字（末尾のカンマを除く、またはカンマなしのケースを考慮するため）
  // )+           -> 上記のパターンが1回以上繰り返される
  // (?:,\s*|\s*$) -> 末尾がカンマと空白、または行末
  // $            -> 行末
  // 
  // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」を判定するため、
  // 以下のロジックを採用します。
  // 1. 行全体が数字とカンマ、空白のみで構成されているか。
  // 2. 少なくとも1つの数字が含まれているか。
  // 3. 末尾のカンマは許容する。
  
  // 判定ロジックの調整:
  // 1. 行をトリムして、カンマと数字以外がないか確認する。
  // 2. カンマで分割し、要素がすべて数字であることを確認する。
  // 3. 少なくとも1つの数字が含まれていることを確認する。

  const trimmedLine = line.trim();

  if (trimmedLine === "") {
    // 空行は妥当ではない
    return;
  }

  // 正規表現による判定: 
  // 1. 行が数字とカンマ、空白のみで構成されているか。
  // 2. 少なくとも1つの数字が含まれているか。
  // 3. 末尾のカンマは許容する。
  
  // パターン: 
  // ^\s*             -> 行頭の空白
  // (?:              -> 非キャプチャグループ
  //   \d+,\s*        -> 数字とカンマのセット（カンマ区切り）
  //   |              -> または
  //   \d+            -> 単独の数字（カンマなし）
  // )+               -> 1回以上繰り返す
  // (?:,\s*|\s*$)     -> 末尾がカンマと空白、または行末
  // \s*$             -> 行末の空白
  
  // よりシンプルに、カンマで分割して、すべてが有効な整数であることを確認するアプローチを採用します。
  
  const parts = line.split(',');
  let isValid = true;
  let hasNumber = false;

  for (const part of parts) {
    const trimmedPart = part.trim();
    if (trimmedPart === "") {
      // カンマが連続している場合（例: ,,）や、行が空でないのにカンマのみの場合
      // 末尾のカンマは許容されるが、空の要素が連続するのはNGと見なす。
      // ただし、仕様は「1個以上の数字列がカンマで区切られて並んでいる」なので、
      // 空の要素が複数連続するのは妥当ではないと解釈する。
      continue;
    }
    
    // 数字のみ、または数字とカンマの組み合わせをチェック
    if (!/^\d+$/.test(trimmedPart)) {
        // 数字とカンマ以外を含む行は妥当ではない
        isValid = false;
        break;
    }
    hasNumber = true;
  }

  // 妥当性の最終判定
  // 1. 少なくとも1つの数字が含まれていること (hasNumber)
  // 2. 空行でないこと (trimmedLine !== "")
  // 3. 形式的に数字とカンマのみで構成されていること (ループ内でisValidが維持されているか、またはpartsの構造)
  
  // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を判定するため、
  // 少なくとも1つの数字が含まれており、かつ、行が数字とカンマのみで構成されていることを確認する。
  
  // 最後の行がカンマで終わる場合、その後の空の要素は無視される。
  // 例: "1,2," -> parts = ["1", "2", ""]。これは妥当。
  // 例: "a,1" -> parts = ["a", "1"]。これは不妥当。
  
  // 正規表現で再評価: 
  // 行全体が、数字とカンマ、空白のみで構成され、かつ数字が少なくとも1つ含まれているか。
  const regex = /^\s*([\d,]*\s*)+$/;
  
  // 1. 行が数字とカンマ、空白のみで構成されているか
  if (!regex.test(line)) {
      isValid = false;
  } else {
      // 2. 少なくとも1つの数字が含まれているか
      // カンマや空白のみの行は除外する
      const containsDigit = line.match(/\d/);
      if (!containsDigit) {
          isValid = false;
      }
  }
  
  if (isValid) {
    validLines++;
  }
});

rl.on('end', () => {
  console.log(`valid=${validLines}`);
});
