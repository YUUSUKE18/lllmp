const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
  // 正規表現: 
  // ^\s*          -> 行頭の空白を許容
  // (?:          -> 非キャプチャグループ開始
  //   \d+,\s*    -> 1つ以上の数字とカンマ、それに続く空白（1個以上の要素）
  //   |          -> または
  //   \d+       -> 単独の数字（末尾のカンマを許容するため）
  // )+           -> 上記のパターンが1回以上繰り返される
  // \s*$         -> 行末の空白を許容
  // この正規表現は「カンマ区切りの整数列」の妥当性を厳密に定義するのは難しい。
  // 仕様を再解釈し、「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
  // 許容されるパターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
  // 末尾のカンマは許容される。空行は無効。数字とカンマ以外は無効。

  // 1. 空行のチェック
  if (line.trim() === "") {
    // 空行は妥当ではない
    return;
  }

  // 2. 正規表現による妥当性の判定
  // パターン: 
  // ^\s*             -> 行頭の空白
  // (?:               -> 非キャプチャグループ
  //   \d+,\s*         -> 数字とカンマのセット（カンマ区切り）
  //   |               -> または
  //   \d+             -> 単独の数字（末尾のカンマを許容するため）
  // )+                -> 1回以上繰り返す
  // (?:,\s*)?         -> 末尾のカンマと空白（オプション）
  // \s*$             -> 行末の空白
  
  // より単純に、「数字とカンマのみ」で構成され、少なくとも1つの数字が含まれていることを確認する。
  // 末尾のカンマは許容される。
  // 妥当な行は、数字とカンマ、および空白のみで構成され、数字が少なくとも1つ含まれている。
  
  // 判定ロジックを再構築:
  // 1. 行が数字、カンマ、空白のみで構成されているか？
  // 2. 少なくとも1つの数字が含まれているか？
  
  // 許容される文字セット: 数字(0-9), カンマ(,), 空白(\s)
  // 末尾のカンマは許容される。
  // 妥当な行は、カンマで区切られた整数列である。
  
  // 正規表現の試み: 
  // ^\s*                -> 行頭の空白
  // (?:                  -> グループ開始
  //   \d+               -> 1つ以上の数字
  //   (?:,\s*\d+)*      -> カンマと数字の繰り返し（カンマ区切り）
  //   |                 -> または
  //   \d+                -> 単独の数字（末尾のカンマを許容するため）
  // )+                   -> 1回以上繰り返す
  // (?:,\s*)?            -> 末尾のカンマと空白（オプション）
  // \s*$                -> 行末の空白
  
  // 最終的な判定: 行が数字とカンマのみで構成され、空行でないこと。
  // 末尾のカンマは許容される。
  // 数字とカンマ以外の文字が含まれていないことを確認する。
  const regex = /^\s*[\d,]*\s*$/;
  
  if (regex.test(line)) {
    // 数字とカンマのみで構成されている。
    // さらに、少なくとも1つの数字が含まれているか確認する。
    const containsDigit = /\d/.test(line);
    if (containsDigit) {
      validLines++;
    }
  }
});

rl.on('end', () => {
  console.log(`valid=${validLines}`);
});
