const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
  // 行の前後の空白を無視
  const trimmedLine = line.trim();

  if (trimmedLine === "") {
    // 空行は妥当ではない
    return;
  }

  // 正規表現による妥当性の判定
  // 1. 1個以上の数字列がカンマで区切られている
  // 2. 末尾のカンマは許容される
  // 3. 数字とカンマ以外を含む行は不適
  // 正規表現の解説:
  // ^\s*          : 行の先頭の空白
  // (?:          : 非キャプチャグループの開始
  //   \d+,\s*    : 1つ以上の数字とカンマ、それに続く空白（数字列の区切り）
  // )+           : 上記パターンが1回以上繰り返される（少なくとも1つの数字列があることを保証）
  // \d+          : 最後の数字列（末尾のカンマがあっても、最後の数字列は存在する）
  // (?:,\s*     : カンマと空白が続く場合（末尾のカンマを許容するため）
  //   |         : または
  //   $         : 行の終わり
  // )?           : カンマと空白が続く部分全体がオプション
  // $            : 行の終わり
  
  // よりシンプルに、カンマ区切りの数字列のみを許容するパターンを考える。
  // 妥当な行は「カンマで区切られた数字の並び」である。
  // 許容されるパターン: 数字とカンマのみで構成され、数字列が1つ以上存在する。
  // 例: "1,2,3", "1,2,", "123"
  
  // 妥当な行の判定ロジックを再考:
  // 1. 数字とカンマ以外の文字が含まれていないこと。
  // 2. 少なくとも1つの数字列が存在すること。
  
  // 許容されるパターン: 数字とカンマのみで構成され、数字列が1つ以上存在する。
  // 1. 数字とカンマのみで構成されているか？ ([\d,]+)
  // 2. 少なくとも1つの数字列があるか？ (数字が1つ以上含まれているか)
  
  // 妥当な行のパターン: 
  // 1. 数字とカンマのみで構成されている ([\d,]* の後に数字が続く)
  // 2. 少なくとも1つの数字列が存在する
  
  // 妥当な行の例: "1,2,3", "1,2,", "123"
  // 不妥当な行の例: "", "a,1", "1,a"
  
  // 正規表現で「数字とカンマのみ」で構成されていることを確認し、かつ「数字」が含まれていることを確認する。
  // 1. 数字とカンマのみで構成されている: /^[\d,]*$/
  // 2. 少なくとも1つの数字が含まれている: /\d/
  
  const regex = /^[\d,]*\d[\d,]*$/;
  
  if (trimmedLine.length > 0 && regex.test(trimmedLine)) {
    validLines++;
  }
});

rl.on('end', () => {
  console.log(`valid=${validLines}`);
});
