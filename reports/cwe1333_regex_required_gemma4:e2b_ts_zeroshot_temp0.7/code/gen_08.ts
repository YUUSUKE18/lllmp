import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現の定義
    // ^\s*      : 行の先頭の任意の空白文字
    // (?:      : 非キャプチャグループの開始
    //   \d+    : 1つ以上の数字
    //   ,      : カンマ
    // )*       : 上記グループが0回以上繰り返される (数字とカンマのパターン)
    // \s*$      : 行の末尾の任意の空白文字
    // このパターンは、カンマ区切りの整数列、またはカンマのみ、または数字のみ、あるいは空行などを許容する広すぎるパターンになるため、
    // 仕様に合わせて「1個以上の数字列がカンマで区切られて並んでいる」ことを厳密にチェックする必要があります。

    // 仕様の再解釈に基づき、以下の条件を満たす行を判定します。
    // 1. 空行、および数字とカンマ以外を含む行は妥当ではない。
    // 2. 1個以上の数字列がカンマで区切られて並んでいること。
    // 3. 末尾のカンマは許容する。

    for (const line of lines) {
        const trimmedLine = line.trim();

        if (trimmedLine === "") {
            // 空行は妥当ではない
            continue;
        }

        // 正規表現による判定
        // ^\s* : 行の先頭の空白を無視
        // (?: \d+(?:,\d+)* ) : 1つ以上の数字、それに続くカンマと数字の繰り返し (最低1つの数字列)
        // (?:,\d+)* : 最後の要素の後のカンマ（末尾のカンマ許容のため）
        // $ : 行末
        
        // よりシンプルに、数字とカンマのみで構成され、少なくとも1つの数字が存在する場合をチェックします。
        // 妥当なパターン: 1つ以上の数字とカンマの組み合わせ。末尾のカンマは許容。
        // 例: 1,2,3, または 1,2,3,
        // 例: 1,2,3,
        
        // パターン解説:
        // ^\s*          : 行頭の空白
        // (?:           : 非キャプチャグループ開始
        //   \d+         : 1つ以上の数字 (最初の数字列)
        //   (?:,\d+)*   : カンマとそれに続く数字の繰り返し (2つ目以降の要素)
        // )             : グループ終了
        // (?:,\d+)?     : 最後の要素の後にカンマが続くことを許容するために、オプションでカンマと数字を再度チェック
        // \s*$         : 行末の空白
        
        // 妥当な行の定義: 1個以上の数字列がカンマで区切られている。
        // 最小のパターン: 数字1つ (例: "1") または 数字とカンマ (例: "1,2")
        
        // 1. 数字とカンマのみで構成されているかチェック
        const regex = /^\s*(\d+(?:,\d+)*)(?:,)?\s*$/;

        // より厳密に「1個以上の数字列がカンマで区切られている」ことをチェック
        // 1. 行が数字とカンマのみで構成されているか
        // 2. 少なくとも1つの数字列が存在するか
        
        // 妥当なパターンの例: "1", "1,2", "1,2,3,", "1,2,3"
        
        // 数字とカンマのみで構成されているか、かつ最低1つの数字が含まれているか
        const isPotentiallyValid = /^\s*(\d+(?:,\d+)*)(?:,)?\s*$/.test(line);

        if (isPotentiallyValid) {
            // 最後に、空の要素がないことを確認する。
            // 上記のパターンは、数字が1つ以上あればマッチする。
            // 例: "1" -> マッチ (1)
            // 例: "1,2" -> マッチ (1,2)
            // 例: "1," -> マッチ (1,)
            // 例: "," -> マッチしない (数字がないため)
            
            // 最後の検証: 少なくとも1つの数字が存在すること。
            // 既に \d+ が含まれているため、このチェックは満たされている。
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
