import * as readline from 'readline';

function solve() {
    const rl = readline.createInterface({
        input: process.stdin,
        output: process.stdout,
        crlfDelay: Infinity
    });

    let lines: string[] = [];
    rl.on('line', (line) => {
        lines.push(line);
    });

    rl.on('close', () => {
        let validCount = 0;
        // 正規表現:
        // ^\s*          -> 行の先頭の空白を無視
        // (?:          -> 非キャプチャグループの開始
        //   \d+        -> 1つ以上の数字
        //   (?:,\d+)* -> カンマと1つ以上の数字の繰り返し (カンマ区切りの列)
        // )            -> グループの終わり
        // (?:,\d+)*    -> 末尾のカンマを許容するための繰り返し
        // \s*$         -> 行末の空白を無視
        // 
        // 妥当な行のパターンを判定するために、より単純なアプローチを採用します。
        // 仕様: 「1 個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容する。」
        // これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを意味します。
        // 空行と数字/カンマ以外を含む行は無効。
        // 妥当な行: 少なくとも1つの数字が含まれ、数字とカンマのみで構成されている。

        // 正規表現の再定義:
        // ^\s*             -> 行頭の空白
        // (?:              -> グループ開始 (非キャプチャ)
        //   \d+            -> 1つ以上の数字
        //   (?:,\d+)*      -> カンマと数字の繰り返し (複数の列)
        // )                -> グループ終了
        // (?:,\d+)*        -> 末尾のカンマを許容
        // \s*$             -> 行末の空白
        //
        // より簡潔に、行が「数字とカンマ」のみで構成され、少なくとも1つの数字が含まれていることを確認します。
        // 妥当な行のパターン: 
        // 1. 数字とカンマのみで構成されていること。
        // 2. 少なくとも1つの数字が含まれていること。
        // 3. 空行ではないこと (これは入力処理でフィルタリングされるか、パターンでカバーされるべき)。

        // 仕様に基づき、行が「カンマ区切りの整数列」であるかを判定します。
        // 妥当な行: 少なくとも1つの数字が含まれ、数字とカンマのみで構成されている。
        // 末尾のカンマは許容。

        // パターン: 
        // ^\s*                -> 行頭の空白
        // (?:                  -> グループ開始
        //   \d+                -> 少なくとも1つの数字 (最初の列)
        //   (?:,\d+)*          -> 続くカンマ区切りの数字 (0回以上)
        //   (?:,\d+)?          -> 最後の要素の後のカンマ（オプション）
        // )
        // \s*$                 -> 行末の空白

        const validRegex = /^\s*(?:\d+(?:,\d+)*)(?:,\d+)*\s*$/;

        for (const line of lines) {
            // 空行を無視し、パターンを適用
            if (line.trim() === "") {
                continue;
            }
            
            // 正規表現による判定
            if (validRegex.test(line)) {
                validCount++;
            }
        }

        console.log(`valid=${validCount}`);
    });
}

solve();
