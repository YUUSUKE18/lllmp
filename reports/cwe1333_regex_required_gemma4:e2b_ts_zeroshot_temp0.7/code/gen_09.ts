import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現の定義
    // ^\s* : 行の先頭の任意の空白文字
    // (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字列とカンマの組み合わせ (グループ)
    // (?:,|$) : カンマまたは行末 (末尾のカンマも許容するため)
    // \s*$ : 行末の任意の空白文字
    // この正規表現は、カンマ区切りの整数列が少なくとも1つ存在することをチェックします。
    // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
    // 各数字列が少なくとも1桁であることを考慮し、全体としてカンマ区切りのパターンをチェックします。

    // 妥当性の定義を再解釈します:
    // 1. 空行、数字とカンマ以外を含む行は無効。
    // 2. 1個以上の数字列がカンマで区切られて並んでいる。
    // 3. 末尾のカンマは許容。

    // 正規表現の設計:
    // ^\s* : 行頭の空白
    // (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字列とカンマのシーケンス。
    // (?:,|$) : 区切り。カンマまたは行末。
    // \s*$ : 行末の空白
    // この問題の「1個以上の数字列がカンマで区切られて並んでいる」を検証するためには、
    // 行全体が数字とカンマのみで構成されており、かつ少なくとも1つの数字列が存在する必要があります。

    // より簡潔なアプローチとして、行が空でないこと、および数字とカンマ以外を含まないことを最初にチェックし、
    // その上で「カンマ区切りの整数列」のパターンをチェックします。

    for (const line of lines) {
        const trimmedLine = line.trim();

        if (trimmedLine === '') {
            // 空行は妥当ではない
            continue;
        }

        // 数字とカンマ以外の文字が含まれていないかチェック
        if (!/^[0-9,]*$/.test(trimmedLine)) {
            // 数字とカンマ以外を含む行は妥当ではない
            continue;
        }

        // カンマ区切りの整数列が1個以上存在するかチェック
        // 妥当なパターン: 1個以上の数字列がカンマで区切られている。
        // 例: "1,2,3", "100" (末尾カンマも許容)
        // 許容されるパターンは、数字とカンマの組み合わせが連続していること。

        // 1. 末尾のカンマを除去してチェックする（末尾のカンマは許容されるため）
        const content = trimmedLine.replace(/,$/, '');

        if (content === '') {
            // 元がカンマのみ（例: "," や ",,"）の場合、これは妥当ではない（数字列が0個になる）
            continue;
        }

        // 2. 残った文字列が数字とカンマのみで構成されていることを確認済み。
        // 3. 少なくとも1つの数字列が存在するか確認する。
        // contentが数字とカンマのみで構成されている場合、少なくとも1つの数字列が存在するため、
        // 妥当であると見なします。
        // 例: "1,2,3" -> content="1,2,3" (OK)
        // 例: "100" -> content="100" (OK)
        // 例: "," -> content="" (NG)
        // 例: "a,1" -> 最初のチェックでNG

        validCount++;
    }

    console.log(`valid=${validCount}`);
}

solve();
