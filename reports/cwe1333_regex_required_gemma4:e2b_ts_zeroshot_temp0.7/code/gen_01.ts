import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim().split('\n');
    let validCount = 0;

    // 正規表現:
    // ^\s*            - 行の先頭の空白をマッチ
    // (?:             - 非キャプチャグループの開始 (数字とカンマの列を表現)
    //   \d+           - 1つ以上の数字
    //   (?:,\d+)*     - カンマとそれに続く1つ以上の数字の繰り返し (カンマ区切りの整数列)
    // )               - グループの終わり
    // \s*             - 行末の空白をマッチ
    // $               - 行末
    // この正規表現は、カンマ区切りの整数列が少なくとも1つ存在することを確認します。
    // 末尾のカンマも許容されるため、最後の要素の後にカンマが続くパターンも考慮します。

    // より単純に、行が「数字とカンマのみ」で構成されており、かつ「カンマで区切られた数字列」が少なくとも1つ存在するかどうかをチェックします。
    // 仕様: 1 個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容。

    // パターン解説:
    // ^\s*              : 行頭の空白
    // (?:                : グループ開始 (非キャプチャ)
    //   \d+              : 1つ以上の数字 (最初の数)
    //   (?:,\d+)*        : カンマとそれに続く数字の繰り返し (カンマ区切りの要素)
    // )                  : グループ終了
    // (?:,\d+)*          : 最後の要素の後に続くカンマと数字の繰り返し（末尾のカンマを許容）
    // \s*$              : 行末の空白

    // 妥当性の判定ロジックを正規表現で行うため、より直接的に構造をチェックします。
    // 妥当な行は、数字とカンマのみで構成され、かつ少なくとも1つの数字列を含む必要があります。

    const regex = /^\s*(?:(?:\d+(?:,\d+)*)(?:,\d+)*)?\s*$/;

    for (const line of input) {
        const trimmedLine = line.trim();

        if (trimmedLine.length === 0) {
            // 空行は妥当ではない
            continue;
        }

        // 数字とカンマ以外を含む行のチェック
        // このチェックは、行が完全に数字とカンマのみで構成されているかを保証します。
        const containsOnlyDigitsAndCommas = /^[0-9,]*$/.test(trimmedLine);

        if (!containsOnlyDigitsAndCommas) {
            // 数字とカンマ以外を含む行は妥当ではない
            continue;
        }

        // 妥当性の判定: 1 個以上の数字列がカンマで区切られて並んでいること。
        // これは、行内に少なくとも1つの数字が存在し、かつカンマの構造を満たしている必要があります。
        // 例: "1,2,3" -> 妥当
        // 例: "1," -> 妥当 (末尾のカンマ許容)
        // 例: "," -> 不妥当 (数字列が0個)
        // 例: "" -> (空行で既に除外済み)

        // 数字が含まれているかチェック
        if (!/\d/.test(trimmedLine)) {
            // 数字が一つもない場合 (例: カンマのみ, または完全に空)
            continue;
        }

        // 構造チェック: 数字とカンマのみで構成され、数字が含まれていれば、
        // 少なくとも1つの数字列がカンマで区切られている構造（あるいはその一部）と見なします。
        // 仕様は「1 個以上の数字列がカンマで区切られて並んでいる」です。
        // これは、カンマが存在する場合、少なくとも1つの数字が存在すれば満たされます。
        // "1" -> 妥当 (1個の数字列)
        // "1,2" -> 妥当 (2個の数字列)
        // "1," -> 妥当 (1個の数字列)
        // "," -> 不妥当 (数字列が0)

        // 最後の行の判定:
        // 妥当な行のカウント
        validCount++;
    }

    console.log(`valid=${validCount}`);
}

solve();
