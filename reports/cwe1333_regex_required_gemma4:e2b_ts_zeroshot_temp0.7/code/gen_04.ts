import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*               : 行の先頭の任意の空白
    // (                  : グループ開始 (1個以上の数字列)
    // [0-9]+             : 1桁以上の数字
    // (,\s*[0-9]+)*      : カンマとそれに続く空白と数字の繰り返し (オプション)
    // (?:\s*,?)*         : 末尾のカンマや空白の繰り返し (オプション)
    // $                  : 行の終わり
    //
    // よりシンプルに、「カンマ区切りの整数列」が1つ以上存在することを確認する。
    // 妥当な行は、「数字とカンマのみ」で構成され、少なくとも1つの数字が含まれている必要がある。
    // 末尾のカンマは許容される。
    // 空行は妥当ではない。
    // 数字とカンマ以外は妥当ではない。

    // 正規表現の解説:
    // ^\s*                  : 行の先頭の空白を無視
    // (?:                  : 非キャプチャグループ (グループ化のため)
    //     [0-9]+           : 1つ以上の数字 (最初の数字列)
    //     (?:,\s*[0-9]+)*  : カンマとそれに続く数字の繰り返し (カンマ区切りの部分)
    // )                    : グループ終了
    // (?:,\s*              : カンマと空白の繰り返し (末尾のカンマを許容するため)
    //     [0-9]+          : 最後の数字列
    // )?                   : この最後の数字列はオプション（カンマで終わる場合や単独の場合）
    // $                    : 行の終わり

    // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
    // 1. 数字とカンマ以外の文字が含まれていないこと。
    // 2. 少なくとも1つの数字が存在すること。

    // 妥当な行のパターン:
    // 1. 数字とカンマのみで構成されていること。
    // 2. 少なくとも1つの数字が含まれていること。

    // パターンを簡略化し、行全体が「数字、カンマ、空白」の組み合わせであるか、またはそれに類する構造を持つかを確認する。
    // 妥当な行は、数字とカンマのみで構成され、空行でない。
    // 少なくとも1つの数字が存在することを保証するため、数字の存在を必須とする。

    const validRegex = /^[\d,]*$/; // 数字とカンマのみを含む行

    for (const line of lines) {
        const trimmedLine = line.trim();

        if (trimmedLine === "") {
            // 空行は妥当ではない
            continue;
        }

        // 数字とカンマ以外を含む行は妥当ではない
        if (!validRegex.test(trimmedLine)) {
            continue;
        }

        // 妥当性の判定: 1個以上の数字列がカンマで区切られて並んでいるか。
        // これは、行内に少なくとも1つの数字が含まれていれば満たされる（数字とカンマのみの場合）。
        // また、末尾のカンマは許容される。
        
        // 1. 数字が1つ以上含まれているか？
        const hasDigits = /\d/.test(trimmedLine);
        if (!hasDigits) {
            // 数字とカンマのみだが、数字が一つもない場合（例: "," や ",," など）
            continue;
        }

        // 2. カンマ区切りで並んでいるか？
        // 妥当な行は、数字とカンマのみで構成され、少なくとも1つの数字を含む。
        // 形式的には、"1,2,3" や "1,2," などが妥当。
        // "123" も、もしこれが1つの数字列として許容されるなら妥当。
        // 仕様：「1 個以上の数字列がカンマで区切られて並んでいる」
        // 1つの数字列のみの場合も、カンマ区切りと見なせるか？
        // 「1 個以上」なので、カンマが0個でも、1つの数字列が許容されるべき。
        // 例: "123" -> 1個の数字列。もしこれが妥当ならOK。
        // 例: "1,2" -> 2個の数字列。OK。
        // 例: "1," -> 2個の数字列（1, 空）。
        // 例: ",1" -> 2個の数字列（空, 1）。これは「数字列」の定義に依存するが、数字列として空文字列を許さないとすればNG。
        
        // 正規表現で「カンマで区切られた整数列」の構造を厳密に捉える。
        // (数字列) followed by (カンマと空白の繰り返し)
        // 少なくとも1つの数字列が存在することを保証する。
        
        // 以下の正規表現は、数字とカンマのみで構成され、少なくとも1つの数字を含む行を捕捉する。
        const structuredRegex = /^[\d,]+$/; // 数字とカンマのみで構成されている

        if (structuredRegex.test(trimmedLine)) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
