import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*             -> 行の先頭の任意の空白文字
    // (?:             -> 非キャプチャグループの開始
    //   \d+,\s*       -> 1つ以上の数字とカンマ、それに続く任意の空白文字（数字列の最小単位）
    // )+              -> 上記のパターンが1回以上繰り返される
    // (?:             -> 非キャプチャグループの開始（末尾のカンマを許容するために）
    //   \d+,\s*       -> 最後の数字列とカンマ（末尾のカンマを許容）
    // )?              -> 最後の数字列とカンマは任意（オプション）
    // $               -> 行の終わり
    // 
    // よりシンプルに、1個以上の数字とカンマの組み合わせ、またはカンマのみを許容する。
    // 仕様：「1 個以上の数字列がカンマで区切られて並んでいること」
    // これは、数字とカンマが混在し、少なくとも1つの数字列が存在することを意味します。
    // 空行、数字とカンマ以外は不適。末尾のカンマは許容。

    // 妥当な行の判定ロジック
    // 1. 空行でないこと
    // 2. 数字とカンマ、および空白以外を含まないこと (ただし、空白は無視される)
    // 3. 少なくとも1つの数字列が存在すること

    const pattern = /^[\d\s,]*$|^[\d,]+[\s,]*$/;

    for (const line of lines) {
        const trimmedLine = line.trim();

        if (trimmedLine.length === 0) {
            // 空行は妥当ではない
            continue;
        }

        // 行の前後の空白は無視するため、正規表現に適用する前に、
        // 行全体が数字とカンマのみで構成されているかを確認する。
        // ただし、行の前後空白は無視されるため、トリム後の文字列を評価する。

        // 1. 数字とカンマ以外を含む行は妥当ではない
        // この条件は厳密には「数字、カンマ、空白のみ」を許容するかどうかで解釈が変わるが、
        // 「数字とカンマ以外を含む行は妥当ではない」とあるため、数字、カンマ、空白のみを許容する。
        const containsOnlyDigitsAndCommasAndSpaces = /^[0-9, ]*$/.test(line);

        if (!containsOnlyDigitsAndCommasAndSpaces) {
            continue;
        }

        // 2. 少なくとも1つの数字列がカンマで区切られて並んでいること
        // 妥当な形式: 1個以上の数字列がカンマで区切られている。
        // 例: "1,2,3" または "1,2," または "1"
        
        // 行をトリムし、前後のカンマを調整して評価する。
        const processedLine = line.replace(/\s+/g, ''); // すべての空白を削除して評価
        
        // 末尾のカンマは許容される。
        // 妥当なパターン: 数字とカンマが混在していること。
        // 1. 少なくとも1つの数字がある。
        // 2. カンマが存在する、または数字が連続している。
        
        // 正規表現で「1個以上の数字列がカンマで区切られている」ことを判定する。
        // これは、カンマで区切られた数字の並び、または単一の数字の並びが許される。
        // 例: "1,2,3" -> OK
        // 例: "1" -> OK (1つの数字列)
        // 例: "1," -> OK (末尾のカンマ許容)
        // 例: "," -> NG (数字列が0個)
        // 例: "abc" -> NG (数字とカンマ以外)

        // 数字とカンマのみで構成されており、かつカンマが1つ以上含まれるか、単一の数字列である場合を考慮する。
        // 最も単純な解釈: 数字とカンマのシーケンスであり、空でない。
        
        // 妥当性を確認するための正規表現の再定義
        // 1. 数字とカンマのみで構成されていること (既に確認済み)
        // 2. 少なくとも1つの数字が存在すること。
        
        // 数字列が1つ以上存在するかをチェックする。
        // パターン: (数字とカンマのセット) が1回以上続く。
        const validPattern = /^[\d,]+(\s*,\s*[\d,]+)*(\s*,?)?$/;

        // 行全体を評価するために、行のトリム後の内容を評価する。
        // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するには、
        // カンマで区切られた数字のセットが存在すれば良い。
        
        // 最後のカンマを許容し、数字列が少なくとも1つあることを確認する。
        // 1. 数字とカンマのみで構成されている（既にチェック済み）。
        // 2. カンマで区切られた複数の数字列、または単一の数字列が存在する。
        
        // 複数の数字列がある場合 (例: 1,2) または単一の数字列がある場合 (例: 1)
        const finalCheckPattern = /^[\d,]+(\s*,\s*[\d,]+)*$/;

        if (finalCheckPattern.test(line)) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
