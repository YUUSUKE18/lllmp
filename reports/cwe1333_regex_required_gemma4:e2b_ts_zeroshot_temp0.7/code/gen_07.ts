import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim().split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*          - 行の先頭の任意の空白（無視するため）
    // (?:          - 非キャプチャグループの開始
    //   \d+        - 1つ以上の数字
    //   (?:,\d+)* - カンマとそれに続く1つ以上の数字の繰り返し（カンマ区切りの整数列）
    // )            - 非キャプチャグループの終了
    // (?:,\d+)*    - 末尾のカンマの繰り返し（末尾のカンマは許容するため）
    // \s*$         - 行の末尾の空白
    //
    // よりシンプルに、1つ以上の数字とカンマの組み合わせをチェックし、空行や不正な文字がないことを確認します。
    // 仕様：「1 個以上の数字列がカンマで区切られて並んでいる」
    // これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを意味します。

    // パターン解説:
    // ^\s*             : 行頭の空白
    // (?:               : 非キャプチャグループ
    //   \d+             : 少なくとも1つの数字
    //   (?:,\d+)*       : カンマと数字の繰り返し（複数の数字列）
    // )                 : グループの終わり
    // (?:,\d+)*         : 末尾のカンマの繰り返し（末尾のカンマは許容）
    // \s*$             : 行末の空白
    //
    // 簡略化された判定ロジック:
    // 1. 行が空でないこと。
    // 2. 行が数字とカンマのみで構成されていること。
    // 3. 少なくとも1つの数字が含まれていること。

    const pattern = /^\s*(\d+(?:,\d+)*)(?:,*\d+)*\s*$/;

    for (const line of input) {
        const trimmedLine = line.trim();

        if (trimmedLine.length === 0) {
            // 空行は妥当ではない
            continue;
        }

        // 数字とカンマ以外を含む行は妥当ではない (正規表現でチェック)
        // この正規表現は「1個以上の数字列がカンマで区切られて並んでいる」という条件を満たすかを確認します。
        // 実際には、数字とカンマ以外の文字が含まれていないことを確認する必要があります。

        // より厳密なチェック:
        // 1. 行が数字とカンマのみで構成されているか
        // 2. 少なくとも1つの数字が含まれているか (これは上記のパターンに含まれている)

        // 許可される文字セット: 数字 (0-9), カンマ (,)
        const validCharsOnly = /^[0-9,]*$/.test(trimmedLine);

        if (!validCharsOnly) {
            continue; // 数字とカンマ以外を含む行は不適格
        }

        // 少なくとも1つの数字が含まれているか (つまり、空でない数字列が存在するか)
        // 1つ以上の数字が含まれていることを確認するために、数字が含まれているかをチェックします。
        const containsDigit = /\d/.test(trimmedLine);

        if (containsDigit) {
            // 1個以上の数字列がカンマで区切られている（またはそれらが連続している）
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
