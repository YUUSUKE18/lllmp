import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^: 行の開始
    // [^,]*: カンマ以外の任意の文字が0回以上続く (数字、空白など)
    // (?:,?\d+)+: カンマで区切られた数字のグループ。
    //   (?:,?\d+): カンマの有無にかかわらず、数字が1つ以上続く
    //   + : それが1回以上繰り返される
    // (?:,*)?: 末尾のカンマが0回または1回続くことを許容するため (末尾のカンマは許容)
    // $ : 行の終了
    // よりシンプルに、仕様を満たすための判定を考える。
    // 「1 個以上の数字列がカンマで区切られて並んでいる」
    // 許容されるパターン: 数字, 数字, ..., 数字, (カンマ)
    // 数字列: \d+
    // カンマ: ,
    // 1個以上の数字列とカンマの組み合わせ: (\d+(?:,\d+)*)
    // 末尾のカンマを許容するため、最後の要素の後にカンマが続く可能性を考慮する。

    // 妥当な行の判定ロジック：
    // 1. 空行ではないこと (trim()で空文字列でないこと)
    // 2. 数字とカンマ以外を含まないこと (正規表現で検証)
    // 3. 1個以上の数字列がカンマで区切られていること。

    const regex = /^[\d,]*(\d+(?:,\d+)*)(?:,*)?$/;

    for (const line of lines) {
        const trimmedLine = line.trim();

        if (trimmedLine === "") {
            // 空行は妥当ではない
            continue;
        }

        // 数字とカンマ以外の文字が含まれていないかチェック
        // このチェックは、行が完全に数字とカンマのみで構成されていることを保証する。
        if (!/^[0-9,]*$/.test(trimmedLine)) {
            // 数字とカンマ以外を含む行は妥当ではない
            continue;
        }

        // 1個以上の数字列がカンマで区切られているかチェック
        // 正規表現の調整:
        // 1. 行が空でないこと (既にチェック済み)
        // 2. 少なくとも1つの数字列が存在すること
        // 3. 区切り文字と数字のパターンに一致すること。

        // 妥当なパターン: (数字,数字,...) の形式。末尾のカンマは許容。
        // 例: "1,2,3" や "1,2," や "1"
        // 最小要件は「1個以上の数字列がカンマで区切られている」
        
        // 最小限の数字列のパターン: \d+
        // カンマ区切りで少なくとも1つの数字列がある。
        // 許容されるパターン: (\d+(?:,\d+)*)(?:,*)?
        
        // より厳密に、カンマで区切られた数字のシーケンスとして検証する。
        // この正規表現は、数字とカンマのみで構成され、少なくとも1つの数字列を含むことを確認する。
        const validPattern = /^(\d+(?:,\d+)*)(?:,*)?$/;

        if (validPattern.test(trimmedLine)) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
