import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim().split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*             -> 行の先頭の任意の空白
    // (?:              -> 非キャプチャグループの開始（数字とカンマの列）
    //   \d+            -> 1つ以上の数字
    //   (?:,\d+)*      -> カンマと1つ以上の数字が0回以上繰り返される
    // )                -> グループの終わり
    // \s*              -> 行末の任意の空白
    // $                -> 行の終わり
    // このパターンは、「1個以上の数字とカンマの組み合わせ」が、行全体を構成することを要求します。
    // 末尾のカンマは許容されます。

    // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」を判定するため、
    // 各要素が数字とカンマのみで構成されているかを確認します。

    const pattern = /^(\d+(?:,\d+)*)(?:,)?\s*$/;

    for (const line of input) {
        const trimmedLine = line.trim();

        if (trimmedLine === "") {
            // 空行は妥当ではない
            continue;
        }

        // 末尾のカンマを許容する場合のパターン調整
        // 1個以上の数字列がカンマで区切られていることを確認する。
        // 例: "1,2,3" または "1,2,"

        // パターンを再定義: 
        // 1. 数字とカンマのみで構成されていること。
        // 2. 空白以外の文字がないこと。
        // 3. 少なくとも1つの数字が含まれていること。

        // 判定ロジックを正規表現で行うために、行全体をチェックします。
        // 妥当な行は、数字とカンマ以外の文字を含まず、かつ少なくとも1つの数字を含む必要があります。
        // 末尾のカンマは許容されます。

        // 1. 数字とカンマのみで構成されているか？
        const isAlphanumeric = /^[0-9,]*$/.test(trimmedLine);

        if (!isAlphanumeric) {
            // 数字とカンマ以外の文字を含む行は妥当ではない
            continue;
        }

        // 2. 少なくとも1つの数字が含まれているか？
        // (数字の列が存在すれば、それはカンマ区切りの整数列の一部であると見なせる)
        const containsDigit = /\d/.test(trimmedLine);

        if (containsDigit) {
            // 数字が含まれており、数字とカンマのみで構成されている。
            // これは「1個以上の数字列がカンマで区切られて並んでいる」という条件を満たすと見なす。
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
