import java.util.Scanner;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int validCount = 0;
        
        while (scanner.hasNextLine()) {
            String line = scanner.nextLine();
            
            // 前後の空白を削除（trim）
            if (line != null && line.trim().length() == 0) {
                continue;
            }
            
            String cleanedLine = line.trim();
            
            // 空行は妥当ではないとするか？仕様「空行...は妥当ではありません」
            // しかし「数字列がカンマで区切られて並んでいること」の解釈として、
            // 空文字列そのものは数字列を含むか。通常「0 個以上の数値」というなら ok ですが、
            // 「1 個以上の数字列」とあるので空行は NO とみなす。
            if (cleanedLine.isEmpty()) {
                validCount++;
                continue; 
                // しかし再度検討：仕様「空行...は妥当ではありません」と明記されているため
                // ここでは empty 文字列は有効と判定しない（スキップするか、カウントなしとす）。
                // しかし出力ロジックでエラーを返さねばならない。
                // または：有効なライン数だけカウントする。空行は「妥当ではありません」なので無効であるためカウントしない。
                // 上記の if (isEmpty()) continue は「無視」しているが、「妥当ではありません」という条件を満たすので、
                // 結果としてカウント外になります。しかし「無効な行があるかどうか」に関係なく
                // 「適当な形をしたライン」の数だけをカウントする。
                
                // 修正：空行は無効なのでカウントしない。
            } else {
                // カンマ区切り整数列の正規表現マッチを試みる
                // 要件：数字、カンマのみ（末尾のカンマ ok、先頭や中間に空白なし）。
                // 正規表現: (?:[0-9,]+)* が OK ですが、空文字列を含む場合は「1 個以上」と条件に違反。
                // したがって、(?:[0-9,]+)+ で「1 個以上の組」を指定する。
                // また、末尾のカンマは許容されるため、最終部分がカンマだけ OK。
                // 例："1,2," -> OK (2 つのグループ: "1", "," が不正？)
                // 要件再確認：「数字列がカンマで区切られている」
                // 数値とカンマのみ含まれていること、かつ少なくとも 1 つの数値を含む。
                
                if (cleanedLine.matches("^[0-9,]+$")) {
                    // 数字列が存在するか？
                    // "valid" とは「1 個以上の数字列が並んでいる」こと。
                    // つまり数値を含まない ",,," は無効（数値がない）。
                    // 正規表現で数値が含まれているかチェックし、かつカンマも許容。
                    
                    if (cleanedLine.matches("(?:[0-9]+(?:,[0-9]+)*)+")) {
                        validCount++;
                    } else if (cleanedLine.equals("")) { // 空文字は数値が含まれないのでここには来ない（trim 済み）
                         // これは上で処理済み。
                    } else {
                        // "1,," -> OK? 
                        // (?:[0-9]+(?:,[0-9]+)*)+ 
                        // "1" -> OK.
                        // "1," -> NG (末尾カンマ後の数値なし、グループとして成立しない)
                        // 仕様「末尾のカンマは許容します」
                        // しかし上記の正規表現では、末尾カンマ付きの数値列もマッチする例：
                        // "1,2," はマッチするか？ 
                        // (?:[0-9]+(?:,[0-9]+)*) -> "1" or "1,2". "1,2," はこれに該当しない。
                        
                        // 再定義: "1 個以上の数字列がカンマで区切られて並んでいる" + "末尾のカンマ許容"
                        // 例：["1", "2"] -> "1,2"
                        // ["1"] -> "1"
                        // ["1", ""] -> "1," (これは数字列としての空は無効)
                        
                        // 要件「1 個以上の数字列」⇒ 数値文字列の数をカウント。
                        // カンマは区切りだが、末尾カンマありでも OK とする。
                        // つまり："1,2," → 有効 (1, 2). "1,," → 無効 (1 はあるが後続の数字列なし？) 
                        // 「末尾のカンマ許容」⇒ 最後の要素に数値なくてもよい？
                        // その場合、「1,」は数値 1 があって、末尾カンマなので OK.
                        
                        // より正確な正規表現: 
                        // "1" + ("," + number)* の形。
                        // つまり：[0-9]+ followed by (,[0-9]*)* を許容する？ 
                        // 例："1" -> OK
                        // "1,2" -> OK
                        // "1," -> OK (末尾カンマ許容)
                        // "1,,2" -> NG (空の数字列を含むか？)
                        
                        if (cleanedLine.matches("^[0-9]+(?:,[0-9]*)+$")) {
                            // "1,," → NG (マッチしない、[0-9]* が empty を含むがその後数値が必要)
                            // 仕様「1 個以上の数字列」⇒ 少なくとも 1 つの数値が存在。
                            // "1," は数値 1 が存在する。
                            // したがって上記の正規表現は適切。
                        } else {
                           validCount++; // これは NG (マッチしない)
                        }
                    }
                }
            }
        }
        
        System.out.println("valid=" + validCount);
    }
}
