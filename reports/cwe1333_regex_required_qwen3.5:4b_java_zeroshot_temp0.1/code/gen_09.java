import java.util.Scanner;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int validCount = 0;
        
        while (scanner.hasNextLine()) {
            String line = scanner.nextLine();
            
            // 前後の空白を除去し、空行の場合はスキップ（ただし空行は妥当ではないと指定されているため、処理が必要）
            // 仕様：「空行...は妥当ではありません」
            if (line.trim().isEmpty()) {
                continue; 
            }
            
            String trimmedLine = line.trim();
            
            // 正規表現の定義:
            // ^ : 開始
            // \s* : 先頭の空白（許容）
            // ([0-9]+(?:,[0-9]+)*)? : 1 個以上の数字列がカンマで区切られて並んでいること (末尾のカンマも許容するため、最後の数字の後にカンマがついても OK)
            // \s* : 末尾の空白（許容）
            // $ : 終了
            // 注意：「1 個以上の数字列」なので、単独の数字でも OK。
            // 「数字とカンマ以外を含む行は妥当ではありません」という条件を考慮すると、
            // 正規表現は文字列全体が数値とカンマのみで構成されることを保証する必要があります。
            // しかし、上記のパターンでは「123」もマッチします。
            // 「数字とカンマ以外を含む行は妥当ではありません」→ 文字列中に他の文字が含まれてはいけない。
            // したがって、正規表現は数値とカンマのみで構成されることを保証する必要があります。
            // 修正：^[\s]*([0-9]+(?:,[0-9]+)*)(\s*)$ は「123abc」もマッチする可能性がありますか？
            // ^[\s]*([0-9]+(?:,[0-9]+)*)(\s*)$ 
            // 「123abc」の場合：^ 以降は空白なし、[0-9]+ が "123" をマッチし、その後 (?:,[0-9]+)* はマッチしない（abc があるため）。
            // しかし、正規表現の構文では、もし [0-9]+(?:,[0-9]+)* が完全には文字列を消費しなかった場合、$ に到達できない。
            // つまり、「123abc」はマッチしません。
            // 「,abc」の場合：[0-9]+ は "1" をマッチし、次にカンマがあるか？あれば (?:,[0-9]+)* が続く必要があるが、次の文字は 'a' なので失敗。
            // したがって、上記の正規表現で OK です。
            
            if (trimmedLine.matches("^\\s*([0-9]+(?:,[0-9]+)*)\\s*$")) {
                validCount++;
            }
        }
        
        System.out.println("valid=" + validCount);
    }
}
