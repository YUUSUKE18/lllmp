import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現の定義:
    // ^\s*          -> 行の先頭の任意の空白
    // (?:           -> 非キャプチャグループの開始
    //   \d+         -> 1つ以上の数字
    //   ,           -> カンマ
    // )+            -> 上記のグループが1回以上繰り返される (カンマ区切りの数字列)
    // \s*           -> 行末の任意の空白
    // $             -> 行の終わり
    // この正規表現は、数字とカンマのみで構成され、少なくとも1つの数字列が存在することをチェックします。
    // 末尾のカンマも許容されるため、行末にカンマが続くパターンも考慮する必要があります。
    // 仕様：「1 個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容する。」

    // より厳密に「1個以上の数字列がカンマで区切られている」ことを確認します。
    // 許容されるパターン: "1,2,3", "1,2,3,", "1," など
    // 空行や数字とカンマ以外の文字を許容しない。

    const regex = /^[\d,]*$|^[\d,]+(?:,[\d,]+)*$/;

    for (const line of lines) {
        // 行の前後の空白を無視するため、行をトリムする
        const trimmedLine = line.trim();

        if (trimmedLine.length === 0) {
            // 空行は妥当ではない
            continue;
        }

        // 1. 数字とカンマ以外の文字が含まれていないかチェック
        // このチェックは、行が数字とカンマのみで構成されていることを保証します。
        if (!/^[0-9,]*$/.test(trimmedLine)) {
            continue; // 数字とカンマ以外を含む行は妥当ではない
        }

        // 2. 妥当性の判定: 1個以上の数字列がカンマで区切られているか
        // 許容されるパターン: 1個以上の数字列がカンマで区切られている。
        // これは、少なくとも1つの数字が含まれており、カンマの配置が意味を持つことを意味します。
        // 例: "1" (妥当), "1,2" (妥当), "1," (妥当), "," (不妥当, 数字列が0個), "" (空行で除外済み)
        
        // 少なくとも1つの数字が含まれているかを確認する
        if (/\d/.test(trimmedLine)) {
            // 少なくとも1つの数字が含まれていれば、それは「1個以上の数字列がカンマで区切られている」という条件を満たすと見なす。
            // 末尾のカンマは許容されるため、"1," や "1,2," はOK。
            validCount++;
        } else {
            // 数字が含まれていないが、カンマのみの場合 (例: "," や ",," など) は妥当ではない。
            // ただし、"1" のような単一の数字も含まれているため、このelseブロックに入るのは、
            // 数字を含まないが、数字とカンマのみで構成されている行（例: "," や " , " など）のみ。
            // 厳密には、"1" は /\d/.test("1") が true なのでカウントされる。
            // したがって、数字が含まれていない場合は、妥当ではないと判断する。
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
