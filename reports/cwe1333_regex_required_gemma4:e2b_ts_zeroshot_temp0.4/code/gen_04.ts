import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    if (input === "") {
        console.log("valid=0");
        return;
    }

    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*             -> 行の先頭の任意空白
    // (?:             -> 非キャプチャグループの開始 (グループ化のため)
    //   \d+,\s*       -> 1つ以上の数字、カンマ、任意空白
    // )+              -> 上記パターンが1回以上繰り返されること (1個以上の数字列)
    // (?:             -> 非キャプチャグループの開始 (末尾のカンマの有無を考慮)
    //   \d+         -> 最後の数字列
    //   (?:,\s*\d+)* -> その後にカンマと数字のペアが続くこと (末尾のカンマを含む)
    // )?              -> このグループ全体が0回または1回出現すること (末尾のカンマの許容)
    // $               -> 行の終わり
    //
    // よりシンプルに、以下の条件で判定します。
    // 1. 空行でないこと
    // 2. 数字とカンマのみで構成されていること
    // 3. 少なくとも1つの数字列が含まれていること (カンマ区切りで1個以上の数字列)

    // 正規表現の定義:
    // ^\s*             -> 行の先頭の空白
    // (?:              -> 非キャプチャグループの開始
    //   \d+(?:,\s*\d+)* -> 1つ以上の数字、それに続くカンマと数字のペアが0回以上繰り返される (カンマ区切りの数字列)
    // )               -> グループの終わり
    // (?:,\d+)*       -> 末尾のカンマと数字のオプション (末尾のカンマを許容)
    // \s*$            -> 行末の空白
    //
    // 妥当な行の定義: 1個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容。
    // これは、少なくとも1つの数字列が存在し、その間にカンマが挟まれるか、または末尾にカンマがあっても良い、ということを意味します。

    // 妥当な行の判定ロジックを正規表現で表現します。
    // 1. 行が完全に空でないこと。
    // 2. 行が数字とカンマのみで構成されていること。
    // 3. 少なくとも1つの数字列が存在すること。

    // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を表現します。
    // 例: "1,2,3" (OK), "1," (OK), ",1" (NG, 最初の数字列がない), "1,," (NG, 数字列が空になる)
    // 空行や数字とカンマ以外の文字を含む行はNG。

    // 妥当なパターン:
    // 1. 少なくとも1つの数字列 (\\d+) が存在する。
    // 2. その数字列がカンマで区切られているか、あるいは末尾にカンマがあっても良い。

    // 以下のパターンは、数字とカンマのみで構成され、かつ少なくとも1つの数字列を含むことを確認します。
    // (?:\\d+(?:,\\d+)*) : 1つ以上の数字列がカンマで区切られているパターン (例: 1,2,3)
    // |
    // (\\d+(?:,\\d+)*)(?:,\\d+)* : 最後の数字列の後に、任意のカンマと数字のペアが続くパターン (末尾のカンマを許容)

    // 最もシンプルで包括的な判定:
    // 行が数字とカンマのみで構成され、かつ、数字が1つ以上含まれていること。
    // 1. 数字とカンマのみ: /^[\d,]*$/
    // 2. 少なくとも1つの数字: /\d/
    // 3. 妥当な構造: (?:\\d+(?:,\\d+)*)(?:,\\d+)*?  <- これは複雑すぎるため、後続の処理で確認します。

    // 仕様に基づき、行が「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
    // 妥当な行は、数字とカンマのみで構成され、かつ、数字列が1つ以上存在すること。
    const validRegex = /^[\d,]+$/;

    for (const line of lines) {
        const trimmedLine = line.trim();

        if (trimmedLine === "") {
            // 空行は妥当ではない
            continue;
        }

        // 1. 数字とカンマ以外を含む行は妥当ではない (行の前後の空白は無視)
        if (!validRegex.test(trimmedLine)) {
            continue;
        }

        // 2. 少なくとも1つの数字列がカンマで区切られているか、または単一の数字列であること。
        // 妥当な行は、カンマ区切りで1個以上の数字列が存在すること。
        // 例: "1" (OK), "1,2" (OK), "1," (OK), ",1" (NG, 先頭がカンマでない限り)
        // 最初の数字列が存在することを確認します。
        const parts = trimmedLine.split(',');
        let hasDigits = false;
        for (const part of parts) {
            if (/^\d+$/.test(part)) {
                hasDigits = true;
            }
        }

        if (hasDigits) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
