import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim().split('\n');
    let validCount = 0;

    // 正規表現の定義
    // ^\s* : 行の先頭の空白を無視
    // (?:[\d,]+(?:,[\d,]+)*) : 1個以上の数字とカンマの組み合わせ。
    //   [\d,]+ : 1文字以上の数字またはカンマ
    //   (?:,[\d,]+)* : カンマとそれに続く数字の繰り返し（カンマ区切りのリストの本体）
    // \s*$ : 行末の空白を無視
    // この正規表現は「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するのに十分ではありません。
    // 仕様を再解釈し、「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
    // 許容される形式: 1,2,3 または 1,2,3, または 1,2,3,
    // 許容されない形式: 空行、数字とカンマ以外の文字を含む行
    
    // 妥当な行の判定ロジックを正規表現で実現します。
    // 1. 空行や完全に空白の行は妥当ではない。
    // 2. 数字とカンマのみで構成されている行が妥当である。
    // 3. 末尾のカンマは許容される。

    const validRegex = /^[\d,]+(?:,[\d,]+)*$|^[\d,]+(?:,[\d,]+)*,?$/;

    for (const line of input) {
        const trimmedLine = line.trim();

        if (trimmedLine === "") {
            // 空行は妥当ではない
            continue;
        }

        // 数字とカンマ以外の文字が含まれているかチェック
        // このチェックは、正規表現がマッチするかどうかで間接的に行われますが、
        // より厳密に「数字とカンマ以外」を排除する必要があります。
        
        // 正規表現で判定
        // 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」
        // 許容されるパターン: 1,2,3 または 1,2,3,
        // 1. 少なくとも1つの数字が含まれていること。
        // 2. 含まれる文字が数字とカンマのみであること。
        
        // 簡略化された判定: 行が空でなく、数字とカンマのみで構成されているか。
        // 末尾のカンマは許容されるため、行全体が数字とカンマの組み合わせで構成されているかを確認します。
        
        // 1. 数字とカンマのみで構成されているか (行全体が数字とカンマで構成されていることを確認)
        const containsOnlyDigitsAndCommas = /^[0-9,]*$/.test(trimmedLine);

        if (!containsOnlyDigitsAndCommas) {
            // 数字とカンマ以外を含む行は妥当ではない
            continue;
        }

        // 2. 1個以上の数字列がカンマで区切られているか、または単一の数字列であるか。
        // 妥当なパターン: (数字, 数字, ...) または (数字, 数字, ...)
        // 許容されるのは、カンマで区切られた数字の並び、または単一の数字列。
        // 例: "1,2,3" (OK), "1,2," (OK), "1" (OK), "1,2,3, " (OK)
        
        // 妥当性の定義を再度確認: 「1 個以上の数字列がカンマで区切られて並んでいることです。」
        // これは、カンマで区切られた要素が存在することを意味します。
        // 最小の妥当な例: "1" (1個の数字列) または "1,2" (2個の数字列)
        
        // 1. 少なくとも1つのカンマが含まれている、または単一の数字列である。
        // 2. 含まれる要素がすべて数字列である。
        
        // 以下の正規表現は、数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれていることを確認します。
        // ^[\d,]+$ : 数字とカンマのみで構成され、1文字以上あること。
        // これは、"1" や "1,2" や "1,2," など、数字とカンマのみで構成される行を捉えます。
        
        if (/^[\d,]+$/.test(trimmedLine)) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
