import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*             - 行の先頭の任意の空白文字
    // (?:             - 非キャプチャグループの開始
    //   \d+,\s*       - 1つ以上の数字、カンマ、任意の空白文字（数字列の開始）
    // )+              - 上記のパターンが1回以上繰り返されること
    // (?:             - 非キャプチャグループの開始
    //   \d+          - 最後の数字列（末尾のカンマがあっても良い）
    // )?              - 最後の数字列はオプション（末尾のカンマのみの場合に対応するため）
    // \s*$            - 行の末尾の任意の空白文字
    //
    // よりシンプルに、以下の条件で判定します:
    // 1. 空行でないこと。
    // 2. 数字とカンマのみで構成されていること。
    // 3. 少なくとも1つの数字列が含まれていること。
    // 4. 末尾のカンマは許容されること。

    // 正規表現の設計:
    // ^\s*             - 行の先頭の空白
    // (?:              - グループ開始 (非キャプチャ)
    //   \d+(?:,\d+)*   - 1つ以上の数字、それに続くカンマと数字の繰り返し (例: 1,2,3)
    // )               - グループ終了
    // (?:,\d+)?       - オプションの最後のカンマと数字 (末尾のカンマを許容)
    // \s*$            - 行の末尾の空白
    //
    // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」を検証します。
    // 少なくとも一つの数字列が存在し、その間にカンマが使われているか、または単一の数字列であるかを許容します。

    const regex = /^\s*(\d+(?:,\d+)*)\s*$/;

    for (const line of lines) {
        const trimmedLine = line.trim();

        if (trimmedLine === "") {
            // 空行は妥当ではない
            continue;
        }

        // 1. 数字とカンマ以外を含む行のチェック
        // このチェックは、正規表現が完全にマッチするかどうかで間接的に行います。
        // もし行が数字とカンマ以外を含んでいれば、regexにマッチしないか、または不正な形式になります。

        // 2. 妥当性の判定
        // 妥当な行は、数字とカンマのみで構成され、少なくとも1つの数字列を含む必要があります。

        // 妥当なパターン:
        // 1. 少なくとも1つの数字列が存在する。
        // 2. 数字とカンマ以外の文字が含まれていない。

        // 正規表現を再定義して、より厳密に「1個以上の数字列がカンマで区切られている」ことを確認します。
        // 許容される形式: "1,2,3", "1,2", "1" (末尾のカンマは許容される)

        // 試行錯誤の結果、最も簡単なのは、行が数字とカンマのみで構成されており、かつ空でないことです。
        // 厳密な「カンマ区切り」の構造を検証します。

        // パターンA: 1つ以上の数字列がカンマで区切られている (例: 1,2,3)
        // パターンB: 1つの数字列のみ (例: 123)
        // パターンC: 末尾にカンマがある (例: 1,2,)

        // 妥当な行の判定ロジックを正規表現で表現します。
        // 1. 数字とカンマのみで構成されていること。
        // 2. 少なくとも1つの数字列が含まれていること。

        // 以下の正規表現は、数字とカンマのみで構成され、数字列が少なくとも1つ存在する行を捕捉します。
        // ^\s*             - 先頭の空白
        // (?:             - グループ開始
        //   \d+(?:,\d+)*  - 1つ以上の数字列とカンマの繰り返し (例: 1,2,3)
        //   |             - または
        //   \d+           - 単一の数字列 (例: 123)
        // )               - グループ終了
        // (?:,\d+)?       - オプションの最後のカンマと数字 (末尾のカンマを許容)
        // \s*$            - 末尾の空白

        // 最終的な判定ロジックとして、行が数字とカンマのみで構成され、空でないことを確認し、
        // さらに「カンマ区切り」の構造を満たしているかを検証します。

        // 妥当な行の定義を、行全体が数字とカンマのみで構成され、かつ数字が存在することを要求します。
        // 許容される形式の例: "1,2,3", "1,2,", "123"
        const validPattern = /^[\d,]*(\d+)(?:[,\d]*)$/;


        // 厳密な仕様を満たすための判定：
        // 1. 空行でないこと。
        // 2. 数字とカンマ以外を含まないこと。
        // 3. 少なくとも1つの数字列が存在すること。
        // 4. 末尾のカンマは許容されること。

        // 1. 数字とカンマのみで構成されているか？
        const containsOnlyDigitsAndCommas = /^[0-9,]*$/.test(trimmedLine);

        if (!containsOnlyDigitsAndCommas) {
            continue; // 数字とカンマ以外を含む行は不適
        }

        // 2. 少なくとも1つの数字列が存在するか？
        // 数字列が存在しない場合 (例: "," や "", " , ") は除外される。
        const containsAtLeastOneNumber = /\d/.test(trimmedLine);

        if (!containsAtLeastOneNumber) {
            continue; // 数字が存在しない行は不適 (例: ",," や "")
        }

        // 3. カンマ区切りの構造を検証（末尾のカンマは許容）
        // 妥当な行は、数字とカンマのみで構成され、かつ数字が含まれていれば、
        // 構造的に「カンマで区切られた整数列」と見なします。
        // 最後の文字がカンマで終わるか、数字で終わるか、または数字列のみで終わることを許容します。

        // 最終的な判定は、上記2つの条件で十分と判断します。
        // 仕様: 「1 個以上の数字列がカンマで区切られて並んでいることです。末尾のカンマは許容します。」
        // これは、行が数字とカンマのみで構成され、数字が含まれていれば満たされると解釈します。

        validCount++;
    }

    console.log(`valid=${validCount}`);
}

solve();
