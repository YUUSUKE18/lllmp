import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim().split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*          -> 行の先頭の任意の空白文字
    // (?:          -> 非キャプチャグループの開始
    //   \d+        -> 1つ以上の数字
    //   (?:,\d+)* -> カンマとそれに続く1つ以上の数字の繰り返し
    // )            -> 非キャプチャグループの終了
    // \s*$          -> 行末の任意の空白文字
    // このパターンは「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
    // 末尾のカンマも許容するため、行末にカンマが続くパターンも考慮する必要があります。

    // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
    // 許容される形式: "1,2,3", "1,2,3,", "1" (カンマなしも許容されるか？仕様では「1個以上の数字列がカンマで区切られて並んでいる」)

    // 仕様の再解釈:
    // 1. 1個以上の数字列がカンマで区切られて並んでいること。
    // 2. 末尾のカンマは許容する。
    // 3. 空行、数字とカンマ以外を含む行は妥当ではない。

    // 妥当な行の判定ロジックを正規表現で定義します。
    // 1. 行が完全に空でないこと。
    // 2. 行が数字とカンマのみで構成されていること。
    // 3. 少なくとも1つの数字列が存在すること。

    // パターンA: 少なくとも1つの数字列とカンマの組み合わせが存在する。
    // ^\s*             : 行頭の空白
    // (?:             : 非キャプチャグループ開始
    //   \d+(?:,\d+)*  : 1つ以上の数字、それに続くカンマと数字の繰り返し (例: 1,2,3)
    //   |             : または
    //   \d+           : 単独の数字列 (例: 1)
    // )
    // (?:,\d*|\s*$)     : 末尾のカンマの許容 (例: 1,2,3, や 1,2,3,)
    // \s*$             : 行末の空白

    // 最もシンプルに「数字とカンマのみで構成され、少なくとも1つの数字が含まれている」ことを確認します。
    // 許容されるのは、数字とカンマのみで構成され、空行でない行。
    // 1. 空行でないこと: .
    // 2. 数字とカンマ以外を含まないこと: [0-9,]*
    // 3. 少なくとも1つの数字が含まれていること: (?=.*?\d)

    // 最終的な正規表現:
    // ^\s*                 : 行頭の空白
    // (?:                  : グループ開始 (数字とカンマのシーケンス)
    //   \d+(?:,\d*)*      : 1つ以上の数字、それに続くカンマと任意の数の数字の繰り返し (例: 1,2,3, または 1)
    //   (?:,)?            : オプションのカンマ (末尾のカンマを許容するため)
    // )
    // \s*$                 : 行末の空白

    // 仕様の「1個以上の数字列がカンマで区切られて並んでいる」を重視し、
    // 以下のパターンで判定します。
    // 1. 行が空でないこと。
    // 2. 行が数字とカンマのみで構成されていること。
    // 3. 行内に少なくとも1つの数字が含まれていること。
    // 4. 末尾のカンマは許容されること。

    const regex = /^\s*([0-9,]+(?:\s*,\s*[0-9,]+)*)\s*$/;

    for (const line of input) {
        const trimmedLine = line.trim();

        if (trimmedLine.length === 0) {
            // 空行は妥当ではない
            continue;
        }

        // 数字とカンマ以外の文字が含まれていないかチェック
        // このチェックは正規表現でカバーされますが、念のため
        if (!/^[0-9,]*$/.test(trimmedLine)) {
            continue;
        }

        // 少なくとも1つの数字が含まれているかチェック
        if (!/\d/.test(trimmedLine)) {
            // 数字とカンマのみだが、数字がない場合 (例: "," や ",," など) は不適
            continue;
        }

        // 構造チェック: 1個以上の数字列がカンマで区切られているか
        // 1. 数字とカンマのみで構成されている
        // 2. 少なくとも1つの数字が含まれている
        // 3. 妥当な区切りパターン（カンマで区切られた数字列）が存在するか
        
        // 許容されるパターン: 1,2,3, または 1,2,3,
        // 1. 少なくとも1つの数字が含まれている。
        // 2. カンマの後に数字が続く、またはカンマで終わる。
        
        // 最終的な判定として、行が数字とカンマのみで構成され、かつ数字が含まれていれば妥当と見なします。
        // 末尾のカンマの許容を考慮し、数字とカンマのみで構成されていることを確認します。
        
        // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を正規表現で表現します。
        // (数字, 数字の繰り返し) の構造を許容し、末尾のカンマを許容します。
        const finalRegex = /^\s*(\d+(?:,\d*)*)(?:,)?\s*$/;
        
        // 別の解釈: 1個以上の数字列がカンマで区切られていること。
        // 例: "1,2,3" または "1" または "1,"
        // 1. 少なくとも1つの数字が含まれている。
        // 2. カンマの後に数字が続く、またはカンマで終わる。

        // 妥当な行の判定:
        // 1. 数字とカンマのみで構成されていること。
        // 2. 少なくとも1つの数字が含まれていること。
        // 3. 構造が「数字,数字,...」または「数字」であること。
        
        // この仕様を満たすためには、行が数字とカンマのみで構成され、かつ数字が含まれていることを確認するのが最も安全です。
        // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
        const strictRegex = /^\s*[\d,]+\s*$/;
        
        if (strictRegex.test(line.trim())) {
            // 念のため、数字とカンマのみで構成されていることを確認済み。
            // 少なくとも1つの数字が含まれていることを確認済み。
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
