import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現の定義:
    // ^\s*       : 行の先頭の任意の空白文字 (無視される)
    // (?:       : 非キャプチャグループの開始
    //   \d+     : 1つ以上の数字
    //   ,       : カンマ
    // )*        : 上記のグループが0回以上繰り返される (カンマ区切りの数字列)
    // \s*       : 行末の任意の空白文字
    // $         : 行の終わり
    // この正規表現は、行が数字とカンマのみで構成されていることを確認するのではなく、
    // 「1個以上の数字列がカンマで区切られて並んでいる」という構造を検証するために、
    // 厳密には「数字とカンマのみ」という制約と「空行でない」という制約を組み合わせる必要があります。

    // 仕様の再解釈:
    // 1. 1個以上の数字列がカンマで区切られて並んでいること。
    // 2. 空行は妥当ではない。
    // 3. 数字とカンマ以外を含む行は妥当ではない。
    // 4. 末尾のカンマは許容される。

    // 妥当な行の判定ロジックを正規表現で表現します。
    // 許容されるパターン:
    // - 数字とカンマのみで構成されている。
    // - 少なくとも1つの数字列が含まれている。
    // - 末尾にカンマがあっても良い。

    // 1. 数字とカンマのみで構成されていることを確認するパターン:
    // ^[\d,]*$
    // これは、行が数字とカンマのみで構成されていることを保証します。

    // 2. 少なくとも1つの数字列が含まれていることを確認する。
    // これは、行内に少なくとも1つの数字が存在することを意味します。
    // ^[\d,]*\d[\d,]*$ (数字が少なくとも1つあることを確認)

    // 3. 末尾のカンマの許容:
    // 最後の文字がカンマであるか、数字で終わることを許容します。

    // 妥当な行の条件を組み合わせるため、行を読み込み、文字列操作で確認する方が、
    // 正規表現の複雑さを避けて意図を正確に表現できますが、仕様で「判定には正規表現を用いてください」と指定されているため、正規表現で試みます。

    // 正規表現による検証:
    // 1. 行が空でないこと (これは後で別途チェックが必要になるか、パターンに含める)
    // 2. 行が数字とカンマのみで構成されていること。
    // 3. 少なくとも1つの数字が含まれていること。

    // 以下の正規表現は、「数字とカンマのみ」で構成され、かつ「少なくとも1つの数字」を含む行を検出します。
    // ^\s*                 : 先頭の空白
    // (?:                  : 非キャプチャグループ
    //   \d+               : 1つ以上の数字
    //   ,?                : 0または1つのカンマ
    // )+                   : 上記グループが1回以上繰り返される (数字列とカンマの組み合わせ)
    // \d?                 : 最後の文字が数字かもしれない
    // \s*$                : 末尾の空白
    // これは複雑になりすぎるため、より直接的に「数字とカンマのみ」で構成され、かつ「数字」が含まれていることを確認します。

    // 最終的な正規表現戦略:
    // 1. 行が空でないこと。
    // 2. 行が数字とカンマのみで構成されていること。
    // 3. 行内に少なくとも1つの数字が含まれていること。

    // 判定ロジックを簡略化し、正規表現の制約を最大限利用します。
    // 空行の除外と、数字とカンマ以外の文字の除外を同時に行う。

    const validRegex = /^[\d,]+$/; // 数字とカンマのみで構成されている行を検出

    for (const line of lines) {
        const trimmedLine = line.trim();

        if (trimmedLine === "") {
            // 空行は妥当ではない
            continue;
        }

        // 1. 数字とカンマ以外を含む行のチェック (正規表現で検証)
        if (!validRegex.test(trimmedLine)) {
            // 数字とカンマ以外を含む行は妥当ではない
            continue;
        }

        // 2. 少なくとも1つの数字列がカンマで区切られているか (つまり、数字が1つ以上含まれているか)
        // 数字が一つもない場合（例: "," や ",," など、ただし空行は除外済み）は不妥当。
        // ただし、" , " のような行は validRegex に引っかからないため、このチェックは次のステップで行う。
        
        // 数字が含まれているかを確認
        if (/\d/.test(trimmedLine)) {
            validCount++;
        }
        // 数字が含まれていないが、カンマのみの行（例: "," や ",,"）は、
        // 「1個以上の数字列」が条件を満たさないため、妥当ではない。
        // このケースは、validRegexが成立しても、/\d/.test(trimmedLine) が偽になるため、カウントされない。
    }

    console.log(`valid=${validCount}`);
}

solve();
