import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim().split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*          - 行の先頭の空白を無視
    // (?:          - 非キャプチャグループの開始
    //   \d+        - 1つ以上の数字
    //   (?:,\d+)* - カンマとそれに続く1つ以上の数字の繰り返し (カンマ区切りの整数列)
    // )            - 非キャプチャグループの終了
    // (?:,\d+)*    - 末尾のカンマが許容されるように、カンマと数字の繰り返しを許容
    // \s*$         - 行の末尾の空白を無視
    // このパターンは「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するために、
    // 少なくとも一つの数字列が存在し、カンマで区切られている、または末尾にカンマがあることを確認します。
    // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」を判定するため、
    // 少なくとも一つの数字列が存在し、その間にカンマや数字が続くパターンをチェックします。

    // 仕様の再解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
    // これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを意味します。
    // 末尾のカンマは許容されます。

    // パターン詳細:
    // ^\s*             : 行頭の空白を無視
    // (?:              : 非キャプチャグループ開始
    //   \d+            : 1つ以上の数字 (最初の数字列)
    //   (?:,\d+)*      : カンマとそれに続く数字の繰り返し (区切り)
    // )                : グループ終了
    // (?:,\d+)*        : 末尾のカンマが許容されるように、さらにカンマと数字の繰り返しを許容
    // \s*$             : 行末の空白を無視

    // 簡略化された判定:
    // 1. 行が空でないこと (空白行は妥当ではない)
    // 2. 行が数字とカンマのみで構成されていること
    // 3. 少なくとも1つの数字が含まれていること (「1個以上の数字列」)

    // 正規表現を再設計:
    // ^\s*               : 行頭の空白を無視
    // (?:                 : グループ開始 (数字列のセット)
    //   \d+               : 最初の数字列
    //   (?:,\d+)*         : その後に続くカンマ区切りの数字列
    // )                   : グループ終了
    // (?:,\d+)*           : 末尾のカンマが許容されるように、さらにカンマと数字の繰り返し
    // \s*$                : 行末の空白を無視

    // 実際には、行が「数字とカンマ」のみで構成され、かつ「数字」が含まれているかを確認すれば十分です。
    // 妥当な行の例: "1,2,3", "1,2,"
    // 不妥当な行の例: "", "abc", "1a", "1,,2" (カンマの連続は許容されないと仮定)

    // 厳密に「カンマ区切りの整数列」を判定するため、数字とカンマのみで構成され、数字が少なくとも1つあることを確認します。
    // 許容される形式: (数字)(,数字)*
    // 末尾のカンマ許容: (数字)(,数字)*,?

    const regex = /^\s*(\d+(?:,\d+)*)(?:,)?\s*$/;

    for (const line of input) {
        const trimmedLine = line.trim();

        if (trimmedLine === "") {
            // 空行は妥当ではない
            continue;
        }

        // 正規表現で判定
        // このパターンは、数字とカンマのみで構成され、数字が少なくとも1つあることを確認します。
        // 末尾のカンマは許容されるように調整します。
        // 妥当なパターン: 1,2,3, または 1,2,
        // 不妥当なパターン: 1a, 1,,2, 1234 (カンマなし), ,
        
        // 1. 数字とカンマのみで構成されているか (数字とカンマ以外は許容しない)
        // 2. 少なくとも1つの数字が含まれているか
        
        // よりシンプルなアプローチとして、行を分解し、すべてが整数であることを確認します。
        const parts = trimmedLine.split(',');
        let isValid = false;

        if (parts.length === 0) {
            // 空行は既にスキップ済みだが念のため
            continue;
        }

        // 少なくとも1つの要素が存在し、その要素がすべて整数であることを確認
        let allAreIntegers = true;
        for (const part of parts) {
            // 空文字列は許容される（末尾のカンマや連続カンマによる空要素）
            if (part === "") {
                continue;
            }
            // 正規表現で整数のみをチェック
            if (!/^\d+$/.test(part)) {
                allAreIntegers = false;
                break;
            }
        }

        if (allAreIntegers) {
            // 1個以上の数字列がカンマで区切られて並んでいる (つまり、少なくとも1つの数字列が存在する)
            // parts.length > 0 は既に満たしている。
            // 連続するカンマや数字のみで構成されていることを確認した。
            isValid = true;
        }
        
        // 最後のチェック: 妥当な行は、数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
        // 例: "1,2" -> parts=["1", "2"] -> isValid=true
        // 例: "1," -> parts=["1", ""] -> isValid=true (末尾のカンマ許容)
        // 例: "," -> parts=["", ""] -> isValid=false (数字がない)
        // 例: "abc" -> parts=["abc"] -> isValid=false (数字以外)
        // 例: "1,a" -> parts=["1", "a"] -> isValid=false (aが数字でない)


        if (isValid) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
