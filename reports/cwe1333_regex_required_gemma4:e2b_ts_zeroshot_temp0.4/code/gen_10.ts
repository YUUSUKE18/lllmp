import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*          - 行の先頭の任意の空白文字
    // (?:          - 非キャプチャグループの開始
    //   \d+        - 1つ以上の数字
    //   (?:,\d+)* - カンマとそれに続く1つ以上の数字の繰り返し (カンマ区切りの整数列)
    // )            - 非キャプチャグループの終了
    // (?:,\d+)*?   - 末尾のカンマが許容されるため、カンマと数字の繰り返しをオプションにする
    // \s*$         - 行の末尾の任意の空白文字
    // この正規表現は、少なくとも1つの数字列がカンマで区切られていることを確認します。
    // 厳密には「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する必要があります。
    // 以下のパターンで、カンマ区切りの整数列が1つ以上存在することをチェックします。

    const validRegex = /^\s*(?:(?:\d+(?:,\d+)*))(?:\s*,?\d+)*\s*$/;

    for (const line of lines) {
        const trimmedLine = line.trim();

        if (trimmedLine === "") {
            // 空行は妥当ではない
            continue;
        }

        // 空白を除去した後の行に対して正規表現を適用
        // 仕様: 1個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容。
        // 例: "1,2,3" -> OK
        // 例: "1,2," -> OK
        // 例: "1" -> OK (1個の数字列)
        // 例: "abc" -> NG
        // 例: "1,a" -> NG
        
        // より厳密なチェック: 数字とカンマのみで構成され、少なくとも1つの数字列が存在すること。
        // 1. 数字とカンマのみで構成されているか？
        // 2. 少なくとも1つの数字列が存在するか？

        // 1. 数字とカンマのみで構成されているか (数字とカンマのみで構成された文字列)
        const containsOnlyDigitsAndCommas = /^[0-9,]*$/.test(trimmedLine);

        if (!containsOnlyDigitsAndCommas) {
            continue; // 数字とカンマ以外を含む行は妥当ではない
        }

        // 2. 少なくとも1つの数字列が存在するか？
        // 数字列は、カンマで区切られた要素として解釈される。
        // 以下のパターンは、数字とカンマの組み合わせで構成され、少なくとも1つの数字が含まれていることを確認します。
        // (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字列がカンマで区切られているパターン
        // |
        // [0-9]+ : 単一の数字列 (カンマなし)
        const hasAtLeastOneNumber = /(?:[0-9]+(?:,[0-9]+)*)|[0-9]+/.test(trimmedLine);

        if (hasAtLeastOneNumber) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
