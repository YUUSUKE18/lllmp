import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');

    let validCount = 0;

    for (const line of lines) {
        // 行の前後の空白を無視して処理
        const trimmedLine = line.trim();

        if (trimmedLine === "") {
            // 空行は妥当ではない
            continue;
        }

        // 正規表現による判定
        // 妥当なパターン: 1個以上の数字とカンマの組み合わせ。
        // 許容されるのは「1個以上の数字列がカンマで区切られて並んでいること」
        // これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを意味する。
        // 正規表現の解説:
        // ^: 行の開始
        // [0-9,]*: 0個以上の数字またはカンマ
        // (?=\d): 後読み（Positive Lookahead）。少なくとも1つの数字が後に続くことを要求する。
        // .*$: 残りの任意の文字（ただし、この問題の制約から、行全体がこのパターンに一致すれば良い）
        //
        // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックするには、
        // 少なくとも1つの数字が存在し、数字とカンマ以外は存在しない、という制約を考慮する必要があります。
        // 仕様: 「1 個以上の数字列がカンマで区切られて並んでいる」
        // これは、数字とカンマのみで構成され、数字が少なくとも1つ含まれていることを意味します。
        
        // パターン: 数字とカンマのみで構成され、数字が少なくとも1つ含まれている
        // ^[0-9,]+$: これは、行全体が数字とカンマのみで構成されていることを確認します。
        // さらに、数字が少なくとも1つ含まれていることを確認する必要があります。
        
        // 妥当な行の定義を再解釈:
        // 1. 空行ではない (trimmedLine !== "")
        // 2. 数字とカンマ以外を含まない (数字とカンマのみ)
        // 3. 1個以上の数字列がカンマで区切られている (カンマで区切られた数字の並び)
        
        // 正規表現で「数字とカンマのみで構成され、少なくとも1つの数字が含まれている」をチェックします。
        // \d+ : 1つ以上の数字
        // ,? : 0個または1個のカンマ（区切り文字として）
        // この問題の文脈では、数字とカンマの組み合わせが連続していることを確認します。
        
        // 妥当な行の例: "1,2,3", "123", "1,2,"
        // 不妥当な行の例: "abc", "1,a", "", "1,,2" (二重カンマは許容されるか？)
        
        // 「1 個以上の数字列がカンマで区切られて並んでいる」を最もシンプルに捉えると、
        // 数字とカンマのみで構成され、数字が少なくとも1つ含まれていること。
        
        // 厳密なパターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
        const regex = /^[\d,]+$/;
        const match = trimmedLine.match(regex);

        if (match) {
            // パターンに一致した場合、さらに「1個以上の数字列がカンマで区切られている」ことを確認する。
            // これは、文字列内に少なくとも1つの数字が存在すれば満たされる。
            // もし文字列が全てカンマだけで構成されている場合（例: "," または ",,"）、それは妥当ではない。
            
            // 数字が含まれているかチェック
            const containsDigit = /\d/.test(trimmedLine);
            
            if (containsDigit) {
                validCount++;
            }
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
