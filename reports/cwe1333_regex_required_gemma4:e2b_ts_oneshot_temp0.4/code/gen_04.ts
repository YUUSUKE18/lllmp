const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
  // 正規表現: 
  // ^\s* : 行頭の任意の空白
  // (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ（カンマ区切りの整数列）
  // (?:,|$) : カンマまたは行末（末尾のカンマも許容するため）
  // \s*$ : 行末の任意の空白
  // この正規表現は、カンマ区切りの整数列が少なくとも1つ存在することをチェックするために使用します。
  // 妥当な行の判定には、行全体がこのパターンに一致し、かつ空行でないことを確認します。
  
  // 1. 空行のチェック
  if (line.trim() === "") {
    return;
  }

  // 2. 正規表現による妥当性の判定
  // 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」こと。
  // これは、数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれている必要があります。
  // 正規表現: ^\s*(?:[0-9]+(?:,[0-9]+)*)\s*(\s*,)*$
  // より厳密に、「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
  // パターン: 1つ以上の数字（カンマ区切り）が続く。
  // 例: "1,2,3" や "1,2," など
  
  // 妥当な行のパターン: 
  // 1. 数字とカンマのみで構成されている。
  // 2. 少なくとも1つの数字が含まれている。
  // 3. 末尾のカンマは許容される。
  
  // 判定ロジックを正規表現に集約します。
  // 妥当な行は、数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれている必要があります。
  // 許容されるパターン: 数字とカンマのシーケンス。
  // 例: "1,2,3", "1,2,"
  // 否定されるパターン: 空行、数字とカンマ以外の文字、数字が一つもない行。

  // 正規表現の解説:
  // ^\s* : 行頭の空白
  // (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ。これは少なくとも1つの数字が含まれることを保証します。
  // (?:,\s*[0-9]+)* : カンマとそれに続く数字の繰り返し（オプション）。
  // .* : 行末の任意の文字（末尾のカンマを許容するため）
  // \s*$ : 行末の空白
  
  // よりシンプルに、「数字とカンマのみ」で構成され、かつ「少なくとも1つの数字」が含まれていることを確認します。
  // 妥当な行の定義: 数字とカンマのみで構成され、空行でない。
  // 妥当な行のパターン: ^\s*([0-9,]+)\s*$ (数字とカンマのみで構成され、少なくとも1文字ある)
  // ただし、このパターンだと "1,2,3" はOKだが、"abc" はNG。
  
  // 課題の要求: 「1 個以上の数字列がカンマで区切られて並んでいる」
  // これは、カンマで区切られた数字のシーケンスが、少なくとも1つ存在することを意味します。
  
  // 妥当な行の判定: 行が空でないこと、および行が数字とカンマのみで構成されていること。
  // 厳密に「カンマ区切りの整数列」をチェックします。
  
  // 妥当な行のパターン: 
  // ^\s*(?:[0-9]+(?:,[0-9]+)*)(?:,.*)?\s*$
  // または、より単純に、数字とカンマのみで構成され、数字が少なくとも1つあることを確認します。
  
  // 妥当な行の判定のための正規表現:
  // 1. 行が空でないこと (line.trim() !== "")
  // 2. 行が数字とカンマのみで構成されていること。
  //    これは、行に含まれる文字が数字(0-9)とカンマ(,)のみであることを意味します。
  //    末尾のカンマは許容されます。
  
  const trimmedLine = line.trim();
  
  if (trimmedLine === "") {
    // 空行は妥当ではない
    return;
  }
  
  // 数字とカンマのみで構成されているかチェック
  // パターン: 数字とカンマのみで構成され、末尾のカンマが許容される。
  // ^[0-9,]*$ : 数字とカンマのみで構成されている。
  // このパターンだけでは、"1,a" は通ってしまうため、数字が少なくとも1つあることを確認する必要があります。
  
  // 最終的な判定: 行が数字とカンマのみで構成され、かつ数字が少なくとも1つ含まれていること。
  // 妥当な行の例: "1,2,3", "1,"
  // 妥当でない例: "a,b", "1,a"
  
  // 妥当な行のパターン: 
  // ^\s*([0-9,]+)\s*$ 
  // これは、行が数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを示唆します。
  // ただし、"1,2," のような末尾のカンマも許容する必要があります。
  
  // 妥当な行の定義を最も厳密に解釈し、正規表現で表現します。
  // 1. 行が空でないこと。
  // 2. 行が数字とカンマのみで構成されていること。
  // 3. 少なくとも1つの数字が含まれていること。
  
  // 妥当な行のパターン: 
  // ^\s*([0-9,]+(?:,[0-9,]*)*)\s*$ 
  // これは複雑すぎるため、入力が「カンマ区切りの整数列」であるという前提に基づき、
  // 入力に含まれる文字が数字とカンマのみであり、かつ数字が1つ以上あることを確認します。
  
  // 簡略化された判定: 行が数字とカンマのみで構成されているか、かつ空でないことを確認します。
  // 課題の意図を汲み取り、最も一般的な「カンマ区切りの整数列」の形式をチェックします。
  // 妥当な行は、数字とカンマのみで構成され、空行でないこと。
  
  // 妥当な行の判定（最も実用的な解釈）: 
  // 行が空でなく、かつ数字とカンマ以外の文字を含まないこと。
  const isNumericAndCommaOnly = /^[0-9,]*$/.test(line);
  
  if (isNumericAndCommaOnly) {
    // 数字とカンマのみで構成されている。
    // 少なくとも1つの数字が含まれているかチェックする。
    const containsDigit = /[0-9]/.test(line);
    
    if (containsDigit) {
      validLines++;
    }
  }
});

rl.on('end', () => {
  console.log(`valid=${validLines}`);
});
