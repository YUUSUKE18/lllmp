const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
  // 正規表現:
  // ^\s*             - 行の先頭の空白を無視
  // (?:             - 非キャプチャグループ開始
  //   \d+,\s*       - 1つ以上の数字、カンマ、任意の空白
  // )+              - 上記のパターンが1回以上繰り返される
  // \d*             - 末尾の数字（カンマで終わる場合も考慮）
  // \s*$            - 行末の空白を無視
  // この正規表現は、カンマ区切りの整数列が1つ以上存在することをチェックします。
  // 末尾のカンマは許容されるため、最後の要素の後にカンマが続くパターンも考慮する必要があります。
  // より単純に、「カンマで区切られた数字が1つ以上存在するか」をチェックします。

  // 妥当性の判定ロジック:
  // 1. 行が空でなければ、その行に含まれる文字が数字とカンマのみで構成されているかを確認する。
  // 2. カンマで区切られた数字列が1つ以上存在するかを確認する。

  // 妥当な行の判定のための正規表現:
  // ^\s*                  - 行頭の空白
  // (?:                  - 非キャプチャグループ開始
  //   \d+               - 1つ以上の数字
  //   ,?                - カンマ（オプション）
  // )+                   - 上記が1回以上繰り返される
  // \s*$                 - 行末の空白
  // このパターンは、数字とカンマのシーケンスが1つ以上存在することを要求します。
  // 末尾のカンマが許容されるため、最後の要素の後にカンマが続く場合も許容する必要があります。

  // より厳密に、行をカンマで分割し、その要素がすべて整数であることを確認します。
  const trimmedLine = line.trim();

  if (trimmedLine === "") {
    // 空行は妥当ではない
    return;
  }

  // カンマで分割して、各要素が整数であるかを確認する
  const parts = trimmedLine.split(',');
  let isValid = true;

  if (parts.length === 0) {
    // これは空行で既に処理されているはずだが念のため
    isValid = false;
  } else {
    for (const part of parts) {
      // 各部分が空でないこと、かつ整数であることを確認
      if (part.trim() === "") {
        // カンマが連続している場合（例: ,,）、これは妥当ではないと見なすか？
        // 仕様：「1 個以上の数字列がカンマで区切られて並んでいる」
        // 空の要素が連続することは、数字列が存在しないと見なすのが妥当。
        isValid = false;
        break;
      }
      if (!/^\d+$/.test(part)) {
        // 数字とカンマ以外を含む場合
        isValid = false;
        break;
      }
    }
  }

  if (isValid) {
    validLines++;
  }
});

rl.on('close', () => {
  console.log(`valid=${validLines}`);
});
