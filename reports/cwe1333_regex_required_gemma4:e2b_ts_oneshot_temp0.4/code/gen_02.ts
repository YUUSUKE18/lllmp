const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
  // 行の前後の空白を無視
  const trimmedLine = line.trim();

  if (trimmedLine === "") {
    // 空行は妥当ではない
    return;
  }

  // 正規表現による判定:
  // ^\s*             : 行の先頭の空白（無視される）
  // (?:             : 非キャプチャグループの開始（数字とカンマのパターン）
  //   \d+           : 1つ以上の数字
  //   ,?            : 0個または1個のカンマ
  // )+              : 上記パターンが1回以上繰り返される
  // \s*$            : 行末の空白
  // この正規表現は、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
  // 末尾のカンマは許容されるため、行の末尾にカンマが続くパターンも許容する必要があります。

  // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する正規表現を考える。
  // 1個以上の数字とカンマの組み合わせが連続していることを確認する。
  // 例: "1,2,3" または "1,2,"
  // 1. 数字とカンマのみで構成されていること。
  // 2. 少なくとも1つの数字が含まれていること。

  // 妥当な行のパターン: 数字とカンマのみで構成され、数字が少なくとも1つある。
  // ^\s*             : 行頭の空白
  // (?:             : 非キャプチャグループ
  //   \d+           : 1つ以上の数字
  //   ,?            : 0個または1個のカンマ
  // )+              : 上記パターンが1回以上繰り返される
  // \s*$            : 行末の空白

  // 実際には、カンマで区切られた整数列が妥当であるかを判定する。
  // 1. 数字とカンマ以外の文字がないこと。
  // 2. 少なくとも1つの数字が含まれていること。

  // 妥当な行のパターンを再定義:
  // 1. 少なくとも1つの数字が含まれている。
  // 2. 数字とカンマ以外の文字は含まれていない。
  // 3. 末尾のカンマは許容される。

  // 以下の正規表現は、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
  // ^\s*                 : 行頭の空白
  // (?:                  : グループ開始
  //   \d+               : 1つ以上の数字
  //   ,?                : 0または1個のカンマ
  // )+                   : 上記が1回以上繰り返される
  // \s*$                 : 行末の空白
  // このパターンは、"1,2" や "1," のような形式を許容します。
  const validRegex = /^\s*(?:\d+(?:,?\d+)*)\s*$/;

  if (validRegex.test(line)) {
    validLines++;
  }
});

rl.on('end', () => {
  console.log(`valid=${validLines}`);
});
