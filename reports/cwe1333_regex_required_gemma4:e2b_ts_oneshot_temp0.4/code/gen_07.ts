const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
  // 正規表現:
  // ^\s*             - 行の先頭の空白を無視
  // (?:             - 非キャプチャグループ開始
  //   \d+,\s*       - 1つ以上の数字とカンマ、それに続く空白（1個以上の要素）
  //   |             - または
  //   \d+          - 単独の数字（末尾のカンマを除く、または単一の数字）
  // )+              - 上記パターンが1回以上繰り返される
  // (?:,\s*|\s*$)   - 末尾がカンマと空白、または行末
  // $               - 行の終わり
  //
  // よりシンプルに、カンマ区切りの整数列が1つ以上存在することをチェックする。
  // 妥当な行は、数字とカンマのみで構成され、少なくとも1つの数字が含まれている必要がある。

  // 1. 空行または空白のみをチェック
  if (line.trim() === "") {
    // 空行は妥当ではない
    return;
  }

  // 2. 正規表現による妥当性の判定
  // 妥当な行の定義:
  // 1. 数字とカンマのみで構成されていること。
  // 2. 少なくとも1つの数字が含まれていること。
  // 3. 末尾のカンマは許容されること。

  // パターン解説:
  // ^\s*                  : 行頭の空白を無視
  // (?:                  : 非キャプチャグループ開始
  //   \d+                : 1つ以上の数字
  //   (?:,\s*\d+)*       : カンマとそれに続く数字の繰り返し（カンマ区切りのリスト）
  //   |                  : または
  //   \d+                : 単独の数字（リストの最後の要素や単独の入力）
  // )+                   : 上記パターンが1回以上繰り返される
  // (?:,\s*|\s*$)         : 末尾がカンマと空白、または行末
  // \s*$                 : 行末の空白を無視して行全体をマッチさせるために、行末の空白を考慮する。

  // より厳密に「カンマ区切りの整数列」をチェックする。
  // 妥当な行は、数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
  // 許容されるのは、数字とカンマが混在している場合のみ。
  // 例: "1,2,3" や "1,2," や "1" は妥当。
  // 例: "abc" や "1,a" は不妥当。

  // 正規表現: 数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
  // \s* : 前後の空白を無視
  // (?: \d+ (?:,\s*\d+)* ) : 1つ以上の数字とカンマの組み合わせ (例: 1,2,3)
  // |
  // \d+                  : 単一の数字 (例: 1)
  // .*                   : これらは除外したい。数字とカンマ以外が含まれている場合は不妥当。

  // 妥当な行は、数字とカンマ、および空白のみで構成される。
  // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
  // 許容されるのは、数字とカンマのみの文字列。
  // 例: "1,2,3", "1,2,", "1"
  const validPattern = /^\s*[\d,]*\s*$/;

  if (!validPattern.test(line)) {
    // 数字とカンマ以外の文字が含まれている場合、または構造がおかしい場合
    // ただし、空行は既に除外済み。
    // このパターンは、数字とカンマ以外の文字が含まれていれば false になる。
    // 例: "1,a" -> false (OK)
    // 例: "1,2,3" -> true (OK)
    // 例: "  " -> true (空行チェックで除外済み)
    // 例: "1,2," -> true (OK)
    // 例: "abc" -> false (OK)
    // 実際には、数字とカンマ以外の文字が含まれていれば不妥当と見なす。
    // 課題の要求：「数字とカンマ以外を含む行は妥当ではありません。」
    // これは、行全体が数字とカンマのみで構成されていることを意味する。

    // 厳密に「数字とカンマ以外を含む行」をチェックする
    // 1. 数字、カンマ、空白のみが含まれているか？
    // 2. 少なくとも1つの数字が含まれているか？

    // 1. 数字とカンマ以外が含まれていないかチェック
    const containsNonAlphanumeric = !/^[0-9,]*$/.test(line);
    if (containsNonAlphanumeric) {
        return; // 不妥当
    }

    // 2. 少なくとも1つの数字が含まれているかチェック
    const containsDigit = /\d/.test(line);
    if (!containsDigit) {
        return; // 数字が一つもない（例: "," や ",,"）
    }

    // 上記2つの条件を満たせば妥当
    validLines++;
  } else {
    // 上記のチェックを統合し、より簡潔に記述する。
    // 妥当な行は、数字とカンマのみで構成され、少なくとも1つの数字を含む。
    // 空行は既に除外済み。
    // 以下のロジックで再評価する。
    
    // 妥当な行の判定ロジックを再構築
    
    // 1. 行が空または空白のみの場合 -> 不妥当
    if (line.trim() === "") {
        return;
    }

    // 2. 行が数字とカンマのみで構成されているかチェック
    // 正規表現: ^\s*[\d,]+.*$ (数字またはカンマが少なくとも1つ存在し、その他の文字は許容しない)
    // 課題の要求「数字とカンマ以外を含む行は妥当ではありません」を考慮すると、
    // 行に含まれる文字が {0-9, ,} のみで構成されている必要がある。
    const onlyDigitsAndCommas = /^[0-9,]*$/.test(line);
    if (!onlyDigitsAndCommas) {
        return; // 数字とカンマ以外を含む行は不妥当
    }

    // 3. 少なくとも1つの数字が含まれているかチェック
    const hasDigit = /\d/.test(line);
    if (hasDigit) {
        validLines++;
    }
  }
});

rl.on('end', () => {
  console.log(`valid=${validLines}`);
});
