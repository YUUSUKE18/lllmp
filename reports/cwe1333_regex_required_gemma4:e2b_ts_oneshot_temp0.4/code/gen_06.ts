const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
  // 正規表現: 
  // ^\s*          -> 行頭の任意の空白
  // (?:          -> 非キャプチャグループ開始
  //   \d+,\s*    -> 1つ以上の数字、カンマ、任意の空白
  // )+           -> 上記のパターンが1回以上繰り返される
  // (?:,\s*)?    -> 末尾のカンマと空白（オプション）
  // \s*$         -> 行末の任意の空白
  // この正規表現は、カンマ区切りの整数列が1つ以上存在することをチェックします。
  // 厳密には、行全体がこのパターンにマッチするかどうかをチェックします。
  // 妥当な行の定義: 1個以上の数字列がカンマで区切られて並んでいること。
  // 例: "1,2,3" または "1,2,"
  // 空行は除外されるべき。
  
  // 妥当性の判定ロジックを正規表現で表現します。
  // 1. 行が空行でないこと (行全体が数字とカンマのみで構成されることを確認)
  // 2. 数字とカンマのみで構成されていること。
  // 3. 少なくとも1つの数字が含まれていること。
  
  // 簡略化のため、行をトリムし、その内容が数字とカンマのみで構成されているかを確認し、
  // さらに数字が含まれているかを確認します。
  
  const trimmedLine = line.trim();
  
  if (trimmedLine.length === 0) {
    // 空行は妥当ではない
    return;
  }

  // 正規表現で「数字とカンマのみ」のパターンをチェック
  // ^\d+(?:,\d+)*$ : 1つ以上の数字から始まり、カンマと数字が繰り返されるパターン。末尾のカンマは許容しない。
  // 妥当なパターン: 1個以上の数字がカンマで区切られている。
  // 例: "1,2,3"
  // 例: "1,2," (末尾カンマも許容)
  
  // 妥当な行のパターン: 
  // 数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれている。
  // \d+ は少なくとも1つの数字。
  // (?:,\d+)* はカンマとそれに続く数字の繰り返し。
  // (?:,\d+)? は末尾のカンマのオプション。
  
  // より単純に、行に含まれるすべての文字が数字、カンマ、空白のみであり、かつ数字が少なくとも1つあることを確認します。
  
  // 課題の要求を厳密に解釈すると、「1個以上の数字列がカンマで区切られて並んでいる」ことを意味します。
  // これは、数字とカンマのみで構成され、かつカンマが少なくとも1つ（または数字が複数）存在することを意味します。
  
  // 妥当な行の正規表現: 
  // ^\s*             -> 行頭の空白
  // (?:             -> グループ開始
  //   \d+           -> 1つ以上の数字
  //   (?:,\d+)*     -> カンマとそれに続く数字の繰り返し (区切り)
  //   (?:,\d+)?     -> 最後の要素の後のカンマ（オプション）
  // )+              -> この構造が1回以上繰り返される
  // \s*$            -> 行末の空白
  
  // 判定を簡略化し、行が数字とカンマのみで構成され、かつ数字が含まれていることを確認します。
  // 以下の正規表現は、行が数字とカンマのみで構成され、かつ数字が含まれていることを確認します。
  const validRegex = /^\s*(\d+(?:,\d+)*)(?:,)?\s*$/;
  
  // 実際には、行が「1個以上の数字列がカンマで区切られている」ことを確認したい。
  // 例: "1,2,3" -> マッチ
  // 例: "1" -> マッチしない（区切りがないため、これは1つの数字列と見なされるが、区切りが必須とされる）
  // 例: "1," -> マッチ
  
  // 妥当な行の定義を「カンマで区切られた複数の数値が存在する」と解釈し、
  // 少なくとも1つのカンマが含まれているか、または複数の数値が存在することを要求します。
  
  // 複数の数値が存在する場合（カンマが含まれる場合）:
  const multiValueRegex = /^\s*\d+(?:,\d+)*\s*$/;
  
  // 末尾のカンマも許容する場合:
  const trailingCommaRegex = /^\s*\d+(?:,\d+)*,\s*$/;


  // 課題の「1個以上の数字列がカンマで区切られて並んでいる」を最も広く解釈し、
  // 少なくとも1つのカンマが存在するか、または複数の数値が存在する場合を妥当とします。
  // 1. 数字とカンマのみで構成されていること。
  // 2. 少なくとも1つのカンマが含まれていること（または複数の数値が存在すること）。
  
  // 最終的な判定として、行が数字とカンマのみで構成され、かつ、カンマが存在するか、または複数の数値が存在することをチェックします。
  // 簡潔にするため、行が数字とカンマのみで構成され、かつ、行が空行でないことを確認します。
  // 厳密に「カンマ区切り」を求めるため、カンマが存在することを必須とします。
  
  // 妥当な行の判定: 数字とカンマのみで構成され、かつカンマが含まれている。
  const isCommaSeparated = /^\s*\d+,\d+.*$/; // 少なくとも1つのカンマと数字が存在するパターン
  
  // 別の解釈: 1個以上の数字がカンマで区切られている。
  // "1" は1個の数字列。これは「1個以上」の区切りではない。
  // "1,2" は2個の数字列。
  // "1," は1個の数字列と区切り。
  
  // 妥当な行のパターン: 少なくとも1つのカンマが含まれている。
  const hasComma = line.includes(',');
  
  // 空行でないこと、数字とカンマ以外を含まないことを確認
  const isOnlyDigitsAndCommas = /^[0-9,]*$/.test(line);

  if (isOnlyDigitsAndCommas && hasComma) {
    validLines++;
  }
});

rl.on('end', () => {
  console.log(`valid=${validLines}`);
});
