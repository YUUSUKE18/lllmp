const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
  // 正規表現: 
  // ^\s*          - 行の先頭の空白を無視
  // (?:          - 非キャプチャグループ開始
  //   \d+,\s*    - 1つ以上の数字とカンマ、それに続く空白（1個以上のセット）
  // )+           - 上記パターンが1回以上繰り返される
  // \d+          - 最後の数字列（末尾のカンマがあっても許容されるため、最後の数字列が続くことを確認）
  // (?:,\s*)*    - 末尾のカンマと空白が0回以上繰り返される
  // $            - 行の終わり
  // この正規表現は「1個以上の数字列がカンマで区切られて並んでいる」ことをチェックするのに複雑になるため、
  // 仕様を再解釈し、よりシンプルに「カンマ区切りの整数列」の妥当性をチェックする。

  // 仕様の再解釈: 1個以上の数字列がカンマで区切られて並んでいる。末尾のカンマは許容。
  // 妥当なパターン: 数字とカンマのみで構成され、数字列が少なくとも1つある。

  // 1. 空行のチェック
  if (line.trim() === "") {
    // 空行は妥当ではない
    return;
  }

  // 2. 数字とカンマのみで構成されているかチェック
  // パターン: 1つ以上の数字とカンマの組み合わせ。末尾のカンマは許容。
  // 例: "1,2,3", "1,2,", "1"
  // 数字とカンマのみで構成されていることを確認するために、
  // 数字(\d)とカンマ(,)のみを含む文字列であるかを確認する。
  const regex = /^[0-9,]*(\d+)(?:,\d+)*[0-9,]*$/;
  
  // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックする。
  // 1. 数字とカンマ以外の文字が含まれていないこと。
  // 2. 少なくとも1つの数字列が存在すること。
  
  // 妥当な行の判定ロジックを正規表現で表現する。
  // 許容されるパターン: (数字, 数字, ..., 数字) または (数字, 数字, ..., )
  // 少なくとも1つの数字列が存在し、それらがカンマで区切られている。
  // 末尾のカンマは許容。

  // 試行錯誤の結果、以下の正規表現が最も意図に近いと判断します。
  // (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字列がカンマで区切られているパターン。
  // 末尾のカンマを許容するため、最後の要素がカンマで終わることも許容する。
  const isValid = /^(?:[0-9]+(?:,[0-9]+)*)(?:,?[0-9]+)?$|^[0-9]+(?:,[0-9]+)*,?$|^[0-9]+$/;

  // 上記の複雑な正規表現の代わりに、より直接的なチェックを行う。
  // 1. 行をカンマで分割する。
  const parts = line.split(',');
  
  // 2. 各部分が数字のみで構成されているか、または空文字列（末尾のカンマで生じた空文字列）のみを許容する。
  // 3. 少なくとも1つの数字列が存在する。
  
  let allValid = true;
  let hasNumber = false;
  
  for (const part of parts) {
    if (part.trim() === "") {
      // 空文字列はカンマの連続や末尾のカンマによって生じる可能性がある。
      continue;
    }
    // 数字のみで構成されているかチェック
    if (!/^\d+$/.test(part)) {
      allValid = false;
      break;
    }
    hasNumber = true;
  }

  // 少なくとも1つの数字列が存在し、かつ数字とカンマ以外を含まないこと。
  if (hasNumber) {
    validLines++;
  }
});

rl.on('end', () => {
  console.log(`valid=${validLines}`);
});
