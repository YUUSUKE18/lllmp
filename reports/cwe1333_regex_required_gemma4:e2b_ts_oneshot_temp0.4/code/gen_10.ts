const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
  // 正規表現: 
  // ^\s*          -> 行頭の空白
  // (?:[0-9]+(?:,[0-9]+)*) -> 1つ以上の数字とカンマの組み合わせ (カンマ区切りの整数列)
  // (?:,|$)       -> カンマまたは行末
  // \s*$          -> 行末の空白
  // この正規表現は、カンマ区切りの整数列が1つ以上存在することをチェックするために、
  // より柔軟に「カンマで区切られた数字の並び」を捉える必要があります。
  // 仕様: 1個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容。
  
  // 許容されるパターン:
  // 1. 少なくとも1つの数字が含まれている。
  // 2. 数字とカンマ以外の文字は含まれない。
  // 3. 末尾のカンマは許容される。

  // 判定ロジック:
  // 1. 行をトリムして、空行でないことを確認する。
  const trimmedLine = line.trim();
  if (trimmedLine.length === 0) {
    // 空行は妥当ではない
    return;
  }

  // 2. 正規表現で検証する。
  // 許容される形式: 整数とカンマのみで構成され、少なくとも1つの数字が含まれている。
  // 例: "1,2,3", "100", "1,2,"
  // 
  // 正規表現の解説:
  // ^\s*                  : 行頭の空白
  // (?:                  : 非キャプチャグループ開始
  //   \d+                : 1つ以上の数字
  //   (?:,\d+)*          : カンマと1つ以上の数字の繰り返し (カンマ区切りのリスト)
  // )                    : 非キャプチャグループ終了
  // (?:,|$)               : 末尾がカンマまたは行末
  // \s*$                  : 行末の空白
  
  // より単純化して、数字とカンマのみで構成され、少なくとも1つの数字が含まれているかをチェックする。
  // 1. 数字とカンマのみで構成されているか (数字とカンマ以外は許容しない)
  // 2. 少なくとも1つの数字が含まれているか
  
  // 許容されるパターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
  // 例: "1,2,3", "100", "1,"
  const regex = /^\s*([0-9,]+(?:,[0-9,]+)*)\s*$/;
  
  // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
  // これは、数字とカンマのみで構成され、かつ数字が少なくとも1つ存在することを意味します。
  // 末尾のカンマは許容されるため、末尾がカンマで終わることも許容します。
  
  // 修正された正規表現: 数字とカンマのみで構成され、数字が1つ以上存在すること。
  // (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字と、それに続くカンマと数字の繰り返し。
  // このパターンは、数字が1つ以上存在することを保証します。
  const strictRegex = /^\s*(?:[0-9]+(?:,[0-9]+)*)\s*$/;

  if (strictRegex.test(line)) {
    validLines++;
  }
});

rl.on('close', () => {
  console.log(`valid=${validLines}`);
});
