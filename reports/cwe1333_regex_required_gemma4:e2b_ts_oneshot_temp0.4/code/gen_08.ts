const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
  // 正規表現: 
  // ^\s*       -> 行頭の空白を無視
  // (?:      -> 非キャプチャグループ開始
  //   \d+    -> 1つ以上の数字
  //   ,?     -> カンマが0回または1回続く
  // )+       -> 上記のグループが1回以上繰り返される
  // \s*$      -> 行末の空白を無視
  // この正規表現は、数字とカンマのみで構成され、1つ以上の数字列がカンマで区切られていることを確認します。
  // 末尾のカンマも許容するため、行全体が数字とカンマの組み合わせで構成されていることを確認します。
  // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するために、
  // 数字とカンマのみで構成され、空行でないことを確認します。

  // 妥当性の判定ロジックを正規表現で表現します。
  // 1. 空行でないこと (行全体が数字とカンマで構成されていること)
  // 2. 数字とカンマ以外を含まないこと
  // 3. 1個以上の数字列が存在すること (カンマで区切られていること)

  // 判定のための正規表現:
  // ^\s*                 // 行頭の空白
  // (?:                  // 非キャプチャグループ開始 (数字とカンマのパターン)
  //   \d+(?:,\d+)*       // 1つ以上の数字、それに続くカンマと数字の繰り返し (カンマ区切りの数字列)
  //   |                  // または
  //   \d+                // 単独の数字列 (末尾のカンマがない場合も考慮)
  // )+                   // 上記パターンが1回以上繰り返される
  // \s*$                 // 行末の空白
  //
  // 仕様の解釈に基づき、より簡潔に「数字とカンマのみで構成され、空行でない」ことを確認し、
  // 内部でカンマ区切りの数字列の存在をチェックします。
  
  // 妥当性の判定:
  // 1. 行が空でないこと (trim()が空でないこと)
  // 2. 行が数字とカンマのみで構成されていること (数字とカンマ以外が含まれていないこと)
  // 3. 少なくとも1つの数字列が存在すること (カンマで区切られていること)

  const trimmedLine = line.trim();
  
  if (trimmedLine.length === 0) {
    // 空行は妥当ではない
    // validLines は変更しない
    return;
  }

  // 数字とカンマのみで構成されているかチェック
  const regexCheck = /^[0-9,]*$/;
  if (!regexCheck.test(trimmedLine)) {
    // 数字とカンマ以外を含む行は妥当ではない
    return;
  }

  // 1個以上の数字列がカンマで区切られているかチェック
  // 内部の数字列が1つ以上存在するかをチェック。
  // カンマで区切られていることを確認するため、カンマが存在するか、または数字が連続していることを確認します。
  // 少なくとも1つの数字が含まれていることを確認します。
  const containsDigit = /\d/.test(trimmedLine);
  
  if (containsDigit) {
    // 数字が含まれており、数字とカンマのみで構成されているため、これは妥当と見なします。
    // 末尾のカンマは許容されるため、この条件で十分と判断します。
    validLines++;
  }
  // 念のため、もし行が " , " のようなカンマのみで構成されている場合（数字がない場合）、それは妥当ではない。
  // しかし、上記で containsDigit が true であれば、少なくとも1つの数字列が存在するため、
  // 1個以上の数字列がカンマで区切られているという条件を満たすと解釈します。
});

rl.on('end', () => {
  console.log(`valid=${validLines}`);
});
