const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
  // 正規表現:
  // ^\s*          -> 行の先頭の任意の空白
  // (?:          -> 非キャプチャグループの開始
  //   \d+        -> 1つ以上の数字
  //   ,?         -> 0個または1つのカンマ
  // )+           -> 上記グループが1回以上繰り返される
  // \s*$         -> 行末の任意の空白
  // この正規表現は、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
  // 末尾のカンマは許容されるため、行全体が数字とカンマのシーケンスで構成されていることを確認します。
  // ただし、仕様は「1個以上の数字列がカンマで区切られて並んでいる」ことを要求しています。
  // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するためには、
  // 数字の塊がカンマで区切られている構造をチェックする必要があります。

  // 修正された正規表現の考え方:
  // 1. 行が空でないこと。
  // 2. 行が数字とカンマのみで構成されていること。
  // 3. 数字の塊がカンマで区切られていること。

  // 妥当性の判定ロジックを実装します。
  // 1. 行の前後の空白を無視する。
  const trimmedLine = line.trim();

  if (trimmedLine.length === 0) {
    // 空行は妥当ではない
    return;
  }

  // 数字とカンマのみで構成されているかチェック
  // このチェックだけでは「1個以上の数字列がカンマで区切られて並んでいる」を満たしません。
  // 例: "abc,def" は数字ではないが、この課題では「整数列」が前提です。
  // 課題の文脈から、入力は「カンマ区切りの整数列」であると仮定し、
  // その構造が維持されているかをチェックします。

  // 妥当な行の判定のための正規表現:
  // (?:[0-9]+(?:,|$))+
  // これは、数字の塊がカンマで区切られている構造をチェックします。
  // 末尾のカンマは許容されるため、行が数字とカンマの連続で構成されていることを確認します。

  // 妥当な行の判定:
  // 1. 行が空でない。
  // 2. 行に含まれる文字が、数字とカンマのみで構成されている。
  // 3. 数字の塊がカンマで区切られている（少なくとも1つの数字が存在する）。

  // 以下の正規表現は、行が数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
  // (?:[0-9]+(?:,|$))+ の代わりに、より包括的に「カンマ区切りの整数列」の形式をチェックします。
  // 1. 少なくとも1つの数字が含まれていること。
  // 2. 数字とカンマ以外の文字が含まれていないこと。
  // 3. 空行ではないこと。

  // 妥当な行の定義を「1個以上の数字列がカンマで区切られて並んでいる」と解釈し、
  // 以下の正規表現でチェックします。
  // ^\s*               -> 行頭の空白
  // (?:[0-9]+(?:,|$))+ -> 1つ以上の数字の塊と、それに続くカンマまたは行末
  // \s*$               -> 行末の空白

  // 実際には、行全体が「数字とカンマのシーケンス」であり、その中に数字が1つ以上存在し、
  // カンマで区切られている構造を持つことを確認します。
  // 簡略化して、行が数字とカンマのみで構成され、数字が1つ以上存在すれば妥当とします。
  // 末尾のカンマは許容されるため、行の末尾がカンマで終わるか、数字で終わることを許容します。

  // 妥当な行の判定のための正規表現を再考します。
  // 「1個以上の数字列がカンマで区切られて並んでいる」
  // 例: "1,2,3" -> 妥当
  // 例: "1,2," -> 妥当 (末尾のカンマは許容)
  // 例: "123" -> 妥当 (カンマなしでも1個の数字列として解釈可能だが、カンマ区切りの文脈なので注意)

  // 妥当な行は、カンマで区切られた数字のリストと見なします。
  // 1. 行が空でない。
  // 2. 行が数字とカンマのみで構成されている。
  // 3. 少なくとも1つの数字が含まれている。

  // 正規表現: ^\s*[\d,]*\s*$ (数字とカンマのみ)
  // この後に、数字が1つ以上存在するかをチェックします。

  const regex = /^\s*[\d,]+\s*$/; // 数字とカンマのみで構成されていることを確認

  if (regex.test(line)) {
    // 数字とカンマのみで構成されている
    // さらに、数字が1つ以上含まれているか確認
    const containsDigit = /[0-9]/.test(line);
    if (containsDigit) {
      validLines++;
    }
  }
});

rl.on('end', () => {
  console.log(`valid=${validLines}`);
});
