package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// 妥当な行数のみを数える
	for scanner.Scan() {
		line := scanner.Text()

		// 正規表現パターン:
		// ^\s*         -> 行の先頭の任意数の空白
		// (?:[0-9]+,)* -> 1つ以上の数字とカンマのグループ (数字の後にカンマが続く)
		// [0-9]*$      -> 行末の任意の数の数字 (末尾のカンマも許容するため)
		// ただし、より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
		// 数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれていることを確認する。

		// 1. 空行や数字・カンマ以外の文字が含まれていないかチェック
		// 2. 少なくとも1つの数字が含まれているかチェック

		// パターン解説:
		// ^\s*             -> 行の先頭の空白
		// (?:[0-9]+,)*     -> 1つ以上の数字とカンマのセットが0回以上繰り返される
		// [0-9]*$          -> 行末の数字（末尾のカンマも許容）

		// よりシンプルなチェックとして、行全体が数字、カンマ、空白のみで構成され、
		// 少なくとも1つの数字が含まれていることを確認する。
		// 妥当な条件: 1個以上の数字とカンマがカンマで区切られている。
		// 例: "1,2,3" または "1,2," または "1"

		// 以下の正規表現は、カンマで区切られた整数列（末尾のカンマも含む）を許容する。
		// 1つ以上の数字列とカンマの組み合わせで構成されていることを確認する。
		// ^\s*                -> 行頭の空白
		// (?:[0-9]+,)*        -> 1つ以上の数字とカンマのセット
		// [0-9]*$             -> 行末の数字
		// この表現は複雑になりすぎるため、より直接的に「カンマ区切りの整数列」の構造を検証する。

		// 妥当性の定義を再確認: 1個以上の数字列がカンマで区切られて並んでいる。
		// この意味で、カンマで区切られた数字の間に少なくとも1つの数字がある必要がある。

		// パターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれていること。
		// 1. 数字とカンマのみで構成されていること (空白を除く)
		// 2. 少なくとも1つの数字が含まれていること

		// 処理を簡略化するため、行をトリムしてから正規表現を適用する。
		trimmedLine := ""
		for _, r := range line {
			if r != ' ' && r != ',' {
				// 数字とカンマ以外が含まれていたら、この行は妥当ではない
				trimmedLine = "" // 妥当でないと判断し、ループを抜ける準備をする
				break
			}
			trimmedLine += string(r)
		}

		if trimmedLine == "" {
			// 行が完全に空白だった場合 (空行、または空白のみ) -> 妥当ではない
			continue
		}

		// trimmedLineが空でないことを確認した後、数字が含まれているかチェック
		hasDigit := false
		for _, r := range trimmedLine {
			if r >= '0' && r <= '9' {
				hasDigit = true
			}
		}

		if hasDigit {
			// 数字とカンマのみで構成されている (空白は無視されている)
			// 妥当な行数にカウントする
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
