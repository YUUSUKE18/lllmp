package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// 判定用の正規表現: 1個以上の数字とカンマの組み合わせ、末尾のカンマは許容
	// ^\s*       : 行頭の空白
	// (?:[0-9]+,\s*)* : 数字とカンマのペアが0回以上繰り返される（数字とカンマのみ）
	// [0-9]+     : 少なくとも1つの数字があること
	// (?:,\s*[0-9]+)* : カンマと数字のペアが0回以上繰り返される（末尾のカンマを許容するため）
	// \s*$       : 行末の空白
	// よりシンプルに、「数字とカンマのみで構成され、少なくとも1つの数字を含む」ことを確認する。
	// 許容されるパターン: 数字とカンマのみで構成され、空行やその他の文字を含まない。
	// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックする。
	// 例: 1,2,3, または 1,2,3,
	// この仕様に基づき、行が空でないこと、そしてその内容が数字とカンマのみで構成されていることを確認する。
	// 正規表現の解釈を「1個以上の数字とカンマの組み合わせ」とします。
	// パターン: (数字とカンマのセット)が1回以上続く。
	// または、より緩く「数字とカンマのみ」で構成されていることを確認し、空行を除外する。

	// 「1 個以上の数字列がカンマで区切られて並んでいる」
	// これは、カンマで区切られた数字のシーケンスを意味します。
	// ^\s*             -> 行頭の空白
	// (?:[0-9]+,\s*)*  -> 数字とカンマのセットが0回以上繰り返される
	// [0-9]+           -> 少なくとも1つの数字があること
	// (?:,\s*[0-9]+)*  -> カンマと数字のセットが0回以上繰り返される（末尾のカンマを許容するため）
	// $               -> 行末
	// 実際には、カンマ区切りのリストとして、数字とカンマのみで構成されていることを確認します。

	// 妥当な行の定義: 
	// 1. 空行ではない。
	// 2. 数字とカンマのみで構成されている。
	// 3. 少なくとも1つの数字が含まれている。

	// 空行や空白のみの行は除外する。
	// 以下の正規表現は、行が完全に数字とカンマのみで構成されていることを確認します。
	// 任意の数の数字とカンマの組み合わせ: [0-9,]*
	// 少なくとも1つの数字を含む: [0-9]+
	// 末尾のカンマを許容するため、[0-9]+, のパターンが繰り返されることを許容します。
	// 妥当な行: (数字とカンマの組み合わせ)が1つ以上ある。
	// 許容されるパターン例: "1,2,3" または "1,2,"
	validRegex := regexp.MustCompile(`^\s*([0-9,]+)\s*$`)

	for scanner.Scan() {
		line := scanner.Text()
		// 行の前後の空白を無視するため、行全体をチェックする
		if validRegex.MatchString(line) {
			// さらに、少なくとも1つの数字が含まれていることを確認する（" , " のような行は除外）
			// 数字のみで構成されているか、数字とカンマのみで構成されていることを確認。
			// 厳密に「1個以上の数字列」が区切られていることを確認するため、数字が含まれているかチェックする。
			if strings.Contains(line, "0") || strings.Contains(line, "1") || strings.Contains(line, "2") || strings.Contains(line, "3") || strings.Contains(line, "4") || strings.Contains(line, "5") || strings.Contains(line, "6") || strings.Contains(line, "7") || strings.Contains(line, "8") || strings.Contains(line, "9") {
				validCount++
			} else if strings.Contains(line, ",") {
				// 数字を含まないがカンマを含む行（例: ",,"）は不妥当とする
				// このチェックは複雑になるため、正規表現で「1個以上の数字列」を直接チェックする方が適切。
				// 最終的に、行が空でなく、数字とカンマのみで構成されていることを確認し、数字が存在すればOKとする。
				validCount++
			}
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
