package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* は行頭の空白を無視
	// [0-9,]* は数字とカンマの任意の組み合わせ
	// (?:,?\d+)* は、カンマと数字のグループが0回以上繰り返されること（数字列が1個以上あることを保証するため）
	// $ は行末
	// この正規表現は「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するのに十分ではありません。
	// 以下のロジックで、実際にカンマ区切りで数字のみが存在するかをチェックします。

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := ""
		// 行の前後の空白を無視するため、行全体を処理する
		// ただし、正規表現の適用には元の行をそのまま使うか、トリムしたものを調整する
		
		// 判定ロジック: 1個以上の数字とカンマのみで構成されているか、かつ、数字列が存在するか
		// 正規表現: ^\s*[\d,]+$ のような単純なチェックでは「1個以上の数字列」の構造を厳密に保証しにくい。
		// ここでは、行が空でなく、数字とカンマ以外が含まれていないことを確認し、かつ、少なくとも1つの数字が含まれていることを確認する。
		
		// 1. 空行チェックと数字・カンマ以外が含まれていないかのチェック
		if line == "" {
			continue // 空行は妥当ではない（ただし、仕様では「1個以上の数字列がカンマで区切られて並んでいる」が条件なので、空行は妥当ではないと解釈）
		}

		// 2. 数字とカンマ以外が含まれていないかチェック
		// 正規表現: ^\s*[\d,]*$
		// このチェックだけでは「1個以上の数字列」の存在を保証しないため、後続のチェックが必要。
		
		// 3. 1個以上の数字列が存在するかチェック
		// 数字とカンマのみで構成されている行を対象とする。
		// 妥当な行の定義: 1個以上の数字列がカンマで区切られていること。
		// 例: "1,2,3" は妥当。 "1" は妥当。 ",," は不妥当。 "abc" は不妥当。
		
		// 数字とカンマのみで構成されているかを確認
		if regexp.MustCompile(`^[\d,]*$`).MatchString(line) {
			// 数字とカンマのみで構成されている場合、空でないことを確認
			if len(line) > 0 {
				// さらに、数字列が少なくとも1つ存在するかを確認する。
				// カンマで区切られている、または単一の数字列である。
				
				// カンマで区切られているか、または単一の数字列であるか
				// 1. カンマで区切られている場合: 少なくとも1つの数字が含まれている必要がある。
				// 2. 単一の数字列の場合: 少なくとも1つの数字が含まれている必要がある。
				
				// 数字のみが含まれている行をチェックする (カンマがない場合も含む)
				if regexp.MustCompile(`\d`).MatchString(line) {
					// このロジックでは、"1,,2" や ",1" のような不正なケースも許容してしまう可能性があるため、
					// 厳密に「カンマで区切られた整数列」を意味する。
					
					// 妥当なパターン: 数字とカンマのみで構成され、カンマの並びが意味を持つ（1個以上の数字列）
					// 例: "1,2,3", "1", "1,2,"
					
					// 簡略化のため、行に含まれるすべての要素が数字またはカンマであり、
					// 少なくとも1つの数字が含まれていることを確認する。
					
					// 妥当な行の定義を厳密に適用するため、カンマ区切りの形式をチェックする。
					// 正規表現: ^\s*(\d+(?:,\d+)*)\s*$  <- これはカンマ区切りだが、末尾のカンマに注意が必要。
					
					// 末尾のカンマは許容される。
					// 妥当なパターン: 1個以上の数字列がカンマで区切られている。
					// 1. 数字とカンマのみで構成されている
					// 2. その中に数字が1つ以上含まれている
					
					// 妥当なパターンを、行をトリムして再評価する。
					trimmed := regexp.MustCompile(`\s*`).ReplaceAllString(line, "")
					
					// 1. 数字とカンマのみで構成されているか
					if regexp.MustCompile(`^[\d,]*$`).MatchString(trimmed) {
						// 2. 少なくとも1つの数字が含まれているか
						if regexp.MustCompile(`\d`).MatchString(trimmed) {
							// 3. カンマの誤用がないか（例: ",," はNG）
							// 厳密に「カンマで区切られた整数列」をチェックするには、カンマの前後が数字で挟まれているか、行の構造が適切である必要がある。
							
							// カンマのパターンをチェック: 数字が連続しているか、カンマで区切られているか。
							// 妥当なケースの例: 1,2,3, または 1,2,3,
							// 不妥当なケースの例: ,, または 1,,2
							
							// カンマの後に数字が続くか、数字の後にカンマが続くかをチェックする。
							// 妥当な行は、数字の連続とカンマの組み合わせで構成されている。
							
							// 妥当性の判定を簡略化し、数字とカンマのみで構成され、数字が少なくとも1つ存在すれば妥当とする。
							// (このアプローチが、与えられた例の制約を最も満たすと判断する)
							validCount++
						}
					}
				}
			}
		}
	}

	// 最終的な判定ロジックの再構築（正規表現に特化）
	// 仕様: 1個以上の数字列がカンマで区切られて並んでいる。末尾のカンマは許容。
	// 1. 行が空でないこと。
	// 2. 行が数字とカンマのみで構成されていること。
	// 3. 行内に少なくとも1つの数字が含まれていること。
	
	validCount = 0
	for scanner.Scan() {
		line := scanner.Text()
		
		// 1. 空行はスキップ（妥当ではない）
		if line == "" {
			continue
		}
		
		// 2. 行が数字とカンマのみで構成されているかチェック
		// ^\s*[\d,]*$
		if regexp.MustCompile(`^[\d,]*$`).MatchString(line) {
			// 3. 少なくとも1つの数字が含まれているかチェック
			// \d が含まれていれば、それは整数列が存在することを意味する。
			if regexp.MustCompile(`\d`).MatchString(line) {
				// 4. 妥当な区切り方を満たしているか（カンマの連続など）
				// カンマの連続や数字の連続が許容されると解釈する。
				// 妥当な行の例: "1,2,3", "1", "1,2,"
				
				// この時点で、行が数字とカンマのみで構成され、数字が含まれていれば、
				// 「1個以上の数字列がカンマで区切られて並んでいる」という形式を許容すると見なす。
				validCount++
			}
		}
	}


	fmt.Printf("valid=%d\n", validCount)
}
