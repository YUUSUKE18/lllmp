package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列の妥当性を判定するための正規表現
	// ^\s* - 行の先頭の空白（無視される）
	// (?:[0-9]+(?:,\s*[0-9]+)*) - 1個以上の数字がカンマで区切られているパターン
	// (?:,*)? - 末尾のカンマが任意（許容）
	// \s*$ - 行末の空白
	// この正規表現は、行全体がカンマ区切りの整数列であることを確認するのではなく、
	// 少なくとも1つの数字とカンマが混在していることを確認するのに役立つ。
	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// 以下のロジックでチェックする方が確実である。

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 1. 数字とカンマ以外の文字が含まれていないかチェック
		// 数字、カンマ、空白のみを含むことを確認
		if !regexp.MustCompile(`^[0-9, ]*$`).MatchString(line) {
			continue // 数字とカンマ以外を含む行は妥当ではない
		}

		// 2. 妥当性の判定: 1個以上の数字列がカンマで区切られているか
		// 末尾のカンマは許容される
		// パターン: (数字, 任意の空白, 数字)* (カンマの後に数字が続くか、末尾がカンマで終わる)
		// 最も簡単なチェックとして、カンマが少なくとも1つ存在するか、または数字のみが存在するかを考慮する。
		// 仕様: 1個以上の数字列がカンマで区切られて並んでいること。
		// 例: "1,2,3" (OK), "1," (OK), "123" (数字のみ、これは1つの数字列と見なせるか？)

		// 「1個以上の数字列がカンマで区切られて並んでいる」
		// これは、少なくとも1つのカンマが存在するか、または数字のみ（カンマなし）で構成されている必要がある。
		// 妥当なケース: "1,2,3", "1,2,"
		// 不妥当なケース: "", "a,b", "1a"

		// 妥当性の判定を正規表現で行う
		// パターン: 1つ以上の数字があり、カンマで区切られている、または数字のみである。
		// 少なくとも1つの数字が含まれていることを確認する。
		if regexp.MustCompile(`[0-9]+`).MatchString(line) {
			// 数字が含まれていれば、その行は少なくとも1つの数字列を含んでいる。
			// 「1個以上の数字列がカンマで区切られて並んでいる」を満たしていると見なす。
			validCount++
		} else {
			// 数字が含まれていないが、空白やカンマのみの場合（例: ",," や " , " など）
			// 厳密に「数字列」が1個以上ある必要があるため、数字がなければ不妥当。
			// ただし、上記で `[0-9, ]*` でチェック済みなので、数字がなければスキップされる。
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（今回は省略可能だが、堅牢性を保つ）
	}

	fmt.Printf("valid=%d\n", validCount)
}
