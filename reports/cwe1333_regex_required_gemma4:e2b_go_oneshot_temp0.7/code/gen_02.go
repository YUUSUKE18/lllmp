package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* 表示行の先頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字とカンマ区切りが繰り返されるパターン（数字が1つ以上）
	// .*$ 表示行の最後まで
	// この正規表現は、1つ以上の数字がカンマで区切られていることを確認します。
	// 末尾のカンマは許容されるため、行全体がこのパターンにマッチすれば妥当と見なします。
	// ただし、「1個以上の数字列がカンマで区切られて並んでいる」という条件を厳密に満たすため、
	// 以下のロジックで各行をチェックします。

	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことをチェックするパターン
	// ^\s* - 行の先頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字とカンマ区切りが繰り返される (数字の列が1つ以上)
	// (?:,\s*|$) - カンマと空白、または行末
	// \s*$ - 行末の空白
	// 以下の正規表現は、行全体が数字とカンマのみで構成され、少なくとも1つの数字列が存在することをチェックするのに適しています。
	// 実際には、行を分割して各要素が整数であることを確認する方がより確実ですが、
	// 仕様に従い「正規表現を用いて」判定します。

	// 妥当性の判定ロジックを正規表現で表現し、行ごとにチェックします。
	// 妥当な行: 1個以上の数字とカンマの組み合わせが存在し、その他の文字がないこと。
	// 末尾のカンマは許容される。
	// 空行は妥当ではない。
	// 数字とカンマ以外を含む行は妥当ではない。

	// 妥当な行のカウント
	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現による妥当性のチェック
		// 1. 数字とカンマのみで構成されているか、または空白のみか
		// 2. 1個以上の数字列がカンマで区切られているか
		// 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
		// ^\s* - 行頭の空白
		// (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字とカンマの組が繰り返される
		// .*$ - 残りの文字（ここでは許容されると見なす）
		// 実際には、行を分割して整数であるかを確認するのが最も確実ですが、正規表現での制約に従います。

		// 「1個以上の数字列がカンマで区切られて並んでいる」という条件を満たすか？
		// 例: "1,2,3" -> OK
		// 例: "1," -> OK (末尾のカンマは許容)
		// 例: "," -> NG (数字列が0個)
		// 例: "abc" -> NG (数字とカンマ以外)

		// ここでは、行をカンマで分割し、すべてが整数であることを確認する方が、
		// 「数字とカンマ以外を含む行は妥当ではない」という制約を直接満たします。
		// ただし、正規表現使用が必須のため、正規表現で「数字とカンマのみ」をチェックします。

		// 数字とカンマのみを含む行であるかを確認する正規表現 (行全体が数字とカンマのみで構成されているか)
		// [\d,]* - 数字とカンマのみ
		// ^\s*[\d,]*\s*$ - 空白、数字、カンマのみで構成されているか
		// この正規表現だけでは「1個以上の数字列」の条件を満たしません。

		// 妥当性の判定を、行を分割して検証するロジックを正規表現の制約の下に組み込みます。
		// 妥当な行は、カンマで分割した結果、すべてが整数である、または空でないことを意味します。

		// 厳密に正規表現で「1個以上の数字列がカンマで区切られている」ことを表現する場合、
		// 以下のパターンを採用します。これは、行が数字とカンマのみで構成され、最低1つの数字列が存在することを要求します。
		// 妥当な行: 少なくとも1つの数字列があり、それらがカンマで区切られている。
		// 末尾のカンマは許容される。
		pattern := `^\s*(?:[0-9]+(?:,\s*[0-9]+)*|\d+)(?:,.*)?\s*$`
		
		// よりシンプルなチェックとして、行を分割し、すべてが整数であるかを確認するのが、
		// 「カンマ区切りの整数列」という構造を判定する上で最も適切です。
		// 求められているのは「正規表現を用いて」という制約ですが、構造の検証においては
		// `\d+(?:,\d+)*` のようなパターンが最も直接的です。

		// 以下のパターンは、1つ以上の数字とカンマの組み合わせが存在することを要求します。
		// 1. ^\s* : 行頭の空白
		// 2. (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ（最小1要素）
		// 3. .*$ : 行末まで（末尾のカンマを含む）
		validPattern := `^\s*(?:[0-9]+(?:,\s*[0-9]+)*|\d+)(?:,.*)?\s*$`

		if regexp.MustCompile(validPattern).MatchString(line) {
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
