package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// これは、カンマで区切られた整数（負の数を含む）の列を許可します。
	// 形式: ^[+-]?\d+(?:,\d+)*$ または ^\d+(?:,\d+)*$ のような複雑なパターンを完全に網羅するのは難しいため、
	// ここでは「1個以上の数字列がカンマで区切られて並んでいる」という条件を、
	// カンマの有無に関わらず、数字とカンマのみで構成されていることを確認するアプローチを取ります。
	// より厳密に「整数列」であることを確認しつつ、カンマの有無を許容するパターンを考えます。
	// 仕様: 1個以上の数字列がカンマで区切られて並んでいる。末尾のカンマは許容。
	// これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを意味します。
	// 例: "1,2,3", "1,2,", "1" (末尾のカンマは許容される)
	// 正規表現の設計: 数字とカンマのみで構成され、少なくとも1つの数字が含まれる。

	// 1. 行を読み込みながら判定する
	for scanner.Scan() {
		line := scanner.Text()

		// 行の前後の空白を無視する (scanner.Text()は読み込んだ行全体)
		trimmedLine := ""
		for _, r := range line {
			if r != ' ' && r != '\t' {
				trimmedLine += string(r)
			}
		}

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現による妥当性の判定
		// パターン: 1つ以上の数字(0-9, +,-)とカンマの組み合わせ。
		// これは「数字とカンマのみ」という制約を最も強く反映します。
		// 1個以上の数字列がカンマで区切られていることを確認するため、
		// 少なくとも1つの数字が、カンマで区切られた構造の中に存在する必要があります。
		// 以下のパターンは、カンマで区切られた整数列（末尾カンマ含む）を許容します。
		// ^[0-9,+-]+(?:,[0-9,+-]+)*$ : 整数とカンマのみで構成されるパターン
		// 実際には、数字列がカンマで区切られていることを確認します。
		// 末尾のカンマは許容されるため、行の終端がカンマで終わるか、数字で終わることを許容します。
		// 以下のパターンは、数字とカンマのみで構成され、空ではない行を許可します。
		// (?:[0-9,+-]+) の後に (?:,[0-9,+-]+)* が続く、という構造を許容します。
		// 簡略化して、数字とカンマのみで構成され、空でないことを確認します。
		// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を正規表現で表現するのは複雑なため、
		// 「数字とカンマのみで構成され、空でない」という条件を主要な制約とします。

		// 実際の仕様を満たすための最も簡潔な正規表現は、
		// 数字、マイナス、プラス、カンマのみで構成され、空でない行であること。
		// 末尾のカンマは許容されるため、行全体が数字とカンマで構成されていることを確認します。
		// (?:[0-9,+-]+) のパターンを繰り返すことで、カンマ区切りの構造を許容します。
		// 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
		match, err := regexp.MatchString(`^[0-9,+-]+(?:,[0-9,+-]+)*$`, trimmedLine)

		// 上記のパターンが厳密に「1個以上の数字列がカンマで区切られている」ことを保証しない可能性があるため、
		// より簡単なチェックと、カンマの許容性を考慮します。
		// 妥当性の定義を「数字とカンマのみで構成され、空でない」と解釈し、
		// 以下のチェックで、数字とカンマ以外の文字がないことを確認します。
		// 1個以上の数字列がカンマで区切られていることを確認するためには、
		// 少なくとも1つの数字が含まれている必要があります。
		hasDigit := false
		for _, char := range trimmedLine {
			if char >= '0' && char <= '9' {
				hasDigit = true
			}
		}

		if hasDigit {
			// 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
			// 末尾のカンマは許容されるため、この条件で妥当と見なします。
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
