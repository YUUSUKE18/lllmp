package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列の妥当性を判定するための正規表現
	// ^\s*             : 行の先頭の任意の空白
	// (?:             : 非キャプチャグループの開始
	//   \d+           : 1つ以上の数字
	//   \s*,\s*       : カンマとそれに続く任意の空白（区切り）
	// )+              : 上記のグループが1回以上繰り返される
	// (?:             : 末尾のカンマのオプション
	//   \s*,?         : 任意の空白とオプションのカンマ
	// )?              : 末尾のカンマのオプション
	// \s*$            : 行末の任意の空白
	// この正規表現は、少なくとも1つの数字とカンマで区切られた数字のシーケンスを許容します。
	// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
	// 実際には、行が空でないこと、かつ数字とカンマ以外の文字がないことを確認する必要があります。
	// 仕様に基づき、「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
	// 末尾のカンマは許容されます。

	// よりシンプルな判定ロジックを採用し、正規表現で「数字とカンマ以外がない」ことを確認し、
	// その後、空行でないことを確認します。
	// 妥当な行の定義: 1個以上の数字とカンマで構成されており、空行ではない。

	// 妥当性の判定基準を正規表現で表現:
	// 1. 行が空でないこと。
	// 2. 行に含まれる文字が、数字、カンマ、空白のみで構成されていること。
	// 3. 少なくとも1つの数字が含まれていること。（「1個以上の数字列」）

	// 以下の正規表現は、行が空ではなく、数字、カンマ、空白のみで構成されていることをチェックします。
	// ただし、仕様の「1個以上の数字列がカンマで区切られて並んでいる」を厳密に満たすには、
	// 少なくとも1つの数字が存在する必要があります。

	validRegex := regexp.MustCompile(`^\s*[\d,]*\s*$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 行が数字とカンマのみで構成されているかチェック
		if validRegex.MatchString(line) {
			// さらに、数字が少なくとも1つ含まれているかチェック
			if strings.Contains(line, "0") || strings.Contains(line, "1") || strings.Contains(line, "2") || strings.Contains(line, "3") || strings.Contains(line, "4") || strings.Contains(line, "5") || strings.Contains(line, "6") || strings.Contains(line, "7") || strings.Contains(line, "8") || strings.Contains(line, "9") {
				// 数字が含まれていれば妥当
				validCount++
			} else {
				// 数字が含まれていないが、カンマや空白のみの場合（例: ",,,", " , "）は不妥当
				// 厳密には、数字の存在が「1個以上の数字列」を意味するため、数字が含まれていればOKとする。
				// 例: ",," は数字を含まないので不妥当。
				// したがって、数字が一つでも含まれていれば妥当と判断する。
				// ただし、仕様の「1個以上の数字列がカンマで区切られて並んでいる」を厳密に解釈すると、
				// 少なくとも一つの数字が含まれていなければならない。
				// ここでは、数字が含まれていることを主要な条件とする。
			}
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
