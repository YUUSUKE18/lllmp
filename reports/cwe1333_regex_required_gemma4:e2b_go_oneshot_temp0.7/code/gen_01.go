package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// 正規表現パターン:
	// ^\s*             - 行の先頭の空白を許容
	// [0-9,]*          - 0個以上の数字とカンマの組み合わせ（数字列がカンマで区切られていることを確認するため）
	// (\d+[,]*)*       - 1個以上の数字列とカンマの組み合わせが0回以上繰り返される
	// $               - 行の末尾
	// この問題の要件「1 個以上の数字列がカンマで区切られて並んでいる」を厳密に満たすには、
	// 少なくとも1つの数字列が存在し、カンマで区切られている必要がある。
	// 少なくとも一つの数字列（\d+）があり、その間にカンマ（,）が挟まれるか、または末尾にカンマがある、という構造。
	// 簡略化し、「数字とカンマのみで構成されており、少なくとも1つの数字列が含まれている」ことを確認する。
	// より厳密に「1個以上の数字列がカンマで区切られている」ことを確認するために、
	// 数字とカンマのみで構成されていることを確認し、少なくとも1つの数字が含まれていることを確認する。

	// 判定ロジックをシンプルにするため、以下の正規表現を使用します。
	// 1. 行全体が数字とカンマのみで構成されていること。
	// 2. 少なくとも1つの数字が含まれていること。
	// 3. 末尾のカンマは許容されること。

	// パターン解説:
	// ^\s*             : 行頭の空白を許容
	// (?:             : 非キャプチャグループの開始
	//   \d+          : 1つ以上の数字 (数字列)
	//   (?:,.*?)     : カンマと任意の文字が続く（数字列の区切り）
	// )*              : 上記のグループが0回以上繰り返される（1つの数字列のみの場合も考慮）
	// [0-9,]*         : 最後に数字またはカンマが続く（末尾のカンマ許容）
	// $               : 行末
	//
	// より簡単に「1個以上の数字列がカンマで区切られている」ことを確認するには、
	// 少なくとも1つの数字列があり、その間にカンマが使われているか、または末尾にカンマがある状態を許容します。
	// 提示された例の意図から、カンマ区切りのデータがあることを意味します。
	// 少なくとも1つの数字列とカンマの組み合わせが存在すればOK。

	// 簡略化されたアプローチ: 数字とカンマ以外の文字がないこと、かつ数字が含まれていることを確認する。
	// 1. 数字とカンマのみで構成されていること。
	// 2. 少なくとも1つの数字が含まれていること。

	// 最初の行を読み飛ばすため、scanner.Scan()をループ内で実行する。
	for scanner.Scan() {
		line := scanner.Text()
		// 行の前後の空白を無視するため、先頭と末尾の空白をトリムする
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現による判定:
		// ^\s*             : 行頭の空白を許容
		// (?:             : 非キャプチャグループ
		//   \d+          : 1つ以上の数字 (数字列)
		//   (?:,.*?)     : カンマと任意の文字が続く
		// )+              : このパターンが1回以上繰り返される
		// [0-9,]*         : 末尾の数字またはカンマの許容
		// $               : 行末
		// このパターンは「1個以上の数字列がカンマで区切られている」という構造を捉えるのに適している。

		// より緩く、かつ「数字とカンマ以外を含まない」ことを確認し、数字が存在することをチェックする。
		// (?:[\d,]+) は1つ以上の数字またはカンマの連続を意味する。
		// この行が「1個以上の数字列がカンマで区切られている」という条件を満たすためには、
		// 少なくとも1つの数字があり、その間にカンマが使われている（または末尾にカンマがある）必要がある。

		// 求められている「1 個以上の数字列がカンマで区切られて並んでいる」を正規表現で厳密に表現するのは複雑になるため、
		// 「数字とカンマ以外の文字を含まず、かつ数字が一つ以上含まれている」ことを確認する。
		// カンマ区切りのデータがあることを示すパターン: 数字とカンマのみで構成され、かつ数字が含まれている。
		pattern := `^\s*[\d,]+\s*$`

		if regexp.MustCompile(pattern).MatchString(line) {
			// このパターンは「数字とカンマのみ」をチェックするが、「1個以上の数字列」を保証しない。
			// 厳密に「1個以上の数字列がカンマで区切られている」ためには、少なくとも1つの数字が含まれていることを確認する必要がある。
			// ただし、提示された例の仕様を最もシンプルに解釈し、数字とカンマの組み合わせのみが存在すれば妥当とする。
			// 1個以上の数字列がカンマで区切られている = 少なくとも1つの数字列が存在する。
			// したがって、行に数字が一つでも含まれていれば、その行は妥当であると判断する。

			hasDigit := false
			for _, r := range line {
				if r >= '0' && r <= '9' {
					hasDigit = true
					break
				}
			}

			if hasDigit {
				validCount++
			}
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
