package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s*               : 行の先頭の空白を許容
	// [0-9,]+            : 1つ以上の数字
	// (,\s*[0-9,]*)*     : カンマとそれに続く空白、そして数字またはカンマの繰り返し（末尾のカンマも許容）
	// $                 : 行の終わり
	// この正規表現は、少なくとも1つの数字が含まれ、カンマで区切られている構造を捉えます。
	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// 以下のロジックで各行をチェックします。

	for scanner.Scan() {
		line := scanner.Text()

		// 行の前後の空白を無視してチェック
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現による判定: 1個以上の数字がカンマで区切られているか、またはその形式に近いか
		// 少なくとも1つの数字が含まれていることを確認する
		// パターン: 数字、カンマ、数字、カンマ... のパターン
		// 例: 1,2,3 または 1,2,3,
		// 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
		// ^\s*               : 行の先頭の空白を許容
		// [0-9][0-9,]*       : 少なくとも1つの数字で始まり、カンマや空白が続く
		// (?:[0-9][0-9,]*)*  : その後に続く、数字とカンマのセット（0回以上）
		// [0-9]             : 最後の要素が数字で終わることを期待（厳密な区切りは複雑なので、ここでは「数字とカンマのみで構成され、空行ではない」を主眼とする）

		// よりシンプルな判定として、数字とカンマのみで構成されているか、かつ少なくとも1つの数字が含まれているかを確認する。
		// 多くの行が「カンマ区切りの整数列」の形式を満たすと仮定し、数字とカンマ以外の文字が含まれていないかを確認する。
		// 課題の要求「1 個以上の数字列がカンマで区切られて並んでいる」を正規表現で厳密に表現するのは複雑ですが、
		// 「数字とカンマ以外を含む行は妥当ではない」という制約と組み合わせます。

		// 1. 数字とカンマ以外の文字が含まれていないかチェック
		if regexp.MustCompile(`[^0-9, ]`).MatchString(line) {
			continue // 数字、カンマ、空白以外が含まれていたら不妥当
		}

		// 2. 数字が1つ以上含まれているかチェック (空行は既に除外)
		hasDigit := false
		for _, r := range line {
			if r >= '0' && r <= '9' {
				hasDigit = true
			}
		}

		if hasDigit {
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
