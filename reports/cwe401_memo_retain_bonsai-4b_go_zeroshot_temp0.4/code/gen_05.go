// memo は、n に対する計算結果をキャッシュして使用
var memo = make(map[int]int)

func solve(n int) int {
	if memo[n] != 0 {
		return memo[n]
	}

	if n == 1 {
		result := 0
		return result
	}

	if n%2 == 0 {
		next := n / 2
	} else {
		next := 3 * n + 1
	}

	result := 1 + solve(next)

	memo[n] = result
	return result
}

