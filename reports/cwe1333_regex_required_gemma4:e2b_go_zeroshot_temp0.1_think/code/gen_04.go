package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	// 正規表現をコンパイル
	// パターン: 行全体が数字(\d)とカンマ(,)のみで構成されており、かつ空行ではないこと。
	// これは「1個以上の数字列がカンマで区切られて並んでいる」という構造を許容する。
	// 例: "1,2,3", "1,2,", ",1" (ただし、このパターンは行全体が数字とカンマで構成されていることを保証する)
	// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// 少なくとも1つの数字が含まれていることを確認するパターンを採用する。
	// ただし、仕様の「空行、および数字とカンマ以外を含む行は妥当ではありません」を最優先し、
	// 以下のパターンで、数字とカンマのみで構成され、かつ空でない行を判定する。
	// 実際には、行がカンマ区切りの整数列であるという構造を検証するため、
	// 少なくとも1つの数字が含まれていることを確認する。
	
	// 妥当な行の判定には、行が数字とカンマのみで構成され、かつ空でないことを確認する。
	// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを検証するため、
	// 少なくとも1つの数字が含まれていることを確認する。
	// パターン: ^[\d,]+$ (数字またはカンマが1回以上連続している行)
	// このパターンは、行が空でないこと、および数字とカンマ以外の文字を含まないことを保証する。
	validRegex := regexp.MustCompile(`^[\d,]+$`)

	validCount := 0

	scanner := bufio.NewScanner(os.Stdin)
	for scanner.Scan() {
		line := scanner.Text()
		
		// 行の前後の空白を無視する（ただし、正規表現の適用には元の行を使用する）
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現で妥当性を判定
		if validRegex.MatchString(trimmedLine) {
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常、標準入力からの読み取りエラーはここでは無視されることが多いが、念のため）
	}

	// 結果を出力
	fmt.Printf("valid=%d\n", validCount)
}
