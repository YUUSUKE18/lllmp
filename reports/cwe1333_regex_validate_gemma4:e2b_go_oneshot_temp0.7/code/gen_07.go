package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())

		if line == "" {
			// 空行は妥当ではない
			continue
		}

		// 末尾のカンマを除去して、カンマで分割
		trimmedLine := strings.TrimRight(line, ",")

		if trimmedLine == "" {
			// カンマのみの行（例: "," や " , "）は妥当ではない
			continue
		}

		// カンマで分割
		parts := strings.Split(trimmedLine, ",")

		// 1個以上の数字列がカンマで区切られているかを確認する
		// partsの長さが1以上であれば、少なくとも1つの要素（数字列）が存在する。
		// ただし、空の要素が含まれている場合（例: "1,,2" -> ["1", "", "2"]）、
		// 厳密に「1個以上の数字列」が区切られているか、という点に注意が必要。
		// 仕様：「1個以上の数字列がカンマで区切られて並んでいる」
		// 空白や数字とカンマ以外を含む行は妥当ではない。

		isValid := true
		for _, part := range parts {
			// 各部分が空でないことを確認する。数字列のみが期待される。
			if part == "" {
				// 連続するカンマや、先頭/末尾のカンマが原因で空の要素が生成された場合
				// ただし、元の行が "1,2," や "1,,2" のような形式を許容するか？
				// 「末尾のカンマは許容します」という指示と、「1個以上の数字列がカンマで区切られて並んでいる」を考慮する。

				// 行が "1,2," の場合: parts = ["1", "2", ""]。最後の "" は末尾のカンマに対応する。
				// partsの長さが1以上であり、かつ、全ての要素が数字列（または空文字列）で構成されている必要がある。
				// 「数字とカンマ以外を含む行は妥当ではない」という制約を重視する。
				
				// もし、空文字列が含まれることが「妥当ではない」と解釈するなら、
				// 連続するカンマや前後の空白のみを許容する構造をチェックする。

				// 厳密に「数字列」のみで構成されているかを確認する。
				// ここでは、もし空文字列が含まれていたら、それは妥当ではないと判断する。
				isValid = false
				break
			}

			// 部分が数字列であることを確認 (数字とカンマ以外を含む行は妥当ではない、という制約を再確認)
			// 実際には、Splitで得られた要素が全て数字のみで構成されているかを確認する。
			if _, err := fmt.Sscanf(part, "%d", new(int)); err != nil {
				// Sscanfで整数に変換できない場合、それは数字とカンマ以外を含むことになる。
				// ただし、Splitで得られた要素はカンマで区切られた文字列なので、
				// このチェックは、元の行が数字とカンマだけで構成されているかどうかの検証に役立つ。
				// ここでは、もし要素が数字でなければ不妥当とする。
				isValid = false
				break
			}
		}

		if isValid {
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)

	if err := scanner.Err(); err != nil {
		// エラー処理はここでは省略するが、実際には考慮すべき。
	}
}
