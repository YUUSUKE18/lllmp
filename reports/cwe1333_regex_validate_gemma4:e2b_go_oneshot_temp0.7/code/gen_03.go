package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())

		if line == "" {
			// 空行は妥当ではない
			continue
		}

		// 末尾のカンマは許容する
		// 少なくとも1つの数字列が存在する必要がある
		if strings.Contains(line, ",") {
			// カンマを含む場合、カンマで分割した要素が少なくとも1つ以上あるかを確認する
			parts := strings.Split(line, ",")
			// 末尾のカンマがある場合、最後の要素は空文字列になる可能性がある
			// 例: "1,2," -> ["1", "2", ""]
			// 例: "1," -> ["1", ""]
			// 例: "," -> ["", ""] (これは空行として扱われるべきだが、ここでは行全体が妥当か判定する)

			// 妥当なのは、カンマで区切られた要素の中に数字列が含まれている場合。
			// 厳密には、「1個以上の数字列がカンマで区切られて並んでいる」必要がある。
			// これは、カンマで区切った後に、少なくとも1つの非空の要素があることを意味する。
			
			// 処理を単純化するため、カンマで分割した後、空文字列でない要素が1つ以上あるかを確認する。
			// ただし、仕様は「1 個以上の数字列がカンマで区切られて並んでいること」なので、
			// 区切り文字で分割した結果、数字列が1つ以上存在すれば良い。

			hasDigits := false
			for _, part := range parts {
				if strings.TrimSpace(part) != "" {
					// 数字列のみで構成されているか確認する（数字以外の文字が含まれていないか）
					if strings.TrimSpace(part) == "" {
						continue
					}
					if _, err := fmt.Sscan(part); err == nil {
						hasDigits = true
					} else {
						// 数字以外の文字が含まれている場合、それは妥当ではない
						hasDigits = false
						break
					}
				}
			}

			// 末尾のカンマが許容されるため、最後の要素が空でも良いが、全体として数字列が存在する必要がある。
			// "1,2" -> ["1", "2"] -> true
			// "1," -> ["1", ""] -> true (1個以上の数字列が区切られていると見なす)
			// "," -> ["", ""] -> false (数字列が0個)
			
			// 再評価: 「1 個以上の数字列がカンマで区切られて並んでいる」
			// これは、文字列がカンマで区切られ、その区切りで分けられた各部分が数字列である、というよりは、
			// カンマで区切られた全体が「数字とカンマのみ」で構成され、かつ数字列が1つ以上存在することと解釈する。
			
			// 最も単純な解釈：文字列がカンマで区切られた後、少なくとも一つの要素が数字のみで構成されていること。
			// 空行は除外済み。
			
			// 最後の要素が空でも許容される（末尾のカンマが許容されるため）
			// "1,2" -> 2個の数字列
			// "1," -> 1個の数字列と1個の空文字列
			// "," -> 2個の空文字列
			
			// 妥当性の判定を「カンマで区切られた要素の中に、数字のみの文字列が1つ以上含まれているか」とする。
			isValid := false
			for _, part := range parts {
				trimmedPart := strings.TrimSpace(part)
				if trimmedPart != "" {
					// その部分が純粋な整数であるか確認する
					if _, err := fmt.Sscan(trimmedPart); err == nil {
						isValid = true
						break
					}
				}
			}
			
			if isValid {
				validCount++
			}
		} else {
			// カンマを含まない場合、これは「1個の数字列」として妥当と見なすか？
			// 仕様：「1 個以上の数字列がカンマで区切られて並んでいる」
			// カンマがない場合は、カンマ区切りとして成立しないと判断するのが安全。
			// ただし、もし "123" が入力された場合、これは「1個の数字列」と解釈できるかもしれない。
			// 厳密には「カンマで区切られて」いる必要があるため、カンマがない行は不妥当とする。
			// 例: "123" はカンマで区切られていないため、妥当ではないと判断する。
		}
	}

	fmt.Printf("valid=%d\n", validCount)

	if err := scanner.Err(); err != nil {
		// エラー処理はここでは省略するが、通常は必要
	}
}
