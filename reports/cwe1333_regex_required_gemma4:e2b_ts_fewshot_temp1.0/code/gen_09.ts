const data: Buffer[] = [];
process.stdin.on("data", (c: Buffer) => data.push(c));
process.stdin.on("end", () => {
  const s = Buffer.concat(data).toString("utf8");
  const lines: string[] = s.split('\n');
  let validLines = 0;

  // カンマ区切りの整数列の妥当性を判定する正規表現
  // ^\s* は行の先頭の空白を許容
  // (?:[\d,]*\s*)* は数字とカンマ、および空白の任意の繰り返し（非キャプチャグループ）
  // .* は行全体（カンマを含む）
  // $ は行の末尾
  // 正規表現の解説:
  // ^\s* : 行頭の任意の空白
  // (?:[\d,]+\s*)* : 1つ以上の数字とカンマの塊に続く任意の空白（複数の数値が区切られていることを想定）
  // [0-9,]*$ : 行末の数字やカンマのみ（末尾のカンマも許容するため）
  // よりシンプルに、「数字とカンマのみ」で構成されていることを確認し、空行や不正な文字がないかをチェックする。
  // 求められているのは「1個以上の数字列がカンマで区切られて並んでいる」という構造。
  // 正規表現で「カンマで区切られた整数列」を表現するには、数字とカンマのみで構成されていることを確認する。

  // 妥当な行を判定するための正規表現の試行:
  // 1. 行が完全に空でないことを確認
  // 2. 行が数字とカンマのみで構成されていることを確認
  // 3. 末尾のカンマが許容される。

  for (const line of lines) {
    const trimmedLine = line.trim();

    if (trimmedLine === "") {
      // 空行は妥当ではない
      continue;
    }

    // 行が数字、カンマ、空白のみで構成されているかを確認
    // 数字、カンマ、空白以外の文字が含まれていないこと
    const regex = /^[\d,]*\s*$/;
    if (!regex.test(line)) {
      // 数字とカンマ以外の文字が含まれている場合は妥当ではない
      continue;
    }

    // 1個以上の数字列がカンマで区切られているか、または数字とカンマのみで構成されているかを確認する。
    // 「1個以上の数字列がカンマで区切られて並んでいる」という条件を満たすためには、カンマが存在するか、または数字が一つ以上存在する必要があります。
    // 末尾のカンマは許容される。
    
    // 少なくとも1つの数字が含まれているか、カンマが含まれているかを確認する。
    const hasDigits = /\d/.test(line);
    const hasComma = /,/.test(line);

    // 妥当な条件: 数字が含まれている、またはカンマが含まれている（そして空行ではない）。
    // ただし、例として「1個以上の数字列がカンマで区切られている」という点を重視する。
    // 例: "1,2,3" (OK), "10," (OK), " , " (NG, 空行で除外済み), "abc" (NG, 既に除外済み)

    // カンマで区切られた整数列のパターンを厳密にチェックする
    // 任意の数字とカンマのみの文字列であり、かつ、何らかの構造を持っているか。
    // 末尾のカンマは許容される。
    // "1,2" (OK), "1,2," (OK), "," (NG, 数字がないため)
    
    // 数字が含まれている場合、それは通常、1個以上の数字列があることを示唆する。
    if (hasDigits) {
        validLines++;
    } else {
        // 数字が含まれていないが、カンマや空白のみの場合（例: "," や " , " は既に除外済み、"   " は除外済み）、
        // 数字がない行は妥当ではないと判断する。
        // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ので、数字が0個なら不適。
    }
  }

  console.log(`valid=${validLines}`);
});
