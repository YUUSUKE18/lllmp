const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let lines = 0;
let validLines = 0;

rl.on('line', (line) => {
  lines++;
  // 正規表現:
  // ^\s* : 行頭の任意の空白
  // (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ (カンマ区切りの整数列)
  // (?:,*\s*$) : 末尾のカンマと空白（オプション）
  // + : 1回以上繰り返す
  // $ : 行末
  //
  // より厳密に、カンマ区切りの整数列が1つ以上存在することを確認する。
  // 1. 行が空でないこと
  // 2. 行が数字とカンマのみで構成されていること
  // 3. 少なくとも1つの数字列が存在すること
  const regex = /^\s*(?:[0-9]+(?:,\s*[0-9]+)*)(?:,*\s*)*$/;

  // 判定ロジックをよりシンプルに、行全体をテストする。
  // 妥当な行とは、「1個以上の数字列がカンマで区切られている」こと。
  // これは、行内に数字とカンマが混在し、かつ数字の並びがあることを意味します。

  // 簡略化のため、行をトリムし、数字とカンマのみで構成されているかをチェックし、数字が1つ以上あるかを確認する。
  const trimmedLine = line.trim();

  if (trimmedLine === "") {
    // 空行は妥当ではない
    return;
  }

  // カンマ区切りの整数列のパターンにマッチするか確認する
  // パターン: 任意の数の数字とカンマの組み合わせで構成されている
  // 例: "1,2,3", "1,2,", "100"
  const pattern = /^[\d,]+$/;
  
  if (pattern.test(trimmedLine)) {
    // 数字とカンマのみで構成されている。
    // さらに、「1個以上の数字列がカンマで区切られている」という条件を満たすか？
    // これは、文字列内に少なくとも1つの数字が存在すればほぼ満たされるが、「カンマで区切られている」という構造が必要。
    
    // 妥当性の定義を再解釈: 「1個以上の数字列がカンマで区切られて並んでいる」
    // これは、カンマが存在し、その間に数字があることを意味する。
    // 例: "1,2" -> 妥当。 "1" -> 妥当（カンマなしの場合も含まれると解釈）。
    // 仕様に従い、行が数字とカンマのみで構成され、空行でない場合に妥当とする。
    // もし「カンマで区切られている」が必須なら、カンマが含まれていることを要求する。
    
    // 例2 (カンマ区切りの語の例) は、空でない語の数を数えている。
    // ここでは、入力行自体が「カンマ区切りの整数列」として妥当かを判定する。
    // 妥当であるためには、数字とカンマのみで構成され、空行でないことが必要。
    // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ためには、カンマが含まれている必要がある。
    
    // カンマの有無をチェック
    if (trimmedLine.includes(',')) {
        validLines++;
    } else {
        // カンマがない場合、単一の整数列と見なすか？
        // 「1個以上の数字列がカンマで区切られて並んでいる」という記述から、カンマ区切りが主と解釈する。
        // 少なくとも1つの数字列が存在すれば良い、という解釈も可能。
        // 例: "123" は、区切りがないが、1つの数字列として妥当。
        // しかし、他の例の文脈から、"1,2,3" 形式が意図されていると考える。
        // 妥当な行数に合わせるため、カンマの存在を必須とする。
        // もしカンマがなくても許容する場合: validLines++;
        // 今回は、例の文脈に従い、カンマ区切りであることを重視する。
        // 厳密に「カンマで区切られている」ことを要求する。
    }
  }
});

rl.on('end', () => {
  // 最終的な結果を出力
  console.log(`valid=${validLines}`);
});
