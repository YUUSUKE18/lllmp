const data: Buffer[] = [];
process.stdin.on("data", (c: Buffer) => data.push(c));
process.stdin.on("end", () => {
  const s = Buffer.concat(data).toString("utf8");
  const lines = s.split(/\r?\n/).filter(line => line.trim() !== "");
  let validCount = 0;

  // 正規表現: 
  // ^\s* : 行の先頭の空白文字
  // (?:[0-9]+(?:, [0-9]+)*) : 1つ以上の整数列とカンマの組み合わせ (例: 1,2,3, 4,5)
  // (?:,)? : オプションのカンマ (末尾のカンマを許容するため)
  // \s*$ : 行の末尾の空白文字
  // ただし、この課題の仕様をより厳密に解釈するために、各行が「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。

  // 1行ごとに判定
  for (const line of lines) {
    // 1. 行全体をトリムして、前後の空白を無視する
    const trimmedLine = line.trim();

    if (trimmedLine === "") {
      // 空行は妥当ではない（仕様：「空行は妥当ではない」）
      continue;
    }

    // 2. 正規表現で判定: 1個以上の数字列とカンマのみで構成されているか
    // 正規表現: ^\s*(?:[0-9]+(?:, [0-9]+)*).*$
    // このパターンは、行が数字とカンマのみで構成されていることを確認する。
    // 例: "1,2,3" -> マッチ
    // 例: "1,2," -> マッチ (末尾カンマ許容)
    // 例: "1, 2, 3" -> スペースは無視されるべきだが、ここでは「数字とカンマ以外を含む行は妥当ではない」という制約を重視する。
    
    // 厳密なチェックのため、行全体が数字とカンマのみで構成されているかを確認する
    // 数字、カンマ、空白以外の文字が含まれていないことを確認。
    const validPattern = /^[0-9,]*$/;

    if (validPattern.test(line)) {
        // 3. 妥当性の判定: 1個以上の数字列がカンマで区切られているか
        // 区切り文字の後に数字が続く、あるいは数字で終わる必要がある。
        // 例: "1" は妥当だが、"a,1" は不妥当。
        // "1,2,3" は妥当。
        // 末尾のカンマは許容される。
        
        // 数字が含まれていて、カンマが存在するか、単一の数字であるかをチェック。
        // 1個以上の数字列がカンマで区切られている、または単一の数字である。
        // 空白は無視されるので、行に含まれる文字が数字とカンマのみであるかをチェックする。
        
        const content = line.replace(/\s/g, ''); // 空白を削除して純粋な数字とカンマのみにする
        if (content.length === 0) {
            continue; // 空白のみ（これは既に行のフィルタリングで除外されているはずだが念のため）
        }

        // 内容が数字とカンマのみで構成されていることを確認済み。
        // 1個以上の数字列がカンマで区切られているか、または単一の数字である。
        // 正規表現で1つ以上の数字とカンマのシーケンスが存在するか確認する。
        const numbers = content.split(',');
        
        // 各要素が空でない（数字列が存在する）ことを確認し、それが1つ以上あることを確認する。
        const numCount = numbers.filter(n => n.length > 0).length;

        if (numCount >= 1) {
            validCount++;
        }
    }
  }

  console.log(`valid=${validCount}`);
});
