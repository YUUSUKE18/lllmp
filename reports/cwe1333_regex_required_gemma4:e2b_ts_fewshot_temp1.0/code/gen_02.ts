const data: Buffer[] = [];
process.stdin.on("data", (c: Buffer) => data.push(c));
process.stdin.on("end", () => {
  const s = Buffer.concat(data).toString("utf8");
  const lines = s.split('\n').length;
  let validLines = 0;
  const regex = /^[\s\S]*?[\d,]+[\s\S]*$/;

  for (const line of s.split('\n')) {
    const trimmedLine = line.trim();

    if (trimmedLine === "") {
      continue;
    }

    // 末尾のカンマは許容する
    // 正規表現で、数字とカンマのみで構成されているか、またはその周囲に空白のみがあることを確認する
    // 妥当である条件: 1個以上の数字とカンマが、空白を除いて存在すること。末尾のカンマは許容。
    // 正規表現の解説:
    // ^\s* : 行の先頭の任意の空白
    // ([\d,]+) : 1つ以上の数字またはカンマ（これが数字列の存在を示す）
    // \s*$ : 行の末尾の任意の空白
    // ただし、行全体が数字とカンマで構成されていることをより厳密にチェックする。

    // 妥当性の判定ロジックを再考:
    // 「1個以上の数字列がカンマで区切られて並んでいること」
    // 例: "1,2,3" -> 妥当
    // 例: "1," -> 妥当
    // 例: "," -> 不妥当 (数字がない)
    // 例: "abc" -> 不妥当 (数字がない)
    // 例: "1,a,2" -> 不妥当 (数字とカンマ以外を含む)

    // 1. 数字とカンマ以外を含まないかチェック
    if (!/^[0-9,]*$/.test(line.trim())) {
        continue; // 数字とカンマ以外を含む行は不妥当
    }

    // 2. 1個以上の数字とカンマが存在するかチェック
    // 空行はすでにスキップしているため、ここに含まれる行は少なくとも数字またはカンマを含んでいる。
    // 数字やカンマが一つも含まれていない行（これは上記1で除外されるはずだが、念のため）を除外する必要がある。

    // 行が空白のみ、または数字・カンマのみで構成されていることを確認し、少なくとも1つの数字またはカンマが存在するか確認する。
    const content = line.trim();
    if (content === "") {
        continue; // 空行はスキップ
    }

    // 少なくとも1つの数字またはカンマが存在するかをチェック
    if (/[0-9,]/g.test(content)) {
        validLines++;
    }
  }

  console.log(`valid=${validLines}`);
});
