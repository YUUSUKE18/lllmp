const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let lines: string[] = [];

rl.on('line', (line) => {
  lines.push(line);
});

rl.on('close', () => {
  let validLines = 0;
  // 正規表現: ^\s*([0-9,]+(,\s*[0-9,]+)*)?\s*$
  // これは、行が数字とカンマのみで構成されており、カンマ区切りで数字の列が並んでいることを許容する。
  // 末尾のカンマは許容する。空行は除外されるべき。
  // 厳密な要件：1個以上の数字列がカンマで区切られて並んでいる。空行、数字とカンマ以外の文字は不可。

  // 各行に対して正規表現で検証する
  const validRegex = /^[\d,]*(\d+)(?:,[\d,]*)*\s*$/;

  for (const line of lines) {
    // 行の前後の空白を無視するため、トリムは行の前後ではなく、行の内容自体をチェックする
    // 厳密に「数字列とカンマのみ」で構成され、かつ「1個以上の数字列」が区切られているかを判定する。
    // 空行は妥当ではない。
    if (line.trim() === "") {
      continue;
    }

    // 1. 数字とカンマ以外が含まれていないかチェック
    if (!/^[0-9,]*$/.test(line)) {
      continue; // 数字とカンマ以外を含む行は妥当ではない
    }

    // 2. 1個以上の数字列がカンマで区切られているかチェック。末尾のカンマは許容。
    // 可能なパターン: "1,2,3", "1,2,", "1,"
    // 正規表現の解釈:
    // ^[\d,]* : 0個以上の数字またはカンマで始まる
    // (\d+) : 少なくとも1つの数字で始まる（最初の数字列）
    // (?:,[\d,]*)* : カンマとそれに続く任意の文字（数字またはカンマ）が0回以上繰り返される
    // $ : 行の終端
    // 末尾のカンマが許容されるため、行の終端にカンマがあっても良い。

    // よりシンプルなアプローチ：カンマで分割し、空でない要素が1つ以上あるかを確認する。
    const parts = line.split(',');
    let hasDigits = false;
    for (const part of parts) {
      if (part.trim() !== "") {
        hasDigits = true;
      }
    }
    
    // 妥当条件の再評価:
    // - 空行はNG (line.trim() === "") で除外済み
    // - 数字とカンマ以外はNG ( /^[0-9,]*$/ でチェック済み)
    // - 1個以上の数字列がカンマで区切られている。これは、カンマで分割して空でない要素が存在すれば満たされる。
    // 複数の数字列が並んでいる必要があるため、少なくとも1つの数字列が存在すれば良い。
    
    if (hasDigits) {
        validLines++;
    }
  }

  console.log(`valid=${validLines}`);
});
