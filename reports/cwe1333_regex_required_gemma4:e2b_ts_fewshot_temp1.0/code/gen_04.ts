const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let lineCount = 0;
let validLines = 0;

rl.on('line', (line) => {
  lineCount++;
  // 正規表現: ^\s*(\d+(,\d+)*)\s*$
  // ^\s* : 行頭の空白（無視）
  // (\d+(,\d+)*) : 1つ以上の数字、それに続くカンマと数字の繰り返し（1個以上の数字列がカンマで区切られていることを意味する）
  // \s*$ : 行末の空白（無視）
  // 末尾のカンマも許容する場合、より柔軟なパターンが必要。
  // 仕様：「1 個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容する」
  
  // 判定ロジック:
  // 1. 行が空でなければ、その行が数字とカンマのみで構成されているか確認する。
  // 2. 数字とカンマのみで構成されていることを確認する。
  // 3. 末尾のカンマがあっても良い。
  
  // より厳密に「1 個以上の数字列がカンマで区切られている」ことを正規表現で表現する。
  // 数字の塊 (数字とカンマ) の繰り返し。
  // 例: 1,2,3 または 1,2,3,
  // 任意の数字とカンマの組み合わせが1回以上続く。
  // ^\s*  : 行頭の空白
  // (?:     : 非キャプチャグループの開始
  //   \d+  : 1つ以上の数字
  //   (?:,\d+)* : カンマとそれに続く1つ以上の数字の繰り返し（最後の要素以外）
  // )
  // (?:,\d+)? : 最後の要素の後のカンマ（オプション）
  // \s*$ : 行末の空白
  
  // 最も単純に「カンマ区切りの整数列」の形式をチェックし、空行と数字・カンマ以外を弾く。
  // 1. 空行判定
  if (line.trim() === "") {
    // 空行は妥当ではない
    return;
  }
  
  // 2. 数字とカンマのみで構成されているかチェック
  // 正規表現の解説: 
  // ^\s*       : 行頭の空白
  // (?:       : 非キャプチャグループ
  //   \d+     : 1つ以上の数字
  //   (?:,\d+)* : カンマとそれに続く数字の繰り返し (複数の要素がある場合)
  // )
  // (?:,\d+)?  : 最後の要素の後のカンマ（末尾にカンマがあっても良い）
  // \s*$       : 行末の空白
  // この正規表現は「数字とカンマの組み合わせ」をチェックするが、「1個以上の数字列がカンマで区切られている」という構造を直接表現するのは複雑。
  
  // より単純に、行に含まれる文字が数字、カンマ、空白のみで構成されているかを確認し、
  // 少なくとも1つの数字が含まれていることを確認する。
  
  const trimmedLine = line.trim();
  if (!/^[0-9,]*$/.test(trimmedLine)) {
    // 数字とカンマ以外の文字が含まれている場合、妥当ではない
    return;
  }

  // 数字とカンマのみで構成されている場合、少なくとも1つの数字が含まれているか確認する
  if (trimmedLine.length > 0) {
    if (/\d/.test(trimmedLine)) {
      validLines++;
    }
  }
});

rl.on('close', () => {
  console.log(`valid=${validLines}`);
});
