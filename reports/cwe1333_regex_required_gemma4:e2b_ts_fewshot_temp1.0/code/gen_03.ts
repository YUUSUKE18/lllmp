const readline = require('readline');

const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout,
    crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
    // 正規表現による判定:
    // ^\s*          -> 行頭の任意の空白
    // (?:[\d,]+\s*)* -> 数字とカンマのグループが0回以上繰り返される (数字とカンマのみを許容)
    // (?:[\d,]+)?   -> 最後の数字とカンマのグループ (任意)
    // \s*$          -> 行末の任意の空白
    // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
    // これは、カンマで区切られた数字（連続する数字とカンマ）が少なくとも1つ存在することを意味する。

    // より簡潔に、行が「数字とカンマ」のみで構成され、少なくとも1つの数字が存在するかどうかをチェックする。
    // 妥当な行は、数字とカンマのみで構成され、空行ではない、という条件を満たす必要がある。

    // 1. 空行でないことを確認 (トリム後が空でなければOK)
    if (line.trim() === "") {
        // 空行は妥当ではない（ただし、仕様上は「空行、および数字とカンマ以外を含む行は妥当ではない」とあるため、空行は妥当でない）
        return;
    }

    // 2. 数字とカンマのみで構成されていることを確認
    // 正規表現: ^[\d,]*$ (数字とカンマのみで構成されている)
    // しかし、「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する必要がある。

    // 妥当な行の判定ロジックを正規表現で定義する。
    // 妥当な行の例: "1,2,3", "100,"
    // 妥当でない行の例: "", "a,b", "1a", "1,,2" (カンマが連続する場合も問題になる可能性)

    // ここでは、行全体が数字とカンマ（および空白）のみで構成されており、カンマで区切られた数字が含まれていることを確認する。
    // 「数字とカンマ以外を含む行は妥当ではない」 => 許可される文字は数字(0-9), カンマ(,), 空白( )のみ。
    const validPattern = /^[\d,]*$/;

    if (!validPattern.test(line)) {
        // 数字とカンマ以外の文字が含まれている場合、妥当ではない
        return;
    }

    // 3. 1個以上の数字列がカンマで区切られていることを確認する。
    // 末尾のカンマは許容される。
    // 最小の条件: 少なくとも1つの数字が存在し、カンマのパターンが成立していること。
    
    // 処理する文字列をトリムして、内部のカンマの数をチェックする。
    const trimmedLine = line.trim();
    if (trimmedLine.length === 0) {
        return; // 空行は除外
    }

    // カンマで分割し、空でない要素が1つ以上あるかを確認する。
    // 末尾のカンマは無視される（例: "1,2," -> ["1", "2", ""]）
    const parts = trimmedLine.split(',');
    
    // 妥当であるための条件: 
    // 1. 少なくとも1つの数字が含まれている (partsのいずれかが数字であること)
    // 2. カンマの区切りが意味を持つ (カンマがある、または数字が存在する)
    
    let hasNumber = false;
    for (const part of parts) {
        if (part.trim() !== "") {
            // 部分が数字のみで構成されているか、または数字を含むかをチェック
            if (/^\d+$/.test(part.trim())) {
                hasNumber = true;
            }
        }
    }

    // 最終的な妥当性の判定：
    // 1. 空行ではない (既にチェック済み)
    // 2. 数字とカンマ以外を含まない (既にチェック済み)
    // 3. 少なくとも1つの数字列がカンマで区切られている (hasNumberがtrue)
    if (hasNumber) {
        validLines++;
    }
});

rl.on('end', () => {
    console.log(`valid=${validLines}`);
});
