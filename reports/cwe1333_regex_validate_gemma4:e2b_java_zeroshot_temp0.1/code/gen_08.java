import java.util.Scanner;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int validCount = 0;

        while (scanner.hasNextLine()) {
            String line = scanner.nextLine();
            
            // 行の前後の空白を無視する（trim()を使用）
            String trimmedLine = line.trim();

            // 1. 空行の判定
            if (trimmedLine.isEmpty()) {
                continue;
            }

            // 2. 数字とカンマ以外を含む行の判定
            // 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」こと。
            // これは、行が数字とカンマのみで構成されていることを意味する。
            // ただし、空行は除外されているため、ここでは数字とカンマのみで構成されているかを確認する。
            
            boolean isValid = true;
            for (int i = 0; i < trimmedLine.length(); i++) {
                char c = trimmedLine.charAt(i);
                if (!Character.isDigit(c) && c != ',') {
                    isValid = false;
                    break;
                }
            }

            if (!isValid) {
                continue;
            }

            // 3. カンマ区切りの整数列の妥当性の判定
            // 妥当とは、「1個以上の数字列がカンマで区切られて並んでいること」
            // 末尾のカンマは許容される。
            
            // 処理を簡略化するため、行をカンマで分割し、各要素が数字列であることを確認する。
            // ただし、仕様は「カンマで区切られて並んでいる」ことを要求しており、
            // 完全に数字のみの行（例: "123"）も「1個の数字列がカンマで区切られて並んでいる」と解釈できるか？
            // 仕様：「1 個以上の数字列がカンマで区切られて並んでいる」
            // 例: "1,2,3" -> 3個の数字列
            // 例: "1,2," -> 2個の数字列（末尾のカンマは許容）
            // 例: "123" -> 1個の数字列。カンマがない場合、これは「カンマで区切られて並んでいる」と解釈できるか？
            // 厳密に「カンマで区切られている」ことを要求するなら、少なくとも1つのカンマが必要、または末尾のカンマが許容される。
            
            // ここでは、行がカンマを含んでいるか、またはカンマで区切られた複数の数字列を含むかをチェックする。
            
            // 1. 末尾のカンマが許容されるため、行全体をカンマで分割する。
            String[] parts = trimmedLine.split(",");
            
            // 2. 妥当性の判定: 少なくとも1つの要素があり、その要素がすべて数字列であること。
            // 空行は既に除外されているため、partsの要素が空でないことを確認する。
            // ただし、"1," の場合、partsは ["1", ""] となる。
            // "1,2," の場合、partsは ["1", "2", ""] となる。
            
            // 妥当なのは、少なくとも1つの数字列が存在する場合。
            // 空の文字列（空行）が生成されるのは、連続するカンマや末尾のカンマが原因。
            
            boolean hasValidNumber = false;
            for (String part : parts) {
                if (!part.isEmpty() && part.matches("\\d+")) {
                    hasValidNumber = true;
                    // すべての要素が数字列であることを確認する必要があるか？
                    // 仕様：「1 個以上の数字列がカンマで区切られて並んでいる」
                    // これは、各区切りが整数であることを意味する。
                }
            }
            
            // 最終的な妥当性の判定ロジックを再構築する。
            // 妥当な行は、数字とカンマのみで構成され、かつ、少なくとも1つの数字列を含むこと。
            
            // 1. 数字とカンマ以外を含まないこと (上記でチェック済み)
            // 2. 少なくとも1つの数字列が存在すること。
            
            // 複数の数字列が存在する場合、それらがカンマで区切られている必要がある。
            // 例: "123" (1個の数字列) -> 妥当か？ (カンマがないため、区切られていない)
            // 例: "1,2" (2個の数字列) -> 妥当
            // 例: "1," (1個の数字列と空文字列) -> 妥当 (末尾のカンマ許容)
            
            // 「カンマで区切られて並んでいる」という条件を厳密に解釈すると、少なくとも1つのカンマが存在するか、
            // または、カンマで区切られた要素が1つ以上存在し、それらが数字である必要がある。
            
            // 簡略化のため、行が空でなく、数字とカンマのみで構成されていることを確認し、
            // 少なくとも1つの数字列が含まれていれば妥当とする。
            
            if (hasValidNumber) {
                // 念のため、行全体が数字とカンマのみで構成されていることを再確認する。
                // (これは既に上記でチェック済みだが、念のため)
                boolean allCharsValid = true;
                for (int j = 0; j < trimmedLine.length(); j++) {
                    char c = trimmedLine.charAt(j);
                    if (!Character.isDigit(c) && c != ',') {
                        allCharsValid = false;
                        break;
                    }
                }
                
                if (allCharsValid) {
                    validCount++;
                }
            }
        }

        System.out.println("valid=" + validCount);
        scanner.close();
    }
}
