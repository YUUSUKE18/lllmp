import java.util.Scanner;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int validCount = 0;

        while (scanner.hasNextLine()) {
            String line = scanner.nextLine();
            
            // 行の前後の空白を無視する
            String trimmedLine = line.trim();

            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 妥当性の判定ロジック
            // 1. 数字とカンマ以外を含む行は妥当ではない
            // 2. 1個以上の数字列がカンマで区切られていること
            
            // 正規表現を使用して、カンマ区切りの整数列のパターンをチェック
            // パターン: 1つ以上の数字 (\\d+) とカンマ (,) の組み合わせが、
            // 少なくとも1回出現し、行全体がそのパターンで構成されているかを確認する。
            // 許容される形式: 数字,数字,... または 数字, 数字, ... (末尾のカンマは許容)
            
            // 許容されるパターンの例: "1,2,3", "1,2,", "1" (もし1が単独で許容されるなら。仕様では「1個以上の数字列がカンマで区切られて並んでいること」)
            // 最も厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックするには、
            // 数字とカンマ以外の文字が一切含まれず、少なくとも1つのカンマが存在するか、あるいは単一の数字列が存在するかをチェックする必要がある。

            // 判定方針の再確認:
            // 妥当とは、「1 個以上の数字列がカンマで区切られて並んでいること」
            // 空行、および数字とカンマ以外を含む行は妥当ではない。
            
            // 1. 数字とカンマ以外を含む行のチェック (数字とカンマ以外の文字が含まれていないか)
            boolean containsOnlyDigitsAndCommas = true;
            for (int i = 0; i < trimmedLine.length(); i++) {
                char c = trimmedLine.charAt(i);
                if (!((c >= '0' && c <= '9') || c == ',')) {
                    containsOnlyDigitsAndCommas = false;
                    break;
                }
            }
            if (!containsOnlyDigitsAndCommas) {
                continue; // 妥当ではない
            }

            // 2. 1個以上の数字列がカンマで区切られているか (カンマの存在と、数字列の存在)
            // 許容されるのは「1個以上の数字列がカンマで区切られて並んでいる」こと。
            // これは、少なくとも1つのカンマが存在するか、または単一の数字列が存在するケースを考慮する必要がある。
            
            // もし行が空でなければ、その行が数字とカンマのみで構成されている場合、
            // 妥当であるためには、少なくとも1つの数字列が存在する必要がある。
            
            // 数字列が存在しない場合（例: "," または "" は既に除外済み）、このチェックは不要になる。
            // 少なくとも1つの数字列が存在するかどうかをチェックする。
            
            // 複数のカンマ区切りをチェックする最も簡単な方法は、カンマで分割してみて、要素が空でないか確認すること。
            // 末尾のカンマは許容される。
            
            // 処理を簡略化するため、正規表現で「数字とカンマのみ」で構成され、かつ「カンマのパターン」を満たすかを確認する。
            
            // パターン: 1つ以上の数字とカンマのみで構成され、カンマが少なくとも1つ含まれているか、または単一の数字列であるか。
            // 非常に曖昧な仕様であるため、最も厳しい解釈（カンマ区切りであること）を採用する。
            
            // 少なくとも1つのカンマが含まれているか、または単一の数字列であるか。
            boolean isCommaSeparated = false;
            
            // カンマで分割し、要素が1つ以上存在するか確認する。
            // 末尾のカンマを考慮するため、行を処理する前に、末尾のカンマを削除して確認する方が安全かもしれないが、
            // 「末尾のカンマは許容します」という指示があるので、そのまま分割を試みる。
            
            String[] parts = trimmedLine.split(",");
            
            // partsの要素の数（数字列の数）を数える。
            // 末尾のカンマがある場合、最後の要素は空文字列になる可能性がある。
            
            // 例: "1,2,3" -> ["1", "2", "3"] (3個)
            // 例: "1,2," -> ["1", "2", ""] (3個)
            // 例: "1" -> ["1"] (1個)
            // 例: "," -> ["", ""] (2個) -> これは妥当ではないはず。

            // 妥当であるためには、少なくとも1つの数字列が存在しなければならない。
            // 数字列が存在するということは、partsの中に空でない文字列が存在すること。
            
            boolean hasNumberSequence = false;
            for (String part : parts) {
                if (!part.isEmpty()) {
                    // その部分がすべて数字であることを確認 (すでに上記で数字とカンマのみのチェックをしているため、これは冗長かもしれないが安全のため)
                    try {
                        Integer.parseInt(part);
                        hasNumberSequence = true;
                    } catch (NumberFormatException e) {
                        // ここに到達しないはず（数字とカンマのみのチェック済み）
                        hasNumberSequence = false;
                        break;
                    }
                }
            }
            
            // 1個以上の数字列がカンマで区切られて並んでいること。
            // これは、行が空でなく、かつ、数字列が少なくとも1つ含まれている場合に成立すると解釈する。
            if (hasNumberSequence) {
                validCount++;
            }
        }

        System.out.println("valid=" + validCount);
        scanner.close();
    }
}
