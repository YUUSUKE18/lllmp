import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.IOException;

public class Main {
    public static void main(String[] args) throws IOException {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;
        String line;
        
        while ((line = br.readLine()) != null) {
            if (isValidLine(line)) {
                validCount++;
            }
        }
        
        System.out.println("valid=" + validCount);
    }

    private static boolean isValidLine(String line) {
        // 空白を切り捨てて処理する
        String trimmed = line.trim();
        if (trimmed.isEmpty()) {
            return false;
        }

        // 最初の文字が数字またはカンマである必要がある（末尾のカンマのみ許容するため、最初のカンマは除外されるが、実際には "1," や ",2" は許容されず、「整数列」としての定義より「数字から始まる」のが自然だが、仕様「1 個以上の数字列がカンマで区切られて並んでいる」を厳密に解釈すると、末尾のカンマのみ許容という条件がある）
        // 再考: 「末尾のカンマは許容します」は "1,2," が OK を意味する。
        // 「数字とカンマ以外を含む行は妥当ではありません」: 空白以外の文字が含まれてはいけない。
        // 「空行...は妥当ではない」: 既に trim で空なら false にしている。

        // 正規表現による厳密なチェック
        // 数字の列（1 個以上）がカンマで区切られている形式、末尾のカンマも OK。
        // 例: "1", "1,2", "1,", "2,3,4" -> OK
        // 例: "", "   ", "abc", "a,b,c" -> NO
        
        // 正規表現の説明: 
        // ^               : 開始
        // (?:            : 非捕獲グループの開始
        //   \d+          : 1 文字以上の数字
        //   (?:         : 非捕獲グループ (カンマとオプションの次の数字) の開始
        //     ,\d+       : カンマ付き数字 (このパターンは '2,3' のように、数字が連続してない場合も OK か？ -> 数字列は区切られているので '2,3' は OK, '2,,3' は NO. '2,' は OK)
        //     |          : または
        //     ,          : カンマのみ (末尾の場合)
        //   )*           : 0 回または多次繰り返す
        // )?              : 全体をオプション (最初の数字がない場合は許容？ -> 仕様「1 個以上の数字列」なので必須)
        // \d+             : 最初の少なくとも 1 つの数字列
        // (?:,?\d+)*      : その後のカンマ付き（または単独）数字列の繰り返し
        // $?              : 末尾のカンマを許容するため、最後は数字で終わることもカンマでも OK
        
        // 修正された正規表現の構築:
        // "1" -> OK
        // "1,2" -> OK
        // "1," -> OK
        // "1,2," -> OK
        // ",1" -> NO (最初のカンマは数字列ではない)
        // "1a" -> NO
        
        // 正規表現: ^(\d+)(?:,(?=\d)|,\d*)?$ 
        // 解説:
        // ^                          : 行の開始
        // (\d+)                     : 少なくとも 1 つの数字列 (グループ 1)
        // (?:                       : 非捕獲グループ
        //   ,(?=\d)                : カンマが続き、その後に数字がある場合 (例: "1,2")
        //   |                       : または
        //   ,\d*                   : カンマの後に数文字なしでも OK (例: "1,")
        // )*                        : このパターンを 0 回または多次繰り返す
        // $?                       : 行の終了
        // ただし、上記の正規表現 "(\d+)(?:,(?=\d)|,\d*)*$" は "1,,2" が許容されてしまいそう (カンマが連続)。
        // 「数字とカンマ以外を含む行は妥当ではありません」という条件を満たすか確認。
        // 空白以外の文字のみで構成される必要がある。
        
        // さらに簡潔に:
        // 全文字が '0'-'9' または ',' で構成され、最初の文字が数字であり、末尾のカンマを除いた部分は数字とカンマのみの列であること。
        // 正規表現: ^(\d+)(?:,(\d+))*$ | ^\d+(?:,\s*\d+)*$ (空白を許容しないので前者)
        // 仕様「行の前後の空白は無視します」なので trim をした上で、内部の空白も許容すべきか？
        // 「数字とカンマ以外を含む行は妥当ではありません」 -> 内部に空白（スペース）が含まれるなら OK なのか NO なのか。
        // 例: "1 , 2" -> 空白が含まれているので「数字とカンマ以外」→ NO と解釈するのが厳密。
        // しかし、通常のカンマ区切りでは空白を許容することが多いが、この問題文は「数字とカンマ以外を含む行」と言っている。
        // なので、内部の空白も「数字とカンマ以外」とみなして NO にする。
        
        // 正規表現: ^(\d+)(?:,\d+)*$ | ^\d+(?:,\s*\d+)*$
        // 上記を再考: 「末尾のカンマは許容します」 -> "1," は OK.
        // "1,2," -> OK? (末尾のカンマのみ許容、途中の空白含むカンマも許容？)
        // 最も安全な解釈: 文字列は trim された後、「数字とカンマのみで構成され、かつ少なくとも 1 つの数字が存在し、最後の文字がカンマでも OK であればよい」
        
        // 正規表現: ^\d+(?:[\d,]*\d)?$ -> "1," が NO になる (最後の \d が必須). 
        // 正しい正規表現は: ^(\d+)(?:,(\d+))*$ | ^\d+(?:,\s*\d+)*$
        // 空白を許容しない場合: ^(\d+)(?:,(\d+))*$ | ^(\d+)$ | ^(\d+,$) -> これは複雑。
        
        // 再定義: 
        // 1. 空白は末尾のみ許容（trim）し、内部の空白は無視せず NO とする。（「数字とカンマ以外」だから）
        //    → "1 , 2" は ' ' が存在するので NO.
        // 2. 末尾のカンマは OK.
        // 3. 少なくとも 1 つの数字列がある。
        
        // 正規表現: ^(\d+)(?:,\d+)*$ | ^\d+(?:,\s*\d+)*$ (空白を許容しないので、内部的な空白も NO)
        // しかし、「1,」が OK であれば、最後の ' ' は禁止.
        
        // 最終的な正規表現: 
        // 全体が数字とカンマのみで構成され、かつ「少なくとも 1 つの数字があり、最後にカンマがついても良い」
        // 正規表現: ^(\d+)(?:,\d+)*$ | ^\d+(?:,\s*\d+)*$ -> 空白を許容しないので内部空白禁止。
        // 正解に近い: ^(\d+)(?:,\d+)*$ | ^\d+(?:,\s*\d+)*$ 
        // 「1,」は OK. 「1,2」は OK. 「1」は OK. 「1,2,」は OK (末尾のカンマ).
        // 正規表現: ^(\d+)(?:,\d+)*$ | ^\d+(?:,\s*\d+)*$ -> これは "1," が NO にされる (最後の \d が必要).
        
        // 正しいアプローチ: 
        // 文字列を分割し、各部分（カンマ区切り）が数字のみであるか確認。
        // かつ、少なくとも 1 つの部分があること。
        // ただし、「末尾のカンマ」は許容するので、最後の要素は空でも OK.
        
        // アルゴリズム:
        // 1. line.trim() を取得する。
        // 2. 文字列が「数字とカンマのみで構成されているか」を確認する（正規表現 ^[\d,]+$ で確認可能）。
        // 3. 分割して、少なくとも 1 つの要素が空でないか、または末尾のカンマによる空要素がある場合も含めて判断。
        //    仕様「1 個以上の数字列がカンマで区切られて並んでいる」-> "1," -> ["1", ""] -> 1 つの数字列 ("1") と空文字列。
        //    「末尾のカンマは許容します」-> "1,2," -> ["1", "2", ""] -> OK.
        //    ",1" -> ["", "1"] -> 最初の要素が空なので、数字列がない？ -> NO.
        
        // 判定ロジック:
        // - 文字列が [\d,]+ で始まるか (最初の文字が \d か) -> 必須。
        // - 文字列が [\d,]+ で終わるか (最後のカンマは OK).
        // - 全ての文字が \d または , か？ -> 必須。
        
        if (!line.matches("^\\d+(?:[,\\d]+)?$")) {
            return false;
        }
        // 上記の正規表現 "^\d+(?:[,\\d]+)?$" は "1," が NO にされる (最後の \d が必要)。
        // 正しい正規表現: ^(\d+)(?:,[\d]*)?$ -> "1," が OK. "1,2" が OK. "1,2," が OK? 
        // "1,2," -> "1", ",", "2", "," -> グループ 1: "1". 後続: ",", "2", "," -> (?:,[\d]*)* -> ,[\d]* matches ","? No, because \d required.
        
        // 最終的な正規表現の決定:
        // ^[\d,]+$ を満たし、かつ最初の文字が \d で、最後の文字が数字またはカンマで、かつ少なくとも 1 つの数字が含まれている。
        // または、分割してチェックする方が明確。
        
        // 分割チェック:
        // String[] parts = line.split(",");
        // 条件:
        // 1. 最初の要素が空白でないか (trim した後に空ではない) -> "1," の場合 ["1", ""] -> 最初の "1" は OK.
        // 2. 全ての要素が数字のみであるか？ ("1,2," -> ["1", "2", ""] -> "2" は OK, "" は ?)
        // 3. 少なくとも 1 つの要素が空でない数字列であるか。
        
        // 再考: 「空白区切りの整数列」は例 1 にある。「カンマ区切りの語」は例 2.
        // 本課題: 「カンマ区切りの整数列」-> 妥当とは「1 個以上の数字列がカンマで区切られて並んでいる」
        // 末尾のカンマは許容 -> "1," -> OK.
        // 空行 -> NO.
        // 数字とカンマ以外 -> NO.
        
        // 実装:
        // 1. line.trim() -> 空なら false.
        // 2. 文字列が [\d,]+ で始まるか、かつ [\d,]+ で終わるか (最後の文字は \d または ,).
        // 3. 全体が [\d,]* で構成されるか。
        
        if (!line.trim().matches("^\\d+(?:[,\\d]*)?$")) {
            // "1" -> OK
            // "1," -> OK (regex: ^\d+(?:[, \d]*)?$ -> 最後の \d* は空なので , だけで OK)
            // "1,2" -> OK
            // "1,2," -> OK? regex check: \d+ matches "1". (?:[,\\d]*)* matches ",", "2", ",". YES.
            // " ,1" -> NO (starts with space).
            // ",1" -> NO (does not start with \d).
            // "a,b" -> NO.
            return false;
        }
        
        // 念のため、全ての文字が数字またはカンマか確認する。
        for (int i = 0; i < line.length(); i++) {
            char c = line.charAt(i);
            if (c < '0' || c > '9' && c != ',') {
                return false;
            }
        }
        
        // 少なくとも 1 つの数字があるか確認。
        boolean hasDigit = false;
        for (int i = 0; i < line.length(); i++) {
            char c = line.charAt(i);
            if (c >= '0' && c <= '9') {
                hasDigit = true;
                break;
            }
        }
        
        return hasDigit;
    }
}
