package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// 妥当な行数をカウントする
	for scanner.Scan() {
		line := scanner.Text()

		// 正規表現による妥当性の判定
		// ^\s* 表示行の先頭からの空白
		// (?:[\d,]+\s*)* または [\d,]+ 1個以上の数字とカンマの組み合わせ
		// $ 表示行の末尾
		// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
		// 許容されるパターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
		// 形式: (数字,数字,...) または 数字, (数字,数字,...)
		// この仕様は「1 個以上の数字列がカンマで区切られて並んでいる」なので、
		// 少なくとも1つの数字を含む文字列、かつ数字とカンマ以外の文字を含まない、という条件が最も適切。

		// 1. 行が完全に数字とカンマのみで構成されているか
		// 2. 少なくとも1つの数字が含まれているか（カンマのみの行は不適）

		// 正規表現: 1つ以上の数字またはカンマのみで構成されている
		// ^\s* : 行の先頭の空白を許容
		// ([\d,]+) : 1文字以上の数字またはカンマのグループ
		// \s*$ : 行末の空白を許容
		// この単純なパターンでは、「1個以上の数字列がカンマで区切られている」という構造チェックが難しい。

		// 構造チェックをより厳密に行う:
		// 行に含まれる文字が数字(0-9)とカンマ(,)のみで構成されていること。
		// 少なくとも1つの数字が含まれていること。

		// 1. 数字とカンマのみで構成されているか
		if regexp.MustCompile(`^[\d,]*$`).MatchString(line) {
			// 2. 少なくとも1つの数字が含まれているか
			hasDigit := false
			for _, r := range line {
				if r >= '0' && r <= '9' {
					hasDigit = true
					break
				}
			}
			if hasDigit {
				validCount++
			}
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理はここでは省略（競技プログラミングの文脈では通常不要だが、厳密性のため）
	}

	fmt.Printf("valid=%d\n", validCount)
}
