package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列をチェックするための正規表現
	// ^[0-9,]*$ : 行が数字とカンマのみで構成されていることを確認 (末尾のカンマも許容)
	// 1個以上の数字列がカンマで区切られていることを確認するため、
	// 正規表現の適用方法を工夫する。ここでは、少なくとも1つの数字が含まれているかを確認する。
	// 1個以上の数字とカンマの組み合わせを許容するパターン:
	// 少なくとも1つの数字があり、その間にカンマが許される。
	// 具体的には、数字（1回以上）、カンマ、数字（0回以上）の繰り返し。
	// 簡略化のため、行が空でないこと、そして数字とカンマのみで構成されていることを確認し、
	// さらに「1個以上の数字列がカンマで区切られている」ことを確認する。

	// 妥当性の判定ロジックを直接文字列操作と正規表現で実現する。
	// 妥当な行とは、「1個以上の数字列がカンマで区切られて並んでいる」こと。
	// これは、カンマで区切られた複数の非空の数字のシーケンスが許されることを意味する。

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := ""
		// 行の前後の空白を無視する
		for i := 0; i < len(line); i++ {
			if line[i] != ' ' && line[i] != '\t' {
				trimmedLine += string(line[i])
			}
		}

		// 1. 空行のチェック (空行は妥当ではない)
		if trimmedLine == "" {
			continue
		}

		// 2. 数字とカンマ以外を含む行のチェック
		// 正規表現: 数字(0-9)とカンマ(,)以外の文字が含まれていないこと。
		// 妥当な形式: 0-9と,のみで構成されている。
		if !regexp.MustCompile(`^[0-9,]*$`).MatchString(trimmedLine) {
			continue
		}

		// 3. 1個以上の数字列がカンマで区切られているかのチェック
		// この条件を満たすためには、少なくとも1つの数字が含まれており、
		// カンマの並びが意味を持つ必要がある。
		// 例: "1,2,3" は妥当。
		// 例: "1" は妥当（1個の数字列）。
		// 例: "," は不妥当（数字列が0個）。
		// 例: "1,,2" は妥当（空の数字列が許容されるかどうかに依存するが、問題文は「1個以上の数字列」を要求）。

		// 1個以上の数字列が含まれているかを確認する。
		hasDigits := false
		for _, char := range trimmedLine {
			if char >= '0' && char <= '9' {
				hasDigits = true
			}
		}

		// 1個以上の数字が含まれていて、かつ、カンマの存在や数字の配置が許容される。
		// 最小の妥当なケースは "1" のみ。
		// "1,2,3" は妥当。
		// "," は不妥当。
		// "1," は妥当（末尾のカンマは許容されるため）。
		// この条件は、少なくとも1つの数字が存在し、かつ、カンマ区切り形式であること。
		// 最も厳密に「1個以上の数字列がカンマで区切られている」をチェックするには、
		// カンマで区切った後で空のフィールドがないことを確認するか、
		// 少なくとも1つの数字が存在することを確認する。

		// 実際には、空行でないこと、数字とカンマのみであること、そして数字が少なくとも1つ存在すれば、
		// それは「カンマで区切られた整数列」と見なせる。
		// 末尾のカンマは許容されるため、"1," は有効。
		if hasDigits {
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
