package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列が妥当であるかを確認する正規表現
	// ^\s*             : 行の先頭の任意の空白文字
	// (?:             : 非キャプチャグループの開始
	//   \d+           : 1つ以上の数字
	//   ,             : カンマ
	// )*              : 上記のグループが0回以上繰り返される (カンマ区切りでない場合も考慮)
	// \d+             : 少なくとも1つの数字で始まる
	// (?:,\d+)*       : その後にカンマと数字が続く場合
	// $               : 行の終わり
	// この正規表現は「カンマ区切りの整数列」に限定し、末尾のカンマも許容する、という要件を正確に捉える必要があります。
	// よりシンプルに「数字とカンマのみ」で構成され、少なくとも1つの数字が含まれていることを確認します。

	// 許容されるパターン: 任意の空白、数字とカンマの組み合わせ、末尾にカンマがあっても良い。
	// 1. 数字とカンマのみ、または空白のみ。
	// 2. 少なくとも1つの数字が含まれていること。

	// 妥当性の判定ロジックを実装します。
	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 末尾のカンマを無視し、カンマで区切られた数字の集合として評価する
		// 正規表現: 任意の文字、数字、カンマが続く文字列。ただし、数字が少なくとも1つ含まれている必要がある。
		// 末尾のカンマは許容する。
		// ^.*(?:[\d,]*\d).*$ のような複雑な表現ではなく、単純に「カンマ区切りで数字のみ」のパターンを評価します。

		// 妥当な行の定義:
		// 1. 数字とカンマ、および空白のみを含む。
		// 2. 少なくとも1つの数字を含む。
		// 3. 末尾のカンマは許容する。

		// 実際の判定は、行をカンマで分割し、要素が全て数字（またはカンマで区切られた後に数字が存在する）であることを確認するのが最も堅牢です。

		// 正規表現による判定の試み：
		// この行が「カンマで区切られた整数列」であるためには、
		// 数字とカンマ以外の文字がないこと、かつ、数字が少なくとも1つあることを確認する必要があります。
		// 例: "1,2,3" はOK。 "1,2," はOK。 "abc" はNG。 "" はNG。

		// よりシンプルな判定: 行をカンマで分割し、各要素が整数に変換可能であるかを確認する。
		parts := strings.Split(trimmedLine, ",")
		hasNumber := false
		isValidFormat := true

		for _, part := range parts {
			trimmedPart := strings.TrimSpace(part)
			if trimmedPart == "" {
				// 空の要素（例: ",," や ",1," のカンマ後の空要素）は許容するが、
				// "abc" のような非数字が含まれる場合はNG。
				// 仕様：「1 個以上の数字列がカンマで区切られて並んでいる」
				// 空行はNGだが、カンマ区切りで空要素があっても許容されるかは曖昧。
				// 「数字とカンマ以外を含む行は妥当ではありません」という制約から、数字とカンマ以外の文字が含まれていればNGとする。
				continue
			}

			// 要素が完全に数字のみ（または数字とカンマのみ）であるかを確認する
			// 正規表現を使って、その部分が数字とカンマのみで構成されているかチェック
			// ^\d+(?:,\d+)*$ は、数字の羅列とカンマの組み合わせを意味するが、行全体に対して適用する。

			// 今回は「数字とカンマ以外を含む行は妥当ではない」という制約を最優先する。
			// 許容される文字集合は {数字, カンマ, 空白}。
			// trimSpaceで前後の空白を無視した上で、残った文字列が数字とカンマのみで構成されているか。

			// 行全体が数字とカンマ、空白のみで構成されていることをチェック
			// このチェックは、行全体が形式的に妥当であるかを確認するのに十分です。
			// (行全体の構造チェックに焦点を当てる)

			// 正規表現で「数字とカンマのみ」に絞る
			if !regexp.MustCompile(`^[\d, ]*$`).MatchString(line) {
				isValidFormat = false
				break
			}

			// 数字が少なくとも1つ含まれているかチェック
			if regexp.MustCompile(`\d`).MatchString(line) {
				hasNumber = true
			}
		}

		if isValidFormat && hasNumber {
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
