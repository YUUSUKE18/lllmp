package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// 妥当な行の数を数える
	for scanner.Scan() {
		line := scanner.Text()

		// 末尾の空白を削除
		trimmedLine := strings.TrimSpace(line)

		// 正規表現パターン:
		// ^\s*            - 行の先頭の任意の空白文字
		// [0-9,]+         - 1つ以上の数字
		// (,\s*[0-9,]*)*  - カンマと任意の空白、および数字の繰り返し（カンマ区切りリストを許容するため）
		// \s*$            - 行末の任意の空白文字

		// より厳密に「1個以上の数字がカンマで区切られて並んでいる」ことをチェックするため、
		// 以下のパターンを試みる。
		// 1. 少なくとも1つの数字がある。
		// 2. カンマ区切りであることを確認する。
		// 3. 数字とカンマ以外の文字が含まれていないことを確認する。

		// 正規表現の解説:
		// ^\s*               -> 行の先頭の空白を無視
		// [0-9]+             -> 少なくとも最初の数字が1文字以上ある
		// (?:,\s*[0-9]+)*    -> カンマとそれに続く数字のグループが0回以上繰り返される
		// (?:,)?             -> 最後のカンマ（オプション）
		// \s*$               -> 行末の空白を無視

		// 妥当性の定義を再解釈: 1個以上の数字がカンマで区切られていること。
		// 例: "1,2,3", "1,2,", "1" (これはカンマ区切りリストの特殊なケースだが、仕様に従う)

		// 仕様: 1 個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容。
		// これは、数字とカンマだけで構成され、かつ数字が少なくとも1つ存在することを意味する。

		// パターン: 任意の数の数字とカンマのみで構成されていること。
		// ([0-9]+(?:,\s*[0-9]+)*) は、カンマ区切りのリストを表す
		pattern := `^\s*([0-9]+(?:,\s*[0-9]+)*)\s*$`

		if regexp.MustCompile(pattern).MatchString(line) {
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理が必要な場合は追加するが、ここでは単純に続行する
	}

	fmt.Printf("valid=%d\n", validCount)
}
