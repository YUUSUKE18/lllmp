package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* は行頭の空白を無視
	// .* は任意の文字（数字、カンマなど）
	// [\d,]* は数字とカンマの組み合わせ（数字とカンマが0回以上繰り返される）
	// $ は行末
	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
	// ここでは、行が完全に数字とカンマのみで構成されているか、
	// 少なくとも1つの数字が含まれているかをチェックするアプローチを取る。
	// 仕様：「1 個以上の数字列がカンマで区切られて並んでいる」
	// これは、カンマで区切られていれば、その間に数字が来ることを意味します。
	// 末尾のカンマは許容します。空行は妥当ではない。

	// 判定ロジックを工夫する:
	// 1. 空行判定
	// 2. 数字とカンマ以外が含まれていないか判定
	// 3. 1個以上の数字列があるか判定 (カンマで区切られた後、少なくとも1つの数字が存在するか)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 末尾のカンマは許容されるため、行全体が数字とカンマのみで構成されているかをチェックする
		// 正規表現: ^[\d,]*$ -- 行頭から行末まで、数字(\d)またはカンマ(,)のみで構成されているか
		// この正規表現だけでは、「1個以上の数字列」の条件を満たさない（例: "," や ",,," は許可される可能性がある）
		// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するには、
		// カンマで区切って数字が存在するかを確認する。

		// 数字の塊を抽出して、それが存在するか確認する
		// 複数の数字列が存在する、つまりカンマが存在し、かつ数字が存在するという条件をチェックする。
		// 最小の条件として、「カンマが存在し、かつ数字が1つ以上存在する」と仮定します。

		hasDigit := false
		hasComma := false

		for _, char := range trimmedLine {
			if char >= '0' && char <= '9' {
				hasDigit = true
			} else if char == ',' {
				hasComma = true
			} else {
				// 数字とカンマ以外が含まれている場合、妥当ではない
				hasDigit = false // 既に数字は検出済みか、後のチェックで失敗する
				break
			}
		}

		// 妥当性の判定:
		// 1. 空行でないこと (既にチェック済み)
		// 2. 数字とカンマ以外を含まないこと (ループ内でチェック済み)
		// 3. 1個以上の数字列がカンマで区切られて並んでいること
		//    これは、数字が1つ以上存在し、かつカンマが少なくとも1つ存在する（または、カンマが0個でも数字が1つ以上あればOKという解釈）
		//    「1個以上の数字列がカンマで区切られて並んでいる」という条件を満たすには、
		//    少なくとも1つの数字が存在し、かつ、それがカンマによって区切られている必要がある。
		//    もしカンマが0個（例: "123"）の場合も「1個の数字列が並んでいる」と解釈できれば妥当ですが、「カンマで区切られて」という条件を重視します。

		// ここでは、"1個以上の数字列"がカンマで区切られていること、そして末尾のカンマが許容されることを重視します。
		// 少なくとも1つの数字が含まれていること、かつ、それが数字とカンマのみで構成されていることを確認します。
		if hasDigit && (hasComma || strings.Contains(trimmedLine, string(trimmedLine[len(trimmedLine)-1]))) {
			// 末尾のカンマ許容のため、数字が1つ以上存在し、他の文字が含まれていなければOKとする
			// 厳密に「カンマで区切られている」ことを確認する:
			// 区切り文字（カンマ）が存在し、かつ数字が存在する。
			if hasDigit && hasComma {
				validCount++
			} else if hasDigit && !hasComma {
				// カンマがない場合も「1個以上の数字列が並んでいる」と見なす（区切りがゼロでも）
				validCount++
			}
		} else if hasDigit && !hasComma {
			// カンマがない場合 (例: "123")。これは「1個の数字列が並んでいる」と解釈し、妥当とする。
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
