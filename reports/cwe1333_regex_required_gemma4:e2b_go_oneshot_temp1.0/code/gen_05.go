package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列のパターンを定義します。
	// ^\s* は行の先頭の空白を許容
	// .*? は任意の文字（非貪欲に）
	// (?:[0-9]+(?:\s*,\s*)*)* は1つ以上の数字列と、その後にカンマと空白が0回以上繰り返されるパターン
	// (?:[0-9]+(?:,|$))? は最後の数字列と、カンマまたは行末が続くパターン（末尾カンマも許容するため）
	// より簡潔に、1つ以上の数字とカンマの組み合わせを許容するパターンを目指します。
	// 妥当な行の定義: 1個以上の数字とカンマの組み合わせ（末尾カンマ含む）で構成されている。
	// 例: 1,2,3, または 1,2,3,
	// この正規表現は、数字とカンマのみで構成され、少なくとも1つの数字が含まれることをチェックします。
	// ^\s*             行の先頭の空白
	// [0-9]+           少なくとも1つの数字
	// (?:,\s*[0-9]+)*  カンマと数字の繰り返し（0回以上）
	// (?:,\s*)?        末尾のカンマ（任意）
	// \s*$             行末の空白
	regex := regexp.MustCompile(`^\s*[0-9]+(?:,\s*[0-9]+)*\s*$`)

	for scanner.Scan() {
		line := scanner.Text()

		// 行を正規表現で検証
		if regex.MatchString(line) {
			validCount++
		}
	}

	// 標準出力に結果を出力
	fmt.Printf("valid=%d\n", validCount)
}
