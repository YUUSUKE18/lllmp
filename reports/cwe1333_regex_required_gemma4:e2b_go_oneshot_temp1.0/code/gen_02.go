package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// 正規表現: カンマ区切りの整数列、末尾のカンマも許容する。
	// ^\s* : 行の先頭の空白を許容
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字がカンマ区切りで続くパターン
	// (?:,\s*|\s*$) : カンマと空白、または行末
	// $ : 行末
	// 簡略化のため、行全体がカンマと数字のみで構成されていることを確認する。
	// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// 各要素が数字のみで、カンマで区切られているかをチェックする。

	// 判定ロジックの正規表現：
	// ^\s* : 行頭の任意の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の整数（カンマ区切り）
	// (?:,\s*|\s*$) : 区切り（カンマと空白、または行末）
	// $ : 行末
	// この要件を満たすためには、行が空でないこと、かつカンマと数字以外の文字を含まないことを確認する必要があります。

	// 仕様に基づき、各行が「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
	// 以下の正規表現は、少なくとも一つの数字が含まれ、数字とカンマ、空白のみで構成されている行を検出します。
	// (?:[0-9]+(?:,\s*[0-9]+)*) は、カンマ区切りの整数列を意味します。
	// \s* は、行の先頭・末尾および要素間の空白を考慮します。
	// 末尾のカンマが許容されるため、行が空でないことが前提です。

	validRegex := regexp.MustCompile(`^\s*(?:[0-9]+(?:,\s*[0-9]+)*)(?:,?\s*)*$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := ""
		// 行の前後の空白を無視して内容を評価する
		if len(line) > 0 {
			// 行全体を正規表現でチェック
			if validRegex.MatchString(line) {
				validCount++
			}
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
