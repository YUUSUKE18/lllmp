package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* 表示行の先頭から始まり、
	// .*? (任意の文字が0回以上) を含むが、後続のパターンにマッチさせる（ここではカンマ区切りの数字列に焦点を当てる）
	// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことをチェックするため、
	// 行全体が数字とカンマのみで構成されている、またはそのパターンに一致するかを確認する。

	// 判定ロジック：
	// 1. 行を読み込む。
	// 2. 行が空行でないことを確認する（ただし、末尾の空白は無視する）。
	// 3. 正規表現を使って、カンマで区切られた整数列のパターンにマッチするかをチェックする。
	//    パターン: 任意の数の数字とカンマが混在している、またはカンマで区切られた数字列が存在する。
	//    仕様に基づき、「1個以上の数字列がカンマで区切られて並んでいる」ことを検証する。
	//    例: "1,2,3" や "1,2," のような形式。

	// 行ごとに読み込む
	for scanner.Scan() {
		line := scanner.Text()

		// 行の前後の空白を無視して、主要な内容を抽出（ここでは入力された文字列全体をそのままチェックする）
		trimmedLine := ""
		// 先頭の空白を削除
		for i := 0; i < len(line); i++ {
			if line[i] != ' ' && line[i] != '\t' {
				trimmedLine += string(line[i])
			}
		}

		// 空行の場合はスキップ
		if trimmedLine == "" {
			continue
		}

		// 正規表現パターン:
		// ^             行の先頭から
		// (?:[0-9]+,)*  数字とカンマのペアが0回以上続く (数字の列とカンマの間)
		// [0-9]+        最後の数字の列（末尾のカンマは許容される）
		// $             行の末尾
		// このパターンは、「数字、数字、...」のシーケンスがカンマで区切られていることを示唆する。
		// 末尾のカンマの許容を考慮すると、数字とカンマのみで構成されていることを確認する。
		// 少なくとも1つの数字が存在し、カンマで区切られていることを確認する。

		// より単純に、「数字とカンマ以外」の文字が存在しないかチェックし、数字が存在するかチェックする。
		// 仕様: 「空行、および数字とカンマ以外を含む行は妥当ではありません。」
		// 「1 個以上の数字列がカンマで区切られて並んでいる」
		// 正規表現で検証する。
		// パターン: 任意の文字 (数字、カンマ、空白を含むが、最終的に数字とカンマのみで構成されていることを確認)
		// ここでは、行が数字とカンマ、および空白（先頭/末尾）のみで構成されていることを確認し、
		// 実際にカンマ区切りの数字列が存在するかを確認する。

		// 判定のため、まず行を数字とカンマのみにクリーンアップして、数字が存在するか確認する。
		// ただし、正規表現で「妥当な構造」を判定する。
		// パターン: 1つ以上の数字（カンマで区切られている）
		// ^\s*([0-9,]+(?:\s*[0-9,]+)*)\s*$
		// これは複雑すぎるため、仕様の「カンマ区切りの整数列」に焦点を当てる。
		// 1個以上の数字があり、カンマが区切りとして使われていることをチェック。

		// 妥当な行の判定基準を再解釈:
		// 1. 行が空でないこと。
		// 2. 行が数字とカンマのみで構成されていること（空白は無視）。
		// 3. 1個以上の数字がカンマで区切られていること。

		// 行全体を読み込み、数字とカンマ以外の文字が含まれていないか、そしてカンマが存在するかをチェックする。
		// 空白は無視する。
		
		// 行の内容を再度、空白を除去してチェックする。
		content := ""
		for _, r := range line {
			if r != ' ' && r != '\t' {
				content += string(r)
			}
		}

		if content == "" {
			continue // 空行（または空白のみ）は不適格
		}

		// 正規表現チェック: 少なくとも1つの数字が存在し、それがカンマで区切られている構造を持つか。
		// (?:[0-9]+(?:,|$))* : 1つ以上の数字と、それらがカンマで区切られているパターン。
		// 最後の数字の後にカンマが続くか、行が終わることを許容する。
		// 妥当なパターン: 1つ以上の数字列がカンマで区切られている。
		// 例: "1,2,3" または "1," または ",1" は不適格（数字列が最低1つ必要）

		// 数字列のみで構成されているか、または数字とカンマのみで構成されていることを確認する。
		// 以下の正規表現は、「カンマで区切られた数字の列」が存在することをチェックする。
		// 最小要件: 少なくとも1つの数字とカンマが存在すること。
		// 複数の数字列の例: (数字,){1,}
		// ^.*[0-9]+(?:,.*[0-9]+)*$
		
		// 最も単純に、行が数字とカンマのみで構成されているかを確認し、かつ数字が存在するかを確認する。
		// 妥当な行例: "1,2,3", "1,2,", "1"
		// 不適格な行例: "abc", "1,a", "", "1,,2" (連続カンマなど、厳密な区切りが重要)

		// 数字とカンマのみで構成されているかチェック (空白は無視されている前提)
		isAlphanumericAndComma := true
		for _, char := range content {
			if char != '0' && char != '1' && char != '2' && char != '3' && char != '4' && char != '5' && char != '6' && char != '7' && char != '8' && char != '9' && char != ',' {
				isAlphanumericAndComma = false
				break
			}
		}

		if !isAlphanumericAndComma {
			continue // 数字とカンマ以外を含む行は不適格
		}

		// 数字が存在するかチェック
		hasDigit := false
		for _, char := range content {
			if char >= '0' && char <= '9' {
				hasDigit = true
			}
		}

		if hasDigit {
			// 数字が存在し、数字とカンマのみで構成されている場合、これは妥当とする。
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
