package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列であるかを確認するための正規表現
	// ^\s* - 行の先頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字とカンマのパターン。数字の後にカンマと空白が続くことを許容し、カンマで区切られた複数の数字列を意味する。
	// (?:,\s*|$) - カンマと空白、または行末（末尾のカンマも許容するため、これは後の処理で調整が必要かもしれないが、ここでは基本構造をチェックする）
	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するパターンを考える。
	// 許容される形式: [123,456,789] または [123,456] または [123] または [123,]
	// 正規表現で「カンマ区切りの整数列」を判定する。
	// 1. 数字とカンマのみで構成されていること。
	// 2. 1個以上の数字列が存在すること。
	// 3. 末尾のカンマは許容されること。

	// 行全体を読み込み、各行をチェックする
	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない (1個以上の数字列が必要)
			continue
		}

		// 末尾のカンマを削除してチェックする（末尾のカンマは許容されるため）
		// ただし、行全体が数字とカンマのみで構成されていることを確認する。
		// 正規表現で「数字とカンマのみ」をチェックし、かつ「1つ以上の数字」が含まれていることを確認する。

		// 許容されるパターン: (数字,数字,...) の形式。
		// 1. ^\s* - 行の先頭の空白
		// 2. (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字列と、それに続くカンマと空白の繰り返し。
		// 3. (?:,\s*|$) - 区切り文字または行末。
		// 4. (?:,)?$ - 最後のカンマの有無。

		// 最も簡単なチェックとして、行が数字とカンマのみで構成されていることを確認し、
		// かつ、カンマで区切られた少なくとも一つの数字が存在することを確認する。

		// 後続の処理で正規表現を使う指示があるため、その指示に従う。
		// 正規表現: 1つ以上の数字とカンマのみで構成され、カンマが含まれるか、単一の数字列であること。
		// 末尾のカンマも許容する。
		// 例: "1,2,3", "1,2,", "123"
		// 否定されるケース: "a,b", "1,a"

		// 以下の正規表現は、行が数字、カンマ、空白のみで構成されていることを確認し、
		// 少なくとも一つの数字が含まれていることを間接的に満たすように設計する。
		// 正規表現パターン: ^[\d,]*$ (数字とカンマのみ)
		// このパターンだけでは「1個以上の数字列がカンマで区切られている」ことを保証できないため、
		// 構造をより厳密にチェックする。

		// 構造チェックの正規表現:
		// (?:[0-9]+(?:,\s*[0-9]+)*)  -> 複数の数字列がカンマで区切られている場合
		// |                         -> または
		// [0-9]+                     -> 単一の数字列の場合 (カンマなし)
		// $                          -> 行末
		// 末尾のカンマの許容を考慮し、行全体が数字とカンマのみで構成されていることを確認。
		pattern := `^[\d,]*$`
		match, err := regexp.MatchString(pattern, line)

		if err != nil {
			// 正規表現のコンパイルエラーなど（今回は固定パターンなので通常発生しない）
			continue
		}

		if match {
			// このパターンでは、空行や数字とカンマ以外の文字が含まれていないことを確認する。
			// さらに「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する必要がある。

			// 実際に数字列が存在するかをチェック
			hasNumber := false
			for _, r := range line {
				if r >= '0' && r <= '9' {
					hasNumber = true
				}
			}

			// 数字とカンマのみで構成され、かつ数字が存在すれば妥当とする。
			if hasNumber {
				validCount++
			}
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（今回は省略可能だが慣例として）
	}

	fmt.Printf("valid=%d\n", validCount)
}
