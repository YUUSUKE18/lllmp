package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// 正規表現パターン: カンマで区切られた整数列。
	// 1個以上の数字とカンマの組み合わせを許容し、末尾のカンマも許容する。
	// 具体的には、数字とカンマが交互に現れ、数字が少なくとも1つあることを確認する。
	// 許容されるパターン: 数字, (カンマと数字の繰り返し)
	// 例: "1,2,3", "1,2,"
	// この正規表現は、数字とカンマが連続し、数字が1つ以上含まれることを確認することを試みる。
	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// カンマで区切られた各部分が整数であることを確認する。

	// 1行ごとに処理を行う
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())

		// 1. 空行のチェック
		if line == "" {
			continue
		}

		// 2. 正規表現による妥当性の判定
		// パターン説明:
		// ^                                 # 行の開始
		// (?:                                # 非キャプチャグループ: 繰り返しパターン
		//     \d+                          # 1つ以上の数字
		//     ,?                           # 0個または1個のカンマ
		// )
		// +                                 # 上記グループが1回以上繰り返される
		// (?:,?\d*)                         # 末尾のカンマとオプションの数字（末尾のカンマを許容するため）
		// $                                 # 行の終わり
		//
		// よりシンプルに、カンマ区切りの数字列が少なくとも1つ存在することをチェックする。
		// 1個以上の数字とカンマが混在していることを確認する。
		// 1個以上の数字にカンマが挟まれていれば良い。
		// 例: 1,2,3 または 1,2
		// これは、数字とカンマが交互に出現し、全体が数字で構成されていることを確認する。
		// 妥当な行は、少なくとも1つの数字が存在し、カンマで区切られている行。
		// 末尾のカンマが許容されるため、数字の連続とカンマのパターンを確認する。

		// 妥当な形式: (数字, の繰り返し) か、数字のみ。末尾のカンマは許容。
		// 例: "1,2,3" または "1,2," または "1"
		// 以下の正規表現は、「数字とカンマが交互に現れる」ことを確認する。
		// ^\d+(?:,\d+)*$ : 1個以上の数字で始まり、カンマと数字が交互に続く。
		// 末尾のカンマの許容のため、より緩めに。

		// 妥当な行の定義: 少なくとも1つの数字があり、カンマで区切られている。
		// 末尾のカンマも許容する。
		// 1個以上の数字がカンマで区切られていることを確認する。
		// パターン: (数字とカンマのセット)が1回以上繰り返される。
		// 許容されるケース: "1,2,3", "1,2,", "1" (もし "1" も許容するなら)

		// 課題の仕様を再解釈: "1 個以上の数字列がカンマで区切られて並んでいる"
		// これは、カンマで区切られた要素が整数であることを意味する。
		// 例: "1,2,3" -> 3つの数字列 (1, 2, 3)
		// 末尾のカンマは許容。
		// 数字とカンマのみで構成されている必要がある。

		// 正規表現: ^\d+(?:,\d*)*$
		// ^\d+       : 少なくとも最初の数字が存在する (必須)
		// (?:,\d*)*  : カンマに続く、0個以上の数字 (カンマと数字のセット)
		// $         : 行の終わり
		// これにより、「数字」が最低1つ存在し、その後にカンマと数字の組み合わせが続く、または単に数字のみである、という構造をチェックする。
		// 末尾のカンマは、最後の数字の後ろに存在するカンマとして許容される。

		// もし、単に「数字とカンマのみ」で構成されているかをチェックするなら:
		// ^[\d,]*$
		// このパターンでは、"abc" や "1,,2" も通ってしまうため不十分。

		// 1個以上の数字が存在し、それらがカンマで区切られていることを確認する。
		// 少なくとも1つの数字があり、その間にカンマが許容される。
		// 例: "1" (妥当), "1,2" (妥当), "1," (妥当)
		match, err := regexp.MatchString(`^[\d,]+$`, line)
		if err == nil && match {
			// このパターンは「数字とカンマのみ」を許容するが、「1,2,3」の要素数チェックには不十分。
			// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を正規表現で表現するのは複雑。

			// 妥当性の判定をシンプルに「カンマで区切って空でない文字列が存在するか」に絞る。
			// 行が空でないこと、そして数字とカンマ以外の文字がないことを確認する。
			// また、数字が少なくとも1つ含まれていることを確認する。

			// シンプルなアプローチ: 行をカンマで分割し、空でない要素が1つ以上あるか確認する。
			parts := strings.Split(line, ",")
			isValid := false
			for _, part := range parts {
				trimmedPart := strings.TrimSpace(part)
				if trimmedPart != "" {
					// 各要素が整数であるかチェック
					_, err := fmt.Sscanf(trimmedPart, "%d", &result)
					if err == nil {
						isValid = true
					} else {
						// 数字としてパースできないものは不正
						isValid = false
						break
					}
				}
			}

			if isValid {
				validLines++
			}
		}
	}

	// 処理が終わった後、validLinesを標準出力に出力する
	fmt.Printf("valid=%d\n", validLines)

	if err := scanner.Err(); err != nil {
		// エラー処理が必要であれば追加
	}
}
