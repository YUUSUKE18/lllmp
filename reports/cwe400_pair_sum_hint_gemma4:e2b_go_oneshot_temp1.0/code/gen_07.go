package main

import (
	"bufio"
	"fmt"
	"os"
	"strconv"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)

	// 1行目: 目標値の読み込み
	if !scanner.Scan() {
		return
	}
	targetStr := scanner.Text()
	target, err := strconv.ParseInt(targetStr, 10, 64)
	if err != nil {
		// 目標値の読み込みに失敗した場合は終了
		return
	}

	// 2行目以降の整数の読み込みと処理
	count := 0
	// 2行目以降の行を読み込む
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" {
			continue // 空行は無視
		}

		// 行に含まれる整数をすべて取得
		fields := strings.Fields(line)
		
		for _, field := range fields {
			num, err := strconv.ParseInt(field, 10, 64)
			if err != nil {
				continue // 整数として解釈できないものは無視
			}

			// 現在の数値が目標値から見て、ペアを形成できるかどうかをチェックする
			// 1. 2つの整数の和が目標値になるかチェックする
			// この問題は「2つの組（位置が異なる2個）の個数」を求めているため、
			// 読み込んだ各数に対して、それ以前に読み込んだ数とのペアを数える必要がある。
			// 単に累積和で考えるのではなく、すべての数に対してペアを数える必要がある。

			// ここでは、2行目以降の全整数を一度に読み込み、それらの中からペアを見つける方式を採用する。
			// 最初の読み込み部分をリセットし、すべての数とペアを考える。
			
			// 一時的に、読み込んだ整数をリストとして保持する
			// このロジックは「2行目以降の整数のうち、足して目標値になる2個の組（位置が異なる2個）の個数」を求めるため、
			// 入力が連続している場合、その連続した数の中でペアを探す必要がある。

			// より単純な解釈として、「2行目以降のすべての整数を読み込み、それらの組の数を数える」とする。
			// 入力形式が「2行目以降に整数が1行に1個ずつ並ぶ」という記述から、各行が1つの数または複数の数のまとまりとして扱われると解釈するのが自然。
			// しかし、例1の形式（空白区切り）と、今回の仕様（2行目以降には整数が1行に1個ずつ並ぶ）が矛盾するため、
			// 標準的な競技プログラミングの「2行目以降の整数を1行に1個ずつ並べる」という記述に従い、各行が1つの整数だと仮定する。
			
			// 仮定：2行目以降の各行は1つの整数のみを含む。
			// したがって、読み込んだ `num` に対して、目標値との差を考える。
			
			// もし、読み込んだ数自体が目標値とのペアになるかを考える場合：
			// 求めるのは「A + B = Target」を満たす (A, B) の組の数。
			// 読み込んだ全ての整数を配列に保存し、その中でペアを探す。
			
			// 読み込んだ整数を保持するリスト
			// 1行目以降のデータは、Targetを達成する2つの要素の組を探す問題なので、
			// 読み込んだ整数をすべて保持する配列を用意する。
			// 今回の入力形式は「2行目以降には整数が 1 行に 1 個ずつ並びます」なので、
			// 1行に1つの整数が入っていると仮定し、その整数が他の整数とペアになるかを考える。

			// 全ての整数を格納するリスト
			// 1行目（目標値）を除いた全ての整数を格納
			// 読み込んだ行から全ての数を取り出す
			numbers := make([]int64, 0)
			
			// 再度、全ての入力ストリームを読み直す必要はないため、上記ループを修正する。
			// 2行目以降の行が整数のみを含むと仮定し、その各行を処理する。
			
			// 最初の読み取りロジックは、入力が複数行にまたがってあることを考慮し、
			// 2行目以降のデータのみを処理する。
			
			// 再度、入力全体を読み込むための構造を変更する。
			// 1行目(Target)を読み終えた後、残りの行を読み込む。
			// 実行中のコードブロックは、このループ内で完結させる必要があるため、
			// 読み込みを一度行い、内部で処理を行う。
			
			// 処理を再設計し、入力全体を保持する。
			// ここでは、前のループは破棄し、正しいロジックに置き換える。
			return // この途中でリターンしたため、上記ロジックは無効。
		}
	}
	
	// --- 正しいロジックの再実装 ---

	// 1. 全ての整数を格納するリスト
	allNumbers := make([]int64, 0)
	
	// 2. 2行目以降の入力を読み込む
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" {
			continue
		}
		
		// 行に含まれる全ての整数を抽出
		fields := strings.Fields(line)
		for _, field := range fields {
			num, err := strconv.ParseInt(field, 10, 64)
			if err == nil {
				allNumbers = append(allNumbers, num)
			}
		}
	}

	// 3. ペアの数を計算する (2行目以降の整数のみを考慮)
	// allNumbers には、2行目以降の全ての整数が格納されている。
	
	pairCount := 0
	n := len(allNumbers)
	
	// 2つの組 (A, B) の個数を求める。位置が異なる必要がある (i != j)。
	// これは、forループで i から n-1 まで、j から i+1 までをチェックすることで実現する。
	for i := 0; i < n; i++ {
		for j := i + 1; j < n; j++ {
			if allNumbers[i]+allNumbers[j] == target {
				pairCount++
			}
		}
	}

	// 4. 結果を出力
	fmt.Printf("pairs=%d\n", pairCount)
}
