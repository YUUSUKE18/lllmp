import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 行の前後の空白を無視するため、トリムする
            String trimmedLine = line.trim();

            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 正規表現パターン:
            // ^\s*             -> 行の先頭の空白（任意数）
            // [\d,]*           -> 数字またはカンマが0回以上続く
            // \d               -> 少なくとも1つの数字が続く必要がある
            // .*               -> その他（カンマを含む可能性がある）
            // $                -> 行の終わり
            //
            // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」を判定するため、
            // カンマで区切られた数字のパターンをチェックします。
            // 少なくとも一つの数字と、カンマが使われているパターンが存在するかを確認します。
            // 正規表現の説明:
            // ^\s*               : 行の先頭の空白
            // (?:                 : 非キャプチャグループ
            //   \d+              : 1つ以上の数字
            //   ,?               : 0個または1個のカンマ
            // )+                  : 上記のグループが1回以上繰り返される
            // .*                  : その後に任意の文字（カンマを含む）が続く
            // $                   : 行の終わり

            // 課題の要件を再解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
            // これは、カンマで区切られた要素の中に、少なくとも1つの数字が含まれていることを意味します。
            // 末尾のカンマは許容されます。

            // パターンA: 少なくとも一つの数字が含まれ、カンマが含まれている、または数字の並びがある
            // よりシンプルに、「カンマ区切りの数字列」が最低1つ以上存在するかを判定します。

            // 1. カンマ区切りで数字が存在するかをチェックする
            // パターン: 数字、カンマ、数字、カンマ、... のパターン
            // 数字（\d+）とカンマ（,）が交互に現れることを確認したい。
            
            // 妥当な形式の例: 1,2,3, または 1,2,3,
            // 妥当でない例: abc, または ,1,2
            
            // 妥当な行の判定基準を正規表現で表現する:
            // 少なくとも一つの数字が存在し、カンマが使われている、または数字のみが存在する。
            // 末尾のカンマは許容される。

            // 以下のパターンは、数字とカンマのシーケンスが存在することを大まかにチェックします。
            // (?:[\d,]+) : 数字とカンマの連続
            // この行が「数字とカンマのみ」で構成されているかをチェックする。

            // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を判定するには、
            // カンマで区切られた要素の中に数字が少なくとも1つあることを確認する必要があります。

            // 判定ロジック:
            // 1. 行から末尾のカンマを取り除き、残りの部分が数字とカンマのみで構成されているか確認する。
            // 2. その後に、カンマで区切られた要素の中に数字が含まれているか確認する。

            // 簡略化されたアプローチとして、少なくとも1つの数字が含まれており、カンマや数字が混在している行を妥当と見なします。
            // 「数字とカンマ以外を含む行は妥当ではない」という制約を重視します。

            // パターン: 数字とカンマのみ（数字とカンマ以外の文字は禁止）
            // ^\s*                  : 行頭の空白
            // [\d,]*                : 数字とカンマの任意のシーケンス
            // $                     : 行末
            
            // このパターンだけでは、「1個以上の数字列が区切られている」ことを保証できません（例: ",," はマッチするが数字はない）。
            // したがって、数字が最低1つ含まれていることを追加します。
            
            String regex = "^\\s*[\d,]+\\s*"; // 少なくとも数字とカンマが含まれていることを確認

            if (Pattern.matches(regex, line)) {
                // 末尾のカンマのみの行や、数字が含まれていない行を除外する追加チェックが必要。
                
                // 以下のロジックで、カンマ区切りの数字列の妥当性を判定する。
                boolean isValid = false;
                
                // 1. 行をカンマで分割し、各要素が数字のみか、数字とカンマのみで構成されているか確認する。
                String[] parts = line.split(",");
                
                // 少なくとも1つの要素が存在し、その要素の中に数字が含まれているかチェックする。
                if (parts.length > 0) {
                    for (String part : parts) {
                        String trimmedPart = part.trim();
                        if (trimmedPart.isEmpty()) {
                            // 空の要素は許容される（末尾のカンマなど）
                            continue;
                        }
                        // 各要素が整数またはカンマで構成されているかチェック
                        boolean onlyDigitsAndCommas = true;
                        for (char c : trimmedPart.toCharArray()) {
                            if (!Character.isDigit(c) && c != ',') {
                                onlyDigitsAndCommas = false;
                                break;
                            }
                        }
                        if (onlyDigitsAndCommas) {
                            // この行は、カンマ区切りで数字列が並んでいると見なす
                            isValid = true;
                            break;
                        }
                    }
                }
                
                if (isValid) {
                    validCount++;
                }
            }
        }

        System.out.println("valid=" + validCount);
    }
}
