import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン: 少なくとも1つの数字列とカンマのみで構成され、末尾のカンマも許容する
            // ^\s*           : 行の先頭の空白（無視）
            // [0-9,]*       : 0個以上の数字またはカンマ
            // (?:[0-9],)*   : 1つ以上の (数字, カンマ) の繰り返し
            // [0-9]*$       : 行末の数字の繰り返し
            // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」を判定するため、
            // 少なくとも一つの数字とカンマの組み合わせが含まれていることを確認する。
            
            // 妥当な形式の定義:
            // 1. 少なくとも1つの数字列があること。
            // 2. 数字列の間はカンマで区切られていること。
            // 3. 末尾のカンマは許容されること。

            // パターン解説:
            // ^\s*                : 行頭の空白
            // (?:[0-9]+(?:,?[0-9]+)*) : 1個以上の数字列がカンマで区切られているパターンを試みる。
            // 以下のパターンは複雑になりがちなので、より直接的に「数字とカンマのみ」の制約と「少なくとも1つの数字がある」ことを確認する。

            // 判定ロジック:
            // 1. 行が空でないこと（行全体が空白でないこと）
            // 2. 行に含まれる文字が、数字とカンマのみで構成されていること
            // 3. 少なくとも1つの数字が含まれていること
            
            String trimmedLine = line.trim();
            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 正規表現による厳密なチェック
            // パターン: 1個以上の数字とカンマのみで構成されている。
            // 許容される形式の例: "1,2,3", "1,2,"
            // 否定される形式の例: "abc", "1a2", "1,,2" (カンマが連続する場合など、厳密にはここでは許容しないと解釈する)
            
            // 1個以上の数字と、それらを区切るカンマの組み合わせを許可する正規表現
            // ^\s*              : 行頭の空白
            // (?:[0-9]+(?:,|$)) : 1つの数字列、または数字列の後にカンマまたは行末
            // [0-9]+            : 1つ以上の数字
            // (?:,.*)?          : カンマと任意の文字（末尾のカンマを含む）
            
            // 仕様に基づき、「1個以上の数字列がカンマで区切られて並んでいること」に焦点を当てる。
            // これは、カンマで区切られた数字のシーケンスである必要がある。
            
            // 候補となるパターン: 1つ以上の数字の後にカンマが続く、または数字が連続する。
            // 最もシンプルな解釈として、「数字とカンマのみ」で構成され、少なくとも1つの数字が存在することを要求する。
            
            // 正規表現: 少なくとも1つの数字があり、その間にカンマと数字が混在しているパターン。
            // 例: "1,2" または "1," または ",1" (ただし空行は除外)
            
            // 以下のパターンは、数字とカンマのみで構成され、かつ数字が少なくとも1つ存在することをチェックする。
            // \d+ は1つ以上の数字。
            // (?:,?\d+)* は数字とオプションのカンマの繰り返し。
            // 最終的に、行全体がこの構造に従っているかを確認する。
            String regex = "^\\s*([0-9]+(?:,[0-9]+)*)[0-9,]*$";
            
            // 実際には、末尾のカンマの許容性も考慮しつつ、数字とカンマ以外を含まないことをチェックする。
            // 許容されるのは、数字とカンマのみで構成され、少なくとも1つの数字が含まれている場合。
            
            // より簡単な方法として、行をカンマで分割し、すべてが数字に変換可能かを確認し、数字が1つ以上あるかを確認する。
            // しかし、問題文は「正規表現を用いて」と指定しているため、正規表現での構造チェックを試みる。

            // 構造チェックとして、数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれていることを確認する。
            // このパターンは、カンマで区切られた数字の列を許容し、末尾のカンマも許容する。
            Pattern p = Pattern.compile("^\\s*([0-9][0-9,]*)[0-9]*$");
            Matcher m = p.matcher(line);
            
            // さらに、上記のパターンに加えて、少なくとも1つの数字が実際に存在することを保証する。
            // この問題の制約は非常に曖昧なため、ここでは「数字とカンマのみ」で構成され、数字が少なくとも1つ含まれていることを主眼に置く。

            boolean isValid = false;
            if (!trimmedLine.isEmpty()) {
                // カンマで分割して、要素がすべて数字に変換可能で、少なくとも1つの要素があるかを確認する。
                // これは正規表現の要求に反する可能性があるため、正規表現のみで判断を試みる。
                
                // 最終的な決定として、与えられた例で示された「カンマ区切りの整数列」の構造を厳密に捉える。
                // 少なくとも1つの数字が存在し、それらがカンマで区切られていること。
                
                // パターン：数字とカンマのみで構成され、かつ数字が一つ以上存在する。
                // (\d+(?:,\d+)*) は「1,2,3」のような完全なシーケンス。末尾のカンマも許容する。
                if (trimmedLine.matches("^\\s*\\d+(?:,\\d+)*\\s*(\\,|$)") || trimmedLine.matches("^\\s*\\d+(?:,\\d+)*\\s*$")) {
                     // このパターンは非常に複雑になるため、元の解釈を単純化する。
                     // 求められているのは「カンマ区切りの整数列」という構造であるため、
                     // 「数字とカンマ以外の文字がないこと」と「数字が少なくとも1つあること」を正規表現で表現する。
                     
                     // 許容されるのは、数字とカンマのみで構成され、かつカンマの後に数字が続く（または末尾にカンマがある）場合。
                     // 最も緩い解釈で、数字とカンマのみで構成されているか、かつ数字が存在するか。
                     if (Pattern.compile("^\\s*([0-9,]+)*\\s*$").matcher(line).matches()) {
                          // 数字とカンマのみで構成されている行を妥当とする。
                          // さらに、少なくとも1つの数字が含まれていることを確認する。
                          if (line.matches(".*\\d.*")) {
                              validCount++;
                          }
                     }
                }
            }
            
            // 厳密に正規表現で判定する（行の先頭・末尾の空白は無視されたものとして）
            // 妥当な行は、数字とカンマのみで構成されており、少なくとも1つの数字が含まれているもの。
            // 例: "1,2", "1,2,", "1" など。
            // この条件を満たすことを最優先する。
            if (!trimmedLine.isEmpty()) {
                // 数字とカンマ以外の文字を含まないか？
                if (Pattern.compile("^[0-9,]*$").matcher(trimmedLine).matches()) {
                    // 少なくとも1つの数字が含まれているか？
                    if (Pattern.compile(".*\\d.*").matcher(trimmedLine).matches()) {
                        validCount++;
                    }
                }
            }
        }

        System.out.println("valid=" + validCount);
    }
}
