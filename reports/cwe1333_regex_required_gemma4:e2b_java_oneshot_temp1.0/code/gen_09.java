import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        // 行ごとに読み込む
        String line;
        while ((line = br.readLine()) != null) {
            // 1. 行の前後の空白を無視する（readLine()で読み取った行そのものをチェックする）
            String trimmedLine = line.trim();

            // 2. 正規表現で判定する
            // 判定条件: 1個以上の数字列がカンマで区切られて並んでいる。末尾のカンマは許容。
            // パターン解説:
            // ^             : 行の先頭
            // [0-9]+(?:,[0-9]+)* : 1つ以上の数字で始まり、その後カンマと数字のペアが0回以上続く。
            //                     これにより、「1,2,3」や「1,2,」などを捉える。
            // $             : 行の末尾
            // ただし、末尾のカンマのみを許容する場合、より緩い表現が必要。
            // 「1個以上の数字列がカンマで区切られて並んでいる」を厳密に解釈する。

            // 許容されるパターン:
            // 1. 数字が1つ以上ある。
            // 2. カンマで区切られている。
            // 3. 末尾のカンマは許容される。

            // より直接的に「数字とカンマのみで構成され、少なくとも1つの数字が含まれていること」をチェックする
            // パターン: 数字(1回以上)とカンマが混在していること。
            // 例: "1,2,3" -> OK
            // 例: "1," -> OK
            // 例: "," -> NG (数字がない)
            // 例: "" -> NG (空行)
            // 例: "abc" -> NG (数字とカンマ以外を含む)

            // 正規表現を使用して、行が「数字とカンマ」のみで構成され、少なくとも1つの数字が含まれていることを確認する。
            // この問題の意図を「数字とカンマのみで構成され、カンマで区切られた数字列が存在する」と解釈し、
            // 空行や文字の混入を排除しつつ、カンマ区切りの構造をチェックする。

            // 判定ロジックを再考:
            // 「1個以上の数字列がカンマで区切られて並んでいる」
            // これは、文字列内に数字とカンマのみが含まれ、かつ、数字のシーケンスが存在することを意味する。

            // 少なくとも1つの数字が含まれ、かつ、全体が数字とカンマのみで構成されているか？
            // 以下の正規表現は、数字とカンマのみで構成され、数字が少なくとも1つ含まれることを確認する。
            String regex = "^[0-9,]*([0-9]+(?:,[0-9]+)*)[0-9,]*$";
            // 上記の複雑な表現よりも、単純に「数字とカンマのみ」で構成され、「数字」が少なくとも1つ存在することをチェックし、
            // 空行や文字の混入を排除します。

            // より単純なアプローチ:
            // 1. 行が完全に空でなければならない (トリム後)
            // 2. 行に含まれる文字が数字とカンマのみで構成されていること
            // 3. 少なくとも1つの数字が含まれていること (カンマのみの行はNG)

            boolean isValid = false;

            if (!trimmedLine.isEmpty()) {
                // 1. 数字とカンマ以外を含まないかチェック
                if (Pattern.matches("^[0-9,]*$", trimmedLine)) {
                    // 2. 少なくとも1つの数字が含まれているかチェック
                    if (Pattern.matches(".*[0-9].*", trimmedLine)) {
                        // 3. カンマ区切りの構造を許容するため、最低限のチェックとして数字が存在すればOKとする。
                        // 仕様: 1個以上の数字列がカンマで区切られて並んでいる。
                        // 例: "1" (OK), "1," (OK), "," (NG, 数字がない)

                        // 念のため、カンマのみの行はNG
                        if (!trimmedLine.matches(",.*")) { // カンマのみの行はNG（1個以上の数字列が要求されるため）
                             validLines++;
                             isValid = true;
                        }
                    }
                }
            }

            // 読み込んだ行が空行や不正な行であった場合、validLinesはインクリメントされない。
        }

        // 最終結果を出力
        System.out.println("valid=" + validLines);
    }
}
