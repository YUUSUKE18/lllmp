func countSteps(n int) int {
	if n == 1 {
		return 0
	}
	if memo[n] != nil {
		return memo[n]
	}
	if n%2 == 0 {
		next := n / 2
		steps := 1 + countSteps(next)
	} else {
		next := 3*n + 1
		steps := 1 + countSteps(next)
	}
	memo[n] = steps
	return steps
}

