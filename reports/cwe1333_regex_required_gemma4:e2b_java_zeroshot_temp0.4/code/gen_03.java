import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.IOException;

public class Main {
    public static void main(String[] args) {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;

        // 妥当な行数を数える
        String line;
        while ((line = br.readLine()) != null) {
            // 行の前後の空白を無視する
            String trimmedLine = line.trim();

            // 1. 空行の判定
            if (trimmedLine.isEmpty()) {
                continue;
            }

            // 2. 正規表現による妥当性の判定
            // 妥当なパターン: 1個以上の数字とカンマの組み合わせ。
            // 許容されるのは「1個以上の数字列がカンマで区切られて並んでいること」
            // これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを意味します。
            // パターン: (\d+,\s*)*\d+  => 1つ以上の数字とカンマの繰り返し。
            // より厳密に「カンマ区切りの整数列」を判定するために、
            // 少なくとも1つの数字が含まれ、数字とカンマ以外の文字が含まれていないことを確認します。
            
            // 正規表現の解説:
            // ^                 : 行の開始
            // [0-9,]*           : 数字またはカンマが0回以上続く
            // (?=\d)             : 後続の文字が数字であることを確認 (少なくとも1つの数字が続くことを保証)
            // .*                : その後に任意の文字が続く (末尾のカンマを許容するため)
            // $                 : 行の終了
            
            // 仕様の再解釈: 「1 個以上の数字列がカンマで区切られて並んでいること」
            // 例: "1,2,3" や "1,2," など。
            // 数字とカンマ以外の文字を含まないこと。
            // 少なくとも1つの数字が含まれていること。

            // 数字とカンマのみで構成されているかを確認するパターン
            // ^[0-9,]*$ は、数字とカンマのみで構成されていることを確認するが、空行も含む。
            // 少なくとも1つの数字が含まれていることを確認する。
            
            // 妥当な行の定義: 
            // 1. 数字とカンマのみで構成されている。
            // 2. 少なくとも1つの数字が含まれている。
            
            // パターン: 少なくとも1つの数字が含まれ、数字とカンマ以外の文字を含まない。
            // (?:[0-9,]+) は、数字とカンマの連続を意味する。
            // ^[0-9,]+.*$ は、数字とカンマのみで構成されていることを確認する。
            // 
            // 妥当な行の例: "1,2,3", "1", "1,"
            // 妥当でない行の例: "abc", "1a", "", "1,,2" (カンマの連続は許容されるか？)
            
            // 「1 個以上の数字列がカンマで区切られて並んでいる」という記述を、
            // 表現できるのは「数字とカンマのシーケンス」と解釈します。
            // 
            // 正規表現: 少なくとも1つの数字があり、数字とカンマ以外は存在しない。
            // ^[0-9,]+$ : 数字とカンマのみで構成され、空でない。
            // このパターンは "1,2" はマッチするが、"1,2," はマッチしない。末尾のカンマを許容する必要がある。
            
            // 末尾のカンマを許容するパターン:
            // ^[0-9,]+(\s*,)*$  => これはスペースを許容しないため不適切。
            
            // 妥当な行の定義を「数字とカンマのみで構成され、空でない」と仮定し、末尾のカンマを許容する。
            // 1. 数字とカンマのみで構成されていること。
            // 2. 少なくとも1つの数字が含まれていること。
            // 3. 末尾のカンマは許容されること。
            
            // 妥当なパターン: ^[0-9,]*$ かつ (数字が少なくとも1つ存在する)
            // 末尾のカンマを許容するため、行末にカンマがあっても良い。
            // 例: "1,2" (OK), "1," (OK), "1,2," (OK)
            
            // 妥当な行のパターン: 
            // 少なくとも1つの数字が含まれ、その後にカンマが続くか、行が終わる。
            // 
            // 1. 数字とカンマのみで構成されていることを確認: ^[0-9,]*$
            // 2. 少なくとも1つの数字が含まれていることを確認: (?=.*?\d)
            
            // 最終的な判定ロジック：
            // 1. 行が空でないこと (既にチェック済み)
            // 2. 行が数字とカンマのみで構成されていること。
            // 3. 行内に少なくとも1つの数字が含まれていること。
            
            // 厳密に「1 個以上の数字列がカンマで区切られて並んでいる」を正規表現で表現するのは複雑です。
            // ここでは、行が数字とカンマのみで構成され、空でないことを主要な条件とします。
            
            // 妥当な行の定義を「数字とカンマのみで構成され、空でない」と解釈し、末尾のカンマを許容する。
            // 少なくとも1つの数字が含まれていることを保証する。
            if (Pattern.compile("^[0-9,]+$").matcher(trimmedLine).matches()) {
                // このパターンは末尾のカンマを許容しないため、再調整が必要。
                // 末尾のカンマを許容する場合:
                // ^[0-9,]*$
                // このパターンは空行も許容してしまうため、数字の存在を別途チェックする。
                
                // 妥当な行は、数字とカンマのみで構成され、かつ空でないこと。
                // 少なくとも1つの数字が含まれていることを確認する。
                if (trimmedLine.matches(".*\\d.*")) {
                    validCount++;
                }
            }
        }

        // 結果の出力
        System.out.println("valid=" + validCount);
    }
}
