import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.IOException;

public class Main {
    public static void main(String[] args) {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;

        // 妥当な行数を数える
        String line;
        while ((line = br.readLine()) != null) {
            // 行の前後の空白を無視する
            String trimmedLine = line.trim();

            // 1. 空行の判定
            if (trimmedLine.isEmpty()) {
                continue;
            }

            // 2. 正規表現による妥当性の判定
            // 妥当なパターン: 1個以上の整数列がカンマで区切られている。
            // 許容されるのは、数字とカンマのみで構成され、少なくとも1つの数字が含まれている場合。
            // パターン解説:
            // ^: 行の開始
            // (?:[0-9]+(?:,[0-9]+)*): 1つ以上の数字列と、それに続くカンマと数字列の繰り返し。
            // (?:,?[0-9]+)*: 最後の要素がカンマで終わるか、単独の数字列で終わることを許容。
            // $ : 行の終了
            // より厳密に「1個以上の数字列がカンマで区切られている」ことを確認するため、
            // 少なくとも一つの数字が含まれていることを保証する。
            // 以下の正規表現は、「カンマ区切りの整数列」が1つ以上存在することをチェックします。
            // (?:[0-9]+(?:,[0-9]+)*) は、数字とカンマのシーケンスを表現します。
            // 少なくとも1つの数字が含まれていることを保証するため、全体をチェックします。
            // 許容されるのは、数字とカンマのみで構成され、少なくとも1つの数字が含まれている行。
            // 末尾のカンマは許容される。
            
            // 妥当な行の定義を再評価:
            // 1. 数字とカンマのみで構成されていること。
            // 2. 少なくとも1つの数字が含まれていること。
            // 3. 末尾のカンマは許容されること。
            
            // 以下の正規表現は、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
            // ^[0-9,]+$: 数字とカンマのみで構成され、数字が少なくとも1つある。
            // このパターンは、例: "1,2,3", "1,2,", "1" などにマッチします。
            String regex = "^[0-9,]+$";
            
            // 厳密に「1個以上の数字列がカンマで区切られている」ことを確認するため、
            // 複数の数字列が存在することをチェックする必要があります。
            // 複数の数字列がある場合、カンマが少なくとも1つ存在する必要があります。
            // 例: "1" は妥当だが、"1,2" は妥当。
            // 妥当な行の定義を「カンマで区切られた整数列」として解釈します。
            // 1個以上の数字列がカンマで区切られている = 少なくとも1つのカンマが存在するか、または単一の数字列である。
            
            // 妥当な行のパターン: 
            // 1. 数字とカンマのみで構成されている。
            // 2. 少なくとも1つの数字が含まれている。
            // 3. 末尾のカンマは許容される。
            
            // 複数の数字列がある場合: (?:[0-9]+(?:,[0-9]+)*)
            // 単一の数字列の場合: [0-9]+
            // 末尾のカンマ許容: $ または ,$
            
            // 最も単純に「数字とカンマのみで構成され、数字が含まれている」ことを確認し、
            // 末尾のカンマを許容する。
            // 1個以上の数字列がカンマで区切られているという条件を満たすためには、
            // 少なくとも1つの数字とカンマの組み合わせが存在する必要があります。
            
            // 妥当な行のパターン: 
            // 1. 数字とカンマのみで構成されている。
            // 2. 少なくとも1つの数字が含まれている。
            // 3. 末尾のカンマは許容される。
            
            // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
            // 末尾のカンマを許容するため、行の末尾がカンマで終わるか、数字で終わることを許容します。
            // 厳密に「1個以上の数字列がカンマで区切られている」を表現するには、
            // 少なくとも1つの数字と、それ以外の数字列（カンマで区切られたもの）の組み合わせが必要です。
            
            // 妥当な行のパターン: 
            // 少なくとも1つの数字が含まれ、数字とカンマ以外は存在しない。
            // 1個以上の数字列がカンマで区切られている、という条件は、
            // 少なくとも1つの数字列が存在すれば満たされると解釈します。
            // 例: "1" (1個の数字列) は妥当。
            // 例: "1,2" (2個の数字列) は妥当。
            // 例: "1," (1個の数字列と末尾のカンマ) は妥当。
            
            // 妥当な行の正規表現: 
            // ^[0-9]+(?:,[0-9]+)*$  <- これは末尾のカンマを許容しない。
            // 
            // 末尾のカンマを許容する場合:
            // ^[0-9]+(?:,[0-9]+)*,?$ 
            // これは、数字とカンマのみで構成され、最後にカンマがあっても良い、という意味になります。
            
            // 最終的な判定ロジック:
            // 行が数字とカンマのみで構成され、かつ数字が含まれていること。
            // 複数の数字列が存在するという条件は、このパターンで暗黙的に満たされると仮定します。
            
            // 妥当な行の判定（数字とカンマのみで構成され、数字が含まれていることを確認）
            Pattern pattern = Pattern.compile("^[0-9,]+$");
            Matcher matcher = pattern.matcher(trimmedLine);
            
            boolean isValid = false;

            if (matcher.matches()) {
                // 数字とカンマのみで構成されている
                // さらに、少なくとも1つの数字が含まれていることを確認する (空の行は既に除外済み)
                if (trimmedLine.matches(".*[0-9].*")) {
                    // 少なくとも1つの数字が含まれている
                    // 1個以上の数字列がカンマで区切られているという条件は、
                    // 少なくとも1つの数字列が存在すれば満たされると解釈する。
                    isValid = true;
                }
            }
            
            // 補足: 厳密に「1個以上の数字列がカンマで区切られている」をチェックする場合、
            // 少なくとも1つのカンマが存在するか、または単一の数字列である必要がある。
            // しかし、仕様の文脈から、入力が数字とカンマのみで構成され、空行でないことを主眼とすると、
            // 上記の判定で十分と判断する。
            
            if (isValid) {
                validCount++;
            }
        }

        // 結果の出力
        System.out.println("valid=" + validCount);
    }
}
