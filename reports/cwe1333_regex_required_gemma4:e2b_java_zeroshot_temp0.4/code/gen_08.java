import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.Scanner;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int validCount = 0;

        while (scanner.hasNextLine()) {
            String line = scanner.nextLine();
            
            // 行の前後の空白を無視
            String trimmedLine = line.trim();

            // 妥当性の判定のための正規表現
            // 1. 1個以上の数字列 (\\d+) が存在する
            // 2. カンマ (,) で区切られている
            // 3. 末尾のカンマは許容される (カンマで終わるか、カンマで終わらない)
            // 4. 空行や数字とカンマ以外の文字が含まれない
            
            // 正規表現の解説:
            // ^: 行の開始
            // (?:\\d+(?:,\\d+)*): 1つ以上の数字とカンマの繰り返し (例: 1,2,3 または 1,2,3,)
            // (?=.*\\d): 少なくとも1つの数字が含まれていることを保証するため、実際にはこのパターンで十分
            // $ : 行の終わり
            
            // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことをチェック
            // 少なくとも一つの数字があり、その間にカンマが挟まれている、または数字のみである。
            // 許容されるパターン: 1,2,3, または 1,2,3,
            // 許容されるパターン: 123 (カンマなしも許容されるか？仕様は「カンマ区切りの整数列」なので、カンマ区切りを主眼とする)
            
            // 仕様: 「1 個以上の数字列がカンマで区切られて並んでいることです。末尾のカンマは許容します。」
            // これは、数字とカンマのみで構成され、最低1つの数字が含まれていることを意味します。
            
            // パターン: 1つ以上の数字とカンマの組み合わせ。末尾にカンマがあっても良い。
            // (\\d+(?:,\\d+)*) : 1つ以上の数字とカンマのペアの繰り返し。
            // このパターンは、数字が連続してカンマで区切られていることを要求します。
            
            // 1. 数字とカンマのみで構成されているかを確認する
            // 2. 少なくとも1つの数字が含まれていることを確認する
            
            // 妥当な行のパターン: 1つ以上の数字とカンマの組み合わせ。
            // 例: "1,2,3" または "1,2," または "123" (もし数字のみも許容されるなら)
            // 仕様の文脈から、カンマ区切りが必須と解釈し、数字とカンマ以外は許容しない。
            
            // 1. 数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれていることを確認する
            // ^[0-9,]*$ : 数字とカンマのみ。
            // .*? : 任意の文字（ここでは使わない）
            
            // 妥当な行の定義を正規表現で厳密に表現します。
            // 1. 少なくとも1つの数字が含まれている
            // 2. 数字とカンマ以外は含まれない
            // 3. 末尾のカンマは許容される
            
            // パターン: 1つ以上の数字とカンマのシーケンス。
            // (\\d)(?:,\\d*)* : 最初の数字から始まり、それに続くカンマと数字のシーケンス。
            // または、単に数字とカンマのみで構成されていることを確認する。
            
            // 以下のパターンは、「数字とカンマのみで構成され、少なくとも1つの数字が含まれている」ことをチェックします。
            // (\\d)(?:,\\d*)* : 1つ以上の数字とカンマの組み合わせ。
            // 許容されるケース: "1,2,3", "1,2,", "123" (もしカンマなしも許容されるなら)
            
            // 仕様の「カンマ区切りの整数列」を重視し、カンマ区切りを前提とします。
            // 1つ以上の数字とカンマの組み合わせ。末尾のカンマは許容。
            String regex = "^[0-9,]*$";
            
            // 1. 数字とカンマのみで構成されているかチェック
            if (Pattern.matches(regex, trimmedLine)) {
                // 2. 少なくとも1つの数字が含まれているかチェック (空行やカンマのみの行を除外)
                if (trimmedLine.matches(".*\\d.*")) {
                    validCount++;
                }
            }
        }

        System.out.println("valid=" + validCount);
        scanner.close();
    }
}
