import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.Scanner;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int validCount = 0;

        while (scanner.hasNextLine()) {
            String line = scanner.nextLine();
            
            // 行の前後の空白を無視する（ここではnextLine()で読み取った文字列をそのまま扱う）
            // 判定ロジック
            
            // 1. 空行の判定
            if (line.trim().isEmpty()) {
                continue;
            }

            // 2. 正規表現による妥当性の判定
            // 妥当なパターン: 1個以上の整数がカンマで区切られている。末尾のカンマは許容。
            // パターン解説:
            // ^: 行の開始
            // [0-9]+: 1つ以上の数字（整数）
            // (?:,\s*[0-9]+)*: カンマとそれに続く空白、そして数字の繰り返し（0回以上）
            // (?:,)?$: 末尾にカンマが続く場合（任意）
            // よりシンプルに、数字とカンマのみで構成されていることを確認する。
            // 1個以上の数字とカンマの組み合わせ、または数字のみの組み合わせを許容する。
            
            // 妥当性の定義を再確認:
            // 「1 個以上の数字列がカンマで区切られて並んでいる」
            // 例: "1,2,3", "1,2,", "1" (これは1つの数字列と見なせるか？)
            // 仕様: 「1 個以上の数字列がカンマで区切られて並んでいる」
            // これは、カンマで区切られた要素が少なくとも1つ存在することを意味する。
            
            // 許容されるパターン:
            // 1. 数字とカンマのみで構成されている。
            // 2. 少なくとも1つの数字が含まれている。
            
            // 正規表現の試み: 
            // 数字とカンマのみで構成され、かつ数字が少なくとも1つ含まれていることを確認する。
            // ^[0-9,]*$: 数字とカンマのみで構成されている。
            // ^[0-9]+(?:,[0-9]+)*$: 少なくとも1つの数字がカンマで区切られている。
            
            // 末尾のカンマを許容する場合:
            // ^[0-9]+(?:,[0-9]+)*,?$ 
            // このパターンは、数字が少なくとも1つあり、カンマで区切られているか、または末尾にカンマがあることを許容する。
            
            // より厳密に「カンマ区切り」を考慮し、数字のみの行も許容する。
            // 1. 数字とカンマのみで構成されていること。
            // 2. 少なくとも1つの数字が含まれていること。
            
            // 以下のパターンは、数字とカンマのみで構成され、数字が少なくとも1つ含まれていることを確認します。
            // ^[0-9,]*$: 数字とカンマのみ。
            // ^[0-9]+(?:,[0-9]+)*$: 少なくとも1つの数字がカンマで区切られている。
            // 行が "1" の場合、これは1つの数字列と見なされ、妥当であるべき。
            
            // 仕様: 「1 個以上の数字列がカンマで区切られて並んでいる」
            // これは、カンマで区切られた要素が1つ以上あることを意味する。
            // "1" は1つの数字列のみ。カンマ区切りではないが、1つの数字列として妥当か？
            // 「カンマで区切られて並んでいる」という条件を満たすためには、少なくとも1つのカンマが必要、または数字のみで構成されていても許容される必要がある。
            
            // 妥当な行の例を想定: "1,2", "1,2,"
            // 妥当でない行の例を想定: "", "abc", "1,a", "1,,2"
            
            // 妥当な行のパターン: 
            // 少なくとも1つの数字が含まれ、その中にカンマが含まれるか、カンマで区切られている。
            // 1つの数字列のみ (例: "1") も許容されると解釈する。
            // したがって、数字とカンマのみで構成され、かつ数字が少なくとも1つ含まれていれば良い。
            
            // 最終的な正規表現: 
            // 1. 数字とカンマのみで構成されている。
            // 2. 少なくとも1つの数字が含まれている。
            String regex = "^[0-9,]+$";
            
            // この正規表現は、行全体が数字とカンマのみで構成されていることを確認します。
            // 念のため、行が空でないことを確認済みなので、このパターンにマッチすれば妥当とします。
            if (Pattern.matches(regex, line.trim())) {
                validCount++;
            }
        }

        System.out.println("valid=" + validCount);
        scanner.close();
    }
}
