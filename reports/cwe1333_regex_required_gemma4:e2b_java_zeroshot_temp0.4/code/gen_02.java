import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.IOException;

public class Main {
    public static void main(String[] args) {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;

        // 妥当な行の数を数える
        String line;
        while ((line = br.readLine()) != null) {
            // 行の前後の空白を無視する
            String trimmedLine = line.trim();

            // 1. 空行の判定
            if (trimmedLine.isEmpty()) {
                continue;
            }

            // 2. 正規表現による妥当性の判定
            // 妥当なパターン: 1個以上の数字とカンマの組み合わせ。
            // 許容されるのは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていること。
            // パターン解説:
            // ^: 行の開始
            // [0-9,]*: 0個以上の数字またはカンマ
            // (?=\d): 後読み (Positive Lookahead)。少なくとも1つの数字が続くことを要求する。
            // [0-9,]+: 1つ以上の数字またはカンマ（ここでは、少なくとも1つの数字が存在することを保証するため、より厳密にチェックする）
            // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックするため、
            // カンマ区切りの数字列のパターンを検討します。
            
            // 妥当な行の定義: 1個以上の数字列がカンマで区切られている。
            // 例: "1,2,3", "1,2,", "1"
            // 数字とカンマのみで構成され、数字が少なくとも1つ含まれている。
            
            // パターン: 1つ以上の数字とカンマのシーケンスで構成されていること。
            // 少なくとも1つの数字が含まれていることを確認するために、数字が少なくとも1つあることを要求します。
            // \d+ は1つ以上の数字。カンマは区切り文字として許容されます。
            // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
            // ^[0-9,]+$: 数字とカンマのみで構成され、行全体がそれに一致する。
            // ただし、仕様は「1個以上の数字列がカンマで区切られて並んでいる」なので、カンマ区切りを重視します。

            // 妥当な行のパターン: 1つ以上の数字とカンマが混在している。
            // 最小の妥当な例: "1" (1つの数字列) または "1,2" (2つの数字列)
            // 末尾のカンマは許容される。
            
            // 正規表現の再考:
            // 1. 数字とカンマのみで構成されていること。
            // 2. 少なくとも1つの数字が含まれていること。
            // 3. 空白は無視されるため、trim後の文字列に対して適用する。
            
            // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
            // ^[0-9,]+$: これは、数字とカンマのみで構成され、行全体がそれに一致することを意味します。
            // このパターンは、"1,2" や "1," や "1" はマッチしますが、"a,1" はマッチしません。
            String regex = "^[0-9,]+$";
            
            if (Pattern.matches(regex, trimmedLine)) {
                validLines++;
            }
        }

        // 結果の出力
        System.out.println("valid=" + validLines);
    }
}
