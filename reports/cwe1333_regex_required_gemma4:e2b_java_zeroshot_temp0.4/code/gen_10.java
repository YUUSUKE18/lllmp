import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.IOException;

public class Main {
    public static void main(String[] args) {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;

        // 妥当な行数を数える
        String line;
        while ((line = br.readLine()) != null) {
            // 行の前後の空白を無視する
            String trimmedLine = line.trim();

            // 1. 空行の判定
            if (trimmedLine.isEmpty()) {
                continue;
            }

            // 2. 正規表現による妥当性の判定
            // 妥当なパターン: 1個以上の数字とカンマの組み合わせ。
            // 許容されるのは「1個以上の数字列がカンマで区切られて並んでいること」
            // これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを意味します。
            // パターン: (数字とカンマの繰り返し) または (数字が1つ以上連続)
            // より厳密に「カンマ区切りの整数列」をチェックします。
            // 許容されるのは、数字とカンマのみで構成され、少なくとも1つの数字が含まれている行。
            // 末尾のカンマは許容される。
            // 例: "1,2,3", "1,2,", "1"
            // 数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
            
            // 正規表現の解説:
            // ^: 行の先頭
            // [0-9,]*: 0個以上の数字またはカンマ
            // (?=\d): 後読みで数字が続くことを要求 (少なくとも1つの数字が含まれていることを保証するため)
            // .*$: 行の終わり
            // このパターンは、数字とカンマのみで構成され、数字が少なくとも1つ含まれていることを確認します。
            // ただし、仕様は「1個以上の数字列がカンマで区切られて並んでいること」なので、
            // 実際にはカンマで区切られた数字の並び、または単一の数字列が許容されると解釈します。
            
            // 妥当な行の定義を再評価:
            // 1. 1個以上の数字列がカンマで区切られている。
            // 2. 末尾のカンマは許容される。
            // 3. 数字とカンマ以外を含む行は不適。
            
            // この条件を満たすのは、行が数字とカンマのみで構成され、かつ数字が少なくとも1つ含まれている場合です。
            // 例: "1,2,3" (OK), "1,2," (OK), "1" (OK)
            // 例: "abc" (NG), "1,a" (NG)
            
            // 数字とカンマのみで構成されていることを確認
            if (!trimmedLine.matches("[0-9,]*")) {
                continue; // 数字とカンマ以外を含む行は不適
            }

            // 少なくとも1つの数字が含まれていることを確認
            if (!trimmedLine.matches(".*\\d.*")) {
                continue; // 数字が含まれていない行は不適 (例: "," や ",," など)
            }

            // 1個以上の数字列がカンマで区切られている、または単一の数字列であること
            // この条件は、上記2つの条件が満たされれば、実質的に「カンマ区切りの整数列」の形式を満たしていると見なします。
            // 厳密に「カンマで区切られている」ことを確認するために、カンマの存在を考慮します。
            
            // 最終的な判定ロジックとして、行が数字とカンマのみで構成され、かつ数字が含まれていることを採用します。
            validCount++;
        }

        // 結果の出力
        System.out.println("valid=" + validCount);
    }
}
