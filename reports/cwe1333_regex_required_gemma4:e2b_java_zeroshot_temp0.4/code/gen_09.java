import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws IOException {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;

        // 妥当な行数をカウントする
        String line;
        while ((line = br.readLine()) != null) {
            // 行の前後の空白を無視する
            String trimmedLine = line.trim();

            // 1. 空行の判定
            if (trimmedLine.isEmpty()) {
                continue;
            }

            // 2. 正規表現による妥当性の判定
            // 妥当なパターン: 1個以上の数字とカンマの組み合わせ。
            // 許容されるのは「1個以上の数字列がカンマで区切られて並んでいること」
            // これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれている必要がある。
            // パターン解説:
            // ^: 行の開始
            // [0-9,]*: 数字またはカンマが0回以上続く (これは数字とカンマ以外を含む行を排除するのに役立つが、完全なチェックには不十分)
            // より厳密に「カンマ区切りの整数列」をチェックする。
            // 妥当な行は「1個以上の数字列がカンマで区切られている」こと。
            // 例: "1,2,3" または "1,2,"
            // 数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
            
            // 妥当な行の定義を正規表現で表現する:
            // 1. 少なくとも1つの数字が含まれていること。
            // 2. 数字とカンマ以外の文字が含まれていないこと。
            // 3. カンマで区切られていること（または末尾にカンマがあっても良い）。
            
            // 許容されるパターン: 1個以上の数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
            // (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字がカンマで区切られているパターン
            // ^[0-9]+(?:,[0-9]+)*$ : 厳密に数字とカンマのみで構成され、数字で始まる/終わることを確認する。
            // ただし、末尾のカンマも許容されるため、末尾のカンマの有無を考慮する必要がある。

            // 仕様に基づき、行全体が「カンマ区切りの整数列」であるか、またはそれに準ずるかを判定する。
            // 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」こと。
            // これは、数字とカンマのみで構成され、数字が少なくとも1つ含まれていることを意味する。
            
            // 正規表現: 少なくとも1つの数字が含まれ、数字とカンマ以外を含まない。
            // (?:[0-9](?:,[0-9])*): 1つの数字で始まり、カンマと数字が続くパターン (例: 1,2,3)
            // |
            // [0-9]+(?:,)? : 1つの数字が続くパターン (例: 1) または 1つの数字とカンマ (例: 1,)
            // 
            // 簡略化して、数字とカンマのみで構成され、数字が少なくとも1つあることを確認する。
            // 許容されるのは、カンマで区切られた整数列。
            // 例: "1,2,3" -> OK
            // 例: "1," -> OK
            // 例: "123" -> OK (カンマ区切りではないが、1個の数字列と見なせるか？仕様は「カンマで区切られて並んでいる」)
            // 
            // 「1 個以上の数字列がカンマで区切られて並んでいる」
            // これは、カンマが少なくとも1つ含まれているか、または数字がカンマで区切られていることを意味する。
            
            // 妥当なパターンを定義: 
            // 1. 数字とカンマのみで構成されていること。
            // 2. 少なくとも1つの数字が含まれていること。
            // 3. カンマの有無に関わらず、数字列がカンマで区切られている構造を持つこと。
            
            // 以下のパターンは、数字とカンマのみで構成され、数字が少なくとも1つ含まれていることを確認する。
            // (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字がカンマで区切られているパターン (例: 1,2,3)
            // |
            // [0-9]+(?:,)? : 1つの数字が続くパターン (例: 1, または 1)
            
            // よりシンプルに、数字とカンマのみで構成され、数字が1つ以上あることを確認する。
            // 許容されるのは、数字とカンマのみで構成され、空行でないこと。
            // 末尾のカンマは許容されるため、行の末尾がカンマで終わるか、数字で終わることを許容する。
            
            // 妥当な行のパターン: 
            // ^[0-9,]*$ : 数字とカンマのみで構成されていること。
            // このパターンだけでは、"abc" や "," は通ってしまうため、数字の存在をチェックする必要がある。
            
            // 最終的な判定ロジック:
            // 1. 行が数字とカンマのみで構成されているか？ (数字とカンマ以外を含まない)
            // 2. 行に少なくとも1つの数字が含まれているか？
            
            // 1. 数字とカンマのみで構成されているか
            if (!Pattern.matches("^[0-9,]*$", trimmedLine)) {
                continue; // 数字とカンマ以外を含む行は不妥当
            }

            // 2. 少なくとも1つの数字が含まれているか
            boolean containsDigit = false;
            for (char c : trimmedLine.toCharArray()) {
                if (Character.isDigit(c)) {
                    containsDigit = true;
                    break;
                }
            }

            if (containsDigit) {
                // 数字とカンマのみで構成され、数字が含まれているため、妥当と見なす。
                validCount++;
            }
        }

        // 結果の出力
        System.out.println("valid=" + validCount);
    }
}
