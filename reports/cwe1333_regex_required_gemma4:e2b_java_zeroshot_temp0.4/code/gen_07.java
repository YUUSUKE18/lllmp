import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.IOException;

public class Main {
    public static void main(String[] args) {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;

        while (true) {
            String line;
            try {
                line = br.readLine();
            } catch (IOException e) {
                break; // エラーまたはEOF
            }

            // 行の前後の空白を無視
            String trimmedLine = line.trim();

            // 空行は妥当ではない
            if (trimmedLine.isEmpty()) {
                continue;
            }

            // 正規表現パターン:
            // ^: 行の開始
            // [0-9,]+: 1つ以上の数字またはカンマ
            // (?:,\d+)*: カンマとそれに続く数字の繰り返し（カンマ区切りの数字列）
            // $: 行の終了
            // このパターンは、カンマ区切りの整数列が1つ以上存在することをチェックするために、
            // 少なくとも一つの数字とカンマが混在していることを確認する必要があります。

            // 仕様の再解釈: 「1 個以上の数字列がカンマで区切られて並んでいること」
            // これは、数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれていることを意味します。
            // 末尾のカンマは許容されます。

            // パターンA: 少なくとも1つの数字が含まれ、数字とカンマのみで構成されている行
            // ^[0-9,]+$: これは、数字とカンマのみで構成されていることを確認します。
            // さらに、少なくとも1つの数字が含まれていることを確認する必要があります。

            // パターンB: 妥当な行の判定
            // 1. 数字とカンマのみで構成されていること: [0-9,]*
            // 2. 少なくとも1つの数字が含まれていること: 少なくとも1つの '0-9' が存在する。
            // 3. 末尾のカンマは許容される。

            // よりシンプルに、行全体が「数字とカンマ」で構成されており、かつ「数字」が含まれているかをチェックします。
            // 妥当な行は、カンマで区切られた整数列が1個以上存在すること。

            // 妥当な行の定義を正規表現で表現します。
            // 1. 少なくとも1つの数字が含まれていること。
            // 2. 数字とカンマ以外の文字を含まないこと。
            // 3. 末尾のカンマは許容される。

            // 妥当な行の例: "1,2,3", "100,"
            // 不妥当な行の例: "", "abc", "1,a", "1,,2" (これは「1個以上の数字列」の定義に依存するが、ここではカンマ区切りの整数列として解釈)

            // 「1 個以上の数字列がカンマで区切られて並んでいる」
            // これは、カンマで区切られた要素が1つ以上存在することを意味します。
            // 例: "1" (1要素), "1,2" (2要素), "1," (1要素, 末尾カンマ許容)

            // 正規表現: ^[0-9]+(?:,[0-9]+)*$
            // これは、数字がカンマで区切られており、カンマの後に数字が続く、という構造をチェックします。
            // ただし、末尾のカンマを許容する必要があります。

            // 妥当な行のパターン（数字とカンマのみで構成され、少なくとも1つの数字が含まれている）
            // 1. 数字とカンマのみで構成されている: ^[0-9,]*$
            // 2. 少なくとも1つの数字が含まれている: 少なくとも1つの '0-9' が存在する。

            // 妥当な行の判定ロジックを正規表現で実現します。
            // 妥当な行は、数字とカンマのみで構成され、かつ、少なくとも1つの数字が含まれている。
            // 末尾のカンマは許容される。

            // パターン: 少なくとも1つの数字が含まれ、数字とカンマのみで構成されている。
            // (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字列がカンマで区切られている部分
            // (?:,|$) : 最後の要素がカンマまたは行末であること
            // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を表現するには、
            // 少なくとも1つの数字が含まれていることを確認します。

            // 妥当な行のパターン: 少なくとも1つの数字が含まれ、数字とカンマのみで構成されている。
            // 例: "1", "1,2", "1,2,"
            String regex = "^[0-9]+(?:,[0-9]+)*$";
            
            // 末尾のカンマを許容する場合の調整:
            // 1. 数字とカンマのみで構成されていること。
            // 2. 少なくとも1つの数字が含まれていること。
            // 3. 末尾がカンマで終わることも許容される。

            // 妥当な行のパターンを再定義:
            // ^[0-9]+(?:,[0-9]+)*$ : 1,2,3 のような形式。末尾にカンマは許容しない。
            // ^[0-9]+(?:,[0-9]+)*,?$ : 末尾にカンマを許容する。
            
            // 妥当な行の判定（数字とカンマのみで構成され、少なくとも1つの数字が含まれている）
            // 1. 行全体が数字とカンマのみで構成されていること: ^[0-9,]*$
            // 2. 少なくとも1つの数字が含まれていること: 少なくとも1つの数字が存在する。

            boolean isValid = false;
            if (!trimmedLine.isEmpty()) {
                // 数字とカンマのみで構成されているかチェック
                if (trimmedLine.matches("[0-9,]*")) {
                    // 少なくとも1つの数字が含まれているかチェック
                    if (trimmedLine.matches(".*[0-9].*")) {
                        // 妥当な行としてカウント
                        validCount++;
                    }
                }
            }
        }

        System.out.println("valid=" + validCount);
    }
}
