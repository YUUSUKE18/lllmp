import java.util.Scanner;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int validCount = 0;

        while (scanner.hasNextLine()) {
            String line = scanner.nextLine();
            
            // 行の前後の空白を無視する（ここではnextLine()で読み込んだ文字列をそのまま扱う）
            // 正規表現で判定する
            // 妥当なパターン: 1個以上の数字とカンマの組み合わせ。末尾のカンマは許容。
            // ^\s* : 行の先頭の空白
            // (?:[0-9]+(?:,[0-9]+)*) : 1個以上の数字とカンマの繰り返し。数字のみで構成される。
            // (?:,|$) : カンマまたは行末
            // この仕様では「1個以上の数字列がカンマで区切られて並んでいる」ことを判定する必要がある。
            // 例: "1,2,3", "1,2,", "1" (これは1個の数字列と見なせるか？)
            
            // 仕様の解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
            // これは、カンマで区切られた数字のシーケンス全体が、少なくとも1つの数字を含むことを意味すると解釈する。
            // 空行や数字とカンマ以外の文字を含む行はNG。
            // 妥当なパターン: 1つ以上の数字とカンマのみで構成されている。
            // 数字とカンマ以外の文字が含まれていないことを確認する。
            
            // 正規表現の設計:
            // ^\s* : 行頭の空白
            // (?:[0-9][0-9,]*[0-9]) : 少なくとも2つの数字がカンマで区切られているパターン (例: 1,2)
            // |
            // [0-9]+(?:,.*)? : 1つの数字列（末尾のカンマは許容）
            // $ : 行末
            
            // よりシンプルに、数字とカンマ以外の文字が含まれていないことを確認し、少なくとも1つの数字が含まれていることを確認する。
            
            // 1. 数字とカンマのみで構成されているか？
            // 2. 少なくとも1つの数字が含まれているか？
            
            // 妥当な行の例: "1,2,3", "1,2,", "1" (1個の数字列)
            // 不妥当な行の例: "", "abc", "1a"
            
            // 数字とカンマのみで構成されていることを確認するパターン:
            // ^\s*[\d,]*\s*$  <- これは空行や空白行も許してしまうため不十分。
            
            // 妥当な行の定義を厳密に適用する:
            // 1. 空行は妥当ではない。
            // 2. 数字とカンマ以外を含む行は妥当ではない。
            // 3. 1個以上の数字列がカンマで区切られて並んでいること。
            
            // 妥当な行は、数字とカンマのみで構成され、かつ数字が含まれている行。
            // 数字とカンマのみで構成されていることを確認する正規表現:
            // ^\s*[\d,]*\s*$
            
            // このパターンに加えて、数字が少なくとも1つ含まれていることを確認する。
            
            // 判定ロジック:
            // 1. 行をトリムして、空白行でないことを確認する。
            String trimmedLine = line.trim();
            if (trimmedLine.isEmpty()) {
                continue; // 空行は妥当ではない
            }

            // 2. 数字とカンマ以外が含まれていないか確認する。
            // 数字とカンマのみで構成されているか？
            // パターン: 1文字以上、数字またはカンマのみ。
            if (!Pattern.matches("^[\d,]+$", trimmedLine)) {
                continue; // 数字とカンマ以外の文字が含まれている場合は不妥当
            }

            // 3. 1個以上の数字列がカンマで区切られているか？
            // これは、行が数字とカンマのみで構成されていれば、自動的に満たされるか？
            // 例: "abc" -> NG (上記2で除外)
            // 例: "1,2" -> OK
            // 例: "1" -> OK
            // 例: "," -> NG (数字が1個以上必要)
            // 例: "1,,2" -> NG (連続するカンマは許容されないと解釈)
            
            // 連続するカンマや、数字以外の文字が含まれていないことを確認する。
            // 妥当なパターンを再定義: 1個以上の数字と、それらを区切るカンマ。
            // (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ。
            // このパターンは、"1,2,3" や "1" はマッチするが、"1,,2" はマッチしない。
            
            // 妥当な行の判定に特化した正規表現:
            // ^\s*([0-9]+(?:,[0-9]+)*)(?:,)?\s*$
            // これは複雑すぎるため、仕様を再解釈し、最も厳しい制約を適用する。
            
            // 仕様: 妥当とは、1 個以上の数字列がカンマで区切られて並んでいること。
            // これは、カンマで区切られた要素がすべて数字である、ということを意味する。
            
            // 最終的な判定ロジック（正規表現を使用）:
            // 1. 行が空でないこと。
            // 2. 行が数字とカンマのみで構成されていること。
            // 3. 行内に少なくとも1つの数字が含まれていること。
            
            // 1. 数字とカンマのみで構成されているか？
            if (!Pattern.matches("^[\d,]+$", trimmedLine)) {
                continue;
            }
            
            // 2. 少なくとも1つの数字が含まれているか？
            if (!Pattern.matches(".*\\d.*", trimmedLine)) {
                // 数字が含まれていない場合 (例: "," や ",," など)
                continue;
            }
            
            // 3. 連続するカンマのチェック (例: "1,,2" はNGと仮定)
            // 連続するカンマは許容しないという暗黙の制約を適用する。
            if (trimmedLine.contains(",,")) {
                continue;
            }
            
            // 上記の3つの条件を満たせば妥当とする。
            validCount++;
        }

        System.out.println("valid=" + validCount);
        scanner.close();
    }
}
