import java.util.Scanner;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int validCount = 0;
        
        while (scanner.hasNextLine()) {
            String line = scanner.nextLine();
            
            // 前後の空白を除去
            String trimmedLine = line.trim();
            
            if (trimmedLine.isEmpty()) {
                continue; // 空行は妥当ではないと指定されているが、処理ロジックで除外するか？
                         // 仕様: "空行...は妥当ではありません" -> validCount に含めない
                // ただし、正規表現のチェックで除外されるか確認が必要。
                // 空文字列は数字とカンマ以外を含む（何も含まない）ので、正規表現で外すのが安全。
            }
            
            // 正規表現: 空白を許容しつつ、1 個以上の整数列がカンマで区切られていること
            // ^[\s]*((?:-?\d+)(?:,\s*-?\d+)*)$ 
            // 説明:
            // ^ : 行の始まり
            // [\s]* : 開始前の空白（許容）
            // ( ... ) : 1 組以上のグループ
            //   -??: 符号付き整数 (- なし)
            //   \d+ : 数字 1 個以上
            //   (?:,\s*-?\d+)* : カンマと空白（許容）と符号付き整数の繰り返し（0 回以上、但至少 1 回必要なのでグループ外で確保）
            // $ : 行の終わり
            
            // より厳密に: "1 個以上の数字列がカンマで区切られて並んでいる"
            // 末尾のカンマは許容。
            // 例: "1,2", "1,", "1,2,", ""(空) -> 空はダメ
            // 例: "a" -> ダメ
            
            // 正規表現の再考:
            // 空白を先頭と末尾に許容し、中身が [0-9]+(-?[0-9]*)*(?:,[0-9]*(-?[0-9]*)*)* のような形
            // 最もシンプルで堅牢なアプローチ:
            // ^[\s]*((?:-?\d+)(?:,\s*-?\d+)*)$
            // このパターンは "1," をマッチするが、"1,2," はマッチしない（最後のカンマ後の数字がないため）。
            // 仕様: "末尾のカンマは許容します" -> "1,2," が OK。
            // なので、正規表現を修正: ^[\s]*((?:-?\d+)(?:,\s*-?\d+)*)[,]?[\s]*$ ? 
            // いや、もっと単純に: 文字列が空でないこと + 数字とカンマ以外が含まれていないこと + 構造が正しいこと。
            
            // 指定された条件を正規表現で網羅:
            // 1. 空白のみ（空行含む）はダメ。
            // 2. 数字とカンマ以外の文字はダメ。
            // 3. 少なくとも 1 つの整数列があること。
            // 4. カンマで区切られていること（末尾のカンマ OK）。
            
            // 正しい正規表現の提案:
            // ^[\s]*((?:-?\d+)(?:,\s*-?\d+)*)[,]?[\s]*$ 
            // これは "1,2," をマッチするが、"1" もマッチする。
            // しかし、"1,2abc" はマッチしない。
            // " 1 , 2 " (空白が多い) -> マッチ可能か？ [\s]* で先頭を処理し、中身を処理し、末尾の空白も許容すれば OK。
            
            // 最終的な正規表現: ^[\s]*((?:-?\d+)(?:,\s*-?\d+)*)[,]?[\s]*$
            // この式は:
            // - 先頭空白を許容
            // - 少なくとも 1 つの整数列 ((?:-?\d+)...) を要求
            // - その後にオプションのカンマ ([,]?) を許容（末尾カンマの場合）
            // - 末尾空白を許容
            // - 数字とカンマ以外が含まれる場合は、上記のパターンに一致しないため除外される。
            
            if (trimmedLine.matches("^\\s*((?:-?\\d+)(?:,\\s*-?\\d+)*)[,]?\\s*$")) {
                validCount++;
            }
        }
        
        System.out.println("valid=" + validCount);
    }
}
