package main

import (
	"bufio"
	"fmt"
	"os"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	var total int64 = 0

	// メモ化のためのマップ
	memo := make(map[int]int64)

	for scanner.Scan() {
		line := scanner.Text()
		if line == "" {
			continue
		}

		var n int
		_, err := fmt.Sscanf(line, "%d", &n)
		if err != nil {
			continue // 整数として解釈できない行は無視
		}

		if n == 1 {
			// nが1のときの手数は0
			memo[1] = 0
		} else if _, ok := memo[n]; !ok {
			// 計算が必要な場合、再帰または動的計画法で計算
			// ここでは、nが1に到達するまでの手数を求めるため、再帰的に計算し、メモ化する
			// ただし、問題の操作は「nが偶数ならn/2、奇数なら3n+1」であり、これはコラッツ予想の操作に似ている。
			// 求めるのは1に到達するまでの手数。
			// 操作を逆算して、1に到達するまでのステップ数を求める。
			
			// ここで要求されているのは、nから1に到達するまでのステップ数（操作の回数）
			// nを1に到達するまでのステップ数を求めるため、通常のコラッツ操作とは逆の操作を考えるか、
			// または、与えられた操作を適用し続ける。
			
			// 問題の指示: nが偶数なら n/2、奇数なら 3n+1 に置き換える操作を繰り返し、1 に到達するまでの手数を求める。
			// これは、標準的なコラッツ数問題の「n -> 3n+1 または n -> n/2」の操作で1に到達するまでのステップ数を問うている。
			// ただし、与えられた操作は「nが偶数なら n/2、奇数なら 3n+1」であり、これはコラッツの操作とは少し異なります（コラッツはnが3n+1で次のステップに進む）。
			
			// 与えられた操作に従って、nから1に到達するまでのステップ数を計算する。
			
			currentN := n
			steps := 0
			path := []int{n} // 経路を記録してメモ化に利用

			for currentN != 1 {
				if currentN == 0 {
					// 0に到達した場合は無限ループまたは終了条件の判断が必要だが、
					// ここでは「1に到達する」ことを前提とする。
					// 0からは操作が定義されていないため、ここでは無視するか、エラーとするが、
					// 一般的にこの問題では1に到達することが保証される（コラッツ数）。
					break
				}

				if currentN%2 == 0 {
					currentN /= 2
				} else {
					currentN = 3*currentN + 1
				}
				steps++
				path = append(path, currentN)
			}
			
			if currentN == 1 {
				memo[n] = int64(steps)
				// 経路上のすべての数についてもメモ化しておくと、より効率的になるが、
				// 今回は「nから1への手数」のみを求められているため、nのみをメモ化する。
			}
		}
	}

	// すべてのクエリの結果を合計する
	// 注: 最初の読み取りループで、各クエリ n について計算を実行し、その結果を合計する必要がある。
	// 上記のロジックでは、各行が独立したクエリとして扱われ、計算結果が直接合計される形になっていないため、
	// 再度、入力処理を修正し、各行に対して計算を実行する。
	
	// --- 修正された処理 ---
	
	// 再度、全クエリを処理し、その結果を合計する
	scanner = bufio.NewScanner(os.Stdin) // 再度標準入力から読み込む
	
	// メモ化マップを初期化（再計算のために）
	memo = make(map[int]int64)
	total = 0

	for scanner.Scan() {
		line := scanner.Text()
		if line == "" {
			continue
		}

		var n int
		_, err := fmt.Sscanf(line, "%d", &n)
		if err != nil {
			continue
		}

		if n == 1 {
			// n=1 の場合の手数は 0
			total += 0
			memo[1] = 0
			continue
		}

		// メモ化された値があればそれを使用
		if result, ok := memo[n]; ok {
			total += result
			continue
		}

		// 計算が必要な場合
		currentN := n
		steps := 0
		
		// 経路を記録して、中間値のメモ化も行う (DP/メモ化の完全な利用のため)
		path := []int{n}
		
		// 1に到達するまで繰り返す
		for currentN != 1 {
			if currentN == 0 {
				// 0に到達したら、1には到達しない（この操作系では通常到達しない、または無限ループ）
				break 
			}
			
			if _, ok := memo[currentN]; ok {
				// すでに計算済みの値に到達したら、その結果を利用
				result := memo[currentN]
				total += result
				// 現在のパス上の他の要素も、もし未計算ならメモ化する（今回の問題は「nから1への手数」なので、これは不要かもしれないが、DPとして厳密に行う）
				if result != 0 && currentN != n {
					// これは、nから1への手数を求める問題なので、currentNから1への手数を足し合わせる必要がある。
					// しかし、問題文は「各クエリ n について、操作を繰り返し、1 に到達するまでの手数を求め」とあるため、
					// nをスタート地点として、その経路を辿って1に到達するまでの回数を数える。
					// これは、nから1へのステップ数を求める、つまり以下の計算になる。
					
					// n -> ... -> 1 のステップ数を求める
					// nから1へのステップ数を求めるため、再帰的またはDPで1に到達するまでの数を直接求める。
					// ここで、もしmemo[currentN]が「currentNから1への手数」ならば、
					// steps = 1 + memo[currentN] となる。
					
					// しかし、もしmemo[n]を「nから1への手数」として格納するならば、
					// currentNが1に到達したときのステップ数 (steps + memo[currentN]) を全体の合計に加算する。
					
					// シンプルにするため、今回は「nから1へのステップ数」を求めることに集中する。
					// 経路を辿りながらカウントする。
					
					// ここでは、nから1への手数を求めるため、現在のステップ数を更新する。
					// 経路上の各ステップでmemoを更新する。
					// この問題は、各クエリ n に対して独立して計算を行うため、
					// 内部のループで計算し終えたら、その結果を合計する方式が正しい。
					
					// 上記のロジックに戻り、現在のループは「nから1への手数」を計算しているため、
					// ループを抜けた後のstepsが答えとなる。
					// したがって、この内側のifブロックは不要で、メインのtotal加算で十分。
				}
				break // ループを抜ける
			}

			// 次のステップに進む
			if currentN%2 == 0 {
				currentN /= 2
			} else {
				currentN = 3*currentN + 1
			}
			steps++
			path = append(path, currentN)
		}
		
		if currentN == 1 {
			// 1に到達した場合、stepsがnから1への手数
			total += int64(steps)
			// メモ化: nから1への手数を保存
			memo[n] = int64(steps)
		}
	}

	// 結果の出力
	fmt.Printf("total=%d\n", total)
}
