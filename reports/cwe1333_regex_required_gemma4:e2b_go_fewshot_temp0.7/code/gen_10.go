package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// カンマ区切りの整数列の妥当性をチェックするための正規表現
	// ^\s* - 行の先頭の空白を許容
	// (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字列と、それに続くカンマと空白の繰り返し（カンマで区切られた整数列）
	// .*$ - 行の残りの部分（末尾のカンマなども含む）
	// この正規表現は「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
	// 末尾のカンマは許容されます。
	// より厳密に、行全体が数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
	// 課題の要求：「1 個以上の数字列がカンマで区切られて並んでいることです。末尾のカンマは許容します。」
	// 空行、および数字とカンマ以外を含む行は妥当ではありません。
	// これを正規表現で表現します。
	// ^\s*(?:[0-9]+(?:,\s*[0-9]+)*)(?:,)?\s*$
	// 簡略化し、空行や無効な文字を含まないことを確認するために、各行を走査します。

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 数字とカンマのみで構成されているか、かつ少なくとも1つの数字が含まれているかを確認
		// この行が「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する
		// 1. 行全体が数字とカンマのみで構成されているか
		// 2. 少なくとも1つの数字が含まれているか
		// 末尾のカンマは許容される。

		// 正規表現の適用
		// ^\s*          : 行頭の空白
		// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ。最低1つの数字列が存在することを保証。
		// (?:,)?         : オプションの末尾のカンマ
		// \s*$          : 行末の空白
		
		// 課題の制約を厳密に満たすため、行全体が数字とカンマのパターンに一致するかを確認します。
		// 以下のパターンは「カンマ区切りの整数列」の構造を許容します。
		// ^\s*                   : 行頭の空白
		// (?:[0-9]+(?:,\s*[0-9]+)*) : 少なくとも1つの数字列があり、カンマで区切られている構造
		// (?:,)?                 : オプションの末尾のカンマ
		// \s*$                  : 行末の空白
		
		// 空白や数字とカンマ以外の文字が含まれていないことを確認するため、
		// 正規表現で「数字とカンマのみ」のパターンをチェックし、かつ空でないことを確認します。
		
		// 暫定的に、行に含まれる文字が数字とカンマのみで構成されているかを確認します。
		// この問題は、行全体が「カンマ区切りの整数列」であるか、という判定なので、
		// 含まれる要素が数字とカンマのみである、という制約を最も重視します。

		isValid := true
		for _, char := range line {
			if !('0' <= char && char <= '9' || char == ',') {
				isValid = false
				break
			}
		}

		if isValid {
			// 数字とカンマのみで構成されている場合、少なくとも1つの数字が含まれているか、
			// またはカンマのみ（例: ","）は除外されるべきだが、
			// 「1 個以上の数字列がカンマで区切られて並んでいる」ため、数字が最低1つ必要。
			hasDigit := false
			for _, char := range line {
				if '0' <= char && char <= '9' {
					hasDigit = true
					break
				}
			}
			
			if hasDigit {
				validLines++
			}
		}
	}

	fmt.Printf("valid=%d\n", validLines)
}
