package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// カンマ区切りの整数列の妥当性を判定する正規表現
	// ^\s* - 行の先頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) - 1個以上の数字とカンマの組み合わせ (数字とカンマの間に空白があっても良い)
	// (?:,\s*)* - 末尾のカンマと空白が0回以上繰り返される (末尾のカンマを許容するため)
	// \s*$ - 行末の空白
	// 厳密には「1個以上の数字列がカンマで区切られて並んでいる」ことを確認したい。
	// 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
	// 1. 空行や不正な文字を含む行は除外する
	// 2. 1個以上の数字がカンマで区切られていることを確認する
	// 許容するパターン: 数字とカンマの組み合わせのみで構成され、少なくとも1つの数字が含まれる。
	// ^\s* - 行の先頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) - 少なくとも1つの数字列がカンマで区切られているパターン
	// (?:,\s*)* - 末尾のカンマを許容
	// \s*$ - 行末の空白
	// ただし、仕様を厳密に解釈すると、「1個以上の数字列がカンマで区切られて並んでいる」ことが重要。
	// 末尾のカンマは許容。空行はNG。数字とカンマ以外はNG。

	// よりシンプルなアプローチとして、行を読み込み、その内容をチェックする。
	// 1. 空行や数字とカンマ以外の文字が含まれていないか
	// 2. 少なくとも1つの数字が含まれているか（カンマで区切られた数字列が1つ以上あること）

	// 正規表現: 数字とカンマのみで構成され、少なくとも1つの数字が含まれている
	// ^\s* - 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字とカンマのパターン
	// (?:,\s*)* - 末尾のカンマを許容
	// \s*$ - 行末の空白
	// このパターンは、カンマ区切りの整数列が少なくとも1つあることを暗黙的に含意する。

	// 読み込んだ行を一つずつチェックする
	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現の適用
		// 1. 数字とカンマ以外の文字がないかチェック（数字とカンマのみ）
		// 2. 少なくとも1つの数字が含まれているかチェック
		// 許容されるパターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
		// 例: "1,2,3", "1,2,", "1" はOK。 "abc", "1,a" はNG。
		// 正規表現: ^\s*(?:[0-9]+(?:,\s*[0-9]+)*)(?:,\s*)*\s*$
		// このパターンは、数字とカンマのみで構成されていることを確認し、末尾のカンマを許容する。
		// 少なくとも1つの数字が含まれていることを確認するため、`[0-9]+` が最低1回出現することを確認する。
		
		// より安全に、内容が数字とカンマのみで構成されているかを確認し、
		// その後、数字が一つ以上存在するかを確認する。

		var hasDigit bool
		isValidFormat := true
		
		for _, r := range line {
			if r == ',' {
				// カンマはOK
			} else if r >= '0' && r <= '9' {
				hasDigit = true
			} else {
				// 数字とカンマ以外の文字はNG
				isValidFormat = false
				break
			}
		}

		if isValidFormat && hasDigit {
			validLines++
		}
	}

	fmt.Printf("valid=%d\n", validLines)
}
