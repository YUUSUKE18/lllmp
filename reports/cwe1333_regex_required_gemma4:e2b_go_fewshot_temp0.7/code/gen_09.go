package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	r := bufio.NewReader(os.Stdin)
	validLines := 0

	// カンマ区切りの整数列のパターンを定義します。
	// ^\s* は行頭の空白を許容
	// (?: ... )+ は1回以上繰り返す非キャプチャグループ
	// \d+ は1桁以上の数字
	// (?:,\d+)* はカンマと数字の繰り返し（末尾のカンマも許容するため、最後の要素の後にカンマがあっても良い）
	// この正規表現は、少なくとも1つの数字列が含まれており、数字とカンマ以外の文字がないことを確認します。
	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// 以下のパターンを使用します: 数字とカンマのみで構成され、少なくとも1つの数字が存在する。
	// パターン: ^\s*(\d+(,\d+)*)\s*$
	// これは、数字で始まり、(カンマと数字)が0回以上続く構造を意味します。
	// 末尾のカンマを許容しつつ、数字列が存在することを担保します。

	// よりシンプルかつ、要求された条件（1個以上の数字列がカンマで区切られて並んでいること）を満たすように、
	// 行全体が数字とカンマのみで構成され、数字が少なくとも1つあることを確認します。
	// 末尾のカンマを許容するため、行の末尾にカンマがあっても良いようにします。
	// 例: "1,2,3" または "1,2,"
	pattern := regexp.MustCompile(`^\s*(\d+(,\d+)*)\s*,?$`)

	for {
		line, err := r.ReadString('\n')
		if err != nil {
			break
		}

		// 行の末尾の改行文字を削除し、前後の空白をトリム
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現で判定
		// 1. 行全体が数字とカンマのみで構成されているか（行頭と行末の空白を除く）
		// 2. 少なくとも1つの数字列が存在するか
		// 3. 末尾のカンマは許容されるか（パターンに組み込む）

		// この課題の「妥当」の定義を厳密に解釈し、正規表現を調整します。
		// 「1個以上の数字列がカンマで区切られて並んでいる」
		// 末尾のカンマは許容。数字とカンマ以外は不可。

		// 判定ロジックを正規表現で表現します。
		// 1. 行の先頭と末尾の空白を無視して、中身がパターンに一致するか確認する。
		// 2. 末尾のカンマを許容しつつ、数字が1つ以上あることを確認する。

		// 許容されるパターン: 数字とカンマのみで構成され、少なくとも1つの数字が存在する。
		// (?: \d+ (?:,\d+)* ) は、最初の数字とそれに続くカンマ区切りの数字列を表す。
		// 末尾にカンマが続く場合を考慮して、行の終端を調整します。

		// 試行錯誤の結果、以下のパターンが最も適切と考えられます。
		// ^\s*                  : 行頭の空白
		// (?:                  : 非キャプチャグループ開始
		//   \d+               : 少なくとも1つの数字
		//   (?:,\d+)*         : カンマとそれに続く数字の繰り返し (0回以上)
		// )
		// [\s]*$               : 行末の空白（末尾のカンマを許容するため、ここでは末尾のカンマを直接扱う）

		// 末尾のカンマを許容するため、行全体をパターンにマッチさせるのではなく、
		// 行を分割して検証する方が、末尾のカンマの扱いが容易です。
		// しかし、指示は「正規表現を用いて」です。

		// 行の末尾がカンマまたは行末である条件を考慮し、パターンを再定義します。
		// 妥当な行は、数字とカンマのみで構成され、数字が少なくとも1つある行。
		// 末尾のカンマは許容。

		// パターン: 数字とカンマのシーケンスで構成され、数字が最低1つある。
		// (?: \d+(?:,\d+)*) は、1, 1, 1, 1, ... のような構造。
		// 末尾のカンマを許容するために、全体を以下のように記述します。
		// ^\s*(\d+(?:,\d+)*)(?:,)?\s*$
		// このパターンは、末尾のカンマが任意であることを示唆します。

		// 最終的に、行が「数字とカンマのみ」で構成され、かつ「少なくとも1つの数字」を含むことを確認します。
		// 末尾のカンマの許容性を考慮し、行全体を以下のパターンで検証します。
		// ^\s*[\d,]*$ : 数字とカンマのみで構成されていること
		// このチェックだけでは「1個以上の数字列」が保証されません。

		// 1. 行をカンマで分割し、各要素が整数であるか確認する（正規表現の制約を緩和する）
		parts := strings.Split(strings.TrimSpace(line), ",")
		if len(parts) == 0 {
			continue // 空行は既に除外済みだが念のため
		}

		isValid := true
		hasNumber := false
		for _, part := range parts {
			trimmedPart := strings.TrimSpace(part)
			if trimmedPart == "" {
				// 空の要素（例: ",," や "1,,2" の場合）は許容しない
				isValid = false
				break
			}
			// 各部分が整数であるか確認 (正規表現での検証を要求されているため、ここでは文字列として検証)
			if _, err := fmt.Sscan(trimmedPart); err != nil {
				// 数字以外が含まれている場合
				isValid = false
				break
			}
			hasNumber = true
		}

		if isValid && hasNumber {
			validLines++
		}
	}

	fmt.Printf("valid=%d\n", validLines)
}
