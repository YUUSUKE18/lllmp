package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// 1. 正規表現の定義: カンマ区切りの整数列、末尾のカンマを許容するパターン
	// ^\s* : 行頭の空白を許容
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の整数とカンマ区切りで続くパターン（空でない）
	// (?:,\s*|$) : カンマと空白、または行末
	// この正規表現は、数字とカンマのみで構成され、1つ以上の数字が存在することをチェックする。
	// ただし、仕様は「1 個以上の数字列がカンマで区切られて並んでいること」を許容し、末尾のカンマも許容する。
	// 行が空でないこと、数字とカンマ以外を含まないことを確認する。
	// より厳密に、行全体が「整数とカンマのみ」で構成され、少なくとも1つの整数が含まれていることを確認する。

	// 各行を読み込み、判定する
	for scanner.Scan() {
		line := scanner.Text()

		// 行の前後の空白を無視して、行の内容を整形する
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現による検証:
		// ^\s* : 行頭の空白（既にTrimSpaceで除去されているが念のため）
		// (?:[0-9]+(?:,\s*[0-9]+)*) : 少なくとも1つの整数が、カンマと空白で区切られている。
		// (?:,\s*|$) : 末尾にカンマと空白、または行末が続く。
		// このパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを保証する。
		// 末尾のカンマも許容するため、行末はカンマまたは行末である必要がある。

		// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
		// これは、数字とカンマ、空白のみで構成され、少なくとも一つの数字が含まれていることを意味する。

		// パターン: 整数とカンマ、空白のみで構成され、少なくとも1つの数字が含まれている。
		// 以下のパターンは、数字とカンマ、空白のシーケンスをチェックする。
		// ^\s* : 行頭の空白
		// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の整数とカンマ区切り
		// (?:,\s*|\s*$) : 末尾はカンマと空白、または行末
		// 全てをチェックするために、行全体をチェックする。

		// 行が数字とカンマ、空白のみで構成されているか確認
		isAlphanumericOnly := regexp.MustCompile(`^[0-9, \t\r\n]*$`).MatchString(line)

		if !isAlphanumericOnly {
			continue // 数字とカンマ以外を含む行は不妥当
		}

		// 妥当性のチェック: 1個以上の数字列がカンマで区切られているか、または単一の数字列であるか。
		// 末尾のカンマは許容される。
		// 例えば "1,2,3," や "100" など。

		// 1. 末尾のカンマを除去してチェックする
		lineWithoutTrailingComma := strings.TrimRight(line, ",")

		// 2. それが空でなければ、残りの内容が整数とカンマのみで構成されているか確認する
		if lineWithoutTrailingComma != "" {
			// 末尾のカンマを除去した後の文字列が、整数とカンマのみで構成されているか確認
			// 正規表現: 整数とカンマ、空白のみ（末尾のカンマは無視）
			// ^\s* : 行頭の空白
			// [0-9, ]+ : 少なくとも1文字の数字、カンマ、空白
			// $ : 行末
			// このチェックは、行が完全に数字とカンマ、空白のみで構成されていることを担保する。
			match := regexp.MustCompile(`^\s*[0-9, ]+$`).MatchString(line)

			if match {
				// 少なくとも1つの数字が含まれているか確認 (これは上記のチェックに含まれるはずだが念のため)
				if regexp.MustCompile(`[0-9]`).MatchString(line) {
					validLines++
				}
			}
		} else {
			// 末尾がカンマのみ、または空行（既に空行はスキップ済み）
			// 例: "," や "" は不妥当。しかし、行が空でない場合、これは数字列が0個であるため不妥当。
			// 空行はスキップ済みなので、ここでは妥当としない。
		}
	}

	fmt.Printf("valid=%d\n", validLines)
}
