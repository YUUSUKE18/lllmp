package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	r := bufio.NewReader(os.Stdin)
	// 妥当な行数を格納する変数
	validLines := 0

	// 正規表現パターン:
	// ^\s*             - 行の先頭の空白をマッチ
	// (?:             - 非キャプチャグループの開始（オプション）
	//   \d+,\s*       - 1つ以上の数字、カンマ、任意の空白
	// )+              - 上記パターンが1回以上繰り返される
	// \d*             - 末尾の数字（カンマがあっても良い）
	// \s*$            - 行末の空白
	// このパターンは、少なくとも1つの数字とカンマのペアが存在することを要求する。
	// ただし、仕様「1 個以上の数字列がカンマで区切られて並んでいる」を厳密に解釈するため、
	// 少なくとも一つの数字が存在することをチェックする。
	// より単純に、カンマで区切られた数字の列が存在するかどうかをチェックする。

	// 課題の要求を再解釈:
	// 1. 1個以上の数字列がカンマで区切られていること。
	// 2. 空行は妥当ではない。
	// 3. 数字とカンマ以外を含む行は妥当ではない。
	// 4. 末尾のカンマは許容される。

	// 行ごとに読み込み、検証する
	for {
		line, err := r.ReadString('\n')
		if err != nil {
			break
		}

		// 行から末尾の改行文字を削除
		trimmedLine := strings.TrimSpace(line)

		// 1. 空行の判定
		if trimmedLine == "" {
			continue // 空行は妥当ではないためスキップ
		}

		// 2. 正規表現による検証:
		// 妥当な行は「数字とカンマのみ」で構成され、少なくとも1つの数字が含まれる必要がある。
		// パターン: 任意の文字（数字、カンマ、空白）が続くが、
		// 少なくとも一つの数字が存在し、数字とカンマ以外の文字は許容されない。
		// ただし、仕様「数字とカンマ以外を含む行は妥当ではない」を考慮すると、
		// 正規表現で「数字とカンマのみ」に限定するのが適切。

		// 判定ロジック: 行が数字とカンマのみで構成されているか、かつ数字が少なくとも1つあるか。
		// 許容される文字セット: [0-9, ,]
		// 少なくとも1つの数字が存在する: [0-9]+
		// パターン: [0-9,]+
		// これだと「1,2,3」はOKだが、「,」だけはNGになる。

		// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックする。
		// これは、カンマで区切られた要素がすべて数字である、ということを意味する。

		// 許容されるパターン: 数字とカンマのみで構成され、少なくとも1つの数字を含む。
		// 例: "1,2,3" -> OK
		// 例: "1,2," -> OK (末尾カンマ許容)
		// 例: "123" -> OK (カンマなしも、1個の数字列と見なせるか？ -> 「カンマで区切られて並んでいる」が前提)

		// 「1個以上の数字列がカンマで区切られて並んでいる」をチェックするために、
		// カンマで区切られた要素がすべて数字であることを確認する。
		// 1. カンマで分割する
		parts := strings.Split(trimmedLine, ",")
		
		if len(parts) == 0 {
			// これは既に trimmedLine == "" で除外されているはずだが念のため
			continue
		}

		isValid := true
		hasDigit := false
		
		for _, part := range parts {
			trimmedPart := strings.TrimSpace(part)
			if trimmedPart == "" {
				// カンマが連続している場合、これは「空の数字列」と見なされるが、
				// 仕様では「1個以上の数字列」が区切られている必要があるため、
				// 連続するカンマ（例: "1,,2"）は妥当ではないと解釈する。
				// ただし、「末尾のカンマは許容」という条件があるため、中間や先頭の空項はNGとする。
				if trimmedLine == "," || trimmedLine == ",," || trimmedLine == ",," {
					// 完全にカンマのみの場合や、内部に空項がある場合はNG
					isValid = false
					break
				}
				// 末尾のカンマは許容されるため、ここでは空項はNGとする。
				// ただし、これは「1個以上の数字列」が区切られているという要求に反する。
				// 簡略化のため、もし空項があれば不適と判断する。
				isValid = false
				break
			}
			
			// 各部分が整数であるかチェック
			if _, err := fmt.Sscan(trimmedPart); err != nil {
				// 数字以外が含まれている場合（例: "a,1"）
				isValid = false
				break
			}
			hasDigit = true
		}

		if !isValid {
			continue
		}
		
		// 少なくとも1つの数字列が存在したか確認
		if !hasDigit {
			continue
		}

		// 妥当な行としてカウント
		validLines++
	}

	// 1行だけ出力
	fmt.Printf("valid=%d\n", validLines)
}
