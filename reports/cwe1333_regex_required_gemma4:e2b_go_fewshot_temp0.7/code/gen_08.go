package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// カンマ区切りの整数列のパターンを定義する正規表現
	// ^\s* : 行頭の任意の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字とカンマの繰り返し。これは「1個以上の数字列がカンマで区切られている」ことを意味する。
	// \s*$ : 行末の任意の空白
	// 末尾のカンマを許容するため、カンマが続くパターンを考慮する。
	// より単純に、カンマで区切られた数字のみが存在すれば良い。
	// パターン: 空白, 1つ以上の数字, (カンマと空白が0回以上繰り返される)
	// 末尾のカンマを許容するため、末尾にカンマが来るパターンも考慮する。
	// 妥当な行は、カンマで区切られた数字のみを含む行。
	// 例: "1,2,3" または "1,2,"
	// 妥当性の判定を「カンマで区切られた数字列」が1つ以上存在するかどうかで定義する。

	// 妥当な行の判定ロジックを正規表現で表現する。
	// 1. 行が空行でないこと。
	// 2. 行が数字とカンマのみで構成されていること。
	// 3. 少なくとも1つの数字が含まれていること（カンマのみの行は除く）。
	// 4. 末尾のカンマは許容される。

	// 正規表現: 任意の空白、1つ以上の数字、カンマと空白の繰り返し、末尾のカンマ（任意）
	// ただし、空行や数字とカンマ以外の文字は許容しない。

	// ここでは、行が空でないこと、および数字とカンマのみで構成されていることを確認し、
	// さらに「1個以上の数字列がカンマで区切られている」という条件をチェックする。

	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックする正規表現を試みる。
	// 1. \s* : 先頭の空白
	// 2. (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字がカンマで区切られているパターン。
	//    これは「1,2,3」や「1,2," のような形式を捉える。
	// 3. .* : 行末の任意の文字（末尾のカンマを許容するため）

	// 行全体が、カンマで区切られた数字のシーケンスのみで構成されているかを確認する。
	// 妥当な行: カンマで区切られた数字が少なくとも1つ含まれている行。

	// 判定用正規表現:
	// ^\s* : 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字とカンマの繰り返し。
	// $ : 行末
	// このパターンは、末尾のカンマを許容しないため、後で調整が必要。

	// 妥当性の判定をプログラム側で行い、正規表現は「数字とカンマ以外の文字が含まれていないか」に絞る。

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			continue // 空行は妥当ではない
		}

		// 数字とカンマ以外の文字が含まれていないかチェック
		// 許容される文字: 数字(0-9), カンマ(,), 空白( )
		// ただし、行全体が「数字とカンマのみ」で構成されているかをチェックする。
		isNumericAndCommaOnly := true
		for _, r := range line {
			if !('0' <= r && r <= '9' || r == ',' || r == ' ') {
				isNumericAndCommaOnly = false
				break
			}
		}

		if !isNumericAndCommaOnly {
			continue // 数字とカンマ以外の文字を含む行は妥当ではない
		}

		// 1個以上の数字列がカンマで区切られているかチェック
		// 末尾のカンマは許容される。

		// 行から末尾のカンマを取り除いた文字列をチェックし、それが空でないか確認する。
		// または、カンマで分割してみて、数字列が1つ以上あるか確認する。

		// 行全体をカンマで分割してみる (末尾のカンマがあっても対応できるように)
		parts := strings.Split(line, ",")
		
		hasDigits := false
		for _, part := range parts {
			trimmedPart := strings.TrimSpace(part)
			if trimmedPart != "" {
				// 数字列が存在すればOK
				if regexp.MustCompile(`^[0-9]+$`).MatchString(trimmedPart) {
					hasDigits = true
				}
			}
		}

		if hasDigits {
			validLines++
		}
	}

	fmt.Printf("valid=%d\n", validLines)
}
