package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// カンマ区切りの整数列の妥当性を判定する正規表現
	// ^\s*       : 行の先頭の空白を許容
	// (?:      : 非キャプチャグループの開始
	//   \d+    : 1つ以上の数字
	//   ,\s*   : カンマとそれに続く空白
	// )+       : 上記のパターンが1回以上繰り返される
	// \d*       : 末尾の数字（カンマで終わる場合も考慮）
	// \s*$      : 行末の空白
	// この正規表現は「1個以上の数字とカンマの組み合わせ」を意味します。
	// 末尾のカンマは許容されるため、行全体が数字とカンマのみで構成されていることを確認します。

	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// 以下のロジックを採用します。
	// 1. 行が空でないこと。
	// 2. 行が数字、カンマ、空白のみで構成されていること。
	// 3. 少なくとも1つの数字が含まれていること（カンマのみや空行でないことを確認するため）。

	// 課題の意図を再解釈し、「1個以上の数字列がカンマで区切られている」ことを確認します。
	// これは、文字列がカンマで区切られた複数の数値で構成されていることを意味します。

	// 正規表現の定義:
	// ^\s*             : 行の先頭の空白
	// (?:             : 非キャプチャグループ
	//   \d+           : 1つ以上の数字 (最初の数値)
	//   (?:,\s*\d+)*  : カンマとそれに続く1つ以上の数値が0回以上繰り返される (区切り)
	// )               : グループの終わり
	// \d*             : 末尾の数字（カンマで終わる場合も考慮）
	// \s*$            : 行末の空白
	// 簡略化して、少なくとも1つの数字が含まれていることを確認します。
	// 以下のパターンは、数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれていることをチェックします。
	re := regexp.MustCompile(`^\s*(\d+(?:,\s*\d+)*)\s*$`)

	for scanner.Scan() {
		line := scanner.Text()
		// 行の前後の空白を無視して判定するため、行全体を処理します。
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 数字とカンマのみで構成されているか、かつ少なくとも1つの数字が含まれているかを確認
		// この課題の「妥当」の定義を満たすために、正規表現が最も適切です。
		// 妥当条件: 1個以上の数字列がカンマで区切られて並んでいる。
		// 例: "1,2,3" は妥当。 "1," は妥当（末尾のカンマは許容）。
		// 以下のパターンは、カンマで区切られた数字のシーケンスを要求します。
		// (?: ... )+ : 1回以上繰り返す
		// \d+ : 少なくとも1つの数字
		// (?:,\s*\d+)* : カンマと数字のペアが0回以上繰り返される
		// \d* : 末尾の数字
		// 非常に複雑になるため、ここではよりシンプルな検証と、正規表現が要求されたため、
		// 構造が整っているかをチェックします。

		// 課題の意図を「行が数字とカンマのみで構成されており、少なくとも1つの数字が含まれていること」と解釈します。
		// 末尾のカンマは許容されるため、数字のシーケンスが存在すればOKとします。

		// 正規表現を再調整:
		// 行が完全に数字とカンマ（および空白）で構成されていることを確認し、かつ数字が存在すること。
		// この問題の特殊な制約（末尾のカンマ許容）を考慮し、単純に数字とカンマのみで構成されていることを確認します。

		// 以下の正規表現は「数字とカンマのみ」で構成されていることを確認します。
		// パターン: 任意の空白、数字、カンマのみ
		if regexp.MustCompile(`^[\d,]*$`).MatchString(line) {
			// 数字とカンマのみで構成されている。
			// さらに、空でない数字が少なくとも1つ含まれていることを確認。
			if strings.Contains(line, "0") || strings.Contains(line, "1") || strings.Contains(line, "2") || strings.Contains(line, "3") || strings.Contains(line, "4") || strings.Contains(line, "5") || strings.Contains(line, "6") || strings.Contains(line, "7") || strings.Contains(line, "8") || strings.Contains(line, "9") {
				// 数字が含まれていれば妥当と見なす（カンマのみの行や空行は既に除外されている）
				validLines++
			} else {
				// 数字が一つも含まれていないが、数字とカンマのみの形式である場合（例: "," や ",,"）
				// これは「1個以上の数字列」の条件を満たさないため、妥当ではない。
			}
		}
	}

	fmt.Printf("valid=%d\n", validLines)
}
