package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// 正規表現: カンマ区切りの整数列。
	// ^\s* : 行頭の空白（無視される）
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1個以上の整数列とカンマの組み合わせ。
	// .*$ : 行末まで（末尾のカンマも許容するため、厳密には行全体をチェック）
	// より厳密に、行全体が数字とカンマのみで構成され、少なくとも1つの数字が含まれていることをチェックする。
	// 妥当なパターン: 数字とカンマだけで構成され、少なくとも1つの数字が含まれている。
	// 末尾のカンマは許容する。
	// 以下の正規表現は、カンマで区切られた整数列（数字とカンマのみ）が少なくとも1つ存在することを検証する。
	// ^\s* は行頭の空白を許容する。
	// (?:[0-9]+(?:,\s*[0-9]+)*) は、数字とカンマのシーケンスを意味する。
	// 末尾のカンマを許容するため、行全体が数字とカンマで構成され、少なくとも1つの数字が含まれていることを確認する。

	// 課題の要件を再解釈: 「1 個以上の数字列がカンマで区切られて並んでいること」を判定する。
	// これは、カンマで区切られた要素のうち、少なくとも1つが整数であることを意味する。
	// 行全体が「数字とカンマのみ」で構成され、かつ「少なくとも1つの数字」が含まれていることをチェックする。
	// 末尾のカンマは許容される。

	// パターン定義: 行全体が (数字とカンマの組み合わせ) のみで構成され、かつ少なくとも1つの数字を含む。
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字の塊（カンマ区切り）
	// .* : 行末のカンマや空白（末尾のカンマを許容するため）
	// 厳密に、行がカンマで区切られた整数列のみで構成され、かつ少なくとも1つの数字が含まれていることを確認する。

	// 簡略化された判定ロジック: 行をカンマで分割し、空でない要素が1つ以上あるか、およびそれらが整数であるかをチェックする。
	// 正規表現を使うという制約があるため、正規表現で「カンマ区切りの整数列」を表現する。
	// 妥当な行は、カンマで区切られた要素が存在し、それらが数字のみで構成されている必要がある。
	// 末尾のカンマは許容される。

	// 妥当な行の判定ロジックを正規表現で実現する場合:
	// ^\s*(?:[0-9]+(?:,\s*[0-9]+)*)(?:,?\s*[0-9]+)*$
	// これは複雑になるため、ここでは正規表現で「カンマ区切りの整数列」の構造を検証する。

	// 課題の要求を最も直接的に満たすように、行を読み込み、手動でバリデーションを行う（正規表現の使用が必須だが、複雑な構造判定には手動チェックが現実的）。
	// 正規表現で「カンマ区切りの整数列」を定義し、行全体がそれに一致するかを試みる。

	// 妥当な行の判定:
	// 1. 行全体が数字とカンマ、空白のみで構成されていること。
	// 2. 少なくとも1つの数字が含まれていること。
	// 3. 末尾のカンマは許容される。

	// パターン: ^\s*(?:[0-9]+(?:,\s*[0-9]+)*)(?:,*\s*)$
	// このパターンは、少なくとも1つの数字の塊があり、その後ろにカンマや空白が続くことを許容する。
	validPattern := regexp.MustCompile(`^\s*(?:[0-9]+(?:,\s*[0-9]+)*)(?:,*\s*)$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない (ただし、仕様では「空行」が妥当かどうかは明記されていないが、「数字列が並んでいる」という要件を満たさないため、妥当ではないと判断する)
			continue
		}

		// 行全体が数字とカンマのみで構成されているかを確認する（正規表現で検証）
		if validPattern.MatchString(line) {
			// さらに、少なくとも1つの数字が含まれていることを確認する（空のカンマ列のみでないこと）
			// これは、パターンが既に数字の存在を要求しているため、MatchStringがtrueになれば十分とする。
			validLines++
		}
	}

	fmt.Printf("valid=%d\n", validLines)
}
