package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	r := bufio.NewReader(os.Stdin)
	validLines := 0

	for {
		line, err := r.ReadString('\n')
		if err != nil {
			break
		}

		// 行の処理
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現による妥当性の判定
		// 1. 1個以上の数字とカンマのみで構成されていること。
		// 2. 末尾にカンマがあっても良いこと。
		// 3. 数字とカンマ以外の文字を含まないこと。
		// 正規表現: ^[0-9,]*$ は、行全体が数字とカンマのみで構成されていることを確認する。
		// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」という条件を満たすためには、
		// カンマが少なくとも1つ含まれていて、かつ数字が含まれている必要があります。
		// 仕様を再解釈すると、「1個以上の数字列がカンマで区切られている」ことを意味します。
		// 例: "1,2,3" -> 3つの数字列
		// 例: "1," -> 2つの数字列 (1と空) または 1つの数字列 (1と末尾のカンマ)
		// 妥当な行は、数字とカンマのみで構成され、かつ少なくとも1つのカンマを含む、あるいは数字のみで構成されている行と解釈します。
		// 「1個以上の数字列がカンマで区切られて並んでいる」を満たすためには、少なくとも1つのカンマが必要、または数字が複数必要です。
		// 末尾のカンマは許容されます。
		// 最小の妥当な例: "1" (1つの数字列)
		// 妥当なパターン: 数字とカンマのみで構成され、空行でない。
		// ここでは、行が完全に数字とカンマのみで構成されていることを確認し、空行でないことを確認します。
		// "1,2,3" -> OK
		// "1," -> OK (末尾のカンマは許容)
		// "abc" -> NG
		// "1a" -> NG
		// "1" -> OK (1つの数字列)
		// 空行はNG
		
		// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」を、カンマ区切りとして解釈します。
		// これは、数字の並びがカンマで区切られていることを意味します。
		// 正規表現: ^[0-9,]+$ (数字またはカンマが1文字以上続く)
		// 実際には、行が数字とカンマのみで構成されていることを確認し、空行でないことを確認します。
		
		// 行が数字とカンマのみで構成されているか確認
		match, _ := regexp.MatchString(`^[0-9,]*$`, trimmedLine)

		if match {
			// 空行でないことを確認済み (trimmedLine != "")
			// 妥当な行と判断する。
			validLines++
		}
	}

	fmt.Printf("valid=%d\n", validLines)
}
