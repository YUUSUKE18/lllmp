package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* 表示行の先頭の空白
	// [0-9]+ 表示1つ以上の数字
	// (?:,\s*[0-9]+)* 表示カンマとそれに続く空白を含む任意の数の数字の繰り返し（オプション）
	// \s*$ 表示行末の空白
	// この正規表現は、行が少なくとも一つの数字を含む、カンマ区切り（末尾カンマ含む）の形式であるかをチェックします。
	// 仕様では「1個以上の数字列がカンマで区切られて並んでいること」を求められています。
	// より単純に「数字とカンマのみで構成され、数字が少なくとも1つ含まれていること」をチェックする方が実用的です。

	// 妥当な行の判定ロジックを実装します。
	// 1. 空行は妥当ではない。
	// 2. 数字とカンマ以外の文字が含まれていない。
	// 3. 少なくとも1つの数字が含まれている。

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現でチェック: 数字とカンマのみで構成されているか、かつ少なくとも1つの数字があるか
		// ^\s* : 行頭の空白（TrimSpaceで除去済みだが念のため）
		// [0-9,]* : 数字またはカンマのみ
		// [0-9] : 少なくとも1つの数字が含まれていることを保証するため、より詳細なチェックが必要。

		// 妥当な形式の定義を厳密に解釈します:
		// 「1 個以上の数字列がカンマで区切られて並んでいる」
		// これは、数字とカンマのみで構成され、数字が少なくとも1つ含まれていることを意味します。

		// 正規表現: ^\s*([0-9]+(?:,\s*[0-9]+)*)\s*$
		// ^\s* : 行頭の任意の空白
		// ( ... ) : キャプチャグループ（これが数字列全体）
		// [0-9]+ : 少なくとも1つの数字
		// (?:,\s*[0-9]+)* : カンマとそれに続く数字の繰り返し（0回以上）
		// \s*$ : 行末の任意の空白

		// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックします。
		// 末尾のカンマは許容されます。
		// これは、数字とカンマのみで構成され、数字が少なくとも1つ含まれている必要があります。

		// 判定基準を、行全体が数字とカンマのみで構成され、かつ数字が1つ以上あることを確認する正規表現にします。
		// この正規表現は、末尾のカンマを許容するように調整します。
		// 例: "1,2,3" は OK, "1," は OK, "" は NG, "a1,2" は NG
		pattern := `^\s*([0-9,]+)\s*$`
		match, err := regexp.MatchString(pattern, line)

		if err == nil && match {
			// パターンにマッチし、かつ行が空でないことを確認する（既に空行はスキップしているため、ここではマッチすれば妥当と見なす）
			// さらに、キャプチャグループが数字のみで構成されているかを確認するステップが必要ですが、
			// 仕様は「1個以上の数字列がカンマで区切られて並んでいる」なので、数字とカンマの構造を許容します。
			// 実際には、数字とカンマ以外の文字が含まれていないことが最も重要です。

			// 最終的な判定として、行が数字とカンマのみで構成されているか、かつ少なくとも1つの数字が含まれていることを確認します。
			
			// 簡略化のため、行をカンマで分割し、すべてが数字であることを確認するアプローチをとります。
			fields := strings.Split(line, ",")
			hasDigit := false
			for _, field := range fields {
				trimmedField := strings.TrimSpace(field)
				if trimmedField != "" {
					// 空でないフィールドが存在する場合、そのフィールドが整数であることを確認
					if _, err := fmt.Sscanf(trimmedField, "%d", &hasDigit); err == nil {
						hasDigit = true
					} else {
						// 数字以外が含まれていた場合はNG
						goto nextLine
					}
				}
			}
			
			// 末尾のカンマのみの場合 (例: "1," の場合、Splitの結果は ["1", ""] となる)
			// 少なくとも1つの数字が含まれていればOK。
			if hasDigit {
				validLines++
			}
		}
		
		nextLine:
	}

	fmt.Printf("valid=%d\n", validLines)
}
