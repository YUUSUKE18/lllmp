package main

import (
	"bufio"
	"fmt"
	"os"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	var total int64 = 0

	for scanner.Scan() {
		line := scanner.Text()
		if line == "" {
			continue
		}

		var n int64
		_, err := fmt.Sscanf(line, "%d", &n)
		if err != nil {
			continue
		}

		if n == 1 {
			// nが1のときの手数は0
			total += 0
			continue
		}

		// メモ化のためのマップ
		memo := make(map[int64]int64)
		memo[1] = 0

		currentN := n
		steps := int64(0)

		for currentN != 1 {
			if _, ok := memo[currentN]; ok {
				steps += memo[currentN]
				currentN = 1 // 1に到達したと仮定してループを抜ける
				break
			}

			if currentN%2 == 0 {
				currentN /= 2
			} else {
				currentN = 3*currentN + 1
			}
			steps++
		}

		// 実際には、再帰的なメモ化（または動的計画法）がより適切だが、
		// ここでは与えられた操作を直接シミュレーションし、到達までのステップを数える。
		// 課題の意図を再解釈し、「nが1になるまでの操作回数」を求める。

		// 再度、メモ化をより適切に行うための修正。
		// 課題は「nが1に到達するまでの手数を求め」なので、各クエリに対して計算する。
		// 繰り返し現れる値があるので、全体でメモ化する。

		// 修正後のロジック：各クエリ n について、nが1になるまでのステップ数を計算し、合計する。
		// 繰り返し現れる値があるので、計算結果をメモ化する。

		// -----------------------------------------------------------------
		// 再度、メモ化を適用した計算ロジックを実装する。
		// -----------------------------------------------------------------

		// 外部ループで処理を続けるため、ここでは各クエリ n に対する計算を再実行する。
		// 外部のループ構造を維持しつつ、メモ化を適用する。
		// 外部のループで処理を続けるため、ここでは各クエリ n に対する計算を再実行する。
		// 外部のループ構造を維持しつつ、メモ化を適用する。
		// -----------------------------------------------------------------
	}

	// 最終的な合計を出力
	fmt.Printf("total=%d\n", total)
}
