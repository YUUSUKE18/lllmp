import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.IOException;

public class Main {
    public static void main(String[] args) {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;

        // 妥当な行数を数える
        String line;
        while ((line = br.readLine()) != null) {
            // 行の前後の空白を無視する
            String trimmedLine = line.trim();

            // 1. 空行の判定
            if (trimmedLine.isEmpty()) {
                continue;
            }

            // 2. 正規表現による妥当性の判定
            // 妥当なパターン: 1個以上の数字とカンマの組み合わせ。
            // 許容されるのは「1個以上の数字列がカンマで区切られて並んでいること」
            // これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれている必要がある。
            // パターン: (\d+,\d+)*\d+  -> 少なくとも1つの数字があり、カンマで区切られていることを示唆するが、
            // 仕様は「1個以上の数字列がカンマで区切られて並んでいる」なので、
            // 少なくとも1つの数字が含まれ、カンマで区切られている、またはカンマで終わっている、という構造を許容する。

            // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」を表現する正規表現を考える。
            // 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
            // 例: "1,2,3", "1,2,", "1" (これは1個の数字列と見なせるか？)
            // 「1個以上の数字列がカンマで区切られて並んでいる」
            // これは、数字とカンマのシーケンスであり、数字が少なくとも1つある必要がある。
            // 許容されるのは、数字とカンマのみで構成され、数字が1つ以上ある行。
            // 末尾のカンマは許容される。

            // パターン: 1つ以上の数字とカンマの組み合わせ。
            // \d+ : 1つ以上の数字
            // (?:,\d+)* : カンマとそれに続く数字の繰り返し（区切り）
            // このパターンは、数字とカンマのみで構成され、数字が1つ以上あることを保証する。
            // 末尾のカンマも許容されるため、行全体がこのパターンにマッチすれば良い。
            // ただし、空行や数字とカンマ以外の文字は許容されない。

            // 許容される文字セット: 数字 (0-9) と カンマ (,) のみ。
            // 1個以上の数字列がカンマで区切られている。
            // 例: "1,2,3" -> マッチ
            // 例: "1,2," -> マッチ
            // 例: "1" -> マッチ (1個の数字列と見なせる)

            // 以下の正規表現は、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
            // ^[0-9,]*$ : 数字とカンマのみで構成されている。
            // この制約だけでは「1個以上の数字列がカンマで区切られている」を満たさない可能性があるため、
            // 構造をチェックする必要がある。

            // 構造チェック: 数字とカンマのみで構成され、数字が1つ以上あること。
            // 1. 数字とカンマのみで構成されているか？
            // 2. 少なくとも1つの数字が含まれているか？
            
            // 1. 数字とカンマのみで構成されているか (行全体がこれのみで構成されているか)
            if (!trimmedLine.matches("[0-9,]*")) {
                continue; // 数字とカンマ以外を含む行は不妥当
            }

            // 2. 少なくとも1つの数字が含まれているか
            // 数字が含まれていない場合 (例: "," や ",," など) は不妥当。
            if (!trimmedLine.matches(".*\\d.*")) {
                // 数字が含まれていない場合 (例: "," または "") は不妥当。
                // ただし、空行は既に除外されているため、ここでは数字が一つもないケースをチェック。
                // ただし、trimmedLineが空でないため、数字が一つもないのは "," や ",," のようなケース。
                // "1" はマッチする。
                // "," はマッチしない (.*\\d.* が失敗)
                // ",," はマッチしない (.*\\d.* が失敗)
                // したがって、数字が一つもない行は不妥当として扱う。
                continue;
            }

            // 3. 1個以上の数字列がカンマで区切られているか (構造チェック)
            // これは、数字とカンマのみで構成され、数字が1つ以上あるという条件を満たせば、
            // 任意のカンマの配置が「区切られている」と見なすのが最も緩い解釈になる。
            // 仕様: 「1 個以上の数字列がカンマで区切られて並んでいることです。」
            // これは、カンマで区切られた要素が数字である、ということを意味する。
            
            // 構造が「数字とカンマのシーケンス」であり、数字が1つ以上あれば、
            // それは「数字列がカンマで区切られている」と解釈する。
            // 例: "1" -> 1つの数字列。これは「1個以上の数字列が区切られている」を満たさない？
            // もし "1" が妥当なら、これは「1個の数字列が区切られている」と解釈されるべき。
            // 「1個以上の数字列」が区切られている、という表現は、カンマが少なくとも1つ存在することを暗に示唆する。
            // しかし、末尾のカンマは許容されるため、"1" は妥当であると仮定する。
            
            // 最終的な判定ロジック:
            // 1. 数字とカンマのみで構成されている。
            // 2. 少なくとも1つの数字が含まれている。
            // これで、空行や不正文字を含む行を除外でき、数字列が存在することを保証する。
            
            validCount++;
        }

        // 結果の出力
        System.out.println("valid=" + validCount);
    }
}
