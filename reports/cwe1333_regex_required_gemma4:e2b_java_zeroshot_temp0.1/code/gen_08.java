import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.IOException;

public class Main {
    public static void main(String[] args) {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;

        // 正規表現パターン:
        // ^\s*          -> 行の先頭の任意の空白文字
        // (?:          -> 非キャプチャグループの開始
        //   \d+        -> 1つ以上の数字
        //   (?:,\d+)* -> カンマと1つ以上の数字の繰り返し（カンマ区切りのリスト）
        // )            -> グループの終了
        // (?:,\d+)*    -> 末尾のカンマが許容されるように、カンマと数字の繰り返しを許容
        // \s*$         -> 行の末尾の任意の空白文字
        //
        // よりシンプルに、1個以上の数字とカンマの組み合わせ、および末尾のカンマを許容するパターンを考える。
        // 妥当な行の定義: 1個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容。
        // これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれている必要がある。

        // パターン解説:
        // ^\s*             : 行頭の空白
        // (?:              : 非キャプチャグループ開始
        //   \d+            : 1つ以上の数字 (最初の数字列)
        //   (?:,\d+)*      : カンマとそれに続く数字の繰り返し (カンマ区切りのリスト)
        // )                : グループ終了
        // (?:,\d+)*         : 末尾のカンマが許容されるように、カンマと数字の繰り返しを許容
        // \s*$             : 行末の空白
        //
        // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」を表現する。
        // 少なくとも1つの数字が含まれ、数字とカンマのみで構成される。
        // 例: "1,2,3", "1,2,", "1"
        //
        // 妥当な行のパターン:
        // ^\s*             : 行頭の空白
        // (?:              : 非キャプチャグループ開始
        //   \d+            : 少なくとも1つの数字
        //   (?:,\d+)*      : カンマと数字の繰り返し (0回以上)
        // )                : グループ終了
        // (?:,\d+)*         : 末尾のカンマが許容されるように、カンマと数字の繰り返しを許容
        // \s*$             : 行末の空白

        // 実際には、行が空でないこと、数字とカンマ以外を含まないことを確認しつつ、
        // 少なくとも1つの数字が含まれていることを確認する必要があります。

        // 妥当な行の判定ロジックを正規表現で表現します。
        // 1. 行が空でないこと (これは後で手動でチェックするか、パターンで含める)
        // 2. 数字とカンマのみで構成されていること。
        // 3. 少なくとも1つの数字が含まれていること。

        // 妥当な行のパターン:
        // ^\s*                 : 行頭の空白
        // (?:                  : 非キャプチャグループ開始
        //   \d+                : 少なくとも1つの数字
        //   (?:,\d+)*          : カンマと数字の繰り返し (0回以上)
        // )                    : グループ終了
        // (?:,\d+)*             : 末尾のカンマが許容されるように、カンマと数字の繰り返しを許容
        // \s*$                 : 行末の空白

        // このパターンは、"1,2,3" や "1," や "1" をカバーします。
        // ただし、空行は除外する必要があります。
        String validPattern = "^\\s*(?:\\d+(?:,\\d+)*)(?:,\\d+)*\\s*$";
        Pattern pattern = Pattern.compile(validPattern);

        String line;
        while ((line = br.readLine()) != null) {
            String trimmedLine = line.trim();

            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            Matcher matcher = pattern.matcher(line);

            // パターンにマッチし、かつ行が空でないことを確認
            if (matcher.matches()) {
                validCount++;
            }
        }

        System.out.println("valid=" + validCount);
    }
}
