import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.IOException;

public class Main {
    public static void main(String[] args) {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;

        // 妥当な行数を数える
        String line;
        while ((line = br.readLine()) != null) {
            // 行の前後の空白を無視する
            String trimmedLine = line.trim();

            // 1. 空行の判定
            if (trimmedLine.isEmpty()) {
                continue;
            }

            // 2. 正規表現による妥当性の判定
            // 妥当なパターン: 1個以上の数字とカンマの組み合わせ。
            // 許容されるのは「1個以上の数字列がカンマで区切られて並んでいること」
            // これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれている必要がある。
            // パターン: (\d+,\s*)*\d+  -> 1つ以上の数字とカンマの組み合わせ。
            // より厳密に「カンマ区切りの整数列」を判定する。
            // 1個以上の数字とカンマの組み合わせで構成されているか、かつ数字が含まれていることを確認する。
            // 許容されるのは「1個以上の数字列がカンマで区切られて並んでいること」
            // 例: "1,2,3", "1,2,", "1"
            // 少なくとも1つの数字が含まれ、数字とカンマ以外は含まれない。
            
            // 正規表現の解説:
            // ^\s*             -> 行頭の空白（無視されるが、ここでは行全体をチェックするため、trimで処理済み）
            // (?:             -> 非キャプチャグループの開始
            //     \d+,\s*     -> 1つ以上の数字とカンマ、それに続く任意の空白（区切り）
            // )*              -> 上記のグループが0回以上繰り返される
            // \d+             -> 最後に1つ以上の数字が続く
            // (?:,\s*)?       -> 末尾のカンマと空白が任意（末尾のカンマは許容）
            // $               -> 行末
            
            // 仕様の再解釈: 「1 個以上の数字列がカンマで区切られて並んでいること」
            // これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを意味する。
            // 末尾のカンマは許容される。
            
            // パターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
            // 1. 数字とカンマのみで構成されていること: ^[\d,]*$
            // 2. 少なくとも1つの数字が含まれていること: (?=.*\d)
            // 3. 末尾のカンマは許容される。
            
            // 妥当な行のパターン: 
            // 1. 数字とカンマのみで構成される (数字とカンマ以外は含まれない)
            // 2. 少なくとも1つの数字が含まれている
            // 3. 末尾のカンマは許容される (例: "1,2," はOK)
            
            // 厳密に「カンマ区切りの整数列」を判定する正規表現:
            // 1. 少なくとも1つの数字が含まれていること。
            // 2. 数字とカンマ以外の文字が含まれていないこと。
            // 3. 末尾のカンマは許容される。
            
            // 試行: 
            // ^[\d,]*$ : 数字とカンマのみで構成されている。
            // (?=.*\d) : 数字が少なくとも1つ含まれている。
            // この2つを組み合わせることで、空行や数字以外の文字を含む行を除外できる。
            
            // ただし、行全体が「1個以上の数字列がカンマで区切られて並んでいる」ことを意味するため、
            // 区切り文字（カンマ）の存在も考慮する必要がある。
            
            // 妥当な行の定義を再確認:
            // "1,2,3" -> OK
            // "1," -> OK (末尾のカンマ許容)
            // "1" -> OK (1個の数字列)
            // "1,2,3," -> OK
            // "abc" -> NG
            // "1,a" -> NG
            // "" -> NG (空行は既に除外)
            
            // 妥当な行は、数字とカンマのみで構成され、かつ数字が少なくとも1つ含まれている。
            // 末尾のカンマは許容されるため、行の末尾がカンマで終わるか、数字で終わる必要がある。
            
            // パターン: 
            // ^[\d,]*$ : 数字とカンマのみで構成されている。
            // (?=.*\d) : 数字が少なくとも1つ含まれている。
            // このパターンは、"1,2," や "1" など、カンマ区切りの構造を許容する。
            
            // 念のため、行全体が数字とカンマのみで構成されていることを確認する。
            if (Pattern.matches("^[\d,]*$", trimmedLine) && Pattern.compile(trimmedLine).matcher(trimmedLine).find('\d').results().count() > 0) {
                // 少なくとも1つの数字が含まれていることを確認
                validCount++;
            }
        }

        // 結果の出力
        System.out.println("valid=" + validCount);
    }
}
