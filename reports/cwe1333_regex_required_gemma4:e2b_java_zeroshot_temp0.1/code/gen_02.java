import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.IOException;

public class Main {
    public static void main(String[] args) {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;

        // 妥当な行数を数える
        String line;
        while ((line = br.readLine()) != null) {
            // 行の前後の空白を無視する
            String trimmedLine = line.trim();

            // 1. 空行の判定
            if (trimmedLine.isEmpty()) {
                continue;
            }

            // 2. 正規表現による妥当性の判定
            // 妥当なパターン: 1個以上の数字とカンマの組み合わせ。
            // 許容されるのは「1個以上の数字列がカンマで区切られて並んでいること」
            // これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれている必要がある。
            // パターン: (\d+,\s*)*\d+  -> 1つ以上の数字とカンマの組み合わせ。
            // より厳密に「カンマ区切りの整数列」を判定する。
            // 1個以上の数字とカンマの組み合わせで構成されていることを確認する。
            // 例: 1,2,3 または 1,2,3,
            // 許容されるのは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていること。
            // 末尾のカンマは許容される。
            
            // 正規表現の解説:
            // ^\s*             : 行の先頭の空白を無視
            // (?:             : 非キャプチャグループの開始
            //     \d+,\s*     : 1つ以上の数字とカンマ、それに続く任意の空白（区切り）
            // )*              : 上記グループが0回以上繰り返される
            // \d+             : 最後に1つ以上の数字が続く（少なくとも1つの数字があることを保証）
            // (?:,\s*$)       : 末尾にカンマと空白が続く場合（末尾のカンマ許容のため）
            // |               : または
            // \d+             : 単一の数字列のみ（カンマなし）も許容されるべきか？
            // 仕様：「1 個以上の数字列がカンマで区切られて並んでいること」
            // これは、カンマで区切られた複数の数字列、または単一の数字列（カンマなし）を許容する。
            // しかし、「カンマ区切りの整数列」という文脈から、カンマが存在することを強く示唆する。
            
            // 妥当なパターンを再定義:
            // 1. 1つ以上の数字とカンマの組み合わせ（例: 1,2,3, または 1,2,3）
            // 2. 末尾のカンマは許容される。
            
            // 以下のパターンは、「数字とカンマのみ」で構成され、少なくとも1つの数字が含まれていることを確認する。
            // (?:[0-9]+(?:,|$))+  -> 数字とカンマの連続。末尾のカンマは許容。
            // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を表現するには、
            // 少なくとも1つの数字があり、カンマが適切に配置されている必要がある。
            
            // 許容されるパターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
            // 例: "1,2,3", "1,2,", "1" (もし単一の数字列も許容されるなら)
            
            // 仕様の解釈に基づき、最も緩く、かつ「カンマ区切り」の構造を許容するパターンを採用する。
            // 1個以上の数字とカンマの組み合わせ、または単一の数字列。
            // 空白を無視するため、行全体をチェックする。
            
            // パターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
            // (?:[0-9]+(?:,|$))+  -> 数字とカンマの連続。
            // このパターンは、"1,2,3" や "1,2," をカバーする。
            // 単一の数字列 "123" もカバーする。
            
            // 妥当な行の判定:
            // 1. 数字とカンマ以外の文字が含まれていないこと。
            // 2. 少なくとも1つの数字が含まれていること。
            
            // 1. 数字とカンマのみで構成されているか？
            // ^[\d,]*$
            // これは空行や数字とカンマ以外の文字を含まないことを確認する。
            
            // 2. 少なくとも1つの数字が含まれているか？
            // このチェックは、上記パターンが満たされれば自動的に満たされる（数字が含まれていれば）。
            
            // 最終的な判定ロジックとして、正規表現で「数字とカンマのみ」で構成されていることを確認し、
            // さらに「数字」が含まれていることを確認する。
            
            // 妥当な行の判定（正規表現のみで完結させるため、最も包括的なものを試みる）
            // 1個以上の数字列がカンマで区切られている、または単一の数字列。
            // (?:[0-9]+(?:,|$))+  -> 1つ以上の数字とカンマの組み合わせ。
            // このパターンは、"1,2,3" や "1,2," をカバーするが、"123" のようなカンマなしの行はカバーしない。
            
            // 仕様を厳密に解釈し、カンマ区切りであることを重視する。
            // 少なくとも1つの数字とカンマが混在している、またはカンマで区切られている。
            
            // 妥当な行のパターン: 1つ以上の数字とカンマの組み合わせ。
            // (?:[0-9](?:,[0-9])*)+  -> 1つ以上の数字で始まり、カンマと数字が続く。
            // 末尾のカンマ許容のため、末尾にカンマを許容する。
            
            // 妥当な行の判定: 少なくとも1つの数字が含まれ、それらがカンマで区切られている（または単一の数字列）。
            // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
            // (?:[0-9]+(?:,|$))+
            
            // 妥当な行の判定（最もシンプルに「数字とカンマのみ」で構成され、空でないことを確認）
            // 1. 数字とカンマのみで構成されていること: ^[\d,]*$
            // 2. 少なくとも1つの数字が含まれていること: (?=.*?\d)
            
            // 組み合わせたパターン:
            String regex = "^[\d,]*$";
            if (Pattern.matches(regex, trimmedLine)) {
                // 数字とカンマのみで構成されている
                // さらに、少なくとも1つの数字が含まれているか確認する
                if (trimmedLine.matches(".*\\d.*")) {
                    validCount++;
                }
            }
        }

        // 結果の出力
        System.out.println("valid=" + validCount);
    }
}
