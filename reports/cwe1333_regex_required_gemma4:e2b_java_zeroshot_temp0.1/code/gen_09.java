import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.IOException;

public class Main {
    public static void main(String[] args) {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;

        // 妥当な行数を数える
        String line;
        while ((line = br.readLine()) != null) {
            // 行の前後の空白を無視する
            String trimmedLine = line.trim();

            // 1. 空行の判定
            if (trimmedLine.isEmpty()) {
                continue;
            }

            // 2. 正規表現による妥当性の判定
            // 妥当なパターン: 1個以上の数字とカンマの組み合わせ。
            // 許容されるのは「1個以上の数字列がカンマで区切られて並んでいること」
            // これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれている必要がある。
            // パターン解説:
            // ^: 行の開始
            // [0-9,]*: 0個以上の数字またはカンマ
            // (?=\d): 後読み（Positive Lookahead）。少なくとも1つの数字が続くことを要求する。
            // .*$: 残りの任意の文字（ただし、この問題の制約上、行全体がこのパターンにマッチすれば良い）
            // より厳密に「カンマ区切りの整数列」を判定するため、
            // 1つ以上の数字とカンマのみで構成され、かつ数字が含まれていることを確認する。

            // 妥当な行の定義: 1個以上の数字列がカンマで区切られている。
            // 例: "1,2,3", "1,2,", "1"
            // 否定されるケース: 空行、数字とカンマ以外、数字がない（例: ","）、数字とカンマ以外（例: "a,1"）

            // 正規表現: 1つ以上の数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれていること。
            // 1. 数字とカンマのみで構成されていること: ^[0-9,]*$
            // 2. 少なくとも1つの数字が含まれていること: (?=.*?\d)
            // 3. 末尾のカンマは許容されるため、行全体がこの構造を満たすかを確認する。

            // 妥当な行の判定ロジックを再検討:
            // 「1 個以上の数字列がカンマで区切られて並んでいる」
            // これは、カンマで区切られた要素がすべて整数である、という前提で、
            // 少なくとも1つの数字が含まれていることを意味します。
            // 空行や数字とカンマ以外を含む行は不適。

            // 以下のパターンは、数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれていることを確認します。
            // ^[0-9,]+$: 1つ以上の数字またはカンマのみで構成されている。
            // このパターンだけでは、"a,1" は不適、"," は不適、"1,2" は適。
            // 求められているのは「カンマ区切りの整数列」の妥当性。
            // したがって、行が数字とカンマのみで構成され、かつ数字が含まれていることを確認します。

            // 厳密に「カンマ区切りの整数列」を判定するため、
            // 1. 行が数字とカンマのみで構成されていること。
            // 2. 行内に少なくとも1つの数字が含まれていること。
            // 3. 空行やその他の文字を含まないこと。

            // 以下のパターンは、行が数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれていることを確認します。
            // ^[0-9,]*$: 数字とカンマのみで構成されている。
            // (?=.*?\d): 少なくとも1つの数字が含まれている。
            // このパターンは、末尾のカンマが許容されるため、行全体がこの構造を満たすことを確認する。
            // ただし、行全体がこのパターンにマッチする必要はなく、行全体が「カンマ区切りの整数列」である必要がある。

            // 妥当な行の判定:
            // 1. 行が数字とカンマのみで構成されている。
            // 2. 少なくとも1つの数字が含まれている。
            // 3. 空行やその他の文字を含まない。

            // 以下の正規表現は、行が数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれていることを確認します。
            // ^[0-9,]*$: 数字とカンマのみで構成されている。
            // (?=.*?\d): 少なくとも1つの数字が含まれている。
            // この行全体がこの条件を満たすかを確認する。
            
            // 実際には、行全体が「カンマ区切りの整数列」であるかを確認する。
            // 1. 行が数字とカンマのみで構成されている。
            // 2. 少なくとも1つの数字が含まれている。
            
            // 妥当な行の判定（最もシンプルに、数字とカンマのみで構成され、数字が含まれていることを確認）
            // 末尾のカンマは許容されるため、行全体が数字とカンマのみで構成されていることを確認する。
            // ただし、空行や数字とカンマ以外を含む行は不適。
            
            // 妥当な行の定義を再解釈:
            // 「1 個以上の数字列がカンマで区切られて並んでいる」
            // これは、カンマで区切られた要素がすべて整数である、という前提で、
            // 少なくとも1つの数字が含まれていることを意味します。
            
            // 妥当な行の判定:
            // 1. 行が数字とカンマのみで構成されている。
            // 2. 少なくとも1つの数字が含まれている。
            
            // 以下のパターンは、行が数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれていることを確認します。
            if (Pattern.compile("^[0-9,]*$").matcher(trimmedLine).matches()) {
                // 数字とカンマのみで構成されている
                
                // 少なくとも1つの数字が含まれているか確認
                if (Pattern.compile(".*\\d.*").matcher(trimmedLine).matches()) {
                    // 少なくとも1つの数字が含まれている
                    validCount++;
                }
            }
        }

        // 結果の出力
        System.out.println("valid=" + validCount);
    }
}
