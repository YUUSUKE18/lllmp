import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン: 
            // ^\s*          -> 行頭の任意の空白
            // (?:[0-9]+,\s*)* -> 1つ以上の (数字 + カンマ + 任意の空白) の繰り返し
            // [0-9]+       -> 最後の数字列
            // (?:,\s*|$)    -> カンマと空白、または行末
            // \s*$         -> 行末の任意の空白
            // このパターンは「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するのに複雑になるため、
            // よりシンプルに「数字とカンマのみで構成され、空行でないこと」をチェックし、
            // 妥当性の定義（1個以上の数字列がカンマで区切られている）を正規表現で表現します。

            // 妥当性の定義: 1個以上の数字列がカンマで区切られて並んでいる。末尾のカンマは許容。
            // 例: "1,2,3" または "1,2,"
            // 数字とカンマのみで構成され、空行でないこと。

            // 1. 空行チェック (行が空または空白のみの場合)
            if (line.trim().isEmpty()) {
                continue;
            }

            // 2. 数字とカンマのみで構成されているかチェック
            // パターン: 1つ以上の数字とカンマの組み合わせ。末尾にカンマがあっても良い。
            // ^\s*             -> 行頭の空白
            // (?:[0-9]+,\s*)*  -> 1つ以上の (数字 + カンマ + 空白) の繰り返し
            // [0-9]+           -> 最後の数字列
            // (?:,\s*|$)       -> カンマと空白、または行末
            // \s*$            -> 行末の空白
            
            // より簡潔に、行が数字とカンマのみで構成されているかを確認し、
            // 少なくとも1つの数字が含まれていることを確認します。
            
            // 妥当な行のパターン: 
            // 1つ以上の数字列がカンマで区切られている。
            // 例: "1,2,3", "1,"
            // 否定的な条件: 数字とカンマ以外の文字が含まれている、または完全に空行である。

            // 以下の正規表現は、行が数字とカンマのみで構成されていることを確認します。
            // ^\s*             -> 行頭の空白
            // (?:[0-9]+(?:,\s*[0-9]+)*) -> 1つ以上の数字列とカンマの組み合わせ (例: 1,2,3)
            // (?:,\s*|$)       -> 最後のカンマと空白、または行末
            // \s*$            -> 行末の空白
            
            // 妥当な行の判定ロジックを再考します。
            // 「1個以上の数字列がカンマで区切られて並んでいる」
            // これは、カンマで区切られた要素がすべて整数である、という条件に集約されます。
            
            // 1. 行が空でないこと (既にチェック済み)
            // 2. 行に含まれるすべてのトークンが整数であること。
            
            // 簡易的なチェックとして、行をカンマで分割し、すべてが整数であるかを確認します。
            String[] parts = line.split(",");
            boolean isValid = true;
            
            if (parts.length == 0) {
                // これは行が空でないのに分割で0になることは通常ないが、念のため
                isValid = false;
            } else {
                for (String part : parts) {
                    // 末尾のカンマや空白のみの要素は空文字列になる可能性があるため、trim()してチェック
                    if (part.trim().isEmpty()) {
                        // 末尾のカンマや連続するカンマによる空要素は許容されるが、
                        // 妥当な行は「1個以上の数字列がカンマで区切られている」ため、
                        // 空要素が連続して存在しても、数字列が少なくとも1つあれば妥当と見なす。
                        // ただし、「数字とカンマ以外を含む行は妥当ではない」という制約があるため、
                        // 空要素が混在する場合は注意が必要。
                        continue;
                    }
                    try {
                        Integer.parseInt(part.trim());
                    } catch (NumberFormatException e) {
                        // 数字とカンマ以外を含む行は妥当ではない
                        isValid = false;
                        break;
                    }
                }
            }

            if (isValid) {
                // 1個以上の数字列がカンマで区切られているか、または数字のみの行も許容されるか？
                // 仕様: 「1 個以上の数字列がカンマで区切られて並んでいることです。」
                // これは、少なくとも1つの数字列が存在し、それらがカンマで区切られていることを意味します。
                // 例: "1" は1個の数字列だが、カンマで区切られていない。
                // 例: "1," は1個の数字列がカンマで区切られている。
                
                // 妥当な行は、少なくとも1つの数字列が含まれていれば良い。
                // 上記のループでisValidがtrueになった場合、少なくとも1つの数字列が存在したことになる。
                validLines++;
            }
        }

        System.out.println("valid=" + validLines);
    }
}
