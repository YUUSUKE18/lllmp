import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン: 
            // ^\s*          -> 行の先頭の空白を無視
            // (?:[0-9]+,\s*)* -> 1つ以上の数字とカンマのグループ（数字とカンマの間に空白があっても良い）
            // [0-9]+        -> 最後の数字列
            // (?:,\s*|$)    -> カンマと空白、または行末
            // $             -> 行末
            // 
            // よりシンプルに、カンマ区切りの整数列が1つ以上存在し、それ以外に数字やカンマ以外の文字がないことを確認する。
            // 妥当な形式: 1個以上の数字とカンマの組み合わせ、末尾にカンマがあっても良い。
            // 
            // 妥当なパターン: 
            // ^\s*             -> 行頭の空白
            // (?:[0-9]+,\s*)*  -> 0回以上、数字とカンマのペア（数字の後にカンマと空白）
            // [0-9]+           -> 少なくとも1つの数字列
            // (?:,\s*|$)       -> カンマと空白、または行末
            // \s*$            -> 行末の空白
            
            // 課題の要件を再解釈: 「1 個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容する。」
            // これは、行が数字とカンマのみで構成されており、少なくとも1つの数字が含まれていることを意味します。
            // 空行は妥当ではない。数字とカンマ以外は許容されない。
            
            // パターン: 
            // ^\s*             -> 行頭の空白
            // (?:[0-9]+,\s*)*  -> 0回以上の (数字 + カンマ + 空白) の繰り返し
            // [0-9]+           -> 少なくとも1つの数字列
            // (?:,\s*|$)       -> カンマと空白、または行末
            // \s*$            -> 行末の空白
            
            // より簡潔に、行が数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
            // 妥当な行は、数字とカンマのみで構成され、空行ではない。
            // 
            // 妥当な行の定義: 
            // 1. 行が空でない。
            // 2. 行に含まれる文字が、数字、カンマ、空白のみである。
            // 3. 行に少なくとも1つの数字が含まれている。
            
            // 正規表現で「数字とカンマのみ」かつ「少なくとも1つの数字」をチェックする。
            // この課題の意図を最も満たすのは、行が数字とカンマのシーケンスで構成されていることです。
            // 例: "1,2,3" や "1," や ",1" は妥当。空行は不妥当。
            
            // 妥当な行の判定ロジックを正規表現で実装します。
            // 妥当な行は、数字とカンマのみで構成され、空行ではない。
            // 
            // 妥当な行のパターン: 
            // ^\s*             -> 行頭の空白
            // [0-9,]*          -> 数字とカンマのみ
            // \s*$            -> 行末の空白
            // 
            // このパターンだけでは、"abc" や "," は許容されてしまうため、数字の存在を保証する必要があります。
            
            // 最終的な判定: 行が空でなく、かつ、その行が数字とカンマのみで構成されていることを確認します。
            // 
            // 妥当な行のパターン: 
            // ^\s*             -> 行頭の空白
            // [0-9,]*          -> 数字とカンマのみ（0個以上）
            // \s*$            -> 行末の空白
            // 
            // このパターンは、"abc" や "," も許容してしまうため、数字の存在を明示的にチェックする必要があります。
            
            // 妥当な行の判定（最も厳密に「カンマ区切りの整数列」を意味するものとして）
            // 1. 行が空でない。
            // 2. 行に含まれる文字が、数字、カンマ、空白のみである。
            // 3. 行に少なくとも1つの数字が含まれている。
            
            // 課題の意図を「数字とカンマのみで構成され、少なくとも1つの数字が含まれている」と解釈し、正規表現で判定します。
            // 
            // パターン: ^\s*([0-9,]+)\s*$
            // これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
            
            String regex = "^\\s*([0-9,]+)\\s*$";
            Matcher matcher = Pattern.compile(regex).matcher(line);
            
            if (matcher.matches()) {
                // 念のため、数字が少なくとも1つ含まれていることを確認（[0-9,]+ は数字とカンマのシーケンスを意味するため、数字が含まれていることが保証される）
                validLines++;
            }
        }

        System.out.println("valid=" + validLines);
    }
}
