import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン: 
            // ^\s*       -> 行頭の任意の空白
            // (?:[0-9]+,\s*)* -> 1つ以上の数字とカンマのグループ（数字とカンマの間に空白があっても良い）
            // [0-9]+     -> 最後の数字列
            // (?:,\s*|$)  -> カンマと空白、または行末
            // $          -> 行末
            // 
            // よりシンプルに、1つ以上の数字とカンマの組み合わせ、および末尾のカンマを許容するパターンを考える。
            // 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」こと。
            // これは、数字とカンマが混在し、少なくとも1つの数字が含まれている必要がある。
            // 末尾のカンマは許容される。
            
            // パターン解説:
            // ^\s*             : 行頭の空白
            // (?:[0-9]+,\s*)*  : 0個以上の「数字 + カンマ + 空白」の繰り返し
            // [0-9]+           : 少なくとも1つの数字
            // (?:,\s*|$)       : カンマと空白、または行末
            // \s*$            : 行末の空白
            
            // 課題の要件を再解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
            // 例: "1,2,3" (OK), "1," (OK), "," (NG), "" (NG)
            // 空行はNG。数字とカンマ以外を含む行はNG。
            
            // 妥当な行の判定ロジックを正規表現で表現する。
            // 1. 行が完全に空でないこと。
            // 2. 行が数字とカンマのみで構成されていること。
            // 3. 少なくとも1つの数字が含まれていること。
            
            // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字を含むことを確認する。
            // ^\s*             : 行頭の空白
            // (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ（例: 1,2,3, または 1,）
            // \s*$            : 行末の空白
            
            // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックする。
            // 少なくとも1つの数字が含まれ、数字とカンマ以外の文字が含まれていない。
            // 末尾のカンマは許容される。
            
            // 妥当な行のパターン: 
            // 1. 数字とカンマのみで構成されている。
            // 2. 少なくとも1つの数字が含まれている。
            // 3. 末尾がカンマで終わるか、数字で終わる。
            
            // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字を含むことを確認する。
            // (?:[0-9]+(?:,\s*[0-9]+)*) は、数字とカンマのシーケンスを表現する。
            // 末尾のカンマを許容するため、最後の要素が数字で終わるか、カンマで終わることを許容する。
            
            // 妥当な行の判定: 
            // 1. 行が空でない。
            // 2. 行に含まれる文字が、数字、カンマ、空白のみである。
            // 3. 行に少なくとも1つの数字が含まれている。
            
            // 正規表現で「数字とカンマのみ」かつ「少なくとも1つの数字を含む」ことをチェックする。
            // ^\s*             : 行頭の空白
            // (?:[0-9,]*[0-9])? : 任意の文字の後に数字が続く（少なくとも1つの数字を含むことを試みる）
            // .*              : 残りの文字（カンマや空白など）
            // $               : 行末
            
            // 課題の制約を最も満たすのは、行が「数字とカンマ」で構成され、かつ「数字」が含まれていること。
            // 末尾のカンマは許容される。
            
            // 妥当な行のパターン: 
            // ^\s*             : 行頭の空白
            // (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ（例: 1,2,3, または 1,）
            // \s*$            : 行末の空白
            
            // このパターンは、数字とカンマのみで構成され、少なくとも1つの数字を含むことを保証する。
            String pattern = "^\\s*(?:[0-9]+(?:,\\s*[0-9]+)*)[,\\s]*$";
            
            // 実際には、行全体が数字とカンマのみで構成され、かつ数字が含まれているかを確認する。
            // 末尾のカンマを許容するため、行の末尾がカンマで終わるか、数字で終わることを許容する。
            
            // 最終的な判定ロジック:
            // 1. 行が空でない。
            // 2. 行に含まれる文字が数字、カンマ、空白のみ。
            // 3. 行に少なくとも1つの数字が含まれている。
            
            boolean isValid = false;
            if (!line.trim().isEmpty()) {
                // 数字とカンマ以外の文字が含まれていないかチェック
                boolean containsOnlyDigitsAndCommas = true;
                for (int i = 0; i < line.length(); i++) {
                    char c = line.charAt(i);
                    if (!((c >= '0' && c <= '9') || c == ',' || Character.isWhitespace(c))) {
                        containsOnlyDigitsAndCommas = false;
                        break;
                    }
                }

                if (containsOnlyDigitsAndCommas) {
                    // 少なくとも1つの数字が含まれているかチェック
                    boolean containsDigit = false;
                    for (int i = 0; i < line.length(); i++) {
                        if (Character.isDigit(line.charAt(i))) {
                            containsDigit = true;
                            break;
                        }
                    }
                    if (containsDigit) {
                        // 妥当な行としてカウント
                        validLines++;
                    }
                }
            }
        }

        System.out.println("valid=" + validLines);
    }
}
