import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン: 
            // ^\s*       -> 行の先頭の空白を無視
            // (?:[0-9]+,\s*)* -> 1つ以上の数字とカンマの組み合わせ（カンマ区切りの整数列）が0回以上繰り返される
            // [0-9]+     -> 少なくとも1つの数字が存在すること
            // .*         -> 残りの文字（末尾のカンマなども含む）
            // $          -> 行の終わり
            // このパターンは「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するのではなく、
            // 「数字とカンマのみで構成され、少なくとも1つの数字が含まれている」ことを確認するのに適しています。
            // 仕様の「1 個以上の数字列がカンマで区切られて並んでいる」を厳密に解釈し、
            // 「数字とカンマのみで構成され、少なくとも1つの数字が含まれている」ことを確認します。
            // 末尾のカンマは許容されます。

            // 妥当性の判定ロジックを再考します。
            // 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」ことです。
            // これは、行内に数字とカンマのみが含まれ、かつ数字が少なくとも1つ存在することを意味します。
            // 空行は妥当ではありません。
            // 数字とカンマ以外を含む行は妥当ではありません。

            // 正規表現: 
            // ^\s*             -> 行頭の空白
            // (?:[0-9]+,\s*)*   -> 0個以上の (数字 + カンマ + 空白) の繰り返し
            // [0-9]+           -> 少なくとも1つの数字
            // .*               -> 残りの文字（末尾のカンマなど）
            // $                -> 行末
            // このパターンは複雑になるため、より単純に「数字とカンマのみ」で構成され、「数字」が含まれているかをチェックします。

            // 1. 行をトリムして、数字とカンマのみで構成されているかチェック
            String trimmedLine = line.trim();
            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 2. 正規表現で数字とカンマのみで構成されているかチェック
            // パターン: 数字とカンマのみで構成されていること。末尾のカンマは許容。
            // ^[0-9,]*$ : 数字とカンマのみで構成されている
            // ただし、これは「1個以上の数字列がカンマで区切られて並んでいる」という条件を満たしません。

            // 3. 1個以上の数字列がカンマで区切られていることを確認する
            // 少なくとも1つの数字が含まれており、数字とカンマ以外は含まれていないことを確認します。
            // 妥当な行の例: "1,2,3", "1,2,"
            // 不妥当な行の例: "abc", "1,a", "", "1,,2" (これは数字列の区切りが不適切)

            // 妥当な行の定義を「数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれている」と解釈します。
            // 末尾のカンマは許容されます。
            // したがって、行全体が数字とカンマのみで構成されていることを確認します。
            // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を正規表現で表現するのは困難なため、
            // 「数字とカンマのみで構成され、かつ数字が含まれている」という条件で判定します。

            // パターン: 数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれている
            // ^\s*             -> 行頭の空白
            // [0-9,]*          -> 数字とカンマのみ
            // [0-9]            -> 少なくとも1つの数字が含まれている
            // [0-9,]*          -> その後に数字とカンマが続く
            // $                -> 行末

            // 最もシンプルな解釈: 行が数字とカンマのみで構成され、かつ数字が1つ以上あること。
            // 末尾のカンマは許容されるため、行の末尾がカンマで終わるか、数字で終わるか、カンマで終わるかのいずれか。

            // 妥当な行の例: "1,2,3", "1,2,"
            // 不妥当な行の例: "abc", "", "1,,2" (これは数字列の区切りが不適切)

            // 妥当な行の判定: 行が数字とカンマのみで構成され、かつ、カンマで区切られた数字列が存在すること。
            // 以下のパターンは、数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれていることを確認します。
            // (?:[0-9]+(?:,.*)?)+ : 1つ以上の数字列が続くことを試みる
            
            // 最終的な判定として、行をカンマで分割し、各要素が数字であることを確認します。
            // ただし、末尾のカンマは許容されるため、split(",")の結果をチェックします。

            String[] parts = line.trim().split(",");
            boolean isValid = false;

            if (parts.length > 0) {
                // 少なくとも1つの要素がある
                // 各要素が空でないか、または数字のみで構成されているかを確認する
                // 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」
                // これは、splitの結果、空でない要素が少なくとも1つ存在し、それらがすべて数字である、ということを意味します。
                
                // 1. 空行は除外済み。
                // 2. 数字とカンマ以外を含む行は除外。
                // 3. 1個以上の数字列がカンマで区切られている。

                // 妥当な行の例: "1,2,3" -> parts = ["1", "2", "3"] (3個の数字列)
                // 妥当な行の例: "1,2," -> parts = ["1", "2", ""] (3個の要素。最後の要素が空)
                
                // 妥当な行の定義を「split(",")で得られた要素のうち、数字としてパースできるものが1つ以上存在すること」とします。
                
                int numberCount = 0;
                for (String part : parts) {
                    if (!part.trim().isEmpty()) {
                        try {
                            Integer.parseInt(part.trim());
                            numberCount++;
                        } catch (NumberFormatException e) {
                            // 数字以外が含まれている場合、この行は不妥当
                            isValid = false;
                            break;
                        }
                    }
                }
                
                if (isValid && numberCount >= 1) {
                    // 少なくとも1つの数字列が存在し、それ以外は数字とカンマのみで構成されていると仮定する。
                    // このロジックでは、"1,,2" のような不正な区切りも許容してしまう可能性があるため、
                    // 正規表現による厳密なチェックに戻ります。
                    
                    // 正規表現による厳密なチェック（数字とカンマのみで構成され、数字が1つ以上存在すること）
                    // ^\s*([0-9,]+)\s*$ : 数字とカンマのみで構成され、数字が含まれていることを確認
                    // このパターンは、"1,2," や "1,2,3" はマッチしますが、"a,1" はマッチしません。
                    
                    // 妥当な行の判定を、行全体が数字とカンマのみで構成され、かつ数字が含まれていることとします。
                    // 末尾のカンマは許容されるため、行の末尾がカンマで終わるか、数字で終わるか、カンマで終わるかのいずれか。
                    
                    // 最終的な判定として、行全体が数字とカンマのみで構成されていることを確認します。
                    // 1. 行をトリム
                    // 2. 正規表現で数字とカンマのみで構成されているかチェック
                    // 3. 少なくとも1つの数字が含まれているかチェック
                    
                    // 妥当な行の例: "1,2,3" -> OK
                    // 不妥当な行の例: "abc" -> NG
                    // 不妥当な行の例: "1,a" -> NG
                    // 不妥当な行の例: "" -> NG (空行は既に除外)
                    // 不妥当な行の例: "1,,2" -> NG (これは数字列の区切りが不適切)
                    
                    // 妥当な行の定義を「カンマで区切られた要素がすべて整数であり、少なくとも1つの要素が存在すること」とします。
                    // この場合、split(",")で得られた要素がすべて整数である必要があります。
                    
                    boolean allPartsAreIntegers = true;
                    for (String part : parts) {
                        if (!part.trim().isEmpty()) {
                            try {
                                Integer.parseInt(part.trim());
                            } catch (NumberFormatException e) {
                                allPartsAreIntegers = false;
                                break;
                            }
                        }
                    }
                    
                    if (allPartsAreIntegers && numberCount >= 1) {
                        validLines++;
                    }
                }
            }
        }

        System.out.println("valid=" + validLines);
    }
}
