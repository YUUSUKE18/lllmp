import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン: 
            // ^\s*       -> 行の先頭の空白を無視
            // (?:[0-9]+,\s*)* -> 1つ以上の数字とカンマの組み合わせ（カンマ区切りの整数列）が0回以上繰り返される
            // [0-9]+     -> 少なくとも1つの数字が存在すること
            // .*         -> 残りの文字（末尾のカンマなども含む）
            // $          -> 行の終わり
            // 
            // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
            // 以下のパターンで「数字とカンマのみ」で構成されているかを確認し、
            // さらに「1個以上の数字」が含まれていることを確認します。
            
            // 妥当な行の判定ロジックを正規表現で表現します。
            // 1. 行が空でないこと (trim()でチェック)
            // 2. 行が数字とカンマのみで構成されていること
            // 3. 少なくとも1つの数字が含まれていること
            
            String trimmedLine = line.trim();
            
            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 正規表現: 
            // ^\s*             -> 行頭の空白
            // (?:[0-9]+,\s*)*  -> 0回以上の (数字 + カンマ + 空白) の繰り返し
            // [0-9]+           -> 少なくとも1つの数字
            // .*              -> 残りの文字（末尾のカンマなど）
            // $               -> 行末
            
            // 妥当な形式: 1個以上の数字列がカンマで区切られている。末尾のカンマは許容。
            // これは、数字とカンマのみで構成され、かつ数字が少なくとも1つ含まれていることを意味します。
            // 例: "1,2,3" または "1,2," または "1"
            
            // パターン解説:
            // ^\s*                  : 行頭の空白
            // (?:[0-9]+,\s*)*        : 0回以上の (数字 + カンマ + 空白) の繰り返し
            // [0-9]+                : 少なくとも1つの数字
            // .*                    : 残りの任意の文字（末尾のカンマなど）
            // $                     : 行末
            
            // よりシンプルに、行が数字とカンマのみで構成され、かつ数字が含まれていることを確認します。
            // 妥当な行は、数字とカンマのみで構成され、かつ数字が1つ以上含まれている。
            // 末尾のカンマは許容されるため、行全体が数字とカンマで構成されていることを確認します。
            
            // 妥当な行の定義: 
            // 1. 数字とカンマ以外の文字を含まない (数字とカンマのみ)
            // 2. 少なくとも1つの数字を含む
            
            // 1. 数字とカンマのみで構成されているか (末尾のカンマも許容)
            // ^\s*[\d,]*$ 
            // このパターンは、"1,2," や "123" はマッチしますが、"a1,2" はマッチしません。
            
            // 2. 少なくとも1つの数字を含むか (これは上記パターンに含まれている)
            
            // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を表現するには、
            // 最初の数字と最後の数字の間がカンマで区切られている構造をチェックする必要があります。
            
            // 簡略化された解釈に基づき、行が数字とカンマのみで構成され、かつ数字が含まれていることを確認します。
            // 課題の意図を最も満たすのは、行が数字とカンマのみで構成されていることです。
            
            // 妥当な行の判定: 
            // 行が空でなく、数字とカンマ以外の文字を含まないこと。
            // (末尾のカンマは許容されるため、行全体が数字とカンマのみで構成されていることを確認)
            
            // 妥当な行の判定を正規表現で表現します。
            // ^\s*[\d,]*$ : 行が数字とカンマのみで構成されている。
            // このパターンは、"1,2," や "123" はマッチしますが、"1,a,2" はマッチしません。
            
            // 妥当な行の判定: 
            // 1. 行が空でない (既にチェック済み)
            // 2. 行が数字とカンマのみで構成されている。
            
            // 妥当な行の判定を正規表現で実行
            Pattern pattern = Pattern.compile("^\\s*([0-9,]*)\\s*$");
            Matcher matcher = pattern.matcher(line);
            
            if (matcher.matches()) {
                // 数字とカンマのみで構成されている。
                // さらに、少なくとも1つの数字が含まれているか確認する。
                boolean containsDigit = false;
                for (char c : line.toCharArray()) {
                    if (Character.isDigit(c)) {
                        containsDigit = true;
                        break;
                    }
                }
                if (containsDigit) {
                    validLines++;
                }
            }
        }

        System.out.println("valid=" + validLines);
    }
}
