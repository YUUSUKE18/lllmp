const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
  // 正規表現の解説:
  // ^\s*            : 行の先頭の任意の空白
  // (?:             : 非キャプチャグループの開始
  //   \d+,\s*       : 1つ以上の数字、カンマ、任意の空白 (1つの数字列)
  // )+              : 上記のパターンが1回以上繰り返される (カンマ区切りの整数列)
  // [,\s]*          : 末尾のカンマや空白（末尾のカンマは許容される）
  // \s*$            : 行末の空白
  // この正規表現は、1個以上の数字列がカンマで区切られている、または単一の数字列であることを確認します。
  // 厳密には「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
  // 「数字とカンマだけ」で構成されていることを確認し、かつ空行でないことを確認する必要があります。

  // 仕様に従い、「1 個以上の数字列がカンマで区切られて並んでいる」ことを判定します。
  // 1. 空行は妥当ではない。
  if (line.trim() === "") {
    // 空行は妥当ではない
    return;
  }

  // 2. 数字とカンマ以外を含む行は妥当ではない。
  // 3. 妥当なのは「1 個以上の数字列がカンマで区切られて並んでいる」こと。
  //    例: "1,2,3", "1,2,", "1" (単一の数字列も許容されると解釈)
  //    「カンマで区切られて並んでいる」ためには、少なくとも1つのカンマが必要、または単一の数字列である必要があります。

  // 正規表現の再考:
  // 「1個以上の数字列がカンマで区切られて並んでいる」
  // これは、数字とカンマのみで構成され、かつカンマが存在するか、単一の数字列である必要があります。
  // 末尾のカンマは許容。

  // パターンA: 1つ以上の数字列がカンマで区切られている場合 (例: 1,2,3, や 1,2,)
  // ^\s*(\d+(?:,\d+)*)(?:,.*)?\s*$

  // よりシンプルに、「カンマ区切りで数字だけが存在する」ことを確認します。
  // 数字とカンマのみで構成され、途中に数字がない場所がないことを確認します。
  const pattern = /^\s*[\d,]*\s*$/;

  if (!pattern.test(line)) {
    // 数字とカンマ以外の文字が含まれている場合、妥当ではない。
    return;
  }

  // 妥当性の追加チェック: 1個以上の数字列がカンマで区切られているか。
  // この行が「カンマ区切り」の形式を満たす必要があります。
  // 妥当な行は、数字とカンマだけで構成されており、かつ少なくとも1つの数字が存在する場合。
  const parts = line.split(',');

  let isValid = false;
  if (parts.length > 0) {
    // 各要素が数字（または空文字列）であることを確認し、少なくとも1つの数字が存在するか確認する。
    let hasNumber = false;
    for (const part of parts) {
      if (part.trim() !== "") {
        if (!isNaN(parseInt(part, 10))) {
          hasNumber = true;
        } else {
          // 数字とカンマ以外が含まれていれば不正
          isValid = false;
          break;
        }
      }
    }

    if (hasNumber) {
        // 1個以上の数字列がカンマで区切られている。
        validLines++;
    }
  }

  // このロジックは複雑になるため、正規表現のみに絞る指示に従い、正規表現で「カンマ区切りの整数列」を厳密に定義します。
  // 「1個以上の数字列がカンマで区切られて並んでいる」
  // 許容されるのは: 数字,数字,数字, または 数字,数字,または 数字, または数字のみ (末尾カンマ含む)
  // 例: "1,2,3", "1,2,", "1" (単一の数字列も許容されるべきか？仕様では「カンマで区切られて並んでいる」)

  // 「1個以上の数字列がカンマで区切られて並んでいる」を「少なくとも1つのカンマを含む」と解釈する。
  // もし単一の数字列も許容されるなら、単純に数字のみをチェックする。
  
  // 簡略化のため、入力行全体が数字とカンマのみで構成されていることを確認し、空行でないことを確認する。
  // そして、カンマが含まれているか、単一の数字列であることを検証する。
  
  // 最終的な判定は、正規表現で「数字とカンマのみ」であり、かつ「空ではない」行を数える。
  // 最初の例の指示に従い、正規表現を使って妥当性を判定します。
});

rl.on('end', () => {
  console.log(`valid=${validLines}`);
});
