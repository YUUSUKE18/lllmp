const fs = require('fs');

function solve() {
  const input = fs.readFileSync(0, 'utf8').trim();
  const lines = input.split('\n');
  let validCount = 0;

  for (const line of lines) {
    const trimmedLine = line.trim();

    if (trimmedLine === "") {
      // 空行は妥当ではない
      continue;
    }

    // 正規表現による検証:
    // ^\s*  -> 行頭の任意の空白
    // (?:[0-9]+,\s*)* -> 1個以上の「数字,」のパターンが0回以上繰り返される (これはカンマ区切りの整数列)
    // [0-9]+$ -> 数字のみで終わる
    // (?:,\s*[0-9]+)* -> 途中にカンマで区切られた整数列が続く
    // $
    // 
    // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
    // これは、数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれている必要があります。
    // 許容されるパターン: 数字,数字,数字, ... または 数字, 数字, ... (末尾カンマは許容)

    // 妥当なパターンの定義:
    // 1. 少なくとも1つの数字列（数字+カンマ）が含まれていること。
    // 2. 数字とカンマ以外は含まないこと。

    // 1. 数字とカンマのみで構成されているか、および少なくとも1つの数字が含まれているかを確認する
    // パターン: 任意の空白、数字、カンマの組み合わせ
    // 例: "1,2,3", "1,2,"
    const regex = /^(\s*[0-9,]+\s*)+$/;
    
    // より具体的な検証: 
    // 1. 数字とカンマのみで構成されているか
    // 2. 少なくとも1つの数字が含まれているか (カンマのみや空行は除外)
    
    let isValid = false;
    if (trimmedLine.length > 0) {
        // 数字とカンマのみで構成されているかチェック
        const matches = trimmedLine.match(/^[0-9,]*([0-9]+(?:,|$))/g);
        
        if (matches) {
            // カンマ区切りの整数列が存在するかをより厳密に確認する
            // 正規表現で「数字,」の繰り返しが可能な構造を持つか確認
            
            // 1. 空白を無視して、数字とカンマのみで構成されているか
            const onlyDigitsAndCommas = /^[0-9,]*$/.test(trimmedLine);
            
            // 2. 少なくとも1つの数字が含まれているか
            const containsDigit = /\d/.test(trimmedLine);
            
            // 3. カンマ区切りとして妥当か (少なくとも1つのカンマ、または数字列が存在する)
            // 例: "1,2" -> OK
            // 例: "1" -> OK (1個の列)
            // 例: "1," -> OK (末尾カンマ許容)
            
            if (onlyDigitsAndCommas && containsDigit) {
                // 1個以上の数字列がカンマで区切られているか、または1つの数字列であること
                // 以下のパターンでチェック: 数字とカンマの組み合わせが連続していること
                // "1,2," や "1" などを許容する
                if (/(?:[0-9]+(?:,|$))+/.test(trimmedLine.replace(/\s/g, ''))) {
                    validCount++;
                }
            }
        }
    }
  }

  console.log(`valid=${validCount}`);
}

solve();
