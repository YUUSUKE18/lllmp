process.stdin.on("data", (data: Buffer) => {
  const line = data.toString().trim();
  if (line === "") {
    // 空行は妥当ではない (1個以上の数字列がカンマで区切られている必要があるため)
    // ただし、仕様を再確認すると「1 個以上の数字列がカンマで区切られて並んでいること」が妥当の定義。
    // 空行はこれに該当しないため不妥当。
  } else {
    // 正規表現: カンマで区切られた整数列（末尾のカンマも許容）
    // ^\s*             : 行頭の空白（無視）
    // (?:            : 非キャプチャグループ開始
    //   \d+(,\d+)*  : 1つ以上の数字とカンマの組み合わせ（例: 1,2,3, または 1,2,3,）
    // )
    // \s*$            : 行末の空白（無視）

    // 妥当なパターン: 1つ以上の数字とカンマの組み合わせがあり、それが一行全体を構成する。
    // (数字とカンマが1回以上続く) という構造をチェックする。
    // 最小の妥当なパターンは "1" または "1,2" など。
    // 末尾のカンマは許容される。
    // 数字とカンマのみで構成され、少なくとも1つの数字が存在すること。

    const regex = /^\s*(?:(?:\d+(?:,\d+)*)(?:,)?)*\s*$/;

    // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックするために、
    // 1つ以上の数字とカンマの組み合わせが存在することをチェックする。
    // 許容される形式の例: "1,2,3", "1,2,"
    // 否定される形式の例: "", "a,b", "1,2,a"

    // 正規表現の再設計: 1つ以上の数字とカンマのみで構成されているか、かつ数字が含まれているか。
    // \d+(?:,\d+)* : 少なくとも1つの数字から始まり、カンマと数字を繰り返す。
    // (?:,\d+)* : カンマと数字のペアが0回以上続く。
    // (?:,\d+)? : 末尾のカンマを許容する場合。

    // 「1 個以上の数字列がカンマで区切られて並んでいる」を厳密に表現するには、
    // 少なくとも1つの数字が存在し、カンマで区切られている（またはカンマがない）必要がある。

    // 妥当な文字列の例: "1", "1,2", "1,2,"
    // 不妥当な文字列の例: "", "a", "1a"

    // 1. 数字とカンマのみで構成されていることを確認する
    if (!/^[0-9,]*$/.test(line)) {
      // 数字とカンマ以外を含む行は不妥当
    } else {
      // 2. 少なくとも1つの数字が含まれていることを確認する (例: "," や ",," は含まれない)
      if (/\d/.test(line)) {
        // 3. カンマのルールをチェックする。末尾のカンマは許容される。
        // 許容される構造は、数字で始まり、カンマで区切られている。
        // \d+(?:,\d+)* ： 1つ以上の数字がカンマで区切られている形式（末尾カンマは許容される）
        // または \d+ ： 単一の数字（カンマなし）
        const validPattern = /^(\d+(?:,\d+)*)(?:,)?$/;

        // 末尾のカンマを許容しつつ、数字列が存在することをチェックする。
        // 例: "1,2,3" -> OK
        // 例: "1,2," -> OK
        // 例: "1" -> OK (上記のパターンは"1"はパスしないため、単一の数字も考慮する必要がある)

        // 最もシンプルな解釈：カンマ区切りで、少なくとも1つの数字が存在する。
        // 形式: (数字 + カンマ) の繰り返し、または 単一の数字。末尾のカンマは許容。
        const check = /^(?:\d+(?:,\d+)*|\d+)$/;

        // 上記のパターンで、行全体がこの形式に一致するかチェックする。
        // (このパターンは "1" や "1,2" は通るが、空行は通らない)
        if (check.test(line)) {
          // 妥当な行としてカウント
        }
      }
    }
  }
});

