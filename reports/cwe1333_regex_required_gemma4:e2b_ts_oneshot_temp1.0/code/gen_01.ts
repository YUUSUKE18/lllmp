const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validCount = 0;

rl.on('line', (line) => {
  // 行の前後の空白を無視
  const trimmedLine = line.trim();

  // 正規表現による妥当性の判定
  // 妥当なパターン: 1個以上の数字がカンマで区切られている。末尾のカンマも許容。
  // ^\s*      : 行頭の任意の空白
  // (?:      : 非キャプチャグループ
  //   \d+    : 1つ以上の数字
  //   ,      : カンマ
  // )*       : 上記グループが0回以上繰り返される（数字が1つだけの場合など）
  // (?:,\d+)? : 最後の要素がカンマと数字で終わる、というパターンを許容するため
  // $        : 行末
  //
  // よりシンプルに、「カンマ区切りの整数列」を判定する。
  // 1. 数字とカンマのみで構成されていること。
  // 2. 1個以上の数字が含まれていること。
  // 3. 末尾のカンマは許容されること。

  // 正規表現の意図：
  // ^\s*                  : 行頭の空白
  // (?:                  : 非キャプチャグループ（1回以上）
  //   \d+                : 1つ以上の数字
  //   (?:,\d+)*          : カンマとそれに続く数字の繰り返し（カンマ区切り）
  // )                     : グループの終わり
  // [,\d]*                : カンマと数字以外の文字（空行やゴミ）を許可するための緩いチェック（後で絞る）
  // \s*$                  : 行末の空白

  // 妥当な行の判定ロジック
  let isValid = false;

  if (trimmedLine.length > 0) {
    // 末尾のカンマを取り除いて、数字だけが残るかチェックする
    const cleanedLine = trimmedLine.replace(/,$/, '');

    // 数字とカンマのみで構成されているか、かつ数字が含まれているかを確認する
    // 1. 数字とカンマ以外の文字が含まれていないか
    //    `^[0-9,]*$` は、数字とカンマのみで構成されていることを示すが、これは「数字とカンマのみ」を満たす。

    // 2. 1個以上の数字が含まれているか
    const containsDigits = /\d/.test(trimmedLine);

    if (containsDigits) {
      // カンマ区切りのパターンに厳密に合わせるため、正規表現で検証する
      // ^\s*   -> 行頭の空白
      // (?:[0-9]+(?:,|$))+ -> 1つ以上の数字とカンマの組み合わせ
      // \s*$   -> 行末の空白
      const regex = /^\s*(?:[0-9]+(?:,|$))+.*$/;
      
      // 末尾のカンマが許容されることを考慮し、より厳密に「数字の塊」が存在するかを確認する。
      // 最小のパターンとして、数字が少なくとも1つ含まれていればOKとする。
      // 末尾のカンマが許容されるため、最後の文字がカンマで終わることも許容する。
      const strictRegex = /^\s*(\d+(?:,\d+)*)(?:,*)?$/; // 数字とカンマのみで構成され、数字が1つ以上あることを確認
      
      // より寛容に、数字とカンマで構成されていることを確認し、空行でないことを確認する
      // 問題の仕様：「1 個以上の数字列がカンマで区切られて並んでいる」
      // これは、数字が1つ以上存在し、カンマで区切られている状態を意味する。
      
      // 試行的な判定: 数字とカンマのみで構成されているか、かつ数字が1つ以上あるか。
      let allValidChars = true;
      for (let i = 0; i < trimmedLine.length; i++) {
        const char = trimmedLine[i];
        if (!/\d/.test(char) && char !== ',') {
          allValidChars = false;
          break;
        }
      }

      if (allValidChars) {
          // 空行は除外（trimmedLine.length > 0で既に除外済み）
          // 1個以上の数字がカンマで区切られている、という条件を満たすか？
          // 例: "1,2" -> OK。 "1," -> OK（末尾カンマ許容）。 "" -> NG（空行）。 "abc" -> NG。
          
          // 数字が1つ以上含まれていることを確認すれば、十分とみなす。
          if (containsDigits) {
              validCount++;
          }
      }
    }
  }
});

rl.on('end', () => {
  console.log(`valid=${validCount}`);
});
