const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let lineCount = 0;
let validCount = 0;

rl.on('line', (line) => {
  lineCount++;
  // 正規表現: 
  // ^\s*          -> 行頭の空白文字
  // (?:          -> 非キャプチャグループの開始
  //   \d+,\s*    -> 1つ以上の数字とカンマ、それに続く空白文字
  //   |          -> または
  //   \d+       -> 1つ以上の数字
  // )+           -> 上記パターンが1回以上繰り返される
  // .*           -> 残りの任意文字（末尾のカンマなどを許容するため）
  // \s*$         -> 行末の空白文字
  // この正規表現は、カンマ区切りの整数列が1つ以上存在することを確認することを目的とします。
  // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
  
  // 妥当性のチェックロジック:
  // 1. 行が空行でないこと。
  // 2. 行が数字、カンマ、空白のみで構成されていること。
  // 3. カンマで区切られた数字列が1つ以上存在すること。

  // カンマ区切りの整数列が1つ以上存在することを確認するために、
  // 少なくとも1つの数字列がパターンに含まれているかを確認します。
  // 例: "1,2,3" -> 複数の数字列がある
  // 例: "123" -> 1つの数字列がある (末尾にカンマがあっても良い)
  // 例: ",," -> 妥当ではない
  // 例: "abc" -> 妥当ではない
  
  // 正規表現の再設計: 
  // 少なくとも1つの数字列とカンマの組み合わせが存在することを確認する。
  // 数字(1回以上) とカンマが混在しているか、または単なる数字列があるかを判定します。
  // 妥当な行は、カンマで区切られた整数列が1つ以上存在する場合です。
  
  // カンマと数字が混在し、かつ最低1つの数字列が存在することを確認するパターン
  const regex = /^\s*(?:\d+(?:,\d+)*|\d+)(?:,.*)*\s*$/;
  
  // よりシンプルに、行に含まれる要素が数字のみ（カンマで区切られている）であることを確認する
  // カンマ区切りで1つ以上の数字が存在する場合、それを許容します。
  // 例: "1,2,3" は妥当
  // 例: "123" は妥当 (末尾にカンマがあっても良い)
  // 例: "," は不妥当
  // 例: "abc" は不妥当

  // カンマ区切りの整数列が1つ以上存在することを確認するため、
  // 行をカンマで分割し、空でない数字列が1つ以上あるかを確認する方が確実です。
  const parts = line.split(',');
  let isValid = false;
  
  if (parts.length > 0) {
    for (const part of parts) {
      const trimmedPart = part.trim();
      if (trimmedPart.length > 0) {
        // 各部分が整数のみで構成されているかチェック
        if (/^\d+$/.test(trimmedPart)) {
          isValid = true;
          break;
        } else {
          // 数字とカンマ以外の文字が含まれている場合、妥当ではない
          isValid = false;
          break;
        }
      }
    }
  }
  
  // 空行の場合 (parts.length === 1 && line.trim() === '')
  if (line.trim() === "") {
      isValid = false;
  }
  
  if (isValid) {
    validCount++;
  }
});

rl.on('close', () => {
  console.log(`valid=${validCount}`);
});
