process.stdin.resume();
process.stdin.setEncoding("utf8");

let input = "";
let validLines = 0;

process.stdin.on("data", (chunk: string) => {
  input += chunk;
});

process.stdin.on("end", () => {
  const lines = input.split("\n");
  let validCount = 0;

  // 行ごとに判定
  for (const line of lines) {
    // 行の前後の空白を無視
    const trimmedLine = line.trim();

    if (trimmedLine === "") {
      // 空行は妥当ではない（行の判定は「1個以上の数字列がカンマで区切られて並んでいること」）
      continue;
    }

    // 正規表現の解説:
    // ^ : 行の始まり
    // (?:[0-9]+(?:, [0-9]+)*) : 1個以上の数字列がカンマで区切られているパターンをキャプチャ
    // (?:,*)? : 末尾のカンマが任意（末尾のカンマは許容）
    // $ : 行の終わり
    // この正規表現は、数字とカンマのみで構成されており、1つ以上の数字列がカンマで区切られていることを要求します。
    // ただし、課題の要求は「1 個以上の数字列がカンマで区切られて並んでいること」であり、
    // 例として「1,2,3」や「1,2」が妥当です。
    // 末尾のカンマは許容されます。
    
    // 妥当なパターン: 数字とカンマの組み合わせで構成され、少なくとも1つの数字が存在し、カンマ区切りになっていること。
    // 例: "1,2,3" や "1,2," など。
    // ここでは、数字とカンマのみで構成され、数字が含まれていることを確認します。
    const regex = /^[\d,]+(?:\s*,?\s*[\d,]+)*\s*$/;

    // より厳密に「1個以上の数字列がカンマで区切られている」ことを確認するため、数字の存在をチェックする。
    // 妥当な行は、カンマ区切りの数字列のみで構成され、数字が含まれている必要がある。
    // 正規表現を調整して、数字とカンマのみで構成され、少なくとも1つの数字が含まれることを確認する。
    
    // カンマ区切りの整数列のパターンをより正確に定義します。
    // (数字, の繰り返し) が少なくとも1回以上存在すること。
    // 許容されるのは「カンマで区切られた整数列」のみ。
    const isPotentiallyValid = /^[0-9,]+(?:,([0-9,]+))*$/;

    // 末尾のカンマの許容性を考慮し、全体として数字とカンマのみで構成されているか、かつ数字が含まれていることを確認。
    // 末尾のカンマは許容される。
    // 妥当な行の定義: 少なくとも1つの数字がカンマで区切られている（または単一の数字）。
    // 例: "1" または "1,2" または "1,2,"
    
    // 行全体を評価する際には、行内の全ての要素が数字とカンマのみで構成されているか、かつ数字が存在するかを確認するのが最も安全です。
    // 課題の要件「1 個以上の数字列がカンマで区切られて並んでいる」を正規表現で表現します。
    // 例: "1,2,3" または "1" または "1,"
    const validRegex = /^[\d,]+(?:\s*,\s*[\d,]+)*\s*$/;

    if (trimmedLine.length > 0 && validRegex.test(line)) {
      validLines++;
    }
  }

  console.log(`valid=${validLines}`);
});
