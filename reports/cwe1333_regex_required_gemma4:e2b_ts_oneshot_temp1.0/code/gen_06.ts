    // ^\s* : 行頭の空白
    // (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列のシーケンス。最初の数字列に続くカンマ区切りの数字列。
    // (?:,\s*)? : 最後のカンマをオプションで許容（末尾のカンマを許容するため）
