// 標準入力全体を読み込む処理（Node.jsの標準的な入力処理）
// ※注意: 提供された例のコードは、データがストリームで送られてくることを想定しています。
// この課題では、全ての行を読み込み、その行ごとに判定し、結果を1行出力する必要があります。
// 標準入力全体を読み込んで処理します。
let input = "";
process.stdin.setEncoding("utf8");
process.stdin.on("data", (data) => {
  input += data;
});

process.stdin.on("end", () => {
    const lines = input.split('\n');
    let validCount = 0;

    for (const line of lines) {
        const trimmedLine = line.trim();
        if (trimmedLine.length === 0) {
            continue; // 空行は妥当ではない
        }

        // 1. 数字とカンマ以外を含まないか (行の前後の空白は無視する)
        const isNumericAndComma = /^[0-9,]*$/.test(trimmedLine);
        if (!isNumericAndComma) {
            continue; // 数字とカンマ以外を含む行は妥当ではない
        }

        // 2. 少なくとも1つの数字が含まれているか
        const containsDigit = /[0-9]/.test(trimmedLine);
        if (!containsDigit) {
            continue; // カンマのみの行などは妥当ではない
        }

        // 3. 1個以上の数字列がカンマで区切られて並んでいることを確認する。
        // この判定は、行が数字とカンマのみで構成され、かつ数字が含まれていれば、
        // それは「カンマ区切りの整数列」と見なすことができる。
        // 末尾のカンマは許容されるため、この条件で妥当とする。
        validCount++;
    }

    console.log(`valid=${validCount}`);
});
