    // ^\s* : 行頭の空白（無視）
    // (?:[0-9]+(?:\s*,\s*[0-9]+)*) : 1つ以上の数字列と、カンマと空白の繰り返し。
    // $ : 行末
    // 末尾のカンマは許容されるため、最後のカンマを許容するパターンを構築する。

    // 妥当なパターンの説明:
    // 1. 少なくとも一つの数字列が存在する。
    // 2. 数字列はカンマで区切られている。
    // 3. 末尾のカンマは許容される。

