package main

import (
	"bufio"
	"fmt"
	"os"
)

func main() {
	reader := bufio.NewReader(os.Stdin)

	var target int64
	line, err := reader.ReadString('\n')
	if err != nil || len(line) == 0 {
		return
	}

	target, err = fmt.ScanInt64(line[:len(line)-1])
	if err != nil {
		return
	}

	values := []int64{}
	for {
		line, err := reader.ReadString('\n')
		if err != nil {
			break
		}

		if len(line) == 0 {
			continue
		}

		parts := trimAndSplit(line)
		for _, s := range parts {
			val, err := fmt.ScanInt64(s + "\n")
			values = append(values, val)
		}
	}

	count := int64(0)
	n := len(values)
	if n < 2 {
		fmt.Printf("pairs=%d\n", count)
		return
	}

	for i := int64(0); i < n; i++ {
		for j := int64(i + 1); j < n; j++ {
			sum := values[i] + values[j]
			if sum == target {
				count++
			}
		}
	}

	fmt.Printf("pairs=%d\n", count)
}

func trimAndSplit(line string) []string {
	line = trimSpaces(line)
	parts := []string{}
	for _, p := range line {
		parts = append(parts, string(p))
	}
	return parts
}

func trimSpaces(s string) string {
	start := 0
	end := len(s)
	if s == "" {
		return s
	}
	for start < end && (s[start] == ' ' || s[start] == '\t') {
		start++
	}
	for end > start && (s[end-1] == ' ' || s[end-1] == '\t') {
		end--
	}
	if start >= end {
		return ""
	}
	return s[start:end]
}

