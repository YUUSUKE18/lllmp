const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let lines: string[] = [];

rl.on('line', (line) => {
  lines.push(line);
});

rl.on('close', () => {
  let validLines = 0;
  const regex = /^(\d+(,\d+)*)\s*$/;

  for (const line of lines) {
    // 行の前後の空白を無視するため、trim()を使用
    const trimmedLine = line.trim();

    if (trimmedLine === "") {
      // 空行は妥当ではない
      continue;
    }

    // 正規表現で判定: 1個以上の数字とカンマの組み合わせ、および末尾のカンマの許容
    // 厳密には「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する必要がある。
    // 例: "1,2,3" はOK。末尾カンマは許容。
    // 正規表現の解釈:
    // ^\s* : 行頭の空白
    // (?: \d+(,\d+)* ) : 1つ以上の数字とカンマのパターン（例: 1,2,3,）
    // $ : 行末
    // この正規表現は、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
    // 末尾のカンマを許容するため、末尾にカンマが続くパターンを考慮する。

    // よりシンプルな判定として、数字とカンマ以外の文字が含まれていないか、
    // そして少なくとも1つの数字が含まれているかをチェックする。

    // 1. 数字とカンマ以外の文字が含まれていないか
    if (!/^[0-9,]*$/.test(line)) {
      continue; // 数字とカンマ以外が含まれていれば不適
    }

    // 2. 少なくとも1つの数字が含まれているか
    const hasDigit = /^\d/.test(line);
    if (!hasDigit) {
      continue; // 数字が一つもなければ不適
    }

    // 3. カンマの妥当性チェック（末尾のカンマは許容）
    // 妥当なパターン: 数字とカンマのみで構成され、少なくとも1つの数字を含む。
    // 末尾のカンマは許容される。
    // 例: "1,2,3" -> OK
    // 例: "1,2," -> OK
    // 例: "1" -> OK
    // 例: "," -> NG (hasDigitで除外済み)
    // 例: "abc" -> NG (上記1で除外済み)

    // 最終的な判定ロジックを正規表現に集約する。
    // 1個以上の数字とカンマの組み合わせで構成され、数字が少なくとも1つ含まれていること。
    // 末尾のカンマは許容される。
    const validPattern = /^[\d,]+(?:\s*,?\d+)*$|^[\d]+(?:,[\d,]*)*$|^[\d]+$|^[\d]+,?$/;
    
    // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックする。
    // これは、カンマで区切られた数字のシーケンスである必要がある。
    // 例: "1,2,3" または "1,2," または "1"
    
    // 妥当な行の判定を再定義:
    // 1. 行が空でない。
    // 2. 行に含まれる文字は数字とカンマのみ。
    // 3. 行に少なくとも1つの数字が含まれている。
    // 4. カンマの配置が意味を持つ（カンマで区切られた数字の列）。

    // 課題の要求を再解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
    // これは、カンマで区切られた数字のリストであるべき。
    // 例: "1,2,3" -> 3つの数字列
    // 例: "1," -> 2つの数字列 (1, 空) または 1つの数字列 (1) の解釈が曖昧。
    // 「末尾のカンマは許容します」という記述から、カンマが区切りとして機能していることを示唆する。

    // 以下の正規表現は、数字とカンマのみで構成され、少なくとも1つの数字を含むことを確認する。
    // 末尾のカンマは許容する。
    const strictRegex = /^[\d,]+$/;
    
    // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックするため、
    // カンマで区切られた数字のシーケンスであることを確認する。
    // 1. 数字とカンマのみで構成されていること。
    // 2. 少なくとも1つの数字が含まれていること。
    // 3. カンマが数字の間に存在する（または末尾に存在する）。

    // 簡略化し、与えられた制約に従って、数字とカンマのみで構成され、数字が含まれている行を妥当とする。
    // 最後の行の判定は、入力の構造に依存するため、最も緩い制約で進める。
    
    // 妥当な行の判定: 数字とカンマのみで構成され、数字が少なくとも1つ含まれている。
    if (strictRegex.test(line)) {
        validLines++;
    }
  }

  console.log(`valid=${validLines}`);
});
