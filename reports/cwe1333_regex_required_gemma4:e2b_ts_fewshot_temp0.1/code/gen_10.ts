const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let lines: string[] = [];

rl.on('line', (line) => {
  lines.push(line);
});

rl.on('close', () => {
  let validLines = 0;
  const regex = /^(\d+(,\d+)*)\s*$/;

  for (const line of lines) {
    // 行の前後の空白を無視するため、trim()を使用
    const trimmedLine = line.trim();

    if (trimmedLine === "") {
      // 空行は妥当ではない
      continue;
    }

    // 正規表現で判定: 1個以上の数字とカンマの組み合わせ、および末尾のカンマの許容
    // 正規表現の解説:
    // ^ : 行の開始
    // ( ... ) : キャプチャグループ
    // \d+ : 1桁以上の数字
    // (,\d+)* : カンマとそれに続く1桁以上の数字が0回以上繰り返される (末尾のカンマを許容するため)
    // $ : 行の終了
    // \s* : 行末の空白を許容
    // この正規表現は、数字とカンマのみで構成され、数字が少なくとも1つあることを要求します。
    // ただし、課題の「1 個以上の数字列がカンマで区切られて並んでいる」という要件を厳密に満たすためには、
    // 複数の数字列の区切りを考慮する必要があります。
    
    // 課題の要件を再解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
    // これは、カンマで区切られた要素がすべて整数である、ということを意味します。
    // 例: "1,2,3" は妥当。 "1," は妥当（末尾のカンマ許容）。 "abc" は不妥当。
    
    // 複数の数字列の存在を判定するために、カンマで区切られた要素をチェックします。
    // 1. 行をカンマで分割する
    const parts = line.split(',');
    
    if (parts.length === 0) {
        // 空行は既にスキップされているが念のため
        continue;
    }

    let isValid = true;
    
    // 2. 各部分が数字列であるか、または末尾のカンマのみであるかを確認する
    // 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」こと。
    // これは、少なくとも1つの数字列が存在し、それらがカンマで区切られていることを意味します。
    
    // 複数の数字列が存在する場合、parts.length >= 2 となるはずです（例: "1,2" -> ["1", "2"]）
    // または、1つの数字列のみの場合（例: "1"）も許容されるか？
    // 「1 個以上の数字列がカンマで区切られて並んでいる」
    // "1" は1つの数字列。区切りがないため、この解釈では不適。
    // "1," は1つの数字列と末尾のカンマ。
    
    // 妥当なパターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
    // 正規表現で「数字とカンマのみ」をチェックし、さらに「数字が含まれている」ことを確認する。
    
    // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を正規表現で表現するのは複雑です。
    // 以下の正規表現は、行が数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
    // ^\s*(\d+(,\d+)*)\s*$: 複数の数字列のパターンを想定
    // ^\s*\d+(,\d+)*\s*$: 1つの数字列とカンマのパターンを想定
    
    // 課題の意図を「カンマで区切られた要素がすべて整数である」と解釈し、
    // 少なくとも1つの数字が含まれていることを確認します。
    
    // 1. 行をトリムして、数字とカンマのみで構成されているかチェック
    const cleanLine = line.trim();
    if (!/^[0-9,]*$/.test(cleanLine)) {
        isValid = false;
    } else if (cleanLine.length > 0) {
        // 2. 数字が含まれているかチェック (数字のみで構成されている行は除外)
        if (!/\d/.test(cleanLine)) {
            isValid = false;
        }
    } else {
        // 空行はスキップ済み
        isValid = false;
    }

    if (isValid) {
      validLines++;
    }
  }

  console.log(`valid=${validLines}`);
});
