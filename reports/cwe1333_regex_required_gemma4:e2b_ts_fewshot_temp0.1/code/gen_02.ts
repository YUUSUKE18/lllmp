const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let lines: string[] = [];

rl.on('line', (line) => {
  lines.push(line);
});

rl.on('close', () => {
  let validLines = 0;
  const regex = /^[\d,]+(?:,[\d,]+)*$|^[,]*$/;

  for (const line of lines) {
    const trimmedLine = line.trim();

    if (trimmedLine === "") {
      // 空行は妥当ではない
      continue;
    }

    // 末尾のカンマは許容するが、数字とカンマ以外は許容しない
    // 正規表現の解説:
    // ^[\d,]+(?:,[\d,]+)*$ : 1個以上の数字またはカンマで始まり、カンマ区切りで続くパターン。
    // | : または
    // [,]*$ : カンマのみ、または何もなし（末尾のカンマのみも含む）
    // この問題の仕様「1 個以上の数字列がカンマで区切られて並んでいること」を厳密に解釈し、
    // 少なくとも1つの数字が含まれていることを確認する。

    // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックする正規表現を試みる。
    // 1個以上の数字列がカンマで区切られている場合、少なくとも1つの数字が存在する。
    // 例: "1,2,3" -> OK
    // 例: "1," -> OK (末尾のカンマは許容)
    // 例: "," -> NG (数字列が1個以上必要)
    // 例: "abc" -> NG

    // 妥当なパターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
    // 1. 数字とカンマのみで構成されていること: /^[0-9,]*$/
    // 2. 少なくとも1つの数字が含まれていること: /\d/
    // 3. 末尾のカンマは許容されること: (?:,)?$ (これは複雑になるため、元の仕様に忠実に)

    // 仕様: 1 個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容。
    // これは、カンマで区切られた要素がすべて数字（または空文字列、ただしここでは数字列と解釈）である必要がある。

    // 試行: カンマで区切られた要素がすべて数字（または空）で構成されているか、かつ少なくとも1つの数字があるか。
    // 以下の正規表現は、カンマで区切られた要素が数字のみで構成されていることを確認する。
    // 1. 少なくとも1つの数字が含まれていること。
    // 2. 数字とカンマ以外の文字が含まれていないこと。
    // 3. 末尾のカンマは許容。

    // 妥当な行の判定ロジックを再構築します。
    // 1. 行をカンマで分割する。
    // 2. 各要素が数字（または空文字列）のみで構成されているか確認する。
    // 3. 少なくとも1つの数字が含まれているか確認する。

    const parts = line.split(',');
    let hasDigit = false;
    let isValid = true;

    for (const part of parts) {
      const trimmedPart = part.trim();
      if (trimmedPart.length > 0) {
        // 数字のみで構成されているかチェック
        if (!/^\d+$/.test(trimmedPart)) {
          isValid = false;
          break;
        }
        hasDigit = true;
      }
      // 空の要素（カンマが連続している場合など）は無視するが、
      // 仕様では「1個以上の数字列がカンマで区切られて並んでいる」ため、
      // 空の要素が混在しても、数字列が区切られている限りは許容されるべき。
      // ただし、「空行、および数字とカンマ以外を含む行は妥当ではない」という制約がある。
      // 空行は既に除外済み。
    }

    // 1個以上の数字列がカンマで区切られていること (hasDigitがtrue)
    // 数字とカンマ以外を含む行はNG (上記ループでチェック済み)
    // 末尾のカンマは許容 (splitで処理されるため、ここではOK)

    if (isValid && hasDigit) {
      validLines++;
    }
  }

  console.log(`valid=${validLines}`);
});
