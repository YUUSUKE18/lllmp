const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let lines: string[] = [];

rl.on('line', (line) => {
  lines.push(line);
});

rl.on('close', () => {
  let validLines = 0;
  const regex = /^(\d+(,\d+)*)\s*$/;

  for (const line of lines) {
    // 行の前後の空白を無視するため、trim()を使用
    const trimmedLine = line.trim();

    if (trimmedLine === "") {
      // 空行は妥当ではない
      continue;
    }

    // 正規表現で判定: 1個以上の数字とカンマの組み合わせ、および末尾のカンマの許容
    // 正規表現の解説:
    // ^ : 行の開始
    // (?: ... )* : グループ化された部分が0回以上繰り返される
    // \d+ : 1つ以上の数字
    // (?:,\d+)* : カンマとそれに続く1つ以上の数字の組み合わせが0回以上繰り返される
    // ,? : 末尾のカンマが任意（ただし、行全体が数字とカンマのみで構成されている必要がある）
    // $ : 行の終了
    // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
    // 以下のロジックで正規表現を調整する。
    
    // 仕様: 1個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容。
    // 例: "1,2,3" は妥当。 "1," は妥当。 "123" は妥当（区切りがない場合も1つの数字列と見なせるか？仕様を再解釈）
    // 「1 個以上の数字列がカンマで区切られて並んでいる」
    // これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを意味する。

    // 1. 数字とカンマのみで構成されているか？
    // 2. 少なくとも1つの数字が含まれているか？

    // 許容されるパターン: 数字とカンマのみで構成され、数字が少なくとも1つある。
    // 例: "1,2,3", "1,2,", "123" (もしこれが許容されるなら)
    
    // 厳密に「カンマ区切り」を重視し、数字とカンマのみで構成されていることを確認する。
    // 1つの数字列がカンマで区切られている、または単一の数字列である。
    
    // 以下の正規表現は、数字とカンマのみで構成され、数字が少なくとも1つ含まれていることを確認する。
    // (?:(\d+)(?:,\d+)*) : 少なくとも1つの数字列があり、それらがカンマで区切られているパターン。
    // | : または
    // \d+ : カンマなしの単一の数字列（例: "123"）も許容する場合。
    
    // 仕様を再解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
    // これは、カンマで区切られた要素が1つ以上存在することを意味する。
    // 例: "1" (1つの数字列), "1,2" (2つの数字列)
    
    // 妥当な行の判定ロジックをシンプルにするため、数字とカンマ以外の文字がないことを確認し、
    // 少なくとも1つの数字が含まれていることを確認する。
    
    // 数字とカンマのみで構成されているか？
    const onlyDigitsAndCommas = /^[0-9,]*$/.test(line.trim());

    if (!onlyDigitsAndCommas) {
      continue; // 数字とカンマ以外を含む行は妥当ではない
    }

    // 少なくとも1つの数字が含まれているか？
    const containsDigit = /\d/.test(line.trim());

    if (containsDigit) {
      // 妥当な行としてカウント
      validLines++;
    }
  }

  console.log(`valid=${validLines}`);
});
