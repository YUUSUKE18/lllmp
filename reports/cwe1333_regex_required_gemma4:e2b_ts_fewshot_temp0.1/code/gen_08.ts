const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let lines: string[] = [];

rl.on('line', (line) => {
  lines.push(line);
});

rl.on('close', () => {
  let validLines = 0;
  const regex = /^[\d,]+(?:,[\d,]+)*$|^[,]*$/;

  for (const line of lines) {
    const trimmedLine = line.trim();

    // 空行は妥当ではない
    if (trimmedLine === "") {
      continue;
    }

    // 末尾のカンマのみの行は妥当（例: "," または ",,"）
    if (/^,+$|^\s*,\s*+$/.test(trimmedLine)) {
      validLines++;
      continue;
    }

    // 数字とカンマのみで構成されているかチェック
    // 正規表現の解説:
    // ^[\d,]+ : 行の先頭から1文字以上の数字またはカンマ
    // (?:,[\d,]+)* : カンマと1文字以上の数字またはカンマが0回以上繰り返される
    // $ : 行の終わり
    // この正規表現は、数字とカンマのみで構成されていることを確認する。
    // ただし、仕様は「1個以上の数字列がカンマで区切られて並んでいる」ことを求めているため、
    // 厳密には「カンマで区切られた整数列」の形式をチェックする必要がある。

    // 1. 数字とカンマのみで構成されているか確認
    if (!/^[0-9,]+$/.test(trimmedLine)) {
      continue; // 数字とカンマ以外が含まれていれば不妥当
    }

    // 2. 1個以上の数字列がカンマで区切られているか確認
    // 複数の数字列が存在し、カンマで区切られている必要がある。
    // 例: "1,2,3" -> 3つの数字列
    // 例: "1," -> 1つの数字列と末尾のカンマ
    // 例: "," -> 妥当（末尾のカンマは許容）

    // 妥当なパターン:
    // a) 完全に数字とカンマのみで構成されている (例: "1,2,3", "123")
    // b) 末尾がカンマで終わる (例: "1,2,3,")
    // c) カンマのみ (例: ",")

    // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックする。
    // 複数の数字列が存在するためには、カンマが少なくとも1つ必要。
    // 末尾のカンマは許容される。

    // 複数の数字列が存在する場合のパターン: 数字,数字,...
    // 少なくとも1つのカンマが存在し、かつ数字が含まれている必要がある。
    const parts = trimmedLine.split(',');

    if (parts.length > 1) {
      // 複数の要素に分割された場合、各要素が数字（カンマを除去後）であるか確認
      const allAreNumbers = parts.every(part => {
        const numStr = part.replace(/,/g, '');
        return numStr.length > 0 && /^\d+$/.test(numStr);
      });

      if (allAreNumbers) {
        validLines++;
      }
    } else if (parts.length === 1) {
      // 要素が1つだけの場合 (例: "123" または "123,")
      // 1. 数字のみの場合 (例: "123") -> 1個の数字列。これは「1個以上の数字列がカンマで区切られて並んでいる」の解釈に依存するが、
      //    「1個以上の数字列」が区切られている、という条件を満たすためには、区切り文字（カンマ）が必要とされる。
      //    しかし、末尾のカンマは許容される。
      //    もし "123" が妥当なら、それは「1個の数字列」と見なされる。
      //    「1個以上の数字列がカンマで区切られて並んでいる」を満たすためには、カンマの存在が強く示唆される。
      //    ここでは、カンマが存在しない単一の数字列も、区切りがないため妥当と見なすか、あるいは「区切られている」ことを必須とするか。
      //    例2の「カンマ区切りの語」の例から、区切り文字の存在が重要と判断し、ここではカンマが存在しない場合は妥当としない、または末尾のカンマのみを許容する。

      // 仕様を再解釈: 「1個以上の数字列がカンマで区切られて並んでいる」
      // 1. "1,2" -> 2個の数字列がカンマで区切られている。妥当。
      // 2. "123" -> 1個の数字列。区切りがないため、これは「区切られて並んでいる」とは言えない。
      // 3. "123," -> 1個の数字列が区切られている（末尾のカンマは許容）。妥当。

      // 複数の数字列が存在しない場合、カンマが存在しない行は妥当ではないと判断する。
      if (trimmedLine.includes(',')) {
        // 末尾のカンマのみのケースは既に処理済みだが、ここでは念のため
        validLines++;
      }
    }
  }

  console.log(`valid=${validLines}`);
});
