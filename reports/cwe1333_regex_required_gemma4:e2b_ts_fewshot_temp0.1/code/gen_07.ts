const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let lines: string[] = [];
let lineNumber = 0;

rl.on('line', (line) => {
  lines.push(line);
  lineNumber++;
});

rl.on('close', () => {
  let validLines = 0;
  // 各行を正規表現で判定
  // 正規表現の解説:
  // ^\s*          : 行の先頭の任意の空白文字
  // (?:          : 非キャプチャグループの開始
  //   \d+        : 1つ以上の数字
  //   ,          : カンマ
  // )*           : 上記のグループが0回以上繰り返される (カンマ区切りが0個の場合も許容)
  // \s*          : 行末の任意の空白文字
  // $            : 行の終わり
  // この正規表現は、数字とカンマのみで構成され、空行やその他の文字を含まないことを確認します。
  // ただし、仕様では「1個以上の数字列がカンマで区切られて並んでいること」を判定する必要があります。
  // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
  // 少なくとも1つの数字列が存在し、それがカンマで区切られている構造をチェックします。

  // 修正された判定ロジック:
  // 1. 行が空でないこと (空行は妥当ではない)
  // 2. 行が数字とカンマのみで構成されていること
  // 3. 少なくとも1つの数字列が存在すること (例: "1,2" は妥当、"" や "," は妥当ではない)

  const regex = /^\s*(\d+(?:,\d+)*)\s*$/;

  for (const line of lines) {
    // 行の前後の空白を無視して判定するため、lineをトリムする
    const trimmedLine = line.trim();

    if (trimmedLine.length === 0) {
      // 空行は妥当ではない
      continue;
    }

    // 正規表現で数字とカンマのみで構成されているかチェック
    // 許容されるパターン: 数字とカンマのみ。末尾のカンマは許容。
    // 例: "1,2,3", "1,2,"
    // 否定されるパターン: "a,1", "1,a", "1,2,3,4" (これは許容されるべきだが、仕様の解釈に注意)

    // 仕様: 「1 個以上の数字列がカンマで区切られて並んでいること」
    // これは、カンマで区切られた要素がすべて整数である、ということを意味します。
    // したがって、行全体が「数字とカンマ」のシーケンスで構成されている必要があります。

    // より厳密に「数字とカンマのみ」で構成されているかを確認し、
    // さらに「少なくとも1つの数字」が含まれているかを確認します。

    // 1. 数字とカンマのみで構成されているか (末尾のカンマも許容)
    // ^\s*[\d,]*\s*$ は、数字とカンマのみを含むことを確認する。
    // ただし、これは「1個以上の数字列」の構造を保証しない。

    // 2. 正規表現で「1個以上の数字列がカンマで区切られている」ことを確認する
    // パターン: (数字, 数字, ...) の構造。末尾のカンマは許容。
    // 例: "1,2,3" または "1,2,"
    const structureRegex = /^(\d+(?:,\d+)*)(,?\d*)?$/;

    // 実際には、行が数字とカンマのみで構成され、かつ数字が含まれていることを確認する。
    // 以下の正規表現は、数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれていることを確認します。
    // (?: ... )* : 0回以上の繰り返し
    // \d+ : 少なくとも1つの数字
    // (?:,\d+)* : カンマと数字のペアが0回以上繰り返される
    // (?:,\d*)? : 最後の要素がカンマと数字のペア（または単なるカンマ）で終わることを許容
    const finalRegex = /^\s*(\d+(?:,\d+)*)(?:,?\d*)?\s*$/;

    // 簡略化して、行が数字とカンマのみで構成され、かつ数字が含まれていることを確認する。
    // 妥当な行は、数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれている。
    // 例: "1,2" -> OK
    // 例: "1," -> OK
    // 例: "," -> NG (数字がない)
    // 例: "a,1" -> NG (文字が含まれる)

    // 妥当な行の判定:
    // 1. 行が空でない (既にチェック済み)
    // 2. 行に含まれる文字がすべて数字またはカンマである。
    // 3. 行に少なくとも1つの数字が含まれている。

    let isStructurallyValid = true;
    let containsDigit = false;

    for (const char of line) {
      if (!/\d/.test(char) && char !== ',') {
        isStructurallyValid = false;
        break;
      }
      if (/\d/.test(char)) {
        containsDigit = true;
      }
    }

    if (isStructurallyValid && containsDigit) {
      validLines++;
    }
  }

  console.log(`valid=${validLines}`);
});
