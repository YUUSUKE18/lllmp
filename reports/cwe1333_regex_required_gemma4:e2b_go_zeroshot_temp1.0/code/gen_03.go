package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列のパターンを定義
	// ^ 表示行の先頭
	// [0-9]+ 表示1桁以上の数字
	// (?:,|$)? 表示カンマまたは行末（カンマは任意で0回以上）
	// この正規表現は、カンマ区切りの整数列が1つ以上存在することを許容します。
	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// 行全体が数字とカンマのみで構成されており、かつ少なくとも1つの数字が含まれていることを確認する必要があります。

	// 仕様：「1 個以上の数字列がカンマで区切られて並んでいることです。末尾のカンマは許容します。」

	// パターン解説:
	// ^\s*             -> 行の先頭の空白（無視）
	// (?:              -> 非キャプチャグループの開始
	//   \d+           -> 1つ以上の数字（数字列）
	//   (?:,\s*)?     -> その後にカンマと任意の空白が続くが、任意（0回または複数回）
	// )+               -> 上記グループが1回以上繰り返される（複数の数字列）
	// (?:,\s*)?        -> 末尾のカンマと空白が任意（末尾のカンマは許容）
	// \s*$             -> 行末の空白

	// よりシンプルかつ、行が「カンマ区切りの整数列」であることと「空行でない」ことを確認するアプローチを取ります。

	// 妥当な行のカウント
	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現の適用
		// この正規表現は、行が数字とカンマのみで構成されており、少なくとも1つの数字が含まれていることをチェックします。
		// パターン: [0-9,]* または [0-9]+
		// 妥当な形式: 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
		// 末尾のカンマは許容。
		// 1個以上の数字列がカンマで区切られていることを確認するには、少なくとも1つの数字があることを確認すれば十分です。

		// パターン: ^[\d,]*$ (数字とカンマのみ) かつ 少なくとも1つの数字が含まれていること
		// この要件を満たす最も簡単な正規表現は、数字とカンマのみで構成され、空でないことです。
		// 「1 個以上の数字列がカンマで区切られて並んでいる」という構造を厳密にチェックするには、
		// 少なくとも一つの数字があることを確認します。

		// 正規表現: 任意の数の数字、カンマ、空白（行の先頭と末尾の空白を除く）のみで構成されていることをチェックし、かつ数字が1つ以上あることを確認する。
		// ここでは、行が数字とカンマのみで構成されているか、または空行でないかをまず確認します。
		// 後続のロジックで、数字の存在をチェックします。

		// 数字とカンマのみで構成されているかを確認する（末尾のカンマは許容）
		// 妥当な形式: (数字, 数字, ...) または 数字, 数字, ...
		// 数字列が1つ以上あることを確認する。
		// \d+ は少なくとも1つの数字を意味する。
		// [,\d]* は数字とカンマのみで構成される。
		// 末尾のカンマは許容。
		// 少なくとも1つの数字列が存在するという条件を厳密に表現するのは複雑なので、
		// 「数字とカンマ以外を含む行は妥当ではない」という条件を優先します。

		// 正規表現: 行が数字とカンマのみで構成されているか？
		// ^[0-9,]*$
		match := regexp.MustCompile(`^[0-9,]*$`).MatchString(trimmedLine)

		if !match {
			// 数字とカンマ以外を含む行は妥当ではない
			continue
		}

		// 空行ではない（既にチェック済みだが念のため）
		if trimmedLine == "" {
			continue
		}

		// 妥当な行の追加条件: 1個以上の数字列がカンマで区切られていること。
		// これは、行内に少なくとも1つの数字が存在すれば満たされます。（数字とカンマのみの行であるため）
		hasDigit := false
		for _, char := range trimmedLine {
			if char >= '0' && char <= '9' {
				hasDigit = true
				break
			}
		}

		if hasDigit {
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常は不要だが、念のため）
	}

	fmt.Printf("valid=%d\n", validCount)
}
