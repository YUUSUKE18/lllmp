package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	var validLines int
	scanner := bufio.NewScanner(os.Stdin)

	// カンマ区切りの整数列、またはカンマのみの文字列を許容する正規表現。
	// /^(\d+(,\d+)*)(,)?$/ のような複雑なパターンを避けるため、
	// より単純に「数字とカンマのみで構成され、数字が少なくとも1つある」ことを確認します。
	// 妥当なパターン: 1個以上の数字と、それらを区切るカンマ（末尾のカンマは許容）
	// ^\s*                : 行の先頭の空白を無視
	// (\d+(,\d+)*)        : 1つ以上の数字とカンマの繰り返し（数字列のセット）
	// (?:,?\d*)*           : オプションのカンマと数字の繰り返し（末尾のカンマも許容するため）
	// $                  : 行の終わり
	//
	// よりシンプルに、行が数字とカンマのみで構成され、空行でないことを確認し、
	// さらに「カンマ区切りの整数列」の構造に焦点を当てます。

	// 仕様の再解釈: 「1 個以上の数字列がカンマで区切られて並んでいること」
	// これは、カンマで区切られた数字のセットと解釈できます。
	// 例: "1,2,3" (3つの数字列)
	// 例: "1,2," (2つの数字列、末尾のカンマあり)

	// 妥当なパターン: 少なくとも1つの数字が含まれ、数字とカンマのみで構成されている。
	// \d+ は1つ以上の数字。カンマ区切りを許容するため、
	// 正規表現で「数字とカンマのみ」を許容するパターンを作成します。

	// 正規表現の設計:
	// ^\s*             -> 行頭の空白を無視
	// (?:             -> 非キャプチャグループ開始
	//   \d+          -> 1つ以上の数字 (最初の数字列)
	//   (?:,\d+)*    -> カンマとそれに続く数字の繰り返し (次の数字列)
	// )               -> グループ終了
	// (?:,\d*)?       -> 末尾のカンマをオプションで許容
	// \s*$            -> 行末の空白を無視
	//
	// より単純に「数字とカンマのみ」で構成され、空行でないことを確認し、
	// カンマ区切りの整数列の構造に焦点を当てます。

	// 妥当性の判定基準:
	// 1. 空行でないこと。
	// 2. 数字とカンマ以外を含まないこと。
	// 3. 少なくとも1つの数字が含まれていること。
	// 4. 末尾のカンマは許容されること。（これは上記2, 3を組み合わせることで満たされることが多い）

	// 最も厳密なパターン: 数字とカンマのみで構成され、空でない。
	// (数字とカンマのみで構成され、最低1つの数字を含む)
	// ^\s*(\d+(?:,\d+)*)(?:,)?\s*$
	// このパターンは、数字とカンマのみで構成され、任意の数のカンマを許容します。

	// 行ごとに読み込み、判定
	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 数字とカンマのみで構成されているかチェック
		// 含まれる文字が数字(0-9)とカンマ(,)のみであること
		isAlphanumericAndComma := true
		for _, char := range trimmedLine {
			if !('0' <= char && char <= '9') && char != ',' {
				isAlphanumericAndComma = false
				break
			}
		}

		if !isAlphanumericAndComma {
			continue // 数字とカンマ以外を含む行は妥当ではない
		}

		// 少なくとも1つの数字が含まれているかチェック
		hasDigit := false
		for _, char := range trimmedLine {
			if '0' <= char && char <= '9' {
				hasDigit = true
				break
			}
		}

		if hasDigit {
			// 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
			// これは「1個以上の数字列がカンマで区切られて並んでいる」という要件を満たすと解釈します。
			validLines++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（ここでは無視）
	}

	// 結果を出力
	fmt.Printf("valid=%d\n", validLines)
}
