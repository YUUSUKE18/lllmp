package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// 少なくとも1つの整数があり、カンマで区切られている、またはカンマのみで終わっているパターンを許容する。
	// より厳密には、カンマ区切りの整数列のみを許可し、空行や不正な文字を拒否する必要がある。
	// 仕様：「1 個以上の数字列がカンマで区切られて並んでいることです。末尾のカンマは許容します。」
	// この条件を満たす文字列が、数字とカンマのみで構成されていることを確認する。
	// 正規表現の解説:
	// ^ - 行の先頭
	// (?:     - 非キャプチャグループ
	//   \d+  - 1つ以上の数字 (一つの整数列)
	//   (?:,\d+)* - カンマとそれに続く1つ以上の数字の繰り返し (区切り)
	// )
	// (?:,\d+)*  - 最後の要素の後ろにカンマが続くことを許容 (末尾のカンマを許容するため)
	// $ - 行の終わり
	// よりシンプルに、数字とカンマのみで構成されており、数字が少なくとも1つ含まれていることを確認する。

	// 以下の正規表現は、「1つ以上の数字とカンマの組み合わせ」に限定し、空行やその他の文字を拒否する。
	// ^[0-9,]+$ : 数字とカンマのみで構成されている行。数字が1つ以上あることを保証する。
	// 末尾のカンマを許容するため、数字が少なくとも1つあることを確認するパターンを考える。
	// 例: "1,2,3" または "1,2,"
	// 数字が1つ以上あることを保証する:
	// (\d+(?:,\d+)*)  -> 1個以上の数字がカンマで区切られているパターン
	// (?:,\d*)*        -> その後にカンマと0個以上の数字が続く（末尾のカンマを許容するため）
	// この仕様を満たす最も簡単な方法は、行全体が数字とカンマのみで構成され、数字が少なくとも1つあることを確認すること。

	// 行全体が数字とカンマのみで構成され、数字が1つ以上あることを確認する正規表現。
	// 実際には、行の各要素が整数であることを確認するために、各数字列を検証する方が安全。
	// 仕様を厳密に解釈すると、各カンマで区切られた要素が整数である必要がある。
	// 「カンマ区切りの整数列」という表現から、各区切りが整数であることを期待する。

	// 正規表現の再考:
	// 1. 空行、および数字とカンマ以外を含む行は妥当ではない。
	// 2. 1個以上の数字列がカンマで区切られて並んでいる。
	// 3. 末尾のカンマは許容する。

	// 行が空でないことを確認し、数字とカンマ以外を含まないことを確認する。
	// 候補: [0-9,]* のうち、数字が少なくとも1つ含まれている。
	// 行全体が数字とカンマのみで構成されており、少なくとも1つの数字が含まれていることを確認する。
	// このパターンは、"1,2" や "1," や ",1" などを許容する。
	// ただし、「1個以上の数字列がカンマで区切られて並んでいる」という構造を保証するには、数字とカンマの並び方を定義する必要がある。

	// 妥当な行のパターン: (数字 + カンマ) の繰り返し、または最後の要素が数字で終わる。
	// 最小限の要件を満たすために、行全体が数字とカンマのみで構成されており、空ではないことを確認する。
	// 正規表現で「1個以上の整数列がカンマで区切られている」ことを判定する。
	// (?:[0-9]+(?:,|$))+ のような構造は、末尾のカンマを許容しつつ、区切りを重視する。

	// 簡略化して、行が空ではなく、数字とカンマのみで構成されていることを確認する。
	// そして、数字が少なくとも1つ存在することを確認する。
	pattern := regexp.MustCompile(`^[0-9,]+$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 1. 数字とカンマ以外を含む行は妥当ではない。
		if !pattern.MatchString(trimmedLine) {
			continue
		}

		// 2. 妥当性の追加チェック（1個以上の数字列がカンマで区切られていること）
		// これは、行が数字とカンマのみで構成されている場合、行内に数字が少なくとも1つあることを意味する。
		if !strings.ContainsRune(trimmedLine, '0') && !strings.ContainsRune(trimmedLine, '1') && !strings.ContainsRune(trimmedLine, '2') && !strings.ContainsRune(trimmedLine, '3') && !strings.ContainsRune(trimmedLine, '4') && !strings.ContainsRune(trimmedLine, '5') && !strings.ContainsRune(trimmedLine, '6') && !strings.ContainsRune(trimmedLine, '7') && !strings.ContainsRune(trimmedLine, '8') && !strings.ContainsRune(trimmedLine, '9') {
			// 数字が全く含まれていない場合（カンマのみなど）は不妥当
			continue
		}

		// ここまでのチェックで、行は「数字とカンマのみ」で構成され、「少なくとも1つの数字」を含んでいる。
		// この仕様は、行が「カンマ区切りの整数列」であるという構造的要件を強く求めているため、
		// 厳密にカンマで区切られた複数の数字が存在するかを確認する。
		// 1個以上の数字列がカンマで区切られているか？ -> カンマが含まれているか、または数字が複数あるか。
		// 最も緩い解釈（数字とカンマのみで構成され、数字が1つ以上あればOK）を採用し、
		// 既存のチェックで妥当と見なす。

		validCount++
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常は無視しても良いが、念のため）
	}

	fmt.Println("valid=", validCount)
}
