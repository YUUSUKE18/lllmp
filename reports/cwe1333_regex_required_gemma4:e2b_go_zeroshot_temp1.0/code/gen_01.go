package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列の妥当性を判定するための正規表現
	// 正規表現の解説:
	// ^                    : 行の先頭
	// (                   : グループ開始
	//   [0-9]+             : 1つ以上の数字 (整数)
	//   (?:,\s*[0-9]+)*    : カンマとそれに続くスペースと1つ以上の数字が0回以上繰り返される (カンマ区切りの列)
	// )                   : グループ終了
	// (?:,\s*$)           : オプションで末尾のカンマと行末（オプション）
	// $                    : 行の末尾
	//
	// より簡潔に、これは「1個以上の数字がカンマで区切られている」ことをチェックします。
	// 以下のパターンは、カンマで区切られた整数列、またはカンマのみ（または末尾のカンマ）が許容されることを確認します。
	// 妥当な形式: 整数とカンマが混在している、または単なる整数列。
	// 許容されるパターン: 数字の連続、カンマと数字の繰り返し、末尾のカンマ。
	// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を捉えるには、数字とカンマの組み合わせを評価します。

	// 仕様に基づき、行が「1個以上の数字列がカンマで区切られて並んでいる」かを判定します。
	// 数字とカンマのみを含む行、または数字のみの行が対象です。
	// 空行や不正な文字を含む行はNGです。

	// 正規表現の設計:
	// ^                       : 行の開始
	// (                       : グループ開始 (少なくとも1つのパターンが存在することを確認)
	//   [0-9]+                : 1つ以上の数字 (最初の数字列)
	//   (?:,\s*[0-9]+)*       : その後にカンマと数字の繰り返し（任意回）
	// )                       : グループ終了 (これは、数字とカンマが混在している、または単なる数字列)
	// (?:,\s*$)               : オプションで末尾のカンマと行末 (末尾のカンマは許容)
	// $                       : 行の終了
	//
	// 実際には、行が数字とカンマのみで構成されていることを確認し、少なくとも1つの数字が存在することを保証する必要があります。
	// 空行や数字とカンマ以外の文字を含む行はNGです。

	// 以下のパターンは、行が数字とカンマのみで構成されていること、かつ、少なくとも1つの数字を含むことをチェックします。
	// これは、カンマ区切りの整数列が「妥当」であるという定義を満たすように調整する必要があります。
	// 妥当: 1個以上の数字列がカンマで区切られて並んでいる。

	// 1. 空行や不正な文字の除外 (数字とカンマのみに限定)
	// 2. 少なくとも1つの数字が含まれていることを確認
	pattern := regexp.MustCompile(`^[0-9,]*$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 数字とカンマ以外の文字が含まれていないかチェック
		if !pattern.MatchString(trimmedLine) {
			continue
		}

		// 妥当性の判定: 1個以上の数字列がカンマで区切られているか。
		// 最小要件: 少なくとも1つの数字が存在すること。
		// 最小要件: 数字とカンマのみで構成されていること。

		// 数字のみの行 (例: "123") も「1個以上の数字列がカンマで区切られている」と解釈できるか？
		// 「1個以上の数字列がカンマで区切られて並んでいる」 -> 1個の列のみ、または複数列。
		// 1個の列 (例: "123") は、カンマで区切られているわけではないが、これは「1個以上の数字列」を含むため、妥当と見なすのが自然。

		// 妥当性の定義を「数字とカンマのみで構成され、少なくとも1つの数字が含まれている」と解釈する。
		hasDigit := false
		for _, char := range trimmedLine {
			if char >= '0' && char <= '9' {
				hasDigit = true
			}
		}

		if hasDigit {
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常は不要だが念のため）
	}

	fmt.Println("valid=", validCount)
}
