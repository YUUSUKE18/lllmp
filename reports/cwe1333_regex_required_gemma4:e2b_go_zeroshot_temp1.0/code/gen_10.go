package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* は行の先頭の空白を無視
	// (?:[0-9]+(?:,?[0-9]+)*) は1つ以上の数字とカンマの組み合わせを意味するグループ
	// $ は行の終わり
	// 末尾のカンマが許容されるため、行の末尾がカンマで終わる場合も考慮する必要がある。
	// 妥当な行の定義: 1個以上の数字列がカンマで区切られて並んでいること。
	// これは「数字とカンマのみで構成されている」ことを意味する。
	// 許容されるパターン: 数字とカンマのみ、カンマが連続しても良い。
	// 妥当な行: 1個以上の数字とカンマの組み合わせ。
	// 空行は妥当ではない。数字とカンマ以外の文字は妥当ではない。

	// 正規表現の設計:
	// ^\s* : 行頭の空白を無視
	// (?:[0-9]+(?:,|$))+ : 1つ以上の数字の塊、それに続くカンマまたは行末
	// 厳密には「1個以上の数字列がカンマで区切られている」ことを確認する。
	// 各要素は「1個以上の数字」である必要がある。
	// 例: 1,2,3 または 1,2,3,
	// この正規表現は「数字がカンマで区切られている」ことを確認するのに適している。
	// 1個以上の数字 (\\d+) がカンマで区切られている。
	// (\\d+(?:,\\d+)*) : 最初の数字、それに続くカンマと数字の繰り返し。
	// 末尾のカンマを許容するため、行末がカンマで終わるか、数字の列で終わることを確認する。
	// 妥当な行は、少なくとも1つの数字が含まれ、数字とカンマ以外を含まない。
	// 例: 1,2,3 または 1,2,3,
	// 数字とカンマのみで構成されていることを確認する。
	// ^\s* : 行頭の空白
	// (?:[0-9]+(?:,[0-9]+)*) : 1個以上の数字列とカンマの組み合わせ。
	// 最後の要素がカンマで終わることも許容するため、末尾のカンマはオプションとする。
	// より簡単な定義: 少なくとも1つの数字が含まれ、数字とカンマ以外の文字を含まない。
	regex := regexp.MustCompile(`^\s*(?:[0-9]+(?:,[0-9]+)*)(?:,|$)`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 数字とカンマ以外の文字が含まれているかチェック (厳密な要求に基づく)
		// 空白を除去した行が、数字とカンマのみで構成されているかを確認する
		// 正規表現の調整: 数字とカンマのみで構成されているか。
		// 妥当な行: 1個以上の数字列がカンマで区切られている。
		// 1,2,3 または 1,2,3,

		// 妥当性の判定ロジックを、正規表現を使って再定義する。
		// 「1個以上の数字列がカンマで区切られて並んでいる」
		// これは、カンマで区切られた数字のシーケンスである必要がある。
		// 1. 行頭の空白を無視する。
		// 2. 数字とカンマのみで構成されている。
		// 3. 少なくとも1つの数字が含まれている。

		// この要件を満たすためには、カンマで区切られた数字列が主要な構造である。
		// 正規表現の再検討:
		// (?:[0-9]+(?:,[0-9]+)*) は、カンマ区切りの数字のシーケンスを捉える。
		// 末尾のカンマを許容する場合、行末がカンマで終わるか、数字で終わることを許容する。
		// よりシンプルなチェックとして、行が数字とカンマのみで構成されていることを確認する。
		isAlphanumericOnly := regexp.MustCompile(`^[0-9,]*$`).MatchString(trimmedLine)

		if !isAlphanumericOnly {
			// 数字とカンマ以外の文字が含まれている行は妥当ではない
			continue
		}

		// 数字とカンマのみの場合、少なくとも1つの数字が含まれているかチェックする。
		// ただし、"1,," や ",," は妥当ではない（1個以上の数字列）。
		// 数字が存在するかどうかを確認する。
		hasDigit := false
		for _, r := range trimmedLine {
			if r >= '0' && r <= '9' {
				hasDigit = true
				break
			}
		}

		if hasDigit {
			validCount++
		}
	}

	// 結果を出力
	fmt.Printf("valid=%d\n", validCount)
}
