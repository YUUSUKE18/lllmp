package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// 正規表現パターン: 
	// ^\s*        -> 行の先頭の任意の空白
	// (            -> グループ開始
	// [0-9,]+      -> 1文字以上の数字またはカンマ（数字列）
	// (,\s*       -> 1文字以上のカンマと任意の空白（区切り）
	// )*          -> 0回以上の繰り返し（最後のカンマや数字列の後に続く）
	// $           -> 行の末尾
	// このパターンは、カンマ区切りの整数列が1つ以上存在することをチェックするために調整する必要があります。
	// 仕様に基づき、「1個以上の数字列がカンマで区切られて並んでいること」を判定します。
	// 最小要件：数字とカンマのみで構成され、少なくとも1つの数字列が存在すること。
	// 許容される形式: 数字,数字,数字, ... または 数字,数字, ... , (末尾カンマも許容)
	
	// よりシンプルに、行が完全に数字とカンマのみで構成され、空行でないことを確認しつつ、
	// 少なくとも1つの数字列が存在するかどうかをチェックします。
	// 妥当な行の定義: 1個以上の数字列がカンマで区切られている。
	// これは、少なくとも1つの数字列が含まれ、かつ、それらがカンマで区切られている、という構造を意味します。
	
	// パターンを再定義: 
	// (?:[0-9]+(?:,[\s]|$))+  <- 1つ以上の数字列とカンマの組み合わせ（連続）
	// ただし、末尾のカンマも許容され、空行や数字以外の文字は許容されない。
	
	// 妥当な行のチェックロジック:
	// 1. 空行でないこと (scanner.Scan()が実行された場合、行は存在する)
	// 2. 行が数字とカンマのみで構成されていること。
	// 3. 少なくとも1つの数字列が含まれていること。

	// 行を読み込む
	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現チェック: 数字とカンマのみで構成されているか？
		// ^[0-9,]*$ : 行全体が数字とカンマのみで構成されている
		// このチェックだけでは「1個以上の数字列」を保証できないため、後続のチェックが必要。
		if !regexp.MustCompile(`^[0-9,]*$`).MatchString(trimmedLine) {
			// 数字とカンマ以外を含む行は妥当ではない
			continue
		}

		// 少なくとも1つの数字列が存在するかチェック
		// 数字列 [0-9]+ が少なくとも1回出現するかどうか
		if regexp.MustCompile(`[0-9]+`).MatchString(trimmedLine) {
			// このチェックでは、「1個以上の数字列がカンマで区切られている」という構造を完全に検証するには不十分です。
			// 仕様：「1 個以上の数字列がカンマで区切られて並んでいる」
			
			// 構造チェックを正規表現で厳密に行う
			// 形式: (数字)(,数字)*
			// 許容される最小構造: 数字列が1つ以上存在し、それらがカンマで区切られている。
			// 例: 1,2,3 または 1,2,3,
			
			// パターン: (数字列)(カンマとスペースの繰り返し) の組み合わせを考慮
			// 少なくとも1つの数字列が含まれており、その間にカンマが存在するか、または行が単一の数字列である。
			
			// 簡略化された解釈に基づき、行がカンマで区切られた数字のシーケンスであるかを確認します。
			// 数字列の境界がカンマであるべき。
			// ^[0-9]+(?:,[0-9]+)*$ : 1つ以上の数字列がカンマで区切られている（末尾カンマなし）
			// ^[0-9]+(?:,[0-9]+)*,?$ : 末尾カンマを許容する場合
			
			// 最終的な判定は、行が「数字」と「カンマ」のみで構成され、かつ「数字」が存在すること。
			// この仕様では、「カンマ区切り」という形式が主要なものであり、空行や不正文字の排除が最優先。
			// 空行と数字以外の文字の排除は行っているため、数字列が存在すれば妥当と見なします。
			
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常は不要だが、堅牢性のために）
	}

	fmt.Println("valid=", validCount)
}
