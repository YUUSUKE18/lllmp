package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^: 行の開始
	// [^,]*: 0個以上の数字とカンマ以外の文字（ただし、数字とカンマ以外は後のチェックで除外）
	// (\d+): 1つ以上の数字（これが最小の要素）
	// (?:,\d+)*: カンマとそれに続く数字の繰り返し（カンマ区切りで複数の数字がある場合）
	// (?:,)?$: 末尾のカンマは任意
	// この正規表現は「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// 実際には「数字とカンマのみ」で構成されており、少なくとも1つの数字が含まれていることを確認する必要があります。

	// 仕様に基づき、「1個以上の数字列がカンマで区切られて並んでいる」ことを判定します。
	// 許容されるパターンは、数字の羅列とカンマの組み合わせです。
	// 少なくとも一つの数字が含まれており、数字とカンマ以外は含まない、という条件をより厳密にチェックします。

	// 許容されるパターン: 1つ以上の数字とカンマの組み合わせ。
	// 数字(\d+)とカンマ(,)が交互に現れるか、数字の塊とカンマが続く形式。
	// 正規表現の解釈:
	// ^                  - 行の先頭
	// (?:              - 非キャプチャグループ（グループ化は不要）
	//     \d+          - 1つ以上の数字
	//     (?:,\d+)*   - カンマとそれに続く数字の繰り返し（複数の要素）
	// )
	// $                  - 行の末尾

	// ただし、「末尾のカンマは許容する」という点も考慮する必要があります。
	// 例えば "1,2," は妥当。
	// 空行は不妥当。
	// 数字とカンマ以外は不妥当。

	// より単純に、行が空でないこと、かつ行に含まれる文字が数字とカンマのみであることを確認し、
	// 少なくとも1つの数字が含まれていることを確認するアプローチを採用します。

	// 1. 空行チェックと文字セットチェック
	// 2. 数字が含まれているかチェック

	// 正規表現で「数字とカンマのみで構成されていること」と「少なくとも1つの数字が含まれていること」を同時にチェックするのは複雑です。
	// 仕様の「1個以上の数字列がカンマで区切られて並んでいる」に焦点を当てます。

	// パターン定義:
	// ^                 - 行の開始
	// (?:               - 非キャプチャグループ
	//     \d+           - 1つ以上の数字
	//     (?:,?\d+)*    - カンマと任意の数の数字が続くパターン
	// )
	// (?:,|$)            - 行末がカンマか、行末か（末尾のカンマ許容）
	// ここが非常に複雑になるため、後続の処理で検証します。

	// ステップバイステップで検証する方が実装が容易かつ仕様に忠実です。
	// 正規表現は、入力された文字列が「数字とカンマのみで構成されており、1つ以上の数字が含まれている」ことを確認するために使用します。

	// 判定用の正規表現:
	// このパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
	// \d+ は1つ以上の数字。カンマは区切り文字として機能する。
	// ^[0-9,]*$ : 数字とカンマのみで構成されている。
	// \d : 少なくとも1つの数字が含まれている（これは全体の制約として既に含まれている）。

	// 妥当な行の判定（後続の厳密なチェックを組み合わせる）
	// 行が空でないこと、かつ、行が数字とカンマ以外の文字を含まないこと。

	validRegex := regexp.MustCompile(`^[\d,]*$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 1. 数字とカンマ以外が含まれていないかチェック
		if !validRegex.MatchString(line) {
			continue
		}

		// 2. 少なくとも1つの数字が含まれているかチェック
		// もし行が " , " や ",," のようなカンマだけで構成されている場合、これは不妥当。
		hasDigit := false
		for _, char := range line {
			if char >= '0' && char <= '9' {
				hasDigit = true
				break
			}
		}

		if hasDigit {
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常は無視されることが多いが、念のため）
	}

	fmt.Printf("valid=%d\n", validCount)
}
