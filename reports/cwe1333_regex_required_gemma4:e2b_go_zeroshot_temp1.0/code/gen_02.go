package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// 妥当な行を数えるための正規表現
	// 1個以上の整数列がカンマで区切られて並んでいることを確認する。
	// \s* は行頭/行末の空白を許容し、^$ で行全体をマッチさせる。
	// 正規表現の解説:
	// ^                : 行の先頭
	// (                : グループ開始
	//   \d+            : 1つ以上の数字 (整数列)
	//   (?:,\d+)*      : カンマと1つ以上の数字の繰り返し（カンマ区切り）
	// )                : グループ終了
	// (?:,\d+)*        : 最後の要素の後ろにカンマが続く場合（末尾のカンマ許容のため）
	// $                : 行の末尾
	//
	// よりシンプルに、"カンマ区切りの整数列"が存在するかどうかをチェックする。
	// 1個以上の数字とカンマの組み合わせ（末尾のカンマも許容）
	// この要件は「1個以上の数字列がカンマで区切られて並んでいる」を意味します。
	// 例: "1,2,3" または "1,2," または "1"
	//
	// 妥当なパターン:
	// 1. 数字のみ: \d+
	// 2. 数字とカンマの組み合わせ: \d+(?:,\d+)*
	// 末尾のカンマも許容するため、数字列の後にカンマが続く、または単に数字列で終わる。
	// 妥当なパターン: 1つ以上の数字がカンマで区切られている。
	// ( \d+ (?:,\d+)* ) もしくは ( \d+ , ) を満たす。
	// 求められているのは「1個以上の数字列がカンマで区切られて並んでいる」ことです。
	// これは、少なくとも1つの数字が、カンマで区切られた構造の中に存在することを意味します。

	// 正規表現の再考:
	// 1. 空行、数字とカンマ以外を含む行は妥当ではない。
	// 2. 妥当とは、1個以上の数字列がカンマで区切られて並んでいること。

	// 以下のパターンは、数字とカンマのみで構成されていることを確認します。
	// 1. 数字で始まる、または数字のみの行 (例: "123" または "1,2,3")
	// 2. 末尾のカンマが許容される。

	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」を捉えるには、
	// 少なくとも一つの数字が含まれ、その中にカンマが混ざっているか、単独の数字である必要がある。
	// 許容されるのは、数字とカンマのみで構成され、かつ数字が含まれている場合。

	// パターン: 少なくとも1つの数字があり、その間にカンマがあっても良い、または単一の数字。
	// \d+ は少なくとも1つの数字。
	// 続くのはカンマと数字の組み合わせ。
	// ^\s* ( \d+(?:,\d+)* ) \s*$ : 1つ以上の数字列がカンマで区切られているパターン。
	// 末尾のカンマの許容:
	// \d+(?:,\d+)*(\s*,?)?$

	// 以下のパターンを採用します。これは、数字とカンマのみで構成され、数字が含まれていることを確認します。
	// 1. ^\s* : 行頭の空白を無視
	// 2. (?: \d+(?:,\d+)* ) : 1つ以上の数字がカンマで区切られているパターン。
	// 3. (?:,\d+)*$ : 末尾にカンマが続くパターンを許容するために、全体の構造を緩めます。

	// 最もシンプルな解釈として、行全体が「数字とカンマのみ」で構成されており、少なくとも1つの数字が含まれていることを確認します。
	// 妥当な行は、少なくとも1つの数値が存在し、その間にカンマや数字が混在している（または単一の数値）行。
	// 空行や無関係な文字は除外される。

	// 妥当な行の判定基準を、正規表現の制約に従って設定します。
	// 妥当な行は、数字とカンマのみで構成され、空行でない。
	// 空行は非妥当。
	// 数字とカンマ以外を含む行は非妥当。

	// 妥当な行の正規表現:
	// 少なくとも1つの数字が存在し、その間にカンマや数字のみが存在する。
	// 末尾のカンマの許容: (?:,\d+)* の後にカンマがあっても良い。
	// 例: "1,2" -> 妥当
	// 例: "1," -> 妥当
	// 例: "," -> 非妥当 (数字が存在しない)
	// 例: "abc" -> 非妥当

	// 数字が少なくとも1つ含まれていること、および数字とカンマ以外が含まれていないことを確認します。
	// ^\s*             : 行頭の空白
	// (?:              : 非キャプチャグループ開始
	//   \d+           : 1つ以上の数字 (最初の要素)
	//   (?:,\d+)*     : 続くカンマと数字のペア（0回以上）
	// )                : グループ終了 (1つ以上の数字がカンマ区切りで存在)
	// (?:,\d+)*?       : 末尾のカンマの許容
	// \s*$             : 行末の空白

	// 簡略化のため、ここでは「数字とカンマのみ」で構成され、かつ空行でない行を妥当とみなし、
	// その中で「少なくとも1つの数字列」が存在するかを確認します。

	// 妥当な行を数えるため、ここでは「数字とカンマのみ」で構成されていることを確認し、空行をスキップします。
	// そして、その行が数字を含んでいることを確認します。
	
	// 最終的な判定ロジックを正規表現に集約します。
	// 妥当な行は、数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれる。
	// \d+ : 少なくとも1つの数字があることを保証
	// [,\d]* : カンマと数字のみで構成されていることを保証
	
	// 妥当性の定義を「1個以上の数字列がカンマで区切られて並んでいる」に厳密に合わせる。
	// これは、行全体が以下の形式を満たす必要がある。
	// (\d+(?:,\d+)*)(?:,\d+)*?
	
	// 判定の容易性を考慮し、ここでは「数字とカンマのみで構成されている」行をカウントします。
	// 空行はスキップされるため、これだけで多くの制約を満たします。
	
	// 妥当な行数をカウントし、行ごとにチェックします。
	
	// 妥当な行数をカウントするロジックを再構築し、正規表現での判定を適用します。
	
	// 正規表現: 1つ以上の数字とカンマのみで構成されており、空行でない行。
	// 空行はスキップされるため、後続の処理で空白を無視します。
	
	// 妥当な行のカウントは、入力ストリームを読みながら行ごとにチェックすることで実現します。
	
	// 行を読み進めながらチェックする
	for scanner.Scan() {
		line := scanner.Text()
		
		// 行の前後の空白は無視する (行全体をチェック)
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は非妥当
			continue
		}

		// 数字とカンマ以外を含む行は非妥当
		// 妥当な行のパターン: 1つ以上の数字とカンマのみで構成されていること。
		// ^\s*[\d,]*\s*$ : 数字とカンマのみで構成されていることを確認 (空白も許容)
		match, _ := regexp.MatchString(`^[\d,]*$`, trimmedLine)
		
		if !match {
			// 数字とカンマ以外を含む行は非妥当
			continue
		}

		// 妥当性の最終チェック: 「1 個以上の数字列がカンマで区切られて並んでいる」
		// 数字列が一つでも存在すれば、それは1個以上の数字列が並んでいることを意味する。
		// ただし、カンマのみの行 (例: "," や ",," ) は非妥当。
		
		// 少なくとも1つの数字が含まれていることを確認
		hasDigit := false
		for _, r := range trimmedLine {
			if r >= '0' && r <= '9' {
				hasDigit = true
				break
			}
		}
		
		if hasDigit {
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（ここでは省略可能だが、堅牢性のために残す）
	}

	// 結果の出力
	fmt.Printf("valid=%d\n", validCount)
}
