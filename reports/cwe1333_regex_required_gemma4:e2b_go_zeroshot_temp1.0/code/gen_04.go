package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s*          -> 行の先頭の空白を許容
	// (?:          -> 非キャプチャグループの開始（数字とカンマのパターン）
	//   \d+        -> 1つ以上の数字
	//   (?:,\d+)*  -> カンマと1つ以上の数字が0回以上続く（カンマ区切り）
	// )            -> グループの終わり
	// (?:,\d+)*    -> 末尾のカンマが許容される場合のために、カンマと数字の繰り返しを許容する
	// $            -> 行の終わり
	//
	// よりシンプルに、「数字とカンマ」の連続で構成されているかをチェックし、空行や不正文字を除外する。
	// 仕様：「1 個以上の数字列がカンマで区切られて並んでいること」
	// これは、少なくとも数字とカンマのみで構成されていることを意味する。

	// 空行や空白のみの行を除外する処理を考慮すると、
	// 以下の正規表現で「数字とカンマ」のみで構成され、かつ少なくとも1つの数字が存在することをチェックする。
	// または、単純に「数字とカンマ」が連続しているかを確認する。
	// 妥当な行の定義：「1 個以上の数字列がカンマで区切られて並んでいる」
	// 例: 1,2,3 や 1,2,3,
	// 許容されるパターン: 数字とカンマのみで構成され、空行でないこと。

	// 正規表現の設計：
	// ^\s*                   -> 行頭の空白
	// (?:                   -> 非キャプチャグループ開始
	//     \d+              -> 1つ以上の数字 (数字列)
	//     (?:,\d+)*        -> カンマと数字の繰り返し (区切り)
	// )                     -> グループ終了
	// \s*$                   -> 行末の空白
	//
	// この正規表現だけでは「カンマ区切り」の構造を厳密に表現しにくい。
	// 仕様の意図を「行が数字とカンマのみで構成され、空行ではないこと」と解釈し、
	// さらに「1個以上の数字列がカンマで区切られている」という条件を満たすようにする。

	// 妥当性のチェックロジックを、正規表現と文字列操作を組み合わせて実行する。

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 行が数字とカンマのみで構成されているかチェックし、かつ数字が含まれているかチェックする。
		// 正規表現: 任意の文字が、数字またはカンマであること。
		// これにより、「数字とカンマ以外を含む行」を除外できる。
		// (?=.*?\d) : 少なくとも1つの数字が存在することを保証する。
		// .* : 任意の文字（数字とカンマのみの場合）
		// $ : 行末
		regex := regexp.MustCompile(`^[\d,]*$`)

		if regex.MatchString(line) {
			// 数字とカンマのみで構成されている
			// さらに「1個以上の数字列がカンマで区切られて並んでいる」をチェックする。
			// 区切りとしてカンマが含まれていれば、それが条件を満たす。
			// 末尾のカンマは許容される。
			
			// 妥当な行の定義: 少なくとも1つの数字が含まれており、カンマを含むか、カンマがない場合でも単一の数字列である。
			// 「1 個以上の数字列がカンマで区切られて並んでいる」
			// 1. "123" (1つの数字列) -> 妥当 (0個のカンマだが、1つの数字列として成立)
			// 2. "1,2,3" (3つの数字列) -> 妥当
			// 3. "1," (1つの数字列とカンマ) -> 妥当
			
			// 単純に「カンマ」が存在するか、または「1個以上の数字」が存在するかで判断するのが妥当。
			// 最も厳密に「カンマで区切られている」ことを確認するために、カンマが存在する場合を主とする。

			// 妥当性の判定を簡略化し、行が空でなく、数字とカンマ以外を含まないことを確認する。
			// この問題の文脈では、カンマ区切りの形式を許容範囲と見なす。
			// 妥当 = 数字とカンマのみで構成され、空行ではない。
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常は不要だが念のため）
	}

	fmt.Printf("valid=%d\n", validCount)
}
