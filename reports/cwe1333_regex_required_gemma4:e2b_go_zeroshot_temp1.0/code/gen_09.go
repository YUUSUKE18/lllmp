package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列、またはカンマのみの列を許容する正規表現
	// ^\s*                : 行頭の空白を無視
	// ([\d,]+)            : 1つ以上の数字またはカンマのシーケンスをキャプチャ
	// (\s*,\s*)*           : ゼロ個以上の、カンマと空白のペア（末尾のカンマを許容するため）
	// $                  : 行末
	// この正規表現は、実質的に「数字とカンマのみで構成され、少なくとも1つの数字が含まれている」ことを確認します。
	// ただし、仕様の「1 個以上の数字列がカンマで区切られて並んでいる」を厳密に捉えるため、
	// 各要素が整数であることを確認するために、より複雑なアプローチが必要になる場合があります。

	// 仕様の再解釈：各要素が整数であり、それらがカンマで区切られていること。
	// 妥当な行は、カンマ区切りの整数列、またはカンマのみの列。
	// 空行や数字とカンマ以外の文字を含む行は無効。

	// 妥当な行の判定ロジックを、正規表現と文字列操作で組み合わせることを検討します。

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 行がカンマと数字のみで構成されているかを確認する（数字とカンマ以外の文字は許容されない）
		if !regexp.MustCompile(`^[\d,]*$`).MatchString(trimmedLine) {
			// 数字とカンマ以外の文字を含む行は妥当ではない
			continue
		}

		// 妥当性の判定: 1個以上の数字列がカンマで区切られて並んでいること。
		// これは、カンマが少なくとも1つ存在するか、またはカンマがない場合でも数字のみである必要がある。
		// 「1 個以上の数字列がカンマで区切られて並んでいる」
		// -> これは、カンマで区切られた複数の要素（数字）が存在することを意味する。

		// 1. カンマを含む行、またはカンマで区切られた要素が複数ある行
		if strings.Contains(trimmedLine, ",") {
			// カンマを含む行は、少なくとも1つの数字列が存在すれば妥当と見なせる。
			// ただし、"1," や "," のような、数字列ではないものが存在しないか確認が必要。
			parts := strings.Split(trimmedLine, ",")
			hasDigits := false
			for _, part := range parts {
				// 各部分が空でない、または数字のみで構成されているかチェック
				if strings.TrimSpace(part) != "" {
					if regexp.MustCompile(`^\d+$`).MatchString(strings.TrimSpace(part)) {
						hasDigits = true
					}
				}
			}
			if hasDigits {
				validCount++
			}
		} else {
			// カンマを含まない行の場合 (例: "123" や "")
			// 仕様：「1 個以上の数字列がカンマで区切られて並んでいる」
			// カンマがない場合、それは1つの数字列のみを意味する。
			// "1 個以上の数字列がカンマで区切られて並んでいる" は、カンマ区切りでない場合は不適と解釈するのが妥当。
			// しかし、「妥当とは、1 個以上の数字列がカンマで区切られて並んでいることです」という定義に従うと、カンマがない行は不適。
			// 例: "123" は1つの数字列のみ。区切りがないため、複数列ではない。
			// したがって、カンマを含まない行は妥当ではない。
		}
	}

	// 標準出力へ出力
	fmt.Printf("valid=%d\n", validCount)
}
