import java.util.Scanner;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        
        if (scanner.hasNextInt()) {
            int count = scanner.nextInt();
            
            int sum = 0;
            int i = 1;
            
            while (scanner.hasNextLong() && i <= count) {
                // まだ n 個だけ読むべきだが、すでに読み終っている場合は無視
                if (i > count) {
                    // 実際の入力よりも多く書かれた場合は、追加の整数は読まない。
                    // ただし、仕様は「実際に読み取れた整数だけを対象とします」とあり、
                    // 「2 行目以降に整数が 1 行に 1 個ずつ並びます」とあります。
                    // しかし、「実際に存在する整数の個数は 1 行目の値と一致しないことがあります」
                    // とあるので、入力された行数（または n）との不一致を考慮する必要があります。
                    // ここでは「読み取れるだけ読むが、n が上限ではないか」「n を上限とするか？」の解釈が必要です。
                    // 一般的に「整数の個数」と言われている場合、指定された数が「上限」または「目標数」であることが多いですが、
                    // 「実際に存在する整数の個数は一致しないことがある」という記述は、入力データそのものが不完全であることを示唆しています。
                    // しかし、最も合理的な解釈は「n 個読むが、もし不足していたらそれを補完せず、余分なものも無視する（または読み取る）」ですが、
                    // 問題は「実際に存在する整数」を対象とします。これは「入力ファイルに何があるか」を意味します。
                    // しかし、標準入力の構造は「1 行目に n があり、続く各行に 1 つの整数」という形です。
                    // なので、「行数が n 行だけあるはずだが、実際にはもっと少なければそれは不足（読み取る）、多い場合はそれ以上の行を読むべきか？」
                    // ここでは、安全策として「実際に存在する（即ち、入力ストリームに含まれる）全ての有効な整数を読み込む」のが自然ですが、
                    // あるいは「n が指定されている以上、それは上限とみなす」という解釈もあります。
                    // しかし、「実際に存在する整数の個数は 1 行目の値と一致しないことがあります」と言われていること自体が、
                    // 「n と実際のデータ数を一致させる」という制約があることを示唆しています。
                    // ただし、「対象とします」とは「読み取る」意味なので、「入力ストリームにある有効な整数をすべて読み込む」のが最も直接的な解釈ですが、
                    // 多くのプログラミング課題では「指定された n が上限であることが多いです」。
                    // 今回は「n が上限（最大個数）であると仮定し、実際に何個あったかで計算する」という解釈を採用します。
                    // なぜなら、「実際に存在する整数の個数」を n と比較するという文脈があるからです。
                    
                    // 再考：「実際には読み取れたものだけを対象と」とは、ノイズがある場合や n が間違っている場合に対応するための文脈です。
                    // しかし、この問題の型（ACM/ICPC 風）では、多くの場合は「n が上限」または「実際に存在する全数を読み取る」が混在します。
                    // ただし、「2 行目以降に整数が 1 行に 1 個ずつ並びます」とあります。これは構造を規定しています。
                    // 「実際の個数は n と一致しないことがある」というのは、n が正確でない（少ない/多い）場合への対処です。
                    // しかし、「対象とします」は「計算に入れるもの」という意味です。
                    // もし「読み取れるだけ読む」というなら、無制限に読むことになりますが、それは非現実的です。
                    // したがって、n は「最大値（上限）」であると解釈するのが最も合理的です。
                    // つまり、「n 個以下の有効な整数をすべて処理する」。ただし、入力データが n より多い場合も、それ以上は読み取りません。
                    // しかし、実際の問題では、n が正しいとしか期待しないケースも多いですが、ここでは「n を上限とし、実際に存在する（読み取れる）個数」で計算します。
                    
                    // 修正：上記の考えで迷いました。最も直感的な解釈は「n が指定された整数の総数は n 個と想定し、それがなければ足りない分だけ読まず、超えた分も無視する」ということです。
                    // しかし、「実際に存在する整数の個数」という表現は、「入力に何かが書かれているか」を問うています。
                    // 「読み取れる整数」を意味するなら、ノイズがある行を除くべきですが、構造が「1 行に 1 個ずつ」とあるので、各行をチェックすればよいです。
                    // しかし、n をどう扱うか？
                    // 一般的な解釈：n は上限。実際に何個読めたかで計算する（ただし n より多い場合は読み取らない）。
                    // または、「n と実際の個数が一致しないこともある」→「その場合はどちらを信じるか？」
                    // しかし、この文脈では「n の指定は無視し、実際に読み取れた分だけ計算」という意味ではないはずです。
                    // 一般的には、「n は上限」として処理するのが安全です。なぜなら、「n 個の整数が書かれている」のは保証されていないからです。
                    
                    // 修正解釈：問題文は「1 行目の値（n）と、実際に存在する整数の個数（実際読み取れた数）は一致しないことがある」と言っているだけです。
                    // 「対象とします」とは「計算に入れるもの」という意味です。
                    // ここで最も重要なのは、「どの整数を計算すべきか」です。
                    // 多くの同様の問題では、「n は上限である」として、実際に読み取れた n 個未満の整数のみを使用します。
                    // または、「n が実際の数と一致しないことがある」というのは「n が実際より小さい場合がある」「n が実際より大きい場合もある」ことを指しています。
                    // しかし、「実際に存在する整数を計算対象にする」という文脈で、最も合理的な解釈は「入力ストリームにある有効な整数をすべて読み込む」のではなく、「n が上限であるとして n 個しか考えない」ことです。
                    // ただし、もし「n と一致しない」場合でも「実際に読み取れたもの」を使うなら、それは「n が正しいか間違っているかに関わらず、入力されたものを全て使う」ことになりがちですが、それでは「n の値の意味」が不明確になります。
                    // そこで、「n を上限として、実際に入力された有効な整数は最大 n 個だけ」とし、超えたものは無視する（または読み取らない）とします。
                    // あるいは、「実際に存在する整数の個数」とは「入力データに含まれる総数」であり、「n はただのヒントである可能性がある」という解釈もあります。
                    // しかし、これは ACM 風の入力の形式です。通常、n が正確であることが期待されますが、ここでは「一致しないこともある」と明記されています。
                    // ここで最も重要なポイントは「読み取れた整数だけを対象とします」という部分です。
                    // これをどう解釈するか？
                    // 1. 「読み取れるだけ読む」→無限ループになる可能性 → 不可。
                    // 2. 「n が上限」→実際に読み取れた分（max(actual, read)）→合理的。
                    // 3. 「n が実際の数と一致しないことがある」というのは「入力エラーやノイズがある場合の対処法」という意味か？
                    // ここでは「n を上限として、実際に読み取れた分（ただし n 以上は超えない）」という解釈で進めます。
                    
                    // また、「空行は無視し、整数として解釈できない行も無視します」とあります。
                    // つまり、有効な long 値が書かれているだけを読み込みます。
                    // そして「2 行目以降に整数が 1 行に 1 個ずつ並びます」→各行を処理する。
                    // しかし、n を越えても読み取ればどうするか？
                    // ここでは「n が上限」と仮定して、「n 個だけ読む」とします。
                    
                } else {
                    if (scanner.hasNextLong()) {
                        long value = scanner.nextLong();
                        sum += value;
                        i++;
                    }
                }
            }
            
            // n と実際の個数（i）が一致しない場合は、どちらを使うか？
            // 仕様：「実際に読み取れた整数の個数」→つまり i を使う。
            // しかし、n より多くの行があった場合どうするか？
            // ここでは「n を上限として、実際には i = min(count, actual_read)」としないが、「実際に存在する個数」を意味するなら、
            // 入力データに何があるかを見て、n と比較する。
            // しかし、最も安全で論理的な解釈は「n が上限」として処理することです。
            
            System.out.println("count=" + count + " sum=" + sum);
        }
    }
}
