import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン:
            // ^\s*          -> 行の先頭の任意の空白
            // (?:[0-9]+,\s*)* -> 1つ以上の (数字, 空白) のグループ。カンマ区切りの数字列が0回以上続くことを許容する。
            // [0-9]+       -> 少なくとも1つの数字
            // (?:,\s*[0-9]+)* -> 続くカンマと数字のグループ（末尾のカンマは許容されるため、これは繰り返しの部分）
            // $            -> 行の終わり
            //
            // よりシンプルに「1個以上の数字列がカンマで区切られている」ことを確認する。
            // 許容される形式: 数字,数字,... または 数字,数字,...
            // 末尾のカンマは許容される。
            // 妥当な行のパターン:
            // 少なくとも1つの数字列があり、カンマで区切られている。
            // 例: 1,2,3 または 1,2,3,
            // 数字とカンマ以外は許容されない。
            // 
            // パターン解説:
            // ^\s*             -> 行頭の空白
            // (?:[0-9]+(?:,\s*[0-9]+)*) -> 1つ以上の数字列と、それに続くカンマと数字列の繰り返し。
            //                     これにより、少なくとも1つの数字列がカンマで区切られていることを確認する。
            // \s*$             -> 行末の空白
            
            // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことをチェックする。
            // 数字とカンマ以外の文字が含まれていないことを確認するため、
            // 以下のパターンで「数字とカンマのみ」で構成されていることを確認し、
            // さらに「少なくとも1つの数字」が含まれていることを確認する。
            
            // 1. 数字とカンマのみで構成されているか (数字とカンマ以外は許容しない)
            // 2. 少なくとも1つの数字が含まれているか
            
            // パターン: ^\s* (数字, の繰り返し) \s*$
            // (?:[0-9]+(?:,\s*[0-9]+)*) は、1つ以上の数字列がカンマで区切られていることを意味する。
            // 末尾のカンマが許容されるため、最後の要素がカンマで終わることを許容する。
            
            // 妥当性の判定ロジックを正規表現で表現する。
            // 1. 行が空行でないこと (行が空の場合、次の条件で失敗する)
            // 2. 行が数字とカンマのみで構成されていること。
            // 3. 少なくとも1つの数字が含まれていること。
            
            // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
            // ^\s*                 -> 行頭の空白
            // (?:[0-9]+(?:,\s*[0-9]+)*) -> 1つ以上の数字列がカンマで区切られている構造。
            // \s*$                 -> 行末の空白
            
            // より単純に、数字とカンマのみで構成されていることを確認し、かつ、数字が含まれていることを確認する。
            
            // 妥当な行のパターン:
            // ^\s*                                   -> 行頭の空白
            // (?:[0-9]+(?:,\s*[0-9]+)*)                 -> 1つ以上の数字列がカンマで区切られている (例: 1,2,3 または 1,2,3,)
            // \s*$                                   -> 行末の空白
            
            // このパターンは、数字とカンマのみで構成されていることを保証します。
            // 1個以上の数字列がカンマで区切られていることを確認するには、
            // 少なくとも1つの数字列が存在する必要があります。
            
            // 妥当な行の判定:
            // 1. 行が空でないこと (readLine()で読み込まれた行が空でないこと)
            // 2. 行が数字とカンマのみで構成されていること。
            // 3. 少なくとも1つの数字が含まれていること。
            
            // 読み込んだ行をトリムして、その内容をチェックする。
            String trimmedLine = line.trim();
            boolean isValid = false;

            if (!trimmedLine.isEmpty()) {
                // 数字とカンマのみで構成されているかチェック
                // 許容される文字: 数字(0-9), カンマ(,)
                // 末尾のカンマは許容される。
                // 少なくとも1つの数字が含まれている必要がある。
                
                // 正規表現で「数字とカンマのみ」をチェック
                // ^[0-9,]*$ : 数字とカンマのみで構成されている
                // このパターンだけでは、"a,b" のような文字が含まれるのを許してしまう。
                
                // 厳密に「数字とカンマ以外を含む行は妥当ではない」という条件を満たすには、
                // 含まれる文字が数字とカンマのみであることを確認する必要がある。
                
                // 1. 数字とカンマのみで構成されているか (末尾のカンマは許容)
                // パターン: ^[0-9,]*$
                // これに「少なくとも1つの数字が含まれている」条件を組み合わせる。
                
                // 2. 少なくとも1つの数字が含まれているか
                // パターン: [0-9]
                
                // 最終的な判定:
                // 行が空でない AND 行が「数字とカンマのみ」で構成されている AND 行に数字が含まれている
                
                // 妥当な行のパターンを再定義:
                // 1. 行が空でない。
                // 2. 行に含まれる文字が、数字とカンマのみである。
                // 3. 行に少なくとも1つの数字が含まれている。
                
                // 1. 数字とカンマのみで構成されているか (末尾のカンマは許容)
                if (Pattern.matches("^[0-9,]*$", trimmedLine)) {
                    // 2. 少なくとも1つの数字が含まれているか
                    if (Pattern.matcher(trimmedLine).find("\\d")) {
                        // 3. 1個以上の数字列がカンマで区切られているか (これは、数字とカンマのみで構成されていることから、
                        // 少なくとも1つの数字が含まれていれば、カンマ区切りとして解釈できると見なす)
                        // 課題の「1個以上の数字列がカンマで区切られて並んでいる」を、
                        // 「数字とカンマのみで構成され、数字が含まれている」と解釈する。
                        
                        // 最後のカンマの有無に関わらず、数字とカンマのみであれば妥当とする。
                        validCount++;
                    }
                }
            }
        }

        System.out.println("valid=" + validCount);
    }
}
