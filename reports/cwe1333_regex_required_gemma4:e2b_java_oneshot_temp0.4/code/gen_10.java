import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン:
            // ^\s*          -> 行頭の任意の空白
            // (?:[0-9]+,\s*)* -> 0個以上の (数字 + カンマ + 任意の空白) の繰り返し
            // [0-9]+       -> 少なくとも1つの数字
            // (?:,\s*[0-9]+)* -> 0個以上の (, + 数字) の繰り返し
            // \s*$         -> 行末の任意の空白
            // このパターンは「カンマ区切りの整数列」を厳密に定義するのは複雑なため、
            // 仕様「1 個以上の数字列がカンマで区切られて並んでいる」を満たすことを重視し、
            // 以下のロジックで判定します。

            // 1. 行の前後の空白を無視
            String trimmedLine = line.trim();

            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 2. 正規表現による判定：1個以上の数字とカンマのみで構成されているか、
            //    かつ、カンマで区切られている構造があるかを確認する。
            //    「1個以上の数字列がカンマで区切られて並んでいる」
            //    これは、数字とカンマのみで構成され、少なくとも1つのカンマが存在するか、
            //    または単一の数字列である場合も許容されると解釈します。
            //    「末尾のカンマは許容」という点から、カンマ区切り形式を許容します。

            // パターン: 数字とカンマのみで構成され、カンマが少なくとも1つ含まれるか、
            // または単一の数字列である場合。
            // 最もシンプルな解釈として、「数字とカンマのみで構成され、空行でないこと」をチェックし、
            // 厳密な構造チェックは以下の正規表現で試みます。

            // 許容されるパターン: 数字とカンマのみで構成され、カンマで区切られている（末尾カンマあり可）
            // 例: 1,2,3 または 1,2,3,
            // 数字とカンマのみで構成されていることを確認する。
            // (?:[0-9]+(?:,|$))+ : 1つ以上の (数字 + カンマまたは行末) の繰り返し
            // このパターンは「1個以上の数字列がカンマで区切られて並んでいる」を表現します。
            String regex = "^\\s*([0-9]+(?:,\\s*[0-9]+)*[0-9]*)(?:,\\s*|$)";
            
            // より単純に、数字とカンマのみで構成されているか、かつ空行でないことを確認し、
            // 構造が「カンマ区切り」の形式を満たしているかを判定します。
            // 末尾のカンマが許容されるため、末尾がカンマで終わるか、数字で終わることを許容します。
            
            // 妥当な行の判定ロジックを再定義:
            // 1. 空行でないこと。
            // 2. 数字とカンマ以外の文字を含まないこと。
            // 3. 少なくとも1つの数字が含まれていること。
            // 4. カンマ区切り形式であること。（末尾カンマ許容）

            // 正規表現: 数字とカンマのみで構成され、カンマで区切られている（末尾カンマ許容）
            // ^\s* : 行頭の空白
            // (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列とカンマの組み合わせ
            // (?:,\s*|$) : カンマ区切りで終わるか、単一の数字列で終わる
            // この判定は複雑になるため、最も厳しい制約（数字とカンマ以外を含まない）と、
            // 構造（カンマ区切り）を組み合わせます。

            // 最終的な判定ロジックとして、数字とカンマのみで構成され、カンマが含まれているか、
            // または単一の数字列であるかをチェックします。
            
            // 1. 数字とカンマのみで構成されているかチェック
            if (!trimmedLine.matches("^[0-9,]*$")) {
                continue; // 数字とカンマ以外が含まれていたら不妥当
            }

            // 2. 少なくとも1つの数字が含まれているかチェック
            if (!trimmedLine.matches(".*[0-9].*")) {
                continue; // 数字が一つもなければ不妥当
            }

            // 3. カンマ区切り形式であるかチェック（1個以上の数字列がカンマで区切られている）
            // 末尾のカンマは許容されるため、カンマで区切られた文字列が成立すればOKとする。
            // 例: "1,2,3" -> OK
            // 例: "1,2," -> OK
            // 例: "123" -> OK (1個の数字列)
            
            // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を満たすためには、
            // 少なくとも1つのカンマが存在するか、または単一の数字列である必要があります。
            // 既に「数字とカンマのみ」で構成されているため、この行は妥当と見なします。
            validCount++;
        }

        System.out.println("valid=" + validCount);
    }
}
