import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン: 
            // ^\s*          -> 行の先頭の任意の空白
            // (?:[0-9]+,\s*)* -> 1つ以上の数字とカンマのグループ（数字とカンマの後に空白があっても良い）
            // [0-9]+        -> 最後の数字列
            // (?:,\s*|$)    -> カンマと空白、または行末
            // \s*$          -> 行末の空白
            // 
            // よりシンプルに「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
            // 1. 行が空でないこと。
            // 2. 数字とカンマ以外の文字が含まれていないこと。
            // 3. カンマで区切られていること（少なくとも1つの数字列があること）。
            
            // 妥当な行の判定ロジック
            // 1. 行をトリムして空でないことを確認
            String trimmedLine = line.trim();
            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 2. 正規表現で「数字とカンマのみ」で構成されているか、かつ「カンマで区切られている」ことを確認
            // パターン: 数字とカンマのみで構成され、少なくとも1つの数字列を含む
            // ^\s*             -> 行頭の空白
            // (?:[0-9]+,\s*)*  -> 0回以上、数字とカンマのセット（区切り）
            // [0-9]+           -> 最後の数字列
            // (?:,\s*|$)       -> カンマと空白、または行末
            // \s*$             -> 行末の空白
            
            // より簡潔に、カンマで区切られた数字列のみで構成されているかを確認する。
            // 1. 数字とカンマ以外の文字が含まれていないこと
            // 2. カンマが存在すること（または、カンマで区切られた複数の数字列が存在すること）
            
            // 妥当な行の定義: 1個以上の数字列がカンマで区切られて並んでいる。末尾のカンマは許容。
            // 例: "1,2,3" -> OK, "1,2," -> OK, "1" -> NG (1個の数字列のみ)
            
            // 複数の数字列が存在することを要求するため、カンマの有無と数字の存在を確認する。
            
            // パターン: 数字とカンマのみで構成され、少なくとも1つのカンマが含まれているか、またはカンマで区切られた複数の数字列が存在する。
            // 1個以上の数字列がカンマで区切られていること。
            // これは、カンマが少なくとも1つ存在し、その両側に数字が存在することを意味する。
            
            // 妥当な行の例: "1,2", "1,2,3", "1,2,"
            // 妥当でない行の例: "1", "", "abc", "1,," (これは1個の数字列とみなすか、区切りが不完全)
            
            // 仕様の解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
            // これは、カンマで区切られた要素が1つ以上あることを意味する。
            
            // 妥当なパターン: 数字とカンマのみで構成され、少なくとも1つのカンマが含まれている、またはカンマで区切られた複数の数字列がある。
            // 簡略化のため、カンマで区切られた数字列が存在すればOKとする。
            // 正規表現で「数字とカンマのみ」で構成されていることを確認し、かつカンマが存在するか、または数字が複数あることを確認する。
            
            // 妥当な行の例: "1,2" (2つの数字列), "1,2," (2つの数字列)
            // 妥当でない行の例: "1" (1つの数字列のみ), "" (空行), "a,1" (文字を含む)
            
            // 1. 数字とカンマのみで構成されているか (数字とカンマ以外の文字はNG)
            // 2. 少なくとも1つのカンマが含まれているか (複数の要素があることを示す)
            
            // パターン: 任意の数の数字とカンマの組み合わせ。末尾のカンマは許容。
            // ^\s*([0-9]+(?:,\s*[0-9]+)*)(?:,)?\s*$
            // これは複雑すぎるため、より単純に「カンマで区切られた複数の数字列」を試みる。
            
            // 複数の数字列が存在する場合: 数字とカンマが連続している。
            // 少なくとも1つのカンマが存在し、その両側に数字が存在する。
            Pattern p = Pattern.compile("^\\s*([0-9]+(?:,\\s*[0-9]+)*)(?:,)?\\s*$");
            Matcher m = p.matcher(trimmedLine);
            
            // 1. 数字とカンマ以外の文字が含まれていないか (このチェックは正規表現でカバーされるべきだが、念のため)
            boolean containsOnlyDigitsAndCommas = true;
            for (char c : trimmedLine.toCharArray()) {
                if (!((c >= '0' && c <= '9') || c == ',' || Character.isWhitespace(c))) {
                    containsOnlyDigitsAndCommas = false;
                    break;
                }
            }
            
            if (!containsOnlyDigitsAndCommas) {
                continue; // 数字とカンマ以外が含まれていたら不妥当
            }
            
            // 2. 1個以上の数字列がカンマで区切られているか
            // カンマが存在し、かつ、カンマで区切られた要素が複数あることを確認する。
            // "1" は不妥当。 "1,2" は妥当。 "1," は妥当。
            
            // カンマが存在し、かつ、カンマの前後で数字が存在することを要求する。
            // 少なくとも1つのカンマが存在すれば、それは区切りがあることを示唆する。
            if (trimmedLine.contains(",")) {
                // 末尾のカンマのみの行 ("1,") も妥当とみなす。
                validCount++;
            } else {
                // カンマがない行は、1つの数字列のみ（例: "1"）であり、仕様を満たさない。
                // "1" は「1個の数字列」であり、「1個以上の数字列がカンマで区切られて並んでいる」ではない。
            }
        }

        System.out.println("valid=" + validCount);
    }
}
