import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        // カンマ区切りの整数列を判定するための正規表現
        // ^\s* は行頭の空白を許容
        // (?:[0-9]+(?:,|$))+ は1つ以上の数字とカンマの組み合わせ（末尾のカンマも許容）
        // $ は行末
        // この正規表現は「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する
        // より厳密に「数字とカンマのみ」で構成されていることを確認する
        // 妥当な行のパターン: 少なくとも1つの数字があり、数字とカンマ以外は含まれない。
        // 妥当な行の定義: 1個以上の数字とカンマのみで構成されており、空行ではない。
        // 妥当な行のパターンをより具体的に定義する:
        // ^\s* (数字とカンマのシーケンス) \s*$
        // 数字とカンマのみで構成され、空行でないことを確認する。
        // 1個以上の数字とカンマの組み合わせ: 数字とカンマが混在している。
        // 例: "1,2,3" または "1,2,"
        // 数字とカンマのみで構成され、空行ではないことを確認する。
        // 妥当な行は、数字とカンマのみで構成され、少なくとも1つの数字が含まれている必要がある。
        // 正規表現: ^\s*([0-9,]+)\s*$
        // これは「数字とカンマのみ」で構成されていることを確認する。
        // さらに「1個以上の数字列」が区切られていることを確認する必要がある。
        // 妥当な行のパターン: 少なくとも1つの数字があり、数字とカンマのみで構成されている。
        // 妥当な行のパターンを「1個以上の数字とカンマの組み合わせ」として解釈する。
        // 少なくとも1つの数字が含まれていることを確認する:
        // ^\s*.*[0-9].*\s*$ (数字が少なくとも1つある)
        // 数字とカンマ以外を含まないことを確認する:
        // ^\s*[\d,]*\s*$ (数字とカンマのみ)
        
        // 課題の定義に従い、「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
        // これは、カンマで区切られた要素が少なくとも1つ以上存在し、それらが数字であることを意味する。
        // 妥当な行のパターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
        // 少なくとも1つの数字が含まれていることを確認する:
        // ^\s*.*[0-9].*\s*$
        // 数字とカンマ以外を含まないことを確認する:
        // ^\s*[\d,]*\s*$
        
        // 妥当な行の判定ロジックをシンプルにするため、行をトリムし、数字とカンマのみで構成されているか、かつ数字が含まれているかを確認する。
        
        String line;
        while ((line = br.readLine()) != null) {
            String trimmedLine = line.trim();
            
            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }
            
            // 正規表現で、行が数字とカンマのみで構成されているかを確認
            // ^\s*[\d,]*$ : 行頭から行末まで、数字(0-9)とカンマ(,)のみで構成されている
            // このパターンは「数字とカンマ以外を含む行は妥当ではない」という条件を満たす。
            // さらに「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、数字が少なくとも1つ含まれていることを追加する。
            
            // 1. 数字とカンマのみで構成されているか
            if (!Pattern.matches("^\\s*[\d,]*\\s*$", line)) {
                continue; // 数字とカンマ以外を含む行は妥当ではない
            }
            
            // 2. 少なくとも1つの数字が含まれているか
            // 数字が含まれているかを確認するために、行からカンマを取り除いた後の文字列に数字が含まれているかを確認する。
            String digitsOnly = line.replaceAll("[^0-9]", "");
            if (digitsOnly.isEmpty()) {
                continue; // 数字が一つも含まれていない行は妥当ではない (例: "," や ",," など)
            }
            
            // 上記の条件を満たせば妥当
            validLines++;
        }

        System.out.println("valid=" + validLines);
    }
}
