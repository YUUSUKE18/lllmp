import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン: 
            // ^\s*          -> 行の先頭の空白を許容
            // (?:[0-9]+,\s*)* -> 数字とカンマのペアが0回以上繰り返される (数字とカンマの列)
            // [0-9]+        -> 少なくとも1つの数字列が存在すること
            // (?:,\s*[0-9]+)* -> カンマと数字のペアが0回以上繰り返される (末尾のカンマを許容するため)
            // \s*$          -> 行末の空白を許容
            // この正規表現は「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するのに複雑になるため、
            // より直接的に「カンマ区切りの整数列」の構造をチェックします。
            
            // 仕様の解釈に基づき、行が「カンマ区切りの整数列」であるか、かつ「空行でない」ことを確認します。
            // 妥当とは「1個以上の数字列がカンマで区切られて並んでいる」ことです。
            // 末尾のカンマは許容されます。
            
            // パターン: 
            // ^\s*             -> 行頭の空白
            // (?:[0-9]+,\s*)*  -> 1つ以上の数字とカンマのペア (例: 1, 2, 3, )
            // [0-9]+           -> 少なくとも1つの数字列が存在すること (これは必須)
            // (?:,\s*[0-9]+)*  -> 任意の数のカンマと数字のペア (末尾のカンマを許容)
            // \s*$             -> 行末の空白
            
            // より簡潔に、行が数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
            // 妥当な行の例: "1,2,3", "1,2,"
            // 不妥当な行の例: "", "abc", "1,a", "1,,2" (カンマの連続は許容しないと解釈)
            
            // 妥当な行の定義を厳密に正規表現で表現します:
            // 1. 行が空でないこと。
            // 2. 行が数字とカンマのみで構成されていること。
            // 3. 数字とカンマが正しく区切られていること（カンマの連続や数字以外の文字の混入を避ける）。
            
            // 妥当なパターン: 少なくとも1つの数字があり、カンマで区切られている。
            // (?:[0-9]+(?:,\s*[0-9]+)*)  -> 1つ以上の数字列と、それに続くカンマと数字の列の繰り返し。
            // このパターンは末尾のカンマを許容しつつ、数字のみで構成されていることを保証します。
            String regex = "^\\s*(?:[0-9]+(?:,\\s*[0-9]+)*)\\s*$";
            
            // このパターンでは、行が完全に数字とカンマのみで構成されていることを確認します。
            // ただし、"1,2," のように末尾にカンマが続く場合、(,\\s*[0-9]+)* の繰り返しがうまく機能しない可能性があります。
            
            // 仕様の「1 個以上の数字列がカンマで区切られて並んでいる」に焦点を当てます。
            // 1. 数字とカンマのみで構成されている。
            // 2. 少なくとも1つの数字が含まれている。
            
            // 簡略化されたチェック: 数字とカンマ以外の文字がないこと、かつ少なくとも1つの数字があること。
            // 末尾のカンマは許容されるため、行の末尾がカンマで終わるか、数字で終わる必要があります。
            
            // 妥当な行の例: "1,2,3", "1,2,"
            // 不妥当な行の例: "", "abc", "1,,2"
            
            // 妥当な行を判定する正規表現 (数字とカンマのみで構成され、数字が少なくとも1つあることを確認):
            // ^\s*                -> 行頭の空白
            // (?:[0-9]+(?:,|$))* -> 数字列と、カンマまたは行末の繰り返し。
            // この複雑な構造を避けるため、後続の処理で検証します。
            
            boolean isValid = false;
            if (!line.trim().isEmpty()) {
                // 1. 数字とカンマ以外の文字が含まれていないかチェック
                if (Pattern.matches("^\\s*([0-9,]*)\\s*$", line)) {
                    // 2. 少なくとも1つの数字が含まれているかチェック
                    if (line.matches(".*[0-9].*")) {
                        // 3. カンマの連続や不正な構造がないか（例: "1,,2" は不正）
                        // カンマの後に数字が続くか、行末か、または数字で終わっていることを確認する。
                        // 厳密には、カンマの後に数字が続く構造が繰り返されていることを確認します。
                        
                        // 妥当な行の例: "1,2,3", "1,2,"
                        // 不妥当な行の例: "1,,2" (カンマの後にカンマが続く)
                        
                        // カンマの連続をチェックするために、カンマの後に数字が続くパターンを許容します。
                        // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字を含むことを確認します。
                        // 末尾のカンマは許容されるため、行の末尾がカンマで終わることも許容します。
                        if (line.matches("^\\s*([0-9]+(?:,\\s*[0-9]+)*|\\d+)(?:,\\s*)*$")) {
                            isValid = true;
                        }
                    }
                }
            }

            if (isValid) {
                validCount++;
            }
        }

        System.out.println("valid=" + validCount);
    }
}
