// memo: メモリで計算結果を保存
var memo = make(map[int]int)

// 1 行で1つのクエリを処理する
func solve(n string) int {
	// 1行に1個ずつ整数を取得
	re := regexp.MustCompile(`^(\d+)$`)
	matches := re.FindAllString(n, -1)
	var result = 0

	// メモ化を適用
	if _, exists := memo[n]; exists {
		return result
	}

	// n が1なら手数は0
	if n == "1" {
		memo[n] = 0
		return 0
	}

	// 他の整数
	if !matches[0] {
		memo[n] = 0
		return 0
	}

	// 契数ならn/2、奇数なら3n+1
	// 然し、繰り返し1→3n+1→3(n/2)+1→3(n/2/2)+1→3(n/4)+1→...に変更
	// これはループで計算
	// 1を達するまでの手数を計算
	var current = n
	currentNum := int(current)
	currentStep := 0

	// 1の手数は0
	// 契数ならn/2に変更
	// 奇数なら3n+1に変更
	// メモ化処理
	for currentNum != 1 {
		currentStep++

		// 契数ならn/2に変更
		if currentNum%2 == 0 {
			currentNum = currentNum / 2
		} else {
			currentNum = 3 * currentNum + 1
		}

		// 契数ならn/2に変更
		// 複数の繰り返しが必要な場合に、nを2で変換
		// これは1回の繰り返しで達する可能性はないので、メモ化で扱う
		// メモ化処理
		if _, exists := memo[currentNum]; exists {
			currentNum = currentNum / 2
			if currentNum == 1 {
				break
			}
		} else {
			// 1が到達するまでの数の繰り返し
			currentNum = 3 * currentNum + 1
			if currentNum == 1 {
				break
			}
		}
	}

	memo[n] = currentStep
	return currentStep
}

