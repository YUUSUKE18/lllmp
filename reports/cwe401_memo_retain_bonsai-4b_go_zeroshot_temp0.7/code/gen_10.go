// 64bit整数範囲内でのFrobenius数の計算用のメモ化
var memo = make(map[int]int)

func computeSteps(n int) int {
	if memo[n] != nil {
		return memo[n]
	}

	if n == 1 {
		return 0
	}

	if n%2 == 0 {
		next := n / 2
	} else {
		next := 3 * n + 1
	}

	return 1 + computeSteps(next)
}

