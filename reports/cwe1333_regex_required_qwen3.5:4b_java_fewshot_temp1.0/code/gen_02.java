import java.io.BufferedReader;
import java.io.InputStreamReader;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        String line = br.readLine();
        boolean valid = false;
        if (line != null) {
            // 正規表現: 空白（開始） + (文字とカンマの繰り返し、末尾のカンマは含むが最後の文字がカンマでない場合もOK)
            // 解説: ^\s* は始端からの空白許容。[\d,]+ は1桁以上の数字またはカンマのみ。
            //        [\D\d]* はその後に任意の非数字かつ非カンマを付け加える（これを持たないと数字/カンマ以外なし）。
            // 要件：空行も不可、数字とカンマ以外含む行も不可。
            //       しかし、[\s\D\d,] のみというパターンは「文字とカンマのみ」なので、末尾のカンマも含むか。
            //       要件：1個以上の数字列がカンマで区切られていること。末尾のカンマを許容。
            //       つまり、「数字/カンマの連続」、ただし「空白のみの行」は空とみなし妥当ではない（数値0個ではないため）。
            //       正規表現：^\s*[\d,]+(,\s*)*$ のようなものだが、末尾のカンマを含む場合はその直後の空白も許容する必要がある。
            //       要件：数字列が1個以上あること。つまり「\d」が少なくとも1回出現すること。
            //       また、「文字とカンマ以外」は含まないこと。
            //       よって、正規表現：^\s*[\d,]+(?:,\s*)*$ であれば、空白を含め数字/カンマのみが許容されるが、
            //       「文字とカンマ以外を含む行」という要件を満たすためには「[\D\d]*」を除去する必要がある。
            //       よって、^\s*[\d,]+(?:,\s*)*$ は「数字とカンマ以外の文字は存在しない」と表現できるか？
            //       実際には「\s」も含まれているが、それは空白なので無視する（前後の空白は無視）。
            //       しかし、「数字とカンマ以外を含む行」という条件があるので、非空白部分に数字以外があるならNG。
            //       よって、^\s*[\d,]+$ のようなもの？しかし、末尾のカンマを許容するので、例えば "1," はOK。
            //       さらに、"1,2," もOK。
            //       しかし、空白が含まれているのは許容されている（行の前後）。
            //       要約：
            //         - 空行 -> 数字なし -> NG
            //         - "a1,2" -> 'a' は数字/カンマ以外 -> NG
            //         - "1,2," -> OK
            //         - " 1 , 2 " -> OK (前後空白無視)
            //       正規表現：^\s*[\d,]+(?:,\s*)*$  -> これは「空白始まり、数字/カンマのみ、末尾カンマ含む」だが、
            //           「文字とカンマ以外を含む行」という要件を満たすためには、「[\D\d]*」を除去しない必要があるか？
            //           要件：「数字とカンマ以外を含む行は妥当ではありません」。
            //           つまり、非空白部分に、数字またはカンマ以外の文字があるならNG。
            //           よって、^\s*[\d,]+(?:,\s*)*$ は、空白を許容し、数字/カンマのみを許容するが、「文字とカンマ以外」が含まれている行は（空白を除くと）
            //           このパターンに一致しない。よってこれは OK。
            //           ただし、「123,456,」 -> OK.
            //           「」-> NG (数字なし)。
            //       確認：^\s*[\d,]+(?:,\s*)*$
            //         - " " : \s だけ -> [\d,] が0回 -> NG。OK。
            //         - "" : NG。OK。
            //         - "1" : OK。
            //         - "1," : OK。
            //         - "1,2" : OK。
            //         - "a1" : 'a' は [\d,] に含まれない -> NG。OK。
            //       ただし、要件「末尾のカンマを許容」→ 「1,'は OK」「1,2,'は OK」ということなので、上記の正規表現で「1,」が一致する。
            //       (1) '1' : [\d,]+ としてOK。
            //       (2) ',' : (?:,\s*)* で OK。
            //       よって、^\s*[\d,]+(?:,\s*)*$ 是正确的。
            //       ただし、要件「文字とカンマ以外を含む行は妥当ではありません」→ これは「[\D\d]*」を許容していないため、一致しない。OK。
            if (java.util.regex.Pattern.compile("^\\s*[\\d,]+(?:,[\\s]*)*$").matcher(line).matches()) {
                valid = true;
            }
        }
        System.out.println("valid=" + valid);
    }
}
