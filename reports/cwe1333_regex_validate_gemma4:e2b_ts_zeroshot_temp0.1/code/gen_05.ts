import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    if (!input) {
        console.log('valid=0');
        return;
    }

    const lines = input.split('\n');
    let validCount = 0;

    for (const line of lines) {
        // 行の前後の空白を無視
        const trimmedLine = line.trim();

        if (trimmedLine === '') {
            // 空行は妥当ではない
            continue;
        }

        // 末尾のカンマは許容する
        // 正規表現で、数字とカンマのみで構成されているか、または数字とカンマで終わるかをチェックする
        // 妥当な形式: 1個以上の数字とカンマの組み合わせ。
        // 許容されるパターン: 数字とカンマのみで構成され、空行でないこと。
        // 妥当性の定義: 1個以上の数字列がカンマで区切られて並んでいること。
        // これは、行が数字とカンマのみで構成されていることを意味する。

        // 1. 数字とカンマ以外を含む行は妥当ではない
        // 2. 妥当とは、1個以上の数字列がカンマで区切られて並んでいること。
        // 3. 末尾のカンマは許容する。

        // 妥当な行の判定ロジック:
        // 行が空でないこと。
        // 行に含まれる文字が、数字(0-9)とカンマ(,)のみで構成されていること。
        // ただし、行全体が「1個以上の数字列がカンマで区切られて並んでいる」ことを満たす必要がある。
        // これは、カンマで区切られた要素がすべて整数である、という前提に基づいている。

        // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
        // これは、行がカンマで区切られた数字のシーケンスである必要がある。

        // 正規表現で検証:
        // ^: 行の開始
        // (?:[0-9]+(?:,|$))+: 1つ以上の数字列とカンマの組み合わせ。
        // このパターンは、数字とカンマのみで構成され、少なくとも1つの数字列が含まれていることを示唆する。

        // より単純な解釈: 行が数字とカンマのみで構成されており、空行でないこと。
        // 末尾のカンマは許容される。

        // 妥当な行の判定を、行が数字とカンマのみで構成されているか、かつ空でないことと定義する。
        // 1. 数字とカンマ以外を含む行は妥当ではない。
        // 2. 空行は妥当ではない。

        // 妥当な行の判定:
        // 行が空でないこと。
        // 行に含まれる文字が、数字とカンマのみであること。
        // (末尾のカンマは許容される)

        // 1. 数字とカンマ以外を含む行のチェック
        let isValidFormat = true;
        for (const char of trimmedLine) {
            if (!/[0-9,]/ .test(char)) {
                isValidFormat = false;
                break;
            }
        }

        if (!isValidFormat) {
            continue;
        }

        // 2. 1個以上の数字列がカンマで区切られて並んでいること。
        // これは、行が「数字とカンマのみ」で構成されていれば、
        // 少なくとも1つの数字列（カンマで区切られたもの）が存在すると見なす。
        // 例: "1,2,3" -> 妥当
        // 例: "," -> 妥当ではない（数字列が0個）
        // 例: "1," -> 妥当
        // 例: ",1" -> 妥当
        // 例: "" -> 既に除外済み

        // カンマのみの行（例: "," や ",,"）は、数字列が0個であるため、妥当ではないと解釈する。
        // 少なくとも1つの数字が含まれていることを確認する。
        let containsDigit = false;
        for (const char of trimmedLine) {
            if (/[0-9]/.test(char)) {
                containsDigit = true;
                break;
            }
        }

        if (containsDigit) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
