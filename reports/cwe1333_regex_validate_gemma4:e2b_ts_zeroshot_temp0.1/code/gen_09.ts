import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    if (!input) {
        console.log('valid=0');
        return;
    }

    const lines = input.split('\n');
    let validCount = 0;

    for (const line of lines) {
        // 行の前後の空白を無視
        const trimmedLine = line.trim();

        if (trimmedLine === '') {
            // 空行は妥当ではない
            continue;
        }

        // 末尾のカンマは許容する
        // 正規表現で、数字とカンマのみで構成されているか、または数字とカンマで終わるかをチェックする
        // 妥当な形式: 1個以上の数字とカンマの組み合わせ。末尾のカンマは許容。
        // 許容されるパターン: 数字とカンマのみで構成されていること。
        // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
        
        // 1. 数字とカンマ以外の文字が含まれていないかチェック
        // 2. 少なくとも1つの数字が含まれているかチェック
        
        // 妥当な行の定義を再解釈:
        // 「1 個以上の数字列がカンマで区切られて並んでいる」
        // 例: "1,2,3" (3つの数字列)
        // 例: "1,2," (2つの数字列、末尾のカンマあり)
        // 例: "1" (1つの数字列)
        // 例: "," (これは数字列ではないため不適)
        
        // 正規表現で、数字とカンマのみで構成されていることを確認する
        // ^[0-9,]*$ : 行全体が数字とカンマのみで構成されている
        // 少なくとも1つの数字が含まれていることを確認する
        
        const isValidFormat = /^[0-9,]*$/.test(trimmedLine);

        if (!isValidFormat) {
            // 数字とカンマ以外を含む行は妥当ではない
            continue;
        }

        // 数字とカンマのみの場合、空行でないことを確認済み。
        // 妥当であるためには「1個以上の数字列がカンマで区切られて並んでいる」必要がある。
        // これは、カンマが少なくとも1つ含まれているか、または数字のみで構成されている場合に成立する。
        
        // 1. カンマが含まれている場合 (例: "1,2", "1,2,")
        // 2. カンマが含まれていない場合 (例: "123") - これは1つの数字列と見なせる。
        
        // 妥当性の判定を厳密に行うため、カンマの存在をチェックする。
        // 「1個以上の数字列がカンマで区切られて並んでいる」
        // これは、カンマが1つ以上存在するか、または数字のみで構成されている場合に満たされると解釈する。
        
        // もし行が空でない場合、数字とカンマのみで構成されていれば、それは「数字列の並び」と見なせる。
        // 例: "123" -> 1つの数字列。これは「1個以上の数字列がカンマで区切られて並んでいる」の特殊ケースとして許容されるべきか？
        // 仕様: 「1 個以上の数字列がカンマで区切られて並んでいる」
        // 区切り文字（カンマ）が存在しない場合、それは「区切られて並んでいる」とは言えない。
        // したがって、カンマが少なくとも1つ存在することを要求する。
        
        const containsComma = trimmedLine.includes(',');

        if (containsComma) {
            validCount++;
        } else {
            // カンマを含まないが、数字とカンマのみで構成されている場合 (例: "123")
            // これは「1個以上の数字列がカンマで区切られて並んでいる」の定義に厳密には合致しないため、不妥当とする。
            // ただし、もし「1個以上の数字列」が「区切りなしの列」も含むと解釈するなら、この判定は変わる。
            // 仕様を厳密に解釈し、カンマ区切りであることを要求する。
            // したがって、カンマがない場合は不妥当とする。
            // validCount はインクリメントされない。
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
