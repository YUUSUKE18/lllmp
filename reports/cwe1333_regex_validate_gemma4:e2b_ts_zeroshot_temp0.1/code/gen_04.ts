import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    if (!input) {
        console.log('valid=0');
        return;
    }

    const lines = input.split('\n');
    let validCount = 0;

    for (const line of lines) {
        // 行の前後の空白を無視
        const trimmedLine = line.trim();

        if (trimmedLine === '') {
            // 空行は妥当ではない
            continue;
        }

        // 末尾のカンマは許容する
        // 正規表現で、数字とカンマのみで構成されているか、または数字列が1つ以上存在するかをチェックする
        // 妥当な行の定義: 1個以上の数字列がカンマで区切られて並んでいること。
        // これは、カンマで区切られた要素がすべて整数である、という条件を暗黙的に満たす必要がある。
        // 仕様の「1 個以上の数字列がカンマで区切られて並んでいる」を厳密に解釈する。
        // 例: "1,2,3" -> 3つの数字列
        // 例: "1,2," -> 2つの数字列 (末尾のカンマは許容)
        // 例: "1," -> 1つの数字列
        // 例: "abc" -> 不妥当
        // 例: "1,a" -> 不妥当 (数字とカンマ以外を含む)

        // 行がカンマと数字のみで構成されているかを確認する
        // 妥当な行は、カンマで区切られた要素がすべて整数である、という前提で、
        // 少なくとも1つの数字列が存在すれば妥当とする。

        // 1. 数字とカンマ以外を含む行は妥当ではない
        if (!/^[0-9,]*$/.test(trimmedLine)) {
            continue;
        }

        // 2. 1個以上の数字列がカンマで区切られて並んでいるかを確認する
        // カンマで分割し、空でない要素が1つ以上あるかを確認する。
        // 末尾のカンマは許容されるため、末尾のカンマで終わる場合も考慮する。

        // 末尾のカンマを削除して、カンマで分割する
        let parts;
        if (trimmedLine.endsWith(',')) {
            // 末尾のカンマがある場合、それを削除して分割
            parts = trimmedLine.slice(0, -1).split(',');
        } else {
            // 末尾のカンマがない場合
            parts = trimmedLine.split(',');
        }

        // 分割後の要素をフィルタリングし、空でない要素が1つ以上あるかを確認する
        // ただし、"1," のようなケースを考慮する必要がある。
        // "1," -> slice(0, -1) -> "1" -> split(',') -> ["1"] (OK)
        // "1,2" -> split(',') -> ["1", "2"] (OK)
        // "," -> slice(0, -1) -> "" -> split(',') -> [""] (NG)
        // "1," -> slice(0, -1) -> "1" -> split(',') -> ["1"] (OK)
        // "," -> slice(0, -1) -> "" -> split(',') -> [""] (NG)

        // 厳密に「1 個以上の数字列がカンマで区切られて並んでいる」
        // これは、カンマで区切られた要素がすべて非空の文字列であり、その要素が数字列である、ということを意味する。
        // 仕様の「数字とカンマ以外を含む行は妥当ではない」を満たしているため、
        // 以下のチェックで十分であると判断する。

        // 1. カンマで分割した結果、空文字列が1つ以上存在しないこと。
        // ただし、末尾のカンマが許容されるため、末尾の要素が空になることは許容される。
        // 例: "1,2," -> slice(0, -1) -> "1,2" -> ["1", "2"] (OK)
        // 例: "," -> slice(0, -1) -> "" -> [""] (NG)

        // 妥当な行の判定ロジックを再構築する。
        // 妥当な行は、カンマで区切られた要素が、すべて数字列（空でない）である必要がある。

        // 1. 行をカンマで分割する
        const elements = trimmedLine.split(',');

        // 2. 妥当な要素が1つ以上存在するか確認する
        // 末尾のカンマが許容されるため、最後の要素が空になることは許容される。
        // 例: "1,2," -> elements = ["1", "2", ""] (長さ3)
        // 例: "1,2" -> elements = ["1", "2"] (長さ2)
        // 例: "," -> elements = ["", ""] (長さ2)

        // 妥当な行は、少なくとも1つの非空の要素を持つ必要がある。
        const hasValidElement = elements.some(el => el.length > 0);

        if (hasValidElement) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
