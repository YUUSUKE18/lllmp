import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    if (input === "") {
        console.log("valid=0");
        return;
    }

    const lines = input.split('\n');
    let validCount = 0;

    for (const line of lines) {
        // 行の前後の空白を無視
        const trimmedLine = line.trim();

        if (trimmedLine === "") {
            // 空行は妥当ではない
            continue;
        }

        // 末尾のカンマは許容する
        // 正規表現で、数字とカンマのみで構成されているかを確認する
        // ^\s* 表示行の先頭から
        // [\d,]* 表示数字またはカンマが0回以上続く
        // \s*$ 表示行の末尾まで
        // この正規表現だけでは「1個以上の数字列がカンマで区切られている」ことを完全に保証できないため、
        // 以下のロジックで検証する。

        // 妥当性の判定ロジック:
        // 1. 数字とカンマ以外の文字が含まれていないこと。
        // 2. 少なくとも1つの数字が含まれていること（空行は除外済み）。
        // 3. カンマ区切りであること（カンマが1つ以上あるか、または数字のみか）。

        let isValid = false;

        // 1. 数字とカンマのみで構成されているかチェック
        const validCharsOnly = /^[0-9,]*$/.test(trimmedLine);

        if (validCharsOnly) {
            // 2. 少なくとも1つの数字が含まれているかチェック
            const containsDigit = /\d/.test(trimmedLine);

            if (containsDigit) {
                // 3. カンマ区切りであるか、または数字のみであるか
                // 妥当の定義: 1個以上の数字列がカンマで区切られていること。
                // これは、カンマが存在するか、または数字のみである場合に成立する。
                // 例: "1,2,3" (妥当), "123" (妥当 - 1つの数字列), "1,2," (妥当)
                
                // 妥当性の定義を再解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
                // これは、カンマで区切られた要素が1つ以上存在することを意味する。
                
                // カンマで区切られた要素を抽出して、その数が1以上であれば妥当とする。
                const parts = trimmedLine.split(',');
                
                // 末尾のカンマが許容されるため、末尾が空文字列になる可能性がある。
                // 例: "1,2," -> ["1", "2", ""] (長さ3)
                // 例: "123" -> ["123"] (長さ1)
                
                // 妥当なのは、分割された要素の数が1以上であること。
                // ただし、"123" のようなカンマのないケースも許容されるべきか？
                // 仕様: 「1 個以上の数字列がカンマで区切られて並んでいることです。」
                // "123" はカンマで区切られていないが、1つの数字列として存在する。
                // 厳密に「カンマで区切られている」ことを要求するなら、カンマが存在する必要がある。
                
                // 妥当なケースの例: "1,2", "1,2,"
                // 不妥当なケースの例: "", "abc", "1a", "1,,2" (カンマが連続する場合、これは通常不正)

                // カンマで区切られた要素の数を数える。
                // 末尾のカンマが許容されるため、末尾の空文字列は無視する。
                const actualParts = parts.filter(p => p.length > 0);
                
                if (actualParts.length >= 1) {
                    validCount++;
                }
            }
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
