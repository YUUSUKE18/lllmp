import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.IOException;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws IOException {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン: 
            // ^\s*          -> 行の先頭の空白を無視
            // (?:[0-9]+,\s*)* -> 1個以上の (数字, 空白) の組が0回以上繰り返される (カンマ区切りの整数列)
            // [0-9]+        -> 少なくとも1つの数字が含まれていることを保証する
            // (?:,\s*[0-9]+)* -> 最後の要素がカンマで終わる場合、それ以降の要素が続くことを許容する
            // $             -> 行の終わり
            // よりシンプルに、カンマ区切りの整数列が1つ以上存在し、それ以外に数字とカンマ以外がないことを確認する。

            // 仕様に基づき、"1個以上の数字列がカンマで区切られて並んでいる"ことを確認する。
            // これは、カンマで区切られた要素が1つ以上存在し、それらがすべて整数である、ということを意味する。
            // 末尾のカンマは許容される。空行は妥当ではない。

            // パターン解説:
            // ^\s*             : 行頭の空白
            // (?:[0-9]+,\s*)*  : 1つ以上の (整数, カンマ, 空白) のグループ。これらが0回以上繰り返される。
            // [0-9]+           : 少なくとも1つの数字が続くことを保証する。
            // (?:,\s*[0-9]+)*  : 最後の要素がカンマで終わる場合、それ以降の要素が続くことを許容する（末尾カンマの許容のため）
            // $               : 行末
            
            // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックする。
            // 許容されるのは、数字とカンマ、空白のみで構成され、最低1つの数字が含まれている場合。
            // 末尾のカンマは許容される。空行はNG。

            // 1. 空行チェック（空白のみ、または完全に空）
            String trimmedLine = line.trim();
            if (trimmedLine.isEmpty()) {
                continue; // 空行は妥当ではない
            }

            // 2. 正規表現による検証
            // パターン: 
            // ^\s*                : 行頭の空白
            // (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列と、それに続くカンマと空白の繰り返し。
            //                               これは、数字とカンマが交互に現れることを要求する。
            //                               末尾のカンマも許容する。
            // $                   : 行末
            
            // より単純に、カンマで区切られた非空の要素が存在するかどうかをチェックする。
            // 末尾のカンマが許容されるため、行全体が数字とカンマ、空白のみで構成され、
            // 少なくとも1つの数字が含まれていることを確認する。

            // 許容されるパターン: 数字, カンマ, 空白が混在し、少なくとも1つの数字が存在する。
            // 末尾のカンマは許容される。
            // 例: "1,2,3,", "1,"
            
            // 以下のパターンは、「数字」が少なくとも1つ存在し、それらがカンマと空白で区切られていることを確認する。
            // 末尾のカンマが許容されるため、行の末尾がカンマで終わるか、数字で終わることを許容する。
            // 厳密には、行全体が整数とカンマのみで構成され、かつカンマが少なくとも1つ存在すること。
            
            // 妥当な行の定義を再解釈: 
            // 1個以上の数字列がカンマで区切られている。
            // 例: "1,2" (妥当), "1," (妥当), ",1" (NG), "" (NG)
            
            // 正規表現で「数字とカンマのみ」で構成され、「1個以上の数字」が存在し、「末尾のカンマ」が許容されることを確認する。
            // 少なくとも1つの数字を含む、カンマ区切りの整数列。
            Pattern pattern = Pattern.compile("^\\s*(?:[0-9]+(?:,\\s*[0-9]+)*)?\\s*,?\\s*$");
            Matcher matcher = pattern.matcher(line);

            // このシンプルなパターンでは「末尾のカンマ」の許容と「空行でない」のチェックが難しい。
            // 仕様を最大限満たすため、要素を分割して検証するアプローチを採用する。
            
            String[] parts = line.trim().split(",");
            boolean isValid = false;

            if (parts.length > 0) {
                // 1. 全ての要素が数字列であるか確認する
                boolean allAreNumbers = true;
                for (String part : parts) {
                    if (part.isEmpty()) {
                        // カンマが連続している場合、空文字列になる。これは「空行」と見なされるか？
                        // 仕様：「空行、および数字とカンマ以外を含む行は妥当ではありません。」
                        // 空行はNG。カンマ連続はNGと解釈する。
                        continue; // 空の要素はスキップ（後で個数チェックを行う）
                    }
                    try {
                        Integer.parseInt(part.trim());
                    } catch (NumberFormatException e) {
                        allAreNumbers = false;
                        break;
                    }
                }

                if (allAreNumbers) {
                    // 2. 1個以上の数字列がカンマで区切られているか確認する。
                    // これは、parts配列の中に、空でない要素が少なくとも1つ存在すれば満たされる。
                    // ただし、末尾のカンマが許容されるため、parts.length > 0 であれば、
                    // 少なくとも1つの要素（たとえそれが空でも）が存在する。
                    
                    // 末尾のカンマの許容を考慮し、数字列の数が1以上であることを確認する。
                    // 例: "1,2," -> parts = ["1", "2", ""]。数字列は2つ。
                    // 例: "1," -> parts = ["1", ""]。数字列は1つ。
                    
                    // 少なくとも1つの数字列が存在すればOKとする。
                    boolean hasNumber = false;
                    for (String part : parts) {
                        if (!part.trim().isEmpty()) {
                            hasNumber = true;
                            break;
                        }
                    }
                    
                    if (hasNumber) {
                        validLines++;
                    }
                }
            }
        }

        System.out.println("valid=" + validLines);
    }
}
