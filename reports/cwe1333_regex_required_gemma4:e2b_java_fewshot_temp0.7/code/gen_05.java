import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現: 
            // ^\s* : 行の先頭の空白
            // (?:[0-9]+(?:,?[0-9]+)*) : 1個以上の数字とカンマの組み合わせ。
            // このパターンは、数字とカンマのみで構成されていることを確認する。
            // 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」こと。
            // 末尾のカンマは許容。空行はNG。
            
            // ここでは、行全体が「数字とカンマのみ」で構成され、少なくとも1つの数字が含まれているかをチェックする。
            // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を正規表現で表現するのは複雑なため、
            // 以下のロジックで「数字とカンマのみ」で構成され、かつ空行でないことを確認し、
            // さらに「1個以上の数字列」が存在するかどうかを確認する。
            
            // 仕様を再解釈し、正規表現で「1個以上の数字列がカンマで区切られている」ことをチェックする。
            // 1. 行が空でないこと (行の前後の空白を無視)
            // 2. 行が数字とカンマのみで構成されていること
            // 3. 少なくとも1つの数字列が存在すること
            
            // (?:[0-9]+(?:,?[0-9]+)*) は、数字とカンマのシーケンスを試みる。
            // 実際には、行全体をチェックし、その内容が「数字とカンマ」で構成されているかを確認する。
            
            // 妥当な行の判定ロジックを正規表現で表現する。
            // 許容されるパターン: 数字とカンマのみで構成され、空でない。
            // 複数の数字列がカンマで区切られていることを確認するには、
            // 少なくとも一つの数字が含まれていること、そしてカンマの構造が許容されることを確認する。
            
            // 簡略化されたチェック：行が空でなく、数字とカンマ以外が含まれていないこと。
            // そして、数字列が1つ以上存在すること。
            
            // 行全体をチェックする正規表現：
            // ^\s* : 先頭の空白
            // (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字列と、その間にカンマが挟まるパターンを想定。
            // 末尾のカンマも許容する。
            
            // 非常に厳密に「1個以上の数字列がカンマで区切られて並んでいる」を判定するには、
            // 例えば、"1,2,3" や "1," や ",1" などを許容し、"abc" や "1a" を拒否する必要がある。
            
            // 以下の正規表現は、行が数字とカンマのみで構成されていることを確認し、
            // 少なくとも1つの数字が含まれていることを保証するように試みる。
            // 妥当な行の例: "1,2,3", "1,"
            // 不妥当な行の例: "", "a1", "1a", "1,,2" (連続カンマは不妥当と仮定)
            
            // 連続する数字とカンマのシーケンスを許容するパターン:
            // ^\s* 表示行の先頭の空白
            // (?:[0-9]+(?:,[0-9]+)*) は、数字列がカンマで区切られていることを保証する
            // 末尾のカンマも許容する
            
            // 簡略化のため、行全体が数字とカンマのみで構成され、空でないことを確認し、
            // 少なくとも1つの数字が含まれていることを確認する。
            
            // 正規表現パターン: 
            // ^\s* : 行の先頭の空白
            // (?:[0-9]+(?:,?[0-9]*)*) : 少なくとも1つの数字列が存在し、それらがカンマで区切られている構造。
            // これは非常に複雑になるため、行を分割して個別にチェックする方が実用的である。
            
            String trimmedLine = line.trim();
            if (trimmedLine.isEmpty()) {
                continue; // 空行は妥当ではない
            }

            // 各要素をカンマで分割し、空でない要素が数字のみで構成されているかチェックする。
            // 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」
            
            // 行をカンマで分割
            String[] parts = line.split(",");
            
            boolean isValid = false;
            if (parts.length > 0) {
                // 少なくとも1つの要素が存在する
                for (String part : parts) {
                    String trimmedPart = part.trim();
                    if (!trimmedPart.isEmpty()) {
                        // 各要素が整数であることを確認
                        try {
                            Integer.parseInt(trimmedPart);
                        } catch (NumberFormatException e) {
                            // 数字以外が含まれていた場合、この行は不妥当
                            isValid = false;
                            break;
                        }
                    }
                }
                
                if (isValid) {
                    // 1個以上の数字列がカンマで区切られて並んでいること。
                    // これは、parts配列に少なくとも1つの有効な数字列が含まれていれば満たされる。
                    // ただし、" ," のような連続したカンマや、数字以外の文字が含まれていないことが重要。
                    
                    // 連続したカンマや数字以外の文字が含まれる場合を厳しくチェックする。
                    // 例: "1,,2" -> parts = ["1", "", "2"]. 空の要素は許容されるか？
                    // 仕様：「1 個以上の数字列がカンマで区切られて並んでいることです。」
                    // 空の数字列（""）は数字列ではないため、空要素を無視して残った要素が数字のみであるかを確認する。
                    
                    // 連続するカンマや、数字以外の文字が混入している行は不妥当とする。
                    // 例: "1,a,2" -> parts=["1", "a", "2"]. "a"はNG。
                    // 例: "1,,2" -> parts=["1", "", "2"]. ""は無視されるべきか？
                    
                    // 連続するカンマのみで構成されている行（例: "," や ",,"）は不妥当。
                    // 少なくとも1つの有効な数字が含まれているかを確認する。
                    
                    boolean hasNumber = false;
                    for (String part : parts) {
                        String trimmedPart = part.trim();
                        if (!trimmedPart.isEmpty()) {
                            try {
                                Integer.parseInt(trimmedPart);
                                hasNumber = true;
                            } catch (NumberFormatException e) {
                                // 数字以外が含まれていれば、この行は不妥当
                                isValid = false;
                                break;
                            }
                        }
                    }
                    
                    if (isValid && hasNumber) {
                        validLines++;
                    }
                }
            }
        }

        System.out.println("valid=" + validLines);
    }
}
