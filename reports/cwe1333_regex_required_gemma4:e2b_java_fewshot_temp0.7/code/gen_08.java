import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン:
            // ^\s*           -> 行の先頭の空白文字 (0回以上)
            // (?:             -> 非キャプチャグループの開始 (非キャプチャ)
            //   \d+           -> 1つ以上の数字
            //   ,             -> カンマ
            // )*             -> 上記のグループが0回以上繰り返される (カンマ区切りの数字の列)
            // \s*            -> 行末の空白文字 (0回以上)
            // $              -> 行の終わり
            // このパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
            // 末尾のカンマも許容するため、行全体をチェックします。
            
            // 妥当性の判定ロジックを調整します。
            // 仕様: 1個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容。
            // 空行、および数字とカンマ以外を含む行は妥当ではない。
            
            // 以下の正規表現は、行が空でないこと、および数字とカンマのみで構成されていることを確認します。
            // ただし、"1,2," のように末尾のカンマがあっても許容する必要があります。
            
            // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するために、
            // まずトリムして空行でないか確認し、次に内容が数字とカンマのみで構成されているか確認します。
            
            String trimmedLine = line.trim();
            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 行が数字とカンマのみで構成されているかチェックする正規表現
            // ^\d+(?:,\d+)*$ : 1つ以上の数字から始まり、カンマと数字が交互に続くパターン（末尾カンマは除外）
            // 末尾のカンマを許容する場合、より柔軟なチェックが必要です。
            
            // 妥当な行の定義を再解釈: 
            // 1個以上の数字列がカンマで区切られて並んでいる。
            // 例: "1,2,3", "1," (末尾カンマ許容), ",1" (先頭カンマは通常許容されないが、ここでは区切りとして扱う)
            
            // 課題の要求：「1 個以上の数字列がカンマで区切られて並んでいる」
            // これは、カンマで区切られた要素が全て整数である、ということを意味します。
            // 末尾のカンマは許容されます。
            
            // パターン: 数字、カンマ、数字の繰り返し。末尾にカンマがあっても良い。
            // (?:\\d+(,\\d*)*) : 1つ以上の数字から始まり、カンマと数字が続く。
            // このパターンでは、"1,2" はマッチするが、"1," はマッチしないため、末尾のカンマの許容を別途考慮する必要があります。

            // 妥当な行の判定をシンプルにするため、行をカンマで分割し、すべてが数字であるかを確認します。
            
            String[] parts = trimmedLine.split(",");
            boolean is_valid = true;
            
            if (parts.length == 0) {
                // これはtrimmedLineが空でない限り発生しないはずだが念のため
                is_valid = false;
            } else {
                for (String part : parts) {
                    // 各部分が空でないことを確認する（例: ",," のようなケース）
                    if (part.isEmpty()) {
                        // 空の要素は許容しない（ただし、末尾カンマの結果として生じる空要素は考慮が必要）
                        // 例: "1,2," -> ["1", "2", ""]。最後の "" は末尾カンマに対応。
                        // 空行は無視されているため、ここでは空の要素は許容する（末尾カンマの結果として）
                        continue;
                    }
                    
                    // 各部分が整数であるかチェック
                    try {
                        Integer.parseInt(part.trim());
                    } catch (NumberFormatException e) {
                        // 数字とカンマ以外を含む行は妥当ではない
                        is_valid = false;
                        break;
                    }
                }
            }

            if (is_valid) {
                // 1個以上の数字列が区切られている（つまり、少なくとも1つの数字が含まれている）
                // 空行は既に除外されているため、ここで妥当と見なす。
                validLines++;
            }
        }

        System.out.println("valid=" + validLines);
    }
}
