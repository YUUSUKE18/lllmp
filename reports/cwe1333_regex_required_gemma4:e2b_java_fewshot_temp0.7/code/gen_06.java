import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン: カンマ区切りの整数列。末尾のカンマは許容する。
            // ^\s* : 行頭の空白を無視
            // (?:[0-9]+(?:\s*,\s*)*) : 1つ以上の数字がカンマと空白で区切られるパターン
            // (?:,\s*)* : 末尾のカンマと空白を0回以上繰り返す（末尾のカンマを許容するため）
            // $ : 行末
            // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
            // 少なくとも一つの数字が含まれている必要がある。
            // \s* は行頭と行末の空白を考慮する。
            
            // より単純に、行全体が数字とカンマと空白のみで構成され、少なくとも一つの数字が含まれているかを確認する。
            // 妥当性の定義：「1個以上の数字列がカンマで区切られて並んでいる」
            // 例: "1,2,3" は OK。末尾カンマ "1,2,3," も OK。
            // 空行は妥当ではない。
            
            // パターン：数字とカンマ、および空白のみで構成され、かつ少なくとも1つの数字が含まれていること。
            // 妥当性のチェックを、正規表現のマッチングと内容の確認で実現する。
            
            // 1. 行全体が数字とカンマ、空白のみで構成されているか？
            // 2. 少なくとも1つの数字が含まれているか？
            
            // この仕様を正規表現だけで厳密に定義するのは難しい（特に「末尾のカンマは許容」という部分）。
            // 妥当な行 = (数字とカンマと空白のシーケンス) かつ (少なくとも1つの数字を含む)
            
            // 妥当な行のパターン:
            // ^\s*                -> 行頭の空白
            // (?:[0-9]+(?:,\s*[0-9]+)*) -> 1つ以上の数字がカンマと空白で区切られているパターン
            // (?:,\s*$)           -> 末尾にカンマと空白が続くことを許容する（末尾のカンマを許容）
            // $                  -> 行末
            
            // 簡易的に、数字とカンマ、空白のみで構成され、数字が少なくとも1つ含まれているかをチェックする。
            
            // 1. 行をトリムして、数字とカンマ以外の文字がないか確認する
            String trimmedLine = line.trim();
            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 2. 正規表現で検証: 数字、カンマ、空白のみで構成されているか、かつ数字が含まれているか。
            // 妥当な形式: 数字とカンマのみで構成され、数字が少なくとも1つある。
            // 許可する文字: 数字(0-9), カンマ(,), 空白(\s)
            // 妥当性の定義を再解釈: 1個以上の数字列がカンマで区切られて並んでいる。
            
            // パターン: (数字, カンマ, 空白の繰り返し) が1回以上続く
            // (?:[0-9]+(?:,\s*[0-9]+)*) : 少なくとも1つの数字で始まり、カンマ区切りで続く。
            // (?:,\s*)* : 末尾のカンマを許容。
            // $ : 行末
            
            // ここでは、行全体が数字とカンマと空白のみで構成されていることを確認し、かつ数字が含まれていることを確認する。
            
            // 許容する文字セット: 数字, カンマ, 空白
            // 否定的なチェック: 数字以外の文字が含まれていないか。
            if (!line.matches("^[\\s]*[0-9,]*[\\s]*$")) {
                // 数字、カンマ、空白以外の文字が含まれている場合は不妥当
                continue;
            }
            
            // 少なくとも1つの数字が含まれているか？
            if (!line.matches(".*[0-9].*")) {
                // 数字が一つも含まれていない（例: "," や " , " など、数字以外の記号のみ）
                continue;
            }
            
            // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を満たしているか？
            // これは、カンマで区切られた要素が存在すれば満たされる。
            // 妥当な行とは、数字とカンマのみで構成され、少なくとも1つの数字を含む。
            
            // より簡潔な検証として、行に含まれる全ての非空白文字が数字またはカンマのみであることを確認する。
            // そして、カンマで区切られている構造があることを確認する。
            
            // 最終的な判定ロジックとして、行をトリムし、カンマで分割した結果、空でない要素が1つ以上存在するかをチェックする方が、
            // 「1個以上の数字列がカンマで区切られて並んでいる」という記述に最も忠実である。
            
            String[] parts = line.trim().split(",");
            boolean isValid = false;
            
            // 1. 空行は除外済み (trimmedLine.isEmpty()でチェック済み)
            // 2. 少なくとも1つの数字列が存在するか？
            // 3. 末尾のカンマの許容について: split(",")の結果が、元の行の構造を反映しているか。
            
            // 例: "1,2,3" -> ["1", "2", "3"] (3個)
            // 例: "1,2," -> ["1", "2", ""] (3個)
            // 例: "," -> ["", ""] (2個) (これは数字列ではないため無効)
            
            // 妥当な行: 1個以上の数字列がカンマで区切られている。
            // これは、分割された要素の中に、数字としてパース可能なものが1つ以上存在すれば良い。
            
            for (String part : parts) {
                if (!part.trim().isEmpty()) {
                    try {
                        Integer.parseInt(part.trim());
                        isValid = true;
                        break;
                    } catch (NumberFormatException e) {
                        // 数字としてパースできなかった（これは、数字とカンマ以外の文字が含まれている場合、
                        // 最初の文字が数字でなくても、後続のチェックで不妥当と判断されることを期待する）
                        // ただし、行全体が数字とカンマのみで構成されていることを保証するため、
                        // ここではこのループ内での成功のみに依存する。
                    }
                }
            }
            
            // 最終的に、行が数字とカンマと空白のみで構成され、かつ数字が含まれていれば妥当とする。
            // 厳密な正規表現での実現を試みる。
            // 妥当な行のパターン: (数字とカンマと空白のシーケンス) が1回以上存在する。
            // 数字とカンマのみで構成され、かつ、最低1つの数字が含まれている。
            // \s* は無視されるため、行全体がこのパターンに一致する必要がある。
            
            // 妥当な行のパターン (行全体に適用): 
            // ^\s*                                  -> 行頭の空白
            // (?:[0-9]+(?:,\s*[0-9]+)*)              -> 1つ以上の数字がカンマで区切られている部分
            // (?:,\s*)*                             -> 末尾のカンマを許容
            // [0-9]                                 -> 少なくとも1つの数字が含まれていることを保証
            // .*                                    -> それ以外の空白やカンマが続くことを許容（非常に緩い）
            
            // 課題の意図を最も満たすのは、行全体が「カンマ区切りの整数列」の形式に従っているか、そして空でない要素があるか。
            
            // 妥当性の判定を、行が数字とカンマのシーケンスのみで構成され、かつ、少なくとも一つの数字が含まれていることとする。
            // このチェックは、前述のsplit処理と組み合わせるのが最も実用的であるため、split結果の検証を採用する。
            
            if (isValid) {
                validLines++;
            }
        }

        System.out.println("valid=" + validLines);
    }
}
