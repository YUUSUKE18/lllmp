import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン: 
            // ^\s*         -> 行の先頭の空白を無視
            // (?:[0-9]+,\s*)* -> 1個以上の数字とカンマのグループ（数字とカンマの間に空白があっても良い）を0回以上繰り返す
            // [0-9]+       -> 少なくとも1つの数字が続く（これは前のグループの後に続くことを保証する）
            // (?:\s*,?)*   -> 末尾のカンマの有無を許容するための繰り返し
            // $            -> 行の終わり
            // 
            // よりシンプルに、"1個以上の数字列がカンマで区切られて並んでいる"ことを確認する
            // これは、数字とカンマのみで構成されており、少なくとも1つの数字が含まれていることを意味する。
            // 末尾のカンマは許容される。
            // 
            // パターン設計: 
            // ^\s*               -> 行頭の空白
            // (?:[0-9]+,\s*)*     -> 数字とカンマのペア（数字の後にカンマと空白）を0回以上繰り返す
            // [0-9]+             -> 最後に少なくとも1つの数字が続く（これにより、空行やカンマのみの行を除外する）
            // (?:,\s*|[0-9]+)     -> 区切り文字（カンマと空白）または数字（末尾のカンマを許容するため）
            // $                  -> 行末
            
            // 仕様の解釈に基づき、正規表現で判定します。
            // 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」ことです。
            // これは、行内に数字とカンマ以外は含まれず、かつ少なくとも1つの数字が含まれている必要があります。
            // 末尾のカンマは許容されます。
            
            // 妥当な行の条件:
            // 1. 行が空でない（空白のみではない）
            // 2. 行が数字とカンマのみで構成されている。
            // 3. 少なくとも1つの数字が含まれている。
            // 4. 末尾のカンマは許容される。
            
            // 最も簡潔に、数字とカンマのみで構成され、数字が含まれていることを確認します。
            // (?:[0-9]+(?:,|$))+ : 数字とカンマのシーケンス。末尾のカンマも許容。
            // 
            // 妥当な行の例: "1,2,3", "1,2,"
            // 不妥当な行の例: "", "abc", "1,a", ",,"
            
            // 正規表現パターン: 
            // ^\s*                 -> 行頭の空白
            // (?:[0-9]+(?:,\s*|$))+ -> 1つ以上の数字とカンマのセット（末尾のカンマも許容）
            // \s*$                 -> 行末の空白
            
            // このパターンで、行が数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
            // ただし、行全体が数字とカンマのみで構成されていることを厳密にチェックする必要があります。
            
            // 判定ロジックを再考: 
            // 行が「数字とカンマ」で構成され、かつ「数字」が少なくとも1つあるか。
            // 
            // 行をトリムして、数字とカンマ以外の文字がないかチェックし、さらに数字が含まれているかチェックします。
            
            String trimmedLine = line.trim();
            boolean isValid = false;

            if (!trimmedLine.isEmpty()) {
                // 1. 数字とカンマのみで構成されているかチェック
                // 2. 少なくとも1つの数字が含まれているかチェック
                
                // 許容されるパターン: 数字とカンマのみで構成され、末尾のカンマも許容される。
                // 例: "1,2,3", "1,"
                // 不許容なパターン: "1a", ",,"
                
                Pattern pattern = Pattern.compile("^[0-9,]*$"); // 数字とカンマのみ
                Matcher matcher = pattern.matcher(trimmedLine);
                
                if (matcher.matches()) {
                    // 数字が含まれているかチェック (数字が0個でないこと)
                    boolean containsDigit = false;
                    for (char c : trimmedLine.toCharArray()) {
                        if (Character.isDigit(c)) {
                            containsDigit = true;
                            break;
                        }
                    }
                    
                    // 空行でないため、数字が含まれていれば妥当
                    if (containsDigit) {
                        isValid = true;
                    }
                }
            }

            if (isValid) {
                validLines++;
            }
        }

        System.out.println("valid=" + validLines);
    }
}
