const data: Buffer[] = [];
process.stdin.on("data", (c: Buffer) => data.push(c));
process.stdin.on("end", () => {
  const s = Buffer.concat(data).toString("utf8");
  let validCount = 0;
  for (const line of s.split("\n")) {
    let trimmed = line.trim();
    if (trimmed.length === 0) continue;
    
    // 空白のみの行は無視するが、上記で trim の後に空文字になった場合はスキップされる。
    // ただし問題文の「空行」は無視（判定対象外）、または妥当でない？
    // 「空行、および数字とカンマ以外を含む行は妥当ではありません」という記述があるが、
    // 例2のロジックのように「数える対象として考慮するか」が微妙だが、通常「妥当かどうかを判定します」
    // の意味は、入力された各行が正規表現に合致するか数を数えること。
    // 「空行...は妥当ではありません」という文脈から、空行を含めカウントしない（0 として扱う）のが自然。
    // ただし、もし「空白以外の数字とカンマ以外が含まれる行」が対象なら、空行は除外する。
    
    // 解析: 文字列のみが '0-9' と ',' で構成されているか確認
    if (!/^[0-9,]+$/.test(trimmed)) continue;
    
    // 「1 個以上の数字列がカンマで区切られて並んでいる」ことが必須。
    // 上記正则表現 ^[0-9,]+$ は空文字も許容する（例: ""）。
    // しかし「1 個以上の数字列」とあるので、少なくとも 1 つの数字が含まれている必要がある。
    // もし '...' に含まれるなら (e.g. ",,,") -> 空白なしでカンマのみだが、数字なし → 不成立
    // 例: "1,2," -> OK
    // 例: "1," -> OK
    // 例: "," -> NO
    
    if (/^[0-9]+$/.test(trimmed.split(",").map(s => s.trim()).filter(s => s.length > 0).join("")) && 
       trimmed.match(/[0-9]/) !== null) {
      // 少し堅牢なチェック:カンマ区切りされた要素の中に「数字」があるか、かつ空白以外のみであるか。
      // 簡易判定法として: 文字が全て数字またはカンマであれば数え上げる。しかし空の要素（コンマのみ）を含めると '..."'はダメか？
      // 「1 個以上の数字列」とあるので、「... , ...」のような連続したカンマはダメなはずだが、
      // 上記 regex ^[0-9,]+$ で通るが、実際には "1,,2" は OK か？問題文「数字とカンマ以外を含む行は妥当でない」なら '1,,2' は OK。
      // 「1 個以上の数字列」という要件は、「空白除去後、数値が存在する」ことを意味するだろう。
      
      // さらに単純化: trimmed が "0-9" と "," のみを含んでいるかつ、少なくとも 1 つの数字を持っている。
      let hasDigit = false;
      for (const char of trimmed) {
        if (!/[0-9]/.test(char)) {
           // 非数字でもないか？
           if (!(char === ',' || char === ' ')) { // 空白も許容されるから trim で処理済みだが、念のため
             continue; 
           }
        }
        hasDigit = true;
      }
      // 上記ロジックは少し複雑すぎるので修正:
      // trimmed は '0-9' と ',' のみであるか？
      // 空文字列も OK か？「1 個以上の数字列」なので、最小限 "0" もあれば OK。",,," は NO。
      
      // 再定義: 
      // 1. 空白を除去済み（trim）
      // 2. 全文字が '0-9' または ',' で構成されるか？
      // 3. 少なくとも 1 つの数字が含まれるか？
      
      if (/^[0-9,]+$/.test(trimmed) && trimmed.match(/[0-9]/) !== null) {
        validCount++;
      }
    }
  }
  console.log(`valid=${validCount}`);
});
