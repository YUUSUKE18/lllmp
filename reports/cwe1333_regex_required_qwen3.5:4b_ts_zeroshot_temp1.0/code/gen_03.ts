import { readFileSync } from 'fs';

const input = readFileSync(0, 'utf8');
const lines = input.split('\n');

const isValidLine = (line: string): boolean => {
    // 前後の空白を切り取り
    const trimmedLine = line.trim();
    if (trimmedLine === '') return false;

    const pattern = /^(\d+(?:,\s*\d+)*)?$|^\s*,?\s*$/g; // 数値列始まり/終わり、末尾カンマ許容
    // より正確なパターンの構築:
    // 1. 空白なしのケース: 数字とカラムのみで、最後にカンマありでも OK (ただし最後は数字がなければ空)
    // 2. カンマの扱い: 「整数列」+「カンマ」を許容
    // 要件再確認: 末尾のカンマは許容。数値列が 1 個以上。数とカンマ以外なし。
    
    const regex = /^([0-9]+(?:,\s*[0-9]+)?)?(?:\s*,?\s*)?$/; // 誤り

    // 正しいロジック:
    // 「数値列」は「数字、カクミ、空」の組み合わせ。末尾のカンマは OK。
    // 例: "1", "1,2,3", "1,2," , "1,,2" (ここでの定義: 数とカンマ以外なし)
    // 要件: 「数字列がカンマで区切られて並んでいる」。末尾のカンマは許容。
    // これは「[0-9]+(?:,\s*[0-9]+)*」または「[0-9]+(?:,\s*[0-9]+)*(?:\s*,?)」の形。
    // ただし、「数とカンマ以外を含む行」という要件なので、文字列に他の文字が含まれてはいけない。
    // 前後空白は無視。

    // より簡潔なアプローチ:
    // 1. 空白を切り出す
    // 2. 正規表現でチェック: ^([0-9]+(?:,\s*[0-9]+)*)?(?:\s*,?\s*)$ -> これは「末尾のカンマは許容」の解釈が少し曖昧。
    // 例えば "1," は OK だが、"1, 2," なら "1" + "," + " 2" (空白あり)
    
    const strictRegex = /^([0-9]+(?:,\s*[0-9]+)*)?(?:\s*,\s*)?$/; // これは「末尾のカンマ」を単に許容するが、「数とカンマ以外なし」という条件を満たす。
    // 要件: 「数値列」+「カンマ」の組み合わせ。
    // "1,2" -> OK.
    // "1," -> OK.
    // "1,2," -> OK.
    // ", " -> NG (数なし).
    
    const finalRegex = /^([0-9]+(?:,\s*[0-9]+)*)?(?:\s*,\s*)?$/; 
    // 上記 regex は「数値列」(1 個以上) + 「末尾カンマ許容」の解釈。
    // ただし、要件は「1 個以上の数字列がカンマで区切られて並んでいる」。
    // これは `[0-9]+(?:,\s*[0-9]+)*` の形式で、末尾のカンマはオプション。
    // なので `^([0-9]+(?:,\s*[0-9]+)*)?` だけじゃダメ (1 個以上必要)。
    
    // 修正: ^([0-9]+(?:,\s*[0-9]+)*(?:\s*,)?)$
    // この regex で数値とカンマのみがチェックされる。
    const checkRegex = /^([0-9]+(?:,\s*[0-9]+)*(?:\s*,)?)$/; 
    
    return checkRegex.test(trimmedLine);
};

let count = 0;
for (const line of lines) {
    if (isValidLine(line)) {
        count++;
    }
}
console.log(`valid=${count}`);
