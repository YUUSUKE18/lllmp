import { createInterface } from 'readline';

const rl = createInterface({
	input: process.stdin,
	output: process.stdout,
});

let validCount = 0;

rl.on('line', (line) => {
	const trimmedLine = line.trim();
	if (trimmedLine === '') {
		return; // 空行は許容されるが、有効なデータ行ではないためカウントしない。ただし仕様「妥当とは...」を厳密に解釈する必要があるか？
		// 再考：「空行...は妥当ではありません」とあり、「1 個以上の数字列...並んでいること」が妥当条件。
		// よって、空行はデータが存在せず、1 個以上の数字列が存在しないため「妥当ではない」。
		// したがって、空行はカウントしない。
	}

	const regex = /^[ \t]*((?:-?\d+)(?:,\s*-?\d+)*)?\s*$/; // 末尾カンマ許容 (例："1,2," は "1,2" + "," だが、正規表現の構文で末尾のカンマを数字として認める必要はないか？)
	// 再考：仕様「末尾のカンマは許容します」。例：「1」→ valid、「1,2」→ valid、「1,」→ valid?
	// 通常カンマ区切りでは「1,」はエラーだが、今回は明示的に許容。
	// つまり、「1」または「1,」などが許容されるのか？それとも「1,2,」まで許容されるのか？
	// 「1 個以上の数字列がカンマで区切られて並んでいること」。
	// 解釈 A: 要素リストである必要がある。(例："1" , "1,2" ) -> Valid. ("1,") は要素の末尾がないので Invalid?
	// しかし「末尾のカンマは許容します」とあるから、「1,」も Valid とすべき。
	// つまり、末尾までカンマが来ても OK。つまりリスト形式ではなく、単に「数字」と「カンマ」の組み合わせで良いのか？
	// 「数字列がカンマで区切られて並んでいること」。これは要素が存在することを含めるか？
	// 例：「1,2,3,」 → Valid. 「1」→ Valid. 「1,」→ Valid. 「,1」→ ? (先頭にカンマは禁止？) -> "数字列...区切られて並んでいる"。最初の数字がなければ「数字列」がない。
	// したがって、最初に数字があることと、末尾まで（または末尾カンマあり）のカンマ構造を許容する必要がある。
	// しかし「1,2」では最後の数字後にはカンマがない。
	// 「1,」では最初の数字後のみカンマがある。
	// 共通項：すべてが「数字」、「カンマ」または「終止」という形で構成されるか？
	// より単純に解釈：すべての文字は「-?d+」(数) または','であること。そして、最初の文字が','ではない（数字で始まる）こと。
	// なぜなら「1 個以上の数字列...並んでいる」から、少なくとも 1 つの数字が必要だから。
	// そして「末尾のカンマは許容します」という条件は、「最後の数字後にカンマがあったとしても OK」という意味。
	// つまり：^[ \t]*(-?\d+(?:,\s*-?\d+)*)?(\s*[,])?$ ではなく、単純に 'd'や','以外の文字禁止 + 数字あり。
	// さらに「並んでいること」→ 複数の数字がカンマで区切られる構造も許容。
	// なので、正規表現は：^[ \t]*[-?\d,]+[ \t]*$ (数字とカンマのみ) が必須条件。そして「1 個以上の数字列」という制約をどう満たすか？
	// 「1 個以上の数字列」→ 少なくとも 1 つの数字があること。
	// つまり、文字列に "d" が含まれていなければならない。
	
	if (!trimmedLine.match(/^[ \t]*[-?\d,]+[ \t]*$/)) {
		return; // キャンマと数字以外を含む行は妥当ではない
	}

	const hasDigit = /[\d-]/.test(trimmedLine);
	if (hasDigit) {
		validCount++;
	}
});

rl.on('close', () => {
	process.stdout.write(`valid=${validCount}\n`);
});
