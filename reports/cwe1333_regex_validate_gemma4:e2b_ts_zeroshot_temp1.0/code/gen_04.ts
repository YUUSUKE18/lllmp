import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    if (input === "") {
        console.log("valid=0");
        return;
    }

    const lines = input.split('\n');
    let validCount = 0;

    for (const line of lines) {
        // 行の前後の空白を無視して処理
        const trimmedLine = line.trim();

        if (trimmedLine === "") {
            // 空行は妥当ではない
            continue;
        }

        // 末尾のカンマは許容するが、それ以外は数字とカンマのみで構成されている必要がある
        // 正規表現でチェックする: 1文字以上の数字とカンマのみで構成されているか
        // 末尾のカンマがあっても許容する
        // (?:[0-9,]+) は1文字以上の数字またはカンマの繰り返しを表す
        const regex = /^[0-9,]*[0-9]$|^[0-9,]+$|^[0-9,]*$/;

        // より厳密に、数字とカンマ以外の文字を含まないことを確認する
        // 妥当な条件: 1個以上の数字列がカンマで区切られて並んでいること。
        // これは、行が数字とカンマだけで構成されていること、かつ空でないこと、という条件から導かれる。

        // 1. 数字とカンマ以外の文字が含まれていないかチェック
        if (!/^[0-9,]*$/.test(trimmedLine)) {
            continue; // 数字とカンマ以外の文字を含む行は不妥当
        }

        // 2. 1個以上の数字列がカンマで区切られているか（空行を除く）
        // 末尾のカンマがあっても良い
        if (trimmedLine.length === 0) {
            continue; // 空行はスキップ済みだが念のため
        }

        // 妥当性の判定ロジック
        // 妥当なのは「1個以上の数字列がカンマで区切られて並んでいる」こと。
        // これは、行内にカンマが存在するか、あるいは数字のみで構成されている必要がある。
        // 例: "1,2,3" (妥当), "123" (妥当, 1個の列), "1," (妥当), "," (不妥当, 1個以上の数字列でない), "abc" (不妥当)

        // 問題文の解釈に基づき、「カンマで区切られて並んでいる」ことを中心に考える。
        // 「1 個以上の数字列がカンマで区切られて並んでいる」
        // これは、カンマが少なくとも1つ含まれているか、または行全体が単一の数字列である必要がある。
        // しかし、「妥当とは、1 個以上の数字列がカンマで区切られて並んでいることです」という定義を最も直接的に満たすのは、
        // 少なくとも一つのカンマが存在し、かつ数字が含まれているケース。
        // もし "123" が妥当なら、それは1個の数字列と解釈できる。

        // 最も一般的な解釈（区切り文字の存在）を採用する: カンマが含まれているか、あるいは数字のみであること。
        // 行が空でない、かつ数字とカンマのみで構成されていれば「妥当」と見なす。
        // 空行は除外済み。
        
        // 末尾のカンマを無視して、カンマで分割してみて、要素がすべて数字列であるか確認する。
        // 妥当なのは、カンマで分割した要素がすべて数字列であること。
        
        const parts = trimmedLine.split(',');
        let isValid = false;

        if (parts.length > 0) {
            // 各要素が数字列であるかチェック
            const allAreNumbers = parts.every(part => {
                // 末尾のカンマが残っている場合は、その部分もチェック対象とする
                const p = part.trim();
                if (p === "") {
                    // カンマが連続した場合 (例: "1,,2") や、末尾のカンマで生じた空文字列
                    // この場合、全体が「1個以上の数字列」という定義に反する可能性がある。
                    // しかし、仕様では「末尾のカンマは許容します」ので、これは空の要素として扱われる。
                    return true; // 空の要素は許容する（カンマが連続している場合）
                }
                // 数字のみ（または数字とカンマの組み合わせ）であること
                return /^[0-9]+$/.test(p) || /^[0-9,]+$/.test(p); // 実際には、部分が数字列であるかを確認すれば十分。
            });

            // シンプルな解釈に戻る: 行が空でなく、数字とカンマ以外を含まず、かつ少なくとも1つのカンマがあるか、または単一の数字列であること。
            // 「1 個以上の数字列がカンマで区切られて並んでいる」 -> 少なくとも1つのカンマが必要であると解釈するのが自然。
            
            // 1. 少なくとも1つのカンマが含まれていること
            if (trimmedLine.includes(',')) {
                // カンマが含まれていれば、カンマ区切りであると見なす。
                isValid = true;
            } else if (/^[0-9]+$/.test(trimmedLine)) {
                // カンマがない場合、単一の数字列として扱う。これは「1個の数字列」と解釈できる。
                isValid = true;
            } else {
                // 数字とカンマ以外を含む行は既に除外済み (regexチェックでフィルタリング)
                isValid = false;
            }
        }
        
        // 再評価: 「妥当とは、1 個以上の数字列がカンマで区切られて並んでいることです。」
        // "123" -> 1個の数字列。区切られていない。 (これは定義に反する可能性)
        // "1,2" -> 2個の数字列がカンマで区切られている。 (妥当)
        // "1," -> 1個の数字列とカンマ。 (妥当)

        // カンマを含むかどうかで判定するのが最も仕様に近いと判断。
        if (trimmedLine.includes(',')) {
            validCount++;
        } else if (/^[0-9]+$/.test(trimmedLine)) {
            // カンマがない場合、単一の数字列と見なす。
            // ただし、もし「区切られて並んでいる」ことを厳密に要求するなら、これは不妥当。
            // しかし、もしこの行が数字列として許容されるならカウントすべき。
            // 今回は「カンマ区切り」を要求しているため、カンマがないものは除外する。
            // 例外的に、"123"を妥当としない前提で進める。
        }
    }

    // 再度、行ごとに厳密に判定し直す
    validCount = 0;
    for (const line of lines) {
        const trimmedLine = line.trim();
        if (trimmedLine === "") continue;

        // 数字とカンマ以外を含まないかチェック
        if (!/^[0-9,]*$/.test(trimmedLine)) {
            continue;
        }

        // 妥当性の判定: 1個以上の数字列がカンマで区切られて並んでいる
        // これは、行内にカンマが存在し、かつ、カンマで区切られた要素が数字列であることを意味する。
        // 末尾のカンマが許容されるため、"1,2," は 1, 2 の2つの数字列とみなせる。
        if (trimmedLine.includes(',')) {
            validCount++;
        }
    }


    console.log(`valid=${validCount}`);
}

solve();
