import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    if (!input) {
        console.log('valid=0');
        return;
    }

    const lines = input.split('\n');
    let validCount = 0;

    for (const line of lines) {
        // 行の前後の空白を無視
        const trimmedLine = line.trim();

        if (trimmedLine === '') {
            // 空行は妥当ではない
            continue;
        }

        // 末尾のカンマは許容される
        // 行が空でない場合、カンマ区切りの整数列である必要がある
        
        // 妥当性の判定ロジック：
        // 1. 数字とカンマ以外を含む行は不妥当
        // 2. 1個以上の数字列がカンマで区切られて並んでいること
        
        // 行全体をカンマで分割してみる
        // 末尾のカンマがあっても、split(',')は要素を生成する
        const parts = trimmedLine.split(',');

        if (parts.length === 0) {
            // これは trimmedLine が空だった場合に対応するが、既に上でチェックしているため不要
            continue;
        }

        // すべての要素が空文字列でないことを確認する（数字列が存在すること）
        // parts.filter(p => p.length > 0).length で、実際の数字列の数を数えることも考えられるが、
        // 仕様「1個以上の数字列がカンマで区切られて並んでいること」を満たすには、
        // 区切り文字で区切られた要素が、数字として解釈できることが重要。
        // ここでは、空でない要素が1つ以上存在すれば、それは「数字列がカンマで区切られている」と見なす。
        // ただし、"数字とカンマ以外を含む行は妥当ではない"という制約があるため、
        // partsの要素をチェックする。
        
        let isValid = true;
        
        // 1. 数字とカンマ以外を含む行のチェック
        // 行が "1,2," の場合、parts は ["1", "2", ""] となる。
        // 空の要素は許容される（末尾カンマの場合）。
        // もし、"a,1" のような行であれば、"a" は数字ではないため不妥当。
        
        for (const part of parts) {
            if (part.length > 0) {
                // 部分が数字のみで構成されているかチェック
                if (!/^\d+$/.test(part)) {
                    isValid = false;
                    break;
                }
            }
        }
        
        // 2. 1個以上の数字列がカンマで区切られて並んでいること
        // これは、partsが少なくとも1つあること（既にチェック済み）と、
        // その中で少なくとも1つは数字列であること（上記ループでカバーされている）で十分か、
        // それとも空の要素がすべて無視されるか？
        
        // 仕様の解釈：「1個以上の数字列がカンマで区切られて並んでいる」
        // 例えば "1,," は、数字列 "1" の1つと空の要素が2つある。
        // 空の要素は区切りが連続していることを示唆する。
        // "1,2" -> ["1", "2"] (2個の数字列) -> OK
        // "1,," -> ["1", "", ""] (1個の数字列) -> OK (1個の数字列が区切られている)
        
        // 空行でないことが保証されており、かつ、行が数字とカンマのみで構成されている場合、
        // 少なくとも1つの非空の数字列が存在すれば、その行は妥当と見なす。
        
        // 実際に入力として与えられた行が、空でないかつ、
        // 全ての非空要素が数字であり、カンマで区切られているという構造があれば妥当。
        
        if (isValid) {
            // 少なくとも1つの非空の数字列が存在するか？
            // partsが全て空文字列（例: "," や ",,"）の場合、isValidはtrueになるが、これは数字列ではない。
            const actualNumberStrings = parts.filter(p => p.length > 0);
            if (actualNumberStrings.length >= 1) {
                validCount++;
            }
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
