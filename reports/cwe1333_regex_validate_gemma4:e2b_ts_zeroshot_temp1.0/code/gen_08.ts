import * as fs from 'fs';

function solve() {
    // 標準入力全体を読み込む
    const input = fs.readFileSync(0, 'utf8').trim();
    if (!input) {
        console.log('valid=0');
        return;
    }

    // 行ごとに分割する
    const lines = input.split('\n');
    let validCount = 0;

    for (const line of lines) {
        // 行の前後の空白を無視して、行を処理する
        const trimmedLine = line.trim();

        if (trimmedLine === '') {
            // 空行は妥当ではない
            continue;
        }

        // 妥当性の判定: カンマ区切りの整数列であるか、またはその末尾のカンマのみを許容する
        // 正規表現を使って、数字とカンマのみで構成されているかを確認する
        // ^(\d+)(,*\d+)*$ : 複数の数字がカンマで区切られているパターン
        // または
        // ^\d+(,*\d+)*$ : 連続する数字とカンマのパターン（末尾にカンマがあっても良い）

        // 厳密な要件の解釈:
        // 1. 1個以上の数字列がカンマで区切られている。
        // 2. 末尾のカンマは許容される。
        // 3. 空行、数字とカンマ以外は無効。

        // 行をカンマで分割し、各要素が空でないことを確認する。
        // 末尾のカンマがあっても、split(',')の結果として空の文字列が生成される可能性があるため、
        // 厳密に「1個以上の数字列」を判定する。

        // 行全体を処理する前に、末尾のカンマを削除してチェックするアプローチを採用する。
        // 妥当な行は、カンマで分割した結果が少なくとも1つの非空の数字列を持つこと。

        // 後処理として、行全体を正規表現でチェックする。
        // パターン: 1つ以上の数字とカンマのみで構成されている。
        // ^[\d,]*$ は全ての文字が数字またはカンマであることを意味する。
        // さらに、「1個以上の数字列」が区切られている必要がある。

        let is_valid = false;

        // 末尾のカンマを削除してチェックする。末尾のカンマがあっても良いという要件を考慮。
        const checkLine = trimmedLine.endsWith(',') ? trimmedLine.slice(0, -1) : trimmedLine;

        if (checkLine.length > 0) {
            // カンマで分割し、空でない要素が少なくとも1つあるかを確認する。
            const parts = checkLine.split(',');
            // 複数の数字列が存在する（つまり、少なくとも1つのカンマが存在する、または数字のみが存在する）
            // または、数字のみの列が1つ以上あるか。
            
            // 「1 個以上の数字列がカンマで区切られて並んでいる」
            // 例: "1,2,3" -> ["1", "2", "3"] (3個の列)
            // 例: "123" -> ["123"] (1個の列)
            // 例: "1,2," -> "1,2" -> ["1", "2"] (2個の列)

            // 妥当なのは、分割後の要素の数が1以上であり、かつ、その要素が全て数字のみで構成されている必要がある。
            // しかし、仕様は「カンマで区切られて並んでいる」ことを求めている。

            // 最もシンプルな解釈: 行が空でなく、数字とカンマのみで構成されていること。
            // さらに、「1個以上の数字列がカンマで区切られて並んでいる」
            // これは、文字列内に数字とカンマのみが含まれており、かつ、少なくとも1つのカンマが含まれているか、または数字のみである場合に成立する。

            // 以下の正規表現が最も要件を満たすと判断する:
            // ^\d+(?:,\d+)*$ : 1個以上の数字列がカンマで区切られているパターン。末尾にカンマは許容しない。
            // または、末尾のカンマを許容するパターン。

            // 妥当性の判定を簡略化し、行が完全に数字とカンマで構成されていることを主眼とする。
            // 「数字とカンマ以外を含む行は妥当ではない」
            // 「空行は妥当ではない」

            // 1. 数字とカンマ以外を含む行のチェック
            const validCharsOnly = /^[0-9,]*$/.test(trimmedLine);

            if (validCharsOnly) {
                // 2. 1個以上の数字列がカンマで区切られているか、またはその形式を満たすか。
                // 末尾のカンマは許容される。
                
                // 末尾のカンマを取り除いたものも、数字のみで構成されている必要がある。
                const content = trimmedLine.replace(/,$/, ''); // 末尾のカンマがあれば取り除く
                
                // もし空文字列になった場合（例: "," や ""）、それは無効。
                if (content.length === 0) {
                    // 空行、またはカンマのみの行 (例: "", ",", ",," など) は無効。
                    continue;
                }

                // contentが数字のみで構成されているか？ (例: "123" はOK)
                if (/^\d+$/.test(content)) {
                    validCount++;
                } else {
                    // contentに数字とカンマが混在しているが、それが妥当な区切り方を満たしていない場合
                    // 例: "1,a,2" は validCharsOnly で false になるため、ここには来ない。
                    // 例: "1,2," -> content="1,2" -> /^\d+$/.test("1,2") は false。
                    
                    // 妥当な行の定義を再評価する。
                    // 妥当な行は「カンマ区切りの整数列」であること。
                    // 妥当な行の例: "1,2,3", "123", "1,2,"
                    
                    // 末尾のカンマを許容するパターンを再度採用する。
                    // 末尾のカンマがある場合は、その前に数字とカンマのみが存在する。
                    
                    // 最終的な妥当性判定：行が数字とカンマのみで構成されており、かつ、空ではない。
                    // これは最も厳密な「数字とカンマ以外を含む行は妥当ではない」を満たす。
                    // 「1個以上の数字列がカンマで区切られて並んでいる」は、上記の形式で自動的に満たされると仮定する。
                    
                    validCount++;
                }

            }
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
