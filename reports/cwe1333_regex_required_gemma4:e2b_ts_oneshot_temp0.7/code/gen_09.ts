process.stdin.setEncoding("utf8");

let validCount = 0;
let buffer = "";

process.stdin.on("data", (data: string) => {
  buffer += data;
});

process.stdin.on("end", () => {
  const lines = buffer.split(/\r?\n/);
  let validLines = 0;

  for (const line of lines) {
    // 行の前後の空白を無視
    const trimmedLine = line.trim();

    if (trimmedLine === "") {
      // 空行は妥当ではない
      continue;
    }

    // 正規表現による判定: 
    // 1. 1個以上の数字とカンマの組み合わせ（カンマ区切り）
    // 2. 末尾のカンマは許容される
    // 3. 数字とカンマ以外を含む行は不適
    
    // 正規表現の解説:
    // ^: 行の先頭
    // [0-9,]*: 0個以上の数字またはカンマ
    // (?:,?\d+)*: カンマで区切られた数字のグループ。
    // $ : 行の末尾
    // この問題の要件は「1個以上の数字列がカンマで区切られて並んでいる」ことと「数字とカンマ以外を含まない」ことです。
    // より厳密に「カンマ区切りの整数列」を判定するために、数字とカンマのみで構成されているかをチェックします。

    // 許容されるパターン: 数字とカンマのみで構成され、1つ以上の数字が含まれている、またはカンマのみの場合。
    // 以下の正規表現は、カンマで区切られた整数列（数字とカンマのみ）を許容します。
    // ^[0-9,]*$: 数字とカンマのみで構成されていること。
    // さらに「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するために、カンマの存在と数字の存在を考慮する必要があります。

    // 妥当性の定義を再確認: 「1個以上の数字列がカンマで区切られて並んでいる」
    // 例: "1,2,3" -> 妥当
    // 例: "1," -> 妥当 (末尾のカンマ許容)
    // 例: "," -> 妥当？ (1個以上の数字列がないため不妥当)
    // 例: "abc" -> 不妥当

    // 数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
    const regex = /^[0-9,]+$/;

    if (regex.test(trimmedLine)) {
      // 数字とカンマのみで構成されている
      // さらに「1個以上の数字列」があるかを確認する。
      // カンマのみの行 (例: ",") は、数字列がないため不妥当。
      // 数字が含まれているかを確認する。
      if (trimmedLine.includes("0") || trimmedLine.includes("1") || trimmedLine.includes("2") || trimmedLine.includes("3") || trimmedLine.includes("4") || trimmedLine.includes("5") || trimmedLine.includes("6") || trimmedLine.includes("7") || trimmedLine.includes("8") || trimmedLine.includes("9")) {
        // 数字が含まれている場合、これは妥当なカンマ区切りの整数列である可能性が高い。
        // 末尾のカンマも許容されるため、この条件で妥当と見なす。
        validLines++;
      } else if (trimmedLine.includes(',')) {
        // 数字を含まず、カンマのみの行 (例: "," や ",," など) は不妥当。
        // ただし、上記の regex.test(trimmedLine) で既にチェックされているため、
        // 1個以上の数字列が区切られているという条件を満たさないため、ここではカウントしない。
        // 例: "," は regex.test("," ) が true。しかし数字を含まないので不妥当。
        // 妥当なのは "1," や "1,2" のように数字が含まれる場合のみ。
        // 厳密に「1個以上の数字列」が区切られているかを判定するため、数字の存在をチェックします。
        // したがって、数字が含まれていればOKとします。
        // 上記の if ブロックが成立すれば、それは妥当です。
      }
    }
  }

  console.log(`valid=${validLines}`);
});
