const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validCount = 0;

rl.on('line', (line) => {
  // 行の前後の空白を無視する
  const trimmedLine = line.trim();

  if (trimmedLine === "") {
    // 空行は妥当ではない
    return;
  }

  // 正規表現による妥当性の判定
  // 1. 少なくとも1つの数字が含まれていること (/\d+/ が1回以上マッチすること)
  // 2. 数字とカンマ以外が含まれていないこと (^[0-9,]*$ )
  // 3. 末尾のカンマは許容される (/\d+(,\d+)*\)?$) のような形を許容する
  // 課題の仕様を厳密に解釈すると、「1個以上の数字列がカンマで区切られて並んでいる」こと、
  // 「数字とカンマ以外を含む行は妥当ではない」ことを考慮する。

  // 妥当なパターン: 1つ以上の数字とカンマの組み合わせのみで構成されている。
  // 例: "1,2,3", "1,2,", "1"
  // 許容されるのは、数字とカンマのみで構成されていること。
  // 正規表現: ゼロ個以上の数字とカンマの組み合わせ
  // ただし、数字とカンマ以外は許されない。

  // 1. 数字とカンマのみで構成されているか (行全体が \d や , のみで構成されている)
  // 2. 複数の数字列がカンマで区切られているか (カンマが1つ以上含まれているか、または数字が複数あるか)

  // より直接的に「1個以上の数字列がカンマで区切られている」ことを判定する。
  // 1. 少なくとも1つの数字が含まれていること。
  // 2. 数字とカンマ以外の文字が含まれていないこと。

  // 数字とカンマのみで構成されていることを確認
  const validPattern = /^[0-9,]*$/;
  if (!validPattern.test(trimmedLine)) {
    return; // 数字とカンマ以外が含まれていたら不妥当
  }

  // 少なくとも1つの数字が含まれていることを確認
  const containsDigit = /\d/.test(trimmedLine);
  if (!containsDigit) {
    return; // 数字が一つも含まれていなければ不妥当
  }

  // 数字とカンマのみで構成され、数字が含まれている場合、これは妥当と見なす。
  // 末尾のカンマは許容される。
  validCount++;
});

rl.on('end', () => {
  console.log(`valid=${validCount}`);
});
