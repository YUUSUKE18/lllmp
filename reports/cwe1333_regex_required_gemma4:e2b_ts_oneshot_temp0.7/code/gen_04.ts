const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
  // 行の前後の空白を無視
  const trimmedLine = line.trim();

  if (trimmedLine === "") {
    // 空行は妥当ではない
    return;
  }

  // 正規表現で判定:
  // ^\s*            - 行の先頭の空白を許容
  // [\d,]+          - 1個以上の数字とカンマの組み合わせ（数字とカンマのみで構成される）
  // \s*$            - 行の末尾の空白を許容
  // この正規表現は、「数字とカンマのみで構成され、1つ以上ある」ことを確認します。
  // ただし、仕様は「1個以上の数字列がカンマで区切られて並んでいる」ことを要求しています。
  // 「1個以上の数字列がカンマで区切られて並んでいる」を厳密に捉えるには、
  // 数字とカンマのみで構成され、カンマを含む（またはカンマで区切られた）ことを確認する必要があります。

  // 妥当な行の定義を再検討します:
  // 1. 1個以上の数字列がカンマで区切られている。
  // 2. 空行、数字とカンマ以外を含む行は妥当ではない。

  // 「カンマ区切りの整数列」の妥当性を判定するために、
  // 「数字とカンマのみで構成され、少なくとも1つのカンマが含まれる、または数字列のみで構成されている」という解釈が考えられます。
  // しかし、「末尾のカンマは許容します」という点から、`/\d+(,\d+)*$/` や `/\d+(,\d+)*,?$/` のような形が適切です。

  // 1. 数字とカンマのみで構成されているか？
  // 2. 末尾のカンマは許容されるか？

  // 正規表現を「1個以上の数字列がカンマで区切られて並んでいる」に絞って解釈します。
  // 少なくとも1つの数字列があり、カンマが含まれる可能性がある。
  // 例: "1,2,3" (妥当), "100," (妥当), "100" (妥当?)
  // 「1個以上の数字列がカンマで区切られて並んでいる」を満たすためには、少なくとも1つのカンマが必要、または数字列が複数ある必要があります。

  // ここでは、数字とカンマのみで構成され、かつカンマが含まれているか、または数字列が複数存在する場合を妥当とします。
  // 厳密に「カンマ区切り」を重視し、数字とカンマのみで構成されていることを確認します。
  // 正規表現: 1つ以上の数字とカンマが混在しているか、またはカンマで区切られている。
  // 妥当なパターン: 数字とカンマのみで構成され、空行でない。
  // 1. 数字とカンマのみで構成されているか: /^[0-9,]*$/
  // 2. カンマが含まれているか、または数字列が複数あるか。

  // 仕様の最も厳しい解釈に基づき、数字とカンマのみで構成されていることを確認します。
  // 末尾のカンマは許容されるため、行全体が数字とカンマのみで構成されていればOKとします。
  // 「1個以上の数字列がカンマで区切られて並んでいる」を満たすには、少なくとも1つの数字が存在する必要があります。

  const regex = /^[\d,]*$/;

  if (regex.test(trimmedLine)) {
    // 数字とカンマのみで構成されている。
    // さらに「1個以上の数字列」があるかを確認する。
    // 数字が存在しない場合（例: "," や "" は既に除外）、これは妥当ではない。
    // 少なくとも1つの数字が存在するかどうかをチェック。
    if (/\d/.test(trimmedLine)) {
      validLines++;
    }
  }
});

rl.on('end', () => {
  console.log(`valid=${validLines}`);
});
