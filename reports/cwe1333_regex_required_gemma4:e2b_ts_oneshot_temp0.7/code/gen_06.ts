const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validCount = 0;

rl.on('line', (line) => {
  // 行の前後の空白を無視
  const trimmedLine = line.trim();

  // 正規表現で判定:
  // ^\s*               -> 行の先頭の空白（無視）
  // (?:[0-9]+(?:,.*)?)* -> 1つ以上の数字列とカンマの組み合わせ（非貪欲マッチで複数回繰り返す）
  // \s*$               -> 行の末尾の空白
  // この正規表現は「1個以上の数字列がカンマで区切られて並んでいる」ことを厳密に捉える必要があります。
  // 仕様：「1 個以上の数字列がカンマで区切られて並んでいる」
  // 例: "1,2,3" -> OK
  // 例: "1,2," -> OK
  // 例: "1,2, " -> OK
  // 例: "abc" -> NG
  // 例: "" -> NG
  
  // 許容されるパターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれていること。
  // 数字とカンマのシーケンスが連続していることを確認しつつ、数字が少なくとも1つあることを確認する。
  // よりシンプルなアプローチとして、数字とカンマのみで構成され、空行でないことを確認します。
  
  // 1. 空行チェック
  if (trimmedLine === "") {
    // 空行は妥当ではない
    return;
  }

  // 2. 数字とカンマ以外が含まれていないかチェック
  // 正規表現: 数字 (0-9) と カンマ (,) のみで構成されているか
  // 末尾のカンマは許容されるため、行全体が数字とカンマで構成されているかを確認します。
  // ^[0-9,]*$ : 数字とカンマのみで構成されている
  // ただし、これは「1個以上の数字列がカンマで区切られている」という構造チェックではありません。
  
  // 構造チェック: カンマで区切られた数字列が存在するか
  // 正規表現の意図を再解釈: カンマで区切られた数字列が1つ以上存在する。
  // 例: "1,2" -> 1と2の2つの数字列
  // 例: "1," -> 1の1つの数字列
  
  // 数字とカンマのみで構成されていることを確認し、かつ数字が少なくとも1つ存在すること。
  const matches = trimmedLine.match(/^[0-9,]+$/);
  
  if (matches) {
    // 数字とカンマのみで構成されている
    // さらに、数字が少なくとも1つ含まれているかを確認する。
    // " ," や "," はNG。数字が少なくとも1つあることを確認。
    if (trimmedLine.includes(String(parseInt(trimmedLine.replace(/,/g, '')) || 0))) {
        // 数字が含まれていることを確認（ただし、全てカンマのみの行はNG）
        // 少なくとも1つの数字が含まれているかを確認する
        const digits = trimmedLine.replace(/,/g, '');
        if (digits.length > 0) {
            validCount++;
        }
    }
  }
});

rl.on('end', () => {
  console.log(`valid=${validCount}`);
});
