const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
  // 正規表現の解説:
  // ^\s*          : 行の先頭の任意の空白文字
  // (?:          : 非キャプチャグループの開始
  //   \d+        : 1つ以上の数字
  //   ,?         : 0個または1個のカンマ
  // )+           : 上記のグループが1回以上繰り返される
  // \s*$         : 行の末尾の任意の空白文字
  // このパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを要求します。
  // 末尾のカンマは許容されます。
  const regex = /^\s*(?:\d+(?:,\d+)*)\s*$/;

  // 末尾のカンマのみの行（例: "," や ",," など）は、数字列が1つ以上存在しないため、
  // この正規表現ではマッチしません。
  // 妥当であるためには「1個以上の数字列がカンマで区切られて並んでいる」必要があります。

  // 厳密な仕様の解釈に基づき、数字とカンマのみで構成され、かつ数字が少なくとも1つ存在することをチェックします。
  // 「1 個以上の数字列がカンマで区切られて並んでいる」
  // 例: "1,2,3" (3つの数字列)
  // 例: "1," (1つの数字列と末尾のカンマ)
  // 例: "," (0個の数字列) -> 不妥当
  // 例: "abc" -> 不妥当

  // 修正された正規表現の考え方:
  // 1. 行が空行でないこと。
  // 2. 行が数字とカンマのみで構成されていること。
  // 3. 数字が含まれていること。

  // 課題の仕様を再評価: 「1 個以上の数字列がカンマで区切られて並んでいることです。末尾のカンマは許容します。」
  // これは、カンマで区切られた要素が整数であることを意味します。
  // 例: "1,2,3" -> 3つの整数列。
  // 例: "1,2," -> 2つの整数列。
  // 例: "," -> 0個の整数列（不妥当）

  // 数字とカンマのみで構成され、かつ数字が少なくとも1つ含まれていることを確認する。
  const isValid = /^\s*[\d,]+\s*$/.test(line);

  // さらに厳密に「1個以上の数字列」をチェックするため、カンマの配置も考慮する必要があります。
  // 少なくとも1つの数字が含まれていることを確認します。
  const containsDigit = /[\d]/g.test(line);

  if (isValid && containsDigit) {
    validLines++;
  }
});

rl.on('close', () => {
  console.log(`valid=${validLines}`);
});
