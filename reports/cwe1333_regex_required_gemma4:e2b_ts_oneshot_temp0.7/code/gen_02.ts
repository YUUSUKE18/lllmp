process.stdin.setEncoding("utf8");
let validCount = 0;

process.stdin.on("data", (data: string) => {
  const line = data.trim();
  if (line === "") {
    // 空行は妥当ではない
    return;
  }

  // 正規表現パターン:
  // ^\s*          -> 行頭の任意の空白
  // (?:         -> 非キャプチャグループの開始
  //   \d+,\s*    -> 1つ以上の数字とカンマ、それに続く任意の空白
  // )+          -> 上記のパターンが1回以上繰り返される
  // \d+         -> 最後の数字列 (カンマなし)
  // (?:,\s*)*    -> 末尾のカンマと空白が0回以上続く
  // $            -> 行末
  // このパターンは、カンマ区切りの整数列が1つ以上存在し、かつ、数字とカンマ以外の文字が含まれていないことをチェックする。
  // 厳密には、「1個以上の数字列がカンマで区切られて並んでいる」という条件を満たすかを確認する必要があります。

  // より厳密な判定ロジック:
  // 1. 行全体が数字、カンマ、空白のみで構成されているか。
  // 2. 少なくとも1つの数字列が存在するか。
  // 3. 末尾のカンマは許容される。

  // 正規表現で「数字とカンマ、空白のみ」であることを確認し、その後に「数字が少なくとも1つ」あるかを確認する。
  // 妥当な行のパターン: (数字, 数字, ...) または (数字, 数字, ...) ,
  // これは、数字とカンマのシーケンスが1つ以上存在し、その中にカンマが少なくとも1つ含まれているか、または数字のみの列が存在することを意味します。

  // 妥当な行の判定基準を正規表現で表現します。
  // 1. 数字とカンマ、空白以外の文字がないこと: ^[\d, \t\n]*$
  // 2. 少なくとも1つの数字列があること: この条件は、上記1つに加えて、数字が存在することを意味します。

  // 以下の正規表現は、「数字、カンマ、空白のみ」で構成されており、かつ、数字が1つ以上含まれていることを確認します。
  // (?:[\d,]+\s*)+ は、カンマ区切りの数字列のシーケンスを意味します。
  // \d+ は、少なくとも1つの数字列が存在することを保証します。

  const regex = /^[\d, \t\n]*((?:\d+(?:,\s*))*)\s*$/;

  if (regex.test(line)) {
    // 数字列が1つ以上存在することを確認
    const parts = line.split(',').map(s => s.trim());
    let hasNumber = false;
    for (const part of parts) {
      if (/^\d+$/.test(part)) {
        hasNumber = true;
        break;
      }
    }

    if (hasNumber) {
      validCount++;
    }
  }
});

process.stdin.on("end", () => {
  console.log(`valid=${validCount}`);
});
