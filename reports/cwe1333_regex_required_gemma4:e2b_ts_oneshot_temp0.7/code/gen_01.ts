const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let lines: string[] = [];
let validCount = 0;

rl.on('line', (line) => {
  const trimmedLine = line.trim();
  if (trimmedLine === "") {
    // 空行は妥当ではない
    return;
  }

  // 正規表現: 1つ以上の数字とカンマのみを含む。末尾のカンマも許容。
  // ^\s* : 行頭の空白を無視
  // ([\d,]+) : 1つ以上の数字とカンマのグループ
  // \s*$ : 行末の空白を無視
  // この正規表現は、行全体が数字とカンマだけで構成されていることを確認する。
  // 妥当な行の定義: 1個以上の数字列がカンマで区切られていること。
  // 厳密に「1個以上の数字列がカンマで区切られている」ことをチェックするには、
  // カンマのパターンをより厳密に定義する必要があります。

  // 妥当な行のパターン:
  // 1. 数字とカンマのみで構成されていること。
  // 2. 少なくとも1つの数字が含まれていること。

  // 正規表現の調整:
  // 行全体が数字とカンマのみで構成されていることを確認しつつ、
  // 少なくとも1つの数字が含まれていることを確認します。
  const pattern = /^[\d,]*$|^[\d,]+.*$/; // これは複雑すぎるため、より直接的にチェックします。

  // 妥当性の判定ロジックを再考:
  // 「1 個以上の数字列がカンマで区切られて並んでいること」
  // これは、カンマで区切られた要素が全て整数である、ということを意味します。
  // 妥当な行の例: "1,2,3", "100,", "1,2,"
  // 不妥当な行の例: "", "a,b", "1,," (空の要素が連続していると見なすか？)

  // 仕様に基づき、行が「カンマで区切られた整数列」であるかを判定します。
  // 1. 行が空でないこと。
  // 2. 行に含まれる各要素が整数であること。
  // 3. 区切り文字がカンマのみであること。

  // 正規表現で「1個以上の数字列がカンマで区切られている」ことを判定する。
  // 少なくとも一つの数字が含まれ、数字とカンマ以外の文字がないことを確認します。
  // 例: "1,2" -> OK
  // 例: "1," -> OK
  // 例: "," -> NG (数字がない)
  // 例: "abc" -> NG (数字とカンマ以外)
  // 例: "1,a" -> NG

  // 妥当な行のパターン:
  // 少なくとも1つの数字が含まれ、数字とカンマ以外の文字を含まない。
  const numbersOnlyPattern = /^[\d,]+$/;

  if (trimmedLine.length > 0 && numbersOnlyPattern.test(trimmedLine)) {
    // さらに、カンマのパターンを考慮する必要があります。
    // "1,2" -> OK
    // "1," -> OK
    // "," -> NG (数字がない)
    // "1,,2" -> これは「1, (空), 2」と解釈されるべきか？仕様では「1個以上の数字列」が区切られている。
    // 厳密に「カンマで区切られた整数列」と解釈し、各要素が整数であることを確認します。

    // カンマで区切られた各部分をチェックする方が確実ですが、正規表現のみで完結させるため、
    // 許容されるパターンを定義します。
    // 許容されるのは、数字とカンマのみで構成され、少なくとも1つの数字が含まれている場合。
    // ただし、連続するカンマや数字以外の文字はNG。

    // 妥当なケース: 数字とカンマのみで構成され、数字が少なくとも1つ含まれている。
    // 例: "1,2,3", "100,", "1,"
    // 例外: "," (数字なし), "a" (数字なし)

    // 妥当なパターン: 少なくとも1つの数字が含まれ、数字以外の文字がない。
    const hasDigits = /\d/.test(trimmedLine);
    if (hasDigits) {
        // このパターンは、"1,a" や "1,2," のようなケースを許容してしまうため、
        // 厳密な「カンマ区切りの整数列」の定義に依存します。
        // ここでは、行が数字とカンマのみで構成されており、少なくとも1つの数字が含まれていることを妥当とします。
        validCount++;
    }
  }
});

rl.on('end', () => {
  console.log(`valid=${validCount}`);
});
