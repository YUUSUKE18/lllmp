const fs = require('fs');

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n').map(line => line.trim());
    let validCount = 0;

    // 正規表現: 
    // ^\s*          - 行の先頭の空白を許容
    // (?:          - 非キャプチャグループ開始
    //   \d+        - 1つ以上の数字
    //   \s*,\s*    - カンマと任意の空白（末尾のカンマも含む）
    // )+           - 上記グループが1回以上繰り返される
    // (?:$|\s*$)   - 行の終わり、または末尾の空白
    // この正規表現は、数字とカンマのみで構成され、少なくとも1つの数字列を含むことを要求します。
    // ただし、問題の仕様「1 個以上の数字列がカンマで区切られて並んでいる」を厳密に満たすように調整します。

    // 仕様の再解釈に基づき、より直接的に「カンマ区切りの整数列」を判定します。
    // 妥当な行は、数字とカンマのみで構成され、少なくとも1つの数字が含まれる行。
    // 末尾のカンマは許容されます。
    // 空行や数字とカンマ以外は無効。

    const validRegex = /^[\d,]*(\d[\d,]*)\d?[\d,]*$|^[\d,]+(?:,[\d,]+)*$|^[\d,]+,?$/;
    
    // より単純に、数字とカンマのみで構成され、少なくとも1つの数字が含まれているかを確認する
    // 妥当な行は、カンマで区切られた数字列のみで構成される。
    // 例: "1,2,3" や "1,2," など。
    // 空行は無効。数字とカンマ以外は無効。

    for (const line of lines) {
        if (line === "") {
            continue; // 空行は妥当ではない
        }

        // 行の前後の空白を無視してチェック
        const trimmedLine = line.trim();

        if (trimmedLine.length === 0) {
            continue; // 空行はスキップ
        }

        // 正規表現の適用
        // 1. 数字とカンマのみで構成されているか (数字、カンマ、空白のみ許容)
        // 2. 少なくとも1つの数字が含まれているか
        // 3. 末尾のカンマは許容される。

        // 妥当な形式: 
        // 1. 完全に数字とカンマのみで構成され、数字が1つ以上ある。
        // 2. 末尾がカンマでも許容される。
        
        // 以下の正規表現は、「数字、カンマ」のシーケンスのみを許可し、
        // 空白やその他の文字を許可しない、という制約を適用します。
        // 妥当なパターン: (数字,数字,...) または (数字,数字,...) ,
        const pattern = /^[\d,]*(\d[\d,]*)(?:,[\d,]*)*[,\d]*$/;

        // より厳密に、行全体が「数字とカンマ」のシーケンスのみで構成されているかを確認する。
        // 妥当な行は、数字とカンマのみで構成され、少なくとも1つの数字を含む。
        // 末尾のカンマは許容される。
        
        // 妥当な行の判定ロジックを再構築:
        // 1. 行が数字とカンマ以外の文字を含まないこと。
        // 2. 少なくとも1つの数字が含まれていること。
        // 3. 空行は除外。

        let isLineValid = true;
        let containsDigit = false;

        for (const char of trimmedLine) {
            if (!/\d/.test(char) && char !== ',') {
                isLineValid = false;
                break;
            }
            if (/\d/.test(char)) {
                containsDigit = true;
            }
        }
        
        if (!isLineValid || !containsDigit) {
            // 数字とカンマ以外を含む、または数字が一つもない場合
            continue;
        }

        // 最後のカンマの許容について、上記のループでは「数字とカンマのみ」を許可しているため、
        // 末尾のカンマの許容は満たされます。
        
        validCount++;
    }

    console.log(`valid=${validCount}`);
}

solve();
