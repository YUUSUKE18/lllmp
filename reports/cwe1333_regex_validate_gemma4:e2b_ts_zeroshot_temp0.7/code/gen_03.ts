import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    if (!input) {
        console.log('valid=0');
        return;
    }

    const lines = input.split('\n');
    let validCount = 0;

    for (const line of lines) {
        // 行の前後の空白を無視する（trimは行全体に対して行う）
        const trimmedLine = line.trim();

        if (trimmedLine === '') {
            // 空行は妥当ではない
            continue;
        }

        // 妥当な行の判定ロジック
        // 妥当とは、「1 個以上の数字列がカンマで区切られて並んでいること」
        // これは、カンマで区切られた要素が少なくとも1つ存在し、
        // その要素が整数である必要があることを意味する。
        
        // 1. 行が空でないこと (既にチェック済み)
        // 2. 数字とカンマ以外を含まないこと
        // 3. カンマで区切られた後、少なくとも1つの数字列が存在すること

        // 正規表現でチェックする: 
        // ^\s* : 行頭の空白（trimで除去済みだが念のため）
        // (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字列とカンマの組み合わせ
        // $ : 行末
        // 末尾のカンマは許容されるため、行末がカンマで終わる、または数字で終わる、またはカンマで終わるパターンを許容する。
        
        // 仕様: 「1 個以上の数字列がカンマで区切られて並んでいること」
        // 例: "1,2,3" -> 妥当
        // 例: "1," -> 妥当 (末尾のカンマは許容)
        // 例: "," -> 不妥当 (数字列が0個)
        // 例: "abc" -> 不妥当
        
        // 行をカンマで分割し、各要素が数字列であることを確認する。
        const parts = trimmedLine.split(',');
        
        if (parts.length === 0) {
            // これは trim() で空行として処理されるはずだが、念のため
            continue;
        }

        let isValid = true;
        for (const part of parts) {
            // 各パートが空文字列でないことを確認し、それが整数であることを確認する
            if (part.length > 0) {
                // 数字のみで構成されているかチェック
                if (!/^\d+$/.test(part)) {
                    isValid = false;
                    break;
                }
            }
            // 空のパート（例: ",," や "1,,2" のようなケース）は、
            // 数字列としてカウントされないが、区切り文字として許容されるかどうかの解釈が必要。
            // 仕様：「1 個以上の数字列がカンマで区切られて並んでいること」
            // これは、カンマが数字列を区切っていることを意味する。
        }

        // 妥当性の再評価:
        // 1. 空行は除外済み。
        // 2. 数字とカンマ以外を含む行は除外。
        // 3. 1個以上の数字列がカンマで区切られているか。
        
        // 空の要素が含まれているか、または数字列が0個になっていないかを確認する。
        // "1,2" -> ["1", "2"] (2個) -> OK
        // "1," -> ["1", ""] (2個) -> ここで「空の要素」が数字列ではないため、これは問題になるか？
        // 仕様：「1 個以上の数字列がカンマで区切られて並んでいる」
        // "1," は「1」と空の要素で区切られていると解釈されるが、空の要素は数字列ではない。
        // したがって、実質的に数字列が1個以上存在する必要がある。

        // フィルタリングされた数字列の数を数える
        const numericParts = parts.filter(p => p.length > 0 && /^\d+$/.test(p));

        if (numericParts.length >= 1) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
