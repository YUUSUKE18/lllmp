import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    if (input === "") {
        console.log("valid=0");
        return;
    }

    const lines = input.split('\n');
    let validCount = 0;

    for (const line of lines) {
        // 行の前後の空白を無視して処理
        const trimmedLine = line.trim();

        if (trimmedLine === "") {
            // 空行は妥当ではない
            continue;
        }

        // 末尾のカンマは許容する
        // 数字とカンマ以外を含む行は妥当ではない
        // 妥当なのは「1個以上の数字列がカンマで区切られて並んでいること」
        
        // 正規表現でチェック: 数字とカンマのみで構成されているか
        // ^: 行の始まり
        // [0-9,]*: 0個以上の数字またはカンマ
        // $: 行の終わり
        // このチェックだけでは「1個以上の数字列」が保証されないため、さらに詳細なチェックが必要。

        // 妥当性の定義: 1個以上の数字列がカンマで区切られている。
        // これは、カンマで区切られた要素がすべて数字列である、ということを意味する。

        // 1. 全体が数字とカンマのみで構成されているか
        if (!/^[0-9,]*$/.test(trimmedLine)) {
            continue; // 数字とカンマ以外を含む行は妥当ではない
        }

        // 2. 1個以上の数字列が存在するか
        // 区切り文字としてカンマを考え、カンマで分割した結果、空でない要素が1つ以上あるか。
        
        // 末尾のカンマが許容されるため、末尾のカンマは無視して処理を試みる。
        let content = trimmedLine;
        if (content.endsWith(',')) {
            content = content.slice(0, -1);
        }
        
        // 空白除去後の文字列が空であれば（例: "," や ""）、妥当ではない。
        if (content.length === 0) {
             // ただし、元の行が " ," のようなケースも考慮する必要があるが、
             // 1.のチェックで既に数字とカンマのみであることを保証している。
             // この行が完全にカンマで構成されている場合 (例: "," や ",,")、これは「1個以上の数字列」ではないため不妥当。
             continue;
        }
        
        // カンマで分割し、各要素が数字列であることを確認する
        const parts = content.split(',');
        let hasDigits = false;
        for (const part of parts) {
            if (part.length > 0 && /^[0-9]+$/.test(part)) {
                hasDigits = true;
            } else if (part.length > 0) {
                // 数字とカンマのみで構成されているが、数字列ではない場合（例: "a,1" は既に除外されているはずだが念のため）
                // 1.のチェックで既に数字とカンマ以外は排除されているため、ここでは数字列として存在しない場合を考える。
                // 例: "1,,2" -> parts = ["1", "", "2"]
                // 空の要素がある場合は、それは「数字列」ではないため、全体として不妥当とみなす必要があるか？
                // 仕様：「1 個以上の数字列がカンマで区切られて並んでいること」
                // 空の要素は数字列ではないため、空の要素があれば不妥当。
                // ただし、"1,,2" は「1」と「2」の2つの数字列がカンマで区切られていると解釈できる。
                // したがって、空の要素は無視して良いと判断するのが自然。
            }
        }
        
        // 1個以上の数字列が存在すれば妥当
        if (hasDigits) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
