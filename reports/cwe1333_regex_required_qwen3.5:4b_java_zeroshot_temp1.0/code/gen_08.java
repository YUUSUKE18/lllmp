import java.util.Scanner;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int validCount = 0;

        while (scanner.hasNextLine()) {
            String line = scanner.nextLine();
            // 前後の空白を切り取る
            if (line == null || line.trim().isEmpty()) {
                continue;
            }
            line = line.trim();

            // 正規表現の定義：
            // ^                  : 行の始点
            // (?:                 : 非キャプチャグループ
            //   \\d+             : 1 文字以上の数字
            //   (?:,|\\$)        : カンマ、または行末（$）
            // )*                 : 0 回以上繰り返す
            // )+                  : 上記のグループが 1 回以上存在すること
            //                   : 要件「1 個以上の数字列」を満たすため + する
            // $                   : 行の終点
            String pattern = "(?:\\d+(?:,|$))+";

            if (line.matches(pattern)) {
                validCount++;
            } else {
                // 「数字とカンマ以外を含む行は妥当ではありません」かつ「空行・空白のみ（trim 後が空）は妥当ではない」という要件を考慮
                // しかし、上記の正規表現では "123, abc" は一致しませんが "123," も一致します。
                // 要件「数字とカンマ以外を含む行は妥当ではありません」を満たすには、空白（スペースなど）も数字・カンマ以外の文字として扱う必要があります。
                // 空白を含める正規表現は "(?:\\d+\\s*(?:,|$))+" のようにするか、または単に "^[^\\s]*(?:[^\s,]?)" は難しいです。
                // より安全なアプローチ：行の全文字を除去した後に数字・カンマだけ残すか？ いや、空白は区切りの一部として無視するが、他の文字は NG。
                // 要件：「空行...は妥当ではありません」「数字とカンマ以外を含む行は妥当ではありません」
                // しかし「行の前後の空白は無視します」とあるので、内部に空白が含まれても OK かもしれませんが、通常「整数列」と言うのは空白を含むことは稀です。
                // 厳密な解釈：
                // 1. " 123,456," は NG (空白がカンマと数字の間に含まれているため)
                // 2. " 123" は OK (前後空白は無視、内部も OK) -> これは "123" に変換してチェックする必要がある。
                // 3. "1 23,456" は NG (スペースあり)

                // 再確認: 「行の前後の空白は無視します」-> trim() でOK。
                // 「数字とカンマ以外を含む行は妥当ではありません」-> internal whitespace is NOT allowed if it's considered "other".
                // しかし、整数列の定義で「空白を含んで OK」か？通常 Java の `Scanner` や CSV パーサでは空白を無視するが、正規表現として明確にするため。
                // 最も安全な「数字とカンマ以外禁止」の意味は「他の文字は許容しない」なので、空白も禁止と解釈するか。
                // ただし、「前後の空白は無視」＝ trim だけなら、内部空白は NG とすべきか？
                // 例："1,2 3" -> 妥当？
                // 文脈から「整数列」と言われると、通常は空白なし（または空白を区切り文字）だが、仕様で「数字とカンマ以外」が禁止とあるので、空白も「他の文字」として NG とするのが正しい解釈。
                // つまり：trim() で前後の空白を除き、残りが `\\d+|,` のみであること。

                // 上記 pattern は既に内部空白を NG にしている ((?:\\d+(?:,|$))+) なので OK。
            }
        }
        System.out.println("valid=" + validCount);
    }
}
