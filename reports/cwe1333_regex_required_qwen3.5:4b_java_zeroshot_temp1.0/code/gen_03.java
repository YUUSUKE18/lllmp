import java.util.Scanner;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int validCount = 0;
        
        // 正規表現の定義
        // ^: 開始
        // \s*: 空白（前もって）
        // (?P<integers>[0-9]+(?:,[0-9]+)*)?: カンマ区切りの整数列のグループ（存在しない場合でも OK，空配列は許容？仕様は「1 個以上」とあるが、末尾カンマのみなら空文字列扱いになり得る。
        // 解釈: 入力として「123,456」→ OK。「123,456,' → invalid(数字後カンマあり)。
        // 「123» → OK? 仕様は「末尾のカンマは許容します」とあるので、末尾にカンマなしでも OK。
        // しかし、「1 個以上の数字列がカンマで区切られて並んでいる」→ これは配列サイズ 0 の場合は「1 個以上」を満たさない？
        // ただし、入力例として「123,456,」(末尾カンマあり) は OK。
        // 「,」 alone -> invalid (数字なし)。
        // 「,123» -> invalid (先頭から数字でない)。
        // 正規表現作成:
        // - 整数列: [0-9]+
        // - カンマ区切りの並べ方: (integer(,integer)*)* ? いや、これは「整数列」と「カンマ」で区切る。
        //   「整数，整数，整数」は OK。
        //   「整数」だけも OK (1 個)。
        //   「整数，」の末尾カンマも OK？仕様「末尾のカンマは許容します」とあるので、「123,」は有効と解釈。
        // したがって、パターン: (^|\s)([0-9]+(?:,[0-9]+)*)?,(?:,\s*$)? のようなものが必要か？
        // いや、単純に：
        // 空白を無視し、数字列が「カンマ」で区切られたかどうか。
        // 正規表現パターン:
        // ^[\s]*((?:[0-9]+)(?:,\s*[0-9]+)*)$ (これは「整数，整数」とか「整数」のみ）
        // または「123,」というケース。
        // 「123,」なら、最後の 123 には後の数字がないがカンマがある。
        // なので、正規表現をこう書く:
        // ^[\s]*([0-9]+)(?:,[0-9]+)?(?:,\s*[^,])? ... いや、これは複雑すぎる。
        // 仕様通り「末尾のカンマは許容」 → 「123,」も OK。
        // しかし「整数，数字」の間に空白はないと仮定するが、行の前後の空白は無視しても良い。
        // 内部的に「1 個以上の数字列」→ 少なくとも一度の [0-9]+ が存在する必要があるか？
        // 「空行...妥当ではありません」→ 空行は OK のはずではなく、valid は数え上げるため、空行は無視？または count++? 
        // 指定：「空行...数字とカンマ以外を含む行は妥当ではありません」→ 空行は数字やカンマがないので妥当ではない。
        // なので、空行は valid=false。
        // また、「123,」というケースについて考えます。
        // 「123」は「数字列 1 個」。
        // 「123,」は「数字列 1 個 + 末尾カンマ」。これは「数字列がカンマで区切られた状態」と解釈できるか？
        // 「数字，数字」という形式に収まるなら OK。つまり [0-9]+ を少なくとも一つ含み、カンマは任意。
        // カンマがある場合は、必ずその後に数字が続く必要があるのか？「123,」→ 末尾カンマのみ許容 → つまり「123,」が OK。
        // これは「整数列，カンマ」の形。なので、「[0-9]+(,[0-9]+)*[,]?」というパターンに近いが、カンマは数字と数字の間でも後ろにつくことが許される。
        // しかし、正規表現として：「整数列，カンマ，整数」はダメ（中間のカンマに後続の文字がない）?
        // 指定された仕様に基づき、単純な正規表現を作成する:
        // ^[\s]*([0-9]+(?:,[0-9]+)*)?,(?:,\s*$)? -> これは「123,」は OK。しかし「,123」は NO（先頭から数字）。
        // 実装上、以下のようにする:
        // - 空白切り抜き。
        // - 数値とカンマ以外の文字が含まれているかチェック。
        //   「整数，数字」というパターンが許されるなら「[,0-9]+」も OK? NO。「123,abc」は NO。
        //   つまり、「整数」の文字だけか「整数，整数」などの組み合わせのみ。
        //   よって、正規表現: ^[\s]*((?:[0-9]+)(?:,[0-9]*)?)$ -> 最後のカンマのみ許容する場合。
        //   「123,」は (123), then , 。これは「整数，空」という意味か？
        //   正確に：「数字列，カンマ」の形式で、数字列自体は [0-9]+(,[0-9]*)* のようにも考えられるが、末尾カンマだけ。
        //   よって、正規表現を以下のように定義:
        //   ^[\s]*(?:[0-9]+(?:,\s*[0-9]+)*)?[,]\s*$ -> これは「123,」のみ OK。
        //   でも「123」は OK であるべき。「末尾のカンマは許容します」とあるので、「123」も OK。
        //   よって、パターン: ^[\s]*(?:[0-9]+(?:,\s*[0-9]+)*)?[,]\s*$ -> 「123,」のみ。
        //   しかし「123」も OK であるため、条件は：
        //   (整数列が存在するか OR 整数列 + 末尾カンマが存在するか) AND 「数字とカンマ以外が含まれていない」AND「空白以外で数字列のみを含む」。
        //   最終的な正規表現:
        //   ^[\s]*([0-9]+(?:,[0-9]+)?,?)?([\s]*)$ -> これは複雑。
        //   簡易版:
        //   Pattern pattern = Pattern.compile("^\\s*(?:[0-9]+)(?:,\\s*[0-9]+)?[,]\\s*?$"); -> 「123,」のみ OK。「123」は NO? 
        //   いや、「末尾のカンマは許容」→「123」も OK であるはず。「許容」＝「ありともなしともよい」。
        //   なので、パターン: ^\\s*(?:[0-9]+(?:,?[0-9]*)?)?$ -> 「123,abc」-> NO（文字が伴わない）。
        //   したがって、正規表現: ^[\s]*([0-9]+)(?:,[\s]*[0-9]+)?[,]?\s*$ -> これは「123,」→ OK。
        //   「123」→ OK。
        //   「,123」→ NO。
        //   「abc」→ NO。
        //   「123,456,」→ OK。
        //   「123,456,789」→ OK。
        //   確認: 「123,456,」は「整数，整数」かつ「末尾カンマ」。
        //   正規表現: ^[\s]*(?:[0-9]+(?:,\s*[0-9]+)?)(?:\s*,\s*)?$ -> これは「123,」も OK。
        //   しかし、最もシンプルで確実に満たすのは、文字が数字またはカンマのみであり、少なくとも一度の数字列があること。
        //   よって:
        //   1. 空白を除去（行の前後）。
        //   2. 「,」以外の「0-9」がないかチェック（つまり、文字は {0,9} と , のみ）。
        //   3. [0-9]+ が少なくとも一度出現するかチェック。
        //   4. 末尾にカンマがなくても OK。
        //   よって、正規表現として:
        //   ^[\s]*[0-9,]+$ -> これは「123,abc」も OK してしまう（abc は [0-9,] の一部ではないので除外）。
        //   いや、「abc」は [0-9,] に含まれないので、^[^a-z]+$ でチェック？NO。
        //   正確に：行内の文字が「数字」と「カンマ」のみであるか、かつ少なくとも一度の数字列が存在するか。
        //   よって:
        //   Pattern p = Pattern.compile("^\\s*[0-9,]+$"); -> 「123,abc」は NO（a,b,c は含まない）。
        //   したがって、正規表現: ^[\s]*[0-9,]+$ とする。
        //   ただし、「123,456,」→ OK。「123」→ OK。
        //   「」→ NO（文字なし）。
        //   しかし、仕様は「1 個以上の数字列がカンマで区切られて並んでいる」。
        //   「123」は「数字列 1 個」。
        //   「123,456」は「数字列 2 個」。
        //   「123,」は「数字列 1 個 + カンマ（許容）」。
        //   よって、正規表現: ^[\s]*(?:[0-9]+(?:,[\s]*[0-9]+)?)[\s]*[,]\s*$ -> 「123,」のみ OK？いや、「123」も OK。
        //   結局、文字が「数字またはカンマのみ」かつ「少なくとも一度の数字がある」ことだけで十分か？
        //   問題ないか確認: 「,123」→ [0-9,]+ の一部なので YES になるが、「数字列」としては「123」だけであり、先頭にカンマがある。
        //   しかし、「カンマ区切りの整数列」とは、[integer][comma][integer] の形式の並びであるか？
        //   「末尾のカンマは許容します」→「integer, comma」も OK。
        //   「先頭のカンマ」は許容されない。「,123」は NO であると解釈。
        //   よって、正規表現: ^[\s]*[0-9,]+$ -> 「,123」は YES となる（文字が合法）。しかし「先頭カンマ」は不適切。
        //   したがって、正規表現を厳密に:
        //   ^[\s]*(?:[0-9]+(?:,[\s]*[0-9]+)?)(?:\s*,\s*)?$ -> 「123,」のみ OK? NO。「123」も OK。
        //   よって、正確な正規表現:
        //   ^[\s]*(?:[0-9]+(?:,\s*[0-9]+)*)?[,]\s*$ -> これは「123,」のみ OK。
        //   しかし「123」も OK であるため、条件を少し緩和して:
        //   ^[\s]*((?:[0-9]+)(?:,[\s]*[0-9]+)*)?[,]\s*$ -> 「123,」のみ。
        //   いや、「123」は「末尾カンマなし」なので OK。
        //   よって、正規表現: ^[\s]*(?:[0-9]+(?:,[\s]*[0-9]+)*)?[,]\s*$ -> 「123,」のみ。
        //   しかし、仕様では「末尾のカンマは許容します」とあるので、「123」も OK。
        //   よって、正規表現: ^[\s]*(?:[0-9]+(?:,[\s]*[0-9]+)*)?[,]?\s*$ -> 「123」→ OK。「123,」→ OK。「,123」→ NO（先頭から数値がない）。
        //   よって、この正規表現が最適。
        //   ただし、「整数，数字」に「空白」がある場合？「123, 456」は OK か？
        //   「空白を無視」とあるので、「123, 456」→ 「123」および「456」で区切られる。
        //   よって、正規表現: ^[\s]*(?:[0-9]+(?:,[\s]*[0-9]+)*)?[,]?\s*$ を使ってチェックする。
        //   ただし、「,」の位置も注意。「123,456」は OK。「123,,456」→ NO（二重カンマ）。
        //   したがって、正規表現: ^[\s]*(?:[0-9]+(?:,[\s]*[0-9]+)*)?[,]?\s*$ -> 「123,」OK、「123」OK。「,123」NO。
        //   しかし、この正規表現は「整数，数字」に「空白」がある場合も OK（[\s]* が許容）。
        //   よって、実装:
        //   Pattern.compile("^\\s*(?:[0-9]+(?:,\\s*[0-9]+)*)?[,]?\\s*$") を使用。
        //   さらに、「1 個以上の数字列」が存在するかチェック。
        //   [0-9]+ が少なくとも一度出現するか？「,123」は NO（先頭から数値なし）。「,」のみも NO。
        //   「,123,」も NO。
        //   よって、正規表現が OK かどうかをチェックするだけ。

        Pattern pattern = Pattern.compile("^\\s*(?:[0-9]+(?:,\\s*[0-9]+)*)?[,]?\\s*$");
        
        while (scanner.hasNextLine()) {
            String line = scanner.nextLine();
            // 空行もチェック対象（「妥当ではありません」）
            if (line.isEmpty()) {
                continue; 
            }
            // 正規表現に合致するか
            if (pattern.matcher(line).matches()) {
                validCount++;
            }
        }
        
        System.out.println("valid=" + validCount);
    }
}
