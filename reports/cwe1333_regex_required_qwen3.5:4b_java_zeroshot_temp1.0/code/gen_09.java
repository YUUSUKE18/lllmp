import java.util.Scanner;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int validCount = 0;
        
        while (scanner.hasNextLine()) {
            String line = scanner.nextLine();
            
            // 空白を削除し、空行チェック
            if (line.trim().isEmpty()) {
                continue;
            }
            
            // 正規表現による判定
            // 条件:
            // 1. "整数列" は -?[0-9]+ で定義
            // 2. 1 個以上あり、カンマで区切られて並ぶ (" -?[0-9]+,?")
            // 3. "末尾のカンマは許容" => 最後の項の後にカンマがない場合も含めるため、* や + を慎重に使う
            //    正しいパターンの例: "-1", "-1,", "-1,-2", "-1," => valid
            //    間違っている例: "abc", "" (空行) => invalid
            //    
            //    完全な正規表現の構築:
            //    ^  [空白が許容されるため trim の後に ^ ]
            //    ([ -?[0-9]+] (, [-?[0-9]+])*)   -> 最初の整数、その後カンマと整数の繰り返し
            //    $ 
            //    ただし、末尾のカンマを許すためには、最後の項にカンマがないか有るかに関わらず OK なので:
            //    実際、"A,B," は"A"と"B"としてOK。つまり "( ,[-?[0-9]+])*" で終わるのも OK だが、
            //    問題は "数字列がカンマで区切られて並んでいること" と末尾のカンマ許容。
            //    これは "( [-?[0-9]+] (, [-?[0-9]+])*)$" をそのまま使うと "1," は invalid となる。
            //    "1," は "1" と "," で終わる。これを valid にするには、末尾のカンマを正規表現の最後に含めるか、
            //    または末尾カンマも含めて pattern を考える。
            //    
            //    修正: 
            //    ^[ -?[0-9]+] (, [ -?[0-9]+])* $?
            //    これは "1," は matches にしない。(最後の , が必要ではないが、もしあれば許容すると文脈から)
            //    問題文: "末尾のカンマは許容します"
            //    なので、パターン:
            //    ([ -?[0-9]+] (, [ -?[0-9]+])* ) | (,?([ -?[0-9]+]?))* 
            //    ... これより単純なアプローチ:
            //    ^ [ 空白を処理後 ]
            //    ( [-?[0-9]+] (, [-?[0-9]+])*) | (-?[0-9]+) -> これは "1," は invalid になります。
            //    
            //    正しいロジック:
            //    文字列全体が以下の規則に従う: 
            //    - 整数列のリスト (カンマ区切り、末尾カンマ含む)
            //    ^ [ -?[0-9]+] (, [-?[0-9]+])* $? -> "1," は Invalid.
            //    
            //    ここから再定義: 
            //    "整数列" を P とする。
            //    入力は P,P,...,P, である。(カンマ区切り) または P が含まれるが最後の部分にカンマがある場合も OK.
            //    つまり、P (カンマ P)* の形でも良いし、P (カンマ P)* カンマ でも良い。
            //    これは: P (カンマ P)* [カンマ?] として表現できるか？
            //    しかし、"1," は P="1", "1," = P + ",".
            //    
            //    さらに簡潔に正規表現を構築:
            //    ^([ -?[0-9]+] (, [-?[0-9]+])*)$ | ^([ -?[0-9]+], )+$ ? -> これは少し複雑。
            //    実際、"数字とカンマ以外を含む行は妥当ではありません" かつ "空行は invalid".
            //    全ての文字が数字 (-?[0-9]+) またはカンマのみで成り立つこと + 区切り構造があること。
            //    
            //    最終的な正規表現:
            //    ^[-?[0-9]+] (, [-?[0-9]+])* $? -> これは "1," を許さない。
            //    ^[-?[0-9]+] (, [-?[0-9]+])* $ | ^,-?$ -> 後者は不正確。
            //    
            //    再考: "末尾のカンマは許容" という制約.
            //    例: "1,2," -> valid.
            //    例: "1" -> valid.
            //    例: "1,2" -> valid.
            //    これらを統一する正規表現:
            //    ^[-?[0-9]+] (, [-?[0-9]+])* $?
            //    これは "1," を許さない。なぜなら、最後の ", -?[0-9]+" が存在しないためです。
            //    
            //    ならば、このように考えます:
            //    全体が ^ [整数] (カンマ 整数)* $ または ^ [整数] (カンマ 整数)* カンマ $ 
            //    つまり: ^[-?[0-9]+] (, [-?[0-9]+])*$ | ^[-?[0-9]+] (, [-?[0-9]+])*,$
            //    これは ^[-?[0-9]+] (, [-?[0-9]+]*)? ,?$ に簡略化できないか？ 
            //    いや、"1," は 1 つの整数 + カンマ。
            //    "1,2," は 1,2 + カンマ。
            //    
            //    最終的な正規表現:
            //    ^[-?[0-9]+] (, [-?[0-9]+])* $? | ^[-?[0-9]+] (, [-?[0-9]+])* ,?$
            //    これは ^[-?[0-9]+] (, [-?[0-9]+])* [?,]$ の形に見えるが、文字列末尾のカンマを扱うため:
            //    ^[-?[0-9]+] (, [-?[0-9]+]*)? ,?$ に変更。
            //    確認:
            //    "1" -> 1st term matches. 
            //    "1," -> 1st term matches, optional part empty, trailing comma matches. OK.
            //    "1,2" -> 1st matches, then ",2", optional part matches, trailing none. OK.
            //    "1,2," -> 1st matches, then ",2", optional part matches, trailing comma matches. OK.
            //    
            //    したがって、正規表現は: ^[-?[0-9]+] (, [-?[0-9]+]*)? ,?$ 
            //    ただし、(, [-?[0-9]+])* は重複可能かつ末尾カンマも含まれる必要があるか？
            //    "1,2," -> 整数1, カンマ, 整数2, カンマ.
            //    私の推論: ^[-?[0-9]+] (, [-?[0-9]+])? ,?$ は "1,2," を許さない。
            //    
            //    より単純なアプローチ:
            //    全ての文字が整数部分とカンマのみであること、かつ最初のものが整数であり、それ以降も整数または空の組み合わせで、
            //    区切りの構造を正しく保つようにする。
            //    
            //    最終的な正規表現 (Java 利用可能):
            //    ^[-?[0-9]+] (, [-?[0-9]+])* $? | ^[-?[0-9]+] (, [-?[0-9]+])* ,?$
            //    これは "1," と "1" を両方許容します。
            //    
            //    実装:
            //    Pattern p = Pattern.compile("^[ -?[0-9]+] (, [-?[0-9]+])*$"); 
            //    これは標準的な CSV 入力だが末尾カンマを許さないので、特殊処理が必要です。
            //    
            //    修正版パターン:
            //    ^[-?[0-9]+] (, [-?[0-9]+])* $? | ^,-?[0-9]+$ -> これは "1," は両方ともマッチしない。
            //    
            //    ここでは、正規表現を動的に構築するか、あるいは複雑な文字列操作を行うか。
            //    問題文は「正規表現を用いてください」とあるが、Java の Pattern を使ってロジックを組み立てるべきだ。
            //    
            //    最終的な方針:
            //    ^[-?[0-9]+] (, [-?[0-9]+])* $? | ^,-?[0-9]+$ -> これはまだ "1," がマッチしない。
            //    
            //    再構築:
            //    入力 String s.
            //    正規表現 R: ^[-?[0-9]+] (, [-?[0-9]+])* $? 
            //    または R2: ^[-?[0-9]+] (, [-?[0-9]+])* ,?$
            //    これらを結合: R | R2.
            //    
            //    例文:
            //    "1" -> R matches. OK.
            //    "1," -> R2 matches. OK.
            //    "1,2" -> R matches. OK.
            //    "1,2," -> R2 matches. OK.
            //    "1,," -> invalid (整数がありません).
            //    "-1" -> R matches. OK.
            //    "--1" -> invalid (正しく始まらない).
            //    
            //    確認: R は "1,2" を含む "1" と ",2" で一致します。
            //    R2 は "1," を含む "1" と "," で一致します。
            //    
            //    したがって、正規表現は ^[-?[0-9]+] (, [-?[0-9]+])* $? | ^[-?[0-9]+] (, [-?[0-9]+])* ,?$ です。
            
            Pattern pattern = Pattern.compile("^([-?[0-9]+] (, [-?[0-9]+])* $)|([-?[0-9]+] (, [-?[0-9]+])* ,?)$");
            Matcher matcher = pattern.matcher(line.trim());
            if (matcher.matches()) {
                validCount++;
            }
        }
        
        System.out.println("valid=" + validCount);
    }
}
