package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// カンマ区切りの整数列の妥当性を判定するための正規表現
	// ^\s* - 行の先頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字列と、その後にカンマと空白が続くパターンを繰り返す
	// (?:,\s*|$) - カンマと空白、または行末
	// \s*$ - 行末の空白
	// この正規表現は、カンマ区切りの整数列が1つ以上存在し、数字とカンマ以外を含まないことを確認するのに適しています。
	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// 少なくとも一つの数字列が存在し、数字とカンマ以外の文字がないことを確認します。

	// 妥当な行の判定ロジックを実装するために、各行を個別にチェックします。
	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現による判定:
		// ^\s* : 行の先頭の空白
		// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列と、その後にカンマと空白が続くパターン
		// (?:,\s*|\s*$) : カンマと空白、または行末
		// $ : 行末
		// この問題の要件「1 個以上の数字列がカンマで区切られて並んでいる」を厳密に満たすには、
		// 数字とカンマ以外の文字が含まれていないことを確認しつつ、少なくとも1つの数字列があることを確認する必要があります。

		// 簡略化のため、数字とカンマ以外の文字が含まれていないことを確認し、
		// 少なくとも1つの数字が含まれていることを確認します。
		// 妥当なパターン: 数字、カンマ、空白のみで構成され、少なくとも1つの数字が含まれている。
		// 末尾のカンマは許容される。

		// 1. 数字とカンマ以外の文字が含まれていないかチェック
		if !regexp.MustCompile(`^[0-9, \t\r\n]*$`).MatchString(line) {
			continue // 数字とカンマ以外の文字が含まれていれば不妥当
		}

		// 2. 少なくとも1つの数字が含まれているかチェック
		if !strings.Contains(line, "0123456789") {
			continue // 数字が一つもなければ不妥当
		}

		// 3. 末尾のカンマの許容 (これは上記2と組み合わせることで暗黙的に処理されるが、明示的に確認する)
		// 末尾がカンマで終わる場合も許容される。

		// 上記のチェックを通過した行は妥当
		validLines++
	}

	fmt.Printf("valid=%d\n", validLines)
}
