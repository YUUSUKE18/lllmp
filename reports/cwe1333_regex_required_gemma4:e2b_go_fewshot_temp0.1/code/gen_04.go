package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// カンマ区切りの整数列の妥当性を判定するための正規表現
	// ^\s* - 行の先頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字とカンマの組み合わせ（数字が1つ以上続く）
	// (?:,\s*)? - オプションのカンマと空白（末尾のカンマも許容するため）
	// \s*$ - 行末の空白
	// この正規表現は、少なくとも1つの数字列がカンマで区切られていることを確認します。
	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// 各数字列が少なくとも1桁であることを保証する必要があります。
	// 課題の要件を再解釈すると、「1個以上の数字列がカンマで区切られて並んでいる」ことを意味します。
	// 例: "1,2,3" は妥当。 "1," は妥当（末尾のカンマ許容）。空行は不妥当。
	// 空行は無視されるため、scanner.Scan()で読み込んだ行をチェックします。

	// 読み込んだ行を一つずつチェック
	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現の定義:
		// ^\s* : 行の先頭の空白
		// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列がカンマで区切られているパターン
		// (?:,\s*)* : 最後の要素の後に続くオプションのカンマと空白（末尾のカンマも許容）
		// $ : 行末
		// このパターンは、少なくとも1つの数字列が存在し、カンマで区切られていることを確認します。
		// ただし、末尾のカンマのみの行（例: "1,"）も許容する必要があります。

		// 妥当性の判定ロジックをよりシンプルにするため、
		// 1. 数字とカンマ以外の文字が含まれていないか
		// 2. 少なくとも1つの数字が含まれているか
		// 3. 末尾のカンマのみの行（例: "," や " , "）は除外する（空行チェックでカバーされる）

		// 1. 数字とカンマ以外の文字が含まれていないかチェック
		if !regexp.MustCompile(`^[0-9,]*$`).MatchString(line) {
			continue // 数字とカンマ以外を含む行は不妥当
		}

		// 2. 少なくとも1つの数字が含まれているかチェック
		if !strings.Contains(line, "0123456789") {
			continue // 数字が一つも含まれていない行は不妥当（カンマのみの行は空行チェックで除外されるか、次のチェックで除外される）
		}

		// 3. 妥当な行としてカウント
		validLines++
	}

	fmt.Printf("valid=%d\n", validLines)
}
