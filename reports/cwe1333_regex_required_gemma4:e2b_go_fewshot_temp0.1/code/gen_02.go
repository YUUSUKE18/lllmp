package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// カンマ区切りの整数列の妥当性を判定するための正規表現
	// ^\s* - 行の先頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字列と、その後にカンマと空白が続くパターンを繰り返す
	// (?:,\s*|$) - カンマと空白、または行末
	// \s*$ - 行末の空白
	// この正規表現は、カンマ区切りの整数列が1つ以上存在し、数字とカンマ以外の文字を含まないことを確認するのに適しています。
	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// 少なくとも一つの数字列が存在し、数字とカンマ以外がないことを確認します。

	// 妥当性の判定ロジックをシンプルにするため、各行をチェックします。
	// 妥当な行の定義:
	// 1. 空行ではない。
	// 2. 数字とカンマのみで構成されている。
	// 3. 少なくとも1つの数字列が含まれている。

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現で数字とカンマのみで構成されているか、かつ少なくとも1つの数字列があるかをチェック
		// ^\s* - 行頭の空白
		// (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字列と、その後にカンマと空白が続くパターン
		// \s*$ - 行末の空白
		// この正規表現は、数字とカンマのみで構成されていることを確認します。
		// さらに、このパターンが全体にマッチすることを要求します。
		// 実際には、行全体が数字とカンマのみで構成されているか、またはそのパターンに一致する部分があるかをチェックします。

		// より簡単なチェックとして、行をカンマで分割し、各要素が整数であることを確認します。
		parts := strings.Split(trimmedLine, ",")
		isValid := false
		if len(parts) > 0 {
			// 少なくとも1つの要素が存在し、その要素が整数に変換可能かチェック
			for _, part := range parts {
				if strings.TrimSpace(part) != "" {
					// 各部分が整数であるかチェック
					_, err := fmt.Sscanf(part, "%d", new(int))
					if err == nil {
						isValid = true
						break
					}
				}
			}
		}

		if isValid {
			validLines++
		}
	}

	fmt.Printf("valid=%d\n", validLines)
}
