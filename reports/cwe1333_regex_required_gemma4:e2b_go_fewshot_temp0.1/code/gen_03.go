package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// カンマ区切りの整数列の妥当性を判定するための正規表現
	// ^\s* - 行の先頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字列と、それに続くカンマと空白の繰り返し
	// (?:,\s*|$) - カンマと空白、または行末
	// $ - 行の終わり
	// この正規表現は、カンマ区切りの整数列が1つ以上存在することをチェックします。
	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// 少なくとも一つの数字列が存在することを保証する必要があります。

	// 妥当性の判定ロジックを直接実装します。
	// 正規表現で「カンマ区切りの整数列」のパターンを定義し、それが存在するかを確認します。
	// 許容されるパターン: 数字とカンマと空白の組み合わせが1つ以上あること。
	// 末尾のカンマは許容される。空行は無効。数字とカンマ以外は無効。

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 1. 数字とカンマ以外の文字が含まれていないかチェック
		// 数字、カンマ、空白のみが許容される
		if !regexp.MustCompile(`^[0-9, \t\r\n]*$`).MatchString(line) {
			continue // 数字とカンマ以外を含む行は無効
		}

		// 2. 妥当性の判定: 1個以上の数字列がカンマで区切られているか
		// 末尾のカンマは許容される。
		// 妥当なパターン: (数字, 数字, ...) または (数字, 数字, ...) ,
		// 少なくとも1つの数字列が存在する必要がある。

		// 末尾のカンマを取り除いた文字列をチェック
		// 末尾のカンマを削除して、残った文字列が数字のみで構成されているか、またはカンマで区切られているかをチェックする。

		// 妥当な行の定義:
		// 1. 空行ではない。
		// 2. 数字とカンマ、空白のみで構成されている。
		// 3. 少なくとも1つの数字列が存在する。

		// 末尾のカンマを削除して、カンマで区切られた数字列が存在するかをチェックする。
		// 例: "1,2,3," -> "1,2,3"
		// 例: "1," -> "1"
		// 例: "," -> "" (これは空行チェックで除外されるべきだが、ここでは処理を続ける)

		// カンマで分割し、空でない要素が1つ以上あるかを確認する。
		parts := strings.Split(line, ",")
		hasNumbers := false
		for _, part := range parts {
			trimmedPart := strings.TrimSpace(part)
			if trimmedPart != "" {
				// 数字列として妥当か確認
				if regexp.MustCompile(`^[0-9]+$`).MatchString(trimmedPart) {
					hasNumbers = true
				} else {
					// 数字以外のものが含まれている場合（例: "a,1"）は無効
					hasNumbers = false
					break
				}
			}
		}

		// 末尾のカンマが残っている場合、最後の要素は空文字列になる可能性がある。
		// 例: "1,2," -> ["1", "2", ""]
		// このロジックでは、空でない数字列が1つ以上存在すればOKとする。

		if hasNumbers {
			validLines++
		}
	}

	fmt.Printf("valid=%d\n", validLines)
}
