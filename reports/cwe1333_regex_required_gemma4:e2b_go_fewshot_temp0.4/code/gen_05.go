package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// カンマ区切りの整数列の妥当性を判定するための正規表現
	// ^\s* - 行の先頭の空白を許容
	// (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字列と、その後にカンマと空白が続くパターンを繰り返す
	// (?:,\s*|$) - カンマと空白、または行末
	// $ - 行末
	// 厳密には「1個以上の数字列がカンマで区切られて並んでいる」ことを確認したい。
	// 以下の正規表現は、少なくとも1つの数字が含まれ、カンマで区切られた数字のシーケンスを許容する。
	// 1個以上の数字列がカンマで区切られている、または単一の数字列である、という構造をチェックする。
	// 許容されるパターン: 数字,数字,... または 数字
	// 末尾のカンマは許容される。
	// 1. 数字が1つ以上あることを確認する。
	// 2. 数字とカンマ、空白以外の文字が含まれていないことを確認する。
	// 3. 末尾にカンマがあっても良い。

	// 妥当な行の判定ロジックをよりシンプルにするため、文字列操作と正規表現を組み合わせる。
	// 妥当な行の定義:
	// 1. 空行ではない。
	// 2. 数字とカンマ、空白以外の文字を含まない。
	// 3. 少なくとも1つの数字が含まれている（カンマのみの行は除く）。
	// 4. 末尾のカンマは許容される。

	// 正規表現: 少なくとも1つの数字が含まれ、数字、カンマ、空白、および行末のカンマのみを含む。
	// ^\s* - 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字列がカンマで区切られているパターン
	// |
	// [0-9]+(?:,\s*)*$ - 単一の数字列、または数字とカンマの組み合わせ（末尾のカンマあり）
	// この要件を満たすために、より単純に「数字とカンマ、空白のみ」という制約を適用し、数字が少なくとも1つあることを確認する。

	// 妥当な行の判定:
	// 1. 行が空でない。
	// 2. 行に含まれる文字が数字、カンマ、空白のみである。
	// 3. 数字が少なくとも1つ含まれている。
	// 4. 末尾のカンマは許容される。

	// 正規表現で「数字、カンマ、空白のみ」をチェックし、数字が少なくとも1つあることを確認する。
	// ^\s* - 行頭の空白
	// (?:[0-9][0-9,]*[0-9]) - 少なくとも2つの数字が連続していることを確認（最低1つの数字が必須）
	// |
	// [0-9]+(?:,.*)?$ - 1つ以上の数字が続く、または数字が続くパターン。

	// 最もシンプルなチェック:
	// 1. 行をトリムし、数字とカンマ、空白のみで構成されているか。
	// 2. その行に数字が含まれているか。
	// 3. 末尾のカンマは無視する。

	// 妥当な行の判定ロジックを再定義し、正規表現を適用する。
	// 1. 行が空でないこと。
	// 2. 行が数字、カンマ、空白のみで構成されていること。
	// 3. 少なくとも1つの数字が含まれていること。
	// 4. 末尾のカンマは許容される。

	// 妥当な行の判定に特化した正規表現:
	// ^\s* - 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字がカンマで区切られているパターン
	// |
	// [0-9]+(?:,.*)?$ - 単一の数字列、または数字とカンマの組み合わせ（末尾のカンマあり）
	// この正規表現は複雑になりすぎるため、文字列操作で補完する。

	// 妥当な行の判定（文字列操作と正規表現の組み合わせ）
	// 1. 行をトリムする。
	// 2. 行が空でないかチェックする。
	// 3. 行が数字、カンマ、空白のみで構成されているかチェックする。
	// 4. 数字が含まれているかチェックする。

	// 妥当な行の判定に特化した正規表現 (数字とカンマ、空白のみを許容し、数字が少なくとも1つあることを確認)
	// ^\s* - 行頭の空白
	// (?:[0-9][0-9,]*[0-9]) - 少なくとも2つの数字が連続していることを確認（最低1つの数字が必須）
	// |
	// [0-9]+(?:,.*)?$ - 単一の数字列、または数字とカンマの組み合わせ（末尾のカンマあり）
	// この正規表現は複雑になるため、今回は「数字とカンマ、空白のみ」という制約を厳密に適用する。

	// 妥当な行の判定:
	// 1. 行をトリムする。
	// 2. 行が空でないかチェックする。
	// 3. 行が数字、カンマ、空白のみで構成されているかチェックする。
	// 4. 数字が含まれているかチェックする。

	// 妥当な行の判定のための正規表現 (数字、カンマ、空白のみを許容し、数字が少なくとも1つあることを確認)
	// ^\s* - 行頭の空白
	// (?:[0-9][0-9,]*[0-9]) - 少なくとも2つの数字が連続していることを確認（最低1つの数字が必須）
	// |
	// [0-9]+(?:,.*)?$ - 単一の数字列、または数字とカンマの組み合わせ（末尾のカンマあり）
	// これは依然として複雑。最も簡単なのは、数字とカンマ以外の文字がないことを確認し、数字が存在することを確認すること。

	// 妥当な行の判定をシンプル化し、正規表現で「数字とカンマ、空白のみ」をチェックする。
	// 妥当な行の定義: 1個以上の数字とカンマ、空白のみで構成され、数字が少なくとも1つ含まれる。
	// 末尾のカンマは許容される。

	// 妥当な行の判定に特化した正規表現 (数字、カンマ、空白のみを許容し、数字が少なくとも1つあることを確認)
	// ^\s* - 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字がカンマで区切られているパターン
	// |
	// [0-9]+(?:,.*)?$ - 単一の数字列、または数字とカンマの組み合わせ（末尾のカンマあり）

	// 妥当な行の判定に特化した正規表現 (数字、カンマ、空白のみを許容し、数字が少なくとも1つあることを確認)
	// ^\s* - 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字がカンマで区切られているパターン
	// |
	// [0-9]+(?:,.*)?$ - 単一の数字列、または数字とカンマの組み合わせ（末尾のカンマあり）

	// 妥当な行の判定のための正規表現を再構成:
	// 1. 行が空でないこと。
	// 2. 行が数字、カンマ、空白のみで構成されていること。
	// 3. 数字が含まれていること。
	// 4. 末尾のカンマは許容される。

	// 妥当な行の判定ロジックを文字列操作で実施し、正規表現は「数字が含まれているか」の確認に限定する。

	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" {
			continue // 空行は妥当ではない
		}

		// 1. 数字とカンマ、空白のみで構成されているかチェック
		isValidChars := true
		for _, char := range line {
			if !('0' <= char && char <= '9' || char == ',' || char == ' ') {
				isValidChars = false
				break
			}
		}
		if !isValidChars {
			continue // 数字とカンマ、空白以外が含まれていれば妥当ではない
		}

		// 2. 少なくとも1つの数字が含まれているかチェック
		hasDigit := false
		for _, char := range line {
			if '0' <= char && char <= '9' {
				hasDigit = true
				break
			}
		}
		if !hasDigit {
			continue // 数字が一つも含まれていなければ妥当ではない (例: ", ,")
		}

		// 3. 末尾のカンマは許容される (これは上記チェックで暗黙的に許容されている)
		// 妥当な行としてカウント
		validLines++
	}

	fmt.Printf("valid=%d\n", validLines)
}
