package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	r := bufio.NewReader(os.Stdin)
	validLines := 0

	// 正規表現: カンマ区切りの整数列をチェックする。
	// ^\s* : 行頭の空白を許容
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列と、それに続くカンマと空白の繰り返しをキャプチャするグループ。
	// (?:,\s*)* : 末尾のカンマと空白の繰り返しを許容する（末尾のカンマは許容される）。
	// $ : 行末
	// この正規表現は、少なくとも1つの数字列が存在し、カンマ区切りで構成されていることを確認する。
	// ただし、仕様の「1 個以上の数字列がカンマで区切られて並んでいる」を厳密に表現するため、
	// よりシンプルに「数字とカンマのみ」で構成されていることを確認し、空行や不正文字を排除するアプローチを取る。

	// 妥当な行のカウント
	for {
		line, err := r.ReadString('\n')
		if err != nil {
			break
		}

		// 行の末尾の改行文字を削除し、前後の空白をトリムする
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現による判定:
		// 1. 行が数字とカンマのみで構成されているか。
		// 2. 少なくとも1つの数字が含まれているか。
		// 3. 末尾のカンマは許容される。
		// 以下の正規表現は、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
		// ^\s* : 行頭の空白を許容
		// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字と、それに続くカンマと空白の繰り返し（少なくとも1つの数字列）
		// (?:,\s*)* : 末尾のカンマと空白の繰り返し（末尾のカンマは許容）
		// $ : 行末
		// より厳密に「1個以上の数字列がカンマで区切られている」ことを確認するため、
		// 少なくとも1つの数字列が存在し、その構造が数字とカンマのみであるかをチェックする。

		// 簡略化のため、行が数字とカンマのみで構成されていることを確認し、空行でないことを確認する。
		// 1. 数字とカンマ以外の文字が含まれていないか
		// 2. 少なくとも1つの数字が含まれているか
		// 3. 末尾のカンマは許容される。

		// 最初の試みとして、行が数字、カンマ、空白のみで構成されているかを確認する。
		// 厳密な「1個以上の数字列がカンマで区切られて並んでいる」を正規表現で表現するのは複雑なため、
		// 以下のロジックで、空行や不正文字を排除し、カンマ区切りの整数列の形式をチェックする。

		// 行が数字とカンマ、空白のみで構成されているかを確認
		if regexp.MustCompile(`^[\d, ]+$`).MatchString(line) {
			// 数字とカンマ、空白のみで構成されている場合、
			// 少なくとも1つの数字が含まれているかを確認する
			if regexp.MustCompile(`\d`).MatchString(line) {
				validLines++
			}
		}
	}

	fmt.Printf("valid=%d\n", validLines)
}
