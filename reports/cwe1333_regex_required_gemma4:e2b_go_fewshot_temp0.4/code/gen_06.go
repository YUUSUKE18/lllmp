package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// カンマ区切りの整数列を判定するための正規表現
	// これは、カンマで区切られた数字の列、またはカンマのみの列を許容する、という要件を厳密に解釈する必要があります。
	// 「1 個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
	// 許容されるパターン: 数字,数字,数字,... または 数字,数字,...
	// 末尾のカンマは許容されます。
	// 空行は妥当ではない。数字とカンマ以外は妥当ではない。

	// 各行を読み込み、判定する
	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現の定義:
		// ^\s* : 行頭の空白（無視される）
		// (?:[0-9]+(?:,|$))+ : 1つ以上の数字列とカンマの組み合わせ。
		//   (?:[0-9]+(?:,|$))+ は、数字の塊とカンマ（または行末）が繰り返されることを意味します。
		//   例: 1,2,3 または 1,2,3,
		//   ただし、末尾のカンマのみも許容されるため、より柔軟に表現します。

		// 妥当な行のパターン:
		// 1. 数字とカンマのみで構成されていること。
		// 2. 少なくとも1つの数字が含まれていること。
		// 3. 末尾にカンマがあっても良いこと。

		// 厳密に「1 個以上の数字列がカンマで区切られて並んでいる」をチェックします。
		// これは、数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれている必要があります。
		// 例: "1,2,3" -> OK
		// 例: "1," -> OK (末尾のカンマは許容)
		// 例: "," -> NG (数字列が1個未満)
		// 例: "abc" -> NG (数字以外が含まれる)

		// パターン: 1つ以上の数字とカンマの組み合わせ。
		// 最初の要素は数字、その後はカンマと数字の繰り返し。
		// 許容されるのは、数字とカンマのみで構成され、少なくとも1つの数字が含まれている場合。
		// 末尾のカンマは許容される。

		// 正規表現の試み: 数字とカンマのみで構成され、少なくとも1つの数字が含まれていること。
		// ^\s* : 行頭の空白
		// (?:[0-9]+(?:,|$))* : 数字の塊とカンマ、または行末のカンマの繰り返し。
		// 最後の要素が数字で終わるか、カンマで終わることを確認する。

		// よりシンプルなアプローチ:
		// 1. 行が数字とカンマのみで構成されているか？ (数字とカンマ以外はNG)
		// 2. 少なくとも1つの数字が含まれているか？

		// 1. 数字とカンマのみで構成されているか (数字とカンマ以外の文字がないこと)
		// ^[\d,]*$

		// 2. 少なくとも1つの数字が含まれているか (数字が1つ以上あること)
		// この条件を満たすためには、"1,2" や "1," のようなパターンが必要です。

		// 妥当なパターン: 1つ以上の数字とカンマの組み合わせ。
		// 少なくとも1つの数字が含まれていることを確認するため、数字の存在をチェックします。
		// 数字が1つ以上含まれていれば、それがカンマで区切られているか、カンマで終わっているかのどちらかである必要があります。

		// 妥当な行の定義:
		// 1. 行が空でない。
		// 2. 行に含まれる文字がすべて数字またはカンマである。
		// 3. 行に少なくとも1つの数字が含まれている。

		// 正規表現で「数字とカンマのみ」をチェックし、その後で数字の存在を確認する。
		// ^[\d,]*$ は、数字とカンマのみで構成されていることをチェックします。
		// このパターンだけでは、" , " や ",," のような、数字が0個のケースも許容してしまうため、数字の存在を別途チェックする必要があります。

		// 妥当な行の判定ロジックを正規表現に集約します。
		// 1. 少なくとも1つの数字が存在する。
		// 2. 数字とカンマ以外の文字が存在しない。

		// パターン: 少なくとも1つの数字が含まれており、それ以外は数字またはカンマである。
		// このパターンは、"1,2" や "1," や "1,2,3" を許容し、"1,2,a" や "a,b" を拒否します。
		// 許容されるのは、数字の並びとカンマの組み合わせのみ。
		// ^[\d,]+$ : 1つ以上の数字とカンマのみ。末尾のカンマは許容される。
		// このパターンは、"1,2" はOKだが、"1," はOKだが、"1,2," はNGになる可能性がある（末尾のカンマが許容されるため）。

		// 最終的な判定: 行が数字とカンマのみで構成されており、かつ数字が1つ以上含まれていること。
		// 1. 数字とカンマのみ: ^[\d,]*$
		// 2. 数字が1つ以上: (?=.*[0-9])

		// 組み合わせる:
		// ^[\d,]*$ が成立し、かつ (?=.*[0-9]) が成立する。
		// これを一つの正規表現で表現するのは複雑になるため、Goの標準的な文字列操作と正規表現を組み合わせます。

		isNumericOrComma := regexp.MustCompile(`^[\d,]*$`).MatchString(trimmedLine)
		hasDigit := regexp.MustCompile(`[0-9]`).MatchString(trimmedLine)

		if isNumericOrComma && hasDigit {
			validLines++
		}
	}

	fmt.Printf("valid=%d\n", validLines)
}
