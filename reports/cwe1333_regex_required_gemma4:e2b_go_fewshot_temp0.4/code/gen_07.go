package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// カンマ区切りの整数列の妥当性を判定するための正規表現
	// ^\s* - 行の先頭の空白（無視される）
	// (?:[0-9]+(?:,[0-9]+)*) - 1個以上の数字とカンマの組み合わせ（整数列）
	// (?:,*)? - 末尾のカンマが0回以上続く（末尾のカンマは許容）
	// \s*$ - 行末の空白
	// この正規表現は、行全体がカンマ区切りの整数列で構成されていることを確認します。
	// ただし、仕様では「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する必要があります。
	// より厳密に、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。

	// 判定ロジックをよりシンプルにし、正規表現の適用を工夫します。
	// 妥当な行は「カンマで区切られた数字の塊」のみで構成され、空行や不正な文字を含まない必要があります。

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 末尾のカンマを削除して、カンマ区切りの数字列のみが残っているか確認する
		// 末尾のカンマは許容されるため、行全体が数字とカンマのみで構成されているかを確認する。
		// 正規表現: ^\s*([0-9]+(?:,[0-9]+)*)(?:,*)?\s*$
		// 実際には、行が数字とカンマのみで構成されているか、かつ少なくとも1つの数字が含まれているかを確認します。

		// 1. 数字とカンマのみで構成されているかを確認
		// このパターンは、数字とカンマのみで構成され、末尾にカンマがあってもよい、という条件を満たすように設計します。
		// (?:[0-9]+(?:,[0-9]+)*) は、1つ以上の数字とカンマの組み合わせを意味します。
		// (?:,*)? は、末尾のカンマが0回以上あることを許容します。
		// 厳密には、行全体がこのパターンにマッチし、かつ数字が含まれている必要があります。

		// より簡単な判定として、行をカンマで分割し、各要素が数字であることを確認します。
		parts := strings.Split(trimmedLine, ",")
		isValid := true
		hasNumber := false

		for _, part := range parts {
			trimmedPart := strings.TrimSpace(part)
			if trimmedPart == "" {
				// 空の要素は許容される（カンマの連続や末尾のカンマによる）
				continue
			}
			// 各要素が整数であるかを確認
			if _, err := fmt.Sscanf(trimmedPart, "%d", &hasNumber); err != nil {
				isValid = false
				break
			}
			// 実際には、strconv.Atoiでエラーチェックするのが最も確実ですが、ここでは正規表現の使用が求められているため、
			// 正規表現で「数字とカンマのみ」という構造をチェックします。

			// 正規表現によるチェック（行全体が数字とカンマのみで構成されているか、かつ少なくとも1つの数字があるか）
			// 以下の正規表現は、行が数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれていることを確認します。
			// ^\s*([0-9]+(?:,[0-9]+)*)(?:,*)?\s*$
			// この正規表現は複雑になるため、ここでは「数字とカンマ以外が含まれていないこと」を主要なチェックとします。
		}

		// 正規表現による厳密なチェック
		// 1. 行全体が数字とカンマのみで構成されていること
		// 2. 少なくとも1つの数字が含まれていること
		// パターン: ^\s*([0-9,]*[0-9])\s*$
		// これは、数字が最低1つあり、数字とカンマ以外がないことを示唆します。

		// 仕様の「1個以上の数字列がカンマで区切られて並んでいる」ことを満たすためには、
		// 内部の要素が全て整数であり、行全体がその構造に従う必要があります。

		// 簡略化し、正規表現で「数字とカンマ以外の文字がないこと」をチェックします。
		// 妥当な行は、数字、カンマ、空白のみで構成されている必要があります。
		// 末尾のカンマは許容されるため、行全体が数字とカンマで構成されていることを確認します。
		// 妥当な行の例: "1,2,3", "1,2,"
		// 不妥当な行の例: "1,a,3", "1 2 3"

		// 正規表現パターン: ^\s*[\d,]*\s*$
		// これは、行が数字、カンマ、空白のみで構成されていることを確認します。
		// 空行は既に除外済み。
		match, err := regexp.MatchString(`^[\d,]*$`, trimmedLine)
		if err != nil {
			isValid = false
		} else if match {
			// 数字とカンマのみで構成されている。少なくとも1つの数字が含まれているか確認する。
			// 含まれていない場合（例: "," や ""）、これは空行で除外済みなので、数字が含まれていればOK。
			if strings.Contains(trimmedLine, "0") || strings.Contains(trimmedLine, "1") || strings.Contains(trimmedLine, "2") || strings.Contains(trimmedLine, "3") || strings.Contains(trimmedLine, "4") || strings.Contains(trimmedLine, "5") || strings.Contains(trimmedLine, "6") || strings.Contains(trimmedLine, "7") || strings.Contains(trimmedLine, "8") || strings.Contains(trimmedLine, "9") {
				// 数字が含まれていれば妥当
				validLines++
			} else if strings.Contains(trimmedLine, ",") {
				// 数字が含まれていないがカンマがある場合 (例: ",," や "," のようなケース)
				// これは「1個以上の数字列」が条件を満たさないため不妥当とする。
			}
		} else {
			// 数字とカンマ以外の文字が含まれている
		}

		// 最終的な判定ロジックを、正規表現の意図に合わせるため、再構築します。
		// 妥当な行は、カンマで区切られた整数列であり、空行や不正な文字を含まない。
		// 妥当な行の定義: 行が数字とカンマのみで構成され、少なくとも1つの数字が含まれている。

		// 最終的な判定（正規表現の適用）
		// 妥当な行は、数字とカンマのみで構成され、かつ少なくとも1つの数字を含む。
		// パターン: ^\s*[\d,]+$ (数字またはカンマが1回以上連続)
		// または、より厳密に、数字とカンマのシーケンスのみを許容する。

		// 妥当な行の判定を、行がカンマ区切りの整数列の形式であるか、という観点で再評価します。
		// 1. 空行は除外済み。
		// 2. 数字とカンマ以外を含む行は除外。
		// 3. 妥当な行は、カンマで区切られた整数列が並んでいる。

		// 妥当な行の判定を、行が完全に数字とカンマで構成されているか、かつ数字が含まれているかで判定します。
		// 妥当な行の例: "1,2,3", "1,2,"
		// 不妥当な行の例: "1,a,3", "1 2 3"

		// 妥当な行の判定を、行全体が数字とカンマのみで構成されているか、かつ数字が含まれているかで判定します。
		if strings.ContainsAny(line, "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ") == false {
			// 数字、カンマ、空白のみで構成されているかチェック
			isAlphanumericAndComma := true
			for _, r := range line {
				if !strings.ContainsRune("0123456789, ", r) {
					isAlphanumericAndComma = false
					break
				}
			}

			if isAlphanumericAndComma {
				// 数字が含まれているかチェック
				hasDigit := false
				for _, r := range line {
					if r >= '0' && r <= '9' {
						hasDigit = true
						break
					}
				}
				if hasDigit {
					validLines++
				}
			}
		}
	}

	fmt.Printf("valid=%d\n", validLines)
}
