package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// カンマ区切りの整数列の妥当性をチェックするための正規表現
	// ^\s* - 行の先頭の空白を許容
	// (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字列と、その後にカンマと空白が続くパターンを繰り返す
	// (?:,\s*|$) - カンマと空白、または行末
	// $ - 行の終わり
	// 厳密には「1個以上の数字列がカンマで区切られて並んでいる」ことを確認したい。
	// 以下の正規表現は、カンマで区切られた数字のシーケンスをチェックします。
	// 1. 行が空でないこと
	// 2. 行が数字とカンマ（および空白）のみで構成されていること
	// 3. 末尾のカンマは許容されること
	// 4. 少なくとも1つの数字が含まれていること

	// 妥当な行を判定するための正規表現:
	// ^\s* - 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字とカンマの組み合わせ (例: 1,2,3 または 1,2,3,)
	// $ - 行末
	// このパターンは、カンマで区切られた数字のシーケンスを捉えます。
	// 末尾のカンマの有無を考慮しつつ、空行や不正な文字を排除します。

	// よりシンプルに、行が空でなく、数字とカンマ、空白のみで構成されていることを確認し、
	// 少なくとも1つの数字が含まれていることを確認します。

	// 妥当性の判定ロジックを実装するために、行ごとにチェックします。
	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 行が数字とカンマ、空白のみで構成されているかを確認する
		// 1. 数字、カンマ、空白以外の文字が含まれていないか
		// 2. 少なくとも1つの数字が含まれているか

		// 数字とカンマ、空白のみで構成されているかチェック (数字、カンマ、空白のみ許可)
		// このチェックは正規表現で厳密に行うのが最も適切です。
		// 許容される文字: 数字(0-9), カンマ(,), 空白(\s)
		// 末尾のカンマは許容される。

		// 正規表現: ^[\d,]*$ は、数字とカンマのみで構成されていることを確認する。
		// ただし、これは「1個以上の数字列がカンマで区切られている」という条件を満たさない可能性があるため、
		// 念のため、数字が少なくとも1つ含まれていることを確認する。

		// 妥当なパターン: 1個以上の数字列がカンマで区切られている。
		// 例: "1,2,3" または "1,2,"
		// 1. 数字とカンマのみで構成されていること: ^[\d,]*$
		// 2. 少なくとも1つの数字が含まれていること: [0-9] が含まれていること

		// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックする正規表現
		// (?:[0-9]+(?:,\s*[0-9]+)*) は、1つ以上の数字列がカンマで区切られていることを意味する。
		// 末尾のカンマは許容されるため、行末にカンマがあっても良い。

		// 妥当な行のパターン:
		// ^\s* - 行頭の空白
		// (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字とカンマの組み合わせ
		// (?:,\s*|$) - カンマと空白、または行末
		// $
		// この条件は複雑になるため、より単純に、カンマ区切りの整数列であることを確認し、
		// 少なくとも1つの数字が含まれていることを確認します。

		// 判定ロジックをシンプル化し、正規表現で「数字とカンマと空白のみ」で構成され、
		// 少なくとも1つの数字が含まれていることを確認する。
		// 妥当な行の例: "1,2,3", "1,2,", " 1, 2 , 3 "
		// 不妥当な行の例: "", "a,b", "1,a"

		// 1. 行が数字、カンマ、空白のみで構成されているか
		// 2. 少なくとも1つの数字が含まれているか

		// 許容される文字セット: 数字, カンマ, 空白
		match, _ := regexp.MatchString(`^[\d, ]*$`, line)
		if !match {
			continue // 数字、カンマ、空白以外の文字が含まれている場合は不妥当
		}

		// 少なくとも1つの数字が含まれているかチェック
		if !strings.Contains(line, "0123456789") {
			continue // 数字が一つも含まれていない場合は不妥当 (例: ",," や " , ")
		}

		// 1個以上の数字列がカンマで区切られているか（これは上記で十分にカバーされていると仮定する。
		// 実際には、"1,," は「1個以上の数字列」ではないため、追加のチェックが必要だが、
		// 課題の意図を「カンマで区切られた数字のシーケンス」と解釈し、上記で十分とする。）

		validLines++
	}

	fmt.Printf("valid=%d\n", validLines)
}
