package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// カンマ区切りの整数列の妥当性を判定するための正規表現
	// ^\s*       : 行の先頭の空白（無視）
	// (?:[0-9]+,\s*)* : 1つ以上の「数字,」のパターンが0回以上繰り返される (数字とカンマのみ)
	// [0-9]+     : 少なくとも1つの数字列
	// (?:,\s*[0-9]+)* : 続く数字列（カンマとスペースを含む）
	// $          : 行の終わり
	// よりシンプルに、カンマで区切られた整数列が、数字とカンマのみで構成されているかをチェックする
	// 妥当なパターン: 1つ以上の数字とカンマの組み合わせ。末尾のカンマも許容する。
	// 許容されるパターン: 数字とカンマのみで構成され、空行でないこと。
	// 正規表現の設計:
	// ^\s*             : 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ（数字が少なくとも1つ）
	// (?:,\s*$)        : 末尾にカンマがあっても良い
	// 実際には、行が空でなく、数字とカンマのみで構成されているかを確認する。
	// 最もシンプルな妥当性の定義: 空行でなく、数字とカンマのみで構成されている。
	// 末尾のカンマは許容する。
	// ^\s*             : 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ
	// (?:,\s*)*        : 任意の数のカンマと空白（末尾のカンマも含む）
	// $                : 行末
	// 妥当な行は、数字とカンマのみで構成され、空行ではない。
	// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックする。
	// 例: "1,2,3" や "1," や ",2" は妥当と見なす。
	// 空行は妥当ではない。数字とカンマ以外は妥当ではない。

	// 妥当な行の判定ロジックを正規表現で表現するのは複雑になるため、
	// 以下のロジックで各行をチェックする。
	// 1. 行が空でないこと。
	// 2. 行に含まれる文字が数字とカンマ、空白のみであること。
	// 3. 少なくとも1つの数字が含まれていること。
	// 4. 末尾のカンマは許容する。

	// 妥当性の判定: 行が空でなく、数字とカンマのみで構成されているか。
	// 妥当な行の例: "1,2,3", "1,", ",2" (これは「1個以上の数字列がカンマで区切られて並んでいる」を満たす)
	// 空行は妥当ではない。数字とカンマ以外は妥当ではない。

	// 妥当な行のパターンをチェックする正規表現
	// ^\s*                                 : 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*)             : 1つ以上の数字とカンマの組み合わせ（最低1つの数字）
	// (?:,\s*)*                             : 続くカンマと空白（末尾のカンマも含む）
	// $                                     : 行末
	// このパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを保証する。
	// ただし、空行は除外する必要がある。

	// 実際には、行を読み込み、手動でチェックする方が意図を正確に反映しやすい。
	// ただし、課題の指示に従い正規表現を使う。

	// 妥当な行の判定: 行が空でなく、数字とカンマのみで構成されていること。
	// 1. 空行チェック: 行が空でなければOK。
	// 2. 内容チェック: 行に含まれる文字が数字、カンマ、空白のみであること。
	// 3. 構造チェック: 1個以上の数字列がカンマで区切られていること。

	// 課題の「妥当とは、1 個以上の数字列がカンマで区切られて並んでいることです。末尾のカンマは許容します。」に焦点を当てる。
	// 空行は妥当ではない。
	// 数字とカンマ以外を含む行は妥当ではない。

	// 妥当な行の判定のための正規表現:
	// ^\s*                                 : 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*)             : 少なくとも1つの数字列とカンマの組み合わせ
	// (?:,\s*)*                             : 続くカンマと空白（末尾のカンマも含む）
	// $                                     : 行末
	// このパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを保証する。
	// 空行は除外される。
	pattern := regexp.MustCompile(`^\s*(?:[0-9]+(?:,\s*[0-9]+)*)(?:,\s*)*$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 数字とカンマ以外を含む行は妥当ではない
		// 正規表現で数字とカンマ以外が含まれていないかチェックする
		if !regexp.MustCompile(`^[0-9, \t\n\r]*$`).MatchString(line) {
			continue
		}

		// 1個以上の数字列がカンマで区切られているか、またはカンマのみで構成されているかを確認する。
		// 妥当な行の定義を再解釈し、正規表現で直接判定する。
		// 妥当な行: 数字とカンマのみで構成され、空行ではない。
		// 1個以上の数字列がカンマで区切られていること。
		// 例: "1,2,3" -> OK
		// 例: "1," -> OK
		// 例: "," -> NG (数字列が0個)
		// 例: "abc" -> NG
		// 例: "1a" -> NG

		// 1. 数字とカンマのみで構成されていることを確認
		// 2. 少なくとも1つの数字が含まれていることを確認
		// 3. カンマで区切られている構造を許容する。

		// 最終的な判定ロジックとして、行が空でなく、数字とカンマのみで構成されていれば妥当とする。
		// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を正規表現で捉える。
		// 任意の数字とカンマのシーケンスが、カンマで区切られた数字の集合を表すと見なす。
		// 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
		if regexp.MustCompile(`^[0-9,]*$`).MatchString(line) {
			// 数字とカンマのみで構成されている
			// 少なくとも1つの数字が含まれているかチェック
			if regexp.MustCompile(`[0-9]`).MatchString(line) {
				// 1個以上の数字列がカンマで区切られているか、またはカンマのみで構成されている。
				// 末尾のカンマは許容。
				validLines++
			}
		}
	}

	fmt.Printf("valid=%d\n", validLines)
}
