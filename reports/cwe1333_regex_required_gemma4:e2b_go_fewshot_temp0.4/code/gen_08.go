package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// 正規表現: カンマ区切りの整数列をチェックする
	// ^\s* は行頭の空白を許容
	// (?:[0-9]+(?:,\s*[0-9]+)*) は1つ以上の数字とカンマの組み合わせ（数字が1つ以上）
	// (?:,\s*)* は末尾のカンマとその後の空白が0回以上続くことを許容
	// $ は行末
	// この正規表現は、少なくとも1つの数字列が存在し、数字とカンマ以外の文字が含まれていないことを確認する。
	// ただし、課題の要件「1 個以上の数字列がカンマで区切られて並んでいる」を厳密に満たすために、
	// 少なくとも一つの数字列が存在することをチェックする。
	// よりシンプルに、行が空でなく、数字とカンマ以外の文字を含まないことを確認し、
	// さらに数字が含まれていることを確認する。

	// 課題の要件を再解釈:
	// 1. 空行は妥当ではない。
	// 2. 数字とカンマ以外を含む行は妥当ではない。
	// 3. 1個以上の数字列がカンマで区切られて並んでいること。
	// 4. 末尾のカンマは許容される。

	// 最初のチェック：行が空でないこと、および数字とカンマ以外の文字を含まないこと。
	// このチェックは、正規表現で「数字とカンマのみ」という条件を適用する。
	// 1. 空行の除外: 行が空でないことを確認する。
	// 2. 数字とカンマ以外を含まないこと: 以下のパターンは、数字とカンマのみで構成されている行を許容する。
	//    ^[\d,]*$ は、行が数字とカンマのみで構成されていることを意味する。

	// 3. 1個以上の数字列がカンマで区切られていること。
	//    これは、行内に少なくとも1つの数字が含まれていることを意味する。
	//    ^[\d,]*$ かつ [\d]+ が含まれていることを確認する。

	// 課題の要件をより厳密に満たすための正規表現の適用:
	// 1. 行が空でないこと。
	// 2. 行が数字、カンマ、空白のみで構成されていること（空白は無視される）。
	// 3. 少なくとも1つの数字が含まれていること。

	// 行を読み込む
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())

		if line == "" {
			// 空行は妥当ではない
			continue
		}

		// 数字とカンマ以外の文字が含まれていないかチェック
		// 許容される文字は数字(0-9), カンマ(,), 空白( )
		// 課題の指示「数字とカンマ以外を含む行は妥当ではありません」を考慮すると、
		// 厳密には「数字とカンマのみ」という制約が最も適切。

		// 行が数字とカンマのみで構成されているかチェック
		// ^[0-9,]*$ は、行が数字とカンマのみで構成されていることを意味する。
		// ただし、行の前後空白は無視されるため、行全体をチェックする。
		// 課題の指示に従い、行全体をチェックする。
		match, _ := regexp.MatchString(`^[\d,]*$`, line)
		if !match {
			// 数字とカンマ以外の文字が含まれている場合、妥当ではない
			continue
		}

		// 少なくとも1つの数字が含まれているかチェック
		hasDigit := false
		for _, char := range line {
			if char >= '0' && char <= '9' {
				hasDigit = true
				break
			}
		}

		if hasDigit {
			validLines++
		}
	}

	fmt.Printf("valid=%d\n", validLines)
}
