package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// カンマ区切りの整数列の妥当性を判定するための正規表現
	// ^\s*                : 行の先頭の空白を許容
	// (?:             : 非キャプチャグループの開始
	//   \d+           : 1つ以上の数字
	//   ,\s*          : カンマとそれに続く空白
	// )+              : 上記のパターンが1回以上繰り返されること
	// (?:             : 非キャプチャグループの開始
	//   \d+          : 最後の数字（カンマなし）
	// )?              : 最後の数字はオプション
	// (?:,\s*$)       : 末尾のカンマと空白（オプション）
	// $                : 行の終わり
	// この正規表現は「1個以上の数字がカンマで区切られている」ことを確認するのではなく、
	// 「数字とカンマのみで構成され、少なくとも1つの数字が含まれている」ことを確認するのに適しています。

	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// 以下のロジックで各行をチェックします。

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現: 1つ以上の数字とカンマのみで構成されているか、かつ、
		// 少なくとも1つの数字が含まれていることを確認する
		// パターン: 任意の数の数字とカンマの組み合わせ（末尾のカンマは許容）
		// ^\s*         : 行頭の空白
		// (?:         : 非キャプチャグループ
		//   \d+       : 1つ以上の数字
		//   (?:,\s*\d+)* : カンマとそれに続く数字の繰り返し（数字が少なくとも1つあることを保証）
		// )
		// (?:,\s*\d+)?  : 最後の数字（カンマなし）はオプション
		// (?:,\s*)$     : 末尾のカンマと空白はオプション
		// この問題の「1個以上の数字列がカンマで区切られて並んでいる」を判定するには、
		// 少なくとも1つの数字が存在し、数字とカンマ以外がないことを確認するのが最も直接的です。

		// 簡略化して、数字とカンマ、空白以外の文字がないことを確認し、数字が含まれていることを確認します。
		// 妥当な行の定義: 数字、カンマ、空白のみで構成され、少なくとも1つの数字が含まれている。

		// 1. 数字とカンマ、空白以外が含まれていないかチェック
		if !regexp.MustCompile(`^[\d, \t\n]*$`).MatchString(line) {
			continue // 数字とカンマ以外が含まれていたら不妥当
		}

		// 2. 少なくとも1つの数字が含まれているかチェック
		// 数字が含まれていない場合（例: ",," や " , " など）、これは不妥当
		if !strings.Contains(line, "0123456789") {
			continue // 数字が一つも含まれていなければ不妥当
		}

		// 3. 末尾のカンマの許容（これは上記でカバーされるが、念のため）
		// 妥当な行としてカウント
		validLines++
	}

	fmt.Printf("valid=%d\n", validLines)
}
