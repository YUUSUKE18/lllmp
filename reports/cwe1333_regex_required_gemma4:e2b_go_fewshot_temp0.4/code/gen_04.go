package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// 正規表現: カンマ区切りの整数列、末尾にカンマがあっても良い。
	// ^\s*       : 行頭の空白を許容
	// (?:       : 非キャプチャグループの開始
	//   \d+     : 1つ以上の数字
	//   ,?      : オプションのカンマ
	// )+        : 上記グループが1回以上繰り返される
	// \s*$       : 行末の空白を許容
	// この正規表現は、少なくとも1つの数字がカンマで区切られていることを確認する。
	// ただし、課題の仕様「1 個以上の数字列がカンマで区切られて並んでいる」を厳密に満たすため、
	// 複数の数字列の区切りを考慮する必要があります。
	// より厳密に「数字とカンマのみ」で構成され、少なくとも1つの数字が存在する行を判定します。

	// 課題の仕様を再解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
	// これは、カンマで区切られた要素がすべて数字である、ということを意味します。
	// 例: "1,2,3" -> 3つの数字列
	// 例: "1,2," -> 2つの数字列 (末尾のカンマは許容)
	// 例: "1,,2" -> 不適格 (空の数字列)
	// 例: "abc,1" -> 不適格 (数字以外を含む)

	// 正規表現を「カンマで区切られた、数字のみの要素が1つ以上存在する」ことに絞る。
	// \s* は行頭/行末の空白を無視するために使用。
	// (?:[\d]+(?:,[\d]+)*)  : 少なくとも1つの数字列と、それに続くカンマと数字列のパターンを許容する。
	// より単純に、行全体が数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。

	// 判定ロジックを文字列操作で補強し、正規表現で形式をチェックします。
	// 正規表現で「数字とカンマのみ」で構成されていることを確認し、その後、数字が存在するかを確認します。
	// 1. 行全体が数字とカンマのみで構成されているか？
	// 2. 少なくとも1つの数字が含まれているか？

	// 1. 数字とカンマのみで構成されているか (空白は無視)
	// ^\s*[\d,]*\s*$ : 行頭から行末まで、数字とカンマのみ（空白は無視される）
	// この正規表現だけでは「空行」や「数字とカンマ以外」を完全に除外できません。

	// 課題の制約を厳密に満たすため、文字列操作で妥当性を確認し、正規表現は形式チェックに特化させます。

	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" {
			// 空行は妥当ではない
			continue
		}

		// 1. 数字とカンマ以外が含まれていないかチェック
		// 数字とカンマのみで構成されているかを確認
		isNumericAndCommaOnly := true
		for _, char := range line {
			if !('0' <= char && char <= '9') && char != ',' {
				isNumericAndCommaOnly = false
				break
			}
		}
		if !isNumericAndCommaOnly {
			continue
		}

		// 2. 1個以上の数字列がカンマで区切られているかチェック (空の数字列がないか)
		// カンマで分割し、各要素が空でないか確認する
		parts := strings.Split(line, ",")
		count := 0
		for _, part := range parts {
			trimmedPart := strings.TrimSpace(part)
			if trimmedPart != "" {
				count++
			}
		}

		if count >= 1 {
			validLines++
		}
	}

	fmt.Printf("valid=%d\n", validLines)
}
