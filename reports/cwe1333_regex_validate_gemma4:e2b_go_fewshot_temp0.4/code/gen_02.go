package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func main() {
	sc := bufio.NewScanner(os.Stdin)
	validLines := 0

	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())

		if line == "" {
			// 空行は妥当ではない
			continue
		}

		// 末尾のカンマを許容して、カンマで区切られた整数列が存在するか確認する
		// 少なくとも1つの数字列が存在すれば妥当とする
		if strings.Contains(line, ",") {
			// 末尾のカンマを削除して、残った部分が数字のみで構成されているかを確認する
			// ただし、問題の仕様は「1個以上の数字列がカンマで区切られて並んでいる」なので、
			// カンマで区切られた後に数字が存在すれば良い。
			
			// 行全体をカンマで分割し、空でない要素が1つ以上あるかを確認する
			parts := strings.Split(line, ",")
			
			hasDigits := false
			for _, part := range parts {
				trimmedPart := strings.TrimSpace(part)
				if trimmedPart != "" {
					// 数字のみで構成されているかチェック（ここでは単純に数字が含まれているかを確認する）
					if strings.TrimSpace(trimmedPart) != "" {
						// 数字が含まれていることを確認。もし、"a,b"のような文字列が許されるなら、
						// 課題の意図をより厳密に解釈する必要があるが、
						// 「カンマ区切りの整数列」という記述から、各要素が整数であると仮定する。
						
						// ここでは、各要素が数字（カンマ区切り）であるという前提で、
						// 空でない要素が1つ以上あれば妥当と判断する。
						
						// 厳密に「整数列」をチェックする場合、各要素が整数である必要がある。
						// 簡単のため、ここでは「カンマで区切られた要素が1つ以上存在し、
						// それらが数字として解釈可能であること」を妥当とする。
						
						// 課題の意図を「カンマで区切られた要素が、全て整数であること」と解釈し、
						// 少なくとも1つの非空の要素があれば妥当とする。
						hasDigits = true
					}
				}
			}
			
			if hasDigits {
				validLines++
			}
		} else {
			// カンマが含まれていない場合、これは1つの整数列と見なせるか？
			// 「1個以上の数字列がカンマで区切られて並んでいる」という条件を満たすためには、
			// カンマが存在することが望ましい。
			// しかし、もしカンマなしの整数列も許容されるなら、それは1つの要素として扱われる。
			// 「妥当とは、1 個以上の数字列がカンマで区切られて並んでいることです」
			// という定義に基づき、カンマがない行は妥当ではないと判断する。
		}
	}

	fmt.Printf("valid=%d\n", validLines)
}
