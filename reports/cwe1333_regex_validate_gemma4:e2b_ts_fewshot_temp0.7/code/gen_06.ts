const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let lineCount = 0;
let validLines = 0;

rl.on('line', (line) => {
  lineCount++;
  // 行の前後の空白を無視して判定
  const trimmedLine = line.trim();

  // 1. 空行のチェック
  if (trimmedLine === "") {
    // 空行は妥当ではない
    return;
  }

  // 2. 数字とカンマ以外の文字が含まれていないかチェック
  // 正規表現: 数字 (0-9), カンマ (,), 空白以外
  const validPattern = /^[0-9,]*$/;

  if (!validPattern.test(trimmedLine)) {
    // 数字とカンマ以外の文字が含まれている場合、妥当ではない
    return;
  }

  // 3. カンマ区切りの整数列であるかチェック
  // 末尾のカンマは許容される (例: "1,2," は妥当)
  // 妥当であるためには、少なくとも1つの数字が含まれている必要がある。
  // 末尾にカンマがあっても、その前が数字で構成されていればOK。
  // ただし、仕様は「1 個以上の数字列がカンマで区切られて並んでいること」を求めている。
  // これは、少なくとも1つの数字が存在し、カンマが適切に使用されていることを意味する。

  // 厳密に「1 個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
  // 少なくとも1つの数字が含まれているかを確認する。
  if (trimmedLine.includes(',')) {
    // カンマが含まれている場合、数字が含まれていることを確認する。
    // 数字が含まれていれば、それはカンマ区切りの整数列として妥当である。
    const containsDigit = /^[0-9]/.test(trimmedLine);
    if (containsDigit) {
      validLines++;
    }
  } else {
    // カンマが含まれていない場合、それは単一の数字列（または数字と空白のみ）である。
    // 仕様は「カンマで区切られて並んでいる」ことを求めているため、カンマがない場合は妥当ではないと解釈する。
    // ただし、例2の仕様が「カンマ区切りの語」なので、カンマがない場合は「1個の数字列」として扱うか？
    // 「1 個以上の数字列がカンマで区切られて並んでいる」を満たすには、区切り文字（カンマ）が必要。
    // 例として、"123" はカンマ区切りのリストではないため、ここでは妥当としない。
    // ただし、行が「数字列」であるという制約を満たしているため、今回は「カンマ区切りのリスト」としての妥当性を重視する。
    // ここでは、カンマが含まれていない行は「妥当ではない」と判断する。
  }
});

rl.on('close', () => {
  console.log(`valid=${validLines}`);
});
