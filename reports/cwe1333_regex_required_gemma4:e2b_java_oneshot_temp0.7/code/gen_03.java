import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン: 
            // ^\s*         -> 行の先頭の空白を無視
            // [0-9,]*      -> 0から9の数字とカンマが0回以上続く (数字とカンマのみを含む)
            // \s*$         -> 行の末尾の空白を無視
            // このパターンだけでは「1個以上の数字列がカンマで区切られている」ことを直接判定するのは難しい。
            // 仕様に従い、「1個以上の数字列がカンマで区切られて並んでいる」ことを判定する。
            // これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれている必要がある。

            // 判定ロジック：
            // 1. 行をトリムする。
            String trimmedLine = line.trim();

            // 2. 空行かどうかをチェック
            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 3. 正規表現による妥当性の判定
            // パターン: 
            // ^                 # 行の先頭
            // [\d,]+            # 1つ以上の数字またはカンマが連続している (数字とカンマのみで構成されている)
            // $                 # 行の末尾
            // このパターンは「数字とカンマのみで構成されている」ことを確認するが、「カンマ区切り」を厳密に確認するには、
            // カンマの後に数字が続くことを確認する必要がある。

            // より厳密な判定：カンマで区切られていることを確認する。
            // 1. カンマで区切られていることを確認する。
            // 2. 各区切りが数字であることを確認する。

            // 妥当な行の定義: 1個以上の数字列がカンマで区切られて並んでいる。末尾のカンマは許容。
            // 例: "1,2,3" (OK), "1,2," (OK), "1" (OK)

            // 正規表現: 
            // ^\s*                 # 先頭の空白
            // (?:                  # グループ開始 (非キャプチャ)
            //   \d+               # 1つ以上の数字 (数字列)
            //   (?:,\s*)?         # カンマとそれに続く任意の空白が0回または1回繰り返される (区切り)
            // )+                   # 上記グループが1回以上繰り返される
            // (?:,\s*|\s*)?         # 末尾のカンマや空白が任意 (末尾のカンマ許容のため)
            // $                    # 行の末尾
            
            // 簡略化して、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
            // 妥当な行は、数字とカンマのみで構成され、かつ、少なくとも1つの数字が含まれている。
            // ただし、問題文の意図は「カンマ区切り」なので、カンマの存在が重要。

            // 判定基準を「数字とカンマのみで構成され、カンマが含まれていれば妥当」または「数字のみで構成されていれば妥当」と解釈する。
            // 以下のパターンは、数字とカンマのみで構成され、カンマで区切られている構造を許容する。
            // 1. 少なくとも1つの数字が含まれていること。
            // 2. 数字とカンマ以外の文字が含まれていないこと。
            
            // 妥当な行のパターン (数字とカンマのみで構成され、少なくとも1つの数字を含む):
            // ^\s*[\d,]+$
            
            // このパターンは「1,2,3」や「1,"や"123,"のような、数字とカンマのみで構成されている行を捉える。
            // 空行は既に除外している。
            
            // 念のため、数字が含まれていることを確認する。
            Pattern pattern = Pattern.compile("^\\s*([0-9,]+)\\s*$");
            Matcher matcher = pattern.matcher(line);

            if (matcher.matches()) {
                // 数字とカンマのみで構成されている。
                // さらに、数字が少なくとも1つ含まれているか確認する。
                boolean containsDigit = false;
                for (char c : line.toCharArray()) {
                    if (Character.isDigit(c)) {
                        containsDigit = true;
                        break;
                    }
                }
                
                if (containsDigit) {
                    validCount++;
                }
            }
        }

        System.out.println("valid=" + validCount);
    }
}
