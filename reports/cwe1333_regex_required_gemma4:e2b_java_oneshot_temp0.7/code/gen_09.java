import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;
        String line;

        // 標準入力から行を読み続ける
        while ((line = br.readLine()) != null) {
            // 行の前後の空白を無視して、正規表現で判定する
            // 正規表現: ^\s*[\d,]+\s*$
            // ^\s* : 行の先頭の空白
            // [\d,]+ : 1文字以上の数字またはカンマ
            // \s*$ : 行末の空白
            // この正規表現は、カンマ区切りの整数列が1つ以上存在し、他の文字がないことを確認する。
            // 仕様では「1 個以上の数字列がカンマで区切られて並んでいる」ことを要求しており、
            // これは「カンマで区切られた数字が少なくとも1つある」ことを意味する。
            // より厳密に「カンマ区切りの整数列」を判定するために、数字とカンマのみで構成されているかを確認する。

            // 1. 行の前後の空白をトリム
            String trimmedLine = line.trim();

            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 2. 正規表現による判定: カンマ区切りの整数列が1つ以上あるか。
            // 1個以上の数字とカンマのみで構成されていることをチェックする。
            // 許容されるパターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
            // 正規表現の解釈を「カンマで区切られた整数列」が妥当かどうか、という点に絞る。
            // 妥当性の定義: 1個以上の数字列がカンマで区切られて並んでいる。
            // これは、カンマが数字の間に存在する、または末尾に存在する構造を意味する。
            
            // シンプルに、行が数字とカンマのみで構成されているかを確認し、かつ数字が含まれているかを確認する。
            // (?:[0-9,]+) は数字またはカンマの連続。
            // 妥当な行は、数字とカンマのみで構成され、少なくとも1つの数字が含まれる。
            
            // 1. 数字とカンマのみで構成されているか (末尾のカンマは許容)
            // ^\s*[\d,]*$ は、数字とカンマのみで構成されることを確認する。
            // 1個以上の数字列がカンマで区切られていることを確認するには、数字が少なくとも1つ必要。
            
            // より直接的に「カンマ区切り」の構造をチェックする。
            // 数字とカンマのみで構成され、かつ数字が少なくとも1つ含まれていることを確認する。
            // 許容されるパターン例: "1,2,3", "100,"
            
            // 正規表現: (\d+)(,?\d*)*
            // これは複雑になるため、仕様を再解釈する。「カンマ区切りの整数列」が妥当であること。
            // 妥当な行は、数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
            
            // 以下の正規表現は、数字とカンマのみで構成されていることを確認する。
            // 妥当性の定義を「カンマで区切られた整数列」が1つ以上あることと解釈し、
            // 実際に入力された文字列が数字とカンマのみで構成されているかをチェックする。
            
            // 妥当な行の判定: 行が数字とカンマのみで構成されており、空行ではない。
            // 正規表現: ^\s*[\d,]*\s*$ (これは全ての行が成立してしまうため不十分)
            
            // 妥当な行の判定を「カンマで区切られた整数列」が1つ以上あること、つまり数字が含まれていることとする。
            // 少なくとも1つの数字が含まれているかを確認する。
            Pattern pattern = Pattern.compile(".*\\d.*"); // 数字が含まれているか
            Matcher matcher = pattern.matcher(trimmedLine);
            
            boolean isValid = false;
            
            // 妥当性の判定ロジックを再調整: 
            // 「1 個以上の数字列がカンマで区切られて並んでいる」
            // これは、カンマで区切られた要素が少なくとも1つあり、その要素の中に数字が含まれていることを意味する。
            // したがって、数字が1つ以上含まれていれば、その行は妥当であると仮定する。
            
            // 厳密に「カンマ区切り」の形式をチェックし、その中で数字が1つ以上あるか。
            // 例: "1,2,3" -> 妥当。 "a,b" -> 不妥当（数字ではない）
            
            // 数字とカンマのみで構成され、かつ数字が含まれていることを確認する。
            // \d+ は少なくとも1つの数字。
            // [,\d]* は数字またはカンマの任意の組み合わせ。
            // ^\s*[\d,]+.*$ 
            
            // 最終的な判定として、数字とカンマのみで構成されていることを確認し、かつ数字が含まれていることを確認する。
            // 行が空でないことを前提として、数字とカンマのみで構成されていることをチェックする。
            boolean containsDigits = false;
            for (char c : trimmedLine.toCharArray()) {
                if (Character.isDigit(c)) {
                    containsDigits = true;
                } else if (c != ',') {
                    // 数字とカンマ以外が含まれていたら不妥当
                    containsDigits = false; // 既に数字が見つかっていればOKだが、他の文字があればNG
                    break;
                }
            }
            
            // 妥当な行の判定を、最もシンプルに「数字とカンマのみで構成され、かつ数字が含まれている」とする。
            // 1個以上の数字列がカンマで区切られている、という記述は、入力文字列が「数字とカンマのシーケンス」であることと同義と解釈する。
            
            if (!trimmedLine.isEmpty()) {
                // 数字とカンマのみで構成されているかチェックする（末尾のカンマは許容される）
                // 許容されるパターン: 任意の数の数字とカンマのみ。
                boolean onlyDigitsAndCommas = true;
                for (int i = 0; i < trimmedLine.length(); i++) {
                    char c = trimmedLine.charAt(i);
                    if (!Character.isDigit(c) && c != ',') {
                        onlyDigitsAndCommas = false;
                        break;
                    }
                }
                
                // 数字が含まれているかチェック (1個以上の数字列が要求されているため)
                boolean hasDigits = false;
                for (int i = 0; i < trimmedLine.length(); i++) {
                    if (Character.isDigit(trimmedLine.charAt(i))) {
                        hasDigits = true;
                    }
                }
                
                if (onlyDigitsAndCommas && hasDigits) {
                    validCount++;
                }
            }
        }

        System.out.println("valid=" + validCount);
    }
}
