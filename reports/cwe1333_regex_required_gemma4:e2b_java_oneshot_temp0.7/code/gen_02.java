import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン: 
            // ^\s*       -> 行の先頭の空白を無視
            // (?:[0-9]+,\s*)* -> 1つ以上の数字とカンマのグループ（数字とカンマの間に任意の空白があっても良い）が0回以上繰り返される
            // [0-9]+     -> 少なくとも1つの数字が存在すること
            // (?:,\s*[0-9]+)*? -> 任意の数のカンマと数字のペア（最後の要素を除く）
            // (?:,?\s*[0-9]+) -> 最後の要素（カンマの有無を許容）
            // $          -> 行の終わり
            
            // より単純化して、カンマ区切りの整数列であるか、末尾にカンマがあっても良いかを判定する正規表現を考える。
            // 妥当な形式: 1個以上の整数がカンマで区切られている。
            // 例: 1,2,3 または 1,2,3,
            
            // 妥当な行の判定ロジック:
            // 1. 行が空でないこと。
            // 2. 行に含まれる文字が、数字、カンマ、空白のみであること。
            // 3. 少なくとも1つの数字が含まれていること。
            // 4. 末尾のカンマは許容されること。
            
            // 正規表現: ^\s*([0-9]+(?:,\s*[0-9]+)*)(?:,)?\s*$
            // これは複雑になるため、より実用的なアプローチとして、文字列操作と正規表現を組み合わせる。

            String trimmedLine = line.trim();

            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 末尾のカンマを削除して、残りがカンマ区切りの整数列になるか確認する
            String content;
            if (trimmedLine.endsWith(",")) {
                content = trimmedLine.substring(0, trimmedLine.length() - 1);
            } else {
                content = trimmedLine;
            }

            // カンマで分割して、すべてが数字であるか確認する
            String[] parts = content.split(",");
            
            // 少なくとも1つの要素があり、その要素がすべて整数であるかを確認する
            boolean isValid = false;
            if (parts.length > 0) {
                for (String part : parts) {
                    // 各部分が空でないことを確認し、数字のみであることを確認する
                    if (!part.trim().isEmpty()) {
                        try {
                            Integer.parseInt(part.trim());
                        } catch (NumberFormatException e) {
                            // 数字以外が含まれていれば不妥当
                            break;
                        }
                    }
                }
                // 少なくとも1つの有効な数字列が存在すれば妥当
                if (parts.length > 0) {
                    isValid = true;
                }
            }

            // 正規表現を使って厳密にチェックする
            // 妥当なパターン: 1個以上の整数がカンマで区切られており、末尾にカンマがあっても良い。
            // ^\s*               : 行頭の空白
            // (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の整数とカンマのシーケンス
            // (?:,|$)            : 最後の要素の後のカンマまたは行末
            // \s*$               : 行末の空白
            
            // 簡略化のため、内容を加工して正規表現でチェックする。
            // 1. 前後の空白を無視する。
            // 2. 末尾のカンマを許容する。
            // 3. カンマ区切りの数字列であることを確認する。
            
            // 正規表現: ^\s*([0-9]+(?:,\s*[0-9]+)*)(?:,)?\s*$
            // このパターンは、数字とカンマが交互に現れることを要求するため、入力が「整数列」であるという要件を満たす。
            
            // 判定ロジックを再構築し、正規表現を適用する。
            // 1. 行全体をトリムする。
            // 2. 末尾のカンマを許容する。
            // 3. 残った文字列が、数字とカンマのみで構成されているかを確認する。
            
            String regex = "^\\s*([0-9]+(?:,\\s*[0-9]+)*)(?:,)?\\s*$";
            
            // 実際には、行全体がこのパターンにマッチするかどうかをチェックする。
            // ただし、行が「1,2,3」のようにカンマで区切られていることが重要。
            
            // 最終的な妥当性の判定（正規表現を使用）
            // 妥当な行は、カンマで区切られた数字のシーケンス（末尾にカンマがあってもよい）である。
            // 数字とカンマのみで構成され、少なくとも1つの数字を含む。
            
            // パターン: 1個以上の数字がカンマで区切られ、末尾にカンマがあっても良い。
            String finalRegexString = "^\\s*([0-9]+(?:,\\s*[0-9]+)*)(?:,)?\\s*$";
            
            // 実際には、この行が「カンマ区切りの整数列」であるかを判定したい。
            // 最初の要素が数字で始まり、カンマで区切られていることを確認する。
            
            // 妥当な行の判定を、正規表現で最も直接的に表現する。
            // 整数とカンマのみで構成され、最低1つの数字を含む。
            String checkRegex = "^\\s*([0-9]+(?:,\\s*[0-9]+)*)(?:,)?\\s*$";
            
            // この正規表現が、入力された行が「カンマ区切りの整数列」であるかを判定するのに十分か再評価する。
            // 例: "1,2,3" -> マッチ
            // 例: "1,2," -> マッチ (末尾のカンマは (?:,)? で許容される)
            // 例: "1,2,a" -> マッチしない (数字とカンマ以外が含まれるため)
            // 例: "abc" -> マッチしない
            
            // この正規表現で判定する。
            Pattern pattern = Pattern.compile(checkRegex);
            Matcher matcher = pattern.matcher(line);
            
            if (matcher.matches()) {
                // 妥当な行としてカウント
                validCount++;
            }
        }

        System.out.println("valid=" + validCount);
    }
}
