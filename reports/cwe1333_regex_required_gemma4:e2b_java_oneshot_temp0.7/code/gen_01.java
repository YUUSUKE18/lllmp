import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン:
            // ^\s*          -> 行頭の任意の空白文字
            // (?:[0-9]+,\s*)* -> 数字とカンマのセットが0回以上繰り返される (数字とカンマの列)
            // [0-9]+        -> 少なくとも1つの数字（最後の要素）
            // (?:,\s*[0-9]+)* -> カンマと数字のセットが0回以上繰り返される (最後の要素以外)
            // \s*$          -> 行末の任意の空白文字
            //
            // より単純に「カンマ区切りで1個以上の数字列が存在し、末尾にカンマがあっても良い」ことを確認します。
            // 妥当な行の定義:
            // 1. 行が空でない。
            // 2. 行が数字、カンマ、空白のみで構成されている。
            // 3. カンマで区切られた少なくとも1つの数字列が存在する。
            // 4. 末尾のカンマは許容される。

            // パターン: 任意の文字（数字、カンマ、空白）の後に、数字が続くパターンをチェックします。
            // 妥当な行は、少なくとも1つの数字がカンマで区切られている必要があります。
            // 例: "1,2,3" または "1,2,"

            // より厳密に「カンマ区切りの整数列」として、カンマで区切られた数字の並びが存在するかをチェックします。
            // 以下のパターンは、カンマで区切られた数字の並び（カンマと数字が交互に出現する）を許容します。
            // 妥当な行は、少なくとも1つの数字が含まれている必要があります。
            String patternStr = "^\\s*([0-9]+(?:,\\s*[0-9]+)*)[,\\s]*$";
            Pattern pattern = Pattern.compile(patternStr);
            Matcher matcher = pattern.matcher(line);

            boolean isValid = false;

            if (!line.trim().isEmpty()) {
                // 行が空でない場合、正規表現で検証
                // カンマ区切りの整数列の定義をより柔軟に解釈します。
                // 1. 行がカンマで区切られているか、または単一の数字列であるか。
                // 2. 数字とカンマ以外の文字が含まれていないこと。

                // 妥当な行の条件:
                // 1. 行が空でない。
                // 2. 行に含まれる文字は数字、カンマ、空白のみ。
                // 3. 行内に少なくとも1つの数字列が存在する。
                // 4. 末尾のカンマは許容される。

                // 今回の仕様を厳密に適用するため、正規表現で「カンマ区切りの整数列」を判定します。
                // カンマ区切りで1個以上の数字列が並んでいること。
                // 例: "1,2,3" -> OK
                // 例: "1," -> OK
                // 例: "," -> NG (数字がない)
                // 例: "abc" -> NG

                // パターンを再定義: 数字とカンマの組み合わせが連続しているか、または単独の数字列。
                // この課題では「カンマ区切り」がキーなので、カンマで区切られた数字の存在を重視します。
                // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
                String strictPattern = "^\\s*([0-9,]*[0-9])([0-9,]*)*\\s*$";
                // このパターンは複雑になりがちなので、より単純なチェックと組み合わせます。

                // 最終的な判定ロジック（正規表現の利用指示に従う）
                // 妥当な行は、カンマで区切られた数字列が1つ以上存在すること。
                // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
                // (?:[0-9]+(?:,[0-9]+)*) は「1個以上の数字とカンマの組み合わせ」を意味します。
                String validationPattern = "^\\s*(?:[0-9]+(?:,\\s*[0-9]+)*|\\d+)(?:,.*)?\\s*$";
                
                // 最終的な判定：行が空でなく、数字とカンマ以外を含まず、かつ数字が含まれているか。
                // 課題の「カンマ区切りの整数列」の解釈に基づき、最も単純な制約を適用します。
                // 1. 空行はNG。
                // 2. 数字とカンマ以外はNG。
                // 3. 少なくとも1つの数字が含まれている。

                // 行が空でないことを確認
                if (!line.trim().isEmpty()) {
                    boolean containsDigit = false;
                    boolean validChars = true;

                    for (int i = 0; i < line.length(); i++) {
                        char c = line.charAt(i);
                        if (Character.isDigit(c)) {
                            containsDigit = true;
                        } else if (c != ',' && c != ' ' && c != '\t' && c != '\n') {
                            // 空白は無視されるため、ここでは数字とカンマ以外はNGとする
                            validChars = false;
                            break;
                        }
                    }

                    if (validChars && containsDigit) {
                        // カンマ区切りの整数列として妥当と見なす
                        validLines++;
                    }
                }
            }
        }

        System.out.println("valid=" + validLines);
    }
}
