package main

import (
	"bufio"
	"fmt"
	"os"
	"strconv"
)

func main() {
	var totalSteps int64 = 0
	scanner := bufio.NewScanner(os.Stdin)

	for scanner.Scan() {
		line := scanner.Text()
		// 空行や整数として解釈できない行を無視
		if line == "" {
			continue
		}

		n, err := strconv.ParseInt(line, 10, 64)
		if err != nil {
			continue
		}

		if n == 1 {
			// nが1のときの手数は0
			totalSteps += 0
			continue
		}

		// メモ化のためのマップ
		memo := make(map[int64]int64)

		// 繰り返し計算とメモ化
		currentN := n
		steps := int64(0)

		// 1に到達するまで繰り返す
		for currentN != 1 {
			// メモ化チェック
			if val, ok := memo[currentN]; ok {
				steps += val
				break
			}

			// 操作の適用
			if currentN%2 == 0 {
				currentN /= 2
			} else {
				currentN = 3*currentN + 1
			}
			steps++

			// メモ化の更新（再帰的なメモ化の代わりに、現在のパスでのステップ数を記録する）
			// ここでは、nから1に到達するまでの「手数」を求めるため、
			// 既に計算済みの値があればそれを利用する。
			// ただし、この問題は「1に到達するまでの手数」を求めるため、
			// サイクル検出（または到達）を考慮する必要がある。
			// 1に到達するまでの経路を追跡するのではなく、
			// 既に計算済みの値からの遷移を考える方が効率的。

			// 簡略化のため、ここでは再帰的なメモ化（または動的計画法）の構造を模倣する。
			// 1に到達するまでの手数を求める問題は、通常、nが3n+1操作で1に到達するまでのステップ数を求める問題（Collatz Conjecture）と関連する。
			// ここでは、各クエリ n について、n から 1 に到達するまでのステップ数を計算する。

			// 再帰的なメモ化（DFS/DP）を採用する。
			// 既に計算済みの値があれば、その結果を現在のステップに加算する。
			// サイクル検出のために、現在のパスを追跡する必要がある。

			// サイクル検出のためのセット
			path := []int64{currentN}
			visitedInPath := make(map[int64]bool)
			visitedInPath[currentN] = true
			
			// サイクルが検出された場合の処理（この問題では1に到達することが保証されると仮定するが、念のため）
			// サイクル検出は、特定のクエリ n に対する計算を最適化するために必要。
			// ここでは、nから1への最短経路を求めるため、到達した時点でメモ化する。

			// 簡略化：各クエリ n について、nから1への経路を計算し、その過程でメモ化する。
			// 既に計算済みの値があれば、その結果を足し合わせる。
			
			// サイクル検出を導入し、到達した値が既に計算済みか確認する。
			if _, ok := memo[currentN]; ok {
				// 既に計算済みなら、その結果を足し合わせる
				// ただし、これは「nから1への手数」を求める問題なので、
				// 既に計算済みの値が「1からnへの手数」である場合、逆の操作が必要になる。
				// ここでは、nから1への手数を直接計算する。
				
				// サイクル検出が複雑になるため、ここでは単純に到達するまで計算し、
				// 途中で同じ値に戻ってきたらサイクルと見なす（ただし、Collatz問題では1に収束するとされる）。
			}
			
			// サイクルが検出された場合（この問題設定では通常発生しないが、安全のため）
			// サイクル内の値は、そのサイクルを抜けるためのステップ数を計算する。
			// 今回は、1に到達することを前提とし、単純なメモ化を行う。
			
			// サイクル検出を厳密に行うために、現在のパスをチェックする。
			isCycle := false
			for _, pVal := range path {
				if pVal == currentN {
					isCycle = true
					break
				}
			}
			if isCycle {
				// サイクル内の値は、そのサイクルを抜けるためのステップ数を計算する必要がある。
				// この問題の制約上、これは通常発生しないため、ここでは無視し、計算を続行する。
				// 厳密な最適化のためには、サイクル内の値を処理する必要があるが、
				// 標準的なCollatz問題の文脈では、これは通常「1に到達する」ことを意味する。
			}
			
			// メモ化の更新（到達した時点で記録）
			memo[n] = steps
			break // 1に到達したのでループを抜ける
		}

		// 最終的なステップ数を合計に加算
		if steps > 0 {
			totalSteps += steps
		}
	}

	fmt.Printf("total=%d\n", totalSteps)
}
