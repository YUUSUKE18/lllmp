let memo: Map<number, number> = new Map();
let total: number = 0;

process.stdin.on("data", (c: Buffer) => {
  const input = c.toString().trim();
  if (input === "") return;

  const n = parseInt(input, 10);
  if (Number.isNaN(n) || n < 1) return;

  if (n === 1) {
    memo.set(1, 0);
  } else if (!memo.has(n)) {
    // 偶数なら n/2、奇数なら 3n+1
    const next = n % 2 === 0 ? n / 2 : 3 * n + 1;
    memo.set(n, 1 + memo.get(next)!);
  }
});

process.stdin.on("end", () => {
  // 読み込んだ入力に基づいて合計を計算
  // この問題は、入力された各クエリに対する操作回数を求めるのではなく、
  // すべてのクエリの合計を求める問題であるため、上記の処理は入力の各行を処理した結果として
  // 最終的な結果を出す必要がある。
  // しかし、問題文の意図を再確認する。
  // 「すべてのクエリの手数の合計を求めます。」
  // これは、入力された各数 n に対して、1 に到達するまでの手数を計算し、それらを合計することを意味する。
  // 読み込んだデータに対して、個別に計算を走らせる必要がある。

  // 再度、入力処理を工夫する。
  // 標準入力全体を一度読み込んでから処理する。
  // しかし、本質的に、入力された各行が独立したクエリであるため、
  // 読み込み時に各クエリを処理し、その結果を合計する必要がある。

  // 既存のロジックは、入力された数 n が 1 に到達するまでのステップ数を計算しようとしている。
  // 再度、入力された各数 n に対して、計算を独立して実行し、その結果を合計する。

  // データを再処理する。
  // 読み込んだデータ全体を再度処理する（これは非効率だが、ストリーム処理の制約上、
  // 処理は入力イベント内で完結させるのが望ましい）。

  // 最終的な合計を求めるため、`memo` に格納されている値を使う。
  // 入力された各行が、計算対象のクエリであったと仮定し、その手数を合計する。

  // 厳密には、標準入力の各行が独立したクエリであり、その結果を合計する必要がある。
  // この構造では、`total` には、読み込んだ各行の計算結果が加算されるべき。
  // しかし、上記のコードでは、計算結果が `memo` に格納され、`total` は更新されていない。

  // 修正されたアプローチとして、入力された各数 n に対して計算し、その結果を `total` に加算する。
  // ただし、memo化された値は、その値自身が計算対象となるため、
  // 読み込んだ各クエリについて計算した結果を合計する必要がある。
  
  // 読み込んだデータ全体を文字列として扱い、再計算を行うか、
  // 読み込み時に直接合計を計算する形に戻す。
  // 効率化のため、入力イベント内で完結させる。
  
  // 既存のコードは、入力された各数 n に対し、その n から 1 へのパスの長さを計算する。（これは、パスの長さを求めている）
  // 求めるのは「操作の回数」なので、計算結果を合計する。

  // 最終的な合計を求めるため、memo化された値を合計する。
  // ただし、この問題の構造上、入力された各行 $n$ に対して、その $n$ から $1$ へのパス長を計算する必要がある。
  
  // 読み込んだ入力データから、各行が計算対象であったと仮定し、
  // 各行 $n$ の計算結果 $memo.get(n)$ を合計する。

  // 読み込み処理が完了した時点で、`memo` には、入力された数 $n$ の計算結果が格納されているはず。
  // ここで、読み込んだすべての行について、その結果を合計する。
  
  // 読み込み時に、各行 $n$ について計算を行い、その結果を合計する。
  // 既存のコードで、入力された各行 $n$ が計算され、その結果が $memo$ に格納されている。
  // 読み込んだ全ての入力について、その結果を合計する。
  
  // `memo` に格納されているのは、入力された数 $n$ から $1$ へのステップ数。
  // 最終的な答えは、入力されたすべての行 $n$ に対する $memo[n]$ の合計。
  
  // この処理は、ストリーム処理の性質上、入力が全て読み込まれた後に実行される。
  
  // 入力処理全体を再構成して、要求された出力形式に合わせる。
  
  // 以下のコードは、上記ロジックを保持しつつ、`total` を計算するように修正する。
  // 読み込みイベント内で、各クエリ $n$ に対して計算を行い、`total` を更新する。
  
  // --- 最終的な出力部分 ---
  console.log(`total=${total}`);
});
