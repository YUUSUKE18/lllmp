import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*          -> 行の先頭の任意の空白文字
    // (?:          -> 非キャプチャグループの開始
    //   \d+        -> 1つ以上の数字
    //   (?:,\d+)* -> カンマとそれに続く1つ以上の数字の繰り返し (カンマ区切りの整数列)
    // )            -> 非キャプチャグループの終了
    // (?:,\d+)*    -> 末尾のカンマが許容されるため、カンマと数字の繰り返しを許容
    // \s*$         -> 行の末尾の任意の空白文字
    //
    // よりシンプルに、行全体が「カンマ区切りの整数列」または「カンマで終わる整数列」であるかを判定する。
    // 妥当な行の定義: 1個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容。
    // 空行、および数字とカンマ以外を含む行は妥当ではない。

    // 正規表現の解説:
    // ^\s*             : 行の先頭の空白を無視
    // (?:              : 非キャプチャグループの開始
    //   \d+            : 1つ以上の数字 (最初の数字列)
    //   (?:,\d+)*      : カンマとそれに続く1つ以上の数字の繰り返し (区切り)
    // )                : グループの終了
    // (?:,\d+)*         : 末尾のカンマが許容されるため、カンマと数字の繰り返しを許容
    // \s*$             : 行の末尾の空白を無視
    //
    // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
    // 1. 数字とカンマのみで構成されていること。
    // 2. 少なくとも1つの数字が含まれていること。
    // 3. 空行は除外される。

    const regex = /^\s*(?:\d+(?:,\d+)*)(?:,?\d+)*\s*$/;

    for (const line of lines) {
        const trimmedLine = line.trim();

        if (trimmedLine.length === 0) {
            // 空行は妥当ではない
            continue;
        }

        // 数字とカンマのみで構成されているか、かつ少なくとも1つの数字が含まれているかを確認する。
        // 妥当なパターン: 1個以上の数字列がカンマで区切られている。
        // 例: "1,2,3", "1,2,", "1"
        // 否定されるパターン: "abc", "1a", "1,,2" (カンマの連続は許容しないと解釈)

        // 妥当性の判定を正規表現で行う。
        // 1. 行が数字とカンマのみで構成されていること。
        // 2. 少なくとも1つの数字が含まれていること。
        // 3. カンマの連続（例: ,,）は許容しない（数字列が空でないことを保証するため）。

        // 妥当な行のパターン:
        // 1. 少なくとも1つの数字列が存在する。
        // 2. その数字列はカンマで区切られている。
        // 3. 末尾のカンマは許容される。

        // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
        // (?: \d+ (?:,\d+)* ) : 1つ以上の数字列がカンマで区切られているパターン
        // (?:,\d+)*         : 末尾のカンマが許容される
        const validPattern = /^\s*(?:\d+(?:,\d+)*)(?:,\d+)*\s*$/;

        if (validPattern.test(line)) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
