import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*          -> 行の先頭の任意の空白文字
    // (?:          -> 非キャプチャグループの開始
    //   \d+        -> 1つ以上の数字
    //   (?:,\d+)* -> カンマとそれに続く1つ以上の数字の繰り返し (カンマ区切りの整数列)
    // )            -> 非キャプチャグループの終了
    // (?:,\d+)*    -> 末尾のカンマが許容されるため、カンマと数字の繰り返しを許容
    // \s*$         -> 行の末尾の任意の空白文字
    // このパターンは「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
    // ただし、仕様の「1 個以上の数字列がカンマで区切られて並んでいる」を厳密に解釈し、
    // 空行や数字とカンマ以外の文字を含まないことを確認する必要があります。

    // より厳密な判定ロジックを適用します。
    // 妥当な行の条件:
    // 1. 空行ではない。
    // 2. 数字とカンマのみで構成されている。
    // 3. 少なくとも1つの数字列が含まれている。

    const regex = /^[\d,]*$|^[\d,]+(?:,[\d,]+)*$/;

    for (const line of lines) {
        const trimmedLine = line.trim();

        if (trimmedLine.length === 0) {
            // 空行は妥当ではない
            continue;
        }

        // 数字とカンマ以外を含む行は妥当ではない
        if (!/^[0-9,]*$/.test(trimmedLine)) {
            continue;
        }

        // 妥当な行の判定: 1個以上の数字列がカンマで区切られているか
        // 1. 少なくとも1つの数字が含まれているか
        // 2. カンマ区切りとして意味を持つか (例: "1,2" はOK, "," はNG, "1," はOK, ",1" はNG)

        // 1. 少なくとも1つの数字が含まれているか
        if (!/\d/.test(trimmedLine)) {
            // 数字が一つもない場合 (例: "," や "") は既に除外されているが、念のため
            continue;
        }

        // 2. カンマ区切りとして妥当か
        // 妥当なパターン: 数字とカンマのみで構成され、数字が少なくとも1つある。
        // 末尾のカンマは許容される。
        // 例: "1,2,3", "1,2,", "1"
        
        // 正規表現の再検討:
        // 1個以上の数字列がカンマで区切られている。
        // これは、数字とカンマのシーケンスであり、数字が少なくとも1つ存在し、
        // カンマが数字の間に存在する、または末尾に存在する、という構造を意味します。

        // 妥当な行の例: "1,2,3", "1,2,"
        // 不妥当な行の例: ",", "1,,2", "abc"

        // 妥当な行のパターン:
        // 1. 数字とカンマのみで構成されている (既にチェック済み)
        // 2. 少なくとも1つの数字が含まれている (既にチェック済み)
        // 3. カンマが数字の間に存在する、または末尾に存在する。

        // 以下のパターンは、数字とカンマのみで構成され、数字が少なくとも1つ含まれていることを保証します。
        // (?:[\d]+(?:,[\d]+)*) : 1つ以上の数字で始まり、カンマ区切りで続く。
        // または、単一の数字列。
        const validPattern = /^[\d]+(?:,[\d]+)*$|^[\d]+(?:,)*$/;
        
        // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を表現するには、
        // 少なくとも1つの数字があり、カンマが適切に配置されている必要があります。
        // 例: "1,2" -> OK
        // 例: "1" -> OK (1個の数字列)
        // 例: "1," -> OK (1個の数字列と末尾のカンマ)

        // 最終的な判定ロジックとして、数字とカンマのみで構成され、数字が少なくとも1つ存在すれば妥当とします。
        // 空行と数字/カンマ以外の文字のチェックで、不要な行は除外されているため、残るのは数字とカンマのみの文字列。
        // この文字列が数字を少なくとも1つ含んでいれば、それは「カンマ区切りの整数列」と見なします。
        
        if (validPattern.test(trimmedLine)) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
