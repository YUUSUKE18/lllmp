import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*          -> 行の先頭の任意の空白文字
    // (?:          -> 非キャプチャグループの開始
    //   \d+        -> 1つ以上の数字
    //   (?:,\d+)* -> カンマとそれに続く1つ以上の数字の繰り返し (カンマ区切りの整数列)
    // )            -> 非キャプチャグループの終了
    // (?:,\d+)*    -> 末尾のカンマが許容されるため、カンマと数字の繰り返しを許容
    // \s*$         -> 行の末尾の任意の空白文字
    // このパターンは「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
    // 厳密には、空行や数字とカンマ以外の文字を含まないことを確認する必要があります。

    // より厳密な判定ロジックを適用します。
    // 妥当な行の条件:
    // 1. 空行ではない。
    // 2. 数字とカンマのみで構成されている。
    // 3. 少なくとも1つの数字列が含まれている。

    for (const line of lines) {
        const trimmedLine = line.trim();

        if (trimmedLine.length === 0) {
            // 空行は妥当ではない
            continue;
        }

        // 正規表現による判定:
        // ^\s*             -> 行の先頭の空白
        // (?:             -> グループ開始
        //   \d+           -> 1つ以上の数字 (最初の数字列)
        //   (?:,\d+)*     -> カンマとそれに続く数字の繰り返し (区切り)
        // )               -> グループ終了
        // (?:,\d+)*       -> 末尾のカンマが許容されるため、カンマと数字の繰り返しを許容
        // \s*$            -> 行の末尾の空白
        
        // 妥当な行は、数字とカンマのみで構成され、少なくとも1つの数字列を含む。
        // 以下のパターンは、「数字とカンマのみ」で構成され、かつ「少なくとも1つの数字」を含むことを確認します。
        // (?:(?:\d+(?:,\d+)*))  -> 1つ以上の数字列 (カンマ区切り)
        // (?:,\d+)*            -> その後にカンマと数字が続く (末尾のカンマ許容)
        // ^\s* ... $         -> 行全体がこれにマッチすること
        
        // 簡略化のため、行が数字とカンマのみで構成されているかを確認し、
        // その後、少なくとも1つの数字が含まれているかを確認します。

        // 1. 数字とカンマのみで構成されているかチェック
        const containsOnlyDigitsAndCommas = /^[0-9,]*$/.test(trimmedLine);

        if (!containsOnlyDigitsAndCommas) {
            // 数字とカンマ以外の文字を含む行は妥当ではない
            continue;
        }

        // 2. 少なくとも1つの数字列が含まれているかチェック
        // 数字列が存在しない場合（例: "," や ",," など）、これは妥当ではない。
        // 少なくとも1つの数字が含まれているかを確認するために、数字が存在するかチェックする。
        const containsAtLeastOneDigit = /\d/.test(trimmedLine);

        if (containsAtLeastOneDigit) {
            // 1個以上の数字列がカンマで区切られている（またはそのように見なせる）
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
