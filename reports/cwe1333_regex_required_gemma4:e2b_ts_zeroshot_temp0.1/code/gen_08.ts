import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*          -> 行の先頭の任意の空白文字
    // (?:          -> 非キャプチャグループの開始
    //   \d+        -> 1つ以上の数字
    //   (?:,\d+)* -> カンマとそれに続く1つ以上の数字の繰り返し (カンマ区切りの整数列)
    // )            -> 非キャプチャグループの終了
    // (?:,\d+)*    -> 末尾のカンマが許容されるため、カンマと数字の繰り返しを許容
    // \s*$         -> 行の末尾の任意の空白文字
    // この正規表現は「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
    // 厳密には「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
    // 少なくとも一つの数字列が存在し、カンマ区切りである必要があります。

    // よりシンプルに、行が空でないこと、かつ数字とカンマのみで構成されていることを確認し、
    // 少なくとも1つの数字が含まれていることを確認します。

    // 仕様の再解釈: 「1 個以上の数字列がカンマで区切られて並んでいること」
    // これは、カンマで区切られた数字のシーケンスが存在することを意味します。
    // 例: "1,2,3" (OK), "1," (OK, 末尾カンマ許容), "," (NG), "" (NG)

    const regex = /^(?:(?:\d+(?:,\d+)*)|(?:\d+)(?:,\d+)*).*$/;

    for (const line of lines) {
        const trimmedLine = line.trim();

        if (trimmedLine.length === 0) {
            // 空行は妥当ではない
            continue;
        }

        // 数字とカンマ以外を含む行は妥当ではない
        // このチェックは正規表現でカバーされるべきだが、念のため確認
        if (!/^[0-9,]*$/.test(trimmedLine)) {
            continue;
        }

        // 妥当性の判定: 1個以上の数字列がカンマで区切られているか
        // 1. 少なくとも1つの数字が含まれているか
        // 2. カンマ区切りであるか (これは、数字とカンマのみで構成されていることと、数字が連続していることを意味する)

        // 1. 少なくとも1つの数字が含まれているか
        if (!/\d/.test(trimmedLine)) {
            continue;
        }

        // 2. カンマ区切りであるか (数字とカンマのみで構成されていることを確認)
        // 既に /^[0-9,]*$/ で確認済み。
        // 1個以上の数字列がカンマで区切られている、という条件を満たすためには、
        // 少なくとも1つの数字があり、カンマが適切に配置されている必要があります。

        // 以下の正規表現は、数字とカンマのみで構成され、かつ少なくとも1つの数字を含むことを確認します。
        // (?: \d+ (?:,\d+)* ) : 1つ以上の数字列がカンマで区切られているパターン
        // (?: \d+ )         : 最後の要素が数字であるパターン
        // (?: \d+(?:,\d+)* )* : 0回以上の区切り
        // (?:,\d+)?         : 末尾のカンマの有無
        const fullRegex = /^((?:\d+(?:,\d+)*)(?:,\d+)*)?.*$/;

        // 仕様の「1 個以上の数字列がカンマで区切られて並んでいる」を最も厳密に解釈すると、
        // 少なくとも1つの数字が存在し、カンマで区切られている必要があります。
        // 例: "1" (OK), "1,2" (OK), "1," (OK)
        // 例: "," (NG), "" (NG)

        // 1. 数字とカンマのみで構成されているか (既にチェック済み)
        // 2. 少なくとも1つの数字が含まれているか (既にチェック済み)

        // 3. 妥当な形式であるか (カンマ区切りであること)
        // 以下のパターンは、数字とカンマのみで構成され、かつ少なくとも1つの数字を含むことを保証します。
        // (?: \d+(?:,\d+)* ) : 1つ以上の数字列がカンマで区切られているパターン
        // (?:,\d+)?         : 末尾のカンマの有無
        const validPattern = /^[\d,]+$/; // 数字とカンマのみで構成されていることを確認

        // 最終的な妥当性の判定:
        // 1. 空行でない
        // 2. 数字とカンマ以外を含まない
        // 3. 少なくとも1つの数字を含む
        // 4. カンマ区切りである（これは、数字とカンマのみで構成され、数字が存在すれば満たされる）

        // 既に上記でチェックした内容を統合し、最もシンプルな判定を行う。
        // 妥当な行は、数字とカンマのみで構成され、かつ数字が1つ以上含まれている行。
        if (validPattern.test(trimmedLine) && /\d/.test(trimmedLine)) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
