import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*          -> 行の先頭の任意の空白文字
    // (?:          -> 非キャプチャグループの開始
    //   \d+        -> 1つ以上の数字
    //   (?:,\d+)* -> カンマと1つ以上の数字の繰り返し（カンマ区切りの数字列）
    // )            -> 非キャプチャグループの終了
    // \s*$         -> 行末の任意の空白文字
    // このパターンは、カンマ区切りの整数列が1つ以上存在することをチェックします。
    // 末尾のカンマも許容するため、行全体が数字とカンマのみで構成されていることを確認します。
    // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
    // 行が空でないこと、および数字とカンマのみで構成されていることを確認します。

    // 仕様の再解釈に基づき、各行を個別にチェックします。
    // 妥当とは、「1 個以上の数字列がカンマで区切られて並んでいること」です。
    // 空行は妥当ではない。数字とカンマ以外は妥当ではない。

    for (const line of lines) {
        const trimmedLine = line.trim();

        if (trimmedLine.length === 0) {
            // 空行は妥当ではない
            continue;
        }

        // 正規表現の適用:
        // ^\s*             -> 行の先頭の空白
        // (?:              -> 非キャプチャグループ
        //   \d+            -> 1つ以上の数字 (最初の数字列)
        //   (?:,\d+)*      -> カンマとそれに続く数字の繰り返し (2つ目以降の数字列)
        // )                -> グループの終了
        // (?:,\d+)?        -> 最後の数字列の後にカンマが続く場合を許容するため、オプション
        // \d+              -> 少なくとも1つの数字が存在すること
        // .*               -> 残りの文字（末尾のカンマなど）
        // $                -> 行末

        // よりシンプルなチェック: 行が数字とカンマのみで構成されており、少なくとも1つの数字が含まれているか。
        // 妥当なパターン: 1個以上の数字列がカンマで区切られている。
        // 例: "1,2,3", "1,2,", "1"
        // 不妥当な例: "", "a,b", "1,,2" (連続カンマは許容しないと解釈)

        // 1. 数字とカンマのみで構成されているか？
        const regex = /^[\d,]*$/;
        if (!regex.test(trimmedLine)) {
            // 数字とカンマ以外を含む行は妥当ではない
            continue;
        }

        // 2. 1個以上の数字列がカンマで区切られているか？
        // 連続するカンマや、数字のみの行（例: "123"）も「1個以上の数字列がカンマで区切られている」と解釈できるか？
        // 仕様: 「1 個以上の数字列がカンマで区切られて並んでいることです。」
        // "123" は1つの数字列であり、カンマで区切られていない。
        // "1,2" は2つの数字列がカンマで区切られている。
        // "1," は1つの数字列と末尾のカンマ。
        // "1,,2" は連続カンマ。これは「数字列がカンマで区切られている」という構造を破綻させる。

        // 妥当なパターンを厳密に表現:
        // (数字列, カンマ, 数字列)*
        // 少なくとも1つの数字列が存在する必要がある。

        // パターン: (数字+カンマの繰り返し) または (数字のみ)
        // 妥当な行は、カンマで区切られた数字のシーケンスである。
        // 最小の妥当なパターンは「1個以上の数字」である。
        const structureRegex = /^(\d+(?:,\d+)*)(?:,*)?$/;

        // 最終的な判定ロジック:
        // 1. 空行は除外済み。
        // 2. 数字とカンマ以外は除外済み。
        // 3. 構造チェック: 少なくとも1つの数字列が存在し、カンマの配置が意味を持つこと。
        //    もし行が数字のみ（例: "123"）の場合、これは「1個の数字列」であり、「カンマで区切られている」とは言えない。
        //    しかし、仕様は「1個以上の数字列がカンマで区切られて並んでいる」なので、
        //    "123" は不適当と考えるのが自然。
        //    "1,2" -> 2つの数字列。OK。
        //    "1," -> 1つの数字列と末尾のカンマ。OK。
        //    "1,,2" -> 連続カンマ。NG。

        // 妥当な行は、少なくとも1つのカンマを含むか、またはカンマで区切られた複数の数字列であるべき。
        // 最小の妥当なパターンは、数字とカンマが混在していること。
        const validPattern = /^[\d,]+$/; // 数字とカンマのみで構成されていること (空行を除く)

        // 連続カンマや、数字のみの行を排除する。
        // 妥当な行は、数字とカンマが混在しているか、少なくとも1つのカンマが存在する。
        // 最小の妥当な行は "1," または "1,2" のような形。
        // 連続カンマや数字のみの行を排除する。
        // 妥当な行の例: "1,2", "1,2,"
        // 不妥当な行の例: "123", "", "a,b", "1,,2"

        // 連続カンマを許容しない、かつ少なくとも1つのカンマが存在することを要求する。
        const finalCheckRegex = /^[\d,]+(?=.*,|$)/; // 数字とカンマのみで構成され、かつ少なくとも1つのカンマが存在する

        // 仕様を再確認: 「1 個以上の数字列がカンマで区切られて並んでいる」
        // これは、カンマが区切りとして機能していることを意味する。
        // したがって、カンマが少なくとも1つ存在し、かつ数字が含まれている必要がある。

        // 最終的な判定: 行が空でなく、数字とカンマのみで構成され、かつカンマが含まれているか、または末尾にカンマがあること。
        // 簡略化して、カンマが存在すればOKとする。
        if (trimmedLine.includes(',') || trimmedLine.endsWith(',')) {
            // カンマが含まれている、または末尾にカンマがある場合
            // ただし、"123" は含まれない。
            if (validPattern.test(trimmedLine)) {
                validCount++;
            }
        }
    }

    // 再度、仕様に厳密に従って、行ごとに判定を修正します。
    // 妥当な行: 1個以上の数字列がカンマで区切られている。
    // これは、カンマが少なくとも1つ存在し、かつ数字が含まれていることを意味する。

    validCount = 0;
    for (const line of lines) {
        const trimmedLine = line.trim();

        if (trimmedLine.length === 0) {
            continue;
        }

        // 1. 数字とカンマ以外を含む行は妥当ではない。
        if (!/^[0-9,]*$/.test(trimmedLine)) {
            continue;
        }

        // 2. 1個以上の数字列がカンマで区切られている。
        // これは、カンマが存在し、かつ数字が存在することを意味する。
        // 連続カンマや数字のみの行は不適当。
        // 妥当な行の例: "1,2", "1,2,", "1,"
        // 不妥当な行の例: "123", "", "1,,2"

        // 少なくとも1つのカンマが存在するか、または末尾にカンマが存在するかをチェックする。
        // 厳密に「区切られている」ことを確認するため、カンマの存在を必須とする。
        if (trimmedLine.includes(',')) {
            validCount++;
        }
    }


    console.log(`valid=${validCount}`);
}

solve();
