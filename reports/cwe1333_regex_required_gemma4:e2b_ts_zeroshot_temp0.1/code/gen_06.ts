import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*          -> 行の先頭の任意の空白文字
    // (?:          -> 非キャプチャグループの開始
    //   \d+        -> 1つ以上の数字
    //   (?:,\d+)* -> カンマとそれに続く1つ以上の数字の繰り返し (カンマ区切りの整数列)
    // )            -> 非キャプチャグループの終了
    // (?:,\d+)*    -> 末尾のカンマが許容されるように、カンマと数字の繰り返しを許容
    // \s*$         -> 行の末尾の任意の空白文字
    //
    // よりシンプルに、1個以上の数字とカンマの組み合わせ、または数字のみの行を許容するパターンを考える。
    // 仕様: 1個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容。
    // 空行、および数字とカンマ以外を含む行は妥当ではない。

    // 妥当な行の判定ロジックを正規表現で定義します。
    // 1. 数字とカンマのみで構成されていること。
    // 2. 少なくとも1つの数字が含まれていること。
    // 3. 末尾のカンマは許容されること。

    // パターン解説:
    // ^\s*             : 行の先頭の空白
    // (?:              : 非キャプチャグループ開始
    //   \d+            : 1つ以上の数字 (最初の数字列)
    //   (?:,\d+)*      : カンマとそれに続く数字の繰り返し (区切り)
    // )                : グループ終了
    // (?:,\d+)*        : 末尾のカンマが許容されるように、さらにカンマと数字の繰り返しを許容
    // \s*$             : 行の末尾の空白
    //
    // このパターンは「数字とカンマのみ」という制約を満たしますが、「1個以上の数字列がカンマで区切られている」という構造をより厳密に捉える必要があります。

    // 妥当な行の定義を再評価します:
    // 妥当な行は、カンマで区切られた整数列（1個以上）で構成されている。
    // 例: "1,2,3", "1,2,", "1" (これは1個の列と見なせるか？)

    // 「1個以上の数字列がカンマで区切られて並んでいる」
    // これは、数字とカンマのみで構成され、かつ数字が少なくとも1つ含まれていることを意味します。

    // パターンA: 少なくとも1つの数字があり、数字とカンマのみで構成されている。
    // ^\s*             : 先頭の空白
    // (?:              : グループ開始
    //   \d+            : 最初の数字列
    //   (?:,\d+)*      : その後にカンマと数字が続く (0回以上)
    // )                : グループ終了
    // (?:,\d+)*        : 末尾のカンマが許容されるように、さらにカンマと数字が続く (0回以上)
    // \s*$             : 末尾の空白

    // このパターンは、"1,2,3" や "1," や "1" をカバーします。
    // ただし、空行や数字とカンマ以外の文字を含む行は除外されます。

    const validRegex = /^\s*(?:\d+(?:,\d+)*)(?:,?\d+)*\s*$/;

    for (const line of lines) {
        const trimmedLine = line.trim();

        if (trimmedLine.length === 0) {
            // 空行は妥当ではない
            continue;
        }

        // 正規表現で判定
        if (validRegex.test(line)) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
