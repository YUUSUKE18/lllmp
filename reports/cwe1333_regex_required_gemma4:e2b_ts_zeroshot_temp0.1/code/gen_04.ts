import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*          -> 行の先頭の任意の空白文字
    // (?:          -> 非キャプチャグループの開始
    //   \d+        -> 1つ以上の数字
    //   (?:,\d+)* -> カンマとそれに続く1つ以上の数字の繰り返し (カンマ区切りの整数列)
    // )            -> 非キャプチャグループの終了
    // (?:,\d+)*    -> 末尾のカンマが許容されるため、カンマと数字の繰り返しを許容
    // \s*$         -> 行の末尾の任意の空白文字
    // このパターンは「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
    // ただし、仕様の「1 個以上の数字列がカンマで区切られて並んでいる」を厳密に解釈し、
    // 空行や数字とカンマ以外の文字を含まないことを確認する必要があります。

    // より厳密な判定ロジックを適用します。
    // 妥当な行の条件:
    // 1. 空行ではない。
    // 2. 数字とカンマのみで構成されている。
    // 3. 少なくとも1つの数字列が含まれている。

    const regex = /^[\d,]*$|^[\d,]+(?:,[\d,]+)*$|^[,]*$/;

    for (const line of lines) {
        const trimmedLine = line.trim();

        if (trimmedLine === "") {
            // 空行は妥当ではない
            continue;
        }

        // 数字とカンマ以外を含む行は妥当ではない
        if (!/^[0-9,]*$/.test(trimmedLine)) {
            continue;
        }

        // 妥当性の判定: 1個以上の数字列がカンマで区切られているか
        // 1. 少なくとも1つの数字が含まれているか
        // 2. カンマの配置が意味を持つか（数字列が区切られているか）

        // 1. 数字が一つ以上含まれているか
        if (!/\d/.test(trimmedLine)) {
            // 数字が一つもない場合（例: "," や ",," など）は妥当ではない
            continue;
        }

        // 2. カンマ区切りの構造をチェック
        // 妥当なパターン: 数字とカンマのみで構成され、数字が少なくとも1つある。
        // 末尾のカンマは許容される。
        // 例: "1,2,3", "1,2,", "1"

        // 正規表現の再検討:
        // 1個以上の数字列がカンマで区切られている。
        // これは、数字とカンマのシーケンスであり、数字が少なくとも1つあることを意味します。
        // 許容されるのは、数字とカンマのみで構成され、数字が1つ以上ある場合。

        // パターン: (数字, 数字)+ の構造を許容し、末尾のカンマを許容する。
        // 最小の妥当な例: "1"
        // 妥当な例: "1,2", "1,2,3", "1,2,"
        const validPattern = /^[\d]+(?:,[\d]+)*(\s*,?)?$/;

        // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックする。
        // 1. 数字とカンマのみで構成されている (既にチェック済み)
        // 2. 少なくとも1つの数字が含まれている (既にチェック済み)
        // 3. カンマ区切り構造を満たす。

        // 以下のパターンは、数字とカンマのみで構成され、数字が1つ以上あることを保証する。
        // 末尾のカンマは許容される。
        const finalRegex = /^[\d]+(?:,[\d]+)*(\s*,?)?$/;

        if (finalRegex.test(trimmedLine)) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
