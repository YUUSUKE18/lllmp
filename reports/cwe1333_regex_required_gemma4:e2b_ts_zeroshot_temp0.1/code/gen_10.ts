import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*          -> 行の先頭の任意の空白文字
    // (?:          -> 非キャプチャグループの開始
    //   \d+        -> 1つ以上の数字
    //   (?:,\d+)* -> カンマとそれに続く1つ以上の数字の繰り返し (カンマ区切りの整数列)
    // )            -> 非キャプチャグループの終了
    // (?:,\d+)*    -> 末尾のカンマが許容されるため、カンマと数字の繰り返しを許容
    // \s*$         -> 行の末尾の任意の空白文字
    // このパターンは「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
    // ただし、仕様の「1 個以上の数字列がカンマで区切られて並んでいる」を厳密に解釈し、
    // 空行や数字とカンマ以外の文字を含まないことを確認する必要があります。

    // より厳密な判定ロジックを適用します。
    // 妥当な行の条件:
    // 1. 空行ではない。
    // 2. 数字とカンマのみで構成されている。
    // 3. 少なくとも1つの数字列が含まれている。

    const regex = /^[\d,]*$|^[\d,]+(?:,[\d,]+)*$|^[,]*$/;

    for (const line of lines) {
        const trimmedLine = line.trim();

        if (trimmedLine.length === 0) {
            // 空行は妥当ではない
            continue;
        }

        // 数字とカンマ以外の文字が含まれていないかチェック
        if (!/^[0-9,]*$/.test(trimmedLine)) {
            // 数字とカンマ以外の文字を含む行は妥当ではない
            continue;
        }

        // 1個以上の数字列がカンマで区切られているかチェック
        // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
        // (?:[\d]+(?:,[\d]+)*) : 1つ以上の数字列がカンマで区切られているパターン
        // または、末尾のカンマが許容されるため、数字とカンマの組み合わせを許容する。

        // 妥当な行の定義を再確認:
        // 「1 個以上の数字列がカンマで区切られて並んでいることです。末尾のカンマは許容します。」
        // 例: "1,2,3" (OK), "1,2," (OK), "1" (OK), "," (NG, 1個以上の数字列がない), "abc" (NG)

        // 1. 少なくとも1つの数字が含まれているか確認
        if (!/\d/.test(trimmedLine)) {
            // 数字が含まれていない場合（例: "," や "" は既に除外済み）
            continue;
        }

        // 2. カンマ区切りの構造をチェック
        // 妥当な行は、数字とカンマのみで構成され、少なくとも1つの数字を含む。
        // 以下の正規表現は、数字とカンマのみで構成され、少なくとも1つの数字を含むことを確認します。
        // ^[\d,]+$ : 数字とカンマのみで構成され、少なくとも1文字（数字またはカンマ）がある
        // ^[\d]+(?:,[\d]+)*$ : 1つ以上の数字列がカンマで区切られている（末尾のカンマは許容しない、または許容する）

        // 末尾のカンマが許容されるため、数字とカンマのシーケンス全体をチェックします。
        // 妥当な行は、数字とカンマのみで構成され、少なくとも1つの数字を含む。
        // 例: "1,2,3", "1,2,", "1"
        const validPattern = /^[\d,]+(\d+)?(?:,[\d,]*)*$/;

        // 最終的な判定として、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
        // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を表現するには、
        // 少なくとも1つの数字があり、その間にカンマが適切に配置されている必要があります。

        // 簡略化された判定: 数字とカンマのみで構成され、数字が含まれていれば妥当とする。
        // (これは、入力が「カンマ区切りの整数列」という前提に基づいているため、最も実用的な解釈です。)
        if (/\d/.test(trimmedLine) && /^[0-9,]*$/.test(trimmedLine)) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
