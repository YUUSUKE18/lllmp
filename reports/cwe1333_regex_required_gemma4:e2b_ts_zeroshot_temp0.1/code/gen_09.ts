import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*          -> 行の先頭の任意の空白文字
    // (?:          -> 非キャプチャグループの開始
    //   \d+        -> 1つ以上の数字
    //   (?:,\s*\d+)* -> カンマとそれに続く空白、そして数字の繰り返し（カンマ区切りの整数列）
    // )            -> 非キャプチャグループの終了
    // (?:,\s*\d+)* -> 末尾のカンマと数字の繰り返し（末尾のカンマも許容するため）
    // \s*$         -> 行の末尾の任意の空白文字
    // このパターンは「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
    // よりシンプルに、行が空でないこと、かつ数字とカンマのみで構成されていることを確認し、
    // 少なくとも1つの数字が含まれていることを確認します。

    // 仕様の再解釈に基づき、より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
    // 1. 空行、または数字とカンマ以外の文字を含む行は無効。
    // 2. 1個以上の数字列がカンマで区切られていること。

    // パターン: 
    // ^\s*             -> 行頭の空白
    // (?:              -> グループ開始 (非キャプチャ)
    //   \d+            -> 1つ以上の数字 (最初の数字列)
    //   (?:,\s*\d+)*   -> カンマと数字の繰り返し (2つ目以降の数字列)
    // )                -> グループ終了
    // (?:,\s*\d+)*     -> 末尾のカンマと数字の繰り返し (末尾のカンマも許容)
    // \s*$             -> 行末の空白

    const validRegex = /^\s*(?:\d+(?:,\s*\d+)*)(?:,\s*\d+)*\s*$/;

    for (const line of lines) {
        const trimmedLine = line.trim();

        if (trimmedLine.length === 0) {
            // 空行は妥当ではない
            continue;
        }

        // 数字とカンマ以外を含む行は無効
        // このチェックは正規表現でカバーされるはずだが、念のため
        if (!/^[0-9,]*$/.test(line)) {
            continue;
        }

        // 正規表現による妥当性の判定
        // 1. 少なくとも1つの数字が含まれていること (これは上記のパターンで暗黙的に満たされる)
        // 2. カンマ区切りの整数列であること
        if (validRegex.test(line)) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
