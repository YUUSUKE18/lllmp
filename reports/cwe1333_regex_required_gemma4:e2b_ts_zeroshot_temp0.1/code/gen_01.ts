import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*          -> 行の先頭の任意の空白文字
    // (?:          -> 非キャプチャグループの開始
    //   \d+        -> 1つ以上の数字
    //   (?:,\d+)* -> カンマとそれに続く1つ以上の数字の繰り返し (カンマ区切りの整数列)
    // )            -> 非キャプチャグループの終了
    // (?:,\d+)*    -> 末尾のカンマが許容されるため、カンマと数字の繰り返しを許容
    // \s*$         -> 行の末尾の任意の空白文字
    //
    // よりシンプルに、行全体が「カンマ区切りの整数列」または「カンマで終わる整数列」であるかを判定する。
    // 妥当な行の定義: 1個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容。
    // 空行、および数字とカンマ以外を含む行は妥当ではない。

    // 正規表現の解説:
    // ^\s*             : 行の先頭の空白を無視
    // (?:              : 非キャプチャグループの開始
    //   \d+            : 1つ以上の数字 (最初の数字列)
    //   (?:,\d+)*      : カンマとそれに続く数字の繰り返し (区切り)
    // )                : グループの終了
    // (?:,\d+)*         : 末尾のカンマが許容されるため、カンマと数字の繰り返しを許容
    // \s*$             : 行の末尾の空白を無視
    //
    // 実際には、行が「数字とカンマのみ」で構成されており、少なくとも1つの数字が含まれていることを確認する。
    // 妥当なパターン: 1つ以上の数字とカンマの組み合わせ。
    // 例: "1,2,3", "1,2,", "1" (これは1個の数字列と見なせるか？仕様は「1個以上の数字列がカンマで区切られて並んでいる」)

    // 仕様の再解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
    // これは、カンマで区切られた複数の数値が存在することを意味します。
    // 例: "1,2,3" -> 3つの数字列
    // 例: "1" -> 1つの数字列 (区切りがない、または区切りが0回)
    // 例: "1," -> 1つの数字列と末尾のカンマ
    // 例: "," -> 不適格 (数字列が0個)
    // 例: "abc" -> 不適格 (数字とカンマ以外を含む)

    // 妥当なパターンを厳密に定義します:
    // 1. 行が空でないこと。
    // 2. 行が数字とカンマのみで構成されていること。
    // 3. 行内に少なくとも1つの数字列が存在すること。

    // 正規表現: 少なくとも1つの数字とカンマの組み合わせが存在する。
    // (?: \d+(?:,\d+)* ) : 1つ以上の数字列と、それに続くカンマと数字の組み合わせ。
    // このパターンは、"1,2,3" や "1,2," をカバーします。
    // ただし、"1" のような単一の数字列もカバーする必要があります。

    // 妥当な行のパターン: 1つ以上の数字列がカンマで区切られている。
    // (?: \d+(?:,\d+)* ) は、カンマで区切られた複数の要素を想定しています。
    // 単一の数字列 "1" も許容されると解釈します。
    // したがって、数字とカンマのみで構成され、かつ数字が含まれている行をチェックします。

    // 妥当な行の判定ロジックを正規表現で表現します。
    // 1. 行が数字とカンマのみで構成されていること: /^[0-9,]*$/
    // 2. 行内に少なくとも1つの数字が含まれていること: /\d/

    // 組み合わせた判定:
    // 行が空でないこと、数字とカンマ以外を含まないこと、かつ数字が含まれていること。
    const validRegex = /^\s*[\d,]*\s*$/; // 数字とカンマのみ、空白のみの行を許容
    
    // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックするため、
    // 少なくとも1つの数字が含まれ、かつ数字とカンマ以外がないことを確認します。
    // 以下のパターンは、数字とカンマのみで構成され、かつ数字が含まれている行を捉えます。
    const strictValidRegex = /^\s*[\d,]+(\s*,\s*[\d,]+)*\s*$/;
    
    // 仕様の「末尾のカンマは許容」を考慮し、より柔軟に：
    // 1. 行が空でない。
    // 2. 行が数字とカンマのみで構成されている。
    // 3. 行内に少なくとも1つの数字が含まれている。
    
    // 最終的な判定ロジック（正規表現で実現）：
    // 行が空でないこと、数字とカンマ以外を含まないこと、かつ数字が含まれていること。
    // 以下のパターンは、数字とカンマのみで構成され、かつ数字が含まれている行を捉えます。
    const finalCheckRegex = /^\s*[\d,]+\s*$/;


    for (const line of lines) {
        const trimmedLine = line.trim();

        if (trimmedLine.length === 0) {
            // 空行は妥当ではない
            continue;
        }

        // 数字とカンマ以外を含む行は妥当ではない
        if (!/^[0-9,]*$/.test(trimmedLine)) {
            continue;
        }

        // 少なくとも1つの数字が含まれているかチェック
        if (!/\d/.test(trimmedLine)) {
            // カンマのみの行 (例: "," や ",," など) は妥当ではない
            continue;
        }

        // 妥当な行としてカウント
        validCount++;
    }

    console.log(`valid=${validCount}`);
}

solve();
