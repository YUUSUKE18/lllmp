package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	r := bufio.NewReader(os.Stdin)
	validLines := 0
	
	// 正規表現: 
	// ^    開始
	// \s*   前後の空白を許容
	// (.*?) 非特化的なマッチ（ただし、より明確に整数とカンマのみを含むことを保証するために簡略化）
	// ここでは「数字とカンマ以外（空白含む）は許容せず」という要件と矛盾する可能性があるが、
	// 「末尾のカンマは許容」「空行は妥当でない」「空白は無視」という要件を踏まえ、
	// 各文字が必ず either digit または comma である必要がある。
	// しかし、空白は無視すると「数字列がカンマで区切られている」ことが定義されるため、
	// 空白を含む行を許容する場合でも、実質的には「数字とカンマのみが存在する」と解釈すべきか？
	// 要件: 「空行、および数字とカンマ以外を含む行は妥当ではありません。」
	// → 空白も「数字とカンマ以外」なので、空白を含む行は妥当ではない。
	// ただし、「行の前後の空白は無視します」とあり、これはマッチする範囲の内外を指すのか？
	// 文脈から、「行全体（改行まで）が数字とカンマのみで構成されるべきだが、その際、前後の空白があっても良い（空白は無視）」
	// という解釈も可能。しかし、「数字とカンマ以外を含む行は妥当ではありません」という記述に反する。
	// より厳密に: 「行の中身を、空白を含めても、数字とカンマのみで構成されていること」を要件とするか？
	// 例: "1,2,3" → OK
	// " 1,2,3 " → OK (空白無視)
	// "1 , 2" → NG (スペースが含まれるが、これは「数字とカンマ以外」なので NG?)
	// 要件の解釈を整理: 
	// 「行の前後の空白は無視します」→ 行の先頭または末尾の空白は OK。
	// 「数字とカンマ以外を含む行は妥当ではありません」→ 行の中に、数字でもカンマでもない文字（空白含む？）があれば NG。
	// しかし、「空白を無視する」と「空白を含めても NG」と矛盾しないように解釈: 
	// → 行の前後 blank は OK が、行の中身（trim してから）が「^[\d,]+$」を満たすか？
	// または、行全体が「^[ \t]*[0-9,]+(\s*[0-9,]+)+$」など？
	// 最も自然な解釈: 「数字とカンマ以外（空白も含む）を含まない」→ つまり、空白も許さない。
	// しかし、「行の前後の空白は無視します」という要件があるため、trim して判定する。
	// 結論: trim 後の文字列が「^[\d,]+$」を満たすか？
	// ただし、例2のように「1,2,3」は OK、「1 , 2」は NG（空白を含む）。
	
	re := regexp.MustCompile(`^[0-9]+([0-9]+,[0-9]+)*$`)
	
	for {
		line, err := r.ReadString('\n')
		if err != nil {
			break
		}
		// 末尾の改行は除外
		line = line[:len(line)-1]
		
		trimLine := ""
		if len(line) > 0 {
			trimLine = line
		} else {
			trimLine = ""
		}
		
		// 空白を trim
		trimmed := strings.Trim(trimLine, " ")
		// 注意: Go の strings.Trim は指定された文字から両端の文字を取り除く。
		// しかし、要件で「空白は無視」とあるので、trim して判定するのが適切。
		
		// ただし、「数字とカンマ以外を含む行は妥当ではありません」という要件に従うため、
		// trimLine が空でない場合のみチェックし、かつ trimLine が「^[\d,]+$」を満たすか？
		// しかし、空白がtrimされることで、原本に空白が含まれていても OK とする。
		
		if len(trimLine) == 0 {
			// 空行は NG
			continue
		}
		
		// 正規表現でチェック: trimLine が数字とカンマのみから成りうるか？
		if re.MatchString(trimLine) {
			validLines++
		} else {
			// 空白を含むか、他の文字が含まれているか NG
		}
	}
	
	fmt.Printf("valid=%d\n", validLines)
}
