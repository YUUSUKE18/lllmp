package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* : 行の先頭の空白を無視
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列とカンマの組み合わせ。
	//   (?:...) は非キャプチャグループ。
	//   [0-9]+ : 1つ以上の数字
	//   (?:,\s*[0-9]+)* : カンマとそれに続く空白、そして数字の繰り返し（0回以上）
	// $ : 行の終わり
	// 末尾のカンマは許容されるため、行末にカンマがあってもマッチさせるように調整する。
	// よりシンプルに、「数字とカンマのみ」で構成されていることを確認し、空行や不正文字を排除する。

	// 仕様に基づき、以下の条件を満たす行を「妥当」と見なす。
	// 1. 空行ではない。
	// 2. 数字とカンマのみで構成されている。
	// 3. 1個以上の数字列がカンマで区切られている（カンマ区切り）。
	// 4. 末尾のカンマは許容される。

	// 正規表現の設計：
	// ^\s* : 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列がカンマで区切られているパターン。
	// (?:,\s*|\s*$) : 最後の要素の後にカンマと空白、または行末の空白。
	// この問題の核心は「1個以上の数字列がカンマで区切られている」ことと「空行や不正文字を含まない」ことです。

	// 妥当な行の判定ロジックを正規表現に依存させるため、
	// まず行を読み込み、その後に詳細なチェックを行う方が安全です。
	// ただし、仕様では「判定には正規表現を用いてください」とあるため、正規表現で可能な限り判定を試みます。

	// 妥当な行の数をカウントする
	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			continue // 空行は妥当ではない
		}

		// 正規表現による判定
		// 1. 数字とカンマ以外の文字が含まれていないか？ (数字とカンマのみ)
		// 2. 1個以上の数字列がカンマで区切られているか？
		// 3. 末尾のカンマは許容されるか？

		// パターンA: 数字とカンマのみで構成されていることを確認
		// ^[0-9,]*$ : 数字とカンマのみで構成されている
		// このパターンだけでは「1個以上の数字列が区切られている」ことを保証できない。

		// パターンB: 1個以上の数字列がカンマで区切られていることを確認
		// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列がカンマで区切られている構造
		// 末尾のカンマを許容するため、行末にカンマがあっても良い。

		// 妥当な行の判定を正規表現で行う。
		// 妥当な行は、数字とカンマのみで構成され、少なくとも1つの数字列を含む。
		// 許容されるのは、数字とカンマのシーケンスのみ。
		// 例: "1,2,3" または "1,2," または "1" または "1,"

		// 1. 数字とカンマのみで構成されていることを確認
		if regexp.MustCompile(`^[0-9,]*$`).MatchString(trimmedLine) {
			// 2. 1個以上の数字列がカンマで区切られているか？
			// これは、カンマが少なくとも1つ含まれているか、または数字のみであるか、という点で判断できる。
			// 1個以上の数字列が区切られている = カンマが1つ以上ある、または数字のみ。
			// ただし、"123" は1個の数字列であり、区切られているとは言えないが、
			// 「1個以上の数字列がカンマで区切られて並んでいる」という条件を満たすためには、
			// 少なくとも1つのカンマが存在するか、あるいは数字のみで構成されていても許容されるべきか？
			// 「1 個以上の数字列がカンマで区切られて並んでいる」 -> 区切り文字（カンマ）が存在することを意味する。

			// 妥当な例: "1,2" (2つの列)
			// 妥当な例: "1,2," (2つの列、末尾カンマあり)
			// 妥当な例: "1" (1つの列。区切られているとは言えないが、1個以上の列なのでOKとするか？)
			// 仕様：「1 個以上の数字列がカンマで区切られて並んでいることです。」
			// これは、カンマが少なくとも1つ存在することを強く示唆する。

			// カンマが存在するかどうかで判定する。
			if strings.Contains(trimmedLine, ",") {
				validCount++
			} else if regexp.MustCompile(`^[0-9]+$`).MatchString(trimmedLine) {
				// カンマがなく、数字のみの場合。これは「1個の数字列」であり、「1個以上の数字列がカンマで区切られて並んでいる」という条件を満たさない。
				// したがって、数字のみの行は妥当ではないと判断する。
			}
		}
	}

	// 最終的な出力
	fmt.Printf("valid=%d\n", validCount)
}
