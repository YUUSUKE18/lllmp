package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* は行の先頭の空白を無視
	// (?:[0-9]+(?:,\s*[0-9]+)*) は1つ以上の数字列と、その後にカンマと空白が続くパターンを繰り返す
	// (?:,\s*)* は末尾のカンマと空白が0回以上続くことを許容する
	// $ は行の終わり
	// この正規表現は「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
	// 厳密には、数字列が少なくとも1つ存在する必要があります。
	// 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字列を含むことを確認します。
	// ^\s*(?:[0-9]+(?:,\s*[0-9]+)*)(?:,)?\s*$
	// よりシンプルに、行が空でなく、数字とカンマのみで構成されていることを確認し、
	// 少なくとも1つの数字列が存在することを保証します。

	// 妥当な行の判定ロジックを正規表現で行う
	// 1. 空行や数字とカンマ以外の文字を含む行は不適格
	// 2. 1個以上の数字列がカンマで区切られていること
	// 以下の正規表現は、行が空でなく、数字とカンマのみで構成されていることを確認します。
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列と、それに続くカンマと空白の繰り返し
	// (?:,)? : 最後のカンマは任意
	// ^\s* ... \s*$ : 行全体がこのパターンに一致すること
	pattern := regexp.MustCompile(`^\s*(?:[0-9]+(?:,\s*[0-9]+)*)(?:,)?\s*$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 数字とカンマ以外の文字が含まれていないかチェック
		// このチェックは正規表現のパターンに依存しますが、念のため確認します。
		// 正規表現がマッチすれば、数字とカンマのみで構成されていることが保証されます。

		if pattern.MatchString(line) {
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
