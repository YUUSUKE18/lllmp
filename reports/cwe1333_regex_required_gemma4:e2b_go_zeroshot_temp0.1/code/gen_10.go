package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* : 行の先頭の空白を無視
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列とカンマの組み合わせ。
	//   (?:...) は非キャプチャグループ。
	//   [0-9]+ : 1つ以上の数字
	//   (?:,\s*[0-9]+)* : カンマとそれに続く空白、そして数字の繰り返し（0回以上）
	// $ : 行の終わり
	// 末尾のカンマは許容されるため、行末にカンマがあってもマッチさせるように調整する。
	// よりシンプルに、「数字とカンマのみ」で構成されていることを確認し、空行や不正文字を排除する。

	// 仕様に基づき、行が「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
	// これは、数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれていることを意味する。
	// 末尾のカンマは許容される。

	// 正規表現の設計:
	// ^\s* : 行頭の空白を無視
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列がカンマで区切られているパターン。
	//   - [0-9]+ : 最初の数字列
	//   - (?:,\s*[0-9]+)* : その後にカンマと数字が0回以上続く
	// このパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを保証する。
	// 末尾のカンマが許容されるため、行末にカンマがあってもマッチする。
	pattern := regexp.MustCompile(`^\s*(?:[0-9]+(?:,\s*[0-9]+)*)(?:,*)?$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現で判定
		if pattern.MatchString(line) {
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常、この問題では無視されることが多いが、堅牢性のために残す）
	}

	// 結果の出力
	fmt.Printf("valid=%d\n", validCount)
}
