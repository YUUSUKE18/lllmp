package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* は行の先頭の空白を無視
	// (?:[0-9]+(?:,\s*[0-9]+)*) は、1つ以上の数字列と、その後にカンマと空白が続くパターンを繰り返す
	// (?:,\s*)* は、末尾のカンマと空白が0回以上繰り返されることを許容する
	// $ は行の終わり
	// この正規表現は、少なくとも1つの数字列が存在し、カンマ区切りで構成されていることを確認します。
	// 厳密には「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する必要があります。
	// 以下の正規表現は、少なくとも1つの数字列が存在し、カンマで区切られていることを確認します。
	// 1個以上の数字列がカンマで区切られていることを確認するため、
	// 少なくとも一つの数字列が存在し、その間にカンマと空白がある、または末尾にカンマがあるパターンを許容します。

	// 妥当な行の判定ロジックを正規表現で実現します。
	// 1. 空行や数字とカンマ以外の文字を含む行は不適。
	// 2. 1個以上の数字列がカンマで区切られていること。

	// 許容されるパターン:
	// 数字列 (1個以上) と カンマと空白の組み合わせ。末尾のカンマは許容。
	// 例: 1,2,3, または 1,2,3,
	// 数字列は [0-9]+
	// カンマと空白は ,\s*
	// 少なくとも1つの数字列が存在することを保証するため、全体をグループ化します。

	// 妥当な行のパターン:
	// ^\s*                                 // 行頭の空白を無視
	// (?:[0-9]+(?:,\s*[0-9]+)*)             // 1つ以上の数字列と、それに続くカンマと空白の繰り返し
	// (?:,\s*$)                            // 末尾にカンマと空白が0回以上続くことを許容 (末尾のカンマ許容)
	//
	// よりシンプルに、数字とカンマのみで構成され、少なくとも1つの数字列があることを確認します。
	// 1個以上の数字列がカンマで区切られていることを確認する正規表現:
	// ^\s*                                 // 行頭の空白を無視
	// (?:[0-9]+(?:,\s*[0-9]+)*)             // 少なくとも1つの数字列と、それに続くカンマと空白の繰り返し
	// (?:,\s*)*                            // 末尾のカンマと空白が0回以上続くことを許容
	// $                                    // 行末
	//
	// このパターンは、数字列が少なくとも1つ存在し、カンマ区切りで構成されていることを確認します。
	// ただし、空行は除外する必要があります。

	// 空行の判定と、数字とカンマ以外の文字の判定を別途行う方が安全です。
	// 正規表現で「数字とカンマのみ」をチェックし、空行を別途チェックします。

	// 妥当な行の判定（数字とカンマのみで構成され、空行でないこと）
	// 1. 行が空でないこと: ^\s*.*$ (これは常に真なので、次の条件で絞る)
	// 2. 数字とカンマのみで構成されていること: ^\s*[\d,]*\s*$
	// 3. 少なくとも1つの数字列が存在すること: 少なくとも1つの [0-9]+ が存在すること。

	// 妥当な行の判定に特化した正規表現:
	// 少なくとも1つの数字列が存在し、それ以外に数字やカンマ以外の文字がないこと。
	// 1個以上の数字列がカンマで区切られていることを確認します。
	// (?:[0-9]+(?:,\s*[0-9]+)*) は、少なくとも1つの数字列が存在することを保証します。
	// 末尾のカンマは許容されます。

	// 妥当な行のパターン:
	// ^\s*                                 // 行頭の空白を無視
	// (?:[0-9]+(?:,\s*[0-9]+)*)             // 少なくとも1つの数字列と、それに続くカンマと空白の繰り返し
	// (?:,\s*)*                            // 末尾のカンマと空白が0回以上続くことを許容
	// $                                    // 行末

	// このパターンは、数字列が1つ以上存在し、カンマ区切りで構成されていることを確認します。
	// 空行は、このパターンにマッチしません（空行は \s* のみ）。
	validRegex := regexp.MustCompile(`^\s*(?:[0-9]+(?:,\s*[0-9]+)*)(?:,\s*)*$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		// 1. 空行の判定
		if trimmedLine == "" {
			continue
		}

		// 2. 数字とカンマ以外を含む行の判定
		// 数字とカンマ以外の文字が含まれていないかチェック
		if !regexp.MustCompile(`^[\d,]*$`).MatchString(line) {
			continue
		}

		// 3. カンマ区切りの整数列であるかチェック (正規表現を使用)
		if validRegex.MatchString(line) {
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常は無視されることが多いが、念のため）
	}

	fmt.Printf("valid=%d\n", validCount)
}
