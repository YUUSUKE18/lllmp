package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s*          : 行の先頭の任意の空白
	// (?:          : 非キャプチャグループの開始
	//   \d+        : 1つ以上の数字
	//   ,          : カンマ
	// )+           : 上記のグループが1回以上繰り返される (カンマ区切りの数字列)
	// \s*          : 行末の任意の空白
	// $            : 行の終わり
	// 末尾のカンマは許容するため、行末にカンマが続くパターンも考慮する必要がある。
	// 仕様：「1 個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容する」
	// これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを意味する。

	// より厳密に「1個以上の数字列がカンマで区切られている」ことを確認するパターン
	// 少なくとも一つの数字が含まれ、カンマと数字のみで構成されていることを確認する。
	// 例: 1,2,3 または 1,2,3,
	// 否定的な条件: 空行、数字とカンマ以外を含む行は妥当ではない。

	// 妥当な行の判定ロジックを正規表現で表現する。
	// 1. 行が空でないこと。
	// 2. 行が数字とカンマのみで構成されていること。
	// 3. 少なくとも1つの数字が含まれていること。

	// 以下の正規表現は、行全体が数字とカンマのみで構成され、
	// 少なくとも1つの数字が含まれていることを確認します。
	// ^\s*             : 行頭の空白
	// (?:             : 非キャプチャグループ
	//   \d+(?:,\d+)*  : 1つ以上の数字、それに続くカンマと数字の繰り返し (例: 1,2,3)
	//   |             : または
	//   \d+           : 単一の数字列 (例: 1)
	// )+              : 上記のパターンが1回以上繰り返される
	// (?:,\d*)?       : 末尾のカンマと数字のオプション (末尾のカンマは許容)
	// \s*$            : 行末の空白
	//
	// よりシンプルに、行が数字とカンマのみで構成され、空でないことを確認し、
	// 少なくとも1つの数字が含まれていることを確認する。

	// 妥当な行の定義:
	// 1. 行が空でない。
	// 2. 行に含まれる文字が数字(0-9)とカンマ(,)のみである。
	// 3. 行内に少なくとも1つの数字が含まれている。
	// 4. 末尾のカンマは許容される。

	// 否定的な条件（空行、数字とカンマ以外を含む行）を排除する。
	// 以下のパターンは、行が数字とカンマのみで構成され、少なくとも1つの数字を含むことを確認します。
	// ^\s*                 : 行頭の空白
	// (?:                  : グループ開始
	//   \d+(?:,\d*)*      : 1つ以上の数字、それに続くカンマと任意の数の数字の繰り返し (例: 1,2,3, または 1)
	// )                   : グループ終了
	// (?:,\d*)?            : 末尾のカンマと数字のオプション (末尾のカンマは許容)
	// \s*$                : 行末の空白

	// 実際には、行が「カンマ区切りの整数列」であるためには、
	// 1. 数字とカンマのみで構成されていること。
	// 2. 少なくとも1つの数字が含まれていること。
	// 3. 空行でないこと。

	// 以下の正規表現は、行が数字とカンマのみで構成され、少なくとも1つの数字を含むことを確認します。
	// (?:^[\s]*$): 空行や空白のみの行を排除する（これは後で手動でチェックする方が安全かもしれないが、正規表現で試みる）
	// 妥当な行のパターン: 少なくとも1つの数字とカンマのみで構成されている。
	// 1. 数字とカンマのみで構成されていることを確認する。
	// 2. 少なくとも1つの数字が含まれていることを確認する。

	// 判定ロジックをシンプルにするため、行をトリムしてからチェックする。
	// 正規表現で「数字とカンマのみ」かつ「数字が含まれる」ことを確認する。
	// 妥当な行のパターン: 1つ以上の数字とカンマの組み合わせ。
	// ^\s*[\d,]+$ : 数字とカンマのみで構成されていることを確認。
	// このパターンは、"1,2,3" や "1," や ",1" など、数字とカンマのみで構成されている行を捉える。
	// 空行は除外される。

	// 最終的な判定ロジックとして、行をトリムし、数字とカンマのみで構成されているか、かつ数字が含まれているかをチェックする。
	// 正規表現で「数字とカンマのみ」をチェックし、空行やその他の文字を排除する。
	// 妥当な行は、数字とカンマのみで構成され、少なくとも1つの数字を含む。
	// 末尾のカンマは許容される。

	// 妥当な行のパターン: 少なくとも1つの数字とカンマのみで構成されている。
	// ^\s*                 : 行頭の空白
	// (?:                  : グループ開始
	//   \d+(?:,\d*)*      : 1つ以上の数字、それに続くカンマと任意の数の数字の繰り返し (例: 1,2,3, または 1)
	// )                   : グループ終了
	// (?:,\d*)?            : 末尾のカンマと数字のオプション (末尾のカンマは許容)
	// \s*$                : 行末の空白

	// 実際には、行が「カンマ区切りの整数列」であるためには、
	// 1. 数字とカンマのみで構成されていること。
	// 2. 少なくとも1つの数字が含まれていること。
	// 3. 空行でないこと。

	// 判定のための正規表現を定義
	// このパターンは、行が数字とカンマのみで構成され、少なくとも1つの数字を含むことを確認します。
	// 末尾のカンマは許容されます。
	validRegex := regexp.MustCompile(`^\s*[\d,]+$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 行が数字とカンマのみで構成されているかチェック
		if validRegex.MatchString(line) {
			// さらに、少なくとも1つの数字が含まれているかチェックする。
			// 数字が含まれていない場合（例: "," や ",,"）、これは妥当ではない。
			hasDigit := false
			for _, char := range line {
				if char >= '0' && char <= '9' {
					hasDigit = true
					break
				}
			}

			if hasDigit {
				validCount++
			}
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常は無視されることが多いが、念のため）
	}

	fmt.Printf("valid=%d\n", validCount)
}
