const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validCount = 0;

rl.on('line', (line) => {
  const trimmedLine = line.trim();

  if (trimmedLine === "") {
    // 空行は妥当ではない
  } else {
    // カンマ区切りの整数列として妥当かを判定
    // 妥当条件: 1 個以上の数字列がカンマで区切られて並んでいる。末尾のカンマは許容。
    // 数字とカンマ以外を含む行は妥当ではない。

    // 1. 数字とカンマ以外が含まれていないかチェック
    // 正規表現で、数字とカンマ以外の文字が含まれていないか確認する
    if (!/^[0-9,]*$/.test(line)) {
      // 数字とカンマ以外の文字が含まれている場合、妥当ではない
    } else {
      // 2. 1個以上の数字列がカンマで区切られているかチェック
      // 末尾のカンマは許容されるため、行全体を処理する
      // 行をカンマで分割し、空文字列で構成されるグループが存在しないか確認する
      
      // 末尾のカンマを無視して処理するために、末尾のカンマを除去してから分割するなどの工夫が必要だが、
      // 仕様は「1個以上の数字列がカンマで区切られて並んでいる」であり、末尾のカンマは許容される。
      // これは、カンマで区切られた数字のセットが一つ以上存在すれば良いことを意味する。

      // 行をカンマで分割し、各要素が数字のみ（または空文字列）であるかを確認する
      const parts = line.split(',');
      let hasDigits = false;
      for (const part of parts) {
        if (part.trim() !== "") {
          // 数字が含まれているかチェック
          if (/^\d+$/.test(part.trim())) {
            hasDigits = true;
          } else {
            // 数字とカンマ以外が含まれている場合、この行は不適
            // ただし、上記の /^[0-9,]*$/ のチェックで、数字とカンマ以外は既に排除されているはず。
            // ここでは、数字列が1つ以上存在することを確認すれば十分と解釈する。
          }
        }
      }

      // 1個以上の数字列が存在するかどうかをチェックする。
      // もし行にカンマが一つも含まれていない場合（例: "123"）、これも1個の数字列として妥当。
      // 妥当条件: 1 個以上の数字列がカンマで区切られて並んでいる。
      // 区切りの有無に関わらず、行全体が数字とカンマのみで構成されていれば妥当であると解釈する。
      
      // 再評価：
      // 「1 個以上の数字列がカンマで区切られて並んでいる」
      // 例: "1,2,3" -> 3つの数字列
      // 例: "123" -> 1つの数字列（カンマなしだが、区切りがない場合も含むか？）
      // 例: "1,2," -> 2つの数字列 (1と2)
      // 例: "," -> 0つの数字列（空の区切り）
      
      // 最も厳密に解釈すると、カンマで区切られた要素の中に数字が存在すること。
      // 末尾のカンマは許容される。
      
      let actualDigitCount = 0;
      for (const part of parts) {
        const trimmedPart = part.trim();
        if (trimmedPart.length > 0 && /^\d+$/.test(trimmedPart)) {
          actualDigitCount++;
        }
      }

      if (actualDigitCount >= 1) {
        validCount++;
      }
    }
  }
});
