const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let lines = 0;
let validLines = 0;

rl.on('line', (line) => {
  lines++;
  // 行の前後の空白を無視して、カンマ区切りの整数列として妥当かを判定する
  // 妥当な行は、カンマで区切られた数字列のみで構成されている必要がある。
  // 末尾のカンマは許容される。
  // 空行は妥当ではない。
  
  // 正規表現で検証:
  // ^\s*             -> 行の先頭の空白（無視される）
  // (?:             -> 非キャプチャグループの開始
  //   \d+           -> 1つ以上の数字
  //   ,?            -> カンマ（0個または1個）
  // )*              -> 上記のグループが0回以上繰り返される
  // \s*$            -> 行末の空白（無視される）
  // この正規表現だけでは「数字とカンマ以外を含む行は妥当ではない」という条件を満たせないため、
  // より厳密に「カンマ区切りの整数列」であることを確認する。

  // 妥当性の判定ロジックを再構築する。
  // 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」こと。
  // 空行は妥当ではない。
  // 数字とカンマ以外を含む行は妥当ではない。

  // 1. 行をトリムして空行でないことを確認
  const trimmedLine = line.trim();
  if (trimmedLine.length === 0) {
    // 空行は妥当ではない
    return;
  }

  // 2. カンマ区切りの整数列として妥当か判定
  // 妥当なパターン: 数字、カンマ、数字が混在している。
  // 末尾のカンマは許容される。
  // 例: "1,2,3," は妥当。 "1,2" も妥当。 "abc" は不妥当。
  
  // 許容される文字は数字(0-9)とカンマ(,)のみ。
  // 末尾のカンマは許容される。
  // 1個以上の数字列がカンマで区切られている必要がある。

  // 正規表現で検証:
  // ^\s*             -> 行の先頭の空白
  // (?:             -> 非キャプチャグループの開始
  //   \d+(?:,\d+)*  -> 数字とカンマの組み合わせ（例: 1,2,3）
  //   |             -> または
  //   \d+           -> 単独の数字列（末尾のカンマなしの場合も考慮）
  // )+              -> 1回以上繰り返される
  // (?:,\d*|\s*)?   -> 末尾のカンマの有無（オプション）
  // \s*$            -> 行末の空白
  
  // より単純に、カンマで区切られた要素が数字のみで構成されているかを確認する。
  // 妥当な行は、数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれている必要がある。
  
  // 許容される文字セット: 数字(0-9), カンマ(,), 空白(\s)
  // 厳密に「数字とカンマ以外を含む行は妥当ではない」という条件を適用する。
  
  let isValid = true;
  for (let i = 0; i < line.length; i++) {
    const char = line[i];
    if (!(char >= '0' && char <= '9') && char !== ',' && char !== ' ' && char !== '\t' && char !== '\n') {
      // 制御文字やその他の記号が含まれていたら不妥当
      isValid = false;
      break;
    }
  }

  if (!isValid) {
    // 数字とカンマ以外を含む行は妥当ではない
    return;
  }
  
  // 3. 1個以上の数字列がカンマで区切られて並んでいるか判定
  // 行をカンマで分割し、各要素が数字のみで構成されているか、または空でないかを確認する。
  const parts = line.split(',');
  let hasNumbers = false;
  for (const part of parts) {
    const trimmedPart = part.trim();
    if (trimmedPart.length > 0) {
      // 数字のみで構成されているかチェック
      if (!/^\d+$/.test(trimmedPart)) {
        // 数字とカンマ以外を含む行は既に除外されているはずだが、念のため。
        isValid = false;
        break;
      }
      hasNumbers = true;
    }
  }

  if (isValid && hasNumbers) {
    validLines++;
  }
});

rl.on('end', () => {
  console.log(`valid=${validLines}`);
});
