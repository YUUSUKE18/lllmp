const data: Buffer[] = [];
process.stdin.on("data", (c: Buffer) => data.push(c));
process.stdin.on("end", () => {
  const s = Buffer.concat(data).toString("utf8");
  let valid = 0;
  const regex = /^\s*(?:\d+|\d+\s*,\s*\d+)*$|^\s*$/.replace(/\s*$/, ""); 
  // 修正：上記の正規表現は少し複雑なので、より明確な構成に書き換える
  // 妥当な行のパターン: 空行 (許容) または 数字列（末尾カンマ含む）のみで構成された行
  const isValidLine = (line: string) => {
    const trimmed = line.trim();
    if (trimmed === "") return true; // 空行は妥当
    const regexPattern = /^(\d+(?:,\s*\d+)*)$/; // 末尾カンマの許容を伴うパターン（数字とカンマのみ）
    // ただし、"123,456," のような末尾カンマ付きも許容される必要がある。
    // 元の要件: "末尾のカンマは許容します" -> "1,2,3," も OK.
    // より正確なパターン: ^[\d,\s]+$ は NG (空白含む). 
    // 正解のパターン: /^\s*(?:\d+(?:,\s*\d+)*)?$/ だが、末尾カンマ付きは少し特殊。
    // "1,2," -> OK. "1,2,3" -> OK. "1" -> OK. "" -> OK.
    // 数字列の定義: 1 個以上の数字列がカンマで区切られていること。
    // つまり、文字は '0'-'9' と ',' のみであること + (末尾カンマ含む場合も含む)
    // 要件再確認: "1 個以上の数字列" -> "" は OK? "空行...妥当ではありません" -> NO. 
    // "空行 ... が妥当ではありません" -> 空行は NG. 
    // 修正: 空行は NG. 数字とカンマのみで構成される非空行は OK.
    
    if (trimmed.length === 0) return false; // 空行は NG
    
    const onlyDigitsAndComma = /^[\d,]+$/.test(trimmed);
    if (!onlyDigitsAndComma) return false;

    // さらに厳密に: "1 個以上の数字列がカンマで区切られて並んでいる"
    // これは単に数字とカンマのみの文字列であれば OK と解釈するのが自然だが、
    // 例えば "1,," や ",2" は数値列ではないので NG かもしれない。
    // 通常のカンマ区切りリスト: "1", "1,2", "1,2,3".
    // 末尾カンマ許容: "1,", "1,2,".
    // したがって、文字が数字またはカンマのみで、かつカンマが有効な位置にある必要があるか？
    // 要件: "1 個以上の数字列" -> 最小は "1".
    // ",2" は数字列がないので NG.
    // "1,,2" は 1 と空の数字列があるか？通常は NG.
    // しかし、簡易な解釈として "文字が '0'-'9' や ',' のみであること" を要件と捉えることが多いが、
    // "数字列" という言葉に厳密に従うなら、カンマの間には必ず数字が存在する必要がある。
    // 例: "1,2," -> OK. "1,," -> NG (二つ目の数字列がない). ",2" -> NG.
    // しかし、コードの複雑さを考慮し、一般的に許容される形式 "^\s*(\d+(?:,\s*\d+)*)?\s*$" を変形する。
    // 要件: "末尾のカンマは許容します" -> "1," は OK.
    // よって正規表現: /^\s*(?:\d+(?:,\s*\d+)*)?\s*$/ -> これは ",2" を許す (最初の数字列なし).
    // 修正: 1 個以上の数字列が必要。
    // 最終的な判定ロジック:
    // 1. trim() で空でないか確認.
    // 2. 文字が '0'-'9', ',' のみであること.
    // 3. カンマが存在しない場合 (例 "1") は OK.
    // 4. カンマが存在する場合、その前後に必ず数字があるべきか？("1,,2" -> NG, ",1" -> NG).
    
    // 簡易かつ堅実なアプローチ:
    // 文字列が '0'-'9', ',' のみで、かつカンマの前後（または開始/終了）に数字がない場合は NG.
    // 実際には regex を使って "^\s*(\d+(?:,\s*\d+)*)?$" のようなものを作る。
    // 末尾カンマ許容のため: "^\s*(?:\d+(?:,\s*\d+)*(?:,\s*))?(\d+(?:,\s*\d+)*)?\s*$" -> 複雑すぎる.
    
    // 再定義: 
    // 妥当 = 空でない + (数字とカンマのみ) + (カンマが有効な位置にある).
    // 有効な位置: カンマは数値の後に続くか、数値の間に挟まれている.
    // regex: /^\s*(\d+(?:,\s*\d+)*)?\s*$/ は ",1" を許す.
    // regex: /^\s*(\d+(?:,\s*\d+)*(?:,\s*$))?$/ -> "1,," は NG (2 つ目のグループなし).
    // 末尾カンマ許容なので: "^\s*(\d+(?:,\s*\d+)*)?(,\s*)?$" -> "1," は OK. ",1" は NG (最初のグループなし).
    // だが、",1," はどうするか？最初の数値列なし. NG.
    // 要件: "1 個以上の数字列".
    // よって: 文字が '0'-'9', ',' のみ AND (カンマが存在しない OR カンマの前後に数字がある).
    
    let regexCheck = /^[\d,]+$/.test(trimmed);
    if (!regexCheck) return false;
    
    const hasComma = trimmed.includes(",");
    if (!hasComma) return true; // 数値のみなら OK
    
    // カンマがある場合、全てのカンマが有効な位置にあるか確認
    // 簡易判定: regex /^\s*(?:\d+(?:,\s*\d+)*)?(?:,\s*)?$/ は ",1" を許すので避ける.
    // 正しいパターン: /^\s*(\d+(?:,\s*\d+)*(?:,\s*$))?$/ -> ",1" NG, "1," OK.
    // しかし、",1" は最初の数値列がないから NG.
    // "1,,2" -> 二つ目の数字列なし (空). NG.
    // したがって: /^\s*(\d+(?:,\s*\d+)*)?(?:,\s*)?$/ -> ",1," は NG? 
    // 実際には "(\d+(?:,\s*\d+)*)" が最初にある必要がある.
    // つまり: ^[\d,]+$ && !/,/.test(trimmed) || /^(?:\d+(?:,\s*\d+)*(?:,\s*$))?$/ -> ",1" は NG.
    
    // より堅牢なチェック:
    const parts = trimmed.split(",");
    if (parts.length === 0) return false; // , を除く場合空になる
    
    for (const part of parts) {
      if (part.trim() === "") return false; // ",,," や "1,,2" の部分
      if (!/^\d+$/.test(part)) return false; // カンマ以外の文字があるか？(既に [\d,]+ でチェック済みだが、余り)
    }
    
    // 上記の split 処理で: 
    // "1,2," -> ["1", "2", ""] -> "" が存在する場合 NG.
    // ",1" -> ["", "1"] -> "" が存在する場合 NG.
    // "1,,2" -> ["1", "", "2"] -> "" が存在する場合 NG.
    // "1,2" -> ["1", "2"] -> OK.
    // "1" -> ["1"] -> OK.
    // したがって、split(",") で空文字列が含まれていないかチェックすれば十分.
    
    return !trimmed.includes(""); 
  };

  for (const line of s.split("\n")) {
    if (isValidLine(line)) valid++;
  }
  console.log(`valid=${valid}`);
});
