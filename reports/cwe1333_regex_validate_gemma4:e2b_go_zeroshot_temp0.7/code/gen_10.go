package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	for scanner.Scan() {
		line := scanner.Text()
		// 行の前後の空白を無視
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 末尾のカンマを許容するため、行全体をチェックする
		// 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」こと。
		// つまり、カンマが少なくとも1つ含まれているか、数字のみで構成されているか、
		// あるいは数字とカンマのみで構成されているかのいずれか。
		// 仕様の解釈：「1 個以上の数字列がカンマで区切られて並んでいる」
		// これは、カンマで区切られた要素が存在することを意味する。
		// 例: "1,2,3" -> 3つの数字列。
		// 例: "123" -> 1つの数字列（区切りがない、またはカンマがない場合も許容されるか？）。
		// 仕様の「妥当とは、1 個以上の数字列がカンマで区切られて並んでいることです」
		// これは、カンマが少なくとも1つ存在するか、または数字列が少なくとも1つ存在することを意味する。

		// 最も厳密な解釈: カンマで区切られた要素が1つ以上存在すること。
		// 空白を無視した上で、カンマが存在するか、または数字のみが存在するかを判定する。

		// 行をカンマで分割してみる
		parts := strings.Split(trimmedLine, ",")

		isValid := false

		// 1. 1個以上の数字列がカンマで区切られて並んでいる (要素数が1以上)
		// ただし、空の要素が含まれる可能性があるため、実際に数字列が存在するか確認する。
		hasNumberColumn := false
		for _, part := range parts {
			// 各部分が空でなく、かつ数字のみで構成されているかを確認
			if strings.TrimSpace(part) != "" {
				// 数字のみで構成されているかチェック（カンマ以外の文字が含まれていないか）
				if strings.TrimSpace(part) == "" {
					continue // 空の要素は無視
				}
				// 数字列であることの確認（すべて数字のみ）
				if _, err := fmt.Sscan(part); err == nil {
					// 成功すれば数字列である
					hasNumberColumn = true
				} else {
					// 数字以外の文字が含まれている場合は、この行は不適
					break
				}
			}
		}

		// 2. 末尾のカンマは許容する。
		// 3. 空行、および数字とカンマ以外を含む行は妥当ではない。

		// 妥当性の再評価:
		// 妥当とは「1 個以上の数字列がカンマで区切られて並んでいること」
		// これは、分割後の要素の数に関わらず、少なくとも1つの有効な数字列が存在すれば良い、と解釈する。
		// ただし、厳密に「区切られて並んでいる」ことを考えると、カンマが存在することが望ましい。

		// 仕様を最もシンプルに解釈し、制約を満たすかチェックする:
		// - 空行はNG (処理済み)
		// - 数字とカンマ以外を含む行はNG (次のチェックで確認)
		// - 1個以上の数字列がカンマで区切られている (分割して空でない要素が1つ以上あるか)

		// カンマで分割して、有効な数字列が1つ以上存在するかを判定する。
		// 末尾のカンマは許容されるため、最後の要素が空でも問題ない。
		for _, part := range parts {
			trimmedPart := strings.TrimSpace(part)
			if trimmedPart != "" {
				// その部分が数字列であるかを確認
				if _, err := fmt.Sscan(trimmedPart); err == nil {
					isValid = true
					break // 1つでも有効な数字列があればOK
				} else {
					// 数字列ではない文字が含まれている場合 (例: "1,a,3")
					isValid = false
					break
				}
			}
		}

		if isValid {
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理は要求されていないが、念のため
	}

	fmt.Printf("valid=%d\n", validCount)
}
