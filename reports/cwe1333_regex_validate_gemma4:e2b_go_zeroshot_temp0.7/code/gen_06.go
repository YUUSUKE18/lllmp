package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	for scanner.Scan() {
		line := scanner.Text()
		// 行の前後の空白を無視するため、TrimSpaceを使用する
		trimmedLine := strings.TrimSpace(line)

		// 1. 空行の判定
		if trimmedLine == "" {
			continue
		}

		// 2. 数字とカンマ以外を含む行の判定
		isValid := true
		for _, char := range trimmedLine {
			if !('0' <= char && char <= '9') && char != ',' {
				isValid = false
				break
			}
		}
		if !isValid {
			continue
		}

		// 3. カンマ区切りの整数列が1個以上あるかの判定
		// 妥当であるためには、カンマで区切られた複数の数字列が存在する必要がある。
		// 末尾のカンマは許容される。
		
		// 処理を簡略化するため、カンマで分割し、空文字列でない要素が1つ以上あれば妥当とみなす。
		// ただし、仕様の「1 個以上の数字列がカンマで区切られて並んでいること」を厳密に解釈する。
		// これは、少なくとも一つの数字列が存在することを意味する。
		
		// 複数の数字列があることを確認するため、カンマで分割して、各要素が数字列であるかを確認する。
		// 妥当性の定義を「カンマで区切られた整数列が1個以上存在すること」と解釈する。
		
		// カンマで分割する
		parts := strings.Split(trimmedLine, ",")
		
		// 末尾のカンマが許容されるため、最後の要素が空文字列になる可能性がある。
		// 例: "1,2," -> ["1", "2", ""]
		
		// 妥当であるための条件：分割された要素の中に、少なくとも1つ、数字のみで構成される要素が存在すること。
		// また、行がカンマを含んでいることが前提。
		
		hasNumberColumn := false
		for _, part := range parts {
			// partが空文字列でないことを確認し、それが数字のみで構成されているか確認する。
			// または、partが数字列であること。
			if part != "" {
				// partが完全に数字のみで構成されているかを確認
				if _, err := fmt.Sscan(part); err == nil {
					hasNumberColumn = true
				}
			}
		}

		// 妥当性の再評価:
		// 仕様：「1 個以上の数字列がカンマで区切られて並んでいること」
		// 例: "123" -> 1つの列。カンマがない場合も許容されるか？
		// 仕様：「1 個以上の数字列がカンマで区切られて並んでいる」
		// これは、カンマで区切られた要素が1つ以上あることを意味する。
		// "123" はカンマを含まないが、これは0個のカンマで区切られた1つの列と解釈できるか？
		// "1,2" -> 2つの列
		// "1," -> 2つの列 (1, "")
		
		// 最もシンプルな解釈：カンマで区切られた要素が1つ以上存在し、それらが数字列であること。
		// 空行と数字とカンマ以外は除外済み。
		// したがって、`strings.Split`で得られた要素の数が1以上であれば妥当と判断する。
		// ただし、"123"の場合、Split("123", ",") -> ["123"] (要素数1)
		// "1,"の場合、Split("1,", ",") -> ["1", ""] (要素数2)
		
		// 妥当な行は、カンマで分割した結果、少なくとも1つの非空の要素を持つ場合、または、
		// 少なくとも1つの数字列として認識される場合。
		
		// 最終的な判定基準として、カンマで分割した結果、空でない要素が1つ以上存在するかを基準とする。
		// (ただし、行全体が数字とカンマのみで構成されていることが前提)
		
		if hasNumberColumn {
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
