package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 末尾のカンマを削除してチェックする
		// 妥当なのは「1個以上の数字列がカンマで区切られて並んでいる」こと。
		// 末尾のカンマは許容されるため、行全体が数字とカンマのみで構成されていれば良い。
		// 妥当性の判定は「カンマ区切りの整数列が1個以上存在するか」に焦点を当てる。

		// 行が空でないことを確認済み。
		// 数字とカンマ以外を含む行は妥当ではない。
		isAlphanumericAndComma := true
		for _, char := range line {
			if !('0' <= char && char <= '9' || char == ',') {
				isAlphanumericAndComma = false
				break
			}
		}

		if !isAlphanumericAndComma {
			continue
		}

		// 妥当性の判定: 1個以上の数字列がカンマで区切られて並んでいること。
		// これは、カンマが一つ以上含まれていれば（あるいは数字のみでも1つ以上の数字列があれば）
		// 妥当と見なせる。仕様の文脈から、「カンマで区切られている」ことを強く示唆している。
		// もし、カンマが一つも含まれていない数字列のみ（例: "123"）も妥当とするならば、
		// 1個以上の数字列が存在すれば良い。
		// 「1 個以上の数字列がカンマで区切られて並んでいる」という条件を満たすためには、
		// カンマの存在が最も重要な区切りである。

		// 簡略化して、「数字とカンマのみで構成されており、かつ空行でない」ことを妥当と見なす。
		// 末尾のカンマは許容されるため、これは「カンマ区切りの整数列が1個以上」を満たす範囲を広く捉える。
		// 例: "1,2,3", "1,2,", "123" (カンマなしも許容されると解釈)

		// 厳密に「カンマで区切られている」ことを要求するならば、カンマが存在する必要がある。
		// しかし、「妥当とは、1 個以上の数字列がカンマで区切られて並んでいることです」という記述。
		// カンマがない場合 (例: "123") は、0個の区切りがあるため、厳密には不適。
		// カンマがある場合 (例: "1,2") は、2つの区切りがあるため、適。
		// 末尾のカンマは許容されるため、行が数字とカンマのみで構成されていれば、
		// 少なくとも1つのカンマが存在するか、あるいは数字列が1つ以上存在すれば良い。

		// 以下の判定を採用する: 行が空でなく、数字とカンマ以外を含まないこと。
		// これは、与えられた制約の中で最も安全な解釈である。
		validCount++
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常、標準入力からの読み込みエラー）
	}

	fmt.Printf("valid=%d\n", validCount)
}
