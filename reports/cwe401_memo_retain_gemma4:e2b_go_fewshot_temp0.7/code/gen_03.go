package main

import (
	"bufio"
	"fmt"
	"os"
	"strconv"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	var total int64 = 0
	memo := make(map[int]int64)

	for scanner.Scan() {
		line := scanner.Text()
		if line == "" {
			continue
		}

		n, err := strconv.Atoi(line)
		if err != nil {
			continue
		}

		if n == 1 {
			// n=1 のときの手数は 0
			memo[1] = 0
		} else if _, found := memo[n]; !found {
			// メモ化されていない場合、再帰的に計算してメモ化
			var steps int64
			if n%2 == 0 {
				// n が偶数なら n/2
				steps = memo[n/2] + 1
			} else {
				// n が奇数なら 3n+1
				steps = memo[3*n+1] + 1
			}
			memo[n] = steps
		}

		// n が初めて読み込まれた場合、その結果を合計に加算する
		// ただし、再帰的な計算で既に計算済みの場合は、その結果を合計に加算する
		// ここでは、各クエリ n について、n から 1 に到達するまでの手数を求め、その合計を求める必要がある。
		// 課題の解釈に基づき、各入力 n について、n から 1 への移動の「手数」を求め、その合計を計算する。
		// 設問の「n が 1 のときの手数は 0」という記述から、n から 1 への操作の回数を数える。
		// 操作: n -> n/2 (n偶数), n -> 3n+1 (n奇数)
		// 1に到達するまでの手数を求める。

		// 再帰的なメモ化（DP）で n から 1 への到達時間を計算する。
		// 1に到達するまでの手数を求める。
		// n=1 の場合、手数は 0。
		// n=2 の場合: 2 -> 1 (1手)
		// n=3 の場合: 3 -> 10 -> 5 -> 16 -> 8 -> 4 -> 2 -> 1 (7手)
		// 設問の指示は「n が 1 のときの手数は 0」であり、これは n=1 からの操作を意味する。
		// しかし、通常この種の問題は、与えられた n から 1 への操作の回数を求める。
		// 設問の「n が 1 のときの手数は 0」を「n=1 は終了状態であり、そこからの操作回数は 0」と解釈し、
		// n から 1 に到達するまでのステップ数を求める。

		if n != 1 {
			// 既に memo[n] が計算されていればそれを使う
			if steps > 0 {
				total += steps
			}
		} else {
			// n=1 の場合、手数は 0
			total += 0
		}
	}

	// メモ化された結果から合計を再計算する方が安全かもしれないが、
	// 設問の構造から、各入力に対して計算した結果を合計していくのが自然。
	// 再度、各入力について計算した手数を合計するロジックに修正する。

	// --- 再計算ロジックの修正 ---
	// 既に読み込んだ入力に対して、メモ化された結果から合計を求める。
	// 最初のループで全ての入力 n について、n から 1 への到達時間を計算し、合計を求める。
	
	finalTotal := int64(0)
	for _, line := range strings.Split(scanner.Text(), "\n") { // スキャナがすでに消費済みなので、再読み込みは困難。
		// 実際には、入力全体を一度に読み込み、その中から処理するのが適切。
		// bufio.Scannerは行ごとに読み込むため、ループ内で完結させる。
	}
	
	// 最初の読み込みループで、各nについて「nから1への手数」を計算したと仮定し、それを合計する。
	// 最初のループで total を更新するロジックが、各入力 n について計算した結果を合計する形になっている。
	// 設問の「すべてのクエリの手数の合計を求めます」に従い、最初のループで計算した total を出力する。

	fmt.Printf("total=%d\n", total)
}
