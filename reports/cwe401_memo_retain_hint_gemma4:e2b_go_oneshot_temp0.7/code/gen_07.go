package main

import (
	"bufio"
	"fmt"
	"os"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	var total int64 = 0

	for scanner.Scan() {
		line := scanner.Text()
		if line == "" {
			continue
		}

		var n int64
		_, err := fmt.Sscanf(line, "%d", &n)
		if err != nil {
			continue
		}

		if n == 1 {
			// n が 1 のときの手数は 0
			total += 0
			continue
		}

		// メモ化のためのマップ
		memo := make(map[int64]int64)

		var count int64 = 0
		current := n
		
		// 1 に到達するまでの手数を計算
		for current != 1 {
			if val, ok := memo[current]; ok {
				count += val
				current = 1 // 既に計算済みなのでループを抜ける
				break
			}
			
			if current%2 == 0 {
				current /= 2
			} else {
				current = 3*current + 1
			}
			count++
		}
		
		// 1 に到達した後の手数を加算（再帰的なメモ化を考慮）
		// ここでは、各クエリが独立しているため、個々の経路の計算結果を合計する。
		// ただし、問題文の「n が 1 のときの手数は 0」という指示と、「操作を繰り返し、1 に到達するまでの手数を求めます」という指示を考慮すると、
		// 実際には、各クエリ n に対して、n から 1 へのパスの長さを求める必要がある。
		// 提示された操作はコナーズの予想（3n+1問題）の操作であり、これは通常、1 に到達するまでのステップ数を問う問題である。
		// 設問の意図を「各クエリ n について、操作を繰り返し1に到達するまでの手数を求め、その合計を求める」と解釈し、各クエリで独立に計算する。
		
		// 再計算を避けるため、より効率的なメモ化を導入する。
		// この問題は、各 n について、n -> f(n) -> f(f(n)) -> ... -> 1 へのステップ数を求める問題である。
		// ここで、各 n の計算に特化したメモ化を導入する。

		// 再度、クエリごとに計算を修正する。
		
		// -----------------------------------------------------------------
		// 新しい計算ロジック (各クエリ n について、n から 1 へのパス長を求める)
		// -----------------------------------------------------------------
		
		// 既に計算済みの値を保持するマップをグローバルに持つか、あるいはループ内で管理する。
		// 今回は、入力全体に対して一度の計算を試みるため、各 n の計算が独立して行われる。
		
		// 外部ループで処理するため、ここでは n ごとに直接計算する。
		
		// 最初に、現在の n から 1 へのパス長を計算する。
		
		currentN := n
		steps := 0
		
		// このクエリ n の計算結果が、他のクエリに影響を与えないように、
		// 外部で管理するメモ化テーブルを使うのが適切。
		// しかし、この問題は「すべてのクエリの手数の合計」を求めるため、
		// 各 n の計算結果をメモ化し、その結果を合計する。
		
		// 外部でメモ化テーブルを管理する（ここでは関数内で再帰的にメモ化を試みる）
		
		// 再帰的なメモ化関数を定義し、それを使って計算する。
		// ただし、標準入力の構造上、これはメインループの外で一度だけ実行されるべき。
		// 課題の要求は「すべてのクエリの手数の合計を求める」ことなので、
		// 各クエリ n について、n から 1 へのパス長を計算し、合計する。
		
		// 以下の実装では、各 n について、そのパス長を計算する。
		
		// 外部でメモ化テーブルを定義し、再帰的に呼び出す。
		// この問題は、入力された各 n に対して、n -> ... -> 1 へのパス長を求める問題である。
		
		// -----------------------------------------------------------------
		// 最終的な実装方針: 各 n について、再帰とメモ化を用いてパス長を求める。
		// -----------------------------------------------------------------
		
		// この部分は、本質的に、各 n に対して、n から 1 へのパス長を求める問題。
		// 最初のループで一度だけ実行されるため、ここでは n の計算結果を合計する。
		
		// 再度、最初のループの処理を、メモ化を活用するように書き直す。
		// 外部でmemoを定義し、再帰的に呼び出す形に変更する。
		// ただし、これは標準入力の構造に合わないため、
		// 外部で処理をまとめることを優先する。
		
		// -----------------------------------------------------------------
		// 最終的な実装（合計を求める）
		// -----------------------------------------------------------------
		
		// 外部でメモ化テーブルを保持する
		memoFinal := make(map[int64]int64)
		
		var calculateSteps func(k int64) int64
		calculateSteps = func(k int64) int64 {
			if k == 1 {
				return 0
			}
			if val, ok := memoFinal[k]; ok {
				return val
			}

			var result int64
			if k%2 == 0 {
				result = calculateSteps(k / 2) + 1
			} else {
				result = calculateSteps(3*k + 1) + 1
			}
			
			memoFinal[k] = result
			return result
		}
		
		// すべてのクエリ n について計算し、合計する。
		// 最初のループは、入力の読み込みのみに限定し、計算は後で行う。
		// しかし、Goの標準入力処理では、一度読み込んだデータに対して、
		// どのように処理するかを決定する必要がある。
		
		// 最初のループで読み込んだ n を使って、計算を実行する。
		
		// 既に n が読み込まれているので、この n に対して計算を実行する。
		stepsForN := calculateSteps(n)
		total += stepsForN
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常は無視）
	}

	fmt.Printf("total=%d\n", total)
}
