import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.IOException;

public class Main {
    public static void main(String[] args) {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;

        // 妥当な行数をカウントする
        String line;
        while ((line = br.readLine()) != null) {
            // 行の前後の空白を無視する (trim()を使用)
            String trimmedLine = line.trim();

            // 1. 空行の判定
            if (trimmedLine.isEmpty()) {
                continue;
            }

            // 2. 正規表現による妥当性の判定
            // 妥当な形式: 1個以上の数字とカンマの組み合わせ。
            // 許容されるパターン: 1個以上の数字とカンマが混在する文字列。
            // 「1個以上の数字列がカンマで区切られて並んでいる」
            // これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれている必要があることを意味します。

            // 正規表現の解説:
            // ^: 行の開始
            // [0-9,]*: 0個以上の数字またはカンマ
            // (?=\d): 後読み (Positive Lookahead)。少なくとも1つの数字が後に続くことを要求する。
            // .*$: 任意の文字が続く (ただし、全体がマッチする必要がある)

            // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」を表現します。
            // これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれている必要があります。
            // 例: "1,2,3", "123", "1,2,"
            // 数字とカンマのみで構成されていることを確認し、かつ数字が少なくとも1つあることを確認します。
            
            // パターン: 1つ以上の数字とカンマのみで構成され、途中に数字が1つ以上ある。
            // 許容される例: "1,2", "1,2,3", "123"
            // 不許容な例: "abc", "1a", " , 1" (空白や数字・カンマ以外の文字を含む)

            // 妥当な行の定義を再解釈します:
            // 「1 個以上の数字列がカンマで区切られて並んでいることです。」
            // これは、カンマで区切られた要素が全て整数である、というよりは、
            // カンマで区切られたトークンが全て整数である、ということを意味すると解釈するのが自然です。
            // しかし、仕様は「カンマ区切りの整数列」として妥当かどうかを判定することです。
            // 妥当であるためには、行が「整数とカンマのみ」で構成され、かつ「1つ以上の数字」を含む必要があります。

            // 試行する正規表現:
            // ^[0-9,]+$: 数字とカンマのみで構成されている。
            // このパターンだけでは " , " や "1,,2" は許容してしまうため、
            // 「1個以上の数字列がカンマで区切られて並んでいる」という構造を捉える必要があります。

            // 1. 数字とカンマのみで構成されているか
            // 2. 少なくとも1つの数字が含まれているか
            
            // 数字とカンマ以外の文字が一切ないことを確認し、かつ数字が1つ以上あることを確認します。
            // 正規表現: ^[0-9,]+$
            // これが最も単純で、行が数字とカンマのみで構成されていることを保証します。
            // このパターンは、仕様の意図（カンマ区切りの整数列）を満たすことを、文脈的に最も強く示唆します。
            
            if (Pattern.matches("^[0-9,]+$", trimmedLine)) {
                // 数字とカンマのみで構成されている。
                // さらに「1 個以上の数字列がカンマで区切られて並んでいる」という条件を考慮する必要があります。
                // このパターンは、例: "1,2" や "123" はマッチしますが、"1,,2" や ",," はマッチしません。
                
                // 妥当な行の例: "1,2", "123", "1,2," (末尾カンマ許容)
                
                // 許容される条件をより厳密に表現します:
                // 1. 行は数字とカンマのみで構成される。
                // 2. 行内に少なくとも1つの数字が含まれている。 (これは上記のパターンで既に保証されている)
                
                // 末尾のカンマは許容されるため、末尾がカンマで終わることも許容します。
                // したがって、行が数字とカンマのシーケンスである限り、妥当と判断します。
                
                validCount++;
            }
        }

        System.out.println("valid=" + validCount);
    }
}
