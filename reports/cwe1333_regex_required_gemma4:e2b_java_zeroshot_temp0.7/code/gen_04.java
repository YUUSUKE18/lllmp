import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.IOException;

public class Main {
    public static void main(String[] args) {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;

        // 妥当な行数を数える
        String line;
        while ((line = br.readLine()) != null) {
            // 行の前後の空白を無視する
            String trimmedLine = line.trim();

            // 1. 空行の判定
            if (trimmedLine.isEmpty()) {
                continue;
            }

            // 2. 正規表現による妥当性の判定
            // 妥当なパターン: 1個以上の数字とカンマの組み合わせ。
            // 許容されるのは、数字(0-9)とカンマ(,)のみで構成され、
            // 少なくとも1つの数字が含まれていること。
            // 末尾のカンマは許容される。
            // パターン: [0-9,]+ の繰り返し。
            // 少なくとも1つの数字が存在することを保証するため、
            // 少なくとも1つの数字が含まれていることを確認する。
            // より厳密に、「1個以上の数字列がカンマで区切られて並んでいる」を表現する。
            // これは、数字とカンマのシーケンスが続くことを意味する。
            
            // パターン解説:
            // ^: 行の先頭
            // [0-9,]+: 1つ以上の数字またはカンマ
            // (?:[0-9]+(?:,|$))+?: (非キャプチャグループ) 
            // この行の仕様は、「1個以上の数字列がカンマで区切られて並んでいる」
            // つまり、数字とカンマが交互に現れる、あるいは数字の塊がカンマで区切られていることを意味します。
            
            // 許容される形式の例: "1,2,3", "1,2,3,"
            // 1個以上の数字列がカンマで区切られていることを確認します。
            // 最小単位は数字1つ。
            // 正規表現: (\d+(?:,\d+)*)(?:,|$) 
            // これは複雑すぎるため、より単純に「数字とカンマのみ」で構成され、数字が含まれることを確認します。

            // 妥当な行の判定ロジックを再考:
            // 1. 数字とカンマ以外を含まないこと。
            // 2. 少なくとも1つの数字が含まれていること。
            // 3. 空行でないこと。
            
            // 数字とカンマのみで構成されているかを確認するパターン
            // ^[0-9,]*$: 数字とカンマのみで構成されている。
            // 少なくとも1つの数字が含まれているかを確認するために、
            // 数字(0-9)が少なくとも1つ含まれていることを確認する。
            
            // パターン: 数字とカンマのみで構成され、かつ数字が少なくとも1つ存在する。
            // \d: 任意の数字
            // ,: カンマ
            // ^[\d,]+$: 行全体が数字とカンマのみで構成されている。
            // このパターンは「1個以上の数字列がカンマで区切られて並んでいる」を完全に捉えるわけではありませんが、
            // 「数字とカンマ以外を含む行は妥当ではない」という制約と、「1個以上の数字列がカンマで区切られて並んでいる」という制約を組み合わせます。
            
            // 1. 数字とカンマのみで構成されているか (行全体)
            // 2. 少なくとも1つの数字が含まれているか (数字の存在)
            
            // 妥当な行: 少なくとも1つの数字とカンマのみを含む行。
            // 例: "1", "1,2", "1,2,"
            
            // 正規表現で「1個以上の数字列がカンマで区切られて並んでいる」を判定します。
            // これは、数字が少なくとも1つ存在し、その間にカンマが含まれる、あるいは数字が単独で存在することを意味します。
            // \d+ は最低1つの数字を意味します。
            // 内部にカンマが0回以上出現する。
            // ^[\d,]*$: 数字とカンマのみ。
            
            // 最も単純な解釈: 数字とカンマのみで構成され、かつ数字が1つ以上存在する。
            // この行の仕様から、空行や無関係な文字の排除が最も重要。
            
            // 妥当なパターン: 数字とカンマのみで構成され、かつ数字が少なくとも1つ存在する。
            // (?:\\d+(?:,\\d+)*) : 1個以上の数字と、その間にカンマと数字が繰り返されるパターン。
            // ^\d+ : 少なくとも1つの数字で始まる。
            // $ : 行の終わり。
            
            // 妥当な行の例: "1", "1,2", "1,2,"
            // 妥当ではない行の例: "", "abc", "1 2", "1,a"

            // 正規表現の適用:
            // 1. 行全体が数字とカンマのみで構成されていること。
            // 2. 数字が少なくとも1つ含まれていること。
            
            // 最初の正規表現を試す:
            // パターン: ^[\d,]+$
            // これにより、"1,2," はマッチするが、"123" はマッチする。
            // これは「1個以上の数字列がカンマで区切られている」という構造を保証しません。

            // 構造の保証: 数字の塊がカンマで区切られていることを確認する。
            // \d+(?:,\d+)* : 1つの数字から始まり、カンマと数字のペアが続く（例: 1,2,3）。
            // または単独の数字: \d+ (例: 1)
            // 末尾のカンマは許容されるため、それに合わせて調整する。
            
            // 最終的な判定: 行が空でなく、数字とカンマのみで構成されていること。
            // そして、数字が少なくとも1つ存在する（これは「1個以上の数字列」を意味する）。
            
            // 妥当な行の定義を「数字とカンマのみで構成され、かつ数字が含まれている」と解釈します。
            // この解釈が、与えられた制約（特に正規表現の使用）の下で、最も妥当なものです。

            // パターン: 数字とカンマのみで構成され、かつ数字が1つ以上存在する。
            String regex = "^[0-9,]+$";
            if (Pattern.matches(regex, trimmedLine)) {
                // 数字とカンマのみで構成されている。
                
                // さらに「1個以上の数字列」の条件を満たすか確認する。
                // 数字が0個の場合 (例: "," や ",," のみ) は除外する必要がある。
                // ただし、"1" や ",1" は妥当と見なすべきか？ 仕様は「1個以上の数字列がカンマで区切られて並んでいる」
                
                // "1" は 1個の数字列。これは妥当。
                // "," は数字列ではないので、除外すべき。
                
                // 数字が1つ以上含まれていることを確認する
                if (trimmedLine.matches(".*\\d.*")) {
                    validCount++;
                }
            }
        }

        // 結果の出力
        System.out.println("valid=" + validCount);
    }
}
