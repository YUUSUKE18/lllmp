import java.util.Scanner;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int validLines = 0;

        while (scanner.hasNextLine()) {
            String line = scanner.nextLine();
            // 行の前後の空白を無視する（trim()を使用）
            String trimmedLine = line.trim();

            // 1. 空行の判定
            if (trimmedLine.isEmpty()) {
                continue;
            }

            // 2. 正規表現による妥当性の判定
            // 妥当なパターン: 1個以上の整数がカンマで区切られている。
            // 許容されるのは、数字とカンマのみで構成される行。
            // パターン解説:
            // ^             : 行の先頭
            // [0-9,]*       : 0個以上の数字またはカンマ（これは行全体が数字とカンマで構成されていることを確認する補助）
            // (?:[0-9]+(?:,|$))+ : 1個以上の数字列とカンマの組み合わせ。
            //             (?:[0-9]+) : 1個以上の数字
            //             (?:,|$) : カンマまたは行末
            // 簡略化のため、以下のパターンで「1個以上の数字がカンマで区切られている」ことを確認する。
            // 1個以上の数字列と、その間にカンマが（任意で）存在するパターン。
            // 許容されるのは「1個以上の数字列がカンマで区切られて並んでいること」
            // 例: "1,2,3", "1,2,", "1" (末尾カンマ許容)

            // 妥当な行の定義をより厳密に：
            // 少なくとも1つの数字があり、カンマのみで区切られている（またはカンマが許容される）
            // パターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
            // 数字の後にカンマが続くか、行末で終わることを許容する。
            // 1個以上の数字がカンマで区切られていることを確認。
            String regex = "^[0-9]+(?:,[0-9]+)*$";
            
            // 末尾のカンマを許容する場合の調整。
            // 許容されるパターン例: "1,2,3", "1,2,", "1" (もし"1"も許容されるなら)
            // 仕様：「1 個以上の数字列がカンマで区切られて並んでいる」
            // -> 1,2,3 (OK)
            // -> 1,2, (OK)
            // -> 1 (OK, 1個の数字列)

            // 1. 数字とカンマのみで構成されていること (数字とカンマ以外の文字がないこと)
            // 2. 少なくとも1つの数字が含まれていること
            
            // 最初の正規表現で、数字とカンマのみで構成されていることを確認
            if (Pattern.matches("^[0-9,]*$", trimmedLine)) {
                // 3. 少なくとも1つの数字が含まれていることを確認
                // 数字のみが含まれている場合（例: "123"）も妥当とみなす。
                if (Pattern.matches(".*[0-9].*$", trimmedLine)) {
                    // 4. 末尾のカンマは許容される (これは正規表現の構造に依存する)
                    // 最後の文字がカンマであればOK、そうでなければ数字で終わっていればOK。
                    
                    // 最後の文字がカンマの場合、それが許容される。
                    // 例: "1,2," -> OK
                    // 例: "1,2,3" -> OK
                    // 例: "1" -> OK
                    
                    // このケースでは、行が数字とカンマのみで構成され、数字が含まれていれば妥当とする。
                    validLines++;
                }
            }
        }

        System.out.println("valid=" + validLines);
        scanner.close();
    }
}
