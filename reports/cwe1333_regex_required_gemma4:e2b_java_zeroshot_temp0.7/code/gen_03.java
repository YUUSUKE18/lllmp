import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.IOException;

public class Main {
    public static void main(String[] args) {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;

        // 正規表現パターン: 
        // ^\s*         -> 行の先頭の任意の空白文字
        // (?:         -> 非キャプチャグループの開始 (数字とカンマのパターン)
        //     \d+      -> 1つ以上の数字
        //     (?:,\d+)* -> カンマと1つ以上の数字が0回以上繰り返される (カンマ区切りのリスト)
        // )           -> グループの終了
        // (?:,\d+)*   -> 末尾のカンマ（オプション）
        // \s*$        -> 行末の任意の空白文字
        // 
        // より簡潔に、1つ以上の数字とカンマの組み合わせ、および末尾のカンマを許容するパターンを考えます。
        // 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」ことです。
        // これは、数字とカンマが混在し、少なくとも1つの数字列が存在することを意味します。
        // 例: "1,2,3" または "1,2," または "1" (この場合、"1"も1個の数字列と見なせるか？)
        // 仕様：「1 個以上の数字列がカンマで区切られて並んでいる」
        // これは、カンマで区切られた複数の数値の集合を意味します。
        // パターン案: (数字,繰り返し) が1回以上出現するパターン。
        // 少なくとも一つの数字が含まれており、カンマで区切られている（または単一の数字）。

        // 妥当な行の判定ロジックを正規表現で実現します。
        // 1. 空行は妥当ではない。
        // 2. 数字とカンマ以外を含む行は妥当ではない。
        // 3. 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」こと。

        // 妥当なパターン:
        // ^\s*             -> 行頭の空白
        // (?:              -> グループ開始
        //     \d+          -> 少なくとも1つの数字 (最初の数値)
        //     (?:,\d+)*    -> カンマと数字が0回以上繰り返される (残りの数値)
        // )                -> グループ終了
        // (?:,\d*|\s*)$     -> 末尾のカンマと数字の組み合わせ、または空白のみを許容。
        // 
        // より単純に、「数字とカンマのみ」で構成され、かつ「少なくとも1つの数字」を含むことを確認します。
        // 妥当なパターン: 数字とカンマのみで構成され、かつ、少なくとも一つの数字が含まれる。
        // 例: "1,2,3" や "1," や "," ではない。
        // 
        // 妥当な形式: 1つ以上の数値とカンマの組み合わせ。
        // (?:(\d+(?:,\d+)*))  -> 1つ以上の数値とカンマの組み合わせ (例: 1,2,3)
        // (?:,\d*)*          -> 末尾のカンマの許容 (例: 1,2,)
        // 
        // 最終的なパターンとして、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
        // \d[\d,]*$ : 数字で始まり、カンマを含む、数字で終わる。
        // 
        // 仕様の解釈を厳密に適用すると、「カンマで区切られた整数列」が複数あることを意味します。
        // 例: "1,2" (2つの整数列)
        // 
        // パターン: (数字,カンマ,数字の繰り返し)
        // ^\s*(\d+(?:,\d+)*)(?:,?\d*)?\s*$
        // これは複雑すぎるため、行の内容が「数字とカンマのみ」で構成され、かつ、その中で数字が少なくとも1つ存在すれば妥当とします。

        // 妥当な行の判定: 数字とカンマのみで構成され、かつ、少なくとも1つの数字が含まれている。
        // 数字とカンマ以外の文字が含まれる行は除外される。
        // 空行は除外される。

        // 妥当なパターン: 少なくとも1つの数字が含まれ、数字とカンマ以外の文字を含まない。
        // 1. 数字とカンマのみで構成されることを保証する (数字とカンマ以外は許容しない)
        // 2. 少なくとも1つの数字が含まれることを保証する。

        // 妥当な行の判定のための正規表現 (行全体が数字とカンマのみで構成され、かつ数字が含まれていることを確認)
        // ^\s*             -> 行頭の空白
        // (?:              -> 非キャプチャグループ
        //     \d+          -> 少なくとも1つの数字 (最初の数値)
        //     (?:,\d+)*    -> カンマと数字の繰り返し
        // )                -> 1つ以上の数値がカンマで区切られている部分
        // (?:,\d*|\s*)$     -> 末尾のカンマや空白の許容
        
        // 非常に厳密に「カンマ区切りの整数列」を判定するには、数字とカンマのみで構成され、かつ、カンマが存在するか、単一の数字である必要があります。
        // 妥当なパターン: 少なくとも1つの数字が含まれ、数字とカンマ以外を含まない。
        // 
        // 妥当な行は、数字とカンマのみで構成され、かつ、カンマの有無に関わらず、少なくとも1つの数値が存在すること。
        // 
        // パターン: 数字またはカンマのみで構成され、かつ、数字が少なくとも1つ存在すること。
        // この仕様は、入力が「カンマ区切りの整数列」であるという前提に基づいています。
        
        // 妥当な行の判定をシンプルに：
        // 1. 空行でないこと。
        // 2. 数字とカンマ以外の文字を含まないこと。
        // 3. 少なくとも1つの数字が含まれていること。
        
        // 妥当な文字列の例: "1,2", "1,", "123"
        String regex = "^\\s*([0-9,]+)\\s*$"; // 数字とカンマのみを含む
        Pattern pattern = Pattern.compile(regex);

        while (br.ready()) {
            String line = br.readLine();
            if (line == null) {
                break;
            }

            String trimmedLine = line.trim();

            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 1. 数字とカンマ以外を含む行の判定（正規表現でチェック）
            if (!pattern.matcher(line).matches()) {
                // 数字とカンマ以外を含む行は妥当ではない
                continue;
            }

            // 2. 少なくとも1つの数字が含まれているかチェック
            // lineから数字のみを抽出して確認する
            boolean containsDigit = false;
            for (char c : line.toCharArray()) {
                if (Character.isDigit(c)) {
                    containsDigit = true;
                    break;
                }
            }

            if (containsDigit) {
                // 3. 妥当な行としてカウント
                validCount++;
            }
        }

        System.out.println("valid=" + validCount);
    }
}
