import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.Scanner;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int validCount = 0;

        while (scanner.hasNextLine()) {
            String line = scanner.nextLine();

            // 行の前後の空白を無視する
            String trimmedLine = line.trim();

            // 1. 空行の判定
            if (trimmedLine.isEmpty()) {
                continue;
            }

            // 2. 正規表現による妥当性の判定
            // 妥当なパターン: 1個以上の整数がカンマで区切られていること。
            // パターン: (数字とカンマの繰り返し) または (数字のみ)
            // 厳密には「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する必要があります。
            // これは、数字とカンマのみで構成されており、少なくとも1つの数字が含まれていることを意味します。
            // 正規表現の解釈:
            // ^                 : 行の先頭
            // [0-9,]*            : 0個以上の数字またはカンマ
            // (?=\d)             : 後続に少なくとも1つの数字が続くことを確認 (空行やカンマのみでないことを保証するため)
            // .*                : 残りの文字列
            // $                 : 行の末尾

            // よりシンプルなアプローチ: 
            // 行が数字とカンマのみで構成されており、かつ数字が含まれているかを確認する。
            // 仕様: 「1 個以上の数字列がカンマで区切られて並んでいる」
            // これは、カンマで区切られた後に数字が続いている、または数字が連続している形を許容します。
            // 末尾のカンマは許容されます。

            // 妥当な行の定義を正規表現で表現します。
            // 1. 少なくとも1つの数字が含まれていること。
            // 2. 数字とカンマ以外の文字が含まれていないこと。
            // 3. 末尾にカンマがあってもよいこと。

            // パターン: (数字とカンマが混在) または (数字のみ)
            // 任意の数の数字とカンマのみで構成されていることを確認します。
            // 1. 少なくとも1つの数字が含まれていることを保証するため、数字が最低1つ必要。
            // 2. 許可される文字は数字(0-9)とカンマ(,)のみ。
            // 3. 末尾のカンマは許容される。

            // [0-9,]* : 0個以上の数字またはカンマ
            // .*      : 残りの任意の文字（ここでは不要だが、行全体をチェックするため）
            
            // 妥当な行は、数字とカンマのみで構成され、かつ数字が少なくとも1つ含まれている。
            // 末尾のカンマは許容されます。
            // 例: "1,2,3", "1,2,", "123" はOK。
            // 例: ",," はNG (数字が0個)
            
            // 正規表現: 
            // ^[0-9,]*$ : 数字とカンマのみで構成されていること (末尾のカンマも含む)
            // このパターンだけだと、",," はマッチしてしまうため、数字の存在を別途確認する必要があります。

            // 最も厳密に「1個以上の数字列」を表現するには、カンマで区切られた後に数字が存在することを要求します。
            // (?:[0-9],)*[0-9]+ : 1つ以上の数字列がカンマで区切られているパターンを試みる。
            // ただし、数字が連続している場合も許容されるため、より緩やかにします。

            // 行が数字とカンマのみで構成されているかを確認し、かつ数字が1つ以上あることを確認する。
            // 妥当な行のパターン: 
            // 任意の文字（数字またはカンマ）が0個以上続き、かつ、その中に少なくとも1つの数字が存在する。
            String regex = "^[0-9,]*$";
            
            if (Pattern.matches(regex, trimmedLine)) {
                // 数字が含まれているかチェック
                boolean containsDigit = false;
                for (char c : trimmedLine.toCharArray()) {
                    if (Character.isDigit(c)) {
                        containsDigit = true;
                        break;
                    }
                }
                
                if (containsDigit) {
                    validCount++;
                }
            }
        }

        System.out.println("valid=" + validCount);
        scanner.close();
    }
}
