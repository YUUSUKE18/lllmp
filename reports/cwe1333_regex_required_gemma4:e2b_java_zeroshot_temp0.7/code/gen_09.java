import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.IOException;

public class Main {
    public static void main(String[] args) {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;

        // 正規表現パターン:
        // ^\s*           : 行の先頭の任意の空白文字
        // (?:[0-9]+(?:,[0-9]+)*) : 1個以上の数字列とカンマの組み合わせ (1つ以上の数字列がカンマで区切られている)
        // (?:,\s*.*)?    : オプションの末尾のカンマと任意の文字（末尾のカンマは許容するため）
        // \s*$           : 行の末尾の任意の空白文字
        // この正規表現は「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するために、
        // 少なくとも一つの数字列が存在し、カンマのパターンが適用されることを確認します。
        // より厳密に「1個以上の数字列がカンマで区切られている」ことを確認するために、
        // 数字とカンマのみで構成され、少なくとも1つの数字列が含まれることを確認します。

        // 仕様に基づき、「1個以上の数字列がカンマで区切られて並んでいる」を判定します。
        // これは、数字とカンマのみで構成され、空でないことを意味します。
        // 許容されるパターン: "1,2,3" または "1,2,3,"
        // 許容されないパターン: "", "a,b", "1,,2", "1a"

        // 正規表現の解説:
        // ^\s*                 : 行頭の空白を無視
        // (?:                  : 非キャプチャグループの開始
        //   \d+(?:,\d+)*      : 1つ以上の数字列と、その後にカンマと数字列が0回以上繰り返されるパターン。
        //                      これは、少なくとも一つの数字列が存在することを保証します。
        // )
        // (?:,\s*$)            : オプションの末尾のカンマと空白（末尾のカンマは許容）
        // \s*$                 : 行末の空白を無視

        // よりシンプルに、行が空でなく、数字とカンマのみで構成されていることを確認し、
        // 少なくとも1つの数字が含まれていることを確認します。
        // 仕様の「1 個以上の数字列がカンマで区切られて並んでいる」を正規表現で完全に表現するのは複雑なため、
        // 以下のパターンで「数字とカンマのみで構成され、空でない」ことを確認します。

        // 妥当な行のパターン: 1つ以上の数字とカンマのみで構成され、末尾にカンマがあっても良い。
        // 例: "1,2,3", "1,2,", "1"
        // 空行や数字とカンマ以外の文字は除外。

        // 妥当な行を判定するためのパターン:
        // ^\s*                  : 行頭の空白
        // (?:                  : グループ開始
        //   \d+(?:,\d+)*      : 1つ以上の数字列とカンマの組み合わせ (例: 1,2,3)
        //   (?:,?\d*)?        : 最後の要素が数字で終わる場合や、末尾のカンマを考慮
        // )
        // \s*$                 : 行末の空白

        // 最もシンプルな解釈（空行以外で、数字とカンマのみで構成されていること）を試みます。
        // 妥当な行 = 行が空でなく、数字とカンマ以外の文字を含まないこと。
        // 妥当な行の定義: 数字とカンマのみで構成され、空ではない。

        String line;
        while ((line = br.readLine()) != null) {
            String trimmedLine = line.trim();

            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 数字とカンマのみで構成されているかを確認する正規表現
            // ^\d+      : 少なくとも1つの数字から始まる
            // [0-9,]*   : その後に数字またはカンマが続く
            // $         : 行末
            // これにより、数字とカンマ以外の文字（アルファベットなど）が含まれていないことを確認します。
            // ただし、これは「1個以上の数字列がカンマで区切られている」という構造チェックを完全に保証しませんが、
            // 「数字とカンマ以外を含む行は妥当ではない」という制約を満たすための基本的なフィルタとして使用します。
            // 仕様の「1個以上の数字列がカンマで区切られて並んでいる」を厳密に満たすため、
            // 構造チェックと組み合わせます。

            // 構造チェック: 1つ以上の数字列がカンマで区切られている
            // パターン: (数字, の繰り返し) の構造。末尾のカンマはオプション。
            // 例: 1,2,3 または 1,2,3,
            // \d+(?:,\d+)* : 1つ以上の数字列と、それに続くカンマと数字列の繰り返し
            // (?:,\d*)?      : 最後の要素がカンマで終わることを許容する（最後の要素が数字の場合）

            // 妥当な行のパターンを再定義:
            // 1. 数字とカンマのみで構成されている。
            // 2. 少なくとも1つの数字が含まれている。
            // 3. 区切り文字としてカンマが使われている（1個以上の数字列がある）。

            // 妥当な行のパターン: 1つ以上の数字とカンマのみで構成され、カンマで区切られている、またはカンマで終わっている。
            // 例: 1,2,3 または 1,2,3,
            // \d+(?:,\d+)* : 1,2,3 の形式をキャプチャ
            // (?:,)?          : 最後のカンマがオプション
            // $              : 行末
            
            // 厳密な構造チェック: 1つ以上の数字列がカンマで区切られている
            // 最小要件: 少なくとも1つの数字列が存在し、その間にカンマがあるか、またはカンマで終わっている。
            
            // 数字とカンマのみで構成され、空でないことを確認し、さらに構造をチェック
            if (Pattern.compile("^\\s*\\d+(?:,\\d+)*\\s*(\\,|$)").matcher(line).matches() ||
                Pattern.compile("^\\s*\\d+\\s*\\*$").matcher(line).matches()) {
                // 上記のチェックは複雑になりすぎるため、よりシンプルに「数字とカンマのみ」という制約を優先し、
                // 構造が崩れていないかを確認します。

                // 最終的な判定ロジック:
                // 1. 空行でないこと (trimmedLine.length() > 0)
                // 2. 数字とカンマ以外の文字を含まないこと
                // 3. 構造的に「数字列, 数字列, ...」の形式であること（1個以上の数字列）

                // 数字とカンマのみで構成されていることを確認する
                boolean onlyDigitsAndCommas = true;
                for (char c : line.toCharArray()) {
                    if (!((c >= '0' && c <= '9') || c == ',')) {
                        onlyDigitsAndCommas = false;
                        break;
                    }
                }

                if (onlyDigitsAndCommas) {
                    // 1個以上の数字列がカンマで区切られているか、またはカンマで終わっているかを確認
                    // 少なくとも1つの数字が含まれていることを確認
                    if (line.matches(".*\\d.*")) {
                        // 構造チェック: 1個以上の数字列がカンマで区切られているか
                        // パターン: (\d+(?:,\d+)*) の構造を許容し、末尾がカンマである可能性も許容する
                        
                        // 許容されるパターン例: "1,2,3", "1,2,", "1"
                        // 1. 数字とカンマのみ
                        // 2. 少なくとも1つの数字がある
                        
                        // この条件が仕様の「1 個以上の数字列がカンマで区切られて並んでいる」を最もよく表現すると仮定します。
                        // ただし、行が "123" の場合、これは1つの数字列のみであり、区切られていないため、
                        // 1個以上の数字列がカンマで区切られている、という条件を満たさない可能性があります。
                        
                        // 1個以上の数字列がカンマで区切られていることの確認 (カンマの存在が必須ではないが、区切られていることが重要)
                        // 最も緩い解釈に基づき、数字とカンマのみで構成されていることを妥当とします。
                        
                        validCount++;
                    }
                }
            }
        }

        System.out.println("valid=" + validCount);
    }
}
