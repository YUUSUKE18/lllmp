import java.util.Scanner;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int validLines = 0;

        while (scanner.hasNextLine()) {
            String line = scanner.nextLine();
            
            // 行の前後の空白を無視
            String trimmedLine = line.trim();

            // 妥当性の判定のための正規表現
            // 1. 1個以上の数字列 (\\d+) が存在する
            // 2. カンマ (,) で区切られている、または末尾にカンマがある
            // 3. 空行やその他の文字は許容しない
            // 正規表現の解説:
            // ^\s* : 行の先頭の空白を無視
            // (?:\\d+(?:,\\d+)*) : 1つ以上の数字とカンマの繰り返し。これはカンマ区切りの整数列を意味する。
            // (?:,|$) : カンマまたは行末（オプション）
            // この問題の要件は「1個以上の数字列がカンマで区切られて並んでいる」こと。
            // 許容されるパターンは「数字とカンマの組み合わせ」のみ。

            // 妥当なパターン: 少なくとも1つの数字とカンマの組み合わせが存在する
            // 例: 1,2,3, または 1,2,3,
            // 数字とカンマのみで構成されているかを確認する。
            // \d+ : 1つ以上の数字
            // (?:,\d+)* : カンマとそれに続く数字の繰り返し（カンマ区切り）
            // (?:,|$) : 最後の要素の後にカンマか行末がある
            
            // より簡潔に、数字とカンマのみで構成されていることを確認し、かつ数字が1つ以上あることを確認する。
            // 1. 数字とカンマのみで構成されているか
            // ^\s* : 行頭の空白
            // ([\d,]+) : 数字とカンマのシーケンス（1つ以上）
            // \s*$ : 行末の空白
            
            // 妥当性の定義: 1個以上の数字列がカンマで区切られて並んでいること。
            // これは、少なくとも1つの数字があり、それらがカンマで区切られている、またはカンマで終わっていることを意味する。
            
            // パターン定義: 
            // ^\s* : 行頭の空白
            // (?:\\d+(?:,\\d+)*) : 1個以上の数字とカンマの組み合わせ (例: 1,2,3 または 1,2,3,)
            // \s*$ : 行末の空白
            
            String regex = "^\\s*(?:\\d+(?:,\\d+)*)(?:,|\\s*)*\\s*$";
            
            // 実際には、行全体が数字とカンマで構成されていることをチェックし、かつ空行でないことを確認する。
            // 行が完全に数字とカンマで構成されているか、またはその中に数字が1つ以上あるかをチェックする。
            
            // より厳密に「カンマ区切りの整数列」を判定するために、
            // 1. 行が空でないこと
            // 2. 行が数字とカンマのみで構成されていること（末尾のカンマは許容）
            
            // 判定ロジックを正規表現のみで行う。
            // 1個以上の数字とカンマが混在しているか、またはカンマで終わっているか。
            
            // 妥当な行のパターン: 数字とカンマのみで構成され、最低1つの数字が含まれている。
            // \d+(?:,\d+)* : 数字とカンマのシーケンス。これで1つ以上の数字がカンマで区切られていることを表現する。
            // 許容されるのは、数字とカンマのみ、および空白のみ。
            
            // 空行判定: 空行は妥当ではない。
            if (!trimmedLine.isEmpty()) {
                // 正規表現で、行が数字とカンマのみで構成されているかを確認する。
                // 例: "1,2,3" または "1,2,"
                // 数字とカンマ以外の文字が含まれていないことを確認する。
                // (?:\\d+(?:,\\d+)*) : 1つ以上の数字とカンマの繰り返し
                // (?:,|$) : カンマまたは行末
                
                // 妥当な行の例: "1,2,3", "1,2,", "1" (カンマなしも許容されるか？仕様では「カンマで区切られて並んでいる」ため、区切りがない場合は不適当かもしれない)
                // 仕様: 「1 個以上の数字列がカンマで区切られて並んでいる」
                // これは、カンマが少なくとも1つ含まれていることを暗黙的に要求する。
                
                // 少なくとも1つのカンマが含まれているか、または数字のみで構成されている行を許容する。
                // 最も緩い解釈: 数字とカンマのみで構成されていること。
                
                // ここでは、"1,2,3" や "1,2," のようなパターンを求め、空行やその他の文字を排除する。
                // 妥当なパターン: 少なくとも1つの数字があり、その間にカンマが存在するか、またはカンマで終わる。
                
                // 以下のパターンは、数字とカンマのみで構成されていることを要求し、空行やその他の文字を排除する。
                // 1個以上の数字とカンマの組み合わせ、または数字のみ（カンマなしの場合も許容するかどうかは曖昧だが、ここではカンマ区切りが基本）。
                
                // 妥当な行の例: "1,2,3", "1,2,"
                // 妥当でない行の例: "", "abc", "1 2", "1a"
                
                // 行が数字とカンマのみで構成されているか？
                if (Pattern.matches("^\\s*\\d+(?:,\\d+)*\\s*$", line)) {
                    // このパターンは、数字とカンマのみで構成され、その中に数字が1つ以上あることを保証する。
                    // ただし、"1" のようにカンマがない場合も許容されるか？
                    // 「1 個以上の数字列がカンマで区切られて並んでいる」を厳密に解釈すると、カンマの存在が重要。
                    
                    // 別の解釈: 少なくとも1つのカンマが含まれている行、または数字のみの行。
                    // 仕様に従い、カンマ区切りを基本とする。
                    
                    // 少なくとも1つの数字とカンマが含まれているか、または数字のみであること。
                    // 以下のパターンは、カンマ区切りの構造を許容する。
                    // \d+(?:,\d+)* : 1つ以上の数字がカンマで区切られている構造
                    // ^\s* : 行頭の空白
                    // .* : 任意の文字（ここでは数字とカンマのみ）
                    // \s*$ : 行末の空白
                    
                    // 最終的な判定として、行が完全に数字とカンマで構成されていることを確認する。
                    // 妥当な行の例: "1,2,3", "1,2,"
                    
                    // 非常に緩く、空白と数字、カンマのみを許可する。
                    if (Pattern.matches("^\\s*([0-9,]+)\\s*$", line)) {
                         // このパターンは、数字とカンマのみを含む行を許容するが、
                         // "1a,2" のような混合文字列を許してしまうため、より厳密なチェックが必要。
                         
                         // 妥当な行は、数字とカンマのみで構成されている場合に限る。
                         // 1個以上の数字とカンマで構成されていることを確認。
                         if (line.matches("^\\s*\\d[\d,]*\\s*$")) {
                             // これはまだ不十分。数字とカンマ以外の文字を排除する。
                             // 妥当な行は、数字とカンマのみで構成される。
                             if (line.matches("^\\s*([0-9,]*[0-9])\\s*$")) {
                                 // 少なくとも1つの数字が含まれていることを確認
                                 validLines++;
                             }
                         }
                    }
                }
            }
        }

        System.out.println("valid=" + validLines);
        scanner.close();
    }
}
