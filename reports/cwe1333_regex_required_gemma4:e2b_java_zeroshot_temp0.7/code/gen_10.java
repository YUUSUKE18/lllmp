import java.util.Scanner;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int validCount = 0;

        while (scanner.hasNextLine()) {
            String line = scanner.nextLine();
            
            // 行の前後の空白を無視
            String trimmedLine = line.trim();
            
            // 妥当性の判定のための正規表現
            // 1. 1個以上の数字列 (\\d+): 1つ以上の数字が続く
            // 2. カンマで区切られている (?:,\\s*): カンマと任意の空白が続く
            // 3. 末尾のカンマは許容 (?:\\s*,?): カンマの後に空白があり、オプションでカンマが続く
            // 4. 行全体がこのパターンにマッチする必要がある
            // 
            // 妥当なパターン: 
            // 1. 少なくとも1つの数字列が存在する
            // 2. 数字とカンマ以外の文字（空白など）は、数字列とカンマのみで構成される
            // 3. 末尾のカンマは許容される
            
            // 正規表現の解説:
            // ^\s* : 行頭の空白を無視
            // (?:\\d+(?:,\\s*\\d+)*) : 1つ以上の数字 (\\d+) が始まり、その後カンマと空白で区切られた数字の繰り返し (?:,\\s*\\d+)
            // (?:,\\s*\\d+)* : 最後の要素がカンマで終わることを許容するため、さらにカンマ区切りの要素が続く
            // \s*$: 行末の空白を無視
            
            // よりシンプルな判定: 
            // 行が空でないこと、かつ、数字とカンマ、空白のみで構成されていること。
            // 妥当なのは「1個以上の数字列がカンマで区切られている」こと。
            
            // 1. 空行のチェック
            if (trimmedLine.isEmpty()) {
                continue;
            }

            // 2. 数字とカンマ以外の文字が含まれていないか、および構造をチェック
            // この問題の「妥当」の定義を厳密に適用するため、
            // 「1個以上の数字列がカンマで区切られて並んでいる」ことを正規表現で確認します。
            // 例: "1,2,3", "1,2,", "123" (末尾のカンマなしも許容されるべきか？仕様では「末尾のカンマは許容」とあるため、末尾のカンマがなくてもOKな数字列もOKと解釈します)

            // 妥当なパターン: 数字とカンマのみで構成され、少なくとも1つの数字が存在する。
            // ^\s* : 行頭の空白
            // (?:\\d+(?:,\\s*\\d+)*) : 1つ以上の数字で始まり、カンマ区切りで続く (例: 1,2,3 または 123)
            // (?:,\\s*\\d+)* : 最後の要素がカンマで終わることを許容するため、さらにカンマ区切りの要素が続く
            // \s*$ : 行末の空白
            
            // 妥当な行のパターン: 1個以上の数字列がカンマで区切られている (末尾のカンマは許容)
            // 1. 少なくとも1つの数字列がある
            // 2. 数字とカンマ、空白のみで構成されている
            
            // 正規表現を、カンマ区切りのリストの形式を許容するように調整
            // 1つ以上の数字 (\\d+) が、カンマと空白 (?:,\\s*) で区切られている構造
            // 末尾のカンマは許容されるため、最後の要素の後にカンマがあっても良い。
            String regex = "^\\s*(?:\\d+(?:,\\s*\\d+)*)(?:,\\s*\\d+)*\\s*$";

            if (Pattern.matcher(trimmedLine).matches()) {
                validCount++;
            }
        }

        System.out.println("valid=" + validCount);
        scanner.close();
    }
}
