import * as readline from 'readline';

function solve() {
    const rl = readline.createInterface({
        input: process.stdin,
        output: process.stdout,
        crlfDelay: Infinity
    });

    let lines: string[] = [];

    rl.on('line', (line) => {
        lines.push(line);
    });

    rl.on('close', () => {
        let validCount = 0;
        const regex = /^(\d+,\d+)*\d+?$|^(\d+)(,\d+)*$/;

        for (const line of lines) {
            const trimmedLine = line.trim();

            if (trimmedLine.length === 0) {
                continue; // 空行は妥当ではない
            }

            // 末尾のカンマが許容されることを考慮し、行全体をチェックする正規表現を工夫する
            // 妥当な形式: 1個以上の数字とカンマの組み合わせ。末尾のカンマは許容される。
            // 少なくとも1つの数字が含まれている必要がある。
            // 許容されるパターン: "1,2,3" または "1,2," または "1,2,3,"
            // 数字とカンマのみで構成され、少なくとも1つの数字が含まれていること。

            // 正規表現の解説:
            // ^                                     # 行の先頭
            // (?:                                    # 非キャプチャグループ: ゼロ回以上繰り返す
            //   \d+                                  # 1つ以上の数字
            //   ,                                    # カンマ
            // )*                                     # 上記グループが0回以上繰り返される
            // \d                                     # 少なくとも1つの数字（最後の数字）
            // (?:,)?                                 # カンマがオプションで続く
            // $                                      # 行の末尾
            //
            // よりシンプルに、数字とカンマが混在し、少なくとも1つの数字が存在し、末尾がカンマで終わるか数字で終わることを確認する。

            // 妥当な行の判定ロジックを正規表現で実現する。
            // 少なくとも1つの数字とカンマの組み合わせがあり、数字のみで終わるかカンマで終わる。
            // 例: "1", "1,2", "1,2,"
            // 負例: "", "a,b", "1,,2" (連続カンマは許容しないと解釈)

            // 以下の正規表現は、「数字とカンマが交互に並んでおり、少なくとも1つの数字が含まれている」ことを確認する。
            // ここでは、カンマ区切りの整数列が並んでいることを確認する。
            // 1個以上の数値とカンマのシーケンス、または単一の数値。末尾のカンマは許容。

            // パターン1: 少なくとも1つの数字が存在し、数字とカンマのみで構成されている。
            // ( \d+ (?:, \d+)* )  -> 1つ以上の数字、それに続くカンマと数字の繰り返し
            // |\d+               -> 単一の数字
            // |                  -> または
            // (?: \d+(?:,|$))*  -> 任意の数字とカンマの組み合わせ (末尾のカンマは許容)

            // 最終的な判定基準：行に数字とカンマのみが含まれ、最低1つの数字があること。
            const pattern = /^[\d,]+$/; // 数字とカンマのみで構成されていること

            if (!pattern.test(trimmedLine)) {
                // 数字やカンマ以外の文字が含まれている場合、またはカンマの連続など不正な形式の場合
                continue;
            }

            // 念のため、最低1つの数字が含まれていることを確認する (これは上記パターンで既にカバーされるはずだが、念のため)
            if (trimmedLine.split(/,/).filter(s => s.length > 0).length === 0) {
                continue;
            }

            // 妥当な行としてカウント
            validCount++;
        }

        console.log(`valid=${validCount}`);
    });
}

solve();
