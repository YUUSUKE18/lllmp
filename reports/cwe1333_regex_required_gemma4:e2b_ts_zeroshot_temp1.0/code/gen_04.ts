import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim().split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*          -> 行の先頭の空白を無視
    // (?:           -> 非キャプチャグループ開始 (1個以上の数字列がカンマで区切られていることを確認)
    //   \d+         -> 1つ以上の数字
    //   (?:,\d+)*   -> カンマと1つ以上の数字の繰り返し (数字列がカンマで区切られていることを意味する)
    // )             -> グループ終了
    // \s*           -> 行末の空白を無視
    // $             -> 行末
    // 末尾のカンマを許容するため、マッチングの後に続く可能性のあるカンマを考慮する必要があるが、
    // 問題文の「1 個以上の数字列がカンマで区切られて並んでいる」を厳密に解釈する。
    // 具体的には、数字とカンマのみで構成され、少なくとも1つの数字列が存在すればよい。
    // 末尾のカンマは許容する。

    // 新しい正規表現の試み:
    // 1. 空行、または数字とカンマ以外の文字を含む行は不適格。
    // 2. 少なくとも1つの数字列が存在し、カンマ区切りであること。

    // パターン: 
    // ^\s*                  -> 行頭の空白
    // (?:                   -> グループ開始 (非キャプチャ)
    //   \d+                 -> 最初の数字列
    //   (?:,\d+)*           -> カンマと数字の繰り返し (0回以上)
    // )                     -> グループ終了
    // [\d,]*                 -> その後、数字またはカンマが続くことを許容 (末尾のカンマ許容のため)
    // \s*$                  -> 行末の空白

    // よりシンプルな解釈:
    // 行が空でないこと。
    // 行が数字とカンマのみで構成されていること。
    // 少なくとも1つの数字列が存在すること。

    // 妥当な行の判定ロジック:
    // 1. 行をトリムして空でないことを確認。
    // 2. 正規表現で数字とカンマのみで構成されていることを確認。
    // 3. 正規表現で少なくとも1つの数字が存在することを確認。

    const regex = /^\s*(\d+(?:,\d+)*)\s*$/; // 数字とカンマのみで構成され、少なくとも1つの数字列が存在するパターン

    for (const line of input) {
        const trimmedLine = line.trim();

        if (trimmedLine === "") {
            continue; // 空行は不適格
        }

        // 正規表現による判定
        // 末尾のカンマの許容について再検討:
        // 「1 個以上の数字列がカンマで区切られて並んでいる」
        // 例: "1,2,3" -> OK
        // 例: "1,2," -> OK (末尾のカンマ許容)
        // 例: "1" -> OK
        // 例: ",," -> NG (数字列が1個以上必要)
        // 例: "abc" -> NG
        // 例: "1a,2" -> NG

        // 正規表現: 1つ以上の数字が、カンマと数字のシーケンスで構成されていること。
        // 任意の数字列がカンマで区切られていることを保証する。
        const validationRegex = /^[\d,]+$/; // 数字とカンマのみで構成されているか

        if (validationRegex.test(trimmedLine)) {
            // さらに、少なくとも1つの数字が存在するか確認する。
            // 0個の数字列（例: "," または空文字列）はNG。
            const containsDigit = /\d/.test(trimmedLine);
            
            if (containsDigit) {
                validCount++;
            }
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
