import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim().split('\n');
    let validCount = 0;

    // 正規表現の定義
    // ^\s*        : 行頭の任意の空白
    // (            : グループ開始
    //   \d+        : 1つ以上の数字
    //   (?:,\d+)* : カンマとそれに続く1つ以上の数字の繰り返し (カンマ区切りの整数列)
    // )            : グループ終了
    // \s*$        : 行末の任意の空白
    // この正規表現は、数字とカンマのみで構成され、少なくとも1つの数字列が含まれていることを確認します。
    // 末尾のカンマも許容されます。
    const validRegex = /^\s*(\d+(?:,\d+)*)\s*$/;

    for (const line of input) {
        const trimmedLine = line.trim();

        // 1. 空行の判定（空行は妥当ではない）
        if (trimmedLine.length === 0) {
            continue;
        }

        // 2. 数字とカンマ以外を含む行の判定
        // 正規表現で、行全体が数字とカンマのみで構成されているかを確認する
        // ただし、仕様では「数字とカンマ以外を含む行は妥当ではない」とあるため、
        // 以下のチェックで、数字とカンマ以外の文字が含まれていないかを確認します。
        if (!/^[0-9,]*$/.test(trimmedLine)) {
            continue; // 数字とカンマ以外が含まれている場合はスキップ
        }

        // 3. カンマ区切りの整数列の妥当性の判定
        // 正規表現を適用して、1個以上の数字列がカンマで区切られているかを確認する
        // 正規表現の調整: 末尾のカンマを許容するため、行全体にマッチさせる。
        // 例: "1,2,3" はマッチする。 "1,2," はマッチする。 "1" はマッチする。
        
        // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する
        // (数字とカンマのみで構成され、かつ、少なくとも1つの数字列が存在する)
        
        // 正規表現の再評価:
        // ^\s*            : 行頭の空白
        // (              : グループ開始
        //   \d+          : 最初の数字列
        //   (?:,\d+)*    : カンマとそれに続く数字列の繰り返し (0回以上)
        // )              : グループ終了
        // \s*$            : 行末の空白
        
        // この正規表現は、カンマで区切られた数字列が1つ以上存在することを保証します。
        // 例: "1,2" -> マッチ
        // 例: "1" -> マッチ
        // 例: "," -> マッチしない (数字がないため)
        // 例: "abc" -> 前のチェックで除外されるはずだが、念のため。
        
        // 以下のチェックを適用します。
        const match = trimmedLine.match(/^\s*(\d+(?:,\d+)*)\s*$/);
        
        if (match) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
