import * as fs from 'fs';

function solve() {
    // 標準入力全体を読み込む
    const input = fs.readFileSync(0, 'utf8').trim();
    
    // 行ごとに分割する
    const lines = input.split('\n');
    
    let validCount = 0;
    
    // 各行を判定する
    for (const line of lines) {
        // 行の前後の空白を無視して、行の内容を処理する
        const trimmedLine = line.trim();
        
        if (trimmedLine === '') {
            // 空行は妥当ではない
            continue;
        }
        
        // 正規表現で判定する
        // 妥当な行: 1個以上の数字とカンマが混在している（または純粋な数字列）
        // 許容されるパターン: 1個以上の数字とカンマの組み合わせ。末尾のカンマは許容。
        // 少なくとも1つの数字が含まれていることが必須。
        // 数字(\d)とカンマ(,)が0回以上連続するパターンをチェックする。
        // 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」こと。
        // これは、数字とカンマのみから構成され、少なくとも1つの数字が含まれていることを意味する。
        // 正規表現: (?:[\d,]+) のように、数字とカンマの組み合わせが存在するかどうかをチェックする。
        
        // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
        // これは、行が数字とカンマのみで構成されており、かつ空でないことを意味する。
        // 1. 数字またはカンマのみで構成されていること: /^[0-9,]*$/
        // 2. 少なくとも1つの数字が含まれていること: /\d/
        
        // 仕様に基づくと、
        // 「1 個以上の数字列がカンマで区切られて並んでいる」
        // 例: "1,2,3", "123", "1,2,"
        
        // 単純に、数字とカンマのみで構成されており、かつ数字が1つ以上あるかを確認する。
        // この問題の解釈として、行が数字とカンマの文字列のみで構成され、
        // 少なくとも1つの数字が含まれている場合に「妥当」と判断します。
        
        // 正規表現の適用:
        // ([\d,]+) : 1つ以上の数字またはカンマのシーケンス
        // この行が「数字とカンマのみ」で構成されていることを確認し、
        // 少なくとも1つの数字が存在することを保証する。
        
        // 行が数字とカンマのみで構成されているかを確認し、かつ数字が1つ以上あるかを確認する。
        // もし行が「1,2,」や「123」など、数字とカンマのみで構成されていれば、それは「カンマ区切りの整数列」のパターンであると見なす。
        const regex = /^[\d,]+$/;
        
        if (regex.test(trimmedLine)) {
            // 数字とカンマのみで構成されている
            // さらに、少なくとも1つの数字が含まれているかを確認する。（例: "," は不適）
            if (/\d/.test(trimmedLine)) {
                validCount++;
            }
        }
    }
    
    // 結果を出力
    console.log(`valid=${validCount}`);
}

solve();
