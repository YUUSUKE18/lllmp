import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim().split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*          -> 行頭の任意の空白
    // (?:           -> 非キャプチャグループの開始 (数字とカンマの列を定義するため)
    //   \d+         -> 1つ以上の数字
    //   (?:,\d+)*   -> カンマと1つ以上の数字の繰り返し (カンマ区切りの整数列)
    // )             -> グループの終わり
    // \s*$          -> 行末の任意の空白
    // この正規表現は、行が「カンマ区切りの整数列」のみで構成されていることを確認するために使われます。
    // 仕様では「1 個以上の数字列がカンマで区切られて並んでいること」が妥当の定義です。
    // これは、カンマで区切られた数字のシーケンス（数字とカンマのみ）が完全に一致するかどうかをチェックします。

    const validRegex = /^(?:(\d+(?:,\d+)*))?$/;

    for (const line of input) {
        const trimmedLine = line.trim();

        if (trimmedLine.length === 0) {
            // 空行は妥当ではない (仕様: 空行は妥当ではない)
            continue;
        }

        // 末尾のカンマは許容される (例: "1,2," は OK)
        // 正規表現を調整して、末尾のカンマを許容しつつ、数字とカンマ以外がないことを確認する。

        // 行全体が数字とカンマのみで構成されているかを確認し、
        // さらに「1個以上の数字列がカンマで区切られている」という構造を検証する。

        // ここでは、行が「数字とカンマ」のみで構成されていることを、
        // そして末尾がカンマで終わっても良い、という条件を満たすか確認します。

        // 正規表現の再定義:
        // ^\s*                 -> 行頭の空白
        // (?:                  -> 非キャプチャグループ
        //     \d+              -> 1つ以上の数字 (最初の数字列)
        //     (?:,\d+)*        -> カンマと数字の繰り返し (残りの数字列)
        // )?                   -> この全体が0回または1回出現 (これは少し複雑になるため、より単純なアプローチをとる)

        // シンプルなアプローチ：
        // 1. 数字とカンマ以外の文字がないかチェック。
        // 2. 少なくとも1つの数字が含まれているかチェック。
        // 3. 妥当な形式（カンマ区切り）を満たしているかチェック。

        let isValid = false;

        // 1. 数字とカンマのみを含むかチェック
        const containsOnlyDigitsAndCommas = /^[0-9,]*$/.test(trimmedLine);

        if (!containsOnlyDigitsAndCommas) {
            continue; // 数字とカンマ以外を含む行は妥当ではない
        }

        // 2. 1個以上の数字が含まれているかチェック
        if (!/\d/.test(trimmedLine)) {
            continue; // 数字がない行は妥当ではない
        }

        // 3. カンマ区切りの構造（1個以上の数字列がカンマで区切られている）をチェック
        // 末尾のカンマは許容される。
        // 例: "1,2,3" (OK), "1,2," (OK), "1" (OK)

        // この構造を表現する正規表現:
        // (数字またはカンマのまとまり)が繰り返され、かつ全体が数字で終わるか、カンマで終わる。
        // 任意の数字列の並び、または数字とカンマの並びを許容する。

        // "1" (OK), "1,2" (OK), "1,2," (OK)
        // "1,2,3" (OK)
        // "1,,2" (NG - カンマが連続している)
        // "1a2" (NG - 既に除外済み)

        // 連続するカンマのチェックを追加
        if (trimmedLine.includes(",,")) {
            continue; // カンマが連続している場合、妥当ではない
        }
        
        // 末尾のカンマは許容されているので、行が空でなければ妥当とする。
        // 上記のチェックで、空行、文字、連続カンマを除外できれば、残りは妥当と見なす。
        validCount++;
    }

    console.log(`valid=${validCount}`);
}

solve();
