import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^                 : 行の開始
    // [^,]*             : カンマ以外の任意の文字が0回以上続く (数字、空白など)
    // (?:,\d+(?:,\d+)*)?  : オプションで、カンマ区切りの整数列 (カンマで区切られた数字) が続く
    // (?:,.*)?          : 末尾のカンマとそれに続く任意の文字 (末尾のカンマを許容するため)
    // $                 : 行の終了
    // 
    // 仕様の要件を再検討すると、よりシンプルに「1個以上の数字列がカンマで区切られていること」を判定する必要があります。
    // 「1 個以上の数字列がカンマで区切られて並んでいること」
    // 例: "1,2,3", "1,2,", "1" (数字のみの場合も許容されるか？)
    // 仕様：「1 個以上の数字列がカンマで区切られて並んでいることです。末尾のカンマは許容します。」
    // 数字列が複数あることを保証するためには、カンマで区切られた数字のシーケンスがあることを確認します。
    // 
    // 数字列のシーケンス: (\d+(?:,\d+)*)
    // 1個以上あることを確認するためには、少なくとも1つの数字列が必要です。
    //
    // パターン案: 少なくとも1つの数字列があり、カンマで区切られている、または数字のみである。
    // 空行は無効。数字とカンマ以外を含む行は無効。
    
    // 行ごとの処理
    for (const line of lines) {
        const trimmedLine = line.trim();

        // 1. 空行の判定
        if (trimmedLine.length === 0) {
            continue;
        }

        // 2. 数字とカンマ以外を含む行の判定 (正規表現での検証)
        // 含まれる文字が数字(0-9)とカンマ(,)のみで構成されているか確認
        if (!/^[0-9,]*$/.test(trimmedLine)) {
            continue; // 数字とカンマ以外を含む行は無効
        }

        // 3. 妥当性の判定: 1個以上の数字列がカンマで区切られて並んでいること
        // パターン: (数字列) をカンマで区切る操作が何回かある
        // 最小の許容ケースは「1個以上の数字列」です。
        // 例: "1", "1,2", "1,2,"
        
        // 数字列のパターン: \d+(?:,\d+)*
        // このパターンにマッチするものが1回以上存在すれば良い。
        // 1. "1" の場合: \d+ にマッチ
        // 2. "1,2" の場合: \d+(?:,\d+)* にマッチ (1,2)
        // 3. "1,2," の場合: \d+(?:,\d+)* にマッチ (1,2)
        // 4. "1,,2" の場合: これは無効。正規表現で区切られた数字列が「1個以上」あることを確認する必要がある。

        // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するために、
        // 少なくとも一つの数字列が存在し、それがカンマで区切られている（または単独）ことを確認します。

        // 数字列のシーケンスを抽出するアプローチが、最も仕様に忠実です。
        // カンマで区切られた数字列のセットが1つ以上存在すればよい。
        
        // 1. カンマで分割してみる
        // 末尾のカンマを許容するため、最後にカンマが残っていても問題ない。
        const parts = trimmedLine.split(',');
        
        // 複数要素が存在し、かつ、その要素のいずれかが数字で構成されていることを確認する。
        // 全ての要素が空でないことを確認する必要はない。「数字列が並んでいる」こと。

        let hasNumberSequence = false;
        for (const part of parts) {
            if (part.length > 0 && /^\d+$/.test(part)) {
                hasNumberSequence = true;
            }
        }

        // 最終的な判定: 
        // 1. 空行は除外済み。
        // 2. 数字とカンマ以外は除外済み。
        // 3. 少なくとも1つの数字列が存在するか？
        //    - "1" -> parts=["1"] -> hasNumberSequence=true (OK)
        //    - "1,2" -> parts=["1", "2"] -> hasNumberSequence=true (OK)
        //    - "1," -> parts=["1", ""] -> hasNumberSequence=true (OK)
        //    - "," -> parts=["", ""] -> hasNumberSequence=false (OK, 妥当ではない)
        //    - "" (空行) -> 除外済み。

        if (hasNumberSequence) {
            validCount++;
        }
    }

    // 最終結果の出力
    console.log(`valid=${validCount}`);
}

solve();
