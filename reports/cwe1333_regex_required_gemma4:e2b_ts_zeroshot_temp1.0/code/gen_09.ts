import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim().split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*               - 行頭の任意の空白文字 (無視)
    // (?:               - 非キャプチャグループ開始
    //   \d+            - 1つ以上の数字
    //   (?:,\d+)*     - カンマと1つ以上の数字の繰り返し (カンマ区切りの整数列)
    // )                 - グループ終了
    // (?:,\d+)*         - 末尾のカンマが続く場合に対応するため、カンマと数字の繰り返し
    // \s*$              - 行末の任意の空白文字
    // このパターンは「1個以上の数字列がカンマで区切られて並んでいる」ことを検証します。
    // 末尾のカンマは許容されるため、行全体が (数字, 数字, ...) の形式になることを確認します。
    // ただし、仕様を厳密に解釈すると、「1個以上の数字列がカンマで区切られて並んでいる」ので、
    // 空白や数字とカンマ以外の文字を含まないことを確認する必要があります。

    // よりシンプルなアプローチ:
    // 1. 行が空でないかチェック
    // 2. 行が数字、カンマ、空白のみで構成されているかチェック
    // 3. 正規表現で「カンマ区切りの整数列」の形式を検証する

    // 正規表現の再考: 1個以上の数字列がカンマで区切られていることを確認する
    // 例: "1,2,3" または "1,2,"
    const validRegex = /^\s*(?:\d+(?:,\d+)*)\s*$/;

    for (const line of input) {
        const trimmedLine = line.trim();

        if (trimmedLine === "") {
            continue; // 空行は妥当ではない
        }

        // 数字とカンマ以外の文字が含まれていないかチェック
        // 仕様: 数字とカンマ以外を含む行は妥当ではない。
        if (!/^[0-9,]*$/.test(trimmedLine)) {
            continue; // 数字とカンマ以外を含む行は妥当ではない
        }

        // カンマ区切りの整数列であるかチェック
        // 1個以上の数字列がカンマで区切られているか、または単一の数字列であるかを検証。
        // 少なくとも1つの数字列が存在する。
        const parts = trimmedLine.split(',');
        
        // 妥当性の判定: 1個以上の数字列がカンマで区切られて並んでいる。
        // これは、splitの結果、要素がすべて空文字列でなく、かつ、
        // その要素群がすべて整数（数字のみ）で構成されていることを意味します。
        // また、"1" のような単一の数字列も許容されるべきです。
        
        let isValid = false;
        
        // partsに含まれる要素（各数字列）がすべて数字のみであることを確認
        const allAreDigits = parts.every(part => {
            // 空文字列はsplitの挙動によって発生する可能性があるため、これを許容する場合があるが、
            // 厳密には「1個以上の数字列」なので、要素が空でないことを確認したい。
            // ただし、末尾のカンマや連続カンマの処理が複雑になるため、正規表現で一括判定する。
            return /^\d+$/.test(part);
        });

        if (allAreDigits) {
            // すべての要素が数字列であれば、それは妥当である。
            // 例: "1,2,3" -> ["1", "2", "3"]
            // 例: "1," -> ["1", ""] (末尾カンマがある場合)
            // 例: "," -> ["", ""] (カンマのみの場合、これは不適)
            
            // 末尾のカンマが許容されるため、split後の最後の要素が空であっても許容する。
            // 例: "1,2," -> ["1", "2", ""]
            // 少なくとも1つの非空の数字列が存在すれば妥当。
            const nonEmptyDigits = parts.some(part => part.length > 0);
            
            if (nonEmptyDigits) {
                 validCount++;
            }
        }
    }

    // 最終的な出力
    console.log(`valid=${validCount}`);
}

solve();
