import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim();
    const lines = input.split('\n');
    let validCount = 0;

    // 正規表現パターン:
    // ^\s*               # 行の先頭の空白を無視
    // (?:                # 非キャプチャグループ: 括弧の有無に関わらず、全体をグループ化
    //   \d+             # 1つ以上の数字
    //   (?:,\d+)*       # カンマと1つ以上の数字の繰り返し（カンマ区切りの整数列）
    //   (?:,\d+)?       # 最後の数字の後にカンマが続く場合を考慮（末尾のカンマ許容のため）
    // )
    // $                 # 行の終端

    // 仕様の「1 個以上の数字列がカンマで区切られて並んでいる」を厳密に解釈し、
    // カンマ区切りの整数列が少なくとも1つ含まれていることを確認します。
    // 妥当な行の定義: 1個以上の数字列がカンマで区切られて並んでいる。
    // 例: "1,2,3" (3つの数字列)
    // 例: "1" (1つの数字列)
    // 例: "1,2," (2つの数字列、末尾のカンマ許容)

    // パターンを修正: 数字とカンマのみで構成され、数字が少なくとも1つ含まれていることを確認。
    // 任意の数の (数字, カンマ) のペア、または単独の数字。
    // ここでは「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
    // 数字とカンマが混在している行、または数字のみの行を対象とします。

    const pattern = /^[\d,]+$/; // 数字とカンマのみで構成されている行を許容（ただし空行や不正文字は除外）

    for (const line of lines) {
        const trimmedLine = line.trim();

        if (trimmedLine === "") {
            // 空行は妥当ではない
            continue;
        }

        // 行の前後の空白は無視する。行全体が数字とカンマのみで構成されているか確認する。
        // 厳密には「1個以上の数字列がカンマで区切られて並んでいる」
        
        // 数字とカンマのみで構成されていることを確認
        if (!pattern.test(trimmedLine)) {
            // 数字とカンマ以外の文字が含まれている場合、妥当ではない
            continue;
        }

        // 妥当性の判定: 1個以上の数字列がカンマで区切られているか？
        // 数字のみの行 (例: "123") も「1個の数字列」として許容されると解釈する。
        // 数字とカンマのみの行であれば、少なくとも1つの数字列が存在する。
        
        // 例: "1,2,3" -> OK
        // 例: "1," -> OK
        // 例: "123" -> OK (1つの数字列)
        // 例: "," -> 不正 (数字が0個)
        // 例: "abc" -> 不正 (pattern.test(trimmedLine)で既に除外されている)
        
        // 数字とカンマのみの文字列が、カンマで区切られた複数の数字列（または単一の数字列）を意味する場合、
        // 少なくとも1つの数字が含まれている必要がある。
        if (/[0-9]/.test(trimmedLine)) {
            validCount++;
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
