import * as fs from 'fs';

function solve() {
    const input = fs.readFileSync(0, 'utf8').trim().split('\n');
    let validCount = 0;

    // 妥当な行数をカウントする
    for (const line of input) {
        // 行の前後の空白を無視する（trimは既に実行済みだが念のため）
        const trimmedLine = line.trim();

        if (trimmedLine === '') {
            // 空行は妥当ではない
            continue;
        }

        // 正規表現による判定
        // 妥当な形式: 1個以上の数字とカンマの組み合わせ。
        // 許容されるパターン: 整数（数字）とカンマの組み合わせ。
        // 末尾のカンマは許容される。
        // 正規表現の解説:
        // ^: 行の開始
        // (?:[0-9]+(?:,|$))+: 1つ以上のグループ。
        //   [0-9]+: 1桁以上の数字 (整数)
        //   (?:,|$) : カンマまたは行末 ($)
        // このパターンは、数字とカンマが交互に続くか、数字が連続する場合を考慮するが、
        // 仕様は「カンマ区切りの整数列」であり、例として "1,2,3" や "1,2,3," が妥当。
        // 厳密に「カンマ区切りの整数列」を意味するものとして、カンマで区切られた数字のリストを想定する。

        // より厳密に「カンマで区切られた整数列」を判定するために、
        // 少なくとも1つの数字とカンマが存在する、または単なる数字列が存在することを検証する。

        // 仕様の解釈に基づき、数字とカンマのみで構成され、かつ空行でないことを確認する。
        // "1,2,3" や "1,2," は妥当。
        // "abc" や "1a" は妥当ではない。

        // 1. 数字とカンマのみを含むか？
        // 2. 空白ではないか？

        // 正規表現で「数字とカンマのみ」で構成されているかをチェックする。
        // パターン: 1文字以上の数字、またはカンマ。
        // 妥当な例: "1,2,3" -> マッチ
        // 妥当な例: "1,2," -> マッチ
        // 妥当でない例: "1,a" -> マッチしない
        // 妥当でない例: "abc" -> マッチしない
        // 妥当でない例: "  1,2 " -> trimしているので、"1,2"になる。

        const regex = /^[\d,]+$/; // 数字とカンマのみを含む行

        if (regex.test(trimmedLine)) {
            // 空行でないこと（trimで既にチェック済み）と、数字とカンマのみで構成されていることを満たす。
            // ただし、" , " や ",," のようなカンマの連続は許容される可能性がある。
            // 仕様：「1 個以上の数字列がカンマで区切られて並んでいる」
            
            // 区切り文字としてカンマのみが使われていることを確認し、
            // 少なくとも1つの数字が含まれていることを確認する。
            const parts = trimmedLine.split(',');
            let hasDigit = false;
            for (const part of parts) {
                if (/^\d+$/.test(part)) {
                    hasDigit = true;
                }
            }
            
            // 1個以上の数字列がカンマで区切られているか、または単なる数字列であること。
            // "1,2,3" -> ['1', '2', '3'] (hasDigit=true) -> OK
            // "1" -> ['1'] (hasDigit=true) -> OK
            // "1,," -> ['1', '', ''] (hasDigit=true) -> OK (空文字列は無視される)
            // "a,b" -> 間違い (regexが既にこれを防いでいるはずだが、厳密に)
            
            // 正規表現による厳密な判定に戻る。
            // 「カンマ区切りの整数列」であるためには、カンマで区切られている必要があります。
            // (?:[\d]+(?:,[\d]+)*) : 1つ以上の数字がカンマで区切られている構造。
            // 末尾のカンマは許容。

            const strictRegex = /^[\d,]+(?=.*?\d)$/; // 数字とカンマのみで構成され、少なくとも1つの数字が含まれていること。
            
            // 最終的な判定ロジックは、与えられた例が満たすべき最も緩い（または厳密な）解釈に依存する。
            // 仕様: 「1 個以上の数字列がカンマで区切られて並んでいる」
            // これは、カンマが存在し、その間に数字があることを意味する。
            
            // 例: "1,2,3" -> 妥当
            // 例: "1" -> 妥当 (1個の数字列)
            // 例: "," -> 不妥当 (数字列が0個)
            // 例: "" -> 不妥当 (空行)
            
            // 少なくとも1つの数字が含まれており、数字とカンマ以外を含まないことを確認する。
            if (parts.length > 0 && parts.some(p => /^\d+$/.test(p))) {
                 validCount++;
            }
        }
    }

    console.log(`valid=${validCount}`);
}

solve();
