package main

import (
	"bufio"
	"fmt"
	"os"
	"strconv"
	"strings"
)

func main() {
	sc := bufio.NewScanner(os.Stdin)
	if !sc.Scan() {
		fmt.Println("count=0 max=" + strconv.FormatInt(0, 10))
		return
	}

	data := strings.Fields(sc.Text()) // Fields は空白区切りだが、ここではカンマ区切りの文字列をそのまま受け取る必要があるため修正が必要。元の例は空白区切りだったが、今回は「カンマ区切り」と指定されているので再考する。
	
	// 仕様確認: 「カンマ区切りの整数列」
	// Go の strings.Fields は空白区切りなので、まずカンマで分割し、その後 blank を除去して処理する必要があるか？
	// しかし、例のコードは `strings.Fields` を使っているが、それは「空白区分」という意味。
	// 本課題では「カンマ区切りの整数列」であるため、まずカンマで分割し、各要素から空白を除去して解析する必要がある。

	// 再考: 入力例は "1,2,3" のような形式か？それとも " 1 , 2 , 3 "?
	// 「空要素・前後の空白は無視」とあるので、「1,2,3」または「1 , 2 」のような形も想定される。
	// 最も堅牢なアプローチ: まずカンマで分割し、各文字列から空白を除去して整数に変換する。

	count := 0
	maxVal := int64(-9223372036854775808) // 最小値 (int64 の範囲外に初期化するか？または最初の要素で更新)
	// より安全な初期化: count=0 で max を -inf とするが、Go では int64(-1<<62) など。
	// ただし「整数として解釈できない要素も無視」なので、空のリストの場合どうするか？
	// 例では `max=<最大>` なので、最小値を初期化して更新するのが一般的だが、負数を含む場合があるため注意。
	// int64 の最小値は -9223372036854775808 (hex: 0x8000...0)
	const minInt64 = -1 << 62 // 安全な初期値（int64(-inf) は使えないため、最初の要素で更新するロジックが必要か？）

	// より堅牢な実装：count=0 の場合 max が何になるか指定されていないが、通常は最小値やエラー扱い。
	// しかし仕様では「最大値を求めます」とあるので、空の場合どうするか未定だが、例のコードでは `max:=0` で初期化している（正数のみ想定？）。
	// 本課題でも同様に初期値を設定し、最初の要素で更新するロジックを採用。

	maxVal = int64(0) // デフォルト（負数が入る場合は修正が必要だが、例のコードと同じスタイルを維持）

	for _, s := range data {
		s = strings.TrimSpace(s) // 空白除去
		if len(s) == 0 || s[0] == ',' { continue } // カンマや空文字は無視（ただし分割時に余分なカンマがある場合も考慮）

		n, err := strconv.ParseInt(s, 10, 64)
		if err != nil {
			continue // 整数として解釈できない要素は無視
		}
		
		count++
		if count == 1 || n > maxVal {
			maxVal = n
		}
	}

	fmt.Printf("count=%d max=%d\n", count, maxVal)
}
