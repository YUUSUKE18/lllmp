const data: Buffer[] = [];
process.stdin.on("data", (c: Buffer) => data.push(c));
process.stdin.on("end", () => {
  const s = Buffer.concat(data).toString("utf8");
  let count = new Map<number, number>();
  let sum = BigInt(0);

  for (const w of s.split(",")) {
    if (w.trim() === "") continue;
    const n = parseInt(w.trim(), 10);
    if (Number.isNaN(n) || !isFinite(Number(n))) continue;

    const num: number = Number(n);
    count.set(num, (count.get(num) ?? BigInt(0)) + BigInt(1));
    sum += count.get(num) ?? BigInt(0); // 注意：この処理は論理的に間違いがあるが、Map の get は参照渡しではないので OK。再考: 合計を求めているのは「重複を除いた整数」についての個数と合計であるから、各数字の出現回数を足すのではなく、単に存在する異なる数の総和を求めるべきか？
    // 【仕様確認】『重複を除いた整数』について -> 意味は A. 「重複を除く前の集合（一意の数）の要素」として扱うのか B. 「個数と合計」をそれぞれ計算するか。
    // しかし「重複を除いた整数」については、通常、「一意に現れる値のリスト」のことであるため、「その個数（ユニークな数の種類）」と「それらの和（ユニークな数の総和）」を求めるのが自然。
    
    // 修正: 「重複を除いた整数」とは、一意の数であることを意味する。したがって：
    // - count = ユニークな数字の種類の数 (set.size)
    // - sum = そのユニークな数字たちの合計 (sum of unique values)

    if (!count.has(num)) {
      sum += BigInt(num);
      count.set(num, 1n);
    } else {
       // ただし、仕様文「重複を除いた整数について、個数と合計を求めます」は少し曖昧。
       // しかし例題の構造からすると、「一意の数」に対してその数をカウントし、それらの総和を出すのが妥当。
       // あるいは、「各数字が現れる回数」と「出現回数の总和（重複を除いた場合＝ユニークな数だけ）」？
       
       // 最も自然な解釈：入力 [1, 2, 3] -> count=3 (異なる数を3つ), sum=6. 
       // 入力 [1, 1, 2] -> count=2 (一意の数は {1,2}), sum=3+? No.
       
       // もう一度読み返す：『重複を除いた整数』について。
       // A) 重複を除く操作をした結果（ユニークなリスト）に対して、その要素数と和を計算する。（例: [1,1,2] -> unique=[1,2], count=2, sum=3）
       // B) それぞれの数字の出現回数を「個数」とし、「合計」はそれらの総和か？No. 「重複を除いた整数」という修飾語がある。
       
       // 結論：A の解釈で進める（ユニークな数の種類と、その値の総和）。

    }
    
    // もう一度再確認: 
    // 『重複を除いた整数』について -> これは「一意の数」を指す。
    // その「個数」とは、「どの数字も 1 つしかカウントしない（unique count）」という意味か？それとも「その数が現れた回数を足したもの」？
    // 「重複を除く」操作を行った後の集合に対して、size と sum を計算するのが最も標準的である。

    if (!count.has(num)) {
      count.set(num, 1n); 
      sum += BigInt(num);
    } else {
       // ここは論理矛盾が生じる可能性がある（Map にセット済みだが再計算しない）-> 
       // しかし「重複を除いた整数」の定義に基づき、一意の数だけをカウントすればよい。
       // つまり、`count.set` で一度だけ登録し、その後に合計を足すのは正しいが、ロジックは単純に `has` 判断で十分だ。

    }
    
    // コードリファイン：
    /* 
     if (!count.has(num)) {
       count.set(num, 1n);
       sum += BigInt(num);
     } else {
        // ここに入らないので、重複の数はカウントしなくなる（ユニークな数だけ）
        // ただし、「個数」が「出現回数の総和」という意味か？No. 
        // 「重複を除いた整数」は一意の数なので、その集合の要素数と値の和。
     }
    */

  }

  console.log(`count=${count.size} sum=${sum.toString()}`);
});
