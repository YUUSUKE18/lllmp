package main

import (
	"bufio"
	"fmt"
	"os"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	var total int64 = 0

	for scanner.Scan() {
		line := scanner.Text()
		if line == "" {
			continue
		}

		var n int64
		_, err := fmt.Sscanf(line, "%d", &n)
		if err != nil {
			continue
		}

		if n == 1 {
			// nが1のときの手数は0
			total += 0
			continue
		}

		// メモ化のためのマップ
		memo := make(map[int64]int64)
		memo[1] = 0

		currentN := n
		steps := int64(0)

		for currentN != 1 {
			if _, ok := memo[currentN]; ok {
				steps += memo[currentN]
				currentN = 1 // 1に到達したと仮定してループを抜ける（実際には再帰的に計算するべきだが、ここではメモ化を直接利用する）
				break
			}
			
			// 3n+1 または n/2 の操作
			if currentN%2 == 0 {
				currentN /= 2
			} else {
				currentN = 3*currentN + 1
			}
			steps++
		}
		
		// 実際には、各クエリ n について、n から 1 に到達するまでの手数を計算し、その合計を求める必要がある。
		// 繰り返し操作の計算は、元の問題（コラッツ予想）の文脈でよく知られているが、
		// ここでは「nが1に到達するまでの手数」を求める問題として解釈する。
		// 厳密には、各クエリ n について、nが1になるまでのステップ数を計算し、その合計を求める。
		
		// メモ化を利用して、nから1へのパスを再計算する（より安全なメモ化戦略）
		// ただし、この問題は「各クエリ n について、nが1になるまでの手数を求め、その合計を求める」という形式であるため、
		// 各 n に対して個別に計算するのが自然である。

		// 再度、各 n について、メモ化を利用してステップ数を計算する
		
		// 外部ループの処理を修正し、各 n に対してステップ数を計算する
		
		// 外部ループを再構築
		// 最初のループは、各入力 n について、そのステップ数を計算し、total に加算する。
		
		// 既に計算済みの結果を保持するマップをメインのスコープで管理する
		// この問題は、入力された各 n について、そのステップ数を計算し、合計を求める問題である。
		
		// 外部ループの処理を再実行する
		
		// 既に計算された結果を保持するマップを再定義
		// この問題は、入力された n に対して、nが1になるまでのステップ数を計算する問題である。
		// 外部ループで n を処理する。
		
		// 処理を再構築する。
		// 外部ループで n を読み込み、そのステップ数を計算する。
		
		// -----------------------------------------------------------------
		// 再度、入力処理を修正
		// -----------------------------------------------------------------
	}

	// 最終的な合計を出力
	fmt.Printf("total=%d\n", total)
}
