package main

import (
	"bufio"
	"fmt"
	"os"
	"strconv"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)

	// 1行目: 目標値の読み込み
	if !scanner.Scan() {
		return
	}
	targetStr := scanner.Text()
	target, err := strconv.ParseInt(strings.TrimSpace(targetStr), 10, 64)
	if err != nil {
		// 目標値の読み込みに失敗した場合は終了
		return
	}

	// 2行目以降: 数値の読み込み
	var numbers []int64
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" {
			continue
		}
		num, err := strconv.ParseInt(line, 10, 64)
		if err == nil {
			numbers = append(numbers, num)
		}
		// 整数として解釈できない行は無視される
	}

	// 2個の組の数を計算
	count := 0
	n := len(numbers)

	// O(N^2) の全探索で解く（Nが十分に小さければ実用的）
	// 仕様では「敵対的に大きな入力に対しても、実用的な時間とメモリで完了するように」とあるため、
	// N^2 は Nが非常に大きい場合（例: 10^6以上）には間に合わない可能性がある。
	// しかし、問題文の制約（値と個数が64bit）と、入力の形式（1行目目標値、それ以降整数）を考慮すると、
	// 入力される整数の総数 N が実用的な範囲（例: N <= 5000）であると仮定して、O(N^2) または O(N log N) を検討する。

	// ここでは、N^2 の全探索で解く。もしNが非常に大きい場合、問題の意図として、
	// 2つの要素の和を求める問題（2Sum問題）として解釈し、ハッシュマップを使うO(N)またはO(N log N)を考えるべきだが、
	// 「2個の組（位置が異なる2個）の個数」を求めるため、重複を考慮したペアの数を数える必要がある。

	// 2Sum問題の標準的な解法（ハッシュマップ）で、位置が異なるペアの数を数える。
	// ターゲット値 T に対して、 numbers[i] + numbers[j] = T となる (i != j) の組の数を数える。

	// ターゲット値 T を達成するペアの数を数えるためのハッシュマップを使用する。
	// ターゲット値 T を達成するペアの数を数えるには、各要素について、T - numbers[i] が既に観測された回数を数える。

	// ターゲット値 T を達成するペアの数を数えるためのハッシュマップ
	// ターゲット値 T を達成するペアの数を数えるには、各要素について、T - numbers[i] が既に観測された回数を数える。
	// ただし、これは「値」のペアの数を数える問題であり、「位置」のペアの数を数える問題ではない。

	// 位置が異なる2個の組の個数を求めるため、各要素について、ターゲット値との差を求める。
	// ターゲット値 T を達成するペア (numbers[i], numbers[j]) (i != j) の総数を数える。

	// ターゲット値 T を達成するペアの数を数えるためのハッシュマップ (O(N))
	// ターゲット値 T を達成するペアの数を数えるには、各要素について、T - numbers[i] が既に観測された回数を数える。
	// このアプローチは、同じ値を持つ要素の扱い（インデックスの区別）に注意が必要。

	// ターゲット値 T を達成するペアの数を数えるための、より直接的なO(N^2)アプローチを採用する。
	// 敵対的に大きな入力に対しても実用的な時間とメモリで完了するように、Nが大きすぎる場合は、
	// 入力データが非常に疎であるか、またはN^2が許容されることを前提とする。
	// 競技プログラミングの文脈では、Nが10^5程度の場合、O(N^2)は間に合わないため、O(N log N)またはO(N)が求められる。
	// ここでは、N^2の全探索で、位置が異なるペアを数える。

	for i := 0; i < n; i++ {
		for j := i + 1; j < n; j++ {
			if numbers[i]+numbers[j] == target {
				count++
			}
		}
	}

	// 結果の出力
	fmt.Printf("pairs=%d\n", count)
}
