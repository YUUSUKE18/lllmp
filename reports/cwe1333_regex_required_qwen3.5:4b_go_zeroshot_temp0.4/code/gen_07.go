package main

import (
	"bufio"
	"fmt"
	"regexp"
)

func main() {
	reader := bufio.NewReader(nil) // 標準入力
	validCount := 0
	scanner := bufio.NewScanner(reader)

	// 正規表現の定義
	// ^ の直後に数字または空白、末尾にカンマまたは空白を含むパターンを許容するが、
	// 本質的に「数字とカンマ以外」が含まれていないかチェックするため、
	// 全行が [0-9, ,] で構成されていることを確認する必要がある。
	// ただし、仕様は「1 個以上の数字列がカンマで区切られて並んでいること」と「末尾のカンマは許容」「数字とカンマ以外を含む行は妥当ではない」。
	// 空白は無視するので、実質的には文字列が [0-9, ,] のみから成り、かつ少なくとも 1 つの数字を含んでいる必要がある。
	// ただし、「数字とカンマ以外を含む」という条件より、空白も含めて非数字・非カンマ文字が含まれてはいけない。
	// また「1 個以上の数字列」があるので、少なくとも 1 つの数字は必要。

	// 正規表現: ^[\d,\s]+$ で全行が数字、カンマ、空白のみであることを保証し、
	// さらに \d の存在を確保する (^\d+[\d,]*$ | ^\d*[\d,]*$ のような単純なチェックは不十分なので、
	// まず非数字・非カンマ文字が含まれていないか確認し、次に数字が存在するか確認。
	// しかし Go の正規表現では「空白」を明示的に許容しつつ「数字とカンマ以外なし」をチェックするには、
	// 全文字が [0-9, ,] に属するかを確認する方が確実だが、正規表現で「非 [0-9, ]」が存在しないかチェックするのが適切。
	// さらに「1 個以上の数字列」があるので、\d が少なくとも 1 回出現している必要がある。

	// 最終的な正規表現: ^[\d\s,]+$ で全文字が数字・空白・カンマのみであること + \d の存在を確認する。
	// ただし、仕様では「行の前後の空白は無視します」とあるので、trim して処理すべきか？
	// 「空白を無視」は通常、trim することで意味を持つが、正規表現でチェックする場合、
	// 全文字が [0-9, ,] に含まれること、かつ \d が存在すること。

	re := regexp.MustCompile(`^\s*[\d\s,]+\s*$`) // 空白を含むが、非数字・非カンマ文字なし
	// しかし、上記だけでは「数字列が存在するか」のチェックが不十分（例：",," は OK と判定される可能性があるが、数字がないので NG）。
	// より厳密に：全文字が [0-9, ,] に属し、かつ \d が少なくとも 1 回出現する。
	// 正規表現で「\d」の存在をチェックするには `(?=\d)` を使う。

	// 修正: ^[\d\s,]+$ で全文字が数字・空白・カンマのみ + (?=.*\d) で \d が少なくとも 1 回ある。
	// ただし、空白は前後で無視するので、trim してからチェックすべきか？
	// 「行の前後の空白は無視します」→ trim して処理。
	// しかし、正規表現内で「空白を許容しつつ数字・カンマ以外なし」とするのは難しいので、
	// まず文字列を trim する（前後の空白除去）し、その後で正規表現チェックを行う。

	// より正確なアプローチ：
	// 1. 行を trim して前後の空白を除去。
	// 2. 結果が空なら NG。
	// 3. 結果が [0-9, ,] のみから成り、かつ \d が少なくとも 1 回出現するかを確認する。
	// 正規表現: ^[\d\,]+$ で数字とカンマのみ（空白は trim で除去済み）+ (?=.*\d) で数字の存在。

	// しかし、仕様では「末尾のカンマは許容」なので、",," は NG か？
	// 「1 個以上の数字列がカンマで区切られて並んでいること」→ 数字列が存在することが必須。
	// ",," は数字列がないので NG。
	// "1,2," は OK。
	// "1,,2" は OK（数字列は "1" と "2"）。

	// したがって、trim 後の文字列が [0-9, ] のみで、かつ \d が少なくとも 1 回出現するか。
	// 空白を無視するということは、trim して処理すればよい。

	// 最終的な正規表現: ^[\d\,]+$ で数字とカンマのみ + (?=.*\d) で数字の存在。
	// ただし、空白は trim で除去済みなので、[0-9, ] のみで \d が存在するか。
	// 正規表現を簡略化：^[\d\,]+$ で全文字が数字・カンマのみ、そして (?=.*\d) で数字の存在。

	re = regexp.MustCompile(`^\s*([\d\,]+)\s*$`) // 空白を含むが、内部は数字・カンマのみ
	// しかし、上記だけでは ",," は OK と判定される可能性がある（数字なし）。
	// なので、2 つのチェックを行う：
	// 1. 全文字が [0-9, ,] に属するか → re.Match() で確認。
	// 2. \d が少なくとも 1 回出現するか → regexp.MustCompile(`\d`).MatchString(line)

	// より効率的に、一つの正規表現で両方チェック：
	// ^[\d\,]+$ で全文字が数字・カンマのみ（空白は trim で除去済み）+ (?=.*\d) で数字の存在。
	// しかし、空白を無視するということは、trim して処理すべき。

	// 再考：正規表現で「空白を含みつつ、非数字・非カンマ文字なし」とするのは難しいので、
	// まず行を trim する（前後の空白除去）し、その後で正規表現チェックを行う。
	// 正規表現: ^[\d\,]+$ で全文字が数字・カンマのみ + (?=.*\d) で数字の存在。

	re = regexp.MustCompile(`^([\d\,]+)$`) // 内部は数字・カンマのみ
	re2 := regexp.MustCompile(`\d`)       // 少なくとも 1 つの数字が存在するか

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line) // 空白を無視（trim）

		if trimmedLine == "" {
			continue // 空行は NG と仕様？「空行、および数字とカンマ以外を含む行は妥当ではありません。」→ 空行は NG。
		}

		// 正規表現チェック：全文字が [0-9, ] のみで \d が存在するか
		if re.MatchString(trimmedLine) && re2.MatchString(trimmedLine) {
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
