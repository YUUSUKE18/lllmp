import { readFileSync } from 'fs';

const input = readFileSync(0, 'utf8').split('\n');

const isValidLine = (line: string): boolean => {
  const trimmed = line.trim();
  
  // 空行は妥当ではありません
  if (trimmed.length === 0) return false;

  // 空白のみ（trim 後が空でない場合、本来は数値とカンマ以外が含まれているはずです）
  // ただし、「数字とカンマ以外を含む行」という要件があります。
  // 空白自体は「数字とカンマ」ではありませんが、trim して数式チェックするのが安全です。
  // 仕様：「数字とカンマ以外を含む行は妥当ではありません」
  // つまり、文字列に含まれる部分文字が「数字」または「カンマ」でないものは NG。
  // ただし、前後の空白は無視します -> trim する必要がある。
  
  let index = 0;
  let length = trimmed.length;

  while (index < length) {
    const char = trimmed[index];

    if (!/[\d,]/.test(char)) {
      return false; // 数字やカンマ以外の文字が含まれている
    }

    // カンマの処理：複数個連続したカンマは許容されるか？
    // 「1 個以上の数字列がカンマで区切られて並んでいる」
    // これを厳密に解釈すると、2 つのカンマが連続している場合（例："1,,2"）は、
    // 空文字列の数字列として解釈されるため「1 個以上の数字列」の要件を満たすかどうかが微妙です。
    // ただし、「末尾のカンマは許容します」という点から、数式構造が崩れている場合も含め、
    // 通常の CSV の厳密さではなく、文字レベルのチェックを想定し、
    // 「数字とカンマ以外が含まれていない」「少なくとも一つの数字が存在する」ことを確認します。

    // 補足：「1 個以上の数字列がカンマで区切られて並んでいる」という文脈において、
    // "1,2" -> ["1", "2"] (OK)
    // "1," -> ["1"] (OK)
    // ",1" -> []? (NG: 最初の部分文字が数字ではないため、数字列が存在しない)
    // したがって、最初の文字が数字でなければ NG と判断します。

    if (char === ',') {
      // カンマの前に必ず数字があるかチェック（ただし、trim 後の開始位置から先は数字かカンマのみ）
      // 既に全体が「[\d,]*」と一致していることを確認するため、
      // ここでは構造の整合性を保つために、カンマの前後に数字がない場合も許容しない方が安全です。
      // しかし、問題文の「1 個以上の数字列」という表現から、
      // "1," (1 つの数字列) は OK, ",1" (0 つの数字列) は NG とするのが自然です。
    }

    index++;
  }

  // 最後のチェック：少なくとも一つの数字が存在する（" ," のような行は上記で failするか、ここで確認）
  // " " は trim で空になるため最初で NG。
  // ",," などは上記のループで OK になるが、「1 個以上の数字列」を満たすか？
  // 数字列とは「少なくとも 1 文字の数字からなるもの」です。
  // ",," に含まれる数字列は存在しないため、NG です。
  
  // 再考：上記のループは「数字とカンマ以外が含まれていないか」をチェックしています。
  // "1,2" -> OK
  // "1," -> OK (1 つの数字列)
  // ",1" -> NG (最初の文字が数字ではないので、数字列が存在しない)
  // ",," -> OK? -> 上記ループでは「全て [\d,]」なので true。
  // しかし、「1 個以上の数字列」という要件があります。
  // ",," は数字列を定義できません（空文字列は数値列ではない）。
  // よって、実際に数字が含まれているかチェックする必要があります。

  return /\d/.test(trimmed);
};

// 再確認：「数字とカンマ以外を含む行」-> trim して [\d,]* で一致するか？
// もし ",," が許容されるなら、「1 個以上の数字列」という要件を満たすか？
// 通常、CSV の解析では空文字列の要素は許可されますが、「数字列（integer sequence）」と指定されているため、
// 数値が含まれていない行を NG とするのが妥当です。

const validCount = input.filter(line => isValidLine(line)).length;

console.log(`valid=${validCount}\n`);
