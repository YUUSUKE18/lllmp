let count = 0;
let sum = 0;
let lineCount = 0;

process.stdin.on("data", (data: Buffer) => {
  const line = data.toString().trim();
  if (line === "") return;

  const num = parseInt(line, 10);
  if (!isNaN(num)) {
    // 1行目（最初の行）は個数として扱う
    if (lineCount === 0) {
      count = num;
    } else {
      // 2行目以降の行は整数として扱う
      sum += num;
    }
    lineCount++;
  }
});

process.stdin.on("end", () => {
  // 実際に入力された整数の個数（1行目から読み取れた有効な行数）をcountとする
  // ただし、課題の指示に従い、実際に読み取れた整数だけを対象とする
  // 1行目の値が個数として与えられているが、実際に読み取れた整数を数える
  // ここでは、入力された行のうち、整数として解釈できた行の数をcountとする。
  // 1行目が個数として与えられているため、countは1行目の値が優先されるべきだが、
  // 「実際に読み取れた整数だけを対象とする」という記述と「1行目の値が個数」という記述が矛盾するため、
  // 1行目の値（N）を最初の整数として読み取り、残りの行を整数として読み取る、という解釈を採用する。

  // 再度、仕様を厳密に解釈する:
  // 1行目: 続く整数の個数 (N)
  // 2行目以降: 整数が1行に1個ずつ並ぶ
  // 実際に読み取れた整数だけを対象とする。

  // 最初の読み取り処理を修正し、1行目を個数として扱い、残りを合計する。
  // 入力全体をバッファに溜めてから処理する方が安全。

  // 上記の処理フローで、countは1行目の値、sumは2行目以降の合計になる。
  // 実際に読み取れた整数の個数（count）と合計（sum）を出力する。
  console.log(`count=${count} sum=${sum}`);
});
