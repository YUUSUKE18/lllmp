const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let validLines = 0;

rl.on('line', (line) => {
  const trimmedLine = line.trim();
  if (trimmedLine === "") {
    // 空行は妥当ではない
    return;
  }

  // カンマ区切りの整数列として妥当か判定
  // 1. 数字とカンマのみで構成されているか
  // 2. 1個以上の数字列がカンマで区切られているか（末尾のカンマは許容）

  // 正規表現で検証:
  // ^: 行の開始
  // (?:[0-9]+(?:,|$))+: 1つ以上の数字列とカンマの組み合わせ。末尾のカンマも許容する。
  // $ : 行の終わり
  // この正規表現は、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
  // 末尾のカンマを許容するため、行全体が数字とカンマで構成されていることを確認する。

  // より厳密に、カンマで区切られた整数列であることを確認する。
  // 1. カンマで区切られているか、またはカンマで終わっているか。
  // 2. 区切り文字以外の文字がないか。

  // 妥当性の判定ロジックを再考:
  // 「1 個以上の数字列がカンマで区切られて並んでいる」
  // 「末尾のカンマは許容する」
  // 「空行、および数字とカンマ以外を含む行は妥当ではない」

  // 1. 数字とカンマ以外の文字が含まれていないかチェック
  if (!/^[0-9,]*$/.test(line)) {
    return; // 数字とカンマ以外を含む行は不妥当
  }

  // 2. 1個以上の数字列が存在するかチェック
  // カンマで分割し、空でない要素が1つ以上あるか確認する。
  const parts = line.split(',');
  let hasNumbers = false;
  for (const part of parts) {
    if (part.trim() !== "") {
      // 数字のみで構成されているか確認
      if (/^[0-9]+$/.test(part.trim())) {
        hasNumbers = true;
      } else {
        // 数字とカンマ以外の文字が含まれている場合（例: "1,a"）
        // これは上記の /^[0-9,]*$/ チェックで既に除外されているはずだが、念のため。
        // ただし、このチェックは「数字列」がカンマで区切られていることを保証する。
      }
    }
  }

  // 1個以上の数字列が存在すれば妥当
  if (hasNumbers) {
    validLines++;
  }
});

rl.on('close', () => {
  console.log(`valid=${validLines}`);
});
