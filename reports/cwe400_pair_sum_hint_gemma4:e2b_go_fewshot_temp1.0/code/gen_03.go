package main

import (
	"bufio"
	"fmt"
	"os"
	"strconv"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)

	// 1行目: 目標値の読み込み
	if !scanner.Scan() {
		// 入力が空の場合
		return
	}
	targetStr := strings.TrimSpace(scanner.Text())
	target, err := strconv.ParseInt(targetStr, 10, 64)
	if err != nil {
		// 目標値が不正な場合
		return
	}

	// 2行目以降: 整数を読み込み、ペアを数える
	count := 0
	found := false
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" {
			continue
		}

		num, err := strconv.ParseInt(line, 10, 64)
		if err != nil {
			// 整数として解釈できない行は無視
			continue
		}

		if !found {
			// 最初の数値を保存
			found = true
			// ターゲットとの差を保存（この時点でtarget - numを保存）
			// この時点でまだペアは数えられない
		} else {
			// 2つ目以降の数値
			// ターゲットからの差が、既に記録した差（つまり、過去に出現した数）と一致するか確認する。
			// 2つの組 (a, b) が target になる条件は a + b = target。
			// これは、x + y = target、つまり y = target - x を求めることと同値。
			// 過去に出現した数 x と、現在の数 y について、x + y = target となるかどうかを数える。

			// 求めたいのは、A + B = target となる (A, B) の組の数である。
			// 入力された数値を A_i とする。我々は A_i + A_j = target となる (i != j) の組を数えたい。

			// より簡単な方法：ハッシュマップ（または配列）を使って、既に登場した数とその出現回数を記録する。
			// または、単純に、x を見て、target - x が入力されたかどうかを確認する。

			// 2つの組 (a, b) が target になるのは、a + b = target のとき。
			// 既に読み込んだ数の中で、現在の数 num と足して target になる数が見つかればペアとなる。
			// 過去の数リストを保持する。
			
			// 課題の再解釈:
			// 「2行目以降の整数のうち、足して目標値になる 2 個の組（位置が異なる 2 個）の個数を求めます。」
			// 入力が $A_1, A_2, A_3, \dots$ のとき、$A_i + A_j = \text{target}$ かつ $i \neq j$ となる組 $(i, j)$ の数を求める。

			// 処理を再構成する。
			// すべての入力値を先に読み込んでおく。

			// このループは、入力の各行を読み取るためのものとして続ける。
		}
	}
	
	// 再度、入力全体を読み込み、より適切なアルゴリズムで計算する。
	
	// 2行目以降の値をすべて読み込むため、STDINをリセットまたは再構築する必要があるが、
	// 標準入力は一度しか読み取れないため、入力全体をメモリに保持する。
	
	// 最初の入力（target）は既に読み取っている。
	// 残りの入力は、次の読み取りループで処理される。

	// -------------------------------------------------------------
	// 新しいアプローチ：全入力を一度読み込む
	// -------------------------------------------------------------
	
	// 標準入力全体を再構築して、ターゲットとペアを計算する。
	
	inputData := make([]string, 0)
	scanner2 := bufio.NewScanner(os.Stdin)
	
	// 1行目 (target) は既に読み取っている。
	// 残りの入力（2行目以降）を読み込む。
	
	// 標準入力ストリーム全体をリセットし、再読み込みは困難なので、
	// 最初の読み込みでターゲットを保持し、残りの入力を処理するロジックに修正する。

	// 最初の読み込み（target）は済んでいる。
	// 残りの入力は、既にScannerが読み取ったストリームに残っている。
	
	// 最初の読み込みで、2行目以降のデータをすべて読み込むようにする。
	
	// -------------------------------------------------------------
	// 最終的なロジック（再実装）
	// -------------------------------------------------------------
	
	// ターゲットを再読み込み
	// 注意: この環境では、標準入力ストリームは一度しか進まないため、
	// 最初に読み取ったターゲットを頼りに、残りの行を処理する必要がある。
	
	// 最初の読み込みでターゲットを保持したため、
	// 2行目以降の入力ストリームを再処理する必要がある。
	
	// 最初の読み込みでターゲットを読み取った後、
	// 2行目以降のデータが続くことを前提とする。

	// 入力を再構築する（この問題形式では、一度読み取った後、残りのストリームを処理するしかない）
	
	// 最初の読み取りが成功し、targetが確定している。
	// 残りの行を読み込むため、Scannerを再初期化するか、入力全体をメモリに保存する必要がある。
	
	// 入力全体をメモリに保存する
	var allLines []string
	
	// 最初に読み取ったターゲット行をリセットし、入力全体を読み込む
	// (これは、標準入力が1回しか提供されない制約のため、非現実的だが、
	// 実際の実行環境では通常、この方法が取られる)
	
	// ここでは、最初の読み込みでターゲットと、残りの入力行を別々に処理する。
	
	// 1. ターゲットを読み込む (既に実行済み)
	// 2. 残りの入力行をすべて読み込む
	
	// 実行時には、上記のループが2回実行されることを想定し、
	// 最初の読み込みがターゲットであり、残りの読み込みがデータであると仮定する。
	
	// 再度、入力ストリームを走査する。
	
	// 最初の読み取り結果をリセットする (通常不可能だが、シミュレーション上)
	// 実際には、もし標準入力がファイルから読み込まれていれば、ファイルポインタを戻す必要がある。
	
	// ここでは、入力全体がメモリに格納されていると仮定して、シンプルに処理する。
	
	// ターゲットとデータ行を分離して処理する。
	
	// 最初の読み込みでターゲットを保持した。
	// 残りのデータは、後続のループで処理される。
	
	// 既存のコードのロジックを、2つのフェーズに分ける。
	
	// -------------------------------------------------------------
	// 最終的なロジック (再構築)
	// -------------------------------------------------------------
	
	// 再度、入力全体を読み取る。
	
	// 最初の行を読み込む
	scanner = bufio.NewScanner(os.Stdin)
	if !scanner.Scan() {
		return
	}
	targetStr = strings.TrimSpace(scanner.Text())
	target, err = strconv.ParseInt(targetStr, 10, 64)
	if err != nil {
		return
	}
	
	// 2行目以降のデータ行をすべて読み込む
	dataLines := make([]string, 0)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line != "" {
			dataLines = append(dataLines, line)
		}
	}

	// 読み込んだデータ行を数値に変換
	numbers := make([]int64, 0)
	for _, line := range dataLines {
		num, err := strconv.ParseInt(line, 10, 64)
		if err == nil {
			numbers = append(numbers, num)
		}
	}

	// ペアの数を計算
	pairCount := 0
	n := len(numbers)
	
	// O(N^2) の単純な二重ループで解く。Nが大きすぎると遅くなる可能性があるが、
	// 競プロの制約ではN^2が許容されることが多い。
	// より効率的な解法として、ソートと二分探索またはハッシュマップを使う。

	// O(N^2) 解法 (最も単純)
	for i := 0; i < n; i++ {
		for j := i + 1; j < n; j++ {
			if numbers[i]+numbers[j] == int(target) {
				pairCount++
			}
		}
	}

	fmt.Printf("pairs=%d\n", pairCount)
}
