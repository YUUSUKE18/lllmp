package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* は行頭の空白を許容
	// (?:[0-9]+(?:,\s*[0-9]+)*) は1つ以上の数字とカンマの組み合わせをキャプチャする非キャプチャグループ
	// (?:,\s*|$) はカンマと空白、または行末を許容する
	// $ は行末
	// この正規表現は、少なくとも1つの数字列がカンマで区切られていることを確認する
	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// 少なくとも一つの数字列が存在することをチェックする。
	// 以下の正規表現は、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
	// ^\s* 表示行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) 表示1つ以上の数字列がカンマで区切られているパターン
	// \s*$ 表示行末の空白
	pattern := regexp.MustCompile(`^\s*(?:[0-9]+(?:,\s*[0-9]+)*)\s*$`)

	for scanner.Scan() {
		line := scanner.Text()
		// 行の前後の空白を無視して判定するため、行全体をパターンに適用する
		if pattern.MatchString(line) {
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
