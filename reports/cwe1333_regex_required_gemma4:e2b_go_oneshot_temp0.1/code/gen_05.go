package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* は行頭の空白を許容
	// (?:[0-9]+(?:,[0-9]+)*) は1つ以上の数字とカンマの繰り返し（整数列）
	// (?:,|$) はカンマまたは行末（末尾のカンマも許容）
	// この正規表現は、少なくとも1つの数字列が存在し、カンマで区切られている、または単一の数字列であるケースを捉えることを目指します。
	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// 少なくとも一つの数字列が存在し、その中にカンマが含まれるパターンをチェックします。

	// 妥当な行の判定ロジックを正規表現で表現します。
	// 1. 行が空でないこと。
	// 2. 行が数字とカンマのみで構成されていること。
	// 3. 少なくとも1つの数字列が存在すること。
	// 4. 末尾のカンマは許容されること。

	// 以下の正規表現は、行が数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
	// ^\s* : 行頭の空白
	// (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字列とカンマの組み合わせ（例: 1,2,3, または 1,2,3,）
	// .* : 任意の文字（ここでは行末まで）
	// $ : 行末
	// 実際には、行全体がこのパターンにマッチするかどうかをチェックします。

	// 妥当性の判定をより直接的に行うため、行を読み込み、手動でチェックする方が、複雑な構造の正規表現よりも意図を正確に表現しやすい場合がありますが、
	// 仕様に従い正規表現を使用します。

	// 妥当な行の判定：
	// 1. 空行でないこと。
	// 2. 数字とカンマのみで構成されていること。
	// 3. 少なくとも1つの数字列が存在すること。
	// 4. 末尾のカンマは許容されること。

	// 以下の正規表現は、行が数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
	// ^\s* : 行頭の空白
	// (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ（例: 1,2,3, または 1,2,3,）
	// .* : 残りの文字（末尾のカンマなど）
	// $ : 行末
	// 実際には、行全体がこのパターンにマッチするかどうかをチェックします。

	// 妥当な行の判定のための正規表現を定義します。
	// 1. 行が空でないこと。
	// 2. 行が数字とカンマのみで構成されていること。
	// 3. 少なくとも1つの数字列が存在すること。
	// 4. 末尾のカンマは許容されること。

	// 妥当な行の判定のための正規表現（より簡潔に、行全体が数字とカンマのみで構成され、数字が含まれていることを確認）
	// この問題の「1個以上の数字列がカンマで区切られて並んでいる」という条件を厳密に満たすためには、
	// 少なくとも一つの数字列が存在し、その間にカンマが適切に配置されている必要があります。

	// 妥当な行の判定ロジックを正規表現で表現します。
	// 1. 行が空でないこと。
	// 2. 行が数字とカンマのみで構成されていること。
	// 3. 少なくとも1つの数字列が存在すること。
	// 4. 末尾のカンマは許容されること。

	// 妥当な行の判定のための正規表現
	// ^\s* : 行頭の空白
	// (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ（例: 1,2,3, または 1,2,3,）
	// .* : 残りの文字（末尾のカンマなど）
	// $ : 行末

	// 実際には、行全体がこのパターンにマッチするかどうかをチェックします。
	// 妥当な行の判定のための正規表現
	pattern := regexp.MustCompile(`^\s*(?:[0-9]+(?:,[0-9]+)*).*$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := ""
		// 行の前後の空白を無視するため、行全体をチェックする前にトリムする
		// ただし、行全体が数字とカンマのみで構成されているかを確認するため、行全体をチェックします。

		// 行が空でないことを確認
		if line == "" {
			continue
		}

		// 行が数字とカンマのみで構成されているか、かつ少なくとも1つの数字が含まれているかを確認
		if pattern.MatchString(line) {
			// さらに、行が完全に数字とカンマのみで構成されていることを確認する必要があります。
			// 以下のチェックは、行が数字とカンマ以外の文字を含まないことを保証します。
			isValid := true
			for _, char := range line {
				if !('0' <= char && char <= '9' || char == ',') {
					isValid = false
					break
				}
			}

			if isValid {
				validCount++
			}
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
