package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* は行の先頭の空白を許容
	// (?:[0-9]+(?:,\s*[0-9]+)*) は1つ以上の数字とカンマの組み合わせをキャプチャするグループ
	// (?:,\s*)* は末尾のカンマと空白を許容する
	// $ は行の終わり
	// この正規表現は、少なくとも1つの数字列がカンマで区切られていることを確認します。
	// 厳密には、行全体が数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する必要があります。
	// 以下の正規表現は、カンマ区切りの整数列（数字とカンマのみ）が1行以上存在することをチェックします。
	// 1. 行が空でないこと
	// 2. 行が数字とカンマのみで構成されていること
	// 3. 少なくとも1つの数字が含まれていること
	// 簡略化のため、ここでは「カンマで区切られた整数列」の構造に焦点を当てます。
	// 妥当性の定義：「1 個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容する。」

	// 妥当性の判定ロジックを実装
	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := ""
		// 行の前後の空白を無視
		for i := 0; i < len(line); i++ {
			if line[i] != ' ' && line[i] != '\t' {
				trimmedLine += string(line[i])
			}
		}

		// 1. 空行の判定
		if trimmedLine == "" {
			continue
		}

		// 2. 数字とカンマ以外を含む行の判定
		// 数字とカンマのみで構成されているかを確認
		// 正規表現: ^[0-9,]*$ (数字とカンマのみ)
		// ただし、これは「1個以上の数字列がカンマで区切られている」という条件を満たさない可能性があるため、
		// より厳密に「数字列」の存在を確認する必要があります。

		// 妥当性の定義を満たすための正規表現:
		// 少なくとも1つの数字列があり、それらがカンマで区切られている。
		// 例: "1,2,3" または "1,2,"
		// 少なくとも1つの数字が含まれていることを確認する。
		// 以下の正規表現は、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
		// ^[0-9]+(?:,[0-9]+)*$ : 厳密にカンマで区切られた整数列（末尾のカンマは許容しない、または末尾のカンマを許容する）
		// 末尾のカンマを許容する場合: ^[0-9]+(?:,[0-9]+)*,?$
		// 課題の仕様：「末尾のカンマは許容します」
		// したがって、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。

		// 妥当なパターン: 1つ以上の数字とカンマの組み合わせで構成されていること。
		// 例: "1,2" -> OK
		// 例: "1," -> OK
		// 例: "," -> NG (数字がない)
		// 例: "abc" -> NG (数字とカンマ以外)

		// 正規表現: ^[0-9,]+$ (数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認)
		// このパターンは、"1,2" や "1," はマッチしますが、"1,2,3" もマッチします。
		// 課題の意図を最も満たすのは、数字とカンマ以外の文字がないこと、そして数字が少なくとも1つあることです。

		// 最終的な判定ロジックとして、行が数字とカンマのみで構成され、かつ数字が含まれていることを確認します。
		// 妥当な行の例: "1,2,3", "1,"
		// 不妥当な行の例: "", "a,b", "1,a"

		// 1. 数字とカンマのみで構成されているかチェック
		isNumericAndComma := regexp.MustCompile(`^[0-9,]*$`).MatchString(trimmedLine)

		if !isNumericAndComma {
			continue // 数字とカンマ以外を含む行は妥当ではない
		}

		// 2. 少なくとも1つの数字が含まれているかチェック
		hasDigit := regexp.MustCompile(`[0-9]`).MatchString(trimmedLine)

		if hasDigit {
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
