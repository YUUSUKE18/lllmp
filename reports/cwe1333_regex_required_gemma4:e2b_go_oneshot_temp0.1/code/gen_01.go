package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* 表示行の先頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*)  -> 1つ以上の数字とカンマ区切りのパターン（数字が1つ以上）
	// (?:,\s*|$)                 -> カンマと空白、または行末
	// $                          -> 行末
	// この正規表現は、カンマ区切りの整数列が1つ以上存在することをチェックするために使用します。
	// よりシンプルに、「カンマで区切られた数字の列」が存在するかどうかをチェックします。
	// 1個以上の数字とカンマの組み合わせが存在すればOK。
	// 許容されるパターン: 数字, 数字, ... または 数字, 数字, ... ,
	// 少なくとも1つの数字が含まれている必要がある。
	// 正規表現の意図を「カンマで区切られた整数列が1個以上存在するか」に絞る。
	// 少なくとも1つの数字が含まれていることを確認する。
	// ^\s*                                 -> 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*)             -> 1つ以上の数字とカンマの組み合わせ（例: 1,2,3 または 1,2,）
	// \s*                                  -> 行末の空白（末尾のカンマが許容されるため、行末の空白も考慮）
	// $                                    -> 行末
	// 実際には、数字が1つ以上存在すれば良い。
	// 以下の正規表現は、少なくとも1つの数字が含まれていることを確認します。
	// ^\s*                                 // 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*)             // 1つ以上の数字とカンマの組み合わせ
	// .*                                   // その他（末尾のカンマなど）
	// $                                    // 行末
	// 簡略化して、数字が1つ以上存在すれば良い、という条件に絞る。
	// 少なくとも1つの数字が含まれていることを確認する。
	// 1個以上の数字がカンマで区切られている、または単一の数字が1つ以上ある。
	// 少なくとも1つの数字が含まれていることを確認するパターン:
	// ^\s*([0-9]+(?:,\s*[0-9]+)*).*$
	// または、より単純に、数字が1つ以上含まれていることを確認する。
	// 以下の正規表現は、少なくとも1つの数字が含まれていることを確認します。
	// ^\s*([0-9]+)                                 // 少なくとも1つの数字
	// .*                                         // その他
	// $
	// 実際には、行が空でないこと、かつ数字とカンマ以外が含まれていないことを確認する。
	// 妥当な行の定義: 1個以上の数字とカンマのみで構成されている。
	// 少なくとも1つの数字が含まれていることを確認する。
	pattern := regexp.MustCompile(`^\s*([0-9]+(?:,\s*[0-9]+)*)\s*$`)

	for scanner.Scan() {
		line := scanner.Text()
		// 行の前後の空白を無視して判定するため、行全体を正規表現でチェックする
		if pattern.MatchString(line) {
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
