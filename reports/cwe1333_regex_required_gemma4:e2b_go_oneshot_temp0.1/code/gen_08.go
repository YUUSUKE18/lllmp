package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* は行頭の空白を許容
	// (?:[0-9]+(?:,\s*[0-9]+)*) は1つ以上の数字とカンマの組み合わせをキャプチャする非キャプチャグループ
	// (?:,\s*|$) はカンマと空白、または行末を許容する
	// $ は行末
	// この正規表現は、少なくとも1つの数字列がカンマで区切られていることを確認する
	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// 少なくとも一つの数字列が存在することをチェックする。
	// 以下の正規表現は、少なくとも1つの数字列が存在し、カンマで区切られているパターンを検出します。
	// ^\s* 表示行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) 表示1つ以上の数字列と、それに続くカンマと空白の繰り返し
	// $ 表示行末
	// 厳密には、行が空でないこと、かつ数字とカンマのみで構成されていることを確認する必要があります。
	// 「1 個以上の数字列がカンマで区切られて並んでいる」という条件を満たすには、
	// 少なくとも一つの数字列が存在し、その間にカンマがあるか、あるいは単一の数字列である必要があります。

	// 妥当性の判定ロジックをシンプルにするため、以下の正規表現を使用します。
	// 1. 行が空でないこと
	// 2. 行が数字とカンマのみで構成されていること
	// 3. 少なくとも1つの数字列が存在すること
	// 以下の正規表現は、数字とカンマのみで構成され、少なくとも1つの数字列を含む行を検出します。
	// ^\s* : 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列と、それに続くカンマと空白の繰り返し（カンマ区切り）
	// $ : 行末
	// このパターンは、カンマ区切りの整数列が1つ以上存在することを要求します。
	pattern := regexp.MustCompile(`^\s*(?:[0-9]+(?:,\s*[0-9]+)*)\s*$`)

	for scanner.Scan() {
		line := scanner.Text()
		// 行の前後の空白を無視して判定するため、行全体を正規表現でチェックする
		if pattern.MatchString(line) {
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
