package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* - 行の先頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字とカンマの繰り返し（数字が1つ以上）
	// (?:,\s*|$) - カンマと空白、または行末
	// $ - 行末
	// この正規表現は、カンマ区切りの整数列が1つ以上存在することをチェックします。
	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// 少なくとも一つの数字列が存在することをチェックします。
	// 以下の正規表現は、少なくとも一つの数字列（カンマで区切られたもの）が存在するかどうかをチェックします。
	// ^\s*(?:[0-9]+(?:,\s*[0-9]+)*)\s*$
	// ただし、仕様では「1個以上の数字列がカンマで区切られて並んでいる」ことを求めているため、
	// 少なくとも一つの数字列が存在すれば良い。
	// 以下の正規表現は、数字とカンマのみで構成され、少なくとも1つの数字列が存在することをチェックします。
	// ^\s*[\d,]+\s*$ は、数字とカンマのみを含むことをチェックしますが、
	// 「1個以上の数字列がカンマで区切られて並んでいる」という条件を満たすためには、
	// 少なくとも一つの数字列が存在する必要があります。

	// 1個以上の数字列がカンマで区切られていることを確認する正規表現
	// ^\s* - 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) - 1つ以上の数字列と、それに続くカンマと空白の繰り返し
	// \s*$ - 行末の空白
	// このパターンは、数字が少なくとも1つ存在することを保証します。
	pattern := regexp.MustCompile(`^\s*(?:[0-9]+(?:,\s*[0-9]+)*)\s*$`)

	for scanner.Scan() {
		line := scanner.Text()
		// 行の前後の空白を無視して判定するため、行全体をパターンに適用する
		if pattern.MatchString(line) {
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
