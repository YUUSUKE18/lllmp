package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* は行頭の空白を許容
	// (?:[0-9]+(?:,[0-9]+)*) は1つ以上の数字とカンマの組み合わせ（整数列）
	// (?:,|$) はカンマまたは行末（末尾のカンマも許容）
	// この正規表現は、少なくとも1つの数字列が存在し、カンマで区切られている、または単一の数字列であるケースを捉えることを目指す。
	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// 少なくとも一つの数字列が存在し、その間にカンマが挟まれるパターンをチェックする。

	// 妥当性の定義: 1個以上の数字列がカンマで区切られて並んでいる。末尾のカンマは許容。
	// 例: "1,2,3" はOK, "1,2," はOK, "1" はOK, "," はNG, "abc" はNG, "" はNG
	// 正規表現の設計:
	// ^\s* : 行頭の空白
	// (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字列と、それに続くカンマと数字列の繰り返し。
	// (?:,|$) : 最後の要素の後にカンマまたは行末。
	// この定義は複雑になるため、より単純に「カンマで区切られた数字のシーケンス」をチェックする。

	// 妥当な行の判定ロジックを実装するために、各行を個別にチェックする。
	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := ""
		// 行の前後の空白を無視
		for i := 0; i < len(line); i++ {
			if line[i] != ' ' && line[i] != '\t' {
				trimmedLine += string(line[i])
			}
		}

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 妥当性の判定: 1個以上の数字列がカンマで区切られているか、または単一の数字列であるか。
		// 1. 数字とカンマのみで構成されているか？
		// 2. 少なくとも1つの数字列が含まれているか？

		// 妥当なパターン: 数字とカンマのみで構成され、かつ数字が少なくとも1つある。
		// ^\s* : 行頭の空白
		// (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ。
		// $ : 行末
		// 末尾のカンマも許容するため、最後の要素が数字で終わるか、カンマで終わるかを考慮する必要がある。

		// 妥当な行の定義を正規表現で表現する:
		// 1. 少なくとも1つの数字列が存在する。
		// 2. その間にカンマが使われているか、または単一の数字列である。
		// 3. 数字とカンマ以外の文字は含まれない。

		// 以下の正規表現は、「数字とカンマのみ」で構成され、かつ「少なくとも1つの数字」を含む行を検出する。
		// ^\s* : 行頭の空白
		// (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字とカンマの繰り返し。
		// (?:,|$) : 最後の要素がカンマまたは行末。
		// このパターンは、"1,2,3" や "1" や "1," のような構造をカバーする。
		// ただし、"1,," のような連続したカンマはNG。

		// よりシンプルなアプローチ: カンマで分割してみて、すべてが数字であることを確認する。
		fields := strings.Split(trimmedLine, ",")
		isValid := true
		hasNumber := false

		for _, field := range fields {
			// 各フィールドの前後空白を無視してチェック
			trimmedField := strings.TrimSpace(field)

			if trimmedField == "" {
				// 空のフィールドは、連続するカンマや末尾のカンマによって生じる。
				// 末尾のカンマは許容されるため、最後のフィールドが空でなければOK。
				continue
			}

			// フィールドが完全に数字のみで構成されているかチェック
			if regexp.MustCompile(`^\d+$`).MatchString(trimmedField) {
				hasNumber = true
			} else {
				// 数字とカンマ以外の文字が含まれている場合、妥当ではない
				isValid = false
				break
			}
		}

		// 妥当であるためには、少なくとも1つの数字列が存在し、数字とカンマ以外の文字が含まれていない必要がある。
		// 空行はスキップ済み。
		// 妥当な行は、数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれている。
		if isValid && hasNumber {
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
