package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* は行頭の空白を許容
	// (?:[0-9]+(?:,[0-9]+)*) は1つ以上の数字とカンマの組み合わせ（整数列）
	// (?:,|$) はカンマまたは行末（末尾のカンマも許容）
	// この正規表現は、カンマ区切りの整数列が1つ以上存在することをチェックします。
	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// 少なくとも一つの数字列が存在することをチェックします。
	// 以下の正規表現は、カンマで区切られた数字のシーケンスが少なくとも1つ存在することをチェックします。
	// ^\s*(?:[0-9]+(?:,[0-9]+)*)(?:,|$)?\s*$
	// よりシンプルに、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。

	// 妥当性の判定ロジックを実装するために、各行を個別にチェックします。
	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := ""
		// 行の前後の空白を無視
		for _, r := range line {
			if r != ' ' && r != '\t' {
				trimmedLine += string(r)
			}
		}

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現による判定: 1個以上の数字列がカンマで区切られているか、または単一の数字列であるか。
		// 妥当なパターン: 1つ以上の数字とカンマの組み合わせ。末尾のカンマも許容。
		// 例: "1,2,3", "1,2,"
		// 否定されるパターン: 数字とカンマ以外の文字、数字が一つもない（空行を除く）

		// 1. 数字とカンマのみで構成されているかを確認
		// 2. 少なくとも1つの数字が含まれているかを確認
		// 3. 末尾のカンマは許容される

		// 正規表現: 少なくとも1つの数字列が存在し、それらがカンマで区切られている、または単一の数字列である。
		// ^\s* : 行頭の空白
		// (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ（例: 1,2,3 または 123）
		// (?:,|$) : カンマまたは行末
		// \s*$ : 行末の空白
		// この正規表現は、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
		// 末尾のカンマも許容するため、末尾のカンマを明示的に扱う必要があります。

		// 妥当な行の定義: 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
		// 末尾のカンマは許容される。
		// 否定される条件: 数字とカンマ以外の文字が含まれる、または数字が一つもない（空行を除く）。

		// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックする正規表現
		// 1つ以上の数字列 ( [0-9]+ ) がカンマ ( , ) で区切られている、または単一の数字列である。
		// 末尾のカンマは許容。
		// 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
		// ^\s* : 行頭の空白
		// (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ（例: 1,2,3 または 123）
		// (?:,|$) : カンマまたは行末
		// \s*$ : 行末の空白
		// このパターンは、末尾のカンマを許容するために調整が必要です。

		// 最終的な判定ロジック:
		// 1. 行が空でないこと (trimmedLine != "")
		// 2. trimmedLine が数字とカンマのみで構成されていること。
		// 3. 少なくとも1つの数字が含まれていること。

		// 数字とカンマ以外の文字が含まれていないかチェック
		if regexp.MustCompile(`[^0-9,]*$`).MatchString(trimmedLine) {
			// 数字とカンマのみで構成されている
			// 少なくとも1つの数字が含まれているかチェック
			if regexp.MustCompile(`[0-9]+`).MatchString(trimmedLine) {
				// 妥当
				validCount++
			}
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
