import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;

        while (true) {
            String line = br.readLine();
            if (line == null) {
                break;
            }

            // 正規表現パターン: 
            // ^\s* : 行の先頭の空白を無視
            // (?:[0-9]+(?:,?[0-9]+)*) : 1個以上の数字列とカンマの組み合わせ。
            // このパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれることを想定する。
            // 末尾のカンマも許容する。
            // 厳密には「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する必要がある。
            // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれることを確認する。
            // 1個以上の数字列がカンマで区切られていることを確認するため、
            // 数字とカンマのシーケンスが少なくとも1つ存在することをチェックする。
            
            // 妥当性の判定ロジックを正規表現で実装する。
            // 1. 行が空でないこと (trim()でチェック)
            // 2. 行が数字とカンマのみで構成されていること。
            // 3. 少なくとも1つの数字が含まれていること。
            
            String trimmedLine = line.trim();
            if (trimmedLine.isEmpty()) {
                continue; // 空行は妥当ではない
            }

            // 正規表現: 
            // ^\s* : 行頭の空白
            // (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字列と、その間にカンマが続くパターン。
            // 末尾のカンマも許容するため、全体をチェックする。
            // 妥当な形式: 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
            // 例: 1,2,3 または 1,2,3,
            
            // 1. 数字とカンマのみで構成されているか？
            // 2. 少なくとも1つの数字が含まれているか？
            
            // この課題の「1個以上の数字列がカンマで区切られて並んでいる」を正規表現で厳密に表現するのは複雑です。
            // 許容される形式: 数字,数字, ... または 数字,数字,...
            // 末尾のカンマは許容。
            
            // パターン: 少なくとも1つの数字があり、数字とカンマのみで構成されている。
            // (?:[0-9]+(?:,[0-9]+)*) は、1つ以上の数字で始まり、カンマ区切りで続くことを意味する。
            // 末尾のカンマを許容するため、行末がカンマで終わることも許容する。
            
            // 妥当なパターン: 
            // ^\s* : 行頭の空白
            // (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ
            // (?:,|$) : カンマまたは行末
            
            // より簡単なアプローチとして、文字列を分割し、各要素が数字であるかを確認する方が、
            // 正規表現の複雑さを避けつつ、仕様を満たしやすい。
            // しかし、仕様で「判定には正規表現を用いてください」と指定されているため、正規表現で試みる。

            // 正規表現による判定: 
            // 1. 行が数字とカンマのみで構成されているか。
            // 2. 少なくとも1つの数字が含まれているか。
            // 3. 末尾のカンマは許容される。
            
            // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
            // (?:[0-9]+(?:,[0-9]+)*) は、数字とカンマのシーケンスを表現する。
            // 末尾のカンマを許容するため、行末がカンマで終わることを許容する。
            
            // 妥当な行のパターン: 数字とカンマの連続であり、少なくとも1つの数字が含まれる。
            // 例: "1,2,3" または "1,2," または "1"
            // このパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
            String pattern = "^\\s*([0-9]+(?:,[0-9]+)*)(?:,|$)";
            
            // 実際には、行全体がこの形式に従うかを確認する。
            // 行全体が、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
            // 末尾のカンマは許容。
            // 妥当な行のパターンを再定義: 
            // 1. 数字とカンマのみで構成されている。
            // 2. 少なくとも1つの数字が含まれている。
            
            // この行が数字とカンマのみで構成されていることを確認する。
            // 任意の文字が数字またはカンマである。
            String allowedCharsPattern = "^[0-9,]*$";
            if (!Pattern.matches(allowedCharsPattern, line)) {
                continue; // 数字とカンマ以外が含まれていたら不妥当
            }
            
            // 少なくとも1つの数字が含まれているか確認する。
            // この行が数字のみで構成されている場合（例: "123"）、これは妥当。
            // この行がカンマのみで構成されている場合（例: "," や ",,"）、これは不妥当。
            
            boolean containsDigit = false;
            for (char c : line.toCharArray()) {
                if (Character.isDigit(c)) {
                    containsDigit = true;
                    break;
                }
            }
            
            if (containsDigit) {
                validLines++;
            }
        }

        System.out.println("valid=" + validLines);
    }
}
