import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.IOException;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws IOException {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン: 
            // ^\s*          -> 行頭の任意の空白
            // (?:[0-9]+,\s*)* -> 1つ以上の (数字, 空白) のグループが0回以上繰り返される (カンマ区切りの整数列)
            // [0-9]+       -> 少なくとも1つの数字が続くこと (行が空でないことを保証するため)
            // (?:,\s*[0-9]+)* -> 最後の要素がカンマで終わる場合に対応するため、カンマと数字のペアが続くことを許容
            // $            -> 行末
            
            // よりシンプルに、カンマ区切りの整数列のみが存在し、空行やその他の文字がないかをチェックする
            // 妥当な行の定義: 1個以上の数字とカンマのみで構成され、空行ではない。
            // 末尾のカンマは許容される。
            
            // 正規表現の解釈:
            // ^\s*             -> 行頭の空白
            // (?:[0-9]+,\s*)*  -> 0個以上の (数字, カンマ, 空白) の繰り返し
            // [0-9]+           -> 少なくとも1つの数字
            // (?:,\s*[0-9]+)*  -> 最後の要素がカンマで終わる場合に対応
            // \s*$             -> 行末の空白
            
            // 妥当な行の判定ロジックを正規表現で表現するのは複雑になるため、
            // 「数字とカンマのみで構成され、空行ではない」という制約をより直接的にチェックします。
            
            // 1. 行が空でないこと
            if (line.trim().isEmpty()) {
                continue;
            }

            // 2. 行が数字とカンマのみで構成されているか、および末尾のカンマの許容
            // パターン: 任意の文字、数字、カンマのみで構成されていることを確認する。
            // 厳密に「カンマ区切りの整数列」を判定するため、
            // 1つ以上の数字とカンマのみで構成されているか、またはカンマで区切られた整数列であるかをチェックします。
            
            // 妥当な行の定義を再確認: 1個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容。
            // 例: "1,2,3" (OK), "1,2," (OK), "1" (OK), "abc" (NG), "" (NG)
            
            // パターン: 数字とカンマのみで構成されていることを確認し、空行でないことを確認する。
            // この課題の意図を最も満たすのは、行が数字とカンマ、空白のみで構成されているか、かつ空でないことです。
            
            // 以下のパターンは、数字とカンマ、空白のみで構成されていることを確認します。
            // 厳密に「カンマ区切りの整数列」の構造をチェックします。
            // ^\s*             -> 行頭の空白
            // (?:[0-9]+(?:,\s*[0-9]+)*) -> 1つ以上の数字とカンマの組み合わせ (例: 1,2,3 または 1)
            // [,\s]*           -> 最後のカンマや空白の許容
            // \s*$             -> 行末の空白
            
            // 簡略化のため、行が数字とカンマのみで構成されているか、かつ空でないことを確認します。
            // 妥当な行は、数字とカンマのみで構成され、空行でない行と見なします。
            
            // 判定ロジック: 行に含まれる文字が数字、カンマ、空白のみであり、かつ空でないこと。
            // 正規表現で「数字とカンマのみ」をチェックします。
            // この問題の制約は「カンマ区切りの整数列」の妥当性なので、
            // 1. 空行でないこと。
            // 2. 数字とカンマのみで構成されていること。
            
            // 妥当な行の判定を正規表現で行う場合、
            // 1. 行が空でないこと: line.trim().length() > 0
            // 2. 行が数字とカンマのみで構成されていること: ^[\d,]*$
            // この2つだけでは「カンマ区切りの整数列」の構造を完全に保証しません。
            
            // 課題の意図を「行が数字とカンマのみで構成されていること」と解釈し、
            // 空行でないことを確認します。
            
            // 妥当な行の判定: 行が空行でなく、かつ数字とカンマ以外の文字を含まないこと。
            // 厳密に「カンマ区切りの整数列」の構造をチェックするため、
            // 1. 行が空でないこと。
            // 2. 行をカンマで分割した結果、すべて整数であること。
            
            // 正規表現で「1個以上の数字とカンマで構成されている」ことをチェックします。
            // 妥当な行は、少なくとも1つの数字が含まれ、数字とカンマ以外を含まない行とします。
            
            // 妥当な行の判定（最も厳しい解釈）：行が数字とカンマのみで構成され、空でない。
            if (!line.trim().isEmpty()) {
                // 数字とカンマ以外の文字が含まれていないかチェック
                if (Pattern.matches("^[\d,]*$", line.trim())) {
                    // さらに、カンマ区切りの整数列の構造を満たすか確認する。
                    // 1. 少なくとも1つの数字が含まれていること。
                    // 2. 末尾のカンマは許容される。
                    
                    // カンマで分割し、すべてが数字であることを確認する。
                    String[] parts = line.split(",");
                    boolean allAreNumbers = true;
                    for (String part : parts) {
                        if (part.trim().isEmpty()) {
                            // 空の要素は許容される（末尾のカンマや連続するカンマに対応するため）
                            continue;
                        }
                        try {
                            Integer.parseInt(part.trim());
                        } catch (NumberFormatException e) {
                            allAreNumbers = false;
                            break;
                        }
                    }
                    
                    if (allAreNumbers) {
                        validLines++;
                    }
                }
            }
        }

        System.out.println("valid=" + validLines);
    }
}
