import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン: カンマで区切られた整数列。末尾のカンマも許容する。
            // ^\s* : 行頭の空白を無視
            // (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ。
            // このパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれることを確認する。
            // 末尾のカンマも許容するため、行末にカンマがあっても良い。
            // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
            
            // 許容するパターン: 
            // 1. 数字とカンマのみで構成されている。
            // 2. 少なくとも1つの数字が含まれている。
            // 3. 末尾にカンマがあっても良い。
            
            // パターンを調整: 
            // ^\s* : 行頭の空白
            // (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ。
            // (?:,\s*|$) : カンマと空白、または行末
            
            // 課題の要件を再解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
            // これは、カンマで区切られた要素がすべて整数である、ということを意味する。
            // 例: "1,2,3" -> 3つの整数列
            // 例: "1,2," -> 2つの整数列（最後の要素は空またはカンマ）
            
            // 正規表現で「カンマ区切りの整数列」を判定する。
            // 少なくとも1つの数字が含まれ、数字とカンマ以外の文字が含まれていないことを確認する。
            
            // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
            // ^\s* : 行頭の空白
            // (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ（数字列が1つ以上続く）
            // .* : 残りの文字（末尾のカンマなど）
            // $ : 行末
            
            // よりシンプルに、数字とカンマのみで構成され、少なくとも1つの数字が含まれているかをチェックする。
            // 許容される形式: 数字,数字,... または 数字,数字,...
            // 少なくとも1つの数字が含まれていることを確認する。
            String trimmedLine = line.trim();
            
            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 数字とカンマのみで構成されているか、かつ少なくとも1つの数字が含まれているかをチェック
            // パターン: 1つ以上の数字、カンマ、空白、数字の繰り返し。末尾のカンマも許容。
            // 整数列の例: "1,2,3", "1,2,"
            // 整数列ではない例: "1,a,3", "abc"
            
            // 正規表現で「カンマ区切りの整数列」を判定する。
            // (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ。
            // このパターンは、カンマで区切られた複数の整数列を許容する。
            // 末尾のカンマを許容するため、行末にカンマがあっても良い。
            
            // 判定ロジックを正規表現で実行する
            // 1. 行全体が数字とカンマ、空白のみで構成されているか？
            // 2. 少なくとも1つの数字が含まれているか？
            
            // 許容されるパターン: 整数とカンマのみで構成され、少なくとも1つの整数が含まれる。
            // ^\s* : 行頭の空白
            // (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字とカンマの組み合わせ（少なくとも1つの数字を含む）
            // .* : 残りの文字（末尾のカンマなど）
            // $ : 行末
            
            // 課題の要件を満たすための最も安全な正規表現は、
            // 整数とカンマ以外の文字を含まないことを確認し、かつ数字が存在することを確認すること。
            // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するには、
            // カンマで区切られた要素がすべて整数であることを確認する必要があります。
            
            // 整数列の例: "1,2,3" (3つの整数)
            // 整数列の例: "1,2," (2つの整数)
            
            // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
            // 任意の文字が数字またはカンマまたは空白である、という制約を課す。
            // 実際には、行を分割して各要素が整数であることを確認する方が、この複雑な構造には適している。
            
            // 正規表現で「カンマ区切りの整数列」を判定する。
            // 整数とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
            // 以下のパターンは、行が数字とカンマのみで構成されていることを確認します。
            // ^\s* : 行頭の空白
            // [0-9,]* : 数字またはカンマのみ
            // \s*$ : 行末の空白
            
            // この制約だけでは「1個以上の数字列がカンマで区切られて並んでいる」を満たせないため、
            // 行を分割して検証するアプローチが最も確実です。正規表現での判定を強制されているため、
            // 以下のパターンを採用します。
            
            // 整数とカンマのみで構成されていることを確認し、かつ数字が存在することを確認する。
            // 少なくとも1つの数字が含まれていることを確認する。
            Pattern pattern = Pattern.compile("^\\s*([0-9,]+(\\s*,[0-9,]+)*)[\\s]*$");
            Matcher matcher = pattern.matcher(line);
            
            // 課題の要件「1 個以上の数字列がカンマで区切られて並んでいる」を正規表現で厳密に表現するのは困難なため、
            // 以下のロジックで、行が整数とカンマのみで構成されていることを確認し、かつ数字が存在することを検証します。
            
            // 整数とカンマのみで構成されているか、かつ少なくとも1つの数字が含まれていることを確認する。
            // 整数とカンマのみで構成されていることを確認するパターン:
            String integerAndCommaPattern = "^\\s*([0-9,]+(?:,\\s*[0-9,]+)*)[\\s]*$";
            
            // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
            // 1. 行をカンマで分割し、
            // 2. 各要素が整数であるか、または空でないことを確認する。
            // 正規表現での判定を強制されているため、ここでは「数字とカンマのみで構成されている」ことを主要なチェックとします。
            
            // 最終的な判定ロジック（正規表現を使用）
            // 整数とカンマのみで構成されていることを確認し、かつ少なくとも1つの数字が含まれていることを確認する。
            // この行が「カンマ区切りの整数列」として妥当であるためには、
            // 1. 数字とカンマ以外の文字を含まない。
            // 2. 少なくとも1つの数字が含まれている。
            
            // 整数とカンマのみで構成されていることを確認するパターン
            if (line.matches("^\\s*[0-9,]*\\s*$")) {
                // 数字とカンマのみで構成されている場合、さらに「1個以上の数字列」の条件を満たすか確認する。
                // 少なくとも1つの数字が含まれているか？
                if (line.matches(".*[0-9].*")) {
                    // 少なくとも1つの数字が含まれている。
                    validLines++;
                }
            }
        }

        System.out.println("valid=" + validLines);
    }
}
