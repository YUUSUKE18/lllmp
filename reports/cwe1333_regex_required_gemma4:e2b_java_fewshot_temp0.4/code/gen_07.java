import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン: 
            // ^\s*       -> 行の先頭の空白を無視
            // (?:[0-9]+,\s*)* -> 1つ以上の数字とカンマの組み合わせ（カンマ区切りの整数列）が0回以上繰り返される
            // [0-9]+     -> 少なくとも1つの数字が続く
            // .*?        -> 残りの任意の文字（末尾のカンマなど）
            // $          -> 行の終わり
            // このパターンは「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するのではなく、
            // 「数字とカンマのみで構成され、少なくとも1つの数字が含まれている」ことを確認するのに適しています。
            // 仕様に合わせて、「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
            // 妥当な形式: 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。末尾のカンマは許容。
            
            // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックします。
            // パターン: ^\s*([0-9]+(?:,\s*[0-9]+)*)(?:,)?\s*$
            // これは複雑になるため、よりシンプルなチェックと正規表現の組み合わせを考えます。
            
            // 妥当な行の条件:
            // 1. 空行ではない (line.trim().length() > 0)
            // 2. 数字とカンマのみで構成されている
            // 3. 少なくとも1つの数字が含まれている
            // 4. 末尾のカンマは許容される
            
            String trimmedLine = line.trim();
            
            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 正規表現によるチェック: 
            // ^\s*                  -> 行頭の空白
            // (?:[0-9]+(?:,\s*[0-9]+)*) -> 1つ以上の数字とカンマのペアが続くパターン (例: 1,2,3 または 1,2)
            // (?:,?\s*$)            -> 末尾のカンマや空白の許容
            
            // 妥当な形式のパターンを定義します。
            // 1. 数字とカンマのみで構成されていること。
            // 2. 少なくとも1つの数字が含まれていること。
            // 3. 末尾のカンマは許容されること。
            
            // 簡略化のため、行全体が数字、カンマ、空白のみで構成されているかを確認し、
            // さらに数字が含まれているかを確認します。
            
            // 1. 数字とカンマ、空白のみで構成されているか (数字とカンマ以外は許容しない)
            // この条件は、行が「カンマ区切りの整数列」であるという構造をチェックします。
            // 正規表現: ^[\d,]*$ (数字とカンマのみ)
            
            // 2. 少なくとも1つの数字が含まれているか
            // 正規表現: [\d]+ (少なくとも1つの数字)
            
            // 妥当な行の判定ロジックを正規表現で表現します。
            // 妥当な行は、数字とカンマ、空白のみで構成され、かつ数字が少なくとも1つ含まれている。
            // 末尾のカンマは許容されるため、行の末尾がカンマで終わるか、数字で終わるか、あるいは数字の後にカンマが続く形を許容します。
            
            // 妥当な行のパターン: 
            // ^\s*                 // 行頭の空白
            // (?:[0-9]+(?:,\s*[0-9]+)*) // 1つ以上の数字がカンマ区切りで続くパターン (例: 1,2,3 または 1,2)
            // (?:,)?               // 最後の要素の後のカンマ（任意）
            // \s*$                 // 行末の空白
            
            // 課題の仕様を再解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
            // これは、カンマで区切られた要素がすべて整数であることを意味します。
            // 例: "1,2,3" -> 3つの整数列 (1, 2, 3)
            // 例: "1,2," -> 2つの整数列 (1, 2)
            
            // 妥当な行のパターン: 数字とカンマ、空白のみで構成され、かつ数字が1つ以上含まれている。
            // 厳密に「カンマ区切りの整数列」として解釈し、数字とカンマ、空白以外の文字を含まないことを確認します。
            
            // 妥当な行の正規表現: 
            // ^\s*                                 // 行頭の空白
            // (?:[0-9]+(?:,\s*[0-9]+)*)              // 1つ以上の数字とカンマのペアが続く（例: 1,2,3 または 1,2）
            // (?:,)?                               // 最後の要素の後のカンマ（任意）
            // \s*$                                 // 行末の空白
            
            // 実際には、行全体が数字とカンマ、空白のみで構成されていることを確認し、数字が含まれていることを確認します。
            // 妥当な行のパターン: 
            // ^\s*                                 // 行頭の空白
            // (?:[0-9][,\s]*)+                     // 少なくとも1つの数字とそれに続くカンマ/空白の繰り返し
            // \s*$                                 // 行末の空白
            
            // 最終的な判定: 行が空でなく、数字とカンマ、空白以外を含まないこと。
            // そして、数字が少なくとも1つ含まれていること。
            
            // 妥当な行の判定: 行が空でなく、数字とカンマ、空白のみで構成されていること。
            // そして、数字が含まれていること。
            
            // 妥当な行のパターン: ^\s*[\d,]*\s*$ (数字とカンマのみで構成されている)
            // このパターンだけでは「1個以上の数字列がカンマで区切られて並んでいる」という構造は保証されません。
            
            // 構造を重視した正規表現: 
            // ^\s*                                 // 行頭の空白
            // (?:[0-9]+(?:,\s*[0-9]+)*)              // 1つ以上の数字とカンマのペアが続く (例: 1,2,3 または 1,2)
            // (?:,)?                               // 最後の要素の後のカンマ（任意）
            // \s*$                                 // 行末の空白
            
            // このパターンが、意図する「カンマ区切りの整数列」の構造を最もよく表すと仮定します。
            
            String pattern = "^\\s*(?:[0-9]+(?:,\\s*[0-9]+)*)(?:,)?\\s*$";
            
            if (Pattern.matches(pattern, line)) {
                validLines++;
            }
        }

        System.out.println("valid=" + validLines);
    }
}
