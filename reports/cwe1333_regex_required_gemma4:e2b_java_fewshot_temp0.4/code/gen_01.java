import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン: カンマ区切りの整数列。末尾のカンマも許容する。
            // ^\s* : 行頭の空白を無視
            // (?:[0-9]+(?:,|$))+ : 1つ以上の数字列とカンマの組み合わせ。数字列の後にカンマまたは行末が続く。
            // $ : 行末
            // この正規表現は「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
            // 末尾のカンマを許容するため、行末にカンマが来ることを許容する。
            // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
            // 少なくとも一つの数字列が存在し、カンマで区切られている構造をチェックする。

            // 妥当性の判定ロジックを正規表現で表現する。
            // 1. 行が完全に空でないこと（空白のみでないこと）
            // 2. 数字とカンマのみで構成されていること
            // 3. 少なくとも1つの数字列が存在すること
            // 4. 末尾のカンマは許容されること

            // 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
            // (?:[0-9]+(?:,|$))+ : 1つ以上の数字列とカンマの組み合わせ。数字列の後にカンマまたは行末が続く。
            // このパターンは、カンマで区切られた数字のシーケンスを捉えるのに適していますが、
            // 末尾のカンマの許容や、行全体が数字とカンマのみで構成されていることを確認する必要があります。

            // 簡略化のため、行をトリムし、その内容が数字とカンマのみで構成されているか、かつ数字が含まれているかをチェックする。
            String trimmedLine = line.trim();

            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 正規表現で、行が数字とカンマのみで構成されているか、かつ少なくとも1つの数字が含まれているかをチェック
            // パターン説明:
            // ^[0-9,]* : 行頭から数字またはカンマが0回以上続く
            // (?=.*[0-9]) : 後読みで、少なくとも1つの数字が存在すること (肯定先読み)
            // [0-9,]*$ : 行末まで数字またはカンマが0回以上続く
            // このパターンは、行全体が数字とカンマのみで構成され、数字が少なくとも1つ含まれていることを確認します。
            String regex = "^[0-9,]*?(?=.*[0-9])[0-9,]*$";
            
            // より単純に、行が数字とカンマのみで構成され、かつ数字が含まれていることを確認する。
            // 末尾のカンマを許容するため、行の末尾がカンマで終わることも許容する。
            // 妥当な行は、数字とカンマのみで構成され、かつ、少なくとも1つの数字が含まれている。
            // 末尾のカンマは許容されるため、行全体が数字とカンマのシーケンスであること。
            
            // 妥当性の定義を再解釈: 「1個以上の数字列がカンマで区切られて並んでいる」
            // これは、カンマで区切られた要素がすべて整数である、という条件を意味します。
            // 例: "1,2,3" (妥当), "1,,2" (妥当と見なすか？) -> 仕様では「1個以上の数字列がカンマで区切られて並んでいる」
            // 空の要素（,,）は許容されないと解釈する。
            
            // 1. カンマで分割し、空でない要素が1つ以上あるか。
            String[] parts = trimmedLine.split(",");
            boolean isValid = false;
            
            if (parts.length > 0) {
                // 空でない要素が1つ以上あるかチェック
                for (String part : parts) {
                    if (!part.trim().isEmpty()) {
                        isValid = true;
                        break;
                    }
                }
            }

            if (isValid) {
                validLines++;
            }
        }

        System.out.println("valid=" + validLines);
    }
}
