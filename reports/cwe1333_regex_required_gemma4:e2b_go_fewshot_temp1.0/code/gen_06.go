package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// 処理対象の行をすべて読み込む
	for scanner.Scan() {
		line := scanner.Text()

		// 末尾の空白を除去した上で、正規表現で判定する
		// 正規表現: 1つ以上の数字、カンマ、空白、または行の終端
		// 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」
		// 末尾のカンマは許容される。
		// 以下の正規表現は、少なくとも1つの数字が含まれ、カンマ区切りであることが必要。
		// (?:[0-9]+(?:,[0-9]+)*) は、1つ以上の数字と、その後にカンマと数字が続くパターンを意味する。
		// ただし、末尾のカンマが許容されるため、より柔軟に考える必要がある。

		// 判定ロジック：行が空行でないこと、および数字とカンマのみで構成されていることを確認する。
		// 1. 空行でないことを確認
		if strings.TrimSpace(line) == "" {
			continue
		}

		// 2. 正規表現による判定
		// 少なくとも1つの数字が含まれ、カンマ区切り（末尾カンマ含む）であることを確認する。
		// 例: "1,2,3", "1,2,", "100,"
		// ^\s*            -> 行の先頭の空白
		// (?:[0-9]+(?:,[0-9]+)*) -> 1つ以上の数字と、カンマと数字の繰り返し
		// [,\s]*          -> 続くカンマや空白（末尾のカンマは許容されるため、末尾の文字に依存させる）
		// $               -> 行の終わり
		//
		// よりシンプルなアプローチとして、以下の条件で妥当性を判定する。
		// 1. 行が空でないこと。
		// 2. 行に含まれる文字が、数字、カンマ、空白のみであること。
		// 3. 少なくとも1つの数字が含まれていること。
		// 4. 末尾のカンマは許容されること。

		// 末尾のカンマを無視して、数字とカンマのみの文字列として扱う
		trimmedLine := strings.TrimSpace(line)

		// 妥当性の判定: 
		// 1. 文字列が空でないこと (すでにチェック済みだが念のため)
		// 2. 文字列に含まれる文字が数字とカンマのみであること。
		// 3. 少なくとも1つの数字が含まれていること。
		// 4. 末尾のカンマは許容されること。

		// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を正規表現で表現する。
		// 数字とカンマのみで構成され、最低1つの数字が含まれていることを確認する。
		// \d+ は少なくとも1つの数字。
		// [,\d]* は、数字とカンマのみで構成される。
		// このパターンで、末尾のカンマが許容されることを考慮する。
		// (?:[0-9][,]*)+  -> 少なくとも1つの数字で始まり、それに続くカンマと数字の繰り返し。
		// $?            -> 行末が任意。
		
		// 提示された仕様に基づき、最もシンプルかつ厳密に「数字とカンマ」のみで構成されていることを確認する。
		// 末尾のカンマが許容されるため、行全体を評価する。
		
		// 妥当な行の定義を「カンマで区切られた数字のセット」と解釈し、末尾のカンマが許容される。
		// 例: "1,2" -> OK, "1,2," -> OK, "abc" -> NG, "" -> NG
		
		// 正規表現: 1個以上の数字がカンマで区切られているパターン。
		// (?:[0-9]+(?:,[0-9]+)*) は、カンマ区切りの数字列を意味する。
		// 末尾のカンマを許容するため、行全体がこのパターンに一致するか、または数字とカンマのみで構成されているかを評価する。
		
		// 簡略化のため、行が完全に数字とカンマ、空白のみで構成されていることを確認し、かつ数字が存在すればOKとする。
		// 行全体が数字とカンマのみで構成されているかを確認する正規表現。
		// ^\s* [0-9,]* \s*$ 
		
		// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックするには、
		// 少なくとも1つの数字があり、カンマが含まれているか、あるいはカンマで区切られている必要がある。
		
		// カンマ区切りパターン: 1つ以上の数字と、カンマ（任意）が交互に現れる。
		// 1. 1個以上の数字が含まれていること
		// 2. 含まれる文字が数字とカンマのみであること
		
		// 以下の正規表現は、数字とカンマのみで構成されており、かつ少なくとも1つの数字が含まれている行をキャプチャする。
		// これは、カンマ区切り数字列が主要な要素であり、空行や無関係な文字が含まれていないことを確認する最も確実な方法となる。
		match, _ := regexp.MatchString(`^[\d,]*$`, line)
		
		if match {
			// 数字またはカンマのみで構成されている。ここで数字が存在するか確認する。
			if strings.Contains(line, "0") || strings.Contains(line, "1") || strings.Contains(line, "2") || strings.Contains(line, "3") || strings.Contains(line, "4") || strings.Contains(line, "5") || strings.Contains(line, "6") || strings.Contains(line, "7") || strings.Contains(line, "8") || strings.Contains(line, "9") {
				// 数字が含まれていれば妥当とする（空のカンマ列 " ," などは除外）
				validLines++
			}
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常、ここでは特に要求されていないが、安全のため）
	}

	fmt.Printf("valid=%d\n", validLines)
}
