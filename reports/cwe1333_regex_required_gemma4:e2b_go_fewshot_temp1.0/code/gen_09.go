package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	r := bufio.NewReader(os.Stdin)
	// 正規表現パターン: カンマで区切られた整数列。
	// ^\s* は行の先頭の空白を無視
	// (?: ... ) は非キャプチャグループ
	// \d+ は1つ以上の数字
	// (?:,\d+)* はカンマと数字の繰り返し（末尾のカンマは許容されるため、最後にカンマが来ることを許容する）
	// \s* は行末の空白を無視
	// ここでは、行全体が「カンマ区切りの整数列」であることを確認したい。
	// 妥当な行の定義: 1個以上の数字とカンマのみで構成され、数字列がカンマで区切られている。
	// より厳密に「1個以上の数字がカンマで区切られている」ことを確認するパターンを採用する。
	// 少なくとも一つの数字があり、カンマと数字以外の文字が一切ない、という条件を満たすようにする。

	// パターン定義: 
	// ^\s*           : 行頭の空白
	// (?:           : 非キャプチャグループの開始
	//   \d+         : 1つ以上の数字 (最初の数字列)
	//   (?:,\d+)*   : カンマとそれに続く1つ以上の数字の繰り返し
	// )             : グループの終了
	// (?:,\d+)?      : 末尾のカンマと数字のオプション (末尾のカンマは許容されるが、これは他の数字列の後に続くものとして扱う)
	// \s*$          : 行末の空白
	// よりシンプルに、行が数字とカンマのみで構成され、数字が少なくとも1つあることを確認する。

	// 妥当性の判定ロジック:
	// 1. 行が空行でないこと (正規表現で非空を保証する)
	// 2. 行が数字とカンマのみで構成されていること
	// 3. 数字が少なくとも1つ存在すること

	// 行が空でないことを確認し、数字とカンマのみで構成されていることを確認する
	// または、よりシンプルに、カンマで分割した結果に空文字列がないことを確認する。
	
	// 仕様を再解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
	// これは、文字列をカンマで分割した際に、空でない要素が1つ以上存在することを意味する。
	// 空行は妥当ではない。数字とカンマ以外を含む行は妥当ではない。

	// 正規表現で「数字とカンマのみ」という制約を厳密に適用し、その後に分割処理で「1個以上の数字」をチェックする。

	// パターン：行全体が数字(\d+), カンマ(,), および空白(\s)のみで構成されている。
	// ただし、例1, 2, 3の入力の読み取り方に基づくと、行全体をそのまま評価するのではなく、内容を解析する方が自然である。
	// 「行が『カンマ区切りの整数列』として妥当かどうかを判定する」

	// 最もシンプルな判定（例2の考え方）に従い、行を読み込み、カンマで分割し、空でない要素の数を数える。
	// ただし、行が「数字とカンマ以外を含む行は妥当ではない」という制約を正規表現で追加する必要がある。

	validLines := 0
	
	for {
		line, err := r.ReadString('\n')
		if err != nil {
			break
		}

		// 行末の改行文字を削除して処理
		line = strings.TrimSpace(line)

		if line == "" {
			// 空行は妥当ではない
			continue
		}

		// 1. 数字とカンマ以外を含む行のチェック（正規表現を使用）
		// 許可される文字: 数字(0-9), カンマ(,), 空白( )
		// ^[\d, ]*$ : 行全体が数字、カンマ、空白のみで構成されていることを確認。
		// ※ただし、仕様は「数字とカンマ以外を含む行は妥当ではない」なので、これは「許可される文字」を定義する。
		// 許可される文字セット: [0-9, , ]
		if !regexp.MustCompile(`^[\d, ]*$`).MatchString(line) {
			continue // 許可されない文字が含まれる
		}

		// 2. カンマ区切りの整数列のチェック
		// カンマで分割し、空でない要素が1つ以上あるかを確認する。
		parts := strings.Split(line, ",")
		count := 0
		for _, part := range parts {
			if strings.TrimSpace(part) != "" {
				count++
			}
		}

		if count > 0 {
			validLines++
		}
	}

	fmt.Printf("valid=%d\n", validLines)
}
