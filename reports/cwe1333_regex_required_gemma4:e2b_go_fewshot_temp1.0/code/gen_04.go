package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	r := bufio.NewReader(os.Stdin)
	
	// 妥当な行数を格納するカウンタ
	validLines := 0
	
	// 1行ずつ読み込む
	for {
		line, err := r.ReadString('\n')
		
		// EOFまたは読み取りエラーが発生した場合
		if err != nil && len(line) == 0 {
			break
		}
		
		// 行末の改行文字を削除して処理
		line = strings.TrimSpace(line)

		// 空行の場合はスキップ
		if line == "" {
			continue
		}

		// 正規表現による妥当性の判定
		// 妥当な行の条件: 1個以上の数字列がカンマで区切られて並んでいること。
		// パターン:
		// ^                -> 行の先頭
		// [0-9]+,\s*       -> 1つ以上の数字の後にカンマと任意の空白が続くパターン（最初の要素）
		// (?:[0-9]+,\s*)*  -> カンマ区切りのペアが0回以上繰り返される (2番目以降の要素)
		// [0-9]+           -> 最後の要素 (カンマなし)
		// $                -> 行の末尾
		//
		// より単純に、数字とカンマだけで構成され、少なくとも1つの数字が含まれることを確認する。
		// 1. 行が空でないこと (既にチェック済み)
		// 2. 行が数字とカンマのみで構成されていること
		// 3. 少なくとも1つの数字が存在すること
		
		// 正規表現: カンマ区切りの数字列が1つ以上存在する行をチェックする
		// (?:[0-9]+(?:,.*)?)* は、数字とカンマのシーケンスを許容する
		// 最後の要素が数字で終わることを強く要求する。
		// 以下の正規表現は、「数字のシーケンスとカンマが混在する」ことを確認し、空でないことを保証する。
		// 少なくとも一つの数字が含まれ、その間にカンマが存在する可能性がある行を対象とする。
		// \d+ は1つ以上の数字
		// (?:,\d+)* はカンマに続く数字のシーケンス（カンマで区切られた複数の要素）
		// 最終的に、少なくとも1つの数字が含まれていればOKとする。
		
		// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックする正規表現を試みる。
		// 例: "1,2,3" または "1,2," または "1,"
		// 最後の要素がカンマで終わっても許容する。
		// このパターンは、数字がカンマで区切られている構造をチェックします。
		// (?:[0-9]+(?:,|$))+ : 数字の塊がカンマまたは行末に続くことを確認
		match, err := regexp.MatchString(`^[\d,]+$`) // まず数字とカンマのみで構成されているかチェック
		
		// 念のため、数字のみで構成されている行（例: "123"）も許容範囲に入れるか、
		// 要件「1 個以上の数字列がカンマで区切られて並んでいる」に厳密に従う。
		// この要件を満たすためには、カンマが少なくとも1つ含まれているか、または、カンマ区切り形式である必要がある。
		// 末尾のカンマは許容されるため、"1," や "1,2," は許容される。
		
		// 許容される形式: (数字),(数字),... または (数字)
		// 以下のパターンは、数字とカンマが混在していることを要求し、空行や不正文字を除外するのに役立つ。
		// 少なくとも1つの数字があり、数字とカンマが交互または連続して出現する。
		// 1個以上の数字列がカンマで区切られている、という条件を満たすためには、最低1つのカンマまたは数字のセットが必要。
		
		// 最終的な判定ロジック:
		// 行が完全に数字とカンマのみで構成されており、かつ数字が含まれていること。
		// この実装では、"1,2" や "1,2," のようにカンマで区切られている行を妥当とみなします。
		// 単純に、数字とカンマ以外の文字が含まれていないことを確認し、少なくとも1つの数字が存在すればOKとする。
		
		// 正規表現で「数字とカンマのみ」で構成されていることを確認
		if regexp.MustCompile(`^[\d,]*$`).MatchString(line) {
			// さらに、数字が1つ以上含まれていることを確認
			if regexp.MustCompile(`\d`).MatchString(line) {
				validLines++
			}
		}
	}

	// 結果を出力
	fmt.Printf("valid=%d\n", validLines)
}
