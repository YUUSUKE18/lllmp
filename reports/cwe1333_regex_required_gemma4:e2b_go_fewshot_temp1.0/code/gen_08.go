package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// カンマ区切りの整数列のパターンを定義します。
	// これは「1個以上の数字とカンマの組み合わせ」を許容するパターンです。
	// 具体的には、数字、カンマ、および空白のみを含む行を許容します。
	// 末尾のカンマも許容し、空行（または空白のみの行）は無視します。
	// 許容されるパターン: 1つ以上の数字とカンマが混在する。
	// 正規表現で「1つ以上の数字、カンマ、空白のみで構成され、空行ではない」ことを確認します。
	// シンプルに、行が空でなく、数字とカンマ以外の文字を含まないか、あるいは少なくとも数字とカンマが含まれているかをチェックします。

	// 課題の「妥当とは、1 個以上の数字列がカンマで区切られて並んでいることです。末尾のカンマは許容します。」
	// 空行、および数字とカンマ以外を含む行は妥当ではありません。
	// 末尾のカンマは許容します。
	// 行の前後の空白は無視します。
	// 判定には正規表現を用いてください。

	// 行を読み進めながら、各行をチェックします。
	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現でチェック:
		// 1. 行が数字、カンマ、空白のみで構成されているか。
		// 2. 少なくとも1つの数字が含まれているか（"1個以上の数字列がカンマで区切られて並んでいる"）。
		// 3. 末尾のカンマは許容される。

		// 妥当な行の条件を再解釈します。
		// 「1 個以上の数字列がカンマで区切られて並んでいる」
		// これは、カンマで区切られた要素が、すべて数字（または数字の塊）で構成されていることを意味します。
		// 例: "1,2,3" はOK。 "1,,3" は? (空の要素が許容されるか？)
		// 「空でない語の数」を数えるというニュアンスではなく、「カンマ区切りの整数列」が妥当かどうかのチェックです。

		// 正規表現で「数字とカンマのみ」を含むかどうかをチェックします。
		// ^\s*[\d,]*\s*$ : 行全体が数字、カンマ、空白のみで構成されているか
		// 1個以上の数字列が含まれていることを確認するために、少なくとも1つの数字があることを追加します。
		// より厳密に、カンマで区切られた要素がすべて整数であるかを確認します。

		// 簡略化のため、行が空ではなく、数字とカンマ以外の文字を含まないことを確認し、
		// さらに、数字が含まれていることを確認します。

		// 正規表現: 少なくとも1つの数字が含まれ、それ以外は数字、カンマ、空白のみ。
		// 実際には、"1,2," や " 1, 2 " のような形式を許容しつつ、無効な文字（例: 'a'）を拒否する必要があります。

		// ここでは、行全体が数字とカンマ、空白のみで構成されていることをチェックします。
		// そして、少なくとも1つの数字が含まれていることを確認します。
		re := regexp.MustCompile(`^[\d, ]+$`)

		if re.MatchString(line) {
			// さらに、数字が含まれているかチェック（空行でなければ、数字が含まれていればOKとされることが多い）
			// 例: "," や " , " は妥当ではないが、"1" は妥当。
			
			// 少なくとも1つの数字が含まれているか確認
			if strings.Contains(line, "0") || strings.Contains(line, "1") || strings.Contains(line, "2") || strings.Contains(line, "3") || strings.Contains(line, "4") || strings.Contains(line, "5") || strings.Contains(line, "6") || strings.Contains(line, "7") || strings.Contains(line, "8") || strings.Contains(line, "9") {
				validLines++
			}
		}
	}

	// 例外処理として、もし全ての行が空（または無効）だった場合、validLinesは0になる。
	fmt.Printf("valid=%d\n", validLines)
}
