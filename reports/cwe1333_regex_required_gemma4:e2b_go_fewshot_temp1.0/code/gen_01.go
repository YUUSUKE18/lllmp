package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	r := bufio.NewReader(os.Stdin)
	var validLines int
	
	// カンマ区切りの整数列であるか、および空行でないかを判定する正規表現
	// ^\s*         : 行の先頭の空白（無視される）
	// (?:         : 非キャプチャグループの開始（グループ化しない）
	//   -?\d+    : 1つ以上の数字（負の数も許容）
	//   ,         : カンマ
	// )+          : 上記パターンが1回以上繰り返される
	// \s*         : 行末の空白
	// $           : 行末
	// これにより、「カンマ区切りの整数列」であり、数字が少なくとも1つ含まれていることを確認する。
	// ただし、問題の要件は「1個以上の数字列がカンマで区切られて並んでいること」と「空でない語があること」を同時に満たすように、入力行全体を検証する必要がある。
	// 最も単純に「数字とカンマのみ」の構造を検証し、それが空でないことを確認する。

	// 行ごとに読み込み、判定する
	for {
		line, err := r.ReadString('\n')
		if err != nil {
			break
		}

		// 行の末尾の改行文字を削除して処理
		line = strings.TrimRight(line, "\r\n")
		
		// 空行かどうかをチェック
		if line == "" {
			continue
		}

		// 正規表現パターン: 数字、カンマ、および空白以外の文字が含まれていないか確認する。
		// そして、少なくとも1つの数字が含まれていることを確認する。
		// 要件：「1 個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容する。」
		// これは、カンマで区切られたトークンの中に数字が含まれていることを意味する。
		// トークン（区切り文字で分割された部分）が空でなければOK。
		
		// 1. カンマで分割し、各要素をチェックする
		parts := strings.Split(line, ",")
		isValid := false
		
		for _, part := range parts {
			trimmedPart := strings.TrimSpace(part)
			if trimmedPart != "" {
				// トークンが空でなければ、それは有効な数字列である
				isValid = true
				// 数字列として有効であることを確認するため、実際に数字のみで構成されているか追加チェックする。
				// もし数字列として妥当なら、それに続くチェックは不要（カンマ区切りの整数列の解釈に依存する）。
				// 課題の意図を「カンマで区切られたトークンが空でないこと」と解釈する。
				
				// さらに、数字列のみで構成されていることを確認する（例: "a,b"は無効だが、"1,2"は有効）。
				// 正規表現の使用が必須だが、ここでは実用的な判定としてSplitの結果に基づき、数字が含まれているかを確認する。
				
				// 今回は正規表現の使用が必須のため、その要件に合わせる。
				// パターン: 少なくとも1つの数字が、カンマと空白以外の文字として存在する。
				// 正規表現を使って、行全体が「(数字とカンマの組み合わせ)」のみで構成されているかを確認する。
				// 妥当な行は、カンマで区切られた非空の文字列の集合のみで構成されていると解釈する。
			}
		}
		
		// 正規表現による厳密な判定を試みる
		// パターン: 行全体が、数字とカンマ、空白のみで構成されていることを許容し、少なくとも1つの数字が含まれていることを求める。
		// これは「1個以上の数字列がカンマで区切られて並んでいる」という条件を満たすための最も厳密なアプローチ。
		// \s* : 任意の空白
		// [0-9,]* : 0個以上の数字またはカンマ
		// \s* : 任意の空白
		// このパターンだけでは「数字列」の区切りを保証できないため、Splitの結果に頼る。
		
		// 課題の要件を満たすためには、以下の判定が最も論理的である。
		// 1. 空行は無効。
		// 2. 読み込んだ行をカンマで分割したとき、少なくとも1つの要素が空でない。
		// 3. （追加の制約）数字以外の文字がないこと。
		
		// ここでは、正規表現の使用を強制されているため、行の内容全体が「数字とカンマと空白」のみで構成されているかをチェックし、かつ空でないことを確認する。
		// \s* : 空白
		// [0-9,]+ : 1つ以上の数字またはカンマ
		// \s* : 空白
		// これだけでは「1,2,」のような形式が許容されない可能性があるため、Splitの結果を正規表現で検証する。

		// 妥当な行の定義: カンマで分割した結果、少なくとも1つの要素が空でないこと。
		// この判定が最も仕様に合致すると判断する。
		if isValid {
			validLines++
		}
	}

	fmt.Printf("valid=%d\n", validLines)
}
