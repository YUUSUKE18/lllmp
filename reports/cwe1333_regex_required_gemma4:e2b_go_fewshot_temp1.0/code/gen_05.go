package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	r := bufio.NewReader(os.Stdin)
	scanner := bufio.NewScanner(r)
	validLines := 0

	for scanner.Scan() {
		line := scanner.Text()
		// 正規表現: カンマで区切られた整数列。末尾のカンマも許容する。
		// ^\s* は行頭の空白を無視
		// (?:[0-9]+(?:,|$))+ は、数字の塊とカンマ、または行末が繰り返されるパターンを意味する。
		// 厳密には、1個以上の数字列がカンマで区切られていることを確認する必要がある。
		// 末尾のカンマが許容されるため、^.*$ ではなく、数字とカンマのみで構成されていることを確認する。
		
		// 妥当な行の定義: 1個以上の数字列がカンマで区切られている。末尾のカンマは許容。
		// これは、カンマで区切られた文字列が、少なくとも1つ以上の数字を含んでいることを意味する。
		// 以下の正規表現は、「数字とカンマのみ」で構成され、少なくとも1つの数字が含まれていることをチェックする。
		// \s* は行頭の空白を考慮するため、先頭に適用する。
		// 妥当なパターン: (数字,の繰り返し)で構成される。末尾のカンマも許容。
		// 例: "1,2,3", "1,2,"
		
		// 判定ロジックをよりシンプルにするため、行をクリーンアップし、数字の存在を確認する。
		trimmedLine := strings.TrimSpace(line)
		
		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 末尾のカンマを削除して、残りが数字のみで構成されているかチェックする、というアプローチを正規表現で表現する。
		// 末尾のカンマを許容する正規表現: ^[\d,]*$ は数字とカンマのみ。
		// 少なくとも1つの数字が含まれていることを確認する必要がある。
		
		// 意図: 1個以上の数字がカンマで区切られている。
		// 例: "1,2" -> OK
		// 例: "1," -> OK (末尾のカンマは許容)
		// 例: ",1" -> OK (先頭のカンマは無視されると解釈する)
		// 例: "a,1" -> NG (数字以外が含まれる)
		
		// 正規表現: 少なくとも1つの数字が存在し、カンマ以外の文字は含まない。
		// これは、行が数字とカンマのみで構成されていることをチェックし、かつ数字が含まれていることを確認する。
		// 妥当な行のパターン: (数字,の繰り返し)で、数字が1つ以上ある。
		// \s* は無視されるため、TrimSpaceは必須。
		
		// 正規表現: 少なくとも1つの数字とカンマのみで構成されている。
		// ^[\d,]+$ は、数字とカンマだけで構成され、少なくとも1つあることを要求する。
		// 末尾のカンマ許容のため、より緩くする。
		
		// 妥当なパターン: 
		// 1. 行が完全に空でないこと (strings.TrimSpaceで確認済み)
		// 2. 行に含まれる文字が数字(0-9)とカンマ(,)のみであること。
		// 3. 少なくとも1つの数字が含まれていること。
		
		// 1. 数字とカンマのみをチェック
		if regexp.MustCompile(`^[\d,]*$`).MatchString(trimmedLine) {
			// 2. 少なくとも1つの数字が含まれているかチェック
			if regexp.MustCompile(`\d`).MatchString(trimmedLine) {
				validLines++
			}
		}
	}

	fmt.Printf("valid=%d\n", validLines)
}
