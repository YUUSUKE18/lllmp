package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validLines := 0

	// 読み込む行を保持するため、ここではすべて読み込む
	linesToProcess := []string{}
	for scanner.Scan() {
		linesToProcess = append(linesToProcess, scanner.Text())
	}

	// 正規表現:
	// ^\s*              -> 行の先頭の空白
	// (?:             -> 非キャプチャグループの開始
	//   \d+           -> 1つ以上の数字
	//   \s*,\s*       -> カンマと任意の空白（区切り）
	// )+              -> 上記のパターンが1回以上繰り返される
	// \d+             -> 最後の数字（末尾のカンマを許容するため、数字が続くことを確認）
	// (?:,\s*       -> 末尾のカンマが続く場合
	// )?              -> カンマのグループ全体がオプション
	// $               -> 行の終わり
	//
	// より単純に、「数字とカンマのみ」で構成され、少なくとも1つの数字列を含むことを確認する。
	// 仕様：「1 個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容する。」
	// これは、カンマで区切られた要素がすべて数字であることを意味します。
	// パターン: [数字, カンマ, 数字, ...] または [数字] または [数字, カンマ]
	// 許容されるパターン: 数字とカンマのみで構成され、途中に数字以外の文字や、数字以外のカンマが存在しないこと。

	// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを正規表現で検証する。
	// 1. 行全体が、数字とカンマと空白のみで構成されている。
	// 2. 少なくとも1つの数字が存在する。
	// 3. 末尾のカンマは許容する。

	// 1. 空行やその他の文字を含まないかチェック
	// 2. カンマ区切りで少なくとも1つの数字があるかチェック
	// 3. 末尾のカンマの有無をチェック（末尾のカンマは許容）

	// より簡潔なアプローチ：
	// 行をカンマで分割し、すべてが数字（または空文字列/空白）であることを確認する。
	// ただし、正規表現の使用が必須であるため、正規表現で構成をチェックする。

	// 以下の正規表現は、「数字とカンマと空白のみで構成され、少なくとも1つの数字が含まれている」ことを確認する。
	// ^\s*                  -> 行の先頭の空白
	// (?:                  -> 非キャプチャグループ
	//   \d+                -> 1つ以上の数字（最初の数字列）
	//   (?:\s*,\s*\d+)*    -> 任意の数の「空白, 数字」のペア（区切り）
	//   (?:\s*,\s*)?       -> 最後の区切りカンマ（オプション）
	// )
	// $                    -> 行の終わり
	//
	// この正規表現は少し複雑になるため、入力文字列を前処理してから正規表現を適用する方が堅牢です。
	// しかし、与えられた制約に従い、入力された文字列全体に対して判定を行う。

	// 入力行を前処理: 前後の空白を無視し、行全体を正規表現で検証する。
	// 正規表現の意味: 行は、数字とカンマ、および空白のみで構成され、少なくとも1つの数字が含まれる。
	// `[\d, ]+` は、数字、カンマ、空白の任意のシーケンス。
	// `(?=\d)` は、少なくとも1つの数字が後に続くことを確認。

	// 課題の意図を再解釈し、最も厳密なマッチングを試みる:
	// 1. 行全体が、カンマ区切りの数字の集合であること。
	// 2. 空行やその他の文字を含まないこと。
	// 3. 末尾のカンマは許容される。

	// 許容されるパターン: (数字, カンマ, 数字, ...) または (数字) または (数字, カンマ)
	// 否定形として「数字以外の文字が含まれていない」ことを確認し、かつ「数字が存在する」ことを確認する。
	// この検証は非常に複雑になるため、一般的な「カンマ区切りで数字のみ」のパターンを検証する。

	// シンプルな検証として、カンマで分割し、要素がすべて数字であることを確認する。
	// ただし、正規表現の使用が必須であるため、ここでは「数字とカンマ以外の文字が存在しない」ことを確認する正規表現に絞る。
	// 実際の入力行に対する検証には、以下のシンプルなパターンを使用し、後続のロジックで妥当性を補強する。
	// ただし、仕様上「正規表現を用いて」とあるため、それに従う。

	// 正規表現の定義: 行が「数字、カンマ、空白」のみで構成されているか、かつ数字が少なくとも1つあるか。
	// \s* : 前後の空白を許容
	// (?: \d+ \s* , )? : 数字とカンマのペアをオプションで繰り返す
	// \d+ : 少なくとも1つの数字が存在することを確認するためのグループ。
	pattern := regexp.MustCompile(`^\s*(?:\d+(?:,\s*\d+)*)(?:,)?\s*$`)

	for _, line := range linesToProcess {
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現で検証
		if pattern.MatchString(line) {
			validLines++
		}
	}

	fmt.Printf("valid=%d\n", validLines)
}
