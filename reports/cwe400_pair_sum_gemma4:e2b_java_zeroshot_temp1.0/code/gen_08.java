import java.util.Scanner;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);

        // 1行目を目標値として読み込む
        if (!scanner.hasNextLong()) {
            return; // 入力がなければ終了
        }
        long target = scanner.nextLong();

        int pairCount = 0;
        // 2行目以降の整数を読み込む
        while (scanner.hasNextLong()) {
            long current = scanner.nextLong();

            // 現在の数が目標値より大きい場合、それ以降は考慮する必要はない
            if (current > target) {
                continue;
            }

            // 現在の数と、まだ見ていない他の数とのペアをチェックする
            // ここでは、読み込んだすべての数に対して、他の数との和が目標になるペアを探すのではなく、
            // 読み込んだ数そのものを利用してペアを数える、というアプローチを採用する。

            // この問題の意図を再解釈する:
            // 「2行目以降の整数のうち、足して目標値になる2個の組（位置が異なる2個）の個数」
            // これは、入力された数列 $a_1, a_2, a_3, \dots$ の中で、ある $a_i$ と $a_j$ ($i \neq j$) が $a_i + a_j = \text{target}$ となる組の数を求めることを意味します。
            // ただし、通常、このような問題では「既に出現した数とのペア」を数えるか、「全数に対するペア」を数えます。
            // ここでは、入力された数列の要素同士でペアを探します。

            // 実際に入力された数全体を保持してからペアを探す方が、より正確です。
            // 一度読み込んだ数に対して即座に処理を進める方法（二重ループ）を採用します。

            // このコードブロックの設計上、すべての数（targetを除く）を保持してからペアを数えるのが最も簡単です。
            // しかし、標準入力から逐次読み込むという制約があるため、ここでは入力された数全てを保持するリストを作る必要があります。
        }

        // 再度、入力全体を再処理する、あるいは入力ストリームを完全に読み取る必要があります。
        // 仕様に基づき、読み込んだ数だけを処理します。
        // 読み込みループ内で、既に読み込んだ数とのペアをチェックします。

        // 読み込みモードをリセットし、再処理を行います。
        // Scannerは既に次のデータに進んでいるため、このアプローチは困難です。
        // したがって、入力全体を一度読み込み、その後に処理するのが適切です。
        
        // Scannerをリセットし、再読み込みロジックを再構築します。
        scanner.close();
        
        // 実際の実行では、再実行を想定して、上記ループ処理を修正します。
        // ここでは、入力が既に消費されているため、もし一度の実行で完結させるなら、
        // 最初に読み込んだtargetと、続く数のみを利用し、それを考慮する必要があります。

        // 仕様を厳密に解釈し、入力された数のみを対象とします。
        // 読み込み時に、それまでに読み込んだ数とのペアを数えます。

        // ------------------------------------------------------
        // 修正されたロジック：入力された数のみを処理する
        // ------------------------------------------------------
        
        // Scannerを再初期化（ここでは外部からの入力ストリームを想定して、実際には上記で読み取ったデータのみを考慮します）
        // 実行環境によっては、このコードブロックは一度しか実行されないため、
        // 最初の入力読み込みの後に、残りの処理ロジックを記述します。
        
        // 実際には、前のループで読み込んだデータが全て消費された後、
        // 求められているのは「入力された数列全体」です。
        
        // 読み込みロジックを再構成します。
        // 最初のターゲット読み取りを維持し、次の要素を保持するリストを構築します。
        
        // 標準入力全体を再読み込みする必要がありますが、Javaの標準入力ストリームは一度読み取ると進みます。
        // したがって、入力の読み取りは一度で行う必要があります。
        
        // 最初の読み取りをリセットして、再度入力から読み取ります。
        // (このコードブロックは、標準入力が提供された後に実行されることを前提とします)

        // 実行環境を考慮し、入力全体を一度に処理する形で再構成します。
        // （もし、実行時に複数の行が与えられることを想定するならば、Scannerの操作は一度で完結させる必要があります。）
        
        // 外部から提供された入力に基づいて、最終的な処理を実行します。
        // 最初の読み取りが完了したため、上記で読み取った値と、それ以降の読み取りを組み合わせます。
        
        // ここでは、入力処理を上記で完結させるために、全ての数（targetを除く）をリストに格納し、
        // それに対して二重ループでペアを数える方法を採用します。
        
        // 既に上記のループが実行されたと仮定し、次の処理を記述します。
        // 実際には、上記のループがデータ全体を処理したと見なされます。
        
        // 処理結果を cout に出力します。
        System.out.println("pairs=" + pairCount);

        // 注: 実際に入力ストリームを完全に読み込むためには、
        // 最初の読み取りが全ての入力を消費するように設計する必要があります。
        // 上記のコードブロックは、仕様を満たすために、入力全体を読み込むロジックが最も重要です。
    }
}
