package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* は行頭の任意の空白を許容
	// (?:[0-9]+(?:,\s*[0-9]+)*) は1つ以上の整数とカンマの組み合わせをグループ化
	// (?:,\s*)* は末尾のカンマと空白の繰り返しを許容
	// $ は行末
	// この正規表現は、少なくとも1つの数字列（カンマで区切られた）が存在することを要求します。
	// 厳密には、行全体が数字とカンマのみで構成され、少なくとも1つの数字列が存在する必要があります。
	// よりシンプルに、行が空でないこと、そして数字とカンマ以外を含まないことを確認し、
	// さらに「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。

	// 妥当な行の判定ロジックを正規表現で実現します。
	// 1. 空行、または数字とカンマ以外の文字を含む行は不適。
	// 2. 1個以上の数字列がカンマで区切られていること。

	// 行が空でないことを確認し、その内容が数字とカンマのみで構成されていることを確認する。
	// そして、少なくとも1つの数字列が存在することを保証する。
	// 以下の正規表現は、行全体が数字とカンマ（および空白）のみで構成され、
	// 少なくとも1つの数字列（カンマで区切られたもの）を含むことをチェックします。
	// ^\s* : 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列と、それらを区切るカンマと空白のパターン
	// (?:,\s*)* : 末尾のカンマと空白の繰り返し（末尾のカンマは許容）
	// \s*$ : 行末の空白
	// この表現は、行が完全に数字とカンマのシーケンスで構成されていることを確認するのに役立ちます。

	// 妥当な行の判定に特化するため、まずは行を読み込み、後で詳細にチェックします。
	// 正規表現は「数字とカンマのみで構成され、少なくとも1つの数字列を含む」ことを確認するのに使います。

	// 実際には、行を読み込み、その内容をチェックする方が、複雑な構造の検証には適しています。
	// 仕様に従い、正規表現を用いて判定します。

	// 妥当な行の判定のための正規表現:
	// 1. 行が空でないこと (これは後で手動でチェックするか、正規表現で含める)
	// 2. 数字とカンマ以外を含まないこと
	// 3. 1個以上の数字列がカンマで区切られていること
	// 以下の正規表現は、行が数字とカンマのみで構成され、少なくとも1つの数字列を含むことを確認します。
	// (?:[0-9]+(?:,\s*[0-9]+)*) は、少なくとも1つの数字列が存在することを保証します。
	// 末尾のカンマは許容されます。
	pattern := regexp.MustCompile(`^\s*(?:[0-9]+(?:,\s*[0-9]+)*)(?:,\s*)*$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 行が数字とカンマのみで構成されているか、かつ少なくとも1つの数字列を含むかを確認
		if pattern.MatchString(line) {
			// この正規表現は、少なくとも1つの数字列が存在することを暗黙的に含んでいます。
			// 例: "1,2,3" -> マッチ
			// 例: "1," -> マッチ (最後のカンマが許容される)
			// 例: "abc" -> マッチしない
			// 例: "1,a" -> マッチしない
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常、この問題では無視されることが多いが、念のため）
	}

	fmt.Printf("valid=%d\n", validCount)
}
