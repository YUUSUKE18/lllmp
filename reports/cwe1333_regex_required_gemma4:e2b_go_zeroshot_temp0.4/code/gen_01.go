package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* : 行の先頭の空白を無視
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の整数とカンマの組み合わせ（カンマで区切られた数字列）
	// (?:,\s*)* : その後にカンマと空白が0回以上続く（末尾のカンマを許容するため）
	// $ : 行の終わり
	// この正規表現は、少なくとも一つの数字列が存在することを要求します。
	// 厳密には、行全体が「カンマ区切りの整数列」であるか、またはその一部である必要があります。
	// 仕様に基づき、「1 個以上の数字列がカンマで区切られて並んでいる」ことを確認します。

	// 判定ロジックをより厳密にするため、行全体をチェックします。
	// 妥当な行の定義: 1個以上の数字列がカンマで区切られていること。
	// これは、数字とカンマのみで構成され、数字が少なくとも1つあることを意味します。

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現パターン:
		// ^\s* : 行頭の空白
		// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列と、それに続くカンマと空白の繰り返し。
		// これは、カンマで区切られた整数列が存在することを意味します。
		// 末尾のカンマも許容するため、行の終わりまでをチェックします。
		// ただし、行全体が数字とカンマのみで構成されている必要があります。

		// 妥当性の判定基準を再解釈:
		// 「1 個以上の数字列がカンマで区切られて並んでいる」
		// これは、行内に少なくとも一つの数字があり、その数字がカンマで区切られている構造を持つことを意味します。

		// パターン: 1つ以上の数字 ( [0-9]+ ) が存在し、その間にカンマと空白 ( , ) があるか、または行の終端にある。
		// 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
		// ^\s* : 行頭の空白
		// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列と、カンマ区切りが続く構造
		// .* : その他の文字（今回は許容しないが、行全体がこのパターンに一致する必要がある）

		// 仕様の「数字とカンマ以外を含む行は妥当ではない」を考慮すると、行全体が数字とカンマのみで構成されている必要があります。
		// 妥当な行のパターン: 1つ以上の数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
		// 例: "1,2,3", "100", "1,2,"

		// 厳密な正規表現:
		// ^\s* : 行頭の空白
		// (?:[0-9]+(?:,\s*[0-9]+)*) : 少なくとも一つの数字列が存在する構造
		// (?:,\s*)* : 末尾のカンマを許容するため、カンマと空白が0回以上続く
		// $ : 行末
		// このパターンは、行全体が数字とカンマのみで構成されていることを保証します。

		// 1. 数字とカンマのみで構成されているかチェック
		if regexp.MustCompile(`^[0-9,]*$`).MatchString(trimmedLine) {
			// 2. 少なくとも1つの数字が含まれているかチェック
			if regexp.MustCompile(`[0-9]`).MatchString(trimmedLine) {
				validCount++
			}
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常は無視されるが、念のため）
	}

	fmt.Printf("valid=%d\n", validCount)
}
