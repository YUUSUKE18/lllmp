package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s*          : 行の先頭の任意の空白
	// (?:          : 非キャプチャグループの開始
	//   \d+        : 1つ以上の数字
	//   ,          : カンマ
	// )*           : 上記のパターンが0回以上繰り返される
	// \d+          : 少なくとも1つの数字で終わる
	// (?:,\s*     : カンマとそれに続く任意の空白が0回以上繰り返される (末尾のカンマを許容するため)
	//   \d+       : 最後の数字列
	// )?$          : 行の終わり
	// この正規表現は、カンマ区切りの整数列（末尾のカンマを含む）を許容します。
	// ただし、仕様では「1 個以上の数字列がカンマで区切られて並んでいること」が重要です。
	// より厳密に「カンマで区切られた整数列」を判定するため、以下のロジックを採用します。

	// 判定ロジックの再考:
	// 1. 空行や数字とカンマ以外の文字を含む行は無効。
	// 2. 1個以上の数字列がカンマで区切られていること。
	// 3. 末尾のカンマは許容。

	// 判定のための正規表現:
	// ^\s*             : 行頭の空白
	// (?:             : 非キャプチャグループ
	//   \d+           : 1つ以上の数字
	//   (?:,\s*)?     : カンマと任意の空白が0回または1回出現 (最後の要素以外)
	// )+              : 上記のグループが1回以上繰り返される (複数の数字列)
	// (?:,\s*)?       : 最後の要素の後のカンマと空白 (末尾のカンマを許容するため)
	// \d              : 最後の数字
	// \s*$            : 行末の空白
	// この複雑な構造よりも、シンプルに「カンマで区切られた整数」が存在するかどうかをチェックし、
	// その後、行が完全に数字とカンマのみで構成されているかを確認する方が安全です。

	// 仕様を再解釈: 「1 個以上の数字列がカンマで区切られて並んでいること」
	// これは、行が「数字,数字,...」の形式（末尾のカンマは許容）で構成されていることを意味します。

	// 判定正規表現:
	// ^\s*                 : 行頭の空白
	// (?:                  : グループ開始 (非キャプチャ)
	//   \d+                : 1つ以上の数字 (最初の要素)
	//   (?:,\s*\d+)*       : カンマとそれに続く数字の繰り返し (中間要素)
	//   (?:,\s*)?          : 最後の要素の後のカンマと空白 (オプション)
	// )
	// \d?                  : 最後の数字 (末尾のカンマの有無に関わらず、少なくとも1つの数字があることを保証)
	// \s*$                 : 行末の空白
	// 実際には、末尾のカンマを許容しつつ、数字が少なくとも1つあることを確認します。

	// 最も単純でロバストな判定方法:
	// 1. 行をトリムする。
	// 2. 行が空でなければ、その行が数字とカンマのみで構成されているかチェックする。
	// 3. カンマ区切りで数字のみが存在するかをチェックする。

	// 正規表現を「カンマ区切りの整数列」の存在に特化させる:
	// ^\s*(\d+(?:,\d+)*)(?:,)?\s*$
	// これは「数字,数字, ...」の形式を検出します。

	// 最終的な判定ロジック（正規表現を使用）:
	// 1. 行が空でないこと。
	// 2. 行が数字とカンマのみで構成されていること。
	// 3. 少なくとも1つの数字が含まれていること。

	// 以下の正規表現は、カンマ区切りの整数列（末尾のカンマを含む）を検出します。
	// ^\s*                 : 行頭の空白
	// (?:                  : 非キャプチャグループ
	//   \d+                : 最初の数字列
	//   (?:,\s*\d+)*       : その後にカンマと数字の繰り返し
	// )                    : 少なくとも1つの数字列が存在すること
	// (?:,\s*)?            : 最後の要素の後のカンマと空白（オプション）
	// \d?                  : 最後の数字（末尾のカンマの有無にかかわらず、少なくとも1つの数字があることを確認）
	// \s*$                 : 行末の空白
	pattern := regexp.MustCompile(`^\s*(?:\d+(?:,\d+)*)(?:,\s*)?\d*\s*$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 行が数字とカンマのみで構成されているか、かつ1個以上の数字列があるかをチェック
		if pattern.MatchString(line) {
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常は無視されるが、念のため）
	}

	fmt.Printf("valid=%d\n", validCount)
}
