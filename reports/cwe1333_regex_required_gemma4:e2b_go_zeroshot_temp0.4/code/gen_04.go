package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s*         : 行の先頭の任意の空白
	// (?:         : 非キャプチャグループの開始
	//   \d+      : 1つ以上の数字
	//   ,        : カンマ
	// )+          : 上記のパターンが1回以上繰り返される (カンマ区切りの数字列)
	// \s*         : 行末の任意の空白
	// $           : 行の終わり
	// 末尾のカンマは許容されるため、行末のカンマを考慮したパターンにする。
	// 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」こと。
	// これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれている必要がある。

	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」を判定する正規表現
	// 1. 少なくとも1つの数字が含まれていること。
	// 2. 数字とカンマのみで構成されていること。
	// 3. 末尾のカンマは許容されること。

	// パターン: (数字, カンマの繰り返し) + (オプションの末尾カンマ)
	// 少なくとも1つの数字が含まれていることを保証するため、少なくとも1つの数字列が必須。
	// 例: 1,2,3 または 1,2,3,
	// 1. 少なくとも1つの数字列 (?: ... )+
	// 2. 各数字列は \d+
	// 3. 区切りはカンマ (,\s*)
	// 4. 末尾のカンマは許容される。

	// 妥当な行の定義を再解釈: 「1個以上の数字列がカンマで区切られて並んでいる」
	// これは、カンマで区切られた数字のシーケンスである必要がある。
	// 数字とカンマのみで構成され、空行やその他の文字を含まない。

	// 妥当な行のパターン:
	// ^\s*                  : 行頭の空白
	// (?:                  : 非キャプチャグループ開始
	//   \d+               : 1つ以上の数字
	//   (?:,\s*\d+)*      : カンマとそれに続く数字の繰り返し (最初の数字列以外)
	// )                    : グループ終了
	// (?:,\s*\d+)?          : 最後の数字列の後にカンマと数字が続く場合 (末尾のカンマ許容のため)
	// $                    : 行末

	// 最も単純に「数字とカンマのみで構成され、少なくとも1つの数字が含まれている」をチェックする。
	// 末尾のカンマは許容される。
	// 妥当な行: 1,2,3, または 1,2,3
	// 不妥当な行: 空行、数字とカンマ以外の文字、数字のみでないもの (例: "abc", "123a")

	// 判定ロジックを正規表現で実現する。
	// 1. 行が空でないこと。
	// 2. 行が数字とカンマのみで構成されていること。
	// 3. 少なくとも1つの数字が含まれていること。

	// 正規表現: 任意の空白、数字、カンマのみで構成され、かつ少なくとも1つの数字が含まれている行。
	// ^\s*                  : 行頭の空白
	// (?:                  : 非キャプチャグループ開始
	//   \d+               : 1つ以上の数字
	//   (?:,\s*\d+)*      : カンマとそれに続く数字の繰り返し
	// )                    : グループ終了
	// (?:,\s*\d+)?          : 最後の要素がカンマで終わるかどうかを許容
	// \s*$                 : 行末の空白
	// この表現は複雑になるため、よりシンプルな「数字とカンマのみ」のチェックと「空でない」チェックを組み合わせる。

	// 妥当な行の判定:
	// 1. 行が空でないこと。
	// 2. 行が数字とカンマのみで構成されていること。
	// 3. 行内に数字が少なくとも1つ含まれていること。
	// 4. 末尾のカンマは許容される。

	// 妥当な行のパターン (数字とカンマのみで構成され、少なくとも1つの数字が含まれる):
	// ^\s*                  : 行頭の空白
	// (?:                  : 非キャプチャグループ開始
	//   \d+               : 1つ以上の数字 (最初の数字列)
	//   (?:,\s*\d+)*      : カンマとそれに続く数字の繰り返し (2番目以降の数字列)
	// )                    : グループ終了
	// (?:,\s*\d+)?          : 最後の要素がカンマで終わる場合を許容
	// \s*$                 : 行末の空白

	// 簡略化: 行が数字とカンマのみで構成され、かつ数字が含まれていることを確認する。
	// 妥当な行は、数字とカンマのシーケンスである。
	// 少なくとも1つの数字が含まれていることを確認するために、数字の存在を必須とする。
	// 妥当な行のパターン: 1個以上の数字とカンマの組み合わせ。
	validRegex := regexp.MustCompile(`^\s*(\d+(?:,\s*\d+)*)(?:,)?\s*$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 行が数字とカンマのみで構成されているか、かつ少なくとも1つの数字が含まれているかを確認する。
		// 正規表現の適用:
		// 1. ^\s* : 行頭の空白
		// 2. (?: ... )+ : 少なくとも1つの数字列が存在すること
		// 3. $ : 行末
		// 4. 数字とカンマ以外の文字が含まれていないこと。

		// 妥当な行の定義を再度厳密に適用する:
		// 1 個以上の数字列がカンマで区切られて並んでいる。
		// これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを意味する。

		// 判定のためのより安全な方法として、文字列を解析して検証する。
		// 正規表現での検証を試みる。
		// 妥当な行は、数字とカンマのみで構成され、かつ数字が含まれている。
		// 末尾のカンマは許容される。

		// 妥当な行のパターン: 数字とカンマのシーケンス。
		// 例: "1,2,3" または "1,2,3,"
		// 数字とカンマ以外の文字は許容しない。
		// 少なくとも1つの数字が含まれている。

		// 正規表現: ^\s*(\d+(?:,\s*\d+)*)(?:,)?\s*$
		// このパターンは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
		// ただし、末尾のカンマの許容を考慮する必要がある。

		// 最終的な判定ロジックを正規表現に集約する。
		// 妥当な行は、数字とカンマのみで構成され、かつ数字が含まれている。
		// 最後の要素がカンマで終わるか、単に終わることを許容する。

		// 妥当な行のパターン:
		// ^\s*                  : 行頭の空白
		// (?:                  : 非キャプチャグループ開始
		//   \d+               : 1つ以上の数字
		//   (?:,\s*\d+)*      : カンマとそれに続く数字の繰り返し
		// )                    : グループ終了
		// (?:,\s*\d+)?          : 最後の要素がカンマで終わる場合を許容
		// \s*$                 : 行末の空白

		// 妥当な行のパターンをシンプルにし、行全体が数字とカンマのみで構成されていることを確認する。
		// 1. 行が空でないこと。
		// 2. 行に含まれる文字が全て数字、カンマ、空白のみであること。
		// 3. 数字が少なくとも1つ含まれていること。

		// 妥当な行の判定を、より直接的に行う。
		// 1. 行が空でないこと。
		// 2. 行を数字とカンマに分解し、全てが数字であることを確認する。

		// 正規表現で「数字とカンマのみ」をチェックし、かつ「数字が1つ以上」をチェックする。
		// 妥当な行のパターン:
		// ^\s*                  : 行頭の空白
		// (?:                  : 非キャプチャグループ開始
		//   \d+               : 1つ以上の数字
		//   (?:,\s*\d+)*      : カンマとそれに続く数字の繰り返し
		// )                    : グループ終了
		// (?:,\s*\d+)?          : 最後の要素がカンマで終わる場合を許容
		// \s*$                 : 行末の空白

		// 妥当な行のパターンを再定義:
		// 少なくとも1つの数字が含まれ、それらがカンマで区切られている。
		// 1,2,3 または 1,2,3,
		validPattern := regexp.MustCompile(`^\s*(\d+(?:,\s*\d+)*)(?:,)?\s*$`)

		if validPattern.MatchString(line) {
			validCount++
		}
	}

	fmt.Println("valid=", validCount)
}
