package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s*      : 行の先頭の任意の空白（無視される）
	// (?:      : 非キャプチャグループの開始
	//   \d+    : 1つ以上の数字
	//   ,      : カンマ
	// )+       : 上記のグループが1回以上繰り返される (カンマ区切りの数字列)
	// \s*      : 行末の任意の空白
	// $        : 行の終わり
	// 末尾のカンマは許容されるため、行末のカンマを考慮する必要がある。
	// より単純に、行が数字とカンマのみで構成され、少なくとも1つの数字が含まれているかをチェックする。

	// 仕様の再解釈: 「1 個以上の数字列がカンマで区切られて並んでいること」
	// これは、カンマで区切られた数字のシーケンスが存在することを意味する。
	// 例: "1,2,3" -> 妥当
	// 例: "1," -> 妥当 (末尾のカンマは許容)
	// 例: "," -> 不妥当 (数字列がない)
	// 例: "abc" -> 不妥当 (数字以外が含まれる)
	// 例: "" -> 不妥当 (空行)

	// 正規表現の設計:
	// ^\s*             : 行頭の空白
	// (?:              : 非キャプチャグループ
	//   \d+           : 1つ以上の数字
	//   (?:,\d+)*     : カンマとそれに続く1つ以上の数字の繰り返し (数字列の区切り)
	// )               : グループの終わり
	// (?:,\d+)*        : 末尾のカンマと数字の繰り返し（末尾のカンマ許容のため）
	// \s*$            : 行末の空白
	//
	// よりシンプルに、「数字とカンマのみで構成され、少なくとも1つの数字が含まれていること」をチェックする。
	// 妥当な行は、数字とカンマのみで構成され、かつ数字が少なくとも1つ含まれている。

	// 判定ロジックを正規表現で実現する。
	// 1. 行が空でないこと。
	// 2. 行が数字とカンマのみで構成されていること。
	// 3. 行に少なくとも1つの数字が含まれていること。

	// 妥当な行の判定のための正規表現:
	// ^\s*                 : 行頭の空白
	// (?:                  : 非キャプチャグループ (数字とカンマのシーケンス)
	//   \d+                : 1つ以上の数字
	//   (?:,\d+)*          : カンマとそれに続く数字の繰り返し (カンマ区切り)
	// )
	// (?:,\d+)*             : 末尾のカンマと数字の繰り返し (末尾のカンマ許容)
	// \s*$                 : 行末の空白

	// 最終的な判定は、行が数字とカンマのみで構成され、かつ数字が含まれていることを確認する。
	// 以下の正規表現は、行全体が数字とカンマのみで構成され、少なくとも1つの数字を含むことを確認します。
	// (?:[\d,]*\d[\d,]*)* : 任意の数字とカンマのシーケンス
	// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を表現するには、
	// 少なくとも1つの数字が存在し、それらがカンマで区切られている必要がある。

	// 妥当な行の判定（より厳密に）:
	// 行が数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれている。
	// 1. 行が空でないこと。
	// 2. 行に含まれる文字が \d または , のみであること。
	// 3. 行に含まれる数字 (\d) が少なくとも1つあること。

	// 判定は正規表現で行うという制約に従うため、以下のパターンを採用します。
	// これは、行が数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれていることを確認します。
	// 妥当な行のパターン: 任意の文字（空白を除く）が数字またはカンマであり、かつ数字が少なくとも1つ存在する。
	// 末尾のカンマは許容されるため、行の終わりは数字またはカンマで終わる。

	// 簡略化された判定: 行が空でなく、数字とカンマのみで構成されていることを確認する。
	// そして、数字が1つ以上存在することを確認する。
	pattern := regexp.MustCompile(`^\s*[\d,]*\d[\d,]*\s*$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 行が数字とカンマのみで構成されているかチェック
		// このチェックは、数字とカンマ以外の文字が含まれていないことを保証する。
		if !regexp.MustCompile(`^[\d,]*$`).MatchString(trimmedLine) {
			continue // 数字とカンマ以外を含む行は不妥当
		}

		// 少なくとも1つの数字が含まれているかチェック
		if regexp.MustCompile(`\d`).MatchString(trimmedLine) {
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常は無視されるが、念のため）
	}

	// 結果の出力
	fmt.Printf("valid=%d\n", validCount)
}
