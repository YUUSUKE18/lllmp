package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列のパターンを定義
	// ^\s* : 行の先頭の任意の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列と、その後にカンマと空白が続くパターン（カンマ区切りの整数列）
	// (?:,\s*)* : 末尾のカンマと空白が0回以上続く（末尾のカンマを許容するため）
	// $ : 行の終わり
	// この正規表現は、少なくとも1つの数字列が含まれていることを保証します。
	// 厳密には、行全体がこのパターンにマッチするかどうかをチェックします。
	// 妥当な行の判定には、より単純に「カンマと数字のみで構成され、少なくとも1つの数字が含まれているか」をチェックします。

	// 仕様に基づき、より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
	// 許容される形式: 1,2,3 または 1,2,3,
	// 許容されない形式: 空行、数字とカンマ以外、数字のみでないもの（例: "abc", "123a"）

	// 妥当な行の判定ロジックを正規表現で実装します。
	// 1. 空行、または数字とカンマ以外を含む行は妥当ではない。
	// 2. 1個以上の数字列がカンマで区切られて並んでいること。

	// 妥当な行のパターン:
	// ^\s* : 行の先頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 少なくとも1つの数字列がカンマで区切られている
	// (?:,\s*)* : 末尾のカンマと空白が0回以上続く (末尾のカンマを許容)
	// \s*$ : 行末の空白

	// 実際には、行全体が数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
	// 以下の正規表現は、行が数字とカンマ（および空白）のみで構成され、少なくとも1つの数字が含まれていることを確認します。
	// 妥当な行の定義: 1個以上の数字列がカンマで区切られて並んでいる。
	// 最小のパターン: 数字, 数字, ...
	// 許容されるパターン例: "1,2,3", "1,2,"
	// 許容されないパターン例: "", "abc", "123a"

	// 妥当な行の判定のための正規表現:
	// ^\s* : 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 少なくとも1つの数字列がカンマで区切られている部分
	// (?:,\s*)* : 末尾のカンマと空白が0回以上続く
	// \s*$ : 行末の空白
	// このパターンは、行が数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
	// ただし、空行は除外する必要があります。

	// 処理を簡略化するため、まず行をトリムし、それが空でないことを確認し、その後正規表現で構造をチェックします。

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現による妥当性の判定
		// 妥当な行: 1個以上の数字列がカンマで区切られている。
		// パターン: 1つ以上の数字列がカンマで区切られている。末尾のカンマは許容。
		// 1. 数字とカンマのみで構成されているか？
		// 2. 少なくとも1つの数字が含まれているか？

		// 以下の正規表現は、行が数字とカンマ（および空白）のみで構成され、少なくとも1つの数字が含まれていることを確認します。
		// ^\s* : 行頭の空白
		// (?:[0-9]+(?:,\s*[0-9]+)*) : 少なくとも1つの数字列がカンマで区切られている
		// (?:,\s*)* : 末尾のカンマと空白が0回以上続く
		// \s*$ : 行末の空白
		// この正規表現は、行が数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
		// 厳密には、行全体がこの構造に従う必要があります。

		// 妥当な行の判定（よりシンプルに、数字とカンマのみで構成され、数字が含まれているか）
		// この問題の制約から、行が「カンマ区切りの整数列」であること、つまり数字とカンマのみで構成され、少なくとも1つの数字が含まれている必要があります。
		// 末尾のカンマは許容されます。

		// 妥当な行の判定のための正規表現を再定義:
		// ^\s* : 行頭の空白
		// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列とカンマのシーケンス
		// (?:,\s*)* : 末尾のカンマと空白
		// \s*$ : 行末の空白

		// 妥当な行のパターンを適用
		pattern := `^\s*(?:[0-9]+(?:,\s*[0-9]+)*)(?:,\s*)*$`

		if regexp.MustCompile(pattern).MatchString(line) {
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常は無視されることが多いが、念のため）
	}

	fmt.Printf("valid=%d\n", validCount)
}
