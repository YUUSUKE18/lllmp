package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s*             : 行の先頭の任意の空白文字
	// (?:             : 非キャプチャグループの開始（数字とカンマのパターン）
	//   \d+           : 1つ以上の数字
	//   (?:,\s*\d+)*  : カンマとそれに続く空白と数字の繰り返し（カンマ区切りのリスト）
	// )?              : この全体がオプション（0回または1回）
	// \s*$            : 行の末尾の任意の空白文字
	// この正規表現は、カンマ区切りの整数列、または単一の整数列、またはカンマのみの列を許容するように調整する必要があります。
	// 仕様：「1 個以上の数字列がカンマで区切られて並んでいること」を判定します。
	// これは、少なくとも一つのカンマを含む、またはカンマで区切られた複数の数字が存在することを意味します。

	// よりシンプルな判定ロジックとして、以下の条件をチェックします。
	// 1. 空行でないこと。
	// 2. 数字とカンマのみで構成されていること。
	// 3. 少なくとも1つのカンマが含まれているか、または複数の数字がカンマで区切られていること。

	// 正規表現の設計：
	// 1. 行全体が数字とカンマのみで構成されているか？ (^\s*[\d,]*\s*$)
	// 2. 少なくとも1つのカンマが含まれているか？ (.*,.*)
	// 3. 少なくとも1つの数字列が存在するか？ (\d+)

	// 仕様の解釈：「1 個以上の数字列がカンマで区切られて並んでいる」
	// 例: "1,2,3" -> 妥当
	// 例: "123" -> 妥当（1個の数字列だが、カンマ区切りではない。仕様の文脈から「カンマ区切りのリスト」を意味すると解釈する）
	// 例: "1,2," -> 妥当（末尾のカンマは許容）
	// 例: "abc" -> 不妥当
	// 例: "" -> 不妥当

	// 「1 個以上の数字列がカンマで区切られて並んでいる」を「カンマで区切られた複数の数字列が存在する」と解釈し、
	// 少なくとも1つのカンマが含まれていることを必須条件とします。

	// 正規表現: 少なくとも1つの数字とカンマの組み合わせが存在し、全体が数字とカンマのみで構成されていること。
	// 以下のパターンは、カンマで区切られた数字のリスト（カンマを含む）を検出します。
	// ^\s*             : 行頭の空白
	// (?:             : 非キャプチャグループ
	//   \d+           : 1つ以上の数字
	//   (?:,\s*\d+)*  : カンマとそれに続く空白と数字の繰り返し
	// )               : グループの終わり
	// (?:,\s*\d+)?    : 最後の要素がカンマで終わる場合に対応
	// \s*$            : 行末の空白
	//
	// 最も簡単な判定は、行が空でなく、数字とカンマのみで構成されており、かつカンマが含まれているか、または複数の数字が存在することです。
	// 仕様の「1 個以上の数字列がカンマで区切られて並んでいる」を満たすためには、少なくとも1つのカンマが必要です。

	// 判定ロジック：
	// 1. 行をトリムする。
	// 2. 行が空でないことを確認する。
	// 3. 行が数字とカンマのみで構成されていることを確認する。
	// 4. 行にカンマが含まれていることを確認する。（複数の数字列が区切られていることを保証するため）

	// 正規表現で「カンマ区切りの整数列」を判定する。
	// 少なくとも1つの数字とカンマの組み合わせが存在し、全体が数字とカンマのみで構成されている。
	// (?:[\d,]+) : 1文字以上の数字またはカンマのシーケンス
	// このパターンは、"1,2" や "1,2," をカバーします。
	pattern := regexp.MustCompile(`^\s*[\d,]+(\s*,?\s*[\d,]+)*\s*$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 数字とカンマ以外を含む行は妥当ではない
		// このチェックは正規表現でより厳密に行う
		if !regexp.MustCompile(`^[\d,]*$`).MatchString(line) {
			continue
		}

		// 妥当性の判定: 1個以上の数字列がカンマで区切られて並んでいること。
		// これは、行内にカンマが含まれていることを意味すると解釈します。
		if strings.Contains(trimmedLine, ",") {
			validCount++
		} else {
			// カンマを含まない場合、単一の数字列のみ（例: "123"）と解釈し、
			// 「カンマで区切られて並んでいる」という条件を満たさないため不妥当とする。
			// ただし、仕様が曖昧なため、ここではカンマの存在を必須条件とします。
			// もし「123」も妥当とするなら、このelseブロックは削除し、行が空でないことのみをチェックすればよい。
			// 仕様：「1 個以上の数字列がカンマで区切られて並んでいる」
			// "123" は1個の数字列であり、カンマで区切られていないため、不妥当と判断します。
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
