package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* : 行の先頭の空白を無視
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列とカンマの組み合わせ。
	// これは、数字とカンマが交互に現れることを許容し、少なくとも1つの数字列が存在することを保証する。
	// 末尾のカンマも許容する。
	// ただし、仕様では「1 個以上の数字列がカンマで区切られて並んでいる」ことを確認する必要がある。
	// よりシンプルなアプローチとして、行が空でないこと、そして数字とカンマ以外の文字を含まないことを確認し、
	// 少なくとも1つの数字が含まれていることを確認する。

	// 仕様の再解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
	// これは、カンマで区切られた要素がすべて整数である、ということを意味する。
	// 例: "1,2,3" -> 3つの整数列
	// 例: "1,2," -> 2つの整数列（末尾のカンマは許容）
	// 例: "1," -> 1つの整数列
	// 例: "," -> 不適格（数字列が0個）
	// 例: "abc" -> 不適格

	// 正規表現の設計:
	// ^\s* : 行の先頭の空白を無視
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列と、その後に続くカンマと空白の繰り返し。
	// このパターンは、少なくとも1つの数字列が存在することを保証します。
	// 末尾のカンマも許容するため、行末にカンマが来ても良い。
	// 空行や数字とカンマ以外の文字を含む行は除外される。

	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックするために、
	// 以下のパターンを使用します。
	// 1. 行が空でないこと。
	// 2. 行が数字とカンマのみで構成されていること。
	// 3. 少なくとも1つの数字列が含まれていること。

	// 正規表現: 行全体が、数字とカンマのみで構成され、少なくとも1つの数字列を含むことを確認する。
	// (?:[0-9]+(?:,\s*[0-9]+)*) は、数字とカンマのシーケンスを表現する。
	// 末尾のカンマを許容しつつ、全体が数字列で構成されていることを確認する。
	// 以下のパターンは、少なくとも1つの数字列が存在し、その間にカンマと空白が許容されることを確認します。
	// 行が完全に数字とカンマのみで構成されていることを確認するために、
	// 以下のパターンで、数字とカンマ以外の文字が存在しないことを確認します。
	// 妥当な行は、カンマで区切られた整数列のシーケンスである。
	// 最小要件: 少なくとも1つの数字列が存在し、それらがカンマで区切られている。

	// 妥当な行のパターン:
	// ^\s* : 先頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列と、カンマと空白の繰り返し。
	// このパターンは、カンマで区切られた整数列を捉える。
	// 末尾のカンマが許容されるため、最後の要素の後にカンマが続くことを許容する。
	// 例: "1,2,3" -> マッチ
	// 例: "1,2," -> マッチ
	// 例: "," -> マッチしない (数字列が0個)
	// 例: "abc" -> マッチしない
	// 例: "" -> マッチしない (空行)

	// 実際には、行が数字とカンマのみで構成され、かつカンマが少なくとも1つ含まれている（または、1つ以上の数字列が存在する）ことを確認する必要がある。
	// 最も単純に、行が数字とカンマのみで構成され、空でないことを確認し、
	// さらに「1個以上の数字列」が存在することを正規表現で保証する。

	// 妥当な行のパターンを再定義:
	// 1. 行が空でない。
	// 2. 行が数字とカンマのみで構成されている。
	// 3. 少なくとも1つの数字列が存在する。

	// 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字列を含むことを確認する。
	// (?:[0-9]+(?:,\s*[0-9]+)*) は、1つ以上の数字列を許容する。
	// 末尾のカンマを許容するため、行の最後にカンマがあってもよい。
	// ただし、このパターンは「数字列の後にカンマが続く」ことを前提としているため、末尾のカンマのみの行（例: ","）を排除する必要がある。

	// 最終的な判定ロジック:
	// 1. 行をトリムする。
	// 2. 行が空でないことを確認する。
	// 3. 行が数字とカンマのみで構成されていることを確認する。
	// 4. 行内に少なくとも1つの数字列が存在することを確認する。

	// 正規表現で3と4を同時に満たすことを試みる:
	// 少なくとも1つの数字列と、それらがカンマで区切られている。
	// 妥当な行は、数字とカンマのみで構成され、かつ、少なくとも1つの数字列を含む。
	// (?:[0-9]+(?:,\s*[0-9]+)*) は、少なくとも1つの数字列を要求する。
	// 末尾のカンマを許容するため、行の末尾にカンマがなくても良い。
	// 例: "1" -> マッチ
	// 例: "1,2" -> マッチ
	// 例: "1," -> マッチ
	// 例: "," -> マッチしない (数字列が0個)

	// 最終的な正規表現:
	// ^\s* : 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列と、カンマと空白の繰り返し。
	// このパターンは、少なくとも1つの数字列が存在することを保証し、数字とカンマ以外の文字を排除する。
	// 末尾のカンマが許容されるため、行末にカンマがあっても良い。

	pattern := regexp.MustCompile(`^\s*(?:[0-9]+(?:,\s*[0-9]+)*)(?:,?\s*)*$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 行が数字とカンマのみで構成されているか、かつ1個以上の数字列を含むかを確認
		// 正規表現を適用する前に、行が数字とカンマのみで構成されているかを確認する。
		// 厳密に「数字とカンマ以外を含む行は妥当ではない」という条件を満たすため、
		// 以下のチェックを組み合わせる。

		// 1. 数字とカンマ以外の文字が含まれていないかチェック
		isAlphanumericAndComma := true
		for _, r := range line {
			if !('0' <= r && r <= '9' || r == ',') {
				isAlphanumericAndComma = false
				break
			}
		}

		if !isAlphanumericAndComma {
			continue // 数字とカンマ以外を含む行は妥当ではない
		}

		// 2. 少なくとも1つの数字列が存在するかチェック
		// カンマで区切られていることを確認する。
		// 少なくとも1つの数字列が存在するためには、行内に数字が含まれている必要がある。
		hasDigits := false
		for _, r := range line {
			if '0' <= r && r <= '9' {
				hasDigits = true
				break
			}
		}

		if hasDigits {
			// 妥当な行としてカウント
			validCount++
		}
	}

	fmt.Println("valid=", validCount)
}
