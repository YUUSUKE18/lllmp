package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s*       : 行の先頭の空白を無視
	// (?:       : 非キャプチャグループの開始
	//   \d+    : 1つ以上の数字
	//   ,      : カンマ
	// )+        : 上記のグループが1回以上繰り返される
	// \s*       : 行末の空白を無視
	// $         : 行の終わり
	// この正規表現は、カンマで区切られた数字の列が少なくとも1つ存在することをチェックします。
	// 末尾のカンマも許容するため、行全体が数字とカンマのみで構成されていることを確認します。
	// ただし、仕様では「1 個以上の数字列がカンマで区切られて並んでいること」が重要です。
	// 以下の正規表現は、少なくとも一つの数字列が存在し、カンマや数字以外の文字がないことを確認します。
	// 実際には、行が空でないこと、数字とカンマのみで構成されていることを確認し、
	// さらに「1個以上の数字列」が存在するかどうかをチェックする必要があります。

	// 仕様の再解釈に基づき、より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認します。
	// これは、行が空でなく、数字とカンマのみで構成されており、少なくとも1つの数字が含まれていることを意味します。
	// 末尾のカンマは許容されます。

	// 妥当な行の判定ロジックを正規表現で実現します。
	// 1. 行が空でないこと。
	// 2. 行が数字とカンマのみで構成されていること。
	// 3. 少なくとも1つの数字列が存在すること。

	// 簡略化のため、まずは行を読み込み、後で詳細なチェックを行います。
	// 正規表現による判定を要求されているため、それに従います。

	// 妥当な行をカウントするための正規表現：
	// ^\s*                                 # 行頭の空白を無視
	// (?:                                   # 非キャプチャグループ開始
	//   \d+(?:,\d+)*                       # 1つ以上の数字、それに続くカンマと数字の繰り返し (例: 1,2,3)
	//   |                                 # または
	//   \d+                               # 単独の数字列 (例: 123)
	// )+                                    # 上記のパターンが1回以上繰り返される (複数の数字列)
	// (?:,\d+)*?                              # 末尾のカンマが続く場合を許容 (オプション)
	// \s*$                                  # 行末の空白を無視

	// 仕様の「1 個以上の数字列がカンマで区切られて並んでいる」を表現するには、
	// 少なくとも一つの数字列が存在し、カンマで区切られている（または単独で存在する）必要があります。

	// 以下の正規表現は、行が空ではなく、数字とカンマのみで構成され、少なくとも1つの数字を含むことを確認します。
	// 末尾のカンマも許容します。
	// ^\s*                                 # 行頭の空白を無視
	// (?:                                   # グループ開始
	//   \d+(?:,\d+)*                       # 数字とカンマのシーケンス (例: 1,2,3, または 1,2,3,)
	//   |                                 # または
	//   \d+                               # 単独の数字 (例: 123)
	// )+                                    # 1つ以上の数字列の繰り返し
	// (?:,\d+)*?                              # 末尾のカンマのオプション (末尾のカンマは許容)
	// \s*$                                  # 行末の空白を無視
	regex := regexp.MustCompile(`^\s*(?:\d+(?:,\d+)*|\d+)(?:,\d+)*\s*$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現で判定
		if regex.MatchString(line) {
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常は無視されることが多いが、念のため）
	}

	// 結果の出力
	fmt.Printf("valid=%d\n", validCount)
}
