package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	for scanner.Scan() {
		line := scanner.Text()
		// 行の前後の空白を無視する（ここでは行全体を処理するため、TrimSpaceで前後の空白を削除する）
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 末尾のカンマは許容する
		// 妥当なのは「1個以上の数字列がカンマで区切られて並んでいること」
		// これは、カンマで区切られた要素が少なくとも1つ存在し、かつ、その区切りが数字のみで構成されていることを意味する。
		// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を判定する。
		// 例: "1,2,3" -> 3つの数字列
		// 例: "1," -> 2つの数字列 (1, 空文字列) または 1つの数字列と末尾のカンマ
		// 仕様の解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
		// これは、カンマで区切られた要素の数が1以上である、または、カンマで区切られた文字列が数字のみで構成されていることを意味する。

		// 最もシンプルな解釈: カンマで区切られた要素が存在し、その要素が数字のみで構成されていること。
		// 空行は除外済み。
		// 数字とカンマ以外を含む行は妥当ではない。

		// 行をカンマで分割する
		parts := strings.Split(trimmedLine, ",")

		isValid := false
		if len(parts) > 0 {
			// 少なくとも1つの要素がある
			// 各要素が数字のみで構成されているか、または空文字列（末尾のカンマによる）を許容するかを判定する。

			// 仕様: 「1 個以上の数字列がカンマで区切られて並んでいる」
			// これは、partsの要素がすべて数字列（または空文字列）で構成されている場合に成立する。
			// 「数字とカンマ以外を含む行は妥当ではない」という制約を考慮すると、各parts要素が数字のみで構成されている必要がある。

			allPartsAreValid := true
			for _, part := range parts {
				// 各部分が数字のみで構成されているかチェックする
				if part == "" {
					// 末尾のカンマによる空文字列は許容される（例: "1," -> ["1", ""]）
					// ただし、"1,,2" のような連続カンマは許容されない（仕様から推測）
					// 「数字とカンマ以外を含む行は妥当ではない」を満たすため、空文字列は許容する。
					continue
				}
				// 数字のみで構成されているかチェック
				if _, err := fmt.Sscan(part); err != nil {
					// 数字以外の文字が含まれている場合、妥当ではない
					allPartsAreValid = false
					break
				}
			}

			if allPartsAreValid {
				// 1個以上の数字列がカンマで区切られているか？
				// partsの長さが1以上であれば、少なくとも1つの要素が存在する。
				// 空行は除外済み。
				isValid = true
			}
		}

		if isValid {
			validCount++
		}
	}

	if scanner.Err() != nil {
		// エラー処理（通常は不要だが念のため）
	}

	fmt.Printf("valid=%d\n", validCount)
}
