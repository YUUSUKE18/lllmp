package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	for scanner.Scan() {
		line := scanner.Text()
		// 行の前後の空白を無視する（ここでは行全体を処理するため、トリミングは不要だが、
		// 後の処理で文字列操作を行うため、念のため行全体を評価する）

		// 末尾の空白を除去して処理
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 妥当性の判定ロジック
		// 1. 数字とカンマ以外を含む行は妥当ではない
		// 2. 1個以上の数字列がカンマで区切られて並んでいること
		
		// 行がカンマで区切られているか、またはカンマで区切れるかを確認する
		// 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」こと。
		// これは、カンマで区切られた要素が存在し、それらがすべて数字列である必要がある。

		// 行をカンマで分割する
		parts := strings.Split(trimmedLine, ",")
		
		// 妥当な行であるためには、少なくとも1つの要素が存在し、
		// その要素がすべて数字列である必要がある。
		// 仕様：「1 個以上の数字列がカンマで区切られて並んでいることです。」
		// これは、分割された各要素が空でないこと、そしてその要素が数字列であることを意味する。
		
		isValid := false
		if len(parts) > 0 {
			// 少なくとも1つの要素がある
			
			// すべての要素が数字列であるか、または空文字列（末尾カンマなど）を許容するかを判定する。
			// 仕様：「末尾のカンマは許容します。」
			// これは、末尾のカンマがある場合、最後の要素が空文字列になることを許容する。
			
			// 例: "1,2,3," -> ["1", "2", "3", ""]
			// 妥当なのは、少なくとも1つの数字列が存在する場合。
			
			hasNumber := false
			for _, part := range parts {
				// 空文字列は末尾カンマによるものとして許容される
				if part != "" {
					// その部分がすべて数字であるかチェック
					if _, err := fmt.Sscan(part); err == nil {
						// Sscanが成功すれば、その文字列は整数として解釈可能（つまり数字列）
						hasNumber = true
					} else {
						// 数字以外の文字が含まれている場合（例: "a,1"）
						// この場合、行全体は妥当ではない。
						isValid = false
						break
					}
				}
			}
			
			if hasNumber {
				// 少なくとも1つの数字列が存在すれば妥当
				isValid = true
			} else if len(parts) > 0 && len(parts) == 1 && parts[0] == "" {
				// 行が空文字列（トリム後）でなかったが、カンマのみで構成されていた場合（例: "," または ""）
				// これは「1個以上の数字列」ではないため不妥当。
				isValid = false
			} else if len(parts) > 0 && len(parts) == 1 && parts[0] != "" {
				// カンマなしの単一の数字列（例: "123"）も「1個以上の数字列がカンマで区切られて並んでいる」を満たすか？
				// 仕様：「1 個以上の数字列がカンマで区切られて並んでいることです。」
				// 単一の数字列は「カンマで区切られて並んでいる」とは言えないが、
				// 厳密には「0個のカンマで区切られている」と解釈できる。
				// しかし、もし「1,2,3」が妥当なら、「123」も妥当であるべき。
				// 妥当性の定義を「カンマで区切られた要素が存在し、それらが数字列であること」と解釈する。
				// 単一の要素も「1個の数字列がカンマで区切られている」と解釈できる。
				isValid = true
			}
		}

		if isValid {
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
