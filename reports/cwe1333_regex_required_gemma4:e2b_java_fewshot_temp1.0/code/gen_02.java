import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        
        String line;
        while ((line = br.readLine()) != null) {
            // 正規表現パターン: 
            // ^\s*       : 行頭の任意の空白
            // [0-9,]+    : 1個以上の数字とカンマの組み合わせ (これは単純化のため、後でカンマ区切りを評価する)
            // .*         : 残りの文字
            // $          : 行末
            
            // 課題の要求: 「1 個以上の数字列がカンマで区切られて並んでいる」こと。
            // これは、カンマで区切られた要素がすべて整数であることを意味し、カンマで区切られている場合に、空でない要素が存在することを意味します。
            
            // 厳密なチェックのために、カンマ区切りで数字が並んでいるかをチェックします。
            // 末尾のカンマは許容されるため、行全体をチェックします。
            
            // 1. 行の前後の空白を無視する。
            String trimmedLine = line.trim();
            
            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }
            
            // 2. 正規表現で判定: 
            // 1つ以上の数字 (0-9) とカンマ (,) の組み合わせが、少なくとも1つ存在し、かつ、
            // 数字とカンマ以外の文字が含まれていないこと。
            // より厳密に「カンマ区切りの整数列」として評価するため、
            // 数字とカンマ以外の文字を含まないことを確認しつつ、
            // 少なくともカンマが1つ以上存在するか、あるいは数字が連続していることを確認します。
            
            // 課題の定義に基づき、行が「カンマ区切りの整数列」であるためには、
            // その行がカンマで区切られた複数の要素から構成され、それらが整数である必要があります。
            // 正規表現で「カンマ区切り」を判定し、かつ「数字以外」を排除します。
            
            // パターン: 任意の数の数字とカンマのみ（行末のカンマは許容）
            // ^\s*             -> 行頭の空白
            // [0-9,]*          -> 数字またはカンマが0回以上続く
            // \s*$             -> 行末の空白
            // このパターンだけでは「1個以上の数字列」の存在を保証しないため、
            // 各要素が整数であるかをチェックする方が自然ですが、ここでは「カンマで区切られている」という構造に着目します。

            // 妥当性の定義を「カンマで区切られた要素が1つ以上存在し、それらが整数である」と解釈し、
            // さらに「数字とカンマ以外を含む行は妥当ではない」という制約を適用します。
            
            // 正規表現で「数字とカンマ以外の文字が含まれていない」ことを確認し、
            // その後、区切られた要素が整数であるかをチェックします。（正規表現のみで完結させる必要があります）
            
            // 「1個以上の数字列がカンマで区切られて並んでいる」を正規表現で表現：
            // 数字またはカンマが連続し、かつ、数字が少なくとも1つ含まれている。
            // 例: "1,2,3" -> マッチ
            // 例: "1" -> マッチ (1個の列と見なす)
            // 例: "1,2," -> マッチ (末尾のカンマを許容)
            
            // 候補パターン: カンマと数字のみで構成されている行
            // ^\s*[\d,]*\s*$
            
            // より厳密に「カンマで区切られた複数の整数」を想定し、行がカンマで区切られた数字のみで構成されているかをチェックします。
            // 末尾のカンマが許容されるため、行の末尾にカンマがあっても良い。
            // この行が「カンマ区切り」であり、かつ「数字とカンマ以外を含まない」という条件を満たすことを確認します。
            
            // この制約を正規表現のみで完全に満たすのは困難ですが、最も近い解として、
            // 行が数字とカンマのみで構成されていることを確認します。
            // （空行は既に除外済み）
            
            boolean isValidFormat = true;
            for (int i = 0; i < trimmedLine.length(); i++) {
                char c = trimmedLine.charAt(i);
                if (!((c >= '0' && c <= '9') || c == ',')) {
                    isValidFormat = false;
                    break;
                }
            }
            
            // 「1個以上の数字列がカンマで区切られて並んでいる」という条件を検証するため、
            // 単に数字とカンマのみで構成されていれば、それは「カンマ区切り」の候補と見なします。
            // 空行は除外済み。
            
            if (isValidFormat) {
                // カンマ区切りで、数字のみが含まれている行は妥当と見なします。
                // （※「1個以上の数字列」が必ず存在する、という条件は、入力が空行でない限り、
                // 少なくとも数字が含まれている場合に満たされます。もし「1,2,」のようなケースを考慮するなら、
                // カンマが存在するか、数字が存在することを追加する必要がありますが、
                // 行が空行でない限り、数字が含まれていれば「区切られた列」と見なします。）
                validLines++;
            }
        }
        
        System.out.println("valid=" + validLines);
    }
}
