import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現: カンマ区切りの整数列。末尾のカンマは許容。
            // ^\s* - 行の先頭の空白
            // (?:(?=\d+,\s*)+|\d+)(?:,\s*\d+)* - 1つ以上の数字とカンマのパターンを繰り返す（または単一の数字）
            // をよりシンプルに、カンマで区切られた数字のリストとして検証する。
            // 妥当な形式: 1つ以上の整数がカンマで区切られている。末尾のカンマは許容。
            // 正規表現の解釈:
            // ^\s*       -> 行頭の空白
            // (?:         -> 非キャプチャグループ開始
            //     \d+     -> 1つ以上の数字
            //     (?:,\s*\d+)* -> カンマとそれに続く数字の繰り返し（カンマの後に数字が続く）
            // )           -> 非キャプチャグループ終了
            // (?:,\s*\d+)* -> 最後の要素がカンマで終わるケースを考慮するため、これは複雑になるため、より単純なチェックに焦点を当てる。

            // 仕様の再解釈: 「1個以上の数字列がカンマで区切られて並んでいる」
            // 1. 空行や数字とカンマ以外の文字を含む行は不適。
            // 2. 妥当な行は、少なくとも1つの数字がカンマで区切られている。末尾のカンマは許容。

            // より直接的なパターン: 
            // 整数、カンマ、そして任意の数の（カンマと整数）の組み合わせ。
            // (?: \d+ | , ) の繰り返し。

            // 妥当な行のパターン:
            // 少なくとも一つの数字（\d+）が含まれており、カンマが使われている、または数字のみである。
            // ただし、空行は不適。
            // 空行判定はreadLine()で既にフィルタリングされる。
            
            // 妥当なケースの例: "1,2,3", "1,2,"
            // 不適なケースの例: "", "abc", "1,a", ",,"

            // 判定ロジック:
            // 行をトリムし、空でなければ、その行がカンマと数字のみで構成されているかを確認する。
            // 正規表現で「数字とカンマ」のみで構成されているか、またはそのパターンを満たしているかを確認。

            // 非常に厳密に「カンマ区切りの整数列」を検証する場合、
            // 以下のパターンが最も適切： (数字、カンマ、数字) の組み合わせが1回以上出現すること。
            // 末尾のカンマを許容するため、末尾がカンマで終わる場合も許可する。
            // 少なくとも一つの数字が存在し、かつ、それらがカンマで区切られている（あるいは数字のみ）ことを確認する。
            
            // 妥当な文字列の例: "1,2,3", "1", "1,"
            // 不適な文字列の例: "", "abc", "1a", ",,"

            // 「数字とカンマ以外を含む行は妥当ではない」という制約を考慮すると、
            // 許容される文字は数字(0-9)とカンマ(,)のみである。
            // さらに、「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
            
            // パターン: 数字とカンマのみで構成され、かつ、少なくとも1つの数字が存在する。
            // \d+ は数字列、, はカンマ。
            // ^[\d,]*$ : 全て数字とカンマのみで構成されている。
            // (?=.*?\d) : その中で少なくとも1つの数字が存在する。

            String trimmedLine = line.trim();
            boolean isValid = false;

            if (!trimmedLine.isEmpty()) {
                // 1. 数字とカンマのみで構成されているかチェック
                if (Pattern.matches("^[0-9,]*$", trimmedLine)) {
                    // 2. 少なくとも1つの数字が存在するかチェック
                    if (Pattern.matches(".*\\d.*", trimmedLine)) {
                        // 3. 末尾のカンマを許容するため、内部構造が適切か確認。
                        // 実際には、数字とカンマのみで構成され、かつ、
                        // 少なくとも1つの数字が存在すれば「妥当」と見なす。
                        // 例: "1,2" -> OK, "1," -> OK, "," -> NG (数字がないため)
                        isValid = true;
                    }
                }
            }

            if (isValid) {
                validLines++;
            }
        }

        System.out.println("valid=" + validLines);
    }
}
