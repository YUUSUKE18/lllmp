import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.IOException;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws IOException {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        String line;
        
        // 読み込み開始
        while ((line = br.readLine()) != null) {
            // 行の前後の空白を無視する。ここでは行全体を判定対象とする。
            // 正規表現パターン: 
            // ^\s*             -> 行の先頭の空白
            // (?:[0-9]+,\s*)+  -> 1つ以上の数字列とカンマ、それに続く空白の繰り返し (これが1個以上の数字列がカンマで区切られていることを示す)
            // [0-9]+           -> 最後の数字列
            // \s*$             -> 行末の空白
            
            // 仕様の解釈に基づき、行全体が「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
            // 末尾のカンマは許容される。空行は妥当ではない。数字とカンマ以外は許容されない。
            
            // 1. 行全体をトリムして、内容を評価する。
            String trimmedLine = line.trim();
            
            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない (空行は妥当ではない、と解釈する)
                continue;
            }

            // 2. 正規表現による判定
            // パターン: (数字,カンマ,空白の繰り返し) + (数字)
            // 妥当性の定義: 1個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容。
            // 例: "1,2,3" -> OK
            // 例: "1,2," -> OK (末尾のカンマが許容される)
            // 例: "123" -> OK (カンマ区切りでなくても、数字列が並んでいると解釈する。ただし「カンマで区切られて並んでいる」が条件)
            
            // 「1 個以上の数字列がカンマで区切られて並んでいる」を厳密に捉えるには、
            // (数字,カンマ)+ のパターンに合致する必要がある。
            // 末尾のカンマを許容するため、行末にカンマがあっても良い。
            // 最小の条件: 数字とカンマのみで構成され、カンマで区切られていること。
            
            // 以下のパターンは、「数字,数字, ...」の形式、かつカンマで区切られていることを要求する。
            // (\\d+,\s*)+  : 数字とカンマのペア（スペース含む）が1回以上繰り返される
            // \\d+         : 最後の数字列
            // $            : 行末
            
            // 厳密に「カンマ区切りの整数列」を評価する。
            // 妥当な行は、数字とカンマ、空白のみで構成され、少なくとも1つの数字列が存在し、カンマ区切りである必要がある。
            // 末尾のカンマは許容される。
            
            // パターン解説:
            // ^\s*             -> 行頭の空白
            // (?:\\d+,\s*)*    -> 0回以上、数字とカンマ、空白のグループ
            // \\d+             -> 最後の数字列
            // (?:,.*)?         -> 最後のカンマの後に続く任意の文字（末尾のカンマ許容のため）
            // \s*$             -> 行末の空白
            
            // よりシンプルに、少なくとも1つの数字とカンマが混在していることを確認する。
            // 空行を除く、数字とカンマのみで構成され、カンマで区切られているか、またはそれに近い形。
            
            // 空行を除外した上で、数字とカンマのみで構成されている行を「妥当」と見なす。
            // 空行、および数字とカンマ以外を含む行は妥当ではない。
            // これは、行が完全に (数字, カンマ) のシーケンスで構成されていることを意味する。
            
            // 正規表現: 1つ以上の数字列とカンマの組み合わせで構成されていること。
            // 1個以上の数字が、カンマで区切られていること。末尾のカンマは許容。
            // \s* はトリム後の評価に使わないため、ここでは行全体に適用する。
            
            // 判定ロジックを再定義:
            // 1. 行が空でなければならない。
            // 2. 行は数字とカンマと空白のみで構成されなければならない。
            // 3. 数字列がカンマで区切られているか、またはそれに近い構造であること。
            
            // 提示された例に基づくと、"1,2,3"や"1,2,"のような形式が妥当であると想定される。
            
            // 簡易的に、行が数字とカンマと空白のみで構成され、かつ最低1つの数字が含まれているかを確認する。
            // (\\d[\s,]*)+ は、数字が連続し、それに続く文字が空白またはカンマである、という構造をチェックする。
            
            // 最終的な判定：トリム後の文字列が、数字、カンマ、空白のみで構成されており、かつ少なくとも1つの数字が含まれていること。
            
            // 正規表現パターン：行全体が数字、カンマ、空白のみで構成されていることを確認する。
            // 否定的な条件（数字とカンマ以外を含む行は妥当ではない）を考慮すると、
            // (数字とカンマ以外が含まれていないこと) と (空でないこと) が最も重要。
            
            // 例外的に、行が完全に数字の羅列のみの場合も許容するか？ 
            // 「1個以上の数字列がカンマで区切られて並んでいる」ため、カンマの存在が強く示唆される。
            
            // 妥当なパターン: 数字、カンマ、空白のみを含む。
            // 以下のパターンは、行が数字、カンマ、空白で構成されていることを確認し、数字が少なくとも1つあることを保証する。
            // （末尾のカンマは許容されるため、行の終端で終わるか、末尾がカンマで終わることを許容する）
            
            // 正規表現を再構築:
            // 行が完全に (数字, カンマ, スペース) のパターンを繰り返すこと。
            // 最後にカンマがあっても良い。
            String regex = "^\\s*(\\d+[,\\s]*)+$";
            
            if (Pattern.compile(regex).matcher(line).matches()) {
                // この行が「数字とカンマと空白のみ」で構成されていることを確認。
                // この条件で、例示された条件を満たしていると仮定する。
                validLines++;
            }
        }

        System.out.println("valid=" + validLines);
    }
}
