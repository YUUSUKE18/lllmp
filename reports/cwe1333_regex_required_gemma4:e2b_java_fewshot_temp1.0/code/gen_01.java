import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン: 
            // ^\s*       - 行頭の任意の空白
            // [0-9,]*    - 数字とカンマの任意の文字列 (0個以上)
            // (?:,\s*[0-9,]*)* - カンマとそれに続く任意の数字/カンマのパターンが0回以上繰り返される (末尾のカンマ含む)
            // \s*$       - 行末の任意の空白
            
            // 課題の仕様に基づき、妥当性の判定ロジックを検討します。
            // 妥当とは「1個以上の数字列がカンマで区切られて並んでいること」です。
            // 末尾のカンマは許容されます。
            // 空行、および数字とカンマ以外を含む行は妥当ではありません。
            
            // 正規表現で「数字とカンマのみ」で構成されているか、かつ「少なくとも1つの数字」が含まれているかをチェックします。
            // 許容されるパターン: 数字とカンマのみ、かつ最低1つの数字が存在する。
            // 念のため、行全体が数字とカンマ、空白のみで構成されていることを確認しつつ、
            // 「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する必要があります。

            // 1. 空行判定（前後の空白無視）
            String trimmedLine = line.trim();
            if (trimmedLine.isEmpty()) {
                continue; // 空行は妥当ではない
            }

            // 2. 正規表現による検証
            // 妥当な行は、数字とカンマ、およびそれらが区切りとして機能している必要があります。
            // 最も緩く「数字とカンマのみ」という条件を適用し、そこから区切りの条件を適用します。
            
            // 構造をより厳密に捉えるために、パターンを以下のように定義します。
            // [0-9,]* は数字とカンマのみ
            // (?:[0-9]+) は少なくとも1つの数字
            // パターン: (数字とカンマの組み合わせ) の中で、少なくとも1つの数字が含まれていること。
            
            // 提案する正規表現: 
            // この行が「数字とカンマのみ」で構成されており、かつ「少なくとも1つの数字」が含まれているか。
            // 数字とカンマ以外の文字は許容しないため、行全体が [0-9, \t\n\r] のみで構成されていることを確認します。
            
            // 課題の制約「空行、および数字とカンマ以外を含む行は妥当ではありません。」を考慮すると、
            // 許容されるのは「数字、カンマ、空白」のみで構成された行であり、かつその中で構造的な妥当性を持つ行です。
            
            // 「1個以上の数字列がカンマで区切られて並んでいる」ことを判定するために、
            // 正規表現で「カンマで区切られた複数の数字列」のパターンを検証します。
            // 例えば、"1,2,3" や "1,2," のような構造。
            
            // 以下のパターンは「数字とカンマのみ」で構成され、カンマで区切られている構造を許容します。
            // ^\s*              - 行頭の空白
            // (?:[0-9]+(?:,?[0-9]+)*) - 1つ以上の数字列がカンマで区切られているパターン
            // .*               - 許容されるため、行全体がそれ以外を含まないように調整が必要。
            
            // 簡略化のため、行をスペースで分割し、各要素が数字のみで構成されているかを確認し、カンマの有無で構造を判定するアプローチを取ります。
            
            // 仕様の解釈に基づき、行をカンマで分割し、各要素が数字であるか、または空文字列でないことを確認します。
            
            String[] parts = line.split(",");
            boolean isValid = false;
            
            if (parts.length > 0) {
                // 少なくとも1つの要素があり、そのうち少なくとも1つが数字であるかを確認する。
                // すべての要素が「数字」のみ（カンマや空白を除去して）で構成されている必要があります。
                
                // 複数の要素があり、そのうち少なくとも1つが数字であるか？
                boolean containsNumber = false;
                for (String part : parts) {
                    String trimmedPart = part.trim();
                    if (!trimmedPart.isEmpty()) {
                        // 要素が純粋な整数（または整数列）であるかチェック
                        if (trimmedPart.matches("\\d+")) {
                            containsNumber = true;
                        } else {
                            // 数字とカンマ以外を含む要素がある場合、これは不妥当
                            isValid = false;
                            break;
                        }
                    }
                }

                if (containsNumber) {
                    // 1個以上の数字列がカンマで区切られて並んでいる (parts.length >= 1)
                    // 末尾のカンマは許容される (parts.length > 0 であれば、区切り文字が存在したことになる)
                    // 空行は既に除外されている
                    validLines++;
                }
            }
        }

        System.out.println("valid=" + validLines);
    }
}
