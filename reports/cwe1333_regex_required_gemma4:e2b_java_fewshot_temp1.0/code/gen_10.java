import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws Exception {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        String line;

        while ((line = br.readLine()) != null) {
            // 正規表現パターン: カンマで区切られた整数列、末尾のカンマを含むことを許容する。
            // ^\s* は行頭の空白を無視
            // .* は任意の文字（数字やカンマ）
            // 整数列が少なくとも1つ存在し、数字とカンマ以外は含まないことをチェックする
            // より厳密に「1個以上の数字列がカンマで区切られている」ことをチェックするため、
            // 以下のパターンを使用する。
            // 1. 少なくとも1つの数字が含まれている
            // 2. 数字とカンマ以外が含まれていない
            // 3. 行全体がこの形式に一致する
            
            // 妥当性の判定のための正規表現:
            // ^\s* : 行頭の空白
            // (?:(?=\d)(?:,?\d*)*) : 少なくとも1つの数字が始まり、カンマ区切りで続く構造
            // .*$ : 行の最後まで
            // 簡易的に、数字とカンマのみで構成されており、少なくとも1つの数字が含まれていることを確認する。
            // 正規表現で「数字とカンマのみで構成され、少なくとも1つの数字が含まれる」ことを確認する。
            // 許容されるパターン: 数字とカンマのみで構成され、空行ではない。
            
            // 1. 空行判定 (trim()で空文字列になる)
            if (line.trim().isEmpty()) {
                continue;
            }

            // 2. 数字とカンマのみで構成されているかを確認する
            // 正規表現: 任意の空白、数字、カンマのみで構成されているか？
            // この課題の仕様は「1個以上の数字列がカンマで区切られて並んでいること」と「数字とカンマ以外を含まないこと」を求めている。
            // 以下のパターンは、数字とカンマのみを含む文字列を許可する。
            // (?:[0-9,]+) は1つ以上の数字とカンマの組み合わせ
            // ^\s* (.*?) $ の範囲で検証を行う。
            
            // 妥当な行の定義: 
            // 1. 空行でない
            // 2. 数字とカンマ以外を含まない
            // 3. 1個以上の数字列がカンマで区切られている（末尾のカンマは許容）

            // まず、数字とカンマ以外の文字が含まれていないかチェックする
            if (!line.matches("^[\\s,]*[0-9,]*$")) {
                continue; // 数字とカンマ以外を含む行は無効
            }

            // さらに、1個以上の数字列が存在するかチェックする
            // カンマで区切られた複数の数字が存在するためには、少なくとも1つの数字が存在する必要がある。
            if (!line.matches(".*\\d.*")) {
                 // 数字が一つも含まれていない（例: "," や ",," のみ）
                 continue;
            }

            // 上記の条件をすべて満たした場合、妥当とみなす。
            validLines++;
        }

        System.out.println("valid=" + validLines);
    }
}
