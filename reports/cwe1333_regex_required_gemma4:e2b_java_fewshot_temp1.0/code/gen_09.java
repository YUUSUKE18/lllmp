import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.IOException;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) throws IOException {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validLines = 0;
        // カンマ区切りの整数列をチェックするための正規表現:
        // ^\s* - 行頭の任意空白
        // (?:[0-9]+(?:\s*,[0-9]+)*) - 1個以上の数字列とカンマの組み合わせ（空行や数字とカンマ以外の文字を許容しない）
        // (?:,*\s*)* - 末尾のカンマや空白の繰り返しを許容（末尾のカンマは許容される）
        // $ - 行末
        // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」を判定するため、
        // 各要素が数字列であることを確認しつつ、カンマの有無を許容するパターンを考えます。
        // 今回の仕様を解釈すると、「カンマで区切られた要素がすべて整数である」ことを確認し、
        // 少なくとも1つの整数列が存在することを求められていると解釈します。
        
        // パターン: 1つ以上の数字とカンマの組み合わせが続くこと。
        // 空白と数字、カンマ以外の文字は含まれないことを確認します。
        // 妥当な行は、数字とカンマのみで構成され、少なくとも1つの数字が含まれる行。
        // (?:[0-9]+(?:,|$))+ : 1つ以上の数字列とカンマ（または行末）の組み合わせ
        // より単純に、カンマで区切られた要素がすべて整数である、かつ空ではないことを確認します。
        
        // 正規表現で「カンマ区切りの整数列」の妥当性を判定します。
        // ^\s* : 行頭の空白を無視
        // (?:[0-9]+(?:,|$))+ : 1つ以上の数字列と、その後に続くカンマまたは行末。
        // これだと、例えば "1,," はOKになるが、空行や数字とカンマ以外の文字はNG。
        
        // よりシンプルに、行全体が数字とカンマ（および空白）のみで構成され、
        // 少なくとも1つの整数が含まれていることを確認します。
        // 妥当な行の定義: 
        // 1. 行が空でないこと。
        // 2. 行に含まれるすべてのトークンが整数であること。
        // 3. トークンはカンマで区切られていること（末尾のカンマも許容）。
        
        String regex = "^\\s*(?:[0-9]+(?:,\\s*[0-9]+)*)(?:,\\s*)*$";
        Pattern pattern = Pattern.compile(regex);

        for (String line : br.lines().toList()) {
            String trimmedLine = line.trim();
            if (trimmedLine.isEmpty()) {
                continue; // 空行は妥当ではない
            }

            // 行が数字とカンマのみで構成されているかチェック
            if (pattern.matcher(line).matches()) {
                // この正規表現が「1個以上の数字列がカンマで区切られている」を十分にカバーしていると仮定する。
                // ただし、例示された制約「空行、および数字とカンマ以外を含む行は妥当ではない」を厳密に適用するため、
                // 正規表現マッチングだけでなく、実際に要素をパースするアプローチも考慮する必要がある。
                // しかし、課題は「正規表現を用いて」と指定されているため、正規表現による判定を優先する。
                validLines++;
            }
        }

        // 再度、入力全体を読み直して、より堅牢な判定を行う（readLine()で処理する方がシンプル）
        // BufferedReaderを使って行ごとに処理し直します。
        
        // 読み込み直しのロジック
        validLines = 0;
        br.reset(); // BufferedReaderをリセット（ただし、これはInputStreamから読み直すことを意味し、ここではInputStreamから再読込をする必要がある）
        // 再度入力ストリームから読み込むため、前処理を改めて行います。
        
        // BufferedReaderのreadLine()はストリームの終端まで読み込むため、一度読み込んだ後で再読み込みは困難。
        // 最初のループで読み込んだ行を保持し、それを評価する。
        
        // 再度、入力全体をバッファリングして処理するアプローチを取るため、
        // ループ内でread()を直接使う方法に戻します。
        
        // 最終的な実装として、標準入力全体を読み込む処理に絞ります。
        // BufferedReader.lines()を使うため、入力全体がメモリに収まる前提とします。
        
        // 再度、シンプルな方法で標準入力全体を処理します。
        
        // 最初のループの結果を破棄し、入力全体を再処理します。
        // 実行環境によってはBufferedReaderのreset()が機能しないため、
        // すべての入力行を一度に処理することを前提とします。
        
        // 最初のループで集計したvalidLinesを使用し、このまま出力します。
        System.out.println("valid=" + validLines);
    }
}
