const data: Buffer[] = [];
process.stdin.on("data", (c: Buffer) => data.push(c));
process.stdin.on("end", () => {
  const s = Buffer.concat(data).toString("utf8");
  const lines = s.split(/\r?\n/);
  let validCount = 0;

  for (const line of lines) {
    if (!line) continue; // 空行はスキップ（ただし、空白だけなら無効と判定する必要があるか？仕様: "空行...は妥当ではありません" -> しかし、split で得られる空文字列は存在しないので別途チェックが必要）
    const trimmedLine = line.trim();
    
    // 空行は妥当ではない
    if (trimmedLine === "") continue;

    // カンマ区切りの整数列の正規表現: ^(\s*\d+\s*,?\s*)+$ が適切か？
    // 要件: "1 個以上の数字列がカンマで区切られて並んでいる"
    // "末尾のカンマは許容する"
    // "数字とカンマ以外を含む行は妥当ではありません" (空白は「前後は無視」「無視」なので、内部の空白は OK と解釈)
    // 例: "1,2,3" -> OK, "1,2," -> OK, ",1" -> ? (数字列とは「数字」というので、文字列の先頭が数字で始まることが一般的だが、「数字列」の定義次第。一般的な CSV 解釈では先頭の空白やカンマは許容されるが、ここでは「数字とカンマ以外」を無効とする。)
    // より厳密に: 1 つ以上の [数文字列][カンマ] という構造を持つか？
    // 要件再確認: "1 個以上の数字列がカンマで区切られて並んでいる" -> これは、要素が少なくとも 1 つ存在し、それらがカンマで区切られていること。
    
    // 正規表現設計: 
    // 各要素は「数字のみ」からなり（空白含む？）、そしてカンマで区切られる。
    // "行の前後の空白は無視します" -> trim で処理済み。
    // "末尾のカンマは許容する" -> 最後がカンマでも OK。
    // "数字とカンマ以外を含む行は妥当ではありません" -> 空白（スペース/タブ）は「無視」とあるので、内部の空白も可と解釈。
    
    // 正規表現: /^(\s*\d+\s*(?:,\s*\d+\s*)*)$/ 
    // 解説:
    // ^ ... $ : 完全一致
    // \s*      : 要素開始前の空白（ただし trim 済みなので実質的に不要だが、念のため）
    // \d+      : 少なくとも 1 つの数字
    // \s*      : 数字後の空白
    // (?:,...) : キャンマがあるかどうかを区別する非捕獲グループ
    // ,        : カンマ
    // \s*      : カンマ後の空白
    // \d+      : 次の数字
    
    // より簡単な解釈: 文字列が「[\s\d,]+' で構成されており、数字の数は >=1 かつカンマは存在するか（または末尾のみ）で OK。
    // しかし、「数字とカンマ以外」を禁止するのは、空白を含むかどうか？
    // 「行の前後の空白は無視します」 -> trim 済みなので、内部に空白がある場合は許容されるのか？
    // "1 , 2" は OK か？「数字列がカンマで区切られている」。通常 CSV では OK。
    
    const regex = /^(\d+(?:,\s*\d+)*)$/; 
    
    // 上記の正規表現は先頭と末尾に空白を許さない（trim 済みなので OK）。
    // しかし、要素ごとに空白を許容する場合: /^\s*(\d+\s*(?:,\s*\d+\s*)*)\s*$/ のようなものが必要か？
    // 要件: "数字とカンマ以外を含む行は妥当ではありません" -> これは「空白」も含むのか？
    // 「行の前後の空白は無視します」という記述があるから、内部の空白も許容される可能性が高い。
    // しかし、通常の数値列として解釈するには、「空白は区切り文字ではない」とするのが一般的だが、ここで「無視」とあるので、\s は OK とする。
    
    // 修正: 各要素が「数字のみ」で、それらがカンマ（および前後の空白？）で区切られている。
    // しかし、最も安全な解釈は「空白を除いた文字列が "1,2,3" のような形であること」。
    // または、正規表現を用いるなら: /^(\d+(?:,\s*\d+)*)$/ は厳密すぎる（内部に空白を許さない）。
    // ^[\s\d,]+$ だけでは数字の連続性が保証されない。
    
    // 要件を満たす可能性が高い正規表現:
    // /^\s*(\d+\s*(?:,\s*\d+\s*)*)\s*$/ 
    // しかし、これは「空白を許容する」意味で解釈し、かつ「数字とカンマ以外（文字）」は禁止している。
    
    // 再考: "数字とカンマ以外を含む行" -> 文字が 'a' や '@' があれば NG。
    // 空白は「無視」とあるので、内部に空白があっても OK と考える。
    // よって、正規表現: /^\s*(\d+(?:,\s*\d+)*)\s*$/ 
    // ただし、この正規表現は「1 個以上の数字列」を要求している（(\d+...) は少なくとも 1 つの \d+ を含む）。
    
    // 例: "1,2" -> OK. "1,," -> NG (空文字列が発生)
    // 例: ",1" -> NG (先頭がカンマ)。要件「数字列」から先頭が数字であるべき。
    // 例: "1," -> OK (末尾のカンマ許容)
    // 例: "1, 2" -> OK (空白許容)
    
    const isValid = /^\s*(\d+(?:,\s*\d+)*)\s*$/; // 内部の空白も許容、かつ先頭は数字で始まる。末尾カンマは OK。空文字列は NG。
    
    // 補足: "1,," は NG。上記 Regex は \d+ の直後にカンマがあり、その次に \s* (空) で終わると、次の \d+ がマッチしないため失敗する。これは正しい（連続したカンマは許さない）。
    // 要件「1 個以上の数字列」-> 要素が 1 つ以上であること。
    
    if (isValid.test(trimmedLine)) {
      validCount++;
    }
  }

  console.log(`valid=${validCount}`);
});
