process.stdin.setEncoding("utf8");

let validCount = 0;
let inputData = "";

process.stdin.on("data", (data: string) => {
  inputData += data;
});

process.stdin.on("end", () => {
  const lines = inputData.split("\n");
  let validLines = 0;

  for (const line of lines) {
    // 行の前後の空白を無視
    const trimmedLine = line.trim();
    if (trimmedLine === "") {
      continue; // 空行は妥当ではない
    }

    // カンマ区切りの整数列として判定
    // 妥当な行: 1個以上の数字列がカンマで区切られている。末尾のカンマは許容。
    // 正規表現パターン:
    // ^\s*          -> 行の先頭の空白
    // (?:          -> 非キャプチャグループ
    //   \d+(?:,\d+)* -> 1つ以上の数字とカンマの繰り返し (数字列が1つ以上あることを保証)
    // )            -> グループ終わり
    // \s*$         -> 行末の空白
    // この正規表現は「数字とカンマの組み合わせ」が少なくとも1つ存在することを要求します。
    // ただし、仕様は「1個以上の数字列がカンマで区切られて並んでいる」です。
    // より単純に、カンマで区切られたものとしてパースを試みます。

    // 妥当な行の判定ロジックを再考:
    // 1. 空行はNG。
    // 2. 数字とカンマ以外を含む行はNG。
    // 3. カンマ区切りの整数列として妥当であること。

    // 数字とカンマのみで構成されているかチェックする
    const isValidFormat = /^[0-9,]*$|^[0-9,]+.*$/; // 非常に緩いチェック

    // カンマ区切りの整数列として妥当であるか、つまり数字とカンマのみで構成されているか、そして少なくとも数字が含まれているか。
    // 末尾のカンマは許容。
    // 整数列のパターン: 数字が1つ以上存在し、カンマが数字と数字の間にある。
    // 例: "1,2,3", "1,2,", "1"
    
    // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を判定するために、カンマで区切った後、全てが数字であることを確認します。
    
    // 1. 行をカンマで分割する
    const parts = line.split(',');
    
    if (parts.length === 0) {
        // 空行や空白のみの場合（既にトリムで除外されているが念のため）
        continue;
    }

    let allAreNumbers = true;
    let hasNumbers = false;

    for (const part of parts) {
        const trimmedPart = part.trim();
        if (trimmedPart === "") {
            // カンマが連続している場合 (例: "1,,2" や ",1")。これは「数字列が並んでいる」という条件を満たさない可能性が高い。
            // ただし、末尾のカンマは許容されるため、連続するカンマは許容されるべきか？
            // 仕様: 「1 個以上の数字列がカンマで区切られて並んでいる」
            // "1,,2" は2つの数字列 (1, 空, 2) と見なせるか？ -> 妥当ではないと解釈する。
            continue; 
        }
        
        // 数字列であるかチェック
        if (!/^\d+$/.test(trimmedPart)) {
            allAreNumbers = false;
            break;
        }
        hasNumbers = true;
    }

    // 妥当である条件:
    // 1. 数字とカンマ以外を含まないこと (空行や文字が含まれない)
    // 2. 少なくとも1つの数字列が存在すること (hasNumbersがtrue)
    // 3. 末尾のカンマは許容される (splitの結果、最後の要素が空文字列になる可能性がある)
    
    // 最後の要素がカンマで終わる場合 (例: "1,2," -> ["1", "2", ""])
    // この行が妥当であるためには、少なくとも1つの要素が数字で構成されている必要がある。
    if (allAreNumbers && hasNumbers) {
        validLines++;
    }
  }

  console.log(`valid=${validLines}`);
});
