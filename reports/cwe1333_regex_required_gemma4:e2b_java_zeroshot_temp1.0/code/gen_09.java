import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStreamReader;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) {
        // 正規表現パターン: 1つ以上の整数とカンマの組み合わせを検出する。
        // ^\s* : 行の先頭の任意の空白（無視される）
        // (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字とカンマの繰り返し（整数列）
        // (?:,|\s*$) : カンマまたは行末の空白（末尾のカンマも許容するため、カンマの後に続くものとして扱う）
        // .*$ : 行の残りの部分
        // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを判定するために、
        // 正規表現の構造を少し調整します。
        // 1個以上の整数がカンマで区切られていることを確認します。
        // 例: 1,2,3 または 1,2,3,
        
        // より厳密な判定のため、行全体が (数字, 数字, ...) の形式であるかを確認します。
        // 許容されるパターン: 1個以上の整数がカンマで区切られており、末尾のカンマも許容される。
        // 空行や数字とカンマ以外の文字が混ざっていないこと。

        // 判定ロジック:
        // 1. 空行 (完全に空白または改行のみ) は無効
        // 2. 数字とカンマ以外を含む行は無効
        // 3. 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」こと。
        //    これは、少なくとも一つのカンマを含む、または数字のみの列が続くことを意味する。

        // 正規表現の設計:
        // ^\s* : 行頭の空白
        // (?:[0-9]+(?:,[0-9]+)*) : 1個以上の数字とカンマの繰り返し。これは、少なくとも1つの数字列が存在することを保証する。
        // (?:,|$) : 最後の要素がカンマまたは行末であること。
        
        // 判定基準をシンプルにし、与えられた要件（1個以上の数字列がカンマで区切られて並んでいる）を直接確認する。
        // 1. 空行でないこと (行に何か文字があること)
        // 2. 数字とカンマ以外の文字がないこと
        // 3. 少なくとも1つの数字列が存在すること。

        // より厳密な正規表現で「1個以上の数字列がカンマで区切られて並んでいる」を表現する。
        // 連続する数字とカンマの組み合わせが1回以上あることを確認する。
        String regex = "^\\s*(?:[0-9]+(?:,[0-9]+)*)(?:,|$)?\\s*$";
        Pattern pattern = Pattern.compile(regex);

        int validCount = 0;
        try (BufferedReader br = new BufferedReader(new InputStreamReader(System.in))) {
            String line;
            while ((line = br.readLine()) != null) {
                String trimmedLine = line.trim();

                if (trimmedLine.isEmpty()) {
                    // 空行は無効
                    continue;
                }

                // 数字とカンマ以外を含む行は無効
                // このチェックは正規表現の範囲外の文字が混入した場合に対応する。
                // 正規表現で全てをカバーするため、以下のチェックを併用する。

                // 妥当性の判定: 正規表現にマッチするかどうかをチェックする。
                // 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」ことです。
                // 空行や数字とカンマ以外の文字を含む行は無効。
                
                // 以下のパターンで、数字とカンマのみで構成され、少なくとも1つの数字列を含むことを確認します。
                // ^\s* : 行頭の空白
                // (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字とカンマの繰り返し。これは少なくとも一つの数字列を意味する。
                // [0-9,]* : カンマ以外の文字（今回は数字とカンマのみが許容されるため、このパターンで十分）
                // \s*$ : 行末の空白
                
                // 要件「空行、および数字とカンマ以外を含む行は妥当ではありません」を考慮すると、
                // 行が数字とカンマのみで構成されていることを確認し、かつ少なくとも1つの数字列があることを確認する。
                
                // 判定：行が数字とカンマのみで構成されているか。
                // このパターンは、行全体が「整数とカンマの連続」であることを確認します。
                String strictRegex = "^\\s*([0-9,]*[0-9])\\s*$"; // 少なくとも一つの数字が含まれ、数字とカンマ以外がないことを確認する。
                
                // 妥当な行の判定: 1個以上の数字列がカンマで区切られていること。
                // パターン (?:[0-9]+(?:,[0-9]+)*) は、少なくとも1つの数字列が存在することを保証します。
                if (Pattern.compile("^(?:[0-9]+(?:,[0-9]+)*).*$").matcher(line).matches()) {
                    // この行が「1個以上の数字列がカンマで区切られて並んでいる」という条件を満たす。
                    // 末尾のカンマの許容は、上記のパターンでカバーされる。
                    validCount++;
                }
            }
        } catch (IOException e) {
            // エラー処理（通常は無視）
        }

        System.out.println("valid=" + validCount);
    }
}
