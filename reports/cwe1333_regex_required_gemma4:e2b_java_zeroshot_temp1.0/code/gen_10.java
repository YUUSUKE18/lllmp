import java.util.Scanner;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int validCount = 0;

        while (scanner.hasNextLine()) {
            String line = scanner.nextLine();

            // 1. 行の前後の空白を無視する (strip()を使用)
            String trimmedLine = line.trim();

            // 2. 空行の判定
            if (trimmedLine.isEmpty()) {
                continue;
            }

            // 3. 正規表現による妥当性の判定
            // 妥当なパターン: 1個以上の整数とカンマの組み合わせ。末尾のカンマは許容される。
            // パターン解説:
            // ^             : 行の先頭
            // (             : グループ開始 (1個以上の要素)
            //   \d+         : 1つ以上の数字 (整数列)
            //   (?:,\d+)*   : カンマとそれに続く1つ以上の数字の繰り返し (カンマ区切り)
            // )             : グループ終了
            // (?:,\d+)*     : 末尾のカンマのみの繰り返し (例: "1,2," の末尾のカンマ)
            // $             : 行の末尾
            //
            // よりシンプルに「数字とカンマのみで構成され、少なくとも1つの数字が含まれている」ことを確認する。
            // 仕様: 1個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容。
            // これは、数字とカンマが混在し、数字が少なくとも1つある、という条件を満たせば良い。

            // 正規表現の再検討:
            // 少なくとも1つの数字列 ( \d+ ) が存在し、その間にカンマ ( , ) が入るか、または末尾にカンマがある状態。
            // 例: "123", "1,2,3", "1,2,"
            // 許可されるのは、数字とカンマのみで構成され、数字が1つ以上含まれていること。

            // パターン: 少なくとも1つの数字が含まれ、それ以外は数字とカンマのみ。
            // これは、行全体が以下のパターンにマッチするかどうかで判定する。
            // (数字とカンマのセットが連続していること)
            // \d+(?:,\d+)*  -> 1つ以上の数字が始まり、カンマと数字のペアが続く。
            // このパターンは、"123", "1,23", "1,2,3" にマッチする。
            // 末尾のカンマ "1,2," にはマッチしない。

            // 末尾のカンマの許容を考慮して、以下のように表現する。
            // 1. 少なくとも1つの数字がある。
            // 2. その他に、数字とカンマのみが存在する。

            // 妥当性の判定ロジックを、正規表現でのマッチングではなく、より直接的な文字セットと構造で確認する。
            // 正規表現を使うという制約があるため、正規表現で末尾のカンマの許容を表現する。

            // パターンA: 少なくとも1つの数字列が含まれ、数字とカンマのみで構成される行。
            // ^\s*                 -> 先頭の空白 (ここではtrimしているので不要だが念のため)
            // (?: \d+ (?:,\d+)* )  -> 1個以上の数字が始まり、カンマ区切りが続くパターン。
            // (?:,\d+)*            -> カンマ区切りが終了し、末尾にカンマが続くパターン。
            // $
            
            // 最もシンプルに「1つ以上の数字とカンマのみで構成されており、空行ではない」ことを確認し、末尾のカンマは許容する。

            // 正規表現：数字（少なくとも1つ）とカンマのみで構成される。
            // ^\s*                                 -> 行の先頭の空白
            // (?: \d+ | , )+                        -> 1つ以上の数字またはカンマ
            // \s*$                                 -> 行末の空白

            // 簡略化のため、trimした文字列に対して判定する。
            // 妥当な行は、数字とカンマ以外の文字を含まないこと。
            // そして、数字が1つ以上含まれていること。

            // 正規表現による判定（数字とカンマのみで構成され、数字が含まれているか）
            // ^[0-9,]*$            -> 数字とカンマのみ。ただし、これは " , " や ",," も許してしまう。
            // ^\d[\d,]*$           -> 1つ以上の数字で始まる。
            
            // 仕様を満たすための正規表現の再定義：
            // 1個以上の数字が、カンマで区切られている (末尾のカンマは許容)。
            // このパターンは、「数字の塊」が少なくとも1つ存在することを意味します。
            String regex = "^\\s*(\\d+(?:,\\d+)*)(?:,\\d+)*\\s*$";
            
            // 実行結果
            Matcher matcher = Pattern.compile(regex).matcher(trimmedLine);
            
            // 判定ロジックを簡略化し、正規表現の厳密な解釈に依存せず、仕様に最も忠実に判定する。
            // 空行や数字とカンマ以外の文字が含まれていないか、数字が1つ以上あるか。

            boolean isValid = false;
            if (!trimmedLine.isEmpty()) {
                // 1. 数字とカンマ以外が含まれていないか？
                boolean containsOnlyDigitsAndCommas = true;
                for (char c : trimmedLine.toCharArray()) {
                    if (!((c >= '0' && c <= '9') || c == ',')) {
                        containsOnlyDigitsAndCommas = false;
                        break;
                    }
                }

                if (containsOnlyDigitsAndCommas) {
                    // 2. 少なくとも1つの数字が含まれているか？
                    boolean containsAtLeastOneDigit = false;
                    for (char c : trimmedLine.toCharArray()) {
                        if (Character.isDigit(c)) {
                            containsAtLeastOneDigit = true;
                            break;
                        }
                    }
                    
                    if (containsAtLeastOneDigit) {
                        // 3. カンマ区切りの構造（カンマが存在するか、または単一の数字列であるか）を満たすか？
                        // 妥当とは、「1個以上の数字列がカンマで区切られて並んでいる」こと。
                        // 例: "123" (1個の数字列と見なせる)、"1,2" (2個の数字列)
                        
                        // 最も緩い解釈（「数字とカンマのみで構成され、数字が1つ以上ある」）を採用する。
                        // 末尾のカンマの許容は、この制約を満たす場合に自動的にカバーされる。
                        isValid = true;
                    }
                }
            }


            if (isValid) {
                validCount++;
            }
        }

        System.out.println("valid=" + validCount);
        scanner.close();
    }
}
