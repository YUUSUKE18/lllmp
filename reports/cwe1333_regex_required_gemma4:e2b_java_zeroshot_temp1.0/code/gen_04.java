import java.util.regex.Pattern;
import java.util.Scanner;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int validCount = 0;

        // 処理する行を読み込む
        while (scanner.hasNextLine()) {
            String line = scanner.nextLine();
            // 行の前後の空白を無視して処理するために、行をトリムする
            String trimmedLine = line.trim();

            // 1. 空行の場合
            if (trimmedLine.isEmpty()) {
                continue;
            }

            // 2. 正規表現による妥当性の判定
            // 妥当なパターン: 1個以上の数字列がカンマで区切られている。
            // 許容されるパターン: 数字とカンマのみで構成され、1つ以上の数字が含まれる。
            // 末尾のカンマは許容される。
            // 正規表現: ^\s*(\d+(,\d+)*)\s*?$
            // より厳密に、「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
            // 数字とカンマのみで構成され、少なくとも1つの数字が含まれているかをチェックする。
            
            // 1. 数字とカンマ以外を含まないことを確認する (数字とカンマのみ)
            if (!trimmedLine.matches("[0-9,]*")) {
                continue;
            }

            // 2. 少なくとも1つの数字が含まれていることを確認する
            // 数字が含まれていない場合（例: "," や ",," など）、妥当ではない。
            if (!trimmedLine.matches(".*\\d.*")) {
                continue;
            }

            // 3. カンマ区切りとしての妥当性を確認する
            // パターン: 1つ以上の数字列と、それらを区切るカンマの組み合わせ。
            // 許容される構造: (数字)(カンマ)(数字)... または (数字) または (数字)(カンマ)*
            // このルールは「1個以上の数字列がカンマで区切られて並んでいる」を意味する。
            // 例: "1,2,3", "123", "1,2,"
            
            // 正則表現の解説:
            // ^                                      : 行の先頭
            // (                                      : グループ開始（1個以上の数字列の始まり）
            //   \d+                                  : 1つ以上の数字
            //   (?:,\d+)*                            : カンマと1つ以上の数字が0回以上繰り返される (区切りと次の数字)
            // )
            // (?:,\d+)*                              : 最後の要素がカンマで終わる場合に対応 (末尾のカンマを許容するため)
            // $                                      : 行の末尾
            
            // より単純に、数字とカンマのシーケンスであり、数字が少なくとも1つ含まれていることを確認する。
            // 以下のパターンは、数字とカンマのみで構成され、途中に数字が存在することをチェックします。
            // 1. 少なくとも1つの数字があること (.*?\d.*)
            // 2. 数字とカンマのみで構成されていること (.*[0-9,].*)
            
            // 仕様の再解釈に基づき、最も緩く妥当なパターンを適用する:
            // 1個以上の数字列がカンマで区切られている。
            // 例: "1,2", "1,2,3", "1,", ",1" は不正。 "123" は有効。
            // 
            // 妥当なパターン: 数字のシーケンスで、カンマが区切りとして機能している。
            // 最小構成: 数字が1つ以上存在する。
            // 1. 数字の列 (1個以上): \d+
            // 2. カンマの列 (0個以上): (?:,)*
            // この組み合わせが、行全体をカバーし、数字とカンマ以外の文字を含まないことを保証する。
            
            // 最終的な判定ロジック:
            // 数字とカンマのみで構成されており、かつ、少なくとも1つの数字が存在する。
            // 途中のカンマが許容されるため、最も制約が緩いのは、数字とカンマが混在している行。
            
            // 妥当な行の定義: 数字とカンマ以外の文字を含まず、かつ、数字が1つ以上含まれている。
            // (.*) で全てをキャプチャし、その中に数字が含まれていることを確認する。
            boolean isValid = false;
            
            // 1. 数字とカンマのみで構成されているか？
            // 2. 少なくとも1つの数字が含まれているか？
            if (trimmedLine.matches(".*[0-9,].*")) {
                // 数字とカンマが混在している場合、これらは「1個以上の数字列がカンマで区切られている」の候補となる。
                // ただし、",," や "," など、数字列がないものは除外する。
                
                // より厳密に、「数字の並び」が基準となる。
                // 数字の並びが少なくとも1つ存在し、それらがカンマで区切られているか、単独で存在する場合。
                // (数字列) (カンマと数字列の繰り返し)
                if (trimmedLine.matches("^\\d+(?:,\\d+)*$") || trimmedLine.matches("^\\d+$")) {
                    isValid = true;
                }
            } 
            // 単純な数字列の場合（区切りがない場合も「1個の数字列」として許容するか？）
            // 仕様: 「1 個以上の数字列がカンマで区切られて並んでいる」
            // 1個の数字列 "123" は「1個の数字列」と見なされる。これは1個以上の数字列がカンマで区切られている (区切りが0個) と解釈できる。
            else if (trimmedLine.matches("^\\d+$")) {
                isValid = true;
            }
            
            // 上記のロジックは複雑になりすぎるため、正規表現をシンプルにする。
            // 妥当な行 = 数字とカンマのみで構成され、少なくとも1つの数字が含まれる。
            // 許容される形式の例: "1,2", "123", "1,"
            // 否定される形式の例: "", ",", "abc", "1a"
            
            // 妥当な行の定義を「数字とカンマのみで構成され、数字が少なくとも1つ含まれる」として再評価。
            // この解釈で、"1,2," は妥当。 "123" は妥当。 "," は不正。
            if (trimmedLine.matches("^[0-9,]*$")) {
                // 数字とカンマのみで構成されている
                // 数字が1つ以上含まれていることを確認
                if (trimmedLine.matches(".*\\d.*")) {
                    validCount++;
                }
            }
        }

        // 結果を出力
        System.out.println("valid=" + validCount);
        scanner.close();
    }
}
