import java.util.Scanner;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int validLines = 0;

        while (scanner.hasNextLine()) {
            String line = scanner.nextLine();
            
            // 行の前後の空白を無視
            String trimmedLine = line.trim();

            if (trimmedLine.isEmpty()) {
                // 空行は妥当ではない
                continue;
            }

            // 正規表現による妥当性の判定
            // 妥当な形式: 1個以上の数字とカンマの組み合わせ。
            // 許容されるパターン: 1個以上の数字とカンマが混在している。
            // 末尾のカンマは許容される。
            // 具体的には: 
            // - 1文字以上の数字とカンマの組み合わせ
            // - 数字とカンマのみで構成され、途中に数字が1つ以上ある
            // 
            // 仕様の解釈: 「1 個以上の数字列がカンマで区切られて並んでいること」
            // これは、数字とカンマが混在している文字列が、少なくとも1つの数字を含むことを意味します。
            // 最小の条件は、少なくとも1つの数字が存在すること、そしてカンマで区切られていること。
            
            // 数字とカンマのみで構成され、少なくとも1つの数字が含まれるパターンをチェックします。
            // ^[0-9,]+$ : 数字とカンマのみで構成される。
            // .*? : 任意の文字（ここでは使わないが、行全体をチェックするため）
            
            // 妥当性の判定ロジックを正規表現で実装します。
            // 1. 数字とカンマのみで構成されていること
            // 2. 少なくとも1つの数字が含まれていること (そうでなければ、カンマのみや空行ではないものも除外したいが、空行は既に除外済み)
            
            // 妥当な行の定義: 
            // 1. 数字とカンマのみで構成されている。
            // 2. 少なくとも1つの数字が含まれている。（もし「1個以上の数字列がカンマで区切られている」が、「カンマで区切られた数字の集合」を指すならば、数字が含まれていることが必要）
            
            // 最も厳密な解釈: 「カンマで区切られた整数列」が1つ以上あること。
            // 例: "1,2,3" -> 3つの数字列
            // 例: "1,2," -> 2つの数字列（末尾のカンマは許容）
            
            // この場合、文字列中に数字（0-9）が含まれ、カンマ（,）が含まれる、または数字のみで構成されていれば良い。
            // 空白や数字とカンマ以外の文字が含まれていないことを確認する。
            
            // 正規表現: 
            // ^[0-9,]*$ : 数字とカンマのみで構成される（空行を除く）
            // ただし、これだけでは " , " のような不正なパターンも通してしまう。
            
            // 妥当なパターン: 
            // 1. 数字とカンマのみで構成されている。
            // 2. 少なくとも1つの数字が含まれている。
            
            // 数字とカンマのみで構成されていることを確認し、かつ数字が含まれていることを確認。
            Pattern pattern = Pattern.compile("^[0-9,]+$");
            if (pattern.matcher(trimmedLine).matches()) {
                // 数字とカンマのみで構成されている。
                // さらに、少なくとも1つの数字が含まれているかを確認する。
                if (trimmedLine.matches(".*[0-9].*")) {
                    validLines++;
                } else if (trimmedLine.matches(",*")) {
                    // カンマのみの行（例: "," または ",,"）。これは「1個以上の数字列」ではないため不適。
                    // ただし、仕様上は「1個以上の数字列がカンマで区切られて並んでいる」という表現なので、
                    // 実際には数字が最低1つ必要。
                    // カンマのみの行を妥当ではないとする。
                }
            }
        }

        System.out.println("valid=" + validLines);
        scanner.close();
    }
}
