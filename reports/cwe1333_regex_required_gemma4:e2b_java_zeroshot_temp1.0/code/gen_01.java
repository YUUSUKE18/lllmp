import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStreamReader;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int validCount = 0;

        // 妥当な行数を数える
        String line;
        while ((line = br.readLine()) != null) {
            // 行の前後の空白を無視する
            String trimmedLine = line.trim();

            // 1. 空行の場合は妥当ではない
            if (trimmedLine.isEmpty()) {
                continue;
            }

            // 2. 正規表現で判定する
            // 正規表現の解説:
            // ^           : 行の先頭
            // [0-9,]*     : 0個以上の数字またはカンマ（数字とカンマのみを含む）
            // $           : 行の末尾
            // このパターンだけでは「1個以上の数字列がカンマで区切られている」ことを保証できません。
            // 「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するために、
            // 少なくとも1つの数字が含まれていること、そしてカンマのパターンをチェックします。
            // 妥当な形式: (数字,数字,...) または (数字,数字) など
            // 任意の数字とカンマの組み合わせ（カンマを含む）が1つ以上続くことを確認
            // これは、少なくとも1つの数字が存在し、その間にカンマが混ざっているパターンを許容する必要があります。

            // 仕様の再解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
            // 例: "1,2,3" (妥当), "1,2," (妥当), "123" (妥当 - 1個の数字列), ",," (無効), "abc" (無効)

            // 正規表現の定義:
            // ^                          開始
            // (?:[0-9]+(?:,[0-9]+)*)      少なくとも1つの数字列がカンマで区切られているパターン (例: 1,2,3 や 123)
            // |                          または
            // [0-9]+                     単一の数字列のみ (例: 123)
            // $                          終了

            // 妥当な行の定義をよりシンプルに表現するため、
            // 「数字とカンマのみ」で構成されており、かつ、カンマの後に数字が続くことを確認します。
            // または、より厳密に「数字とカンマのシーケンス」と「数字の存在」をチェックします。

            // 妥当なパターン: 少なくとも1つの数字が含まれ、数字とカンマ以外は含まない。
            // 1. 数字とカンマのみから構成されていること: ^[0-9,]*$
            // 2. 数字が含まれていること (1個以上の数字列が存在すること): (?=.*[0-9])

            // 総合的な正規表現:
            // ^[0-9,]*$ : 行が数字とカンマのみで構成されている
            // (?=.*[0-9]) : 少なくとも1つの数字が含まれている (この先行アサーションは、上記パターンと組み合わせることで「1個以上の数字列」を間接的に保証します)

            String regex = "^[0-9,]*$";
            if (Pattern.matches(regex, trimmedLine)) {
                // 少なくとも1つの数字が含まれているかチェック
                if (trimmedLine.matches(".*[0-9].*")) {
                    validCount++;
                }
            }
        }

        // 結果の出力
        System.out.println("valid=" + validCount);
    }
}
