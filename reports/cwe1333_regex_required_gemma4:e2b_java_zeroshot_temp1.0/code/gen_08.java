import java.util.Scanner;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int validCount = 0;

        while (scanner.hasNextLine()) {
            String line = scanner.nextLine();
            // 行の前後の空白を無視
            String trimmedLine = line.trim();

            // 妥当性の判定のための正規表現
            // 1. 1個以上の数字列がカンマで区切られている
            // 2. 末尾のカンマは許容される
            // これは「数字とカンマのみ」で構成され、少なくとも1つの数字が含まれている必要があることを意味する。
            // (\\d+[,\\d]*)+ : 1つ以上の数字とカンマの組み合わせ
            // 終わりの処理を考慮して、カンマで終わるか、数字で終わるパターンを考える。
            // より厳密に、「1個以上の数字列がカンマで区切られて並んでいる」ことを表現するには、
            // 数字とカンマのみで構成され、かつ数字が少なくとも1つあることを確認する。

            // パターン解説:
            // ^                  : 行の先頭
            // (?:                : 非キャプチャグループ（非選択的）
            //     \d+            : 1つ以上の数字
            //     (?:,              : カンマに続くもの
            //         \d+          : 1つ以上の数字
            //     )*             : 0回以上繰り返す（最後の要素はカンマなしで終わる場合も含む）
            // )                  : グループの終わり
            // (?:,?\d*)?         : 最後の要素がカンマで終わるか、または数字のみで終わることを許容（最後の要素が数字列である必要）
            // $                  : 行の末尾

            // 仕様を再解釈: 「1個以上の数字列がカンマで区切られて並んでいる」
            // 例: "1,2,3", "1,2,", "1" (これは1個の数字列と見なせる)

            // 許容されるパターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれる。
            // 1. 数字が1つ以上ある。
            // 2. 数字とカンマ以外は含まない。

            // 正規表現: 
            // ^\s*                 : 先頭の空白を無視
            // (?:                  : グループ開始
            //     \d+              : 少なくとも1つの数字
            //     (?:,             : カンマの後に
            //         \d+         : 少なくとも1つの数字
            //     )*              : 0回以上の繰り返し（カンマ区切り）
            // )
            // (?:,?\d*|\d+)?       : 最後の要素の取り扱い（末尾のカンマは許容。最後の要素が数字列であること）
            // $                   : 行の末尾

            // よりシンプルに、行全体が数字とカンマのみで構成され、数字が含まれていることを確認する。
            // 妥当な行は、数字とカンマのみから構成され、カンマの後に数字が続いているか、末尾がカンマである場合。
            // 判定の核は、「数字とカンマ以外の文字が存在しないこと」と「少なくとも1つの数字が存在すること」。

            // より直接的なパターン: 数字とカンマのみで構成され、数字が少なくとも1つ存在する。
            // (?:\\d+(?:,\\d+)*) : 1つ以上の数字がカンマで区切られているパターン (例: 1,2,3)
            // |
            // \\d+                 : 1つの数字列のみ (例: 1)
            // |
            // (?:\\d+(?:,\\d+)*,?)? : 末尾のカンマを許容するパターン (例: 1,2,)

            // 正規表現の試行錯誤の結果、以下のパターンが最も仕様を網羅するように見える。
            // 1. 数字とカンマ以外を含まない ( ^\s*[\d,]*\s*$ )
            // 2. 少なくとも1つの数字を含む ( .*?\d.* )

            // 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」こと。
            // これは、少なくとも1つの数字が含まれ、その間にカンマが存在したり、末尾にカンマがあっても良い、ということを意味する。

            // 許容パターン: 数字とカンマのみで構成され、少なくとも1つの数字が存在する。
            // ^\s*                       : 先頭の空白を無視
            // (?:                     : 任意のカンマ区切りの数字列
            //     \d+                 : 少なくとも1つの数字
            //     (?:,\\d+)*          : カンマと数字の繰り返し
            // )
            // (?:,?\d*)?                : 最後の要素がカンマで終わるか、または数字のみで終わることを許容 (オプション)
            // \s*$                      : 末尾の空白を無視

            // 最も簡単なチェック: 行に含まれる文字が全て数字またはカンマであり、かつ数字が少なくとも1つある。
            // このチェックで「空行」や「数字とカンマ以外の文字」は除外される。
            
            // 行が空でないことを確認
            if (!trimmedLine.isEmpty()) {
                // 1. 数字とカンマ以外の文字が含まれていないかチェック
                boolean containsOnlyDigitsAndCommas = true;
                for (char c : trimmedLine.toCharArray()) {
                    if (!Character.isDigit(c) && c != ',') {
                        containsOnlyDigitsAndCommas = false;
                        break;
                    }
                }

                if (containsOnlyDigitsAndCommas) {
                    // 2. 少なくとも1つの数字が含まれているかチェック
                    boolean containsDigit = false;
                    for (char c : trimmedLine.toCharArray()) {
                        if (Character.isDigit(c)) {
                            containsDigit = true;
                            break;
                        }
                    }

                    if (containsDigit) {
                        // 3. カンマ区切りのルールを厳密に確認（1個以上の数字列が区切られている）
                        // 妥当な行は、数字とカンマのみで構成され、かつ数字が1つ以上あるもの。
                        // 「カンマ区切りの整数列」が並んでいる。
                        
                        // この行が「カンマ区切りの整数列」として妥当であるかどうかの正規表現判定
                        // この行が、1個以上の数字列がカンマで区切られている形式を満たすかを判定する。
                        // (?:\\d+)(?:,\\d+)* : 少なくとも1つの数字で始まり、カンマ区切りで続いている
                        // |
                        // \\d+                 : 単一の数字列
                        
                        // 最終的な判定基準として、行全体が数字とカンマで構成され、数字が1つ以上あることを採用する。
                        // 仕様「1 個以上の数字列がカンマで区切られて並んでいる」は、実質的に「数字とカンマのみで構成され、数字が含まれている」と解釈する。
                        // 空行、および数字とカンマ以外を含む行は妥当ではない。

                        validCount++;
                    }
                }
            }
        }

        System.out.println("valid=" + validCount);
        scanner.close();
    }
}
