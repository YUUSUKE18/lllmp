package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列のパターンを定義
	// ^\s*          : 行の先頭の任意の空白
	// (?:          : 非キャプチャグループ開始
	//   \d+       : 1つ以上の数字
	//   ,\s*      : カンマと任意の空白
	// )+           : 上記のグループが1回以上繰り返される（カンマ区切りの数字列）
	// (?:,\s*)?    : 末尾のカンマと空白（オプション）
	// $            : 行の終わり
	// この正規表現は、「1個以上の数字とカンマの組み合わせ」が、行全体を構成することをチェックします。
	// ただし、仕様の「1 個以上の数字列がカンマで区切られて並んでいる」を厳密に捉えるため、
	// 各数字列がカンマで区切られていることを確認する必要があります。
	// よりシンプルなアプローチとして、行が数字とカンマのみで構成されているか、
	// そして少なくとも1つの数字列が含まれているかをチェックします。

	// 仕様の解釈：
	// 1. 1個以上の数字列がカンマで区切られている。
	// 2. 末尾のカンマは許容される。
	// 3. 空行やその他の文字は許容されない。

	// 行が「数字とカンマのみ」で構成され、かつ「少なくとも1つの数字」を含むことを確認する正規表現
	// \s* は行頭/行末の空白を考慮するため、行全体をマッチさせます。
	// (?: \d+ (?:,\s* \d+)* ) : 1つ以上の数字列がカンマで区切られているパターン。
	// (?:,\s* \d+)*        : 続く区切り
	// これは複雑になりすぎるため、ここでは「行に含まれるすべての文字が数字、カンマ、空白のみであり、かつ数字が含まれていること」をチェックします。

	// 正規表現の再検討：
	// 妥当な行は「カンマ区切りの整数列」である。
	// 例: "1,2,3" または "1,2,"
	// 数字とカンマのみで構成され、少なくとも1つの数字が含まれることを確認する。
	// ^\s*                  : 行頭の空白
	// (?:                  : 非キャプチャグループ開始（数字列のパターン）
	//   \d+               : 1つ以上の数字
	//   (?:,\s*\d+)*      : カンマとそれに続く数字の繰り返し（少なくとも1つの数字列が続くことを保証）
	// )                   : グループ終了
	// (?:,\s*\d+)?         : 最後の要素がカンマで終わる場合を許容
	// \s*$                 : 行末の空白

	// 最もシンプルな解釈に基づき、行が数字とカンマのみで構成され、数字が含まれているかをチェックします。
	// 妥当な行の例: "1,2,3", "1,2,"
	// 不妥当な行の例: "", "a1,2", "1,,2" (カンマの連続は許容しないと仮定)

	// 行が数字とカンマのみで構成されていることを確認し、かつ少なくとも1つの数字が含まれていることを確認する。
	// 正規表現: 少なくとも1つの数字列があり、それらがカンマと空白で区切られている。
	// (?: \d+(?:,\s*\d+)* ) : 1つ以上の数字列がカンマで区切られているパターン。
	pattern := regexp.MustCompile(`^\s*(?:\d+(?:,\s*\d+)*)(?:,?\s*\d+)*\s*$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 行が数字とカンマのみで構成されているか、および構造が妥当かをチェック
		// 厳密な仕様を満たすために、行全体が「数字とカンマのシーケンス」であることを確認する。
		// 以下のパターンは、数字とカンマのみで構成され、かつ少なくとも1つの数字を含むことを確認します。
		// 1. ^\s* : 行頭の空白
		// 2. (?: ... )+ : 1回以上繰り返されるパターン（数字列とカンマ）
		// 3. $ : 行末
		// 以下のパターンは、1つ以上の数字と、それらを区切るカンマ（オプション）で構成されていることを確認します。
		// (?: \d+(?:,\s*\d+)* ) : 1つ以上の数字列がカンマで区切られている構造
		// (?:,\s*\d+)?           : 最後の要素がカンマで終わる場合を許容（末尾のカンマは許容）
		
		// 最終的なチェックとして、行が「数字とカンマ」のみで構成されていることを確認し、かつ数字が含まれていることを確認する。
		// ただし、行の構造が「カンマ区切りの整数列」であるという要件を最も強く満たすように、
		// 正規表現を以下のように調整します。
		// これは、行が数字とカンマのみで構成されており、数字が1つ以上存在することを要求します。
		
		// 妥当な行の例: "1,2,3", "1,2,"
		// 不妥当な行の例: "a,1", "1,2," (もし数字とカンマ以外が許されないなら)
		// 仕様：「数字とカンマ以外を含む行は妥当ではない」
		
		// 1. 数字とカンマのみで構成されているか？
		// ^[\d,]*$
		// 2. 少なくとも1つの数字が含まれているか？
		// (?=.*\d)
		
		// 3. カンマ区切りの構造を持つか？
		// 複数の数字列がカンマで区切られていることを確認します。
		// (?: \d+(?:,\s*\d+)* ) : 1つ以上の数字列がカンマで区切られているパターン
		
		// ここでは、行全体が「カンマで区切られた整数列」の形式であると解釈し、
		// 少なくとも1つの数字が含まれていることを確認します。
		
		// 妥当な行の例: "1,2,3"
		// 不妥当な行の例: "1", "1,2" (これは1個以上の数字列が並んでいると解釈できる)
		// 末尾のカンマは許容。
		
		// 妥当なパターン（1つ以上の数字列がカンマで区切られている、末尾カンマ許容）
		// 1. 数字の列 (\\d+)
		// 2. カンマと空白 (?:,\s*)
		// 3. 繰り返し (?: ... )+
		// 4. 末尾のカンマ (?:,|$)
		
		// 最終的な正規表現を採用します。行が数字とカンマのみで構成され、最低1つの数字が含まれていることを確認します。
		// これは、1個以上の数字列がカンマで区切られているという構造を、行全体で表現します。
		regex := regexp.MustCompile(`^\s*(?:\d+(?:,\s*\d+)*)(?:,?\s*\d*)?\s*$`)

		if regex.MatchString(line) {
			// さらに厳密に、行が「1個以上の数字列がカンマで区切られている」ことを確認します。
			// 1. 数字とカンマのみで構成されているか (行全体)
			// 2. 少なくとも1つの数字が含まれているか
			
			// 構造チェック (数字とカンマのみ)
			isAlphanumericOnly := true
			for _, char := range line {
				if !('0' <= char && char <= '9' || char == ',' || char == ' ' || char == '\t' || char == '\n') {
					isAlphanumericOnly = false
					break
				}
			}
			
			if !isAlphanumericOnly {
				continue // 数字とカンマ以外を含む行は不妥当
			}
			
			// 少なくとも1つの数字が含まれているか
			hasDigit := false
			for _, char := range line {
				if '0' <= char && char <= '9' {
					hasDigit = true
					break
				}
			}
			
			if hasDigit {
				validCount++
			}
		}
	}

	fmt.Println("valid=", validCount)
}
