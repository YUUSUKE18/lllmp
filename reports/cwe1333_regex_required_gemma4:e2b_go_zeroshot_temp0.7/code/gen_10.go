package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// 正規表現: 1つ以上の整数がカンマで区切られていることをチェックする。
	// ^\s* : 行頭の任意空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列と、その後にカンマと空白が続くパターンを繰り返す。
	// (?:,\s*|$) : カンマと空白、または行末
	// $ : 行末
	// よりシンプルに、「数字とカンマのみで構成され、少なくとも1つの数字が含まれていること」をチェックする。

	// 妥当な行の判定ロジックを正規表現で実現する。
	// 1. 行が空でないこと。
	// 2. 行が数字とカンマのみで構成されていること。
	// 3. 少なくとも1つの数字が含まれていること。

	// 正規表現パターン: 
	// ^\s*                                 # 行頭の空白
	// (?:                                   # 非キャプチャグループ：繰り返しパターン
	//   [0-9]+                              # 1つ以上の数字
	//   (?:,\s*[0-9]+)*                     # カンマとそれに続く空白、数字の繰り返し
	// )
	// (?:,\s*|$)                             # 終了条件：カンマと空白、または行末
	// \s*$                                  # 行末の空白（これは上記でカバーされるが念のため）

	// より厳密に「カンマ区切りの整数列」として定義し、空行や不正文字を排除する。
	// 少なくとも1つの数字とカンマの組み合わせが存在し、それ以外の文字がないことを確認する。
	// 妥当な行は、数字とカンマのみで構成され、かつ数字が1つ以上含まれている。
	// 例: "1,2,3", "1,2,", "1" など
	// 不正な行の例: "", "abc", "1a", "1,,2" (これは許容されるか？仕様では「1個以上の数字列がカンマで区切られて並んでいる」)

	// 仕様解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
	// これは、数字とカンマのシーケンスで構成され、少なくとも1つの数字があることを意味する。
	// 末尾のカンマは許容される。

	// パターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれる。
	// ^\s*                                 # 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*)              # 1つ以上の数字列、それに続くカンマと数字の繰り返し
	// (?:,\s*|\s*$)                          # 終了条件：カンマと空白、または行末
	// \s*$                                 # 行末の空白

	// 簡略化して、行全体が数字とカンマ、空白のみで構成され、数字が含まれていることを確認する。
	// 空行や数字とカンマ以外の文字を含む行は妥当ではない。

	// 妥当な行の定義を再確認:
	// 1. 1個以上の数字列がカンマで区切られている。
	// 2. 末尾のカンマは許容される。
	// 3. 空行、数字とカンマ以外の文字を含む行は妥当ではない。

	// 正規表現: 
	// ^\s*                                 # 行頭の空白
	// (?:                                   # グループ開始
	//   [0-9]+                              # 少なくとも1つの数字
	//   (?:,\s*[0-9]+)*                     # カンマとそれに続く数字の繰り返し（任意）
	// )
	// (?:,\s*|\s*)$                          # 終了条件：カンマと空白、または行末
	// \s*$                                 # 行末の空白

	// この正規表現は「1個以上の数字列がカンマで区切られている」という構造を捉えるのに適しています。
	pattern := regexp.MustCompile(`^\s*(?:[0-9]+(?:,\s*[0-9]+)*)(?:,\s*|\s*)$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 行全体をチェックする（行頭の空白も考慮）
		if pattern.MatchString(line) {
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常、標準入力の読み取り中に発生する可能性）
		// この問題の制約上、ここでは無視して続行するが、厳密にはエラーを報告すべき。
	}

	fmt.Printf("valid=%d\n", validCount)
}
