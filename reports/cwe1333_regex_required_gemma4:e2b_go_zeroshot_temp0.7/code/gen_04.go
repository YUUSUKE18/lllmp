package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// 正規表現パターン:
	// ^             : 行の開始
	// [^,]*         : カンマ以外の任意の文字が0回以上続く (数字とカンマ以外の文字を許容しない)
	// (?:[0-9]+(?:,.*)?)+ : 1個以上の数字列とその後のカンマ（オプション）の繰り返し
	// $             : 行の終了
	// よりシンプルに、「カンマ区切りの整数列」の妥当性を確認するために、
	// 行が数字とカンマのみで構成されていること、かつ少なくとも1つの数字列が含まれていることを確認する。

	// 妥当な行の判定ロジックを正規表現で実現します。
	// 1. 行が空でないこと
	// 2. 行が数字とカンマのみで構成されていること
	// 3. 少なくとも1つの数字列が含まれていること（例: "1,2,3" や "123"）

	// パターン定義:
	// ^\s*             : 行頭の空白を無視
	// (?:               : 非キャプチャグループ開始
	//   [0-9]+         : 1つ以上の数字 (一つの数字列)
	//   (?:,|\s*)?     : その後にカンマまたは空白が続く（オプション）
	// )+                : 上記のパターンが1回以上繰り返される
	// (?:,|\s*)*       : 末尾のカンマや空白を許容（末尾のカンマは許容）
	// $                : 行末
	//
	// 最もシンプルかつ厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを検証するには、
	// 少なくとも一つの数字列が存在し、それらがカンマで区切られている状態をチェックします。

	// 妥当な行の判定用正規表現:
	// ^\s*                : 行頭の空白を無視
	// (?:[0-9]+(?:,|$))* : 1つ以上の数字列とその後のカンマまたは行末が繰り返される。
	//                  これにより、数字列が少なくとも1つ存在することを保証します。
	// \s*$                : 行末の空白を無視
	pattern := regexp.MustCompile(`^\s*(?:[0-9]+(?:,|$))*$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 数字とカンマ以外を含む行のチェックは、正規表現の構造により暗黙的に行われますが、
		// 念のため、数字とカンマ以外の文字が含まれていないかを確認します。
		// 正規表現 `^\s*(?:[0-9]+(?:,|$))*$` は、行が数字とカンマのみで構成されていることを確認します。

		if pattern.MatchString(line) {
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常、標準入力からの読み込み中に発生する可能性がある）
		// この問題のスコープでは無視しても良いが、堅牢性のために残す。
	}

	fmt.Println("valid=", validCount)
}
