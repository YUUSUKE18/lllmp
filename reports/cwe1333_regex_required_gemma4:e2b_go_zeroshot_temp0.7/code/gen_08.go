package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// 正規表現パターン:
	// ^: 行の開始
	// [0-9,]+: 1桁以上の数字またはカンマ（数字とカンマが連続して出現するパターンを許容するため、ここでは厳密に数字とカンマのみを対象とする）
	// ただし、仕様は「1 個以上の数字列がカンマで区切られて並んでいる」ことを求めている。
	// これは、数字とカンマの組み合わせが連続し、全体が数字とカンマのみで構成されている必要がある。
	// 妥当な形式: 1つ以上の数字とカンマの組み合わせ。
	// 例: "1,2,3" または "1,2,"
	// 空行や不正な文字は許容しない。
	// 妥当な行の判定基準: 行が空でない、そして行が数字とカンマのみで構成されていること。
	// より厳密に「1個以上の数字列がカンマで区切られている」ことを正規表現で表現する。
	// 数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
	// \d+ は1つ以上の数字。カンマは区切り文字として機能する。
	// 許容されるパターン: 数字、カンマ、そしてそれらが連続している。
	// 妥当な行の判定: 行が空ではなく、数字とカンマのみで構成されている。
	// 1個以上の数字列がカンマで区切られていることを確認するため、少なくとも1つの数字が存在する。
	// パターン: 1文字以上の数字またはカンマが連続している。
	// \d.*: 数字が1つ以上含まれていることを確認する。
	// [0-9,]*: 数字とカンマのみで構成されていることを確認する。
	// 以下のパターンで判定する:
	// ^[0-9,]+$: 行全体が数字とカンマのみで構成され、1文字以上あること。
	// これが「1個以上の数字列がカンマで区切られている」という条件を間接的に満たすと仮定する。
	// (例: "1,2" は \d, \d のパターンに該当)
	pattern := regexp.MustCompile(`^[0-9,]+$`)

	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())

		// 1. 空行のチェック
		if line == "" {
			continue
		}

		// 2. 数字とカンマ以外を含む行のチェック (正規表現で確認)
		if !pattern.MatchString(line) {
			continue
		}

		// 3. 妥当な行の判定（1個以上の数字列がカンマで区切られているか）
		// 行が数字とカンマのみで構成されている場合、さらに「1個以上の数字列」が存在するか確認する。
		// 少なくとも1つの数字が含まれているかを確認する。
		if regexp.MustCompile(`\d`).MatchString(line) {
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常は無視されるが、堅牢性のために記述）
	}

	fmt.Printf("valid=%d\n", validCount)
}
