package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s*       : 行の先頭の任意の空白
	// (?:       : 非キャプチャグループの開始
	//   \d+    : 1つ以上の数字
	//   ,      : カンマ
	// )*       : 上記のグループが0回以上繰り返される
	// \d+       : 少なくとも1つの数字が後に続くことを保証
	// (?:,\d+)* : カンマで区切られた数字の繰り返し（末尾のカンマも許容するため）
	// $         : 行の終わり
	//
	// よりシンプルに「カンマと数字のみ」で構成され、数字が少なくとも1つ含まれているかをチェックする。
	// 仕様の要求を再解釈すると、「1個以上の数字列がカンマで区切られて並んでいる」
	// これは、カンマで区切られた数字のシーケンスが、数字のみで構成されていることを意味します。
	// 末尾のカンマは許容されます。

	// 正規表現の設計:
	// ^\s*                - 行頭の空白
	// (?:                 - 非キャプチャグループの開始
	//   \d+              - 1つ以上の数字
	//   (?:,\d+)*        - カンマとそれに続く数字の繰り返し（0回以上）
	// )                  - グループの終了
	// (?:,\d+)*           - 最後の要素がカンマで終わる場合に対応（末尾のカンマ許容）
	// \s*$                - 行末の空白
	//
	// 最もシンプルな解釈: 数字とカンマのみで構成され、数字が1つ以上あること。
	// 妥当な行は、数字とカンマのみで構成され、数字が1つ以上ある行。
	// 末尾のカンマは許容される。
	// 例: "1,2,3" や "1,2," は妥当。
	// 例: "abc" や "1,a" は不妥当。
	// 例: "" は不妥当。

	// 妥当な行の判定ロジックを正規表現で表現します。
	// これは、カンマで区切られた数字のシーケンスが、数字とカンマのみで構成されていることを確認します。
	// 1. 少なくとも1つの数字が含まれていること。
	// 2. 数字とカンマ以外の文字が含まれていないこと。
	// 3. 空行は不妥当。

	// 空行のチェックは別途行うか、正規表現でカバーします。
	// 空行や数字とカンマ以外を含む行は不妥当。

	// 妥当なパターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれる。
	// (?:(\d+(?:,\d+)*))  -> 少なくとも1つの数字列（カンマ区切り）
	// (?:,?\d+)*         -> その後に続くカンマ区切りの数字
	// このパターンは複雑になりすぎるため、文字クラスと構造をより厳密に定義します。

	// 妥当な行 = 数字とカンマのみで構成され、数字が少なくとも1つ存在する。
	// ^\s*                                  - 行頭の空白
	// (?:                                    - グループ開始 (数字とカンマのシーケンス)
	//   \d+                                 - 少なくとも1つの数字
	//   (?:,\d+)*                           - カンマと数字の繰り返し (末尾のカンマも含む)
	// )
	// (?:,\d+)*                              - 最後の要素がカンマで終わる場合に対応 (これは上記のグループに含まれるべき)
	//
	// 最終的な正規表現案:
	// ^\s*                                  - 行頭の空白
	// (?:                                    - 妥当な内容のグループ
	//   \d+                                 - 少なくとも1つの数字
	//   (?:,\d+)*                           - カンマ区切りの数字の繰り返し
	//   (?:,\d+)?                           - 最後の要素がカンマで終わる場合に対応
	// )
	// \s*$                                  - 行末の空白
	//
	// 簡略化: 数字とカンマのみで構成され、数字が少なくとも1つあること。
	// 末尾のカンマは許容される。
	// 妥当な行は、数字とカンマの組み合わせのみで構成され、数字が1つ以上あるもの。
	pattern := regexp.MustCompile(`^\s*(\d+(?:,\d+)*)(?:,?\d+)*\s*$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は不妥当
			continue
		}

		// 正規表現を使って判定
		if pattern.MatchString(line) {
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常は無視されるが、堅牢性のために含める）
	}

	fmt.Printf("valid=%d\n", validCount)
}
