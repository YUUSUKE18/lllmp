package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s*          : 行の先頭の任意の空白
	// (?:          : 非キャプチャグループの開始
	//   \d+       : 1つ以上の数字
	//   ,         : カンマ
	// )+           : 上記グループが1回以上繰り返される
	// \d*          : 末尾の数字（カンマがなくても数字列として成立させるため、これは少し調整が必要）
	// 妥当性の定義：「1 個以上の数字列がカンマで区切られて並んでいる」
	// これは、数字とカンマが交互に現れる、または数字のみの列が連続するパターンを許容する。
	// より厳密に「カンマ区切りの整数列」として解釈し、数字とカンマのみで構成されていることを確認する。

	// 妥当な行のパターン:
	// 1. 数字とカンマのみで構成されていること。
	// 2. 空行でないこと。
	// 3. 数字とカンマ以外の文字を含まないこと。
	// 4. 少なくとも1つの数字が含まれていること。

	// 判定ロジックを正規表現で実装する。
	// 妥当な行は、数字(\d+)とカンマ(,)のみで構成され、空行でないもの。
	// 末尾のカンマは許容される。
	// 例: 1,2,3, または 1,2,3,
	// 例: 123, (数字のみ) は許容されるか？仕様は「カンマ区切りの整数列」なので、カンマで区切られていることを重視する。

	// 妥当なパターン: 
	// 1つ以上の数字とカンマの組み合わせが連続している。
	// 許容されるのは、数字とカンマのみで構成され、空行でない場合。
	// (?:[\d,]+) は数字とカンマのみの連続を意味する。
	// ^\s*[\d,]*\s*$ : 行全体が数字とカンマ、空白のみで構成されていることを確認する。
	// 少なくとも1つの数字が含まれていることを確認するために、数字が少なくとも1つあることを要求する。
	// より単純に、行が空でなく、数字とカンマ以外の文字を含まない、という制約を優先する。

	// 妥当な行の判定正規表現:
	// ^\s*                 : 行頭の空白
	// (?:                  : 非キャプチャグループの開始（数字とカンマのセット）
	//   [\d,]+            : 1つ以上の数字またはカンマの並び
	// )
	// \s*$                 : 行末の空白
	// このパターンは、数字とカンマのみで構成されていることを確認する。
	// 少なくとも1つの数字が存在することを保証するため、
	// (?:[\d]+(?:,[\d,]*)*) : 少なくとも1つの数字で始まり、カンマと数字が続くパターン。
	// しかし、末尾のカンマは許容されるため、より緩やかに。

	// 最終的な判定: 行が空でなく、数字とカンマ以外を含まないこと。
	// また、数字が少なくとも1つ存在すること。
	// 正規表現で「数字とカンマのみ」かつ「空でない」ことを確認する。
	// 数字(\d)とカンマ(,)のみを含む文字列が、行全体を構成していることを確認する。
	// \d+.*?: 数字が少なくとも1つあり、その後ろにカンマや数字が続く。

	// 最も安全な判定方法として、行を前処理し、内容をチェックする。
	// 正規表現の使用が必須なので、正規表現で「数字とカンマのみ」をチェックする。
	// (?:[\d,]+) は、数字とカンマが連続していることを意味する。
	// 末尾のカンマは許容されるため、行全体が数字とカンマのみで構成されているかを確認する。
	validRegex := regexp.MustCompile(`^\s*[\d,]*\s*$`)

	for scanner.Scan() {
		line := scanner.Text()
		// 行の前後の空白を無視する処理は、正規表現の ^ と $ でカバーされる。

		if validRegex.MatchString(line) {
			// 空行 (line == "") は validRegex でマッチするが、これは妥当ではない。
			// 空行を排除する必要がある。
			if len(strings.TrimSpace(line)) > 0 {
				// 少なくとも1つの数字が含まれているかを確認する（空行を除く）
				if regexp.MustCompile(`\d`).MatchString(line) {
					validCount++
				}
			}
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（ここでは必須ではないが念のため）
	}

	fmt.Printf("valid=%d\n", validCount)
}
