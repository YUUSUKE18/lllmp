package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列の妥当性を判定するための正規表現
	// ^\s*       : 行の先頭の空白文字
	// (?:       : 非キャプチャグループの開始
	//   \d+    : 1つ以上の数字
	//   ,      : カンマ
	// )*       : 上記のグループが0回以上繰り返される (カンマなしの数字列も許容)
	// \d+      : 少なくとも1つの数字が続くことを保証 (空行でないこと)
	// (?:,\d+)*: カンマで区切られた後の数字列が続くことを許容 (末尾のカンマも許容するため、この構造は少し複雑になる)

	// より単純に、行全体が数字とカンマのみで構成され、空行でないことを確認するアプローチを採用します。
	// 仕様：「1 個以上の数字列がカンマで区切られて並んでいること」
	// これは、カンマで区切られた数字のシーケンス（数字とカンマのみ）で構成されていることを意味します。

	// 妥当な行の判定ロジックを正規表現で実現します。
	// 1. 行が空でないこと。
	// 2. 行が数字とカンマのみで構成されていること。
	// 3. 少なくとも1つの数字が含まれていること。
	// 4. 末尾のカンマは許容される。

	// 正規表現の設計:
	// ^\s*             : 行頭の空白
	// (?:              : 非キャプチャグループ開始 (数字とカンマのシーケンス)
	//   \d+           : 1つ以上の数字
	//   ,?            : 任意の数のカンマ (数字の後にカンマが続くことを許容)
	// )+               : 上記のパターンが1回以上繰り返される (少なくとも1つの数字列が存在する)
	// \d?              : 最後の数字 (末尾のカンマの有無に関わらず、最後に数字があることを確認)
	// (?:,|$)          : 末尾がカンマまたは行末であること (末尾のカンマは許容)
	// \s*$             : 行末の空白
	//
	// 最もシンプルかつ堅牢な判定は、行が空でなく、数字とカンマのみで構成されていることを確認し、
	// 少なくとも1つの数字が含まれていることを確認することです。

	// 妥当な行の判定のための正規表現
	// 1. 行が空でないこと
	// 2. 行が数字とカンマのみで構成されていること (空白を除く)
	// 3. 少なくとも1つの数字が含まれていること
	// 4. 末尾のカンマは許容される。

	// この要件を満たすには、まず前後の空白をトリムし、その後にパターンを適用します。
	// 正規表現で「カンマ区切りの整数列」を表現します。
	// 任意の数の数字とカンマのみで構成され、数字が少なくとも1つ含まれる行。
	// 末尾のカンマは許容されます。

	// 判定のため、行全体を処理します。
	// 行のトリミングと、数字とカンマのみで構成されていることを確認します。
	// 実際には、行が空でなく、数字とカンマ以外の文字を含まないことを確認し、
	// 少なくとも1つの数字が含まれていることを確認します。

	// 行を読み込み、処理
	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 数字とカンマのみで構成されているか、および少なくとも1つの数字が含まれているかを確認する
		// パターン: 数字とカンマのみで構成され、数字が1つ以上存在する
		// 例: "1,2,3", "123", "1,2,"
		// 1. ^[0-9,]*  : 数字とカンマのみで構成されている
		// 2. $         : 行末
		// 3. (?=.*?\d) : 少なくとも1つの数字が含まれている (lookahead)
		// ただし、末尾のカンマを許容するため、より柔軟な方法が必要です。

		// 妥当な行の定義:
		// 1. 数字とカンマ以外の文字を含まない (空白を除く)
		// 2. 少なくとも1つの数字が含まれている
		// 3. 末尾のカンマは許容される。

		// 正規表現で「数字とカンマ」のみで構成されているかを確認し、
		// その後、数字が含まれていることを確認します。
		// 許可される文字: 数字 (0-9) および カンマ (,)
		// 末尾のカンマを許容する。

		// 試行する正規表現:
		// ^[0-9,]*$ : 数字とカンマのみで構成されている (末尾のカンマを含む)
		// (?=.*?\d) : その中に少なくとも1つの数字が含まれている (lookahead)
		pattern := regexp.MustCompile(`^[0-9,]*$`)

		if pattern.MatchString(trimmedLine) {
			// 数字とカンマのみで構成されている
			// さらに、少なくとも1つの数字が含まれているか確認
			if regexp.MustCompile(`\d`).MatchString(trimmedLine) {
				validCount++
			}
		}
	}

	// 結果の出力
	fmt.Println("valid=", validCount)
}
