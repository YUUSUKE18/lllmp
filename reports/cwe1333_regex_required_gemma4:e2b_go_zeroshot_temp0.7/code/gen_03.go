package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s*       : 行の先頭の任意の空白文字
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列、カンマと空白で区切られるパターン。
	//                  これは、数字が1つ以上あり、その後にカンマと空白が続く形式を許容する。
	// \s*$       : 行の末尾の任意の空白文字
	// 厳密には「1個以上の数字列がカンマで区切られて並んでいる」ことをチェックする必要がある。
	// 複数の数字列の間にカンマと空白があることを許容し、末尾のカンマも許容する。

	// 仕様の解釈に基づき、以下の正規表現を使用する。
	// 1. 空行、または数字とカンマ以外の文字を含む行は無効。
	// 2. 1個以上の数字列がカンマで区切られていること。
	// 3. 末尾のカンマは許容。

	// 複数の整数列がカンマで区切られていることを確認するパターン
	// ^\s*                  : 行の先頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列がカンマと空白で区切られているパターン。
	//                         これは、少なくとも1つの数字列が始まり、その後カンマ区切りが続くことを意味する。
	// (?:,\s*[0-9]+)*       : 最後の数字列の後にカンマと空白が続くことを許容する（末尾のカンマも含む）。
	// \s*$                  : 行の末尾の空白

	// よりシンプルに、数字とカンマのみで構成されており、少なくとも1つの数字列が存在することをチェックする。
	// 許容されるパターン: 1,2,3 または 1,2,3, または 1,2,3,
	// これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれている必要がある。
	// 以下の正規表現は、「数字とカンマ」のみで構成され、少なくとも1つの数字列が存在することをチェックします。
	// (?:[0-9]+(?:,\s*[0-9]+)*) は、少なくとも1つの数字列が存在することを保証します。
	pattern := regexp.MustCompile(`^\s*(?:[0-9]+(?:,\s*[0-9]+)*)\s*$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 正規表現で妥当性を判定
		if pattern.MatchString(line) {
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常は無視しても良いが、念のため）
	}

	fmt.Printf("valid=%d\n", validCount)
}
