package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定する正規表現
	// ^\s* は行の先頭の空白を無視
	// (?:[0-9]+(?:,\s*[0-9]+)*) は、1つ以上の数字列がカンマと空白で区切られているパターン
	// $ は行の終わり
	// 末尾のカンマは許容されるため、末尾のカンマを任意で許容する
	// より簡潔に、カンマで区切られた数字のみが含まれていることを確認する
	// 妥当なパターン: 1個以上の数字とカンマの組み合わせ。末尾のカンマは許容。
	// 例: 1,2,3, または 1,2,3,
	// 1. 1,2,3 (妥当)
	// 2. 1,2,3, (妥当)
	// 3. 1, (妥当)
	// 4. ,1 (妥当ではない、数字列が必須)
	// 5. 空行は除外される必要がある
	//
	// 妥当なパターン: 1個以上の数字列がカンマで区切られて並んでいること。
	// 数字列のパターン: [0-9]+
	// 区切り文字: ,
	// 許容されるのは、数字の後にカンマが続く、または行全体が数字とカンマのみで構成されている場合。

	// 正規表現の設計:
	// ^\s*                 - 行頭の空白を無視
	// (?:                  - 非キャプチャグループ開始
	//   [0-9]+             - 1つ以上の数字 (最初の数字列)
	//   (?:,\s*[0-9]+)*    - カンマとそれに続く空白、そしてさらに数字列が0回以上繰り返される
	// )                    - グループ終了
	// (?:,\s*)?             - 末尾のカンマと空白がオプションで続く (末尾のカンマを許容するため)
	// $                    - 行末
	//
	// より単純化し、行が完全に数字とカンマのみで構成されていることを確認し、少なくとも一つの数字列があることを確認する。

	// 妥当な行の定義:
	// 1. 空行でないこと。
	// 2. 数字とカンマのみで構成されていること。
	// 3. 少なくとも1つの数字列が含まれていること。

	// 正規表現: 1つ以上の数字とカンマの組み合わせのみを含むことを確認する。
	// ^\s*                  // 行頭の空白
	// (?:                   // 非キャプチャグループ
	//   [0-9]+             // 1つ以上の数字
	//   (?:,\s*[0-9]+)*    // カンマと数字の繰り返し (カンマで区切られた複数の数字)
	// )
	// (?:,\s*$)             // 末尾にカンマと空白が続く場合も許容 (末尾のカンマ許容のため)
	//
	// 最も厳密に「カンマ区切りの整数列」を定義する:
	// 行が完全に数字、カンマ、空白のみで構成され、少なくとも1つの数字列が含まれている。
	// 末尾のカンマは許容される。

	// パターン: 少なくとも1つの数字列があり、その間にカンマと空白が許容され、末尾にカンマがあっても良い。
	// 1. 数字列 ( [0-9]+ )
	// 2. カンマと空白 ( ,\s* )
	// 3. 末尾のカンマ ( , )

	// 妥当なパターンを判定する正規表現 (行全体が数字とカンマのみで構成されていることを確認)
	// ^\s*
	// (?:[0-9]+(?:,\s*[0-9]+)*)  // 1つ以上の数字列がカンマで区切られているパターン
	// (?:,\s*)?                 // 末尾のカンマを許容
	// \s*$                    // 行末の空白

	// ここでは、行が数字とカンマのみで構成され、少なくとも1つの数字列が含まれていることを確認します。
	// 末尾のカンマが許容されるため、行末は数字、カンマ、空白のいずれかで終わる必要があります。

	// 妥当な行判定用の正規表現 (行全体が数字とカンマのみで構成されていることを確認し、空行は除外されることを別途処理)
	// この問題の制約を厳密に満たすため、まず行をトリムし、その後に正規表現で検証します。

	// 処理対象の行を読み込む
	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 末尾のカンマを許容するため、トリムしてから再度チェックするのではなく、
		// 元の行（空白は無視して）を正規表現で検証する方が安全。
		// ただし、仕様では「行の前後の空白は無視する」とあるため、
		// 判定対象は「カンマ区切りの整数列」そのもの。

		// 行が数字とカンマのみで構成されているか、かつ少なくとも1つの数字列が含まれていることを確認する。
		// 妥当なパターン: 1個以上の数字とカンマの組み合わせ。末尾のカンマは許容。
		// 例: "1,2,3" または "1,2,"

		// パターン: 少なくとも1つの数字列があり、その間にカンマと空白が許容され、末尾にカンマがあっても良い。
		// ^\s*                                 // 行頭の空白
		// (?:                                   // 非キャプチャグループ
		//   [0-9]+                              // 1つ以上の数字
		//   (?:,\s*[0-9]+)*                     // カンマと数字の繰り返し
		// )
		// (?:,\s*)?                             // 末尾のカンマを許容
		// $                                     // 行末
		//
		// 厳密に、カンマ区切りの整数列であるという要件を満たすためには、
		// 1. 行全体が数字とカンマのみで構成されていること。
		// 2. 少なくとも1つの数字列が存在すること。
		// 3. 末尾のカンマは許容されること。

		// 行全体を検証するための正規表現
		// ^\s*                                 // 行頭の空白を無視
		// (?:[0-9]+(?:,\s*[0-9]+)*)             // 1つ以上の数字がカンマで区切られているパターン (例: 1,2,3)
		// (?:,\s*)?                             // 末尾のカンマを許容 (例: 1,2,)
		// \s*$                                 // 行末の空白を無視

		// 以下のパターンは、数字とカンマのみで構成され、少なくとも1つの数字列が存在することを要求します。
		// 厳密な検証のため、行全体を検証します。
		pattern := regexp.MustCompile(`^\s*(?:[0-9]+(?:,\s*[0-9]+)*)(?:,\s*)?$`)

		if pattern.MatchString(line) {
			// 空行でないことを確認済みのため、これは妥当である
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常は不要だが、安全のため）
	}

	// 結果を出力
	fmt.Printf("valid=%d\n", validCount)
}
