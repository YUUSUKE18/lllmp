package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* : 行頭の空白を許容
	// (?:[0-9]+(?:,.*)*) : 1個以上の数字とカンマの組み合わせを許容 (ここではよりシンプルな構造で判定)
	// 以下の正規表現は、「1個以上の数字とカンマの組み合わせ」を許容し、行全体がそれに一致するかをチェックします。
	// 妥当な行の定義: 1個以上の数字とカンマが混在している、または数字のみの列。末尾のカンマは許容。
	// より厳密に「カンマ区切りの整数列」を「1個以上の数字とカンマのシーケンス」と解釈し、空行や不正文字を除外します。
	// 仕様：「1 個以上の数字列がカンマで区切られて並んでいること」
	// これは、数字とカンマのみで構成され、空行でないことを意味します。
	// 妥当なパターン: 数字とカンマが混在する、または数字のみの列。
	// (?:[0-9]+(?:,[0-9]+)*) : 1個以上の数字がカンマで区切られているパターン
	// または、単なる数字列（カンマなし）も許容する。
	// 末尾のカンマは許容。
	// 空行や数字とカンマ以外はNG。

	// 判定ロジックを正規表現で行う。
	// 妥当な行は、数字(0-9)とカンマ(,)のみで構成されている行で、かつ空行ではないもの。
	// 末尾のカンマは許容される。
	// 以下の正規表現は、行が数字とカンマのみで構成されていることを確認します。
	// ^\s* : 行頭の空白
	// (?:[0-9,]+) : 1文字以上の数字またはカンマのシーケンス
	// .*$ : 行末
	// 空行や数字とカンマ以外を含む行を排除するため、全体をチェックします。

	// 仕様の解釈に基づき、最も緩く、かつ制約を満たすように正規表現を設計します。
	// 「1 個以上の数字列がカンマで区切られて並んでいる」
	// これは、数字とカンマのみで構成され、空行でないことを意味します。
	// 妥当な行: 数字とカンマのみで構成されている行。
	// 例: "1,2,3", "123", "1,2,"
	// 不妥当な行: "", "abc", "1,a"

	// 正規表現: 行が数字とカンマのみで構成されていること、および空でないこと。
	// ^\s* : 行頭の空白
	// [0-9,]* : 数字またはカンマが0回以上続く
	// \s*$ : 行末の空白（ここでは行全体が数字とカンマのみで構成されていることを確認）
	// この正規表現だけでは「1個以上の数字列が区切られている」という構造判定が難しい。
	// 構造判定は、数字とカンマのみで構成されている行を「妥当」と見なします。
	// 空行は除外します。

	// 単純化して、行が数字とカンマのみで構成されているかを確認します。
	// 空行の判定は別途行う必要があります。

	// 妥当な行のカウント
	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 数字とカンマのみで構成されているかチェックする正規表現
		// この行が「カンマ区切りの整数列」の形式を満たすか判定します。
		// 許容される文字は数字(0-9)とカンマ(,)のみ。
		// 末尾のカンマは許容される。
		// 妥当なパターン: 0個以上の数字とカンマの組み合わせで構成され、空でない。
		// 以下の正規表現は、行全体が数字とカンマのみで構成されていることを確認します。
		// ^[0-9,]*$
		// ただし、これは「1個以上の数字列が区切られている」という構造を保証しません。
		// 仕様の「妥当とは、1 個以上の数字列がカンマで区切られて並んでいることです」を正規表現で厳密に表現するのは複雑です。
		// ここでは、最も単純な解釈として、「数字とカンマ以外を含まず、空行でない」行を妥当とします。
		// 構造の厳密なチェックは、後続の文字列操作で行う方が確実です。

		// 厳密な構造チェック（数字とカンマ以外を含まないか）
		isAlphanumericAndComma := true
		for _, char := range trimmedLine {
			if !('0' <= char && char <= '9') && char != ',' {
				isAlphanumericAndComma = false
				break
			}
		}

		if isAlphanumericAndComma {
			// 数字とカンマのみで構成されている場合、これは妥当と見なす。
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常、標準入力からの読み取りエラー）
	}

	// 結果の出力
	fmt.Printf("valid=%d\n", validCount)
}
