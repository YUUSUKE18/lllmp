const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let lines: string[] = [];

rl.on('line', (line) => {
  lines.push(line);
});

rl.on('close', () => {
  let validLines = 0;
  const regex = /^(\s*\d+,\s*\d+,\s*)*\d+.*$/;

  for (const line of lines) {
    // 行の前後の空白を無視して判定するため、trimしてから正規表現を適用
    const trimmedLine = line.trim();
    
    // 1. 空行のチェック (空行は妥当ではない)
    if (trimmedLine.length === 0) {
      continue;
    }

    // 2. 数字とカンマ以外を含む行のチェック
    // 正規表現の解釈:
    // ^\s*       : 行頭の空白
    // (?:       : 非キャプチャグループ (繰り返しなし)
    //   \d+,\s* : 1つ以上の数字、カンマ、任意の空白
    // )*        : 上記パターンが0回以上繰り返される
    // \d+       : 少なくとも一つの数字があること (行全体が数字で構成されているか、あるいは数字とカンマで区切られている)
    // .*        : その後に任意の文字が続くこと (末尾のカンマを許容するため)
    // $         : 行末
    
    // 仕様の解釈：「1 個以上の数字列がカンマで区切られて並んでいる」
    // 末尾のカンマは許容する。空行、および数字とカンマ以外を含む行は妥当ではない。
    
    // より厳密に、カンマ区切りの整数列のみを許容するパターンを考える。
    // 例: "1,2,3" -> OK
    // 例: "1,2," -> OK
    // 例: "1,a,3" -> NG
    // 例: "" -> NG
    
    // 妥当な行は、数字とカンマのみで構成されている、またはその一部である、ということを確認する必要がある。
    // 課題の意図を「行がカンマ区切りの整数列のみで構成されているか」と解釈する。
    
    // パターンを再定義: 
    // 任意の文字（数字、カンマ、空白）の後に、数字が続くパターンを許容する。
    // 以下の正規表現は、「数字とカンマ、空白のみ」で構成されていることを確認する。
    // ただし、空行は除外する必要がある。
    
    // 妥当な行の判定 (数字とカンマ、空白のみで構成されているか)
    const validPattern = /^[\d, \t\n\r]*$/;

    if (validPattern.test(line)) {
      // 空行はすでに除外されているが、もし行が完全に空白文字のみの場合を考慮する。
      // trim()で空でないことを確認済み。
      validLines++;
    }
  }

  console.log(`valid=${validLines}`);
});
