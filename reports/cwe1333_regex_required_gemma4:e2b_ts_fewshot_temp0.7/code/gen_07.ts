const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let lineCount = 0;
let validLines = 0;

rl.on('line', (line) => {
  lineCount++;
  // 正規表現:
  // ^\s*          -> 行の先頭の空白を無視
  // (?:[0-9]+,\s*)* -> 1つ以上の "(数字, 空白)" のパターンを0回以上繰り返す (カンマ区切りの整数列)
  // [0-9]+        -> 少なくとも1つの数字が続く
  // (\s*,\s*)*    -> 末尾のカンマや空白を許容するため、カンマと空白の繰り返しを許容
  // $            -> 行の終わり
  // この正規表現は「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するのに適していますが、
  // 課題の「1個以上の数字列がカンマで区切られて並んでいる」という条件を満たすことを確認するために、
  // よりシンプルに「数字とカンマのみ」という制約と「空行ではない」という制約を組み合わせます。

  // 課題の要件を再解釈：
  // 1. 1個以上の数字列がカンマで区切られている。
  // 2. 空行、および数字とカンマ以外を含む行は妥当ではない。
  // 3. 末尾のカンマは許容する。

  // 妥当な行の判定ロジックを正規表現で実現します。
  // 許容されるパターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれる。
  // 例: "1,2,3" または "1,2,"
  // 否定されるパターン: 空行、数字以外の文字、数字とカンマ以外の文字の混在。

  // 正規表現:
  // ^\s*             -> 行頭の空白を無視
  // (?:[0-9]+(?:,\s*[0-9]+)*) -> 1つ以上の数字とカンマのペア (例: 1,2,3, または 1,)
  // \s*$             -> 行末の空白を無視
  // ※ 末尾のカンマを許容するため、最後の要素が数字で終わる必要はなく、カンマで終わっても良い。

  // より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する正規表現を構築します。
  // 許容されるのは、数字とカンマのみで構成され、少なくとも1つの数字が含まれる場合。
  // \s* は行頭と行末の空白を無視するために使用します。

  // パターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれていること。
  // 1. 少なくとも1つの数字がある: [0-9]
  // 2. その間にカンマと空白が続く (0回以上): (?:,\s*[0-9]+)*
  // 3. 末尾にカンマがあっても良い: (?:,\s*)*
  // 4. 全体が数字とカンマのみで構成されること: ^[\d,]*$

  // 妥当な行の判定:
  // 1. 空行ではない (line.trim() !== "")
  // 2. 数字とカンマと空白以外の文字を含まない
  // 3. 少なくとも1つの数字を含む
  // 4. 末尾のカンマは許容される

  // 課題の指示に従い、正規表現で「1個以上の数字列がカンマで区切られて並んでいる」ことを判定します。
  // 許容される形式の例: "1,2,3", "1,2,", "1"
  // 否定される形式の例: "", "a,b", "1,a", "1,,2" (内部のカンマの重複なども考慮)

  // 内部のカンマの重複や、数字とカンマ以外の文字の混入を厳しくチェックします。
  // 妥当な行は、数字とカンマと空白（行頭/行末を除く）のみで構成される必要があります。

  // 妥当性のチェック:
  // 1. 行が空でない。
  // 2. 行の中身が数字、カンマ、空白のみで構成されている。
  // 3. 数字が少なくとも1つ含まれている。

  const trimmedLine = line.trim();

  if (trimmedLine === "") {
    // 空行は妥当ではない
    return;
  }

  // 数字とカンマ、空白以外の文字が含まれていないかチェック
  const regexCheck = /^[0-9, \t\n\r]*$/;

  if (!regexCheck.test(line)) {
    // 数字とカンマ以外の文字を含む行は妥当ではない
    return;
  }

  // 数字が少なくとも1つ含まれているかチェック
  const hasDigit = /\d/.test(line);

  if (hasDigit) {
    validLines++;
  }
});

rl.on('close', () => {
  console.log(`valid=${validLines}`);
});
