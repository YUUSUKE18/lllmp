const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let lines: string[] = [];

rl.on('line', (line) => {
  lines.push(line);
});

rl.on('close', () => {
  let validLines = 0;
  const regex = /^[\d,]+(?:,[\d,]+)*$|^[\d,]+(?:,[\d,]+)*,$/;

  for (const line of lines) {
    const trimmedLine = line.trim();
    if (trimmedLine === "") {
      continue; // 空行は妥当ではないが、ここでは行数を数えるためスキップ
    }

    // 末尾のカンマを含むパターン、またはカンマで区切られた数字列のパターンをチェック
    // 妥当なパターン: 1個以上の数字とカンマの組み合わせ。末尾のカンマは許容される。
    // 正規表現の解説:
    // ^[\d,]+ : 行の先頭から数字またはカンマが1回以上続く
    // (?:,[\d,]+)* : カンマと数字のグループが0回以上繰り返される
    // $ : 行の終わり
    // 末尾のカンマの許容: 
    // 1. 完全に数字とカンマのみで構成されている場合 (例: 1,2,3)
    // 2. 末尾がカンマで終わる場合 (例: 1,2,3,)
    
    // 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを検証する。
    // これは、数字とカンマのみで構成されており、数字が少なくとも1つ含まれている必要がある。
    // 末尾のカンマは許容される。
    
    // 許容されるパターン: 
    // 1. 数字とカンマのみで構成され、数字が1つ以上ある。
    // 2. 最後にカンマがある場合。
    
    // 簡略化して、数字とカンマのみで構成され、空でないことを確認する。
    // 妥当な入力: "1,2,3" または "1,2,3,"
    const isValid = /^[0-9,]+(?:,[0-9,]+)*(\,?)$/.test(line);
    
    // さらに厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェック
    // このパターンは、数字とカンマのみで構成され、数字が少なくとも1つ含まれていることを確認する。
    // 例: "1,2,3" -> OK
    // 例: "1," -> OK (末尾カンマ許容)
    // 例: "," -> NG (数字が1つ以上必要)
    
    let actualValid = false;
    if (trimmedLine.length > 0) {
        // 数字とカンマのみで構成されているか確認
        if (/^[\d,]+$/.test(trimmedLine)) {
            // 数字とカンマのみで構成されている場合、カンマの有無をチェック
            if (trimmedLine.includes(',')) {
                // カンマが含まれていれば、区切りがある（1個以上の数字列）
                actualValid = true;
            } else if (trimmedLine.length > 0) {
                // カンマがなく、数字のみの場合（例: "123"）
                // これは「1個以上の数字列がカンマで区切られて並んでいる」の定義に厳密には合わないが、
                // 仕様を「1個以上の数字列がカンマで区切られて並んでいる」と解釈し、カンマが必須ではないケースも考慮する。
                // しかし、例示された入力形式から、カンマ区切りが前提と考える。
                // 厳密には、区切り文字（カンマ）が存在するか、または末尾カンマが存在する場合を許容する。
                
                // 仕様: 「1 個以上の数字列がカンマで区切られて並んでいる」
                // "123" は区切られていないため、ここではNGとする。
                actualValid = false; // カンマがない場合は不適
            }
        }
    }
    
    // 正規表現で再度判定を試みる。末尾のカンマは許容される。
    // 妥当なのは、数字とカンマのみで構成され、かつ、少なくとも1つの数字が含まれている場合。
    // パターン: (数字, カンマの繰り返し) + (オプションの末尾カンマ)
    // (?:[\d]+(?:,[\d]+)*) : 1個以上の数字列がカンマで区切られているパターン
    // |
    // ([\d]+)(?:,[\d]+)*, : 最後の要素の後にカンマがあるパターン
    
    // 最もシンプルな解釈: 数字とカンマのみで構成され、空行でないこと。
    // 妥当な行は、数字とカンマのみで構成され、かつ、数字が含まれている。
    // 妥当な行の例: "1,2,3", "1,2,"
    
    // 正規表現の再定義: 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
    const finalRegex = /^[\d,]+(?:,[\d,]+)*(\,?)$/;
    
    if (trimmedLine.length > 0 && finalRegex.test(line)) {
        // 最後の要素が数字で終わる場合 (例: "1,2,3")
        // または最後の要素がカンマで終わる場合 (例: "1,2,3,")
        validLines++;
    }
  }

  console.log(`valid=${validLines}`);
});
