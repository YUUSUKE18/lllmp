const data: Buffer[] = [];
process.stdin.on("data", (c: Buffer) => data.push(c));
process.stdin.on("end", () => {
  const input = Buffer.concat(data).toString("utf8");
  const lines = input.split('\n');
  let validLines = 0;

  // 各行を検証
  for (const line of lines) {
    const trimmedLine = line.trim();

    // 空行の場合は妥当ではない
    if (trimmedLine === "") {
      continue;
    }

    // 正規表現で検証:
    // ^: 行の開始
    // [0-9,]*: 数字またはカンマが0回以上続く
    // $: 行の終了
    // 末尾のカンマは許容されるため、行全体が数字とカンマのみで構成されていることを確認する。
    // 厳密には「1個以上の数字列がカンマで区切られている」ことを検証する必要がある。
    // これは、行がカンマで区切られた数字の集合であることを意味する。
    
    // 許容されるパターン: 数字とカンマのみで構成されていること。
    // 末尾のカンマは許容される。
    // 例: "1,2,3" -> OK, "1,2," -> OK, "1,2,3," -> OK
    // 例: "1,a" -> NG
    // 例: "1,,2" -> NG (連続するカンマはNG、または空の要素を許容しない)
    
    // 「1個以上の数字列がカンマで区切られて並んでいる」という条件を正規表現で表現する。
    // 少なくとも1つの数字が存在し、それらがカンマで区切られている。
    // 数字とカンマのみで構成され、かつ少なくとも1つの数字が含まれていることを確認する。
    
    // パターン: (数字, カンマ, 数字)+ または (数字, カンマ, 数字)* の形。
    // 最も単純な解釈として、「カンマで区切られた要素がすべて数字である」ことを確認する。
    // 末尾のカンマは許容される。
    // 1. 数字とカンマのみで構成されているか？
    // 2. 少なくとも1つの数字が含まれているか？
    
    // 正規表現の定義:
    // ^[0-9,]*$: 数字とカンマのみで構成される。
    // 少なくとも1つの数字が含まれていることを別途チェックする。
    
    const match = line.match(/^[0-9,]*$/);
    
    if (match) {
      // 数字とカンマのみで構成されている
      let hasDigit = false;
      for (const char of line) {
        if (/\d/.test(char)) {
          hasDigit = true;
          break;
        }
      }
      // 少なくとも1つの数字が含まれているか？
      if (hasDigit) {
        validLines++;
      }
    }
  }

  console.log(`valid=${validLines}`);
});
