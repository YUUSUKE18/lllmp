const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  terminal: false
});

let lines: string[] = [];

rl.on('line', (line) => {
  lines.push(line);
});

rl.on('close', () => {
  let validCount = 0;
  const regex = /^[\d,]*,\s*[\d,]+.*$/;

  for (const line of lines) {
    const trimmedLine = line.trim();

    // 1. 空行のチェック
    if (trimmedLine === "") {
      continue;
    }

    // 2. 数字とカンマ以外を含む行のチェック (正規表現での判定)
    // 仕様: 1個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容。
    // 正規表現の解釈:
    // ^                  : 行の先頭
    // [\d,]*             : 0個以上の数字またはカンマ
    // (?:,[\d,]+)*       : カンマと1個以上の数字/カンマのグループが0回以上繰り返される (区切りと数字のセット)
    // [\d,]*             : 末尾の数字/カンマ
    // $                  : 行の終わり

    // より簡潔に、行が「数字とカンマ」のみで構成されているかを確認し、区切りがあることを確認する。
    // 求められているのは「1個以上の数字列がカンマで区切られている」こと。
    // 空白は無視されるため、行全体が数字とカンマのみで構成されているかを確認する。

    // 1. 数字とカンマ以外が含まれていないか確認（空白は無視されるため、トリム後の文字列をチェック）
    if (!/^[0-9,]*$/.test(trimmedLine)) {
      continue; // 数字とカンマ以外が含まれている場合は妥当ではない
    }

    // 2. 1個以上の数字列がカンマで区切られているか確認
    // 末尾のカンマは許容される。
    // 正規表現の調整: 
    // 1つ以上の数字列がカンマで区切られている。
    // 可能なパターン例: "1,2,3", "1,2,"
    // 最小単位は数字のまとまり。
    
    // カンマで区切られた要素が少なくとも1つ存在することを検証する。
    // 末尾のカンマが許容されるため、行が完全に空でないことと、数字/カンマのみで構成されていることを確認する。

    // 妥当な行の判定ロジックを再検討:
    // 「1個以上の数字列がカンマで区切られて並んでいる」
    // 例: "1,2,3" -> 妥当 (3つの数字列)
    // 例: "1," -> 妥当 (1つの数字列と末尾のカンマ)
    // 例: "," -> 不妥 (数字列が0個)
    // 例: "abc" -> 不妥 (数字とカンマ以外)

    // 妥当な行は、カンマで区切られた要素が少なくとも1つ以上存在し、全体が数字とカンマのみで構成されている。
    
    // 行全体を整形し、カンマで分割して、空でない要素が1つ以上あるか確認する。
    const parts = line.split(',').map(p => p.trim());
    
    // 空行は既に除外されている (trimmedLine === "" のチェックが先にあるため)
    if (parts.length === 0) {
        continue;
    }

    // 1. 数字とカンマ以外が含まれていないか (トリム後の行全体が数字とカンマのみで構成されているか)
    // これは、元の行が数字とカンマのみで構成されていることを確認する。
    if (!/^[0-9,]*$/.test(line)) {
        continue;
    }

    // 2. 1個以上の数字列がカンマで区切られているか
    // 少なくとも1つの要素（数字列）が存在すれば良い。
    // 例: "1," -> split(',') -> ["1", ""] -> parts.length=2。最初の要素は "1"。OK。
    // 例: "," -> split(',') -> ["", ""] -> parts.length=2。最初の要素は ""。NG。
    
    // 空の要素が1つ以上あれば、それはカンマが連続しているか、行がカンマのみになっていることを示唆する。
    // 妥当な行は、カンマで区切られた要素のうち、少なくとも1つが数字を含む必要がある。
    
    let hasNumber = false;
    for (const part of parts) {
        if (part !== "") {
            // 数字列のみを含むか、数字とカンマのみを含むかを確認
            if (/^\d+$/.test(part)) {
                hasNumber = true;
            } else if (/^[\d,]+$/.test(part)) {
                 // 数字とカンマの組み合わせ（例: "1,2" の場合、split(',')で得られる要素がこれに該当する）
                 // ここでは、行全体が「カンマ区切りの整数列」として妥当であるかを判定する。
                 // 整数列がカンマで区切られている、という条件を満たすか。
                 // 末尾のカンマは許容される。
                 
                 // 妥当なパターン: 少なくとも1つの数字列が存在し、行が数字とカンマのみで構成されている。
                 // 1. "1,2" -> parts=["1", "2"]. hasNumber=true. OK.
                 // 2. "1," -> parts=["1", ""]. hasNumber=true. OK.
                 // 3. "," -> parts=["", ""]. hasNumber=false. NG.
            }
        }
    }

    // 最もシンプルな判定: カンマで区切った要素が1つ以上あり、かつ、その要素が数字列を構成していることを確認する。
    // 行が空でなく、カンマで区切られた要素の数が1以上、かつ、数字が含まれていることを確認する。
    
    // 再度、行全体をチェックする。
    // 行が数字とカンマのみで構成されており、かつカンマが含まれているか、または数字が1つ以上存在している。
    
    // 妥当な行の定義を「1個以上の数字列がカンマで区切られている」に厳密に従う。
    // 区切り文字がカンマであるため、空の要素（""）が複数連続する場合、それは区切りとして機能している。
    // 妥当なのは、数字のまとまりが1つ以上存在し、それがカンマで区切られている場合。
    
    // 最小の妥当な例: "1" (カンマなしも許容されるか？「カンマで区切られて並んでいる」なので、カンマが最低1つ必要か？)
    // 「1個以上の数字列がカンマで区切られて並んでいる」
    // "1" は0個のカンマで区切られているため、厳密には不適。
    // "1," は1個の数字列と1個の空文字列で区切られている。
    
    // 最終的な判定: 行が空文字列でなく、数字とカンマのみで構成されており、カンマが存在する（または数字が複数存在）こと。
    
    let actualValid = false;
    if (parts.length > 0) {
        // 少なくとも1つの要素が数字で構成されているかチェック
        for (const part of parts) {
            if (/^\d+$/.test(part)) {
                actualValid = true;
                break;
            }
        }
    }


    if (actualValid) {
        validCount++;
    }
  }

  console.log(`valid=${validCount}`);
});
