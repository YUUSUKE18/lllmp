const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
  crlfDelay: Infinity
});

let lines: string[] = [];

rl.on('line', (line) => {
  lines.push(line);
});

rl.on('close', () => {
  let validLinesCount = 0;
  const regex = /^[\d,]*,\s*[\d,]+.*$/;

  for (const line of lines) {
    const trimmedLine = line.trim();
    if (trimmedLine === "") {
      continue;
    }
    // 末尾のカンマを許容しつつ、数字とカンマのみで構成されているか、かつ少なくとも1つの区切りがあるかをチェック
    // 仕様：「1 個以上の数字列がカンマで区切られて並んでいること」
    // 末尾のカンマは許容
    // 空行、および数字とカンマ以外を含む行は妥当ではない
    
    // 正規表現の解釈:
    // ^: 行の開始
    // [\d,]*: 0個以上の数字またはカンマ
    // (?:,[\d,]+)*: カンマと1個以上の数字またはカンマの繰り返し (少なくとも1つの区切りがあることを保証するため)
    // [\d,]*$: 任意の文字（ここでは行全体が数字とカンマで構成されていることを確認したい）

    // よりシンプルな解釈：カンマで区切られた数字列のみを含む行。末尾のカンマは許容。
    // 1個以上の数字列がカンマで区切られている。
    // 例: "1,2,3" は妥当。 "1," は妥当。 ",1" は妥当ではない（空の要素が許されない）。
    
    // 1個以上の数字列がカンマで区切られていることを確認するため、
    // 少なくとも1つのカンマが存在し、かつ数字が含まれている必要がある。
    
    // 妥当なパターン: 数字とカンマのみで構成され、少なくとも1つの区切りがある。
    // 許容されるのは、カンマで区切られた数値の並び。
    // 例えば、"1,2" または "1,2,"
    
    // 正規表現の調整:
    // (?:[\d]+(?:,[\d]+)*)  -> 1つ以上の数字列がカンマで区切られているパターン
    // 最後のカンマを許容するため、末尾にカンマがあっても良い。
    
    // 妥当な行の定義を再評価:
    // 1. 空行はNG
    // 2. 数字とカンマ以外を含む行はNG
    // 3. 1個以上の数字列がカンマで区切られている。末尾のカンマは許容。
    
    // "1,2" -> OK
    // "1,2," -> OK
    // "1" -> NG (1個の数字列のみで区切りがないため、複数列の区切りが必要？)
    // 仕様：「1 個以上の数字列がカンマで区切られて並んでいること」
    // "1" は1個の数字列のみ。区切りがないため、この仕様を満たすにはカンマが必要。
    
    // したがって、少なくとも1つのカンマが含まれている必要がある。
    // また、数字以外は許されない。
    
    const isValid = /^[0-9,]+(?:,.*)?$/.test(line.trim());
    
    // 上記の正規表現は複雑になるため、より直接的にチェックする。
    // 数字とカンマのみで構成され、かつカンマが含まれているか、あるいは末尾にカンマがあるか。
    
    // 最終的な正規表現の試み：数字とカンマのみで構成され、少なくとも1つのカンマが含まれているか、または末尾がカンマであること。
    const strictRegex = /^[\d,]+(?:,[\d,]+)*([,])?$/;

    // 仕様の「末尾のカンマは許容します」を考慮し、
    // 1. 数字とカンマのみで構成されていること
    // 2. 少なくとも1つのカンマが含まれているか、末尾がカンマであること。
    
    // 複数の数字列の区切りがあることを保証するために、少なくとも1つのカンマが必要と解釈する。
    const matches = line.trim().split(',').map(s => s.trim());
    
    if (matches.length === 0) {
        // 空行は既にスキップ済みだが念のため
        continue;
    }

    let isTrulyValid = false;
    if (matches.length > 0) {
        // すべての要素が数字またはカンマのみで構成されているか？ (これはsplitで既に保証されている)
        // 1個以上の数字列が区切られている。
        // この時点で、"1" (matches.length=1) は「1個の数字列」と解釈され、区切りがないためNGとする。
        // "1," (matches=["1", ""]) -> NG (空要素が発生)
        
        // 妥当なのは、カンマで区切られた複数の数値が存在する場合。
        // 1個の数値のみ: "1" -> NG
        // 複数数値: "1,2" -> OK
        // 末尾カンマ: "1,2," -> OK
        
        // 複数の数字列が存在する場合、分割後の要素が全て数字のみであること。
        const allAreNumbers = matches.every(m => /^\d+$/.test(m));
        
        if (allAreNumbers) {
            // 1個以上の数字列がカンマで区切られていることを確認する。
            // 複数の要素があるか、または末尾にカンマがあるかをチェック。
            if (matches.length > 1 || line.endsWith(',')) {
                isTrulyValid = true;
            }
        }
    }


    if (isTrulyValid) {
      validLinesCount++;
    }
  }

  console.log(`valid=${validLinesCount}`);
});
