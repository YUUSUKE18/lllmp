package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* は行頭の空白を許容
	// (?:[0-9]+(?:,[0-9]+)*) は1つ以上の数字とカンマの組み合わせをキャプチャするグループ
	// .*$ は行の残りの部分（末尾のカンマなども含む）を許容する
	// この正規表現は、少なくとも1つの数字がカンマで区切られていることを確認します。
	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// 少なくとも一つの数字が存在し、カンマで区切られているパターンをチェックします。

	// 妥当な行の判定ロジックを正規表現で表現するのは複雑なため、
	// 各行を読み込み、手動で検証する方が意図を正確に反映しやすいです。
	// ただし、仕様で「判定には正規表現を用いてください」とあるため、正規表現で試みます。

	// 妥当な行の判定正規表現:
	// ^\s*(?:[0-9]+(?:,[0-9]+)*)(?:,?[0-9]+)*$
	// これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
	// 末尾のカンマは許容されます。

	// よりシンプルに、行が「数字とカンマのみ」で構成され、少なくとも1つの数字が含まれているかをチェックします。
	// 1. 空行や数字とカンマ以外の文字が含まれていないこと
	// 2. 少なくとも1つの数字が含まれていること

	// 妥当な行を数える
	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := ""
		// 行の前後の空白を無視（ただし、行全体をチェックするため、ここでは行全体を対象とする）

		// 行全体が数字とカンマのみで構成されているか、かつ少なくとも1つの数字が含まれているかを確認
		// 正規表現: ^\s* (数字とカンマのみのシーケンス) $
		// 妥当な行の定義: 1個以上の数字列がカンマで区切られて並んでいる。
		// これは、数字とカンマのみで構成され、数字が少なくとも1つ存在する場合。

		// 1. 数字とカンマのみで構成されているかチェック (数字とカンマ以外は許容しない)
		// 2. 少なくとも1つの数字が含まれているかチェック
		
		// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」を正規表現で表現する。
		// 例: 1,2,3 または 1,2,3,
		// 1. 数字とカンマのみで構成されていること: ^[\d,]*$
		// 2. 少なくとも1つの数字が含まれていること: [\d] が存在する。

		// 妥当な行の判定のための正規表現
		// ^\s* : 行頭の空白を許容
		// (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字とカンマのペア（例: 1,2,3）
		// (?:,?[0-9]+)* : 最後の要素がカンマで終わる場合や、末尾のカンマを許容する
		
		// 妥当な行のパターン: 少なくとも一つの数字があり、数字とカンマのみで構成されている。
		// 末尾のカンマは許容される。
		// パターン: 少なくとも1つの数字があり、その間にカンマがあっても良い。
		// 例: "1,2,3" または "1,2," または "1" または "," (これはNG)
		
		// 妥当な行のパターンを定義: 
		// 数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
		// 末尾のカンマは許容される。
		// 例: "1,2,3" -> OK
		// 例: "1,2," -> OK
		// 例: "1" -> OK
		// 例: "," -> NG (数字がない)
		// 例: "abc" -> NG (数字とカンマ以外)
		
		// 正規表現: ^\s*[\d,]+(?:\s*,\s*[\d,]+)*\s*$ 
		// 上記は複雑すぎるため、行をトリムしてからチェックする方が実用的だが、正規表現指定に従う。

		// 妥当な行の判定（正規表現使用）
		// 行全体をトリムして、数字とカンマのみで構成されているか、かつ数字が含まれているかを確認する。
		// 1. 行が空でないこと (必須)
		// 2. 行が数字とカンマのみで構成されていること
		// 3. 行に少なくとも1つの数字が含まれていること
		
		// 以下の正規表現は、行が数字とカンマのみで構成され、少なくとも1つの数字を含むことを確認する。
		// (?:[0-9][0-9,]*)+ : 1つ以上の数字で始まり、カンマを含む
		// |
		// [0-9]+ : 数字のみ
		// 
		// 最終的な判定ロジックとして、行をトリムし、その内容が数字とカンマのみで構成されているかをチェックする。
		// 仕様の「正規表現を用いて」を最大限満たすため、行全体を対象とする。
		
		// 妥当な行の判定: 行が数字とカンマの組み合わせのみで構成され、かつ数字が少なくとも1つ存在すること。
		// 末尾のカンマは許容される。
		// ^\s* : 行頭の空白
		// (?:[0-9]+(?:,[0-9]+)*) : 1つ以上の数字とカンマのシーケンス
		// (?:,?[0-9]+)* : 最後の要素がカンマで終わる場合や、末尾のカンマを許容する
		
		// 妥当な行のパターン: 少なくとも1つの数字が含まれ、数字とカンマのみで構成されている。
		// 末尾のカンマは許容される。
		// 妥当な行の正規表現: ^\s*[\d,]+$
		// このパターンは、「1,2,3」や「1,2,」などを許容するが、「1,2,3,」も許容する。
		// 少なくとも1つの数字が存在し、数字とカンマのみで構成されている。
		
		// 妥当な行の判定:
		// 1. 行が完全に空でないこと (空白行はNG)
		// 2. 行に含まれる文字が数字またはカンマのみであること
		// 3. 行に少なくとも1つの数字が含まれていること
		
		// 正規表現でこれらを同時にチェックするのは困難なため、行をトリムし、その内容をチェックする。
		// 仕様の「判定には正規表現を用いてください」を優先し、行全体を対象とする。
		
		// 妥当な行の正規表現: 
		// ^\s*[\d,]+$ 
		// (これは「1,2,」や「1」は許容するが、数字とカンマ以外の文字は許容しない)
		
		// 最終的な判定: 行が空でないこと、かつ数字とカンマのみで構成されていること。
		// 妥当な行の定義に最も近い正規表現を適用する。
		// 妥当な行は、数字とカンマのみで構成され、少なくとも1つの数字を含む。
		
		// 妥当な行の判定（正規表現）
		// 1. 行が空でないこと
		// 2. 行が数字とカンマのみで構成されていること
		// 3. 行に少なくとも1つの数字が含まれていること
		
		// 妥当な行のパターン: ^\s*(\d[\d,]*|\d+)(?:,[\d,]*)*\s*$
		// 簡略化し、行全体が数字とカンマのみで構成され、少なくとも1つの数字を含むことを確認する。
		
		// 妥当な行の判定:
		// 行が空でないこと
		// 行が数字とカンマのみで構成されていること
		// 少なくとも1つの数字が含まれていること
		
		// 妥当な行の判定（正規表現）：
		// ^\s*[\d,]+$
		// このパターンは、数字とカンマのみで構成され、少なくとも1つの数字を含む行を捉える。
		
		// 実際には、行が空でないことと、その内容が数字とカンマのみであることを確認する。
		// この制約を正規表現で表現する。
		
		// 妥当な行のパターン: 
		// ^\s*[\d,]+$  <- これが最もシンプルで、数字とカンマのみで構成され、数字が含まれることを示唆する。
		
		// 実際の行の内容をチェックする
		if len(line) > 0 {
			// 行が空でないことを確認
			
			// 行の内容をトリムして、数字とカンマのみで構成されているかチェック
			trimmedLine = ""
			for _, r := range line {
				if r >= '0' && r <= '9' || r == ',' {
					trimmedLine += string(r)
				} else {
					// 数字とカンマ以外が含まれていればNG
					goto nextLine
				}
			}
			
			// 少なくとも1つの数字が含まれているかチェック
			hasDigit := false
			for _, r := range trimmedLine {
				if r >= '0' && r <= '9' {
					hasDigit = true
					break
				}
			}
			
			if hasDigit {
				validCount++
			}
		}

	nextLine:
		if scanner.Scan() {
			// 次の行へ
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
