package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s*      : 行の先頭の任意の空白
	// (?:      : 非キャプチャグループの開始
	//   \d+    : 1つ以上の数字
	//   ,      : カンマ
	// )+       : 上記のグループが1回以上繰り返される
	// \d+      : 最後の数字（末尾のカンマがあっても、少なくとも1つの数字が続くことを保証するため、厳密には後述のロジックで調整が必要）
	// $        : 行の終わり
	//
	// 仕様の解釈に基づき、「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
	// 末尾のカンマは許容される。
	// 妥当なパターン: 数字とカンマが混在し、少なくとも1つの数字が含まれていること。
	// 例: "1,2,3", "1,2,", "1" (カンマなしも許容されるか？)
	// 仕様：「1 個以上の数字列がカンマで区切られて並んでいる」
	// これは、カンマで区切られた数字のシーケンスを意味すると解釈します。
	// 許容されるパターン: 数字とカンマのみで構成され、少なくとも1つの数字が含まれる。
	// 末尾のカンマは許容される。

	// 正規表現の調整:
	// 1. 行が空でないこと。
	// 2. 行が数字とカンマのみで構成されていること。
	// 3. 少なくとも1つの数字が含まれていること。
	// 4. 末尾のカンマは許容される。

	// 最初の試み: 数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認
	// ^\s*               : 行頭の空白
	// (?:             : 非キャプチャグループ
	//   \d+           : 1つ以上の数字
	//   ,             : カンマ
	// )*              : 上記のパターンが0回以上繰り返される (カンマなしの数字も許容するため)
	// \d+             : 最後の数字
	// (?:,\d+)*       : 最後の数字の後ろにカンマと数字が続く場合
	// \s*$            : 行末の空白
	//
	// よりシンプルな解釈: カンマで区切られた数字のリスト。
	// 妥当な行は、数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
	// 末尾のカンマは許容される。

	// 正規表現: 少なくとも1つの数字が含まれ、数字とカンマのみで構成される行。
	// ^\s*               : 行頭の空白
	// (?:             : 非キャプチャグループ
	//   \d+           : 1つ以上の数字
	//   (?:,\d+)*     : カンマとそれに続く数字が0回以上繰り返される
	// )                 : グループの終わり
	// (?:,\d+)?         : 最後の要素がカンマと数字で終わる場合 (末尾のカンマを許容するため)
	// \s*$              : 行末の空白
	//
	// 簡略化: 数字とカンマのみで構成され、少なくとも1つの数字が含まれていること。
	// 末尾のカンマは許容される。
	// 妥当なパターン: (数字, カンマの繰り返し) か、単一の数字。
	// 妥当な行は、数字とカンマのみで構成され、少なくとも1つの数字が含まれている。
	// 末尾のカンマは許容される。

	// 妥当な行のパターンを定義します。
	// 1. 行が空でないこと。
	// 2. 行が数字とカンマのみで構成されていること。
	// 3. 少なくとも1つの数字が含まれていること。
	// 4. 末尾のカンマは許容される。

	// 以下の正規表現は、行が数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。
	// ^\s*                  : 行頭の空白
	// (?:                  : 非キャプチャグループ
	//   \d+                : 1つ以上の数字
	//   (?:,\d+)*          : カンマとそれに続く数字が0回以上繰り返される
	// )                    : グループの終わり
	// (?:,\d+)?             : 最後の要素がカンマと数字で終わる場合 (末尾のカンマを許容するため)
	// \s*$                 : 行末の空白

	// 最終的な判定ロジックを、正規表現の適用と手動チェックで補強します。
	// 正規表現で「数字とカンマのみ」をチェックし、その後「数字が存在するか」をチェックします。

	validRegex := regexp.MustCompile(`^\s*[\d,]*\s*$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 1. 数字とカンマのみで構成されているかチェック
		if !validRegex.MatchString(line) {
			continue
		}

		// 2. 少なくとも1つの数字が含まれているかチェック
		hasDigit := false
		for _, char := range line {
			if char >= '0' && char <= '9' {
				hasDigit = true
				break
			}
		}

		if hasDigit {
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
