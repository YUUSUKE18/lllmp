package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// 正規表現: 1つ以上の数字とカンマの組み合わせ、末尾にカンマがあっても良い
	// ^\s*       : 行の先頭の空白
	// [0-9,]*    : 0個以上の数字またはカンマ（数字とカンマの組み合わせ）
	// (?:,\s*[0-9,]*)* : カンマとそれに続く任意の空白と数字/カンマの繰り返し（末尾のカンマを許容するため）
	// $          : 行の終わり
	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」をチェックするため、
	// 少なくとも一つの数字が存在し、カンマで区切られていることを確認する。

	// 妥当性の定義を再解釈: 「1個以上の数字列がカンマで区切られて並んでいる」
	// これは、カンマで区切られた要素の中に、少なくとも1つの数字が含まれていることを意味します。
	// 例: "1,2,3" -> 妥当
	// 例: "," -> 不妥当 (数字列が0個)
	// 例: "1," -> 妥当 (1個の数字列が区切られている)
	// 例: "" -> 不妥当 (数字列が0個)

	// 正規表現の設計:
	// ^\s*             : 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列がカンマで区切られているパターン
	// .*              : その他の文字（行末のカンマなど）
	// \s*$             : 行末の空白
	// 実際には、行全体が数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認します。

	// より簡単なアプローチとして、行が空でないこと、そして数字とカンマ以外を含まないことを確認し、
	// 少なくとも1つの数字が含まれていることを確認します。

	// 妥当な行の判定ロジック:
	// 1. 行が空でないこと。
	// 2. 行が数字とカンマのみで構成されていること（空白を除く）。
	// 3. 行内に少なくとも1つの数字が含まれていること。

	// 正規表現: 数字とカンマのみで構成され、少なくとも1つの数字を含む行を検出
	// ^\s*                  : 行頭の空白
	// (?:[0-9,]+(?:,\s*[0-9,]+)*) : 1つ以上の数字とカンマのシーケンス（数字列がカンマで区切られていることを示唆）
	// \s*$                  : 行末の空白
	// この正規表現は複雑になるため、よりシンプルに「数字とカンマのみで構成され、少なくとも1つの数字がある」ことを確認します。

	// 妥当な行の判定: 数字とカンマ以外の文字を含まず、かつ数字が少なくとも1つ含まれている。
	validRegex := regexp.MustCompile(`^\s*([0-9,]+)\s*$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := ""
		// 行の前後の空白を無視して、数字とカンマのみを抽出する
		for _, r := range line {
			if r >= '0' && r <= '9' || r == ',' {
				trimmedLine += string(r)
			}
		}

		// 1. 空行、または数字とカンマ以外の文字が含まれていた場合
		if trimmedLine == "" {
			continue
		}

		// 2. 抽出された文字列が、元の行の空白を除いたものと一致するかをチェック（厳密な判定のため）
		// 仕様に従い、行全体をチェックする方が安全。
		// 「数字とカンマ以外を含む行は妥当ではありません。」
		// これは、行に含まれる文字が {0-9, ,} のみであることを意味します。

		isAlphanumericAndCommaOnly := true
		for _, r := range line {
			if !((r >= '0' && r <= '9') || r == ',') {
				isAlphanumericAndCommaOnly = false
				break
			}
		}

		if !isAlphanumericAndCommaOnly {
			continue
		}

		// 3. 少なくとも1つの数字が含まれているかチェック
		hasDigit := false
		for _, r := range line {
			if r >= '0' && r <= '9' {
				hasDigit = true
				break
			}
		}

		if hasDigit {
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
