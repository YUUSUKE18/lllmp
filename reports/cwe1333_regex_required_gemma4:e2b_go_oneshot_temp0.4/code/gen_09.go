package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* - 行の先頭の空白を許容
	// (?:.*?\d+(?:,\d+)*) - 1つ以上の数字とカンマの組み合わせ（数字列がカンマで区切られていることを確認）
	// .*$ - 行の残りの部分（末尾のカンマなども許容するため）
	// この正規表現は「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するのに十分ではないため、
	// より厳密に「数字とカンマのみ」で構成され、少なくとも1つの数字が含まれていることを確認するパターンを採用する。

	// 妥当な行の判定ロジックを正規表現で表現する。
	// 妥当な行は「1個以上の数字列がカンマで区切られて並んでいる」こと。
	// これは、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを意味する。
	// 例: "1,2,3", "1,2,", "1"
	// 末尾のカンマは許容される。

	// より単純に、行が空でないこと、そして数字とカンマのみで構成されていることを確認する。
	// 課題の仕様を厳密に解釈すると、「1個以上の数字列がカンマで区切られて並んでいる」が核心。
	// 以下の正規表現は、数字とカンマのみで構成され、少なくとも1つの数字が含まれている行を捉えることを試みる。
	// (?:[0-9]+(?:,[0-9]+)*) は、数字とカンマのシーケンスを意味する。
	// 末尾のカンマを許容するため、行全体をチェックする。

	// 妥当な行の判定ロジックを、行ごとに手動で検証する方が、複雑な構造の検証には適しているため、
	// 正規表現の適用範囲を絞り、行の構造をチェックする。

	// 課題の指示に従い、正規表現を用いて判定する。
	// 妥当な行: 1個以上の数字列がカンマで区切られて並んでいる。末尾のカンマは許容。
	// 無妥当な行: 空行、数字とカンマ以外を含む行。

	// 妥当な行を数えるために、各行をチェックする。
	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := ""
		// 行の前後の空白を無視
		for i := 0; i < len(line); i++ {
			if line[i] != ' ' && line[i] != '\t' {
				trimmedLine += string(line[i])
			}
		}

		// 1. 空行の判定
		if trimmedLine == "" {
			continue
		}

		// 2. 数字とカンマ以外を含む行の判定
		// 数字とカンマのみで構成されているかを確認する正規表現
		// ^[0-9,]*$ : 行が数字とカンマのみで構成されていることを確認
		if regexp.MustCompile(`^[0-9,]*$`).MatchString(trimmedLine) {
			// 3. 1個以上の数字列がカンマで区切られて並んでいるか (少なくとも1つの数字が含まれているか)
			// 少なくとも1つの数字が含まれているかを確認する正規表現
			if regexp.MustCompile(`\d`).MatchString(trimmedLine) {
				validCount++
			}
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
