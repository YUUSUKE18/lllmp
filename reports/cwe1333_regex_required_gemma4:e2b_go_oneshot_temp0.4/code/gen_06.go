package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* 表示行の先頭の空白（無視される）
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列がカンマと空白で区切られているパターン
	// (?:,\s*|\s*$) : 最後のカンマと空白、または行末の空白
	// $ : 行末
	// この正規表現は、少なくとも1つの数字列とカンマの組み合わせが存在することを要求します。
	// 末尾のカンマも許容するため、行全体が数字とカンマのみで構成されていることを確認します。
	// より厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認するため、
	// 少なくとも一つの数字列が存在することをチェックします。

	// 判定ロジックをシンプルにするため、行が空でないこと、および数字とカンマのみで構成されていることを確認し、
	// さらに「1個以上の数字列」が存在するかどうかをチェックします。

	// 妥当性の定義: 1個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容。
	// これは、カンマで区切られた要素が少なくとも1つ以上存在し、その要素が整数である必要があることを意味します。

	// 以下の正規表現は、少なくとも一つの整数（数字列）が含まれていることを確認します。
	// ^\s* : 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の整数と、それに続くカンマと空白の繰り返し。
	// (?:,\s*|\s*$) : 最後の要素の後にカンマと空白、または行末の空白。
	// このパターンは、数字列が少なくとも1つ存在することを保証します。
	pattern := regexp.MustCompile(`^\s*(?:[0-9]+(?:,\s*[0-9]+)*)(?:,\s*|\s*)$`)

	for scanner.Scan() {
		line := scanner.Text()
		// 行の前後の空白を無視して判定するため、行全体を正規表現でチェック
		if pattern.MatchString(line) {
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
