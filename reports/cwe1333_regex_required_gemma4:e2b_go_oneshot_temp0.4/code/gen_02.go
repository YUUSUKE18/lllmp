package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列をチェックするための正規表現
	// ^\s* は行頭の空白を許容
	// (?:[0-9]+(?:,\s*[0-9]+)*) は、1つ以上の数字とカンマ区切りのパターンをキャプチャ
	// .*$ は行末まで
	// 末尾のカンマを許容するため、行末にカンマが続くパターンも考慮する
	// 妥当な行の定義: 1個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容。
	// 正規表現の解説:
	// ^\s* : 行頭の任意の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列がカンマと空白で区切られているパターン。
	// (?:,\s*$) : 末尾のカンマと空白（オプション）
	// 厳密に「1個以上の数字列がカンマで区切られて並んでいる」ことを確認する。
	// 以下の正規表現は、数字とカンマのみで構成され、少なくとも1つの数字が含まれていることを確認する。
	// 1つ以上の数字列とカンマの組み合わせを許容し、末尾のカンマも許容する。
	// 妥当な行: 少なくとも1つの数字が含まれ、カンマで区切られている。
	// 例: 1,2,3 または 1,2,3,
	pattern := regexp.MustCompile(`^\s*(?:[0-9]+(?:,\s*[0-9]+)*)(?:,\s*|$)`)

	for scanner.Scan() {
		line := scanner.Text()
		// 行の前後の空白を無視して判定するため、行全体をチェックする
		if pattern.MatchString(line) {
			validCount++
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常は無視されることが多いが、厳密には考慮する）
	}

	fmt.Printf("valid=%d\n", validCount)
}
