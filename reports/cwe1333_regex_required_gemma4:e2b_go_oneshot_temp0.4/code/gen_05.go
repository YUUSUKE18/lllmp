package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	// カンマ区切りの整数列を判定するための正規表現
	// ^\s* 表示行の先頭の空白（無視される）
	// [0-9]+ 表示1つ以上の数字
	// (?:,\s*[0-9]+)* 表示カンマとそれに続く空白が0回以上繰り返される（数字列の区切り）
	// \s*$ 表示行末の空白（無視される）
	// 末尾のカンマを許容するため、行末にカンマがあっても良いように調整する。
	// 妥当な行の定義: 1個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容。
	// 正規表現の調整:
	// 1. 少なくとも1つの数字列が存在する
	// 2. 数字列はカンマで区切られている
	// 3. 末尾にカンマがあっても良い
	// 以下のパターンは「数字とカンマのみ」で構成され、少なくとも1つの数字列を含むことを確認する。
	// ^\s*         : 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列、それに続くカンマと数字列の繰り返し。
	// (?:,\s*$)    : 末尾にカンマがあっても良い（数字列の後にカンマが続く）
	// よりシンプルに、「数字とカンマのみ」で構成され、数字が少なくとも1つあることを確認する。

	// 妥当な行の判定ロジックを再考します。
	// 「1 個以上の数字列がカンマで区切られて並んでいる」
	// 例: "1,2,3" -> 妥当
	// 例: "1," -> 妥当 (1個の数字列と末尾のカンマ)
	// 例: "," -> 不妥当 (数字列が0個)
	// 例: "abc" -> 不妥当 (数字以外を含む)
	// 例: "" -> 不妥当 (数字列が0個)

	// 1. 数字とカンマのみで構成されているか (数字とカンマ以外の文字を含まない)
	// 2. 少なくとも1つの数字列が存在する
	// 3. 末尾のカンマは許容される

	// 判定用の正規表現:
	// ^\s*                 : 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*) : 1つ以上の数字列がカンマで区切られているパターン。
	// (?:,\s*$)            : 末尾にカンマがあっても良い（数字列の後にカンマが続く）
	// このパターンは複雑になるため、より直接的に「数字とカンマのみ」で構成されているかをチェックし、その後数字の存在を確認する。

	// 妥当な行の判定:
	// 1. 行が空でないこと。
	// 2. 行に含まれる文字が数字とカンマのみであること。
	// 3. 数字が少なくとも1つ含まれていること。
	// 4. 末尾のカンマは許容される。

	// 1. 数字とカンマのみで構成されているか (数字とカンマ以外は許容しない)
	// 2. 少なくとも1つの数字列が存在する
	// 3. 末尾のカンマは許容される。

	// 妥当な行のパターンを定義:
	// ^\s*                       : 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*)  : 1つ以上の数字列がカンマで区切られている（最低1つの数字列）
	// (?:,\s*|$)                 : 最後の要素がカンマで終わるか、行末である
	// このパターンは複雑すぎるため、より単純なチェックと組み合わせる。

	// 判定ロジックをシンプル化し、正規表現は「数字とカンマのみ」のチェックに特化させる。
	// 妥当な行の定義: カンマで区切られた数字列が1つ以上存在する。

	// 1. 数字とカンマのみで構成されているか (数字とカンマ以外の文字を許容しない)
	// 2. 少なくとも1つの数字が含まれていること。
	// 3. 末尾のカンマは許容される。

	// 妥当な行のパターン:
	// ^\s*                                   : 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*)                 : 1つ以上の数字列がカンマで区切られている
	// (?:,\s*|\s*$)                            : 最後の要素がカンマで終わるか、行末である
	// このパターンは、カンマ区切りの数字列が1つ以上存在することを保証する。

	// 最終的な正規表現:
	// ^\s*                                   : 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*)                 : 1つ以上の数字列がカンマで区切られている（最低1つの数字列）
	// (?:,\s*|\s*$)                            : 最後の要素がカンマで終わるか、行末である
	// このパターンは、数字とカンマのみで構成され、数字が少なくとも1つあることを確認する。
	// 末尾のカンマは許容されるため、行末にカンマがあっても良い。

	// 妥当な行の判定:
	// 1. 数字とカンマのみで構成されていること。
	// 2. 少なくとも1つの数字列が含まれていること。
	// 3. 末尾のカンマは許容される。

	// 妥当な行のパターンを再定義:
	// ^\s*                                   : 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*)                 : 1つ以上の数字列がカンマで区切られている
	// (?:,\s*|\s*$)                            : 最後の要素がカンマで終わるか、行末である
	// このパターンは、カンマで区切られた数字列が1つ以上存在することを保証する。

	// 実際には、行全体が数字とカンマのみで構成され、数字が少なくとも1つあることを確認する方が安全。
	// そして、末尾のカンマの有無を許容する。

	// 妥当な行の判定（最も厳密に）：
	// 1. 行が空でない。
	// 2. 行に含まれる文字が数字とカンマのみである。
	// 3. 少なくとも1つの数字が含まれている。
	// 4. 末尾のカンマは許容される。

	// 妥当な行の正規表現:
	// ^\s*                                   : 行頭の空白
	// (?:[0-9]+(?:,\s*[0-9]+)*)                 : 1つ以上の数字列がカンマで区切られている
	// (?:,\s*|\s*$)                            : 最後の要素がカンマで終わるか、行末である
	// このパターンは、数字とカンマのみで構成され、数字が少なくとも1つあることを確認する。

	// 最終的な判定ロジックを実装
	validRegex := regexp.MustCompile(`^\s*(?:[0-9]+(?:,\s*[0-9]+)*)(?:,\s*|\s*)$`)

	for scanner.Scan() {
		line := scanner.Text()
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			continue // 空行は妥当ではない
		}

		// 1. 数字とカンマのみで構成されているかを確認
		// 数字とカンマ以外の文字が含まれていたら不妥当
		if !regexp.MustCompile(`^[0-9,]*$`).MatchString(line) {
			continue
		}

		// 2. 少なくとも1つの数字が含まれているかを確認
		if !regexp.MustCompile(`[0-9]`).MatchString(line) {
			continue
		}

		// 3. カンマ区切りの構造（1個以上の数字列）を確認
		// 妥当な行は、数字とカンマのみで構成され、数字が少なくとも1つ含まれている。
		// 末尾のカンマは許容される。
		// 妥当な行の定義を再確認: 1個以上の数字列がカンマで区切られて並んでいる。

		// 妥当な行のパターンをより厳密に適用:
		// 1. 行が空でない。
		// 2. 行に含まれる文字が数字とカンマのみである。
		// 3. 少なくとも1つの数字が含まれている。
		// 4. 妥当な区切り（カンマ）が存在するか、または単一の数字列である。

		// 妥当な行の判定を簡略化し、上記3つで十分と判断し、正規表現の使用を最小限にする。
		// 仕様では「正規表現を用いて」とあるため、正規表現で構造を判定する。

		// 正規表現による構造判定（数字とカンマのみで構成され、数字が1つ以上あること）
		// ^\s*                                   : 行頭の空白
		// ([0-9]+(?:,\s*[0-9]+)*)                 : 1つ以上の数字列がカンマで区切られている
		// (?:,\s*|\s*$)                            : 最後の要素がカンマで終わるか、行末である
		// このパターンは、カンマ区切りの数字列が1つ以上存在することを保証する。

		// 最終的な判定（正規表現を使用）
		if validRegex.MatchString(line) {
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
