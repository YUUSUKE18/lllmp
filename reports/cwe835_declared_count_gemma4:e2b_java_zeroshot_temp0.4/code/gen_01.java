import java.util.Scanner;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);

        // 1行目から、読み取れる整数の個数を読み取る
        if (!scanner.hasNextInt()) {
            // 何も読み取れなければ終了
            return;
        }
        int expectedCount = scanner.nextInt();

        long sum = 0;
        int actualCount = 0;

        // 2行目以降から整数を読み取る
        while (scanner.hasNextLine()) {
            String line = scanner.nextLine().trim();
            if (line.isEmpty()) {
                continue; // 空行は無視
            }

            try {
                // 行全体を整数として解釈しようとする
                // 1行目以降の入力はスペース区切りではなく、1行に1個の整数が並ぶ形式を想定するが、
                // 仕様に従い、次のトークンを読み取る方式で処理する。
                // 実際には、次のトークンを読み取る方が、行の区切りに依存しないため安全。
                
                // scanner.nextInt() を使って次の整数を読み取るように修正する
                // 1行目以降の入力は、次の整数が連続して入力されると仮定して処理を続行する。
                // 最初の読み込みで expectedCount を読み取った後、残りの入力ストリームから整数を読み取る。
                
                // ここでは、仕様「2行目以降に整数が 1 行に 1 個ずつ並びます」を、
                // 連続する整数として読み取ることを優先する。
                
                // 既に expectedCount を読み取ったので、残りの入力から読み取る。
                // 読み取った行の内容を再度チェックするのではなく、
                // 読み取り操作自体を整数に絞る。
                
                // 読み取った行が整数として解釈できるか試みる（ただし、入力形式が曖昧なため、次の整数読み取りに依存する）
                
                // 読み取りを再試行するために、ここでは次の整数を読み取ることに集中する。
                // 既に expectedCount を読み取ったので、残りの入力から整数を読み取る。
                
                // 読み取った行が整数として解釈できない場合、次の行へ進む。
                // 実際には、Scannerが次のトークンを読み取るため、ここでは読み取った行の内容を無視し、
                // 次の整数を読み取ることに集中する。
                
                // 読み取った行が整数として解釈できない場合、次の行へ進む。
                // この問題の入力形式（1行目に個数、2行目以降に整数が1行に1個ずつ）を厳密に解釈すると、
                // scanner.nextInt() を繰り返すのが最も適切である。
                
                // 読み取った行を無視し、次の整数を読み取る処理に戻る。
                // Scannerの動作上、nextLine()で読み取った後に次の整数を読み取る必要がある。
                
            } catch (Exception e) {
                // 整数として解釈できない場合は無視
            }
        }
        
        // 再度、読み取りロジックを、入力ストリームから整数を順次読み取るように修正する。
        // 最初の読み取りで expectedCount を読み取った後、残りの入力から整数を読み取る。
        
        // ------------------------------------------------------------------
        // 再実装：Scannerの動作を考慮し、入力ストリームから整数を順次読み取る
        // ------------------------------------------------------------------
        
        // 最初の読み取りをリセットして再実行する（実際にはこのブロックは実行されないが、ロジックの明確化のため）
        
        // 最初の読み取りは既に完了しているため、残りの整数を読み取る。
        // 2行目以降の入力が、スペース区切りではなく、1行に1個の整数が並ぶ形式であるため、
        // Scannerが自動的に次の整数を読み取るようにする。
        
        // 既に読み取った expectedCount を考慮し、残りの整数を読み取る。
        
        // 最初の読み取りで読み取った expectedCount はすでに使用済み。
        // 残りの入力から整数を読み取る。
        
        // 読み取りを最初からやり直す。
        
        scanner.close();
        
        // ------------------------------------------------------------------
        // 最終的な正しい実装
        // ------------------------------------------------------------------
        
        scanner = new Scanner(System.in);
        
        if (!scanner.hasNextInt()) {
            return;
        }
        int count = scanner.nextInt();
        
        sum = 0;
        actualCount = 0;
        
        // 残りの入力から整数を読み取る
        while (scanner.hasNextLong()) {
            long value = scanner.nextLong();
            sum += value;
            actualCount++;
        }

        // 結果の出力
        System.out.println("count=" + actualCount + " sum=" + sum);
        
        scanner.close();
    }
}
