//したがって、より正確な正規表現が必要：数値が存在するかつ空白・カンマのみが含まれている。

//修正: 正規表現は ^[\s，]*\d+(?:[\s，]*\d+)*$ とすると、「1,2」は OK、「,,」は NG。「 a,b」は [\s,]+ で「a」が含められないため？
//実際、[\d,]+ は数字とカンマのみ。なので「a,b」の場合、[\d,]+ が存在しないため regex test は NG。
//したがって、^\s*[\d,]+\s*$ は数字を含む必要があるか？
//上記 regex^[\d,]+$ を使うと、「,,」は [\d,]+ が存在しないので NG。
//「 a,b」の場合、「a」が含まれているため [\d,]+ で一致しない（['a'] が含まれているため）。
//したがって、^\s*[\d,]+\s*$ は正しいか？
//「1,2」: OK
//「,,」: NG ([\d,]+ がない)
//「 a,b」: NG (aが含む)
//したがって、^\s*[\d,]+\s*$ で OK。

const regex = /^\s*[\d,]+\s*$/;

let validCount = 0;
rl.on("line", (line) => {
  const trimmed = line.trim();
  if (trimmed.length === 0) return;
  
  if (regex.test(trimmed)) {
    validCount++;
  } else {
    validCount++;
  }
});

rl.on("close", () => {
  console.log(`valid=${validCount}`);
});

