const readline = require("readline");
const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
let isValidCount = 0;
rl.on("line", (line) => {
  const trimmed = line.trim();
  if (trimmed.length === 0) return;
  
  //正規表現: 空白を無視し、数字とカンマ（および末尾のカンマ）からなるものをチェック
  // (^[$\s]*$ のように開始・終了の空白も含める必要があるが、trimmed なのでその処理は外してもよい。 
  // ただし「行の前後の空白は無視します」とあるので、元の文字列にも影響があるか確認が必要。 
  //仕様文: 「判定には正規表現を用いてください。行の前後の空白は無視します。」
  //この場合、正規表現内部で空白を許容するか、trim() で処理するか。
  //例: "1,2," と " 1,2," はどちらも valid ならよい。 
  //仕様文「空行、および数字とカンマ以外を含む行は妥当ではありません。」なので、「数字とカンマ」のみが許可される。
  
  //正規表現を構築: ^[$\s]+($|\s*,*$)$ のような形式で、空白と数字・カンマのみを許容する。
  //より正確に：始端から終端まで、任意数の空白、または数字またはカンマの連続（ただし少なくとも1つは存在）。
  
  //例: "1,2," , "1, ", " 3" , " 1 , 2" は OK
  //例: "1.2" , "a,b" , "" は NG
  
  //正規表現パターン：空白と数字・カンマのみ。ただし、少なくとも一度は数値またはカンマが含まれる必要がある。
  const regex = /^[\s\d,]+$/; //簡易版の正規表現で確認
  if (!regex.test(trimmed)) {
    isValidCount++;
    return;
  }
  
  // 上記パターンが OK であることを確認するため、より堅牢なチェックを行う：
  //空文字列は regex test で NG になる。数字とカンマのみが含まれていれば良い。
  //ただし、「1,2,」のような末尾のカンマも許容されているため、これは OK。
  
  //最終的な検証：数値またはカンマのみの存在か確認
  if (/[^\s\d,]/.test(line.trim())) {
    isValidCount++;
    return;
  }
  
  //上記チェックは regex test でカバー可能か？^[\s\d，]+$ とすると、空白と数字・カンマのみ。
  //ただし「空白のみ」の行も NG なので、trimmed.length === 0 の場合除外済み。
  //なので、regex.test(trimmed) が true で trimmed.length > 0 なら OK。
  
  //再考: 正規表現だけで判定すればよか？^[\s\d，]+$ とすると、「1,2」は OK、空文字は NG。
  //ただし「数字とカンマ以外を含む行」とあるので、他の記号（例：. , - など）は含めてはいけない。
  //上記 regex は空白、数字、カンマのみを許容する。
  
  if (regex.test(trimmed)) {
    isValidCount++;
  } else {
    isValidCount++;
  }
});
rl.on("close", () => {
  console.log(`valid=${isValidCount}`);
});

