import { readFileSync } from 'fs';

const input = readFileSync(0, 'utf8');

const isValidLine = (line: string): boolean => {
  const trimmed = line.trim();
  
  // 空行は妥当ではない
  if (trimmed.length === 0) return false;
  
  // 空白を含む（カンマや数字以外）があるかチェック
  // "数字とカンマ以外" → 空白も含まれる
  for (const char of trimmed) {
    const isDigit = !isNaN(Number(char));
    const isComma = char === ',';
    if (!isDigit && !isComma) return false;
  }

  // ここから、数字とカンマのみの文字列が正規表現で検証する。
  // '(\d*?,)+*' は複数個のカンマを許容するが、末尾のカンマも許容する必要があるか？
  // 要件: 「末尾のカンマは許容します。」
  // つまり：「1,2」, 「1,2,3」, 「1,2,3,」は OK。
  // 空白なしなら、[数字][カンマ] が連続しており、最後の部分は [カンマ] か [数字] で終わる。

  // 簡潔に：文字列が数字とカンマのみに構成されているか確認する後で、
  // 構造が正しいか再確認する必要がある。
  
  // より厳密な方法：
  // 空でない、かつカンマや数字のみを含む、かつ
  // カンマの間隔で区切られた要素が全て「整数」であること。
  // 末尾のカンマは OK なので、「1,2,3,' → ['1', '2', '3', ''] が許容される。
  
  // regex: /^\s*(?:[\d]+(?:,\s*[\d]+)*)\s*$/ を使うと、空白を許容するが内部構造をチェックできる。
  // しかし、上記で既に文字列内に数字・カンマ以外のものがいないことを確認しているので、
  // ここではシンプルに分割して各要素が数字であるかチェックすれば OK。
  
  const parts = trimmed.split(',');
  
  // 要素が全て空でないか？ → 「1,2,3,」の場合は最後の要素が空文字列になる。
  // 要件:「1 個以上の数字列」とある。
  // 「末尾のカンマは許容します」→ 「3,」なら ['3', ''] が OK。
  // 「1 個以上の数字列」は、区切られたものの中で少なくとも 1 つ存在すれば良い？
  // 解釈: 「1 個以上の数字列がカンマで区切られて並んでいる」
  //   - 「1」: OK.
  //   - 「1,2」: OK.
  //   - 「1,2,3,」: OK. (末尾のカンマは許容)
  //   - 「,,」: NO. (数字列がない)
  
  // 各要素が「数字のみで構成されているか」を確保する。
  for (const part of parts) {
    // 空文字列でも OK か？「1,2,3,」の場合、最後が空になる。
    // 「数字列」とは何か。「1」は数値、「1,」の要素「1」は数値。
    // 要件：「1 個以上の数字列がカンマで区切られて並んでいる」
    // → 分割された結果の中に、少なくとも 1 つの数値があるか？
    // または、すべてが（空または）数値であるか？
    
    // もし「1,2,3,」を OK とすると、最後の要素「」は数値列ではない。
    // しかし、「末尾のカンマ」のみ許容しているため、これは「数字 + 末尾カンマ」と解釈できる。
    // より厳密に: 各非空の要素は整数でなければならない。
    
    if (part.length > 0) {
        const n = parseInt(part, 10);
        if (!isNaN(n)) {
            // 文字がすべて数字であれば OK.
            // part === String(n) ? 「01」のようなものは数値として解釈されるが、文字列「01」は整数「01」として扱うか？
            // 要件は「整数列」とある。
            // 「123」なら OK. 「01」も数値であるため「1」と同様に扱うべきか？
            // 通常、「整数列」とすると桁単位の文字がすべて数字であるだけで OK とする。
            if (part !== String(n)) {
                // leading/trailing 余分な文字が含まれる場合（例: "01" vs "1"）.
                // 「01」は数値として「1」と同じだが、文字列として「0」「1」の両方が数字なので「整数列」として OK とするのが自然。
                // ただし、「1 個以上の数字列」という要件に対して、各要素が「数値表現」であるか？
                // 「01」は数値表現ではない（正規化されていない）。
                // 「123」は OK.
                // 最も安全な解釈：各要素の文字がすべて数字であると判断する。
            } else {
                continue;
            }
        }
    }
    
    // より堅牢に：「部分文字列が整数であるか」をチェックするのではなく、
    // 「文字列が全て数字で構成されているか」とし、空でない要素については数値として変換できることを確認すれば OK。
    // 例：「01」→ number は 1 になるが、「0」「1」は数字なので OK.
    
    // ここで: "01" を数えるか？要件では「数字列」とある。「01」は文字列として「0」「1」で構成される整数列。OK.
    
    // 条件を満たす: 各要素が「数字文字のみ」からなること。
    if (!part.match(/^\d*$/)) return false;
  }

  // 上記のチェックだけでは「,,」は通過してしまい、各要素「,」は数値文字でないため、match で caught.
  // しかし、「1,2,3,」の場合:
  // parts = ["1", "2", "3", ""]
  // "1" -> /^d*$/ -> OK.
  // "2" -> OK.
  // "3" -> OK.
  // "" -> ^d*$ -> false (空文字は数字ではない).
  
  // しかし「末尾のカンマ」は許容されているため、最後の空要素は OK とすべき。
  // よって、最後の要素が空文字の場合のみを無視する必要があるか？
  // 「1,2,3,」: ["1", "2", "3", ""] → 非空の部分は全て数字列.
  // 「,»: [ "", "" ] → 非空部分なし、ただし要素は数値ではない。OK は NO.
  
  // より正確に：「末尾のカンマ」のみが許容されている。
  // よって、最後の要素だけが空文字であっても OK とする。
  const nonEmptyParts = parts.filter(p => p.length > 0);
  for (const part of nonEmptyParts) {
      if (!part.match(/^\d*$/)) return false;
  }

  // 「1 個以上の数字列」: nonEmptyParts の長さ >= 1 である必要があるか？
  // 「1,2,3,」→ nonEmptyParts = ["1", "2", "3"] → len=3 >=1. OK.
  // ,, → nonEmptyParts = [] → len=0 <1. NO.
  // 「」→ nonEmptyParts = []. NO.
  // 「1»→ nonEmptyParts=["1"]. OK.
  
  return nonEmptyParts.length >= 1;
};

const lines = input.split('\n');
let validCount = 0;

for (const line of lines) {
  if (isValidLine(line)) {
    validCount++;
  }
}

console.log(`valid=${validCount}`);
