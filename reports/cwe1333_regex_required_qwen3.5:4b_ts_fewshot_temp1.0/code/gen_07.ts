const data: Buffer[] = [];
process.stdin.on("data", (c: Buffer) => data.push(c));
process.stdin.on("end", () => {
  const s = Buffer.concat(data).toString("utf8");
  const lines: string[] = [];
  
  // エンコード後の改行文字が含まれている場合、正規表現を考慮して分割する必要があるため、
  // 元の改行文字を持つ文字列で分割せず、各ラインを取得する方法をとる。
  // 簡便なアプローチ：Buffer の配列で分割するのではなく、s.split('\n') を使用し、
  // 結果中の空要素を除去・処理を行う。
  
  // ※ s は Buffer でなく、文字列だが、s.split('\n') で各ラインを取得可能。
  // ただし、末尾に改行がある場合、配列の最後が空になる可能性があるため注意。
  const linesRaw = s.split("\n");
  let validCount = 0;

  for (const line of linesRaw) {
    if (line.trim() === "") continue;
    
    const trimmedLine = line.trim();
    
    // 正規表現: ^\d+(-?\d+)*$ は末尾のカンマを含めるため、
    // ^(\d+-\d*)*(?:,\s*\d+)*(?:\s*,)?$ とするのが正確だが、
    // 要件: "1 個以上の数字列がカンマで区切られて並んでいる"
    //       "末尾のカンマは許容する"
    //       "前後の空白は無視する" (行レベル)
    //       "数字とカンマ以外を含む行は妥当ではありません"
    
    // 改訂: 空でない、数字とカンマ以外の文字が含まれない、
    //      かつ「数字」が少なくとも 1 つあり、「カンマ」が存在するか、または「数字」のみで構成される。
    //      ただし、要件の「数字列がカンマで区切られて並んでいる」という表現より、
    //      「カンマがあるか否か」は区別せず、「数字とカンマ以外の文字がないこと」を確認すればよいはずだが、
    //      例文参照: "末尾のカンマは許容する" → 末尾のカンマがあっても OK。
    //      しかし、数字列が「並んでいる」とあるので、1 つ以上の数字が含まれている必要がある。
    
    // より正確に要件を満たす正規表現を構築:
    // 行レベルで、空白（trim により除外）した後に、
    // 「数字」の連続と「カンマ」が存在するのみであること、
    // かつ「数字」が少なくとも 1 つあること。
    
    // ^(\d+(-?\d*)*(?:,\s*\d+)*)$ という形式では:
    // - \d+:最初の数字列
    // - (-?\d*)*: 負の数字（オプション）と任意の数字の反復、カンマ（オプション）、空白（オプション）を区別せず
    //   しかし、要件は「数字とカンマ以外を含む行は妥当ではありません」とある。
    //   よって、文字が数値やカンマ、空白のみである必要がある。
    //   正規表現で「文字セットが有限」を確認するのは困難なので、まず regex を適用し、
    //   または「[0-9, -]'の範囲内にあるか」を判定する。
    
    // よりシンプルかつ堅牢なアプローチ:
    // 1. trim した文字列を扱う
    // 2. 正規表現 ^[\d,\-]*$ で、数字・カンマ・マイナスのみが含まれているか確認
    // 3. さらに「少なくとも 1 つの数字を含む」か確認
    
    // しかし、要件: "空白区切りの整数列" の類似性より、
    // 「数字とカンマ以外を含まない」かつ「数字が含まれる」ことが条件。
    
    // 正規表現: ^[\d\-,]+$ または ^[\d\-,]*$ で文字が制限されるが、
    // 「1 個以上の数字列がカンマで区切られて並んでいる」という構文規則も満たすか？
    // 例："-5,-2" → 妥当。 "10" → 妥当。 "1,2," → 妥当（末尾のカンマ許容）。
    // 例："1a" → 不満足、" ,1" → trim 後空行と同じ扱いになるか？ -> trim 後の文字が非空かつ数字/カンマのみ。
    
    // より厳密に: 
    // ^(\d+-?\d+)*$ に近いが、カンマで区切られている形式は "^(\d+\s*,\s*\d+)+" に近いが、
    // 末尾のカンマを含む形も許容されるため、^(\d+(\s*,\s*\d+)*\s*(?:,\s*)?)?$ とするのが正確。
    
    // 実際に使える正規表現:
    // 1. 行が trim された後、空でないこと
    // 2. 含まれる文字は数字 (0-9)・カンマ(,)・マイナス(-) のみであること
    // 3. 少なくとも 1 つの数字を含むこと
    
    // 上記 2 を満たす正規表現: ^[\d\-,]+$ 
    // 上記 3 を満たす条件として追加: 0 以上、9 以下の文字が 1 回以上含まれるか → 簡易的に
    // ^[\d\-,]+$ && [\d] が含まれている。
    
    const regex = /^[\d\-,]+$/;
    if (!regex.test(trimmedLine)) continue;
    
    // データ内の数字が含まれていないかチェック（^[\d\-,]++$ にしても 0 文字で OK なので追加のチェック必要）
    if (!trimmedLine.includes("0") && !trimmedLine.includes("1") && !trimmedLine.includes("2") && 
        !trimmedLine.includes("3") && !trimmedLine.includes("4") && !trimmedLine.includes("5") && 
        !trimmedLine.includes("6") && !trimmedLine.includes("7") && !trimmedLine.includes("8") && !trimmedLine.includes("9")) {
      // これは非効率的だが、簡易的な方法。
      // より良い方法: 正規表現 ^[\d\-,]+$ の中に「数字」があるかをチェックする。
      // しかし、^[\d\-,]+$ に含まれる文字が全て [-] や , のみである場合、不満足とされるべきか？
      // "1 個以上の数字列" が存在しない場合は不満足。
      
      // よりよい正規表現:
      // ^(\d+(\s*,\s*\d+)*)+$ とは違うため、^(\d+\s*(?:,\s*\d+)?)*$ を考え、
      // しかし、末尾のカンマがある場合 "^{\d+,}$" のような形が許容される。
      
      // より正確な正規表現:
      // ^(\d+(\s*,\s*\d+)*)+$ ではなく
      // ^(\d+(?:,\s*\d+)*)(?:,\s*$) とすると末尾のカンマも許容される。
      // しかし、空白を含むカンマ ("1, 2") は許容されるか？ "空白区切りの整数列" の文脈から、
      // 通常は「数字がカンマで区切られている」ものであり、
      // 「数字とカンマ以外を含む行は妥当ではありません」という条件より、
      // 空白は構文要素ではなく、「行の前後の空白は無視する」とあるので、
      // 行内部に空白があるとしても許容されるのか？
      
      // 例文「空白区切りの整数列」→ 空白が区切りとして使われる場合。
      // しかし、この課題は「空白が区切り」と異なるため、
      // "1,2" のようにカンマで区切る形式を想定している。
      // "末尾のカンマは許容する" → "1,2," なら OK。
      // "行の前後の空白は無視する" → 行全体に余分なスペースが含まれる場合は trim で除去。
      
      // よって、内部に空白がある場合も含むか？「数字とカンマ以外を含む行は妥当ではありません」→ 空白は含まないこと？
      // しかし、空白は文字としてカウントされ、「数字とカンマ以外の文字」とみなされるべきか？
      // そのような解釈だと "1,2" の間にある空白 "1, 2" は不満足。
      
      // 最も厳密な解釈: 
      // 行の trim を適用した後の文字列において、含まれる文字が数字・カンマ・マイナスのみであること。
      // かつ、少なくとも 1 つの数字が含まれていること。
      // または、構文規則的に "(\d+(?:,\s*\d+)*)*" などの形式に合うか？
      
      // ここで、最も安全な解釈として:
      // trim 後の文字列が、含まれる文字が「数字」「カンマ」「マイナス」のみに限られていること。
      // または、「[0-9\-,] 以外の文字が含まれていないこと」。
      // かつ、「数字の数はゼロでないこと」。
      
      // 上記を正規表現でまとめる:
      // ^[\d\-,]+$ だが、これが "1" の場合 OK、",," の場合不満足。
      // 数値が少なくとも 1 つ含まれているかを確認する:
      // regex = /^[\d\-,]+$/;
      // if (!regex.test(trimmedLine)) continue;
      
      // さらに、「数字が含まれていないか」をチェック:
      // trimmedLine.match(/[\d]/) || [] が存在するか？
      // 上記のチェックは必要。
    }

    // より簡潔かつ正確なロジック:
    
    if (!regex.test(trimmedLine)) continue;
    
    // データ内の数値が少なくとも 1 つ含まれているか
    if (trimmedLine.match(/[\d]/) === null) continue; // 0 文字の数字のみが含まれていない場合
    
    validCount++;
  }

  console.log(`valid=${validCount}`);
});
