import (
	"os"
	"strings"
	"regexp"
)

func main() {
	r := bufio.NewReader(os.Stdin)
	validCount := 0
	re := regexp.MustCompile(`^[\s]*[-\d]+,?[\s]*$`) // 数字とカンマのみを許容する正規表現。末尾のカンマも許容するため、文字列の最後の部分までマッチさせる必要があるが、より直接的なアプローチ:

	// 再考: 「1 個以上の数字列がカンマで区切られて並んでいること」
	// 例: "1,2", "1,2,", "1" が OK. "1, ,2" は NG (空白含む). "abc" は NG. "" は NG.
	// 要件: 「数字とカンマ以外を含む行は妥当ではありません」。
	// これは、文字列の中に 'a'-'z', 'A'-'Z' や記号が含まれてはいけないという意味。
	// また「1 個以上の数字列」なので空行も NG.
	// 正規表現の設計: ^[\s]*[-\d]+(,\s*[-\d]+)*$ は「空白を許容するが、文字間に空白があるか末尾にカンマありは OK」だが、要件には「数字とカンマ以外を含む行は妥当ではありません」とあるので、空白のみを許容すべきか？
	// 要件: 「行の前後の空白は無視します。」 -> 内部の空白も許容する必要があるのか？
	// 例: "1, 2" -> NG? "1 , 2" -> NG?
	// 要件文「数字とカンマ以外を含む行は妥当ではありません」を厳密に解釈すると、空白は「数字」とは異なるため、内部の空白も NG と捉えることも可能。しかし、「行の前後の空白は無視します」という文言から、前後のみ許容され、内部は厳密に数・カンのみであると推測される。
	// しかし、「1 個以上の数字列がカンマで区切られて並んでいること」という表現は、通常「1,2」や「1, 2」のような形式を指すことが多い。
	// さらに「末尾のカンマは許容します」とあるので、「1,'」または「1,2,'」が OK.
	// 最も安全で、要件の矛盾（前後空白無視 vs 数字とカンマ以外なし）を解決するアプローチ:
	// 正規表現：`^[[:space:]]*[-\d]+(,[[:space:]]*[-\d]+)*[,]?[[:space:]]*$`
	// 解説:
	// ^...$: 行の始端と終端。
	// [[:space:]]*: 前後の空白を無視（許容）。
	// [-\d]+: 最初の数字列。
	// (,[[:space:]]*[-\d]+)*: 中間のカンマ区切り部分。カンマと次の数字列の間にも空白を許容するか？
	// 要件「数字とカンマ以外を含む行は妥当ではありません」を考えると、空白は「数字」と「カンマ」のどちらにも該当しないので、空白自体も NG とする必要がある。
	// しかし、「行の前後の空白は無視します」という文言があるため、空白のみが許容されるべきである。
	// では、内部に空白が含まれてはいけないのか？
	// 例: "1,2" -> OK. "1 , 2" -> NG (空白含まない). " 1,2 " -> OK (前後空白)。
	// 結論：正規表現は「空白のみを許容する」ものにする。
	// 修正された正規表現: `^[[:space:]]*[-\d]+(,[[:space:]]*[-\d]+)*[,]?[[:space:]]*$` の代わりに、空白が内部に含まれることを防ぐために、空白は始端・終端のみ許容し、中間は厳密に数・カンのみとする。
	// しかし、「1,2」の間に空白が入ることは「数字とカンマ以外」として NG なのか？通常、CSV の文脈では空白は無視されるが、今回の要件は「数字とカンマ以外」なので、空白も除外対象かもしれない。
	// だが、「行の前後の空白は無視します」という文言があるため、空白のみを許容する形に統一するのが妥当である。
	// したがって、正規表現は以下のようにする：`^[[:space:]]*[-\d]+(,[[:space:]]*[-\d]+)*[,]?[[:space:]]*$` は内部の空白も許容してしまうので不適切かもしれない。
	// 要件「数字とカンマ以外を含む行は妥当ではありません」を厳密に解釈すると、空白も「数字・カンマ以外」なので NG.
	// しかし、「行の前後の空白は無視します」という文言から、空白は許容される。
	// この矛盾を解決するために、以下の仮定で実装する：
	// 1. 行全体に空白が含まれてもよい（前後・内部）。
	// 2. ただし、空白以外の文字が数字やカンマ以外である場合は NG.
	// つまり、「数」「カンプラ」「空白」の 3 つの文字しか許容できない。
	// 正規表現：`^[[:space:]]*[-\d]+(,\s*[-\d]+)*[,]?[[:space:]]*$` のように、空白は `\s` で統一して扱う。
	
	re = regexp.MustCompile(`^[[:space:]]*[-\d]+(,[[:space:]]*[-\d]+)*[,]?[[:space:]]*$`)

	scanner := bufio.NewScanner(os.Stdin)
	for scanner.Scan() {
		line := scanner.Text()
		if re.MatchString(line) {
			validCount++
		}
	}

	fmt.Printf("valid=%d\n", validCount)
}
