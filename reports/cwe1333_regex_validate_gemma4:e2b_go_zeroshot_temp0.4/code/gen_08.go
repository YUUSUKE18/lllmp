package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	validCount := 0

	for scanner.Scan() {
		line := scanner.Text()
		// 行の前後の空白を無視する（ここでは行全体を処理するため、TrimSpaceで前後の空白を除去する）
		trimmedLine := strings.TrimSpace(line)

		if trimmedLine == "" {
			// 空行は妥当ではない
			continue
		}

		// 末尾のカンマは許容される
		// 妥当であるためには、少なくとも1個の数字列が存在する必要がある。
		// これは、カンマで分割した結果、空でない要素が1つ以上存在すれば良い、ということを意味する。

		// 末尾のカンマを削除して、カンマで分割する
		// 末尾のカンマがあっても、その直前までを対象とする。
		parts := strings.Split(trimmedLine, ",")

		// 妥当性の判定ロジック：
		// 1. 空行でないこと (既にチェック済み)
		// 2. 数字とカンマ以外を含まないこと (Splitの結果が数字のみで構成されているか、または数字とカンマのみで構成されているか)
		// 3. 1個以上の数字列がカンマで区切られて並んでいること。
		//    これは、Splitの結果に空でない要素が1つ以上存在すれば満たされる。

		// ただし、仕様を再確認する。「1 個以上の数字列がカンマで区切られて並んでいること」
		// 例: "1,2,3" -> ["1", "2", "3"] (3個の数字列) -> 妥当
		// 例: "1," -> ["1", ""] (2個の要素。1個の数字列と空文字列) -> 妥当（末尾のカンマは許容）
		// 例: "," -> ["", ""] (2個の空文字列) -> 妥当ではない（数字列が0個）
		// 例: "abc" -> ["abc"] (1個の要素) -> 妥当ではない（数字列ではない）

		// 妥当な行の判定：
		// 1. 行が数字とカンマのみで構成されているか？
		// 2. 分割された要素の中に、少なくとも1つの非空の文字列（数字列）が含まれているか？

		isValid := false
		if len(parts) > 0 {
			// 各部分が数字列であるか、または空文字列であるかをチェックする
			hasNumber := false
			for _, part := range parts {
				if part != "" {
					// 部分が数字のみで構成されているかを確認する
					if _, err := fmt.Sscanf(part, "%d", new(int)); err == nil {
						// Sscanfが成功すれば、その部分が整数として解釈可能（数字のみ）
						hasNumber = true
					} else {
						// Sscanfが失敗した場合、その部分には数字以外の文字が含まれている
						// ただし、仕様は「数字列」なので、ここでは数字以外の文字が含まれていれば不適。
						// 厳密に「数字列」を求めるため、部分が完全に数字で構成されているかを確認する。
						// strings.TrimSpaceで既に処理済みなので、ここでは単純に数字のみかを確認する。
						if strings.ContainsAny(part, "0123456789") {
							hasNumber = true
						} else {
							// 数字以外の文字が含まれている場合、これは「数字列」ではない
							// ただし、仕様は「数字列がカンマで区切られて並んでいる」ことを求めているため、
							// 完全に数字のみで構成されているか、または数字とカンマのみで構成されているか、という解釈が自然。

							// ここでは、各部分が数字のみで構成されているかを確認する。
							// 完全に数字のみで構成されているか、または空文字列である必要がある。
							// 厳密に「数字列」を判定する。
							if strings.TrimSpace(part) == "" {
								// 空文字列は許容される（末尾カンマや連続カンマによる）
							} else {
								// 数字以外の文字が含まれていれば不適
								// ただし、Splitの結果、数字以外の文字が含まれている場合、それは妥当ではないと判断すべき。
								// 例: "1,a,2" -> parts=["1", "a", "2"]。この場合、"a"は数字列ではない。
								// 妥当なのは、すべての要素が数字列（または空文字列）である場合。
								// もし「数字列」が「整数」を意味するなら、各要素が整数に変換可能でなければならない。
								
								// ここでは、最も緩い解釈を採用し、非空の要素が数字のみで構成されているかを確認する。
								// 実際には、Splitの結果が数字とカンマのみで構成されているか、または空文字列であるかをチェックする。
							}
						}
					}
				}
			}

			// 最終的な妥当性の判定：
			// 1. 少なくとも1つの非空の数字列が存在すること。
			// 2. 行全体が数字とカンマのみで構成されていること。

			// 再評価：仕様は「1 個以上の数字列がカンマで区切られて並んでいること」
			// 空行や数字とカンマ以外を含む行は妥当ではない。

			// 1. 数字とカンマ以外を含む行の排除
			isAlphanumericOnly := true
			for _, char := range trimmedLine {
				if !strings.ContainsRune("0123456789,-", char) {
					isAlphanumericOnly = false
					break
				}
			}

			if !isAlphanumericOnly {
				continue // 数字とカンマ以外を含む行は不適
			}

			// 2. 1個以上の数字列が存在すること
			// 空文字列を無視して、非空の要素が1つ以上あるか。
			hasValidNumber := false
			for _, part := range parts {
				if part != "" {
					// 部分が数字のみで構成されていることを確認する（数字とカンマのみの制約を考慮）
					if _, err := fmt.Sscanf(part, "%d", new(int)); err == nil {
						hasValidNumber = true
					} else {
						// 数字以外の文字が含まれている場合、これは「数字列」ではないため、妥当ではない。
						// ただし、上記isAlphanumericOnlyチェックで既に数字以外の文字は除外されているはず。
						// このチェックは、行全体が数字とカンマのみで構成されていることを保証する。
					}
				}
			}

			if hasValidNumber {
				validCount++
			}
		}
	}

	if err := scanner.Err(); err != nil {
		// エラー処理（通常は無視されるが、念のため）
	}

	fmt.Printf("valid=%d\n", validCount)
}
