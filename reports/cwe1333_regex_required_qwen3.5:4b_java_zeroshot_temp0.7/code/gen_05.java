import java.util.Scanner;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int validCount = 0;
        
        while (scanner.hasNextLine()) {
            String line = scanner.nextLine();
            
            // 空白を除去して空行判定
            if (line.trim().isEmpty()) {
                continue;
            }
            
            // 正規表現の適用
            // ^: 開始
            // [ \t]*: 先頭の空白
            // ([0-9,]+|): 1 文字以上の数字またはカンマ、または空（末尾カンマのみ含む場合）
            // [\s,\t]*: 末尾の空白やカンマ
            // $: 終了
            String pattern = "^[ \\t]*([0-9,]+|[\\r\\n])?$"; 
            // 修正：上記の簡易パターンは「数字とカンマ以外を含む行」を完全に捉えきれない可能性があるため、より厳密に再確認。
            // 要件: 1 個以上の数字列がカンマで区切られて並んでいること。末尾のカンマは許容。
            // 無効なパターン: 文字が含まれる（文字とは文字以外のものも含む）、空行。
            // 有効な例: "1,2", "1", "", "1,,", " 1 , 2 " (空白は OK), "1,"
            // 無効な例: "a,b", "1 a", "" (空行は要件により無効), "abc"
            
            // 再定義された正規表現:
            // ^[ \t]*: 先頭の空白を許容
            // ([0-9]+(,[0-9]+)*(?:,)?|[0-9]+(?:,[0-9]+)*): 
            //   - [0-9]+: 少なくとも 1 つの数字
            //   - (,[0-9]+)*: カンマと次の数字を繰り返し
            //   - (?:,)?: 末尾のカンマオプション（許容）
            // [\s,\t]*$: 末尾の空白やカンマ（ただし、正規表現の構造上、最初の部分で「数字とカンマ以外」が含まれなければ OK）
            // ※要件に反する可能性のある「文字」とは「数字・カンマ以外の文字」と解釈。
            
            // さらに厳密化: 
            // 1. 行全体が「空白 + (数字列のカンマ区切り)+ / 末尾カンマオプション」で構成されること。
            // 2. 数字列は「数字の列（カンマなし）」または「数字・カンマの列」と定義。
            // 要件: "1 個以上の数字列がカンマで区切られて並んでいる"
            // 例: "1,2" -> 数字列 ["1", "2"]
            // 例: "1," -> 数字列 ["1"] (末尾カンマ許容)
            // 例: " 1, 2 " -> OK (空白無視)
            // 例: "" -> NO (空行は無効)
            
            // 最終的な正規表現ロジック:
            // ^[ \t]*: 先頭の空白
            // ((?:[0-9]+(?:,[0-9]+)*)(?:,)?|[0-9]+(?:,[0-9]+)*(?:,))? -> ここは少し複雑な構造になる。
            // より単純に: 
            // ^[ \t]*[0-9]+(?:,[0-9]+)*(?:,\s*)?$ 
            // 説明:
            // ^[ \t]*: 先頭空白許容
            // [0-9]+: 少なくとも 1 つの数字（数字列の開始）
            // (?:,[0-9]+)*: カンマと次の数字を繰り返す
            // (?:,\s*)? : 末尾のカンマと任意の空白（許容）
            // $: 終了
            
            // 要件確認: "1 個以上の数字列がカンマで区切られて並んでいる" -> [0-9]+(?:,[0-9]+)* が必須。
            // また "末尾のカンマは許容" -> (?:,\s*)? が追加。
            // "数字とカンマ以外を含む行は妥当ではありません" -> 上記パターンで満たされない場合は NO。
            
            if (line.trim().isEmpty()) {
                continue; // 空行は無効（処理しない）
            }
            
            // 正規表現をチェック
            java.util.regex.Pattern pattern = java.util.regex.Pattern.compile("^[ \\t]*[0-9]+(?:,[0-9]+)*(?:,\\s*)?$");
            if (pattern.matcher(line).matches()) {
                validCount++;
            }
        }
        
        System.out.println("valid=" + validCount);
    }
}
