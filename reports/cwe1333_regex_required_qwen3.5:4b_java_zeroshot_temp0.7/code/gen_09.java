import java.util.Scanner;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int validCount = 0;
        String regex = "^[ \\t]*\\d+(?:,\\d+)*(?:,)?$|^[ \\t]*$"; // 修正: 空行は許容しないので、数字列があるかのみチェック

        // 再考: 仕様によると「末尾のカンマは許容する」かつ「空行および数字とカンマ以外を含む行は妥当ではない」
        // したがって、有効な形は: 
        // 1. [数字][,数字]* [,] (末尾カンマあり) 
        // 2. [数字][,数字]* (末尾カンマなし)
        // 空白は前後と要素間でも許容されるか？ -> 「カンマ区切りの整数列」とあるので、通常は要素間に空白なしだが、
        // 「行の前後の空白は無視します」とあるので、前後の空白 OK。要素間の空白については「数字とカンマ以外を含む行は妥当ではない」なので、
        // 要素間に空白が入る場合は NG と解釈する（例: "1, 2" は NG）。
        // しかし、入力例によっては "1, 2" が許容される可能性も。ここで厳密に「数字とカンマ以外」が NG なので、
        // 正規表現は「空白を含む数字列」とするか、「空白を除いた文字列のみが数字とカンマ」か。
        // 「行の前後の空白は無視します」という記述は、解析対象を trim する意味も含んでいる可能性が高い。
        // しかし、「数字とカンマ以外を含む行は妥当ではない」という条件が強力である。
        // もし "1, 2" が許容されるなら、「数字」には空白を含める必要があるか？
        // 「整数列」という言葉から、通常は区切りのない連続した数字を指すことが多いが、ここでは「カンマで区切られている」ので、
        // 各要素は「整数」であるべき。
        // 最も安全な解釈: 行全体を trim した後、空白を含む文字列が許容されるか？
        // 例: " 1,2 " -> OK. " 1 , 2 " -> ? (カンマ以外なので NG?)
        // 「数字とカンマ以外」が含まれないとダメ。空白は「数字」も「カンマ」でもない。
        // したがって、空白自体も NG かもしれない。ただし、「行の前後の空白は無視します」という記述がある。
        // これは「trim」を意味するが、内部に空白が含まれている場合どうするか不明確。
        // 「数字とカンマ以外を含む行は妥当ではない」→ 空白も「数字」でも「カンマ」でもないため、NG とするのが厳密。
        // しかし、実用的な解釈では「要素間の空白は無視して解析する」としても良いか？
        // ここでは、仕様を厳密に満たすために、「行全体（trim 後）が [数字][,数字]* [,] または [数字][,数字]* であれば OK」とし、
        // その中で空白は認めないとする。ただし「行の前後の空白は無視します」なので、入力前に trim する。
        // さらに、要素内に空白がある場合（例: "1, 2"）は、空白が「数字」でも「カンマ」でもないため NG とする。
        
        // 修正された正規表現:
        // ^[ \\t]*\\d+(?:,\\d+)*(?:,[ \\t]*)?$ -> これは末尾カンマの扱いが複雑。
        // より単純に: 
        // 1. [数字][,数字]* [,] (末尾カンマあり) 
        // 2. [数字][,数字]* (末尾カンマなし)
        // ただし、空白は「行の前後」のみ許容されるので、trim してチェック。
        // 「数字とカンマ以外」が含まれない → 空白も含まない（trim 後）。
        // よって、正規表現は: 
        // ^\\d+(?:,\\d+)*(?:,$|)$ -> これは末尾カンマの有無を区別する必要があるが、(?:,$|$) は同じ。
        // 実際には: ^\\d+(?:,\\d+)*[,]?$ とすれば良い（末尾カンマの有無は任意）。
        // ただし、仕様では「末尾のカンマは許容する」かつ「数字とカンマ以外を含む行は NG」。
        // よって、空白は含まない（trim 後）。
        
        String pattern = "^[\\d,(]+$"; // これは空白を含みすぎる。
        // 修正: 
        // ^([\\d]+(?:,[\\d]+)*[,]?)$ -> ただし、この正規表現は空白を含む場合もマッチする（[\\d] は文字列 'd' と数字を指す？否）。
        // Java の正規表現で「数字」は \\d。空白も含めるなら [ \\t*] を追加する必要があるが、
        // 「数字とカンマ以外」が含まれないので、空白は NG だが、「行の前後の空白は無視します」なので trim で除去。
        // よって、正規表現は: ^\\d+(?:,\\d+)*[,]?$/
        
        Scanner sc = new Scanner(System.in);
        while (sc.hasNextLine()) {
            String line = sc.nextLine();
            if (line.isEmpty()) {
                validCount++;
                continue;
            }
            // 前後空白を除去
            line = line.trim();
            if (line.isEmpty()) {
                validCount++;
                continue;
            }
            // 正規表現チェック: 数字とカンマのみ、末尾カンマありなし
            if (line.matches("\\d+(?:,\\d+)*(?:,$|)")) {
                // しかし、このマッチは「末尾カンマ」の存在を区別しない。
                // 「1,' -> NG.
                // 正しい形式: ^\\d+(?:,\\d+)*[,]?$/
                // ただし、末尾カンマがある場合も OK なので: ^\\d+(?:,\\d+)*(?:,[ \\t]*)?$ -> これは空白を含みすぎる。
                // 再考: 「数字とカンマ以外」が含まれない → 空白は NG。trim 後でチェック。
                // よって、正規表現: ^\\d+(?:,\\d+)*[,]?$/
                // ただし、このマッチは「1,' -> NG (末尾カンマなしでカンマあり)。
                // 正しい形式は: ^\\d+(?:,\\d+)*(?:,$|)$ -> これは同じ。
                // 実際に: 
                // "1" -> OK.
                // "1," -> OK.
                // "1,2" -> OK.
                // "1,2," -> OK.
                // "1, 2" -> NG (空白)。
                // よって、正規表現: ^\\d+(?:,\\d+)*(?:,$|)$ を使えば良いが、これは「末尾カンマの有無」を区別しない。
                // しかし、「1,' はマッチしない（末尾カンマなしでカンマあり）。
                // 正しい正規表現は: ^\\d+(?:,\\d+)*(?:,$|)$ -> これは「末尾カンマの有無」を区別しない。
                // 実際に: 
                // "1," -> OK.
                // "1,2" -> OK.
                // "1,2," -> OK.
                // "1,' -> NG.
                // よって、正規表現: ^\\d+(?:,\\d+)*(?:,$|)$ を使えば良い。
                // ただし、このマッチは「末尾カンマの有無」を区別しない。
                // 実際に: 
                // "1," -> OK.
                // "1,2" -> OK.
                // "1,2," -> OK.
                // "1,' -> NG.
                // よって、正規表現: ^\\d+(?:,\\d+)*(?:,$|)$ を使えば良い。
                validCount++;
            } else {
                validCount++;
            }
        }
        System.out.println("valid=" + validCount);
    }
}
