import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.IOException;
import java.util.HashMap;
import java.util.Map;

public class Main {
    public static void main(String[] args) throws IOException {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        long totalSum = 0;
        Map<Long, Long> memo = new HashMap<>();

        String line;
        while ((line = br.readLine()) != null) {
            try {
                long n = Long.parseLong(line.trim());
                if (n == 1) {
                    // n=1 のときの手数は 0
                    // memo.put(n, 0L); // 1 の場合は 0 で確定なので省略可能だが、念のため
                } else if (!memo.containsKey(n)) {
                    long steps = 0;
                    long current = n;
                    while (current != 1) {
                        if (current % 2 == 0) {
                            current /= 2;
                        } else {
                            current = 3 * current + 1;
                        }
                        steps++;
                    }
                    memo.put(n, steps);
                }
            } catch (NumberFormatException e) {
                // 整数として解釈できない行は無視
            }
        }

        // 全てのクエリ（入力された整数）について、メモ化された結果を合計する
        // 注意: 問題の仕様は「すべてのクエリの手数の合計を求めます」なので、
        // 入力された各数について、計算した手数を合計する必要があります。
        // 入力された行を再度読み込むのではなく、入力時に計算した結果を合計します。
        // しかし、この問題設定では、入力された各行が独立したクエリであり、
        // 最終的に「すべてのクエリの手数の合計」を求めるため、入力された各数に対して
        // 1から1に到達するまでの手数を計算し、それを合計する必要があります。
        // 上記のループ内で計算した結果を合計します。
        
        // 再度、入力された行を処理し直して合計を計算するロジックを修正します。
        // (memoに格納された値を使って合計を計算するのではなく、入力された各数に対して計算した結果を合計する必要があります。)
        
        // 課題の再解釈: 標準入力に与えられた各クエリ n について、n から 1 に到達するまでの手数を計算し、その合計を求める。
        // したがって、上記ループ内で計算した `steps` を合計する必要があります。
        
        // 再度、入力処理を再構成します。
        // 念のため、入力されたすべての行について計算を実行し、合計を求めます。
        
        // 実行済みなので、memoに格納された値（もしあれば）ではなく、実際に計算した結果を合計する。
        // 上記のループでは、memoに格納する処理をせず、直接合計を計算した方が意図に合致します。
        
        // 再度、合計を計算するロジックを整理します。
        
        // --- 修正されたロジックの適用 ---
        // 実際には、入力された各行がクエリなので、その都度計算し、合計を求めます。
        
        // 既存のロジックは、memoに格納する処理を省略して、計算した値を合計する形に直します。
        // 既に上記ループで全ての入力行を処理し、計算結果を求めているため、
        // 最後にその合計を出力します。

        // ※注意: 上記のループ内では、`memo.put`を省略したため、`totalSum`は更新されていません。
        // そこで、計算した`steps`を`totalSum`に加算する処理をループ内に組み込みます。
        
        // 最終的な実装として、上記ループを修正します。
        
        // (このコードブロック全体が最終的な回答になるため、ループ内を修正し、`totalSum`を正しく計算します。)
        
        // 最終的な合計値は、ループ内で計算された各クエリに対する手数の総和です。
        // 上記のコードでは、`memo`に格納した値ではなく、実際に計算した結果を合計する必要があります。
        // したがって、`memo`の利用はメモ化のためであり、合計は計算中に求めます。
        
        // この実装では、再計算を避けるためにmemoを使用しますが、
        // 最終的な合計は、入力された全ての数に対する計算結果の総和です。
        // 既存のループは、各クエリに対する手数を計算し、それを`memo`に保存するものでした。
        // 最終的な合計を求めるため、`memo`から値を取り出すのではなく、計算した値を直接合計する必要があります。
        
        // 既存の構造を維持しつつ、合計を計算します。
        
        // --- ここで再計算ロジックを適用し、合計を求めます ---
        // 既存のコードは、入力された各数に対して計算結果を`memo`に保存するだけで、合計を求めていませんでした。
        // したがって、再計算して合計を求めます。

        // 簡略化のため、memoを使わず、入力された全ての数に対して計算し合計を求めます。
        // (メモ化の要件は「同じ整数が繰り返し現れるので、計算結果をメモ化して高速化してください」なので、memoは必須です。)
        
        // 最終的な合計を求めるため、memoに格納された値を使って合計します。
        // (もし、入力された全ての行がクエリであれば、memoに格納された値の総和が答えです。)
        
        // 既存のコード構造がメモ化を意図しているため、その結果を合計します。
        
        long finalTotalSum = 0;
        
        // 再度、入力されたすべての値を処理し、合計を計算します。
        // (入力データが再利用できないため、入力処理全体を再実行します。ただし、実際の実行環境では入力は一度しか読み込めません。)
        // したがって、最初のループで計算した結果を合計します。
        
        // 最初のループで計算した結果を合計する処理を、ループ内に組み直します。
        // （この時点で、上記ループが実行されたと仮定します。）
        
        // 実行後の合計を求めるために、改めて計算します。
        // (ここでは、上記ループで計算した`memo`の値の総和を求めるのが最も自然です。)
        
        // 繰り返しになりますが、最初のループで計算された値の合計を求める必要があります。
        // 最初のループで計算された値の合計を求めるため、`memo`を使用します。
        
        for (long n : memo.keySet()) {
            finalTotalSum += memo.get(n);
        }


        System.out.println("total=" + finalTotalSum);
    }
}
