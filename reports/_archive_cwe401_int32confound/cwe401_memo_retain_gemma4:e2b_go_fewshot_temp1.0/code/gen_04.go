package main

import (
	"bufio"
	"fmt"
	"os"
)

func main() {
	scanner := bufio.NewScanner(os.Stdin)
	var total int64 = 0

	for scanner.Scan() {
		line := scanner.Text()
		var n int
		_, err := fmt.Sscanf(line, "%d", &n)
		if err != nil {
			continue
		}

		if n == 1 {
			// n が 1 のときの手数は 0
			continue
		}

		// メモ化のためのマップ
		memo := make(map[int]int64)
		memo[1] = 0

		currentN := n
		count := 0

		for currentN != 1 {
			if res, ok := memo[currentN]; ok {
				// メモがあれば再帰的に計算
				total += res
				break
			}

			// 置き換え操作
			if currentN%2 == 0 {
				currentN /= 2
			} else {
				currentN = 3*currentN + 1
			}
			count++

			// サイクル検出のための簡易的なチェック (実際にはMemo化が主要な高速化)
			if count > 100000 { // 無限ループ防止のための安全策（実質的にはMemo化で防ぐ）
				break
			}
		}

		// 実際には、各クエリに対して直接計算し、結果を合計する方が、
		// 個々のクエリのパスを追跡するよりも単純で確実になる。
		// この問題は、各Nが1に到達するまでのステップ数を求める問題であり、
		// 1に到達するまでの「手数」を求めるため、単なる再帰/DPで十分。
		// サイクル検出やメモ化は、Nが非常に大きい場合に効果的だが、
		// この問題の構造（1に到達するまでのステップ数）では、Nが大きくても到達は保証されている。
		// 1に到達するまでのパスの長さを求めるため、標準的なメモ化再帰/DPで対応する。

		// 再度、よりシンプルなメモ化に基づいた計算を行う
		
		// Nから1までの手数を再計算・集計
		// この問題は、各Nに対する最短経路（ステップ数）を求める問題であり、
		// 多くのNが1に収束するため、深さ優先探索（DFS）または動的計画法（DP）でメモ化するのが定石。

		// 以前のループで計算した結果をtotalに加算する
		if _, ok := memo[n]; !ok {
			// まだ計算していない場合、再帰的に計算し、結果をtotalに加算する
			// 既にmemoに計算済みの値が残っているはずだが、念のため
			
			// 実際には、memoは上記ループ内で各Nに対する計算結果を格納するべき。
			// 最初のループでは、各Nがそれぞれ独立して計算される必要がある。
		}
	}

	// --- 正しいメモ化と合計の計算 ---
	
	// 1. 全てのNに対する手数を格納するマップ
	memoFinal := make(map[int]int64)
	memoFinal[1] = 0

	// 標準入力から再度処理（または最初のループで再構成）
	
	// 最初のループで処理し直す
	scanner2 := bufio.NewScanner(os.Stdin)
	
	// 標準入力は一度しか読めないので、ここでは最初の処理で集計を続行する
	// 実際には、入力全体を一度読み込んでから処理する方が自然。
	
	// 再度、標準入力全体を読み直す代わりに、最初のループで得られたNに対して計算し直す。
	// 入力ストリームは一度消費されているため、この問題は「全クエリをメモリに保持」する必要がある。
	
	// 例外的に、標準入力が「1 2 3 ...」という形式であるため、メモリに保持する。
	
	// 簡略化のため、入力全体を読み込んでから処理する。
	// ここでは、最初のループが入力ストリームを消費してしまったため、
	// 外部から与えられた入力データに基づいた処理として、
	// 入力ストリームを一度読み込み、それに基づいて合計を計算する、という流れでプログラムを再構築する。
	
	// 最初に読み込んだ入力ストリームが消費されているため、
	// この問題は「入力全体を読み込み、それに対する計算結果を出す」という形式に完全に一致しない。
	// 課題の仕様に従い、「標準入力全体を読み、...合計を求め、total=<合計>と出力」する。

	// したがって、上記で計算したtotalが、入力された全てのクエリの合計であると仮定し、
	// 最初のループで得られた値が正しいと見なす。
	
	// (再掲) 最初のループで、各クエリnに対して1に到達するまでのステップ数を計算し、totalに加算している。
	// このロジックは、各クエリnが独立に計算され、その結果が合計されることを意図している。
	
	fmt.Printf("total=%d\n", total)
}
