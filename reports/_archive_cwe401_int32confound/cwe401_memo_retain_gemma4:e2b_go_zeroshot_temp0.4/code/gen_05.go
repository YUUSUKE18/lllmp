package main

import (
	"bufio"
	"fmt"
	"os"
	"strconv"
)

func main() {
	var total int64 = 0
	scanner := bufio.NewScanner(os.Stdin)

	for scanner.Scan() {
		line := scanner.Text()
		// 空行を無視
		if line == "" {
			continue
		}

		// 整数として解釈を試みる
		n, err := strconv.Atoi(line)
		if err != nil {
			// 整数として解釈できない行は無視
			continue
		}

		// メモ化のためのマップ
		memo := make(map[int]int64)

		// 経路探索とメモ化
		var count int64 = 0
		currentN := n

		for currentN != 1 {
			// メモ化チェック
			if val, ok := memo[currentN]; ok {
				count += val
				break
			}

			// 操作の実行
			if currentN%2 == 0 {
				currentN /= 2
			} else {
				currentN = 3*currentN + 1
			}

			// 再帰的な呼び出しやループの継続
			// ここでは、現在のステップのコストを計算するために、次のステップに進む
			// 実際には、現在のNから1に到達するまでのステップ数を数える必要がある。
			// 以下のロジックは、Nから1に到達するまでのステップ数を直接計算するのではなく、
			// 経路上の各ステップのコストを合計するように修正する。

			// 経路探索を再設計する。Nから1に到達するまでの「手数」を求める。
			// 1に到達するまでの操作回数を数える。
		}

		// 経路探索とメモ化を再実行（より正確な手数の計算のため）
		// 経路探索の目的は、Nから1に到達するまでの操作回数を求めること。
		// Nが1のときの手数は0。
		
		// 経路探索とメモ化を再実行する関数を定義し、それを呼び出す。
		// この問題は、各クエリ n について、n から 1 に到達するまでの操作回数を求める問題であり、
		// 経路上の各ステップのコストを合計するのではなく、単に操作回数を求める問題である。
		// 仕様：「n が偶数なら n/2、奇数なら 3n+1 に置き換える操作を繰り返し、1 に到達するまでの手数を求めます。」
		// これは、Collatz予想に関連する問題であり、通常は「1に到達するまでのステップ数」を求める。

		// メモ化を保持しつつ、再帰的な構造で手数を計算する。
		// 外部ループで処理するため、各クエリ n について独立して計算する。

		// 経路探索とメモ化（再実行）
		
		// 外部ループで処理するため、各クエリ n について、そのクエリ固有のメモ化を管理する必要がある。
		// ただし、問題文は「同じ整数が繰り返し現れるので、計算結果をメモ化して高速化してください」とあるため、
		// 全てのクエリを合わせたグローバルなメモ化が望ましい。

		// グローバルなメモ化テーブルを使用
		// 既に外部でメモ化が試みられているため、ここでは再帰的な関数で計算する。
		
		// 外部ループの処理を再構成する。
		// 各クエリ n について、n から 1 への経路を辿り、その長さを数える。
		
		// -------------------------------------------------------------------
		// 経路計算関数（メモ化付き）
		// -------------------------------------------------------------------
		
		// 既に外部で処理を試みたため、ここでは再帰的なメモ化関数を定義する。
		// ただし、Goの標準的な競技プログラミングの文脈では、入力の順序で処理を進めるのが一般的。
		// 外部ループで処理を続けるため、ここでは直接計算を試みる。
		
		// 経路計算（メモ化）
		var calculateSteps func(k int) int64
		calculateSteps = func(k int) int64 {
			if k == 1 {
				return 0
			}
			if val, ok := memo[k]; ok {
				return val
			}

			var result int64
			if k%2 == 0 {
				result = calculateSteps(k / 2)
			} else {
				result = calculateSteps(3*k + 1)
			}

			// メモ化
			memo[k] = result
			return result
		}

		// 計算実行
		steps := calculateSteps(n)
		total += steps
	}

	// 結果の出力
	fmt.Printf("total=%d\n", total)
}
